#!/usr/bin/env bash
# ПРИЧИНА: Н-39: привязка стаба в прозе
# ОКРУЖЕНИЕ: BARRIER_ROOT=$WORK
# ОКРУЖЕНИЕ: TMPDIR=/tmp
#
# Отличимость ноги (в) от мутанта, сужающего словарь стаб-токенов
# `s[0-9]+|стаб|обманка` до константы `s1` (адверсарий 072-r1, блокер 3):
# зелёная ветка — toy-контракт с ЦИТИРОВАННОЙ отметкой «s2 ловится на
# входе X» (кавычки — отметка, не предложение, правило 8); красная ветка —
# тот же текст БЕЗ кавычек → именованный отказ «Н-39: привязка стаба в
# прозе, строка N». Стаб-токен здесь — s2, НЕ s1 (не дубль
# case_01_honest_green.sh): мутант, сузивший словарь до литерала «s1», эту
# клетку НЕ ловит и остался бы зелёным на обманном дереве — здесь он
# обязан покраснеть.
#
# Каркас _toy.sh (комментарий и зона): зеркало case_01_honest_green.sh;
# toy-мир строится общим mk_toy_repo (реальные гейты + безаргументный
# package.json + минимальный ci.yml + ci_parity_exceptions.txt).
#
# BARRIER_ROOT=$WORK — seam verify_antiplacebo (ap_run): копирует
# scripts/pre_critic.sh в $WORK/scripts/pre_critic.sh перед вызовом;
# BASH_SOURCE/.. двери → $WORK, дверь судит toy-мир, не основной репо.
#
# TMPDIR=/tmp — канон семьи (см. case_01): все файлы игры пишут ВНЕ $WORK.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/_toy.sh"

[ -n "${BARRIER:-}" ] || { echo "BARRIER not set" >&2; exit 2; }
: "${WORK:?WORK must be set by verify_antiplacebo}"
export TMPDIR="/tmp"

mk_toy_repo "$WORK"

# ЗЕЛЁНЫЙ черновик (цитированная отметка «s2 ловится на входе X»): порог
# правила 8 — совпадение внутри кавычек «…» — ОТМЕТКА, не предложение.
cat > "$WORK/contracts/995-toy-draft.md" <<'MD'
# Контракт 995 — честный toy-черновик (s2)

## Предмет
p

## Красные предъявления

Красная клетка батареи кладёт в toy-контракт строку «s2 ловится на входе X» и требует отказа — цитата, не утверждение.

## Незаполненные требования:
нет
MD

# КРАСНЫЙ черновик (голая привязка: s2 ловится на входе X БЕЗ кавычек):
# мутант s[0-9]+→s1 эту строку не ловит — живая различимость (блокер 3).
cat > "$WORK/contracts/995-red-draft.md" <<'MD'
# Контракт 995 — toy-черновик с красным нарушением (s2)

## Предмет
p

## Красные предъявления

s2 ловится на входе X — голое предложение, не цитата.

## Незаполненные требования:
нет
MD

git -C "$WORK" add -A && git -C "$WORK" commit -qm 'toy: s2-привязка'

# ЗЕЛЁНАЯ ВЕТКА: цитата → rc 0, дверь зелёная.
BARRIER_ROOT="$WORK" "$BARRIER" 'contracts/995-toy-draft.md' >/dev/null 2>&1
rc=$?
[ "$rc" -eq 0 ] || { printf 'ОТКАЗ: зелёная ветка rc %s, ожидался 0\n' "$rc" >&2; exit 1; }
printf '%s: rc 0, дверь зелёная\n' "case_02-green" >&2

# КРАСНАЯ ВЕТКА: голое предложение s2 → rc 1 «Н-39: привязка стаба в прозе, строка N».
BARRIER_ROOT="$WORK" "$BARRIER" 'contracts/995-red-draft.md' 2>&1 | grep -Eq -- 'Н-39: привязка стаба в прозе, строка [0-9]+' \
  || { printf 'ОТКАЗ: красная ветка не назвала «Н-39: привязка стаба в прозе, строка N»\n' >&2; exit 1; }
printf '%s: rc 1 «Н-39: привязка стаба в прозе, строка N»\n' "case_02-red" >&2
exit 0
