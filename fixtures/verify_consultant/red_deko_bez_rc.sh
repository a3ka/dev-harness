# Красное предъявление 1/2 семьи verify_consultant (контракт 029, решение владельца Q2):
# ДЕКОЙ-КОНСУЛЬТАНТ, ВРУЩИЙ ТЕКСТОМ. Возвращает «дерево верифицировано, чисто, ок» без
# единой выполненной команды — ровно тот обход, ради которого владелец отклонил прежнюю
# формулировку «слепок дерева ДО вызова + дисциплина» как прозу.
#
# Почему проза не ловит: утверждение «я проверил» и утверждение «я не проверял, но
# говорю, что чисто» неотличимы в тексте. Отличимы они rc-выводом, который барьер
# ПЕРЕИСПОЛНЯЕТ сам; ответ без единой тройки «КОМАНДА/RC/ВЫВОД-SHA256» есть утверждение
# о дереве с нулевой выборкой — красное по правилу «нечего проверять ≠ проверено».
#
# ВХОД / ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА:
#   1) декой: шапка + «Дерево верифицировано, чисто, ок» БЕЗ блока ОСНОВАНИЕ-ДЕРЕВО →
#      rc 1, отказ называет отсутствующее основание и «просмотрено 0 команд» (инв. 8);
#   2) декой-2: блок ОСНОВАНИЕ-ДЕРЕВО есть, но ПУСТ (ни одной тройки) → та же rc 1
#      (ловец «заголовок вместо работы»);
#   3) ПОЗИТИВНЫЙ КОНТРОЛЬ: честный консультант — две тройки с РЕАЛЬНЫМИ rc и sha,
#      снятыми каркасом в память ДО построения ответа → rc 0 (инв. 8: барьер не карает
#      честную работу — иначе консультант выключен целиком);
#   4) честные тройки, но БЕЗ строки МОДЕЛЬ → rc 1 «нет строки МОДЕЛЬ» (инв. 6: без неё
#      запрет двойной роли ненаблюдаем);
#   5) ДЛИННЫЙ ЧЕСТНЫЙ ответ (регрессия 2026-11-13): шапка + ОДИН заголовок блока +
#      130 честных троек, размер >2×ёмкости канала → rc 0. Гейт блока барьера под
#      pipefail потребляет rc конвейера `printf | grep -q`: grep -q выходит на первом
#      совпадении, длинный printf ловит SIGPIPE (141), и правильный ответ отвергается
#      как «нет блока … просмотрено 0» — ЛОЖНЫЙ отказ на честной работе. Минимальное
#      исправление причины (объявление исполнителю, не реализация здесь): гейт блока
#      не должен потреблять rc раннего выхода читателя — дочитывающий
#      `grep '^ОСНОВАНИЕ-ДЕРЕВО:' >/dev/null` либо разбор PIPESTATUS[1] grep'а;
#      семантика инв. 8 не меняется.
#
# СТАБ-ПРИВЯЗКИ (Н-39; каждый стаб назван у входа, где его дефект НАБЛЮДАЕМ):
#   S-grammaronly — проверяет ТОЛЬКО шапку (ПРЕДМЕТ/МОДЕЛЬ/РЕКОМЕНДАЦИЯ): наблюдаем на
#                   входе 1 → краснеет ассертом 1;
#   S-headerok    — засчитывает НАЛИЧИЕ заголовка ОСНОВАНИЕ-ДЕРЕВО без троек: на входе 1
#                   честен, наблюдаем ТОЛЬКО на входе 2 → ассерт 2;
#   S-allred      — «всякий ответ красный»: наблюдаем ТОЛЬКО на входе 3 → ассерт 3;
#   S-nomodel     — строку МОДЕЛЬ не требует: наблюдаем на входе 4 → ассерт 4.
#   S-pipefail-q  — гейт заголовка блока потребляет rc раннего выхода grep -q под
#                   pipefail: на коротких входах 1–4 честен (SIGPIPE не возникает),
#                   дефект наблюдаем ТОЛЬКО на входе 5 → ассерт 5.
# На текущем HEAD (scripts/verify_consultant.sh не существует): rc 127 → ассерт 1.
# HEAD 2026-11-13 (барьер есть, гейт блока потребляет SIGPIPE-rc): вход 5 КРАСНЫЙ —
# rc 1 «нет блока ОСНОВАНИЕ-ДЕРЕВО … просмотрено 0» на ответе 172 КБ с заголовком
# и 130 честными тройками, измерено 3/3 прогона; входы 1–4 зелены.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_konsult.sh"

R="$WORK/repo"; igrushka "$R"
FABLE=anthropic/claude-fable-5

# 1) декой без блока вовсе.
D1="$WORK/deko-proza.md"
otvet_shapka "$D1" porog-gejta "$FABLE" 'вариант б'
printf 'Дерево верифицировано, рабочая копия чиста, всё ок — расхождений не вижу.\n' >> "$D1"
zapusk --root "$R" --otvet "$D1"
zhdu_rc 1 'декой утверждает верификацию дерева без единого выполненного rc (инв. 8)'
zhdu_text 'ОСНОВАНИЕ-ДЕРЕВО' 'отказ обязан называть отсутствующее основание (инв. 8)'
zhdu_text 'просмотрено 0' 'отказ обязан называть число просмотренных команд (инв. 8)'

# 2) декой с пустым заголовком блока.
D2="$WORK/deko-zagolovok.md"
otvet_shapka "$D2" porog-gejta "$FABLE" 'вариант б'
printf 'ОСНОВАНИЕ-ДЕРЕВО:\n(проверено глазами, команд не потребовалось)\n' >> "$D2"
zapusk --root "$R" --otvet "$D2"
zhdu_rc 1 'заголовок основания без единой тройки КОМАНДА/RC/ВЫВОД-SHA256 (инв. 8)'
zhdu_text 'просмотрено 0' 'отказ обязан называть число просмотренных команд (инв. 8)'

# 3) позитивный контроль: честный консультант.
H="$WORK/chestnyj.md"
otvet_shapka "$H" porog-gejta "$FABLE" 'вариант б'
osnovanie_chestnoe "$H" "$R" 'git status --porcelain'
osnovanie_chestnoe "$H" "$R" 'git log -1 --format=%H'
zapusk --root "$R" --otvet "$H"
zhdu_rc 0 'честный ответ с реальными rc и sha обязан проходить (инв. 8)'

# 4) честные тройки, но модель не названа.
N="$WORK/bez-modeli.md"
{
  printf 'ПРЕДМЕТ: porog-gejta\n'
  printf 'ВОПРОС: подставной инженерный форк\n'
  printf 'РЕКОМЕНДАЦИЯ: вариант б\n'
} > "$N"
osnovanie_chestnoe "$N" "$R" 'git status --porcelain'
zapusk --root "$R" --otvet "$N"
zhdu_rc 1 'ответ без строки МОДЕЛЬ — запрет двойной роли ненаблюдаем (инв. 6/8)'
zhdu_text 'МОДЕЛЬ' 'отказ обязан называть отсутствующее поле (инв. 6/8)'

# 5) ДЛИННЫЙ ЧЕСТНЫЙ ОТВЕТ — регрессия ложного «нет блока» (2026-11-13). Размер
#    >2×ёмкости канала делает SIGPIPE детерминированным: критерий измеряет
#    причину (ранний выход grep -q под pipefail), а не тайминг маленького
#    конвейера. Заголовок блока — на строке 5, в первом чтении grep'а.
D5="$WORK/dlinnyj-chestnyj.md"
otvet_shapka "$D5" porog-gejta "$FABLE" 'вариант б'
osnovanie_dlinnoe "$D5" "$R"
trebuet_dlinnyj "$D5"
zapusk --root "$R" --otvet "$D5"
zhdu_rc 0 'длинный честный ответ обязан проходить: ложное «нет блока» на правильном ответе — дефект гейта (инв. 8)'
