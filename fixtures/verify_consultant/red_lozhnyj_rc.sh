# Красное предъявление 2/2 семьи verify_consultant (контракт 029, решение владельца Q2):
# ДЕКОЙ ВТОРОГО ПОРЯДКА — консультант, который ИМИТИРУЕТ форму основания. Тройки на месте,
# грамматика безупречна, числа выдуманы. Отличить его от честного можно ровно одним
# способом: барьер ПЕРЕИСПОЛНЯЕТ названные команды сам и сверяет rc и sha со СВОИМ
# результатом (оракул в памяти проверяющего, не на диске проверяемого).
#
# ВХОД / ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА (дерево игрушки ГРЯЗНОЕ — untracha.txt untracked):
#   1) заявлен ВЫВОД-SHA256 пустого вывода при грязном `git status --porcelain` →
#      rc 1, отказ называет «расхождение вывода» и команду (инв. 9);
#   2) заявлен RC: 1 там, где команда реально даёт 0 → rc 1 «расхождение rc», отказ
#      печатает ОБА числа — заявленное и полученное (инв. 9);
#   3) команда ВНЕ белого списка (`rm -rf verdicts`) → rc 1 «вне белого списка», и
#      каталог verdicts/ ЦЕЛ: барьер не исполняет произвольное, чтобы «проверить»
#      (инв. 9 — иначе анти-плацебо сам становится исполнителем чужого кода);
#   4) метасимвол в разрешённом префиксе (`git status; rm -rf verdicts`) → rc 1, и
#      каталог verdicts/ ЦЕЛ (ловец белого списка по префиксу вместо разбора);
#   5) ПОЗИТИВНЫЙ КОНТРОЛЬ на ТОМ ЖЕ грязном дереве: честные rc и sha, снятые каркасом
#      в память → rc 0 (грязь дерева сама по себе не преступление; преступление —
#      ЛОЖЬ о ней).
#
# СТАБ-ПРИВЯЗКИ (Н-39; стаб назван у входа, где его дефект НАБЛЮДАЕМ):
#   S-rconly   — сверяет только RC, вывод не считает: на входе 2 честен, наблюдаем
#                ТОЛЬКО на входе 1 → краснеет ассертом 1;
#   S-shaonly  — сверяет только sha: наблюдаем ТОЛЬКО на входе 2 → ассерт 2;
#   S-trust    — ничего не переисполняет, верит заявленному: наблюдаем на входах 1 и 2;
#   S-exec     — исполняет ЛЮБУЮ названную команду: наблюдаем на входах 3 и 4 —
#                предъявляется не только rc, но и УЦЕЛЕВШИМ каталогом verdicts/;
#   S-prefix   — белый список по префиксу строки без разбора метасимволов: на входе 3
#                честен, наблюдаем ТОЛЬКО на входе 4 → ассерт 4;
#   S-allred   — «всякий ответ красный»: наблюдаем ТОЛЬКО на входе 5 → ассерт 5.
# На текущем HEAD (барьера нет): rc 127 → ассерт 1.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_konsult.sh"

R="$WORK/repo"; igrushka "$R"
printf 'грязь: незакоммиченный файл\n' > "$R/untracha.txt"   # дерево заведомо ГРЯЗНОЕ
FABLE=anthropic/claude-fable-5
SHA_PUSTOGO="$(printf '%s' '' | sha256sum | cut -d' ' -f1)"

# 1) ложный sha: «чисто» при грязном дереве.
D1="$WORK/lozh-sha.md"
otvet_shapka "$D1" tree-status "$FABLE" 'вариант а'
osnovanie "$D1" 'git status --porcelain' 0 "$SHA_PUSTOGO"
zapusk --root "$R" --otvet "$D1"
zhdu_rc 1 'заявлено чистое дерево при грязном — ложь ловится переисполнением (инв. 9)'
zhdu_text 'git status --porcelain' 'отказ обязан называть команду (инв. 9)'
zhdu_text 'вывод' 'отказ обязан называть класс расхождения (инв. 9)'

# 2) ложный rc при верном выводе.
D2="$WORK/lozh-rc.md"
otvet_shapka "$D2" tree-status "$FABLE" 'вариант а'
osnovanie "$D2" 'git status --porcelain' 1 "$(sha_vyvoda "$R" 'git status --porcelain')"
zapusk --root "$R" --otvet "$D2"
zhdu_rc 1 'заявленный rc 1 при реальном 0 (инв. 9)'
zhdu_text 'rc' 'отказ обязан называть класс расхождения (инв. 9)'
zhdu_text '1' 'отказ обязан печатать заявленное число (инв. 9)'

# 3) команда вне белого списка — барьер её НЕ исполняет.
D3="$WORK/vne-spiska.md"
otvet_shapka "$D3" tree-status "$FABLE" 'вариант а'
osnovanie "$D3" 'rm -rf verdicts' 0 "$SHA_PUSTOGO"
zapusk --root "$R" --otvet "$D3"
zhdu_rc 1 'команда вне белого списка readonly-глаголов (инв. 9)'
zhdu_text 'белы' 'отказ обязан называть класс нарушения (инв. 9)'
[ -d "$R/verdicts" ] || {
  printf 'ОТКАЗ: барьер ИСПОЛНИЛ «rm -rf verdicts» — анти-плацебо стал исполнителем чужого кода (инв. 9)\n' >&2
  exit 1; }

# 4) метасимвол под разрешённым префиксом.
D4="$WORK/metasimvol.md"
otvet_shapka "$D4" tree-status "$FABLE" 'вариант а'
osnovanie "$D4" 'git status; rm -rf verdicts' 0 "$SHA_PUSTOGO"
zapusk --root "$R" --otvet "$D4"
zhdu_rc 1 'белый список обязан судить РАЗОБРАННУЮ команду, не префикс строки (инв. 9)'
[ -d "$R/verdicts" ] || {
  printf 'ОТКАЗ: барьер исполнил хвост после «;» — префиксный белый список дырав (инв. 9)\n' >&2
  exit 1; }

# 5) позитивный контроль на том же грязном дереве.
H="$WORK/chestnyj-grjaznyj.md"
otvet_shapka "$H" tree-status "$FABLE" 'вариант а'
osnovanie_chestnoe "$H" "$R" 'git status --porcelain'
osnovanie_chestnoe "$H" "$R" 'git log -1 --format=%H'
zapusk --root "$R" --otvet "$H"
zhdu_rc 0 'честный отчёт о ГРЯЗНОМ дереве обязан проходить (инв. 9)'
