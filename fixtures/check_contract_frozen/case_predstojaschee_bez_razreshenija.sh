# ПРИЧИНА: РАЗРЕШИЛ-ВЛАДЕЛЕЦ: в изменяющем коммите
#
# Предстоящее v+1 (слово владельца 2026-10-22 ~21:20): accept-вердикт критика v+1 необходим,
# но НЕ достаточен — каждый коммит, меняющий текст после заморозки v$vmax, обязан нести
# валидную строку РАЗРЕШИЛ-ВЛАДЕЛЕЦ этого пути (грамматика razreshil из check_charter.sh).
# Иначе критик разрешил бы текст, который владелец не разрешал.
#
# Зелёный контроль: текст v2 + accept-вердикт v2 + РАЗРЕШИЛ в коммите → 0. Красное: ещё одна
# правка текста коммитом БЕЗ строки — отказ прежний дословно.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
g "$R" tag -a frozen/contracts/001/1 -m 'заморожен'

printf 'предмет, критерий готовности, РАБОТА НЕ РАЗДАЁТСЯ: кодификация\nстрока v2\n' > "$R/contracts/001-x.md"
put_verdict "$R" 2 accept
g "$R" add -A
g "$R" commit -q -m 'текст v2' -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: v2'
"$BARRIER" "$R"

# Порча: дозаметка в текст коммитом без разрешения владельца — вердикт v2 не спасает.
printf 'уточнение по ходу\n' >> "$R/contracts/001-x.md"
commit_all "$R" 'мелкая правка поверх v2 без строки владельца'
"$BARRIER" "$R"
