# ПРИЧИНА: новый вердикт критика v2
#
# Предстоящее v+1 (слово владельца 2026-10-22 ~21:20): текст следующей версии ещё до тега
# проходит ТОЛЬКО с accept-вердиктом критика v+1 — грамматика freeze_contract, первая строка
# `accept`. Без вердикта это не предстоящая заморозка, а правка замороженного, и отказ
# обязан быть прежним дословно: сообщение уже называет выход.
#
# Зелёный контроль: текст v2 + accept-вердикт v2 + строка РАЗРЕШИЛ-ВЛАДЕЛЕЦ в коммите
# текста (CI-режим: удержания нет, дельта чистая) → 0. Красное: вердикт v2 убран → 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
g "$R" tag -a frozen/contracts/001/1 -m 'заморожен'

# Полное валидное v+1: текст, accept-вердикт, разрешение владельца в коммите-носителе.
printf 'предмет, критерий готовности, РАБОТА НЕ РАЗДАЁТСЯ: кодификация\nстрока v2\n' > "$R/contracts/001-x.md"
put_verdict "$R" 2 accept
g "$R" add -A
g "$R" commit -q -m 'текст v2' -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: v2'
"$BARRIER" "$R"

# Порча: вердикт критика v2 исчез — предстоящее v+1 осталось без разрешения критика.
rm "$R/verdicts/critic/contracts-001-v2.md"
commit_all "$R" 'вердикт v2 забран'
"$BARRIER" "$R"
