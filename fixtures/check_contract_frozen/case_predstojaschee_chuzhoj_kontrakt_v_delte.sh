# ПРИЧИНА: судится только по своему контракту и его вердиктам
#
# Предстоящее v+1 в CI (слово владельца 2026-10-22 ~21:20): локальное удержание недостижимо,
# и вместо него судится консистентность дельты — коммиты текста не меняют НИ ОДНОГО другого
# файла contracts/*.md и plans/*.md. Иначе разрешение на один контракт становилось бы крышей
# для правки чужого замороженного текста в том же коммите.
#
# Зелёный контроль: валидное v+1 контракта 001 при нетронутом 002 → 0. Красное: коммит меняет
# тексты 001 и 002 РАЗОМ — у обоих accept-вердикты и строки РАЗРЕШИЛ, но дельта смешана —
# отказ по предмету дельты, а не по чужим недостачам.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"

# Второй замороженный контракт — v1 с accept-вердиктом (put_verdict пишет только 001).
printf 'второй предмет, критерий готовности\n' > "$R/contracts/002-y.md"
printf 'accept\nтело вердикта\n' > "$R/verdicts/critic/contracts-002-v1.md"
mkdir -p "$R/tmp"
commit_all "$R" 'второй контракт'
g "$R" tag -a frozen/contracts/001/1 -m 'заморожен'
g "$R" tag -a frozen/contracts/002/1 -m 'заморожен'

# Полное валидное v+1 контракта 001 — 002 не тронут.
printf 'предмет, критерий готовности, РАБОТА НЕ РАЗДАЁТСЯ: кодификация\nстрока v2\n' > "$R/contracts/001-x.md"
put_verdict "$R" 2 accept
g "$R" add -A
g "$R" commit -q -m 'текст 001 v2' -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: v2'
"$BARRIER" "$R"

# Порча: один коммит меняет ОБА контракта; у каждого есть свой accept-вердикт v2 и своя
# строка РАЗРЕШИЛ — единственная незакрытая дверь и есть дельта.
printf 'ещё строка 001\n' >> "$R/contracts/001-x.md"
printf 'строка 002\n' >> "$R/contracts/002-y.md"
printf 'accept\nтело вердикта\n' > "$R/verdicts/critic/contracts-002-v2.md"
g "$R" add -A
g "$R" commit -q -m 'правка двух контрактов разом' \
  -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: v2 (дозаметка)' \
  -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/002-y.md слово владельца: v2'
"$BARRIER" "$R"
