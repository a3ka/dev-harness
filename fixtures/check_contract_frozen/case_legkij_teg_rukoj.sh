# ПРИЧИНА: лёгкий (объект
#
# Н-35: судья, «имитируя заморозку» в клоне, поставил ЛЁГКИЙ тег frozen/… руками
# в основном репозитории — мимо freeze_contract.sh, без причины в сообщении.
# Барьер различает тип объекта: лёгкий (commit, без сообщения) — отказ,
# аннотированный (tag, с причиной) — законен. Зелёный контроль: v1 по процедуре
# (аннотированный, с вердиктом accept) → 0. Красное: тот же тег переставлен
# лёгким → 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"

R="$WORK/repo"
make_repo "$R"
g "$R" tag -a frozen/contracts/001/1 -m 'заморозка по процедуре, с причиной'
"$BARRIER" "$R"

# Порча: та же заморозка лёгким тегом — без сообщения, мимо писателя реестра
g "$R" tag -d frozen/contracts/001/1 >/dev/null
g "$R" tag frozen/contracts/001/1
"$BARRIER" "$R"
