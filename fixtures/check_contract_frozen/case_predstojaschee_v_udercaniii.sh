# ПРИЧИНА: не совпадает с локальным удержанием
#
# Предстоящее v+1 локально (слово владельца 2026-10-22 ~21:20): писатель уже заморозил v+1,
# и тег снят в удержание refs/frozen-hold/… (gitw_teg_130.sh hold — тег публикуется после
# ленда текста). Точная мера того, что замораживалось, — блоб удержания: дерево проходит, пока
# блоб на HEAD ему равен. Текст, ушедший от удержания, — не предстоящая заморозка, а правка
# замороженного.
#
# Зелёный контроль 1 (CI, без удержания): валидное v+1 → 0. Зелёный контроль 2 (локально,
# удержание равно блобу HEAD) → 0. Красное: текст дописан ПОСЛЕ удержания, с вердиктом и
# строкой РАЗРЕШИЛ — расхождение с удержанием названо.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
g "$R" tag -a frozen/contracts/001/1 -m 'заморожен'

printf 'предмет, критерий готовности, РАБОТА НЕ РАЗДАЁТСЯ: кодификация\nстрока v2\n' > "$R/contracts/001-x.md"
put_verdict "$R" 2 accept
g "$R" add -A
g "$R" commit -q -m 'текст v2' -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: v2'
"$BARRIER" "$R"

# Писатель заморозил v2 и снял тег в удержание — как это делает gitw_teg_130.sh hold.
g "$R" tag -a frozen/contracts/001/2 -m 'заморожен v2 локально'
obj="$(g "$R" rev-parse refs/tags/frozen/contracts/001/2)"
g "$R" update-ref refs/frozen-hold/contracts/001/2 "$obj"
g "$R" update-ref -d refs/tags/frozen/contracts/001/2
"$BARRIER" "$R"

# Порча: текст ушёл от удержания (вердикт v2 и строка РАЗРЕШИЛ при нём — их недостаточно).
printf 'дозаметка после удержания\n' >> "$R/contracts/001-x.md"
g "$R" add -A
g "$R" commit -q -m 'правка после удержания' -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: дозаметка'
"$BARRIER" "$R"
