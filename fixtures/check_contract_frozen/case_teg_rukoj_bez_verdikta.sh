# ПРИЧИНА: без вердикта критика
#
# Тег, поставленный РУКОЙ мимо `freeze_contract.sh`, обходит гейт критика: писатель вердикт
# читает, а голый `git tag` — нет. Поэтому читатель проверяет вердикт на КАЖДУЮ версию от 1 до
# высшей, а не только на высшую.
#
# Зелёный контроль: v1 с вердиктом `accept` → 0. Красное: v2 поставлена голым `git tag`, вердикта
# v2 на HEAD нет.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
g "$R" tag -a frozen/contracts/001/1 -m 'заморожен по процедуре'
"$BARRIER" "$R"

g "$R" tag -a frozen/contracts/001/2 -m 'поставлен рукой мимо писателя'
"$BARRIER" "$R"
