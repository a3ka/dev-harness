#!/usr/bin/env bash
# R16 — негативный контроль НЕ-ослабления фикса круга 11 (bare-channel-line) ПОСЛЕ
# введения состояния `in_enf` в круге 16: контракт содержит (а) валидный
# многострочный ЭНФОРСМЕНТ-абзац (продолжение на 2+ строк, маркер на первой),
# (б) ОТДЕЛЬНУЮ пустую строку, завершающую абзац по markdown-конвенции,
# (в) вслед за ней — генуинно БЕЗ-ПРЕФИКСНУЮ строку `role=…` (роль-файл не
# существует, норма объективно не подключена), (г) ДО следующего `#`-заголовка.
# До круга 16 ЭНФОРСМЕНТ-абзац был красным сам по себе (продолжения падали в
# catch-all); круг 16 это закрыл, НО мог случайно ослабить круг 11 — пропустить
# голый канал после абзаца. Фикстура доказывает обратное: пустая строка
# сбрасывает флаг `in_enf` обратно в 0, голая строка идёт в catch-all → rc 1 с
# поимённой причиной «строка вне грамматики» на САМОЙ голой строке. Пара —
# круг 16 не ослабил круг 11 на классе «после ЭНФОРСМЕНТ-абзаца».
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/_toy.sh"
require_absent_subject

WORK="$(mktemp -d "${TMPDIR:-/tmp}/r16_038.XXXXXX")"; trap 'rm -rf "$WORK"' EXIT
T="$WORK/toy"; make_toy "$T" 1 1

# Позитив-вход: длинный перенесённый ЭНФОРСМЕНТ-абзац, разорванный пустой
# строкой, БЕЗ голого канала → rc 0. Доказывает, что фикс круга 16 не
# регрессирует сам перенос абзаца.
put_contract "$T" 'ПРОВОДКА:
- guard=scripts/check_ok.sh

ПРОВОДКА-ЭНФОРСМЕНТ: chistyj enforsment — абзац перенесён на несколько строк;
продолжение по markdown-конвенции НЕ носит префикса маркера;
поэтому фикс круга 16 вводит состояние in_enf=1 на первой строке маркера
и сбрасывает на первой пустой строке.

## Риски (named residual)'
commit_all "$T" 'kontrakt s perekjuchennym ENF abzatsem bez kanalov bez prefiksa'
run_barrier "$T"
[ "$LAST_RC" -eq 0 ] || { printf 'ОТКАЗ: R16-positive: перенесённый абзац без голого канала дал rc %s:\n%s\n' "$LAST_RC" "$LAST_OUT" >&2; exit 1; }
printf 'R16-positive: перенесённый ЭНФОРСМЕНТ-абзац rc 0\n' >&2

# Негатив-вход: тот же перенесённый абзац + ОТДЕЛЬНАЯ пустая строка, его
# завершающая по конвенции, + вслед за ней генуинно БЕЗ-ПРЕФИКСНАЯ строка
# `role=…` (ДО следующего `#`-заголовка) → rc 1 с поимённой причиной
# «строка вне грамматики» НА САМОЙ голой строке. Доказывает, что пустая
# строка сбрасывает `in_enf` обратно в 0 и catch-all ловит голую строку
# ПОСЛЕ абзаца — круг 11 остаётся регресс-красным.
BAD='role=roles/missing.md «Missing role norm.»'
put_contract "$T" "ПРОВОДКА:
- guard=scripts/check_ok.sh

ПРОВОДКА-ЭНФОРСМЕНТ: chistyj enforsment — абзац перенесён на несколько строк;
продолжение по markdown-конвенции НЕ носит префикса маркера;
поэтому фикс круга 16 вводит состояние in_enf=1 на первой строке маркера
и сбрасывает на первой пустой строке.

$BAD

## Риски (named residual)"
commit_all "$T" 'kontrakt s perekjuchennym ENF + goloj strokoj posle abzaca'
run_barrier "$T"
refuse 'R16-bare-after-enf-paragraph' 'проводка: строка вне грамматики: role=roles/missing.md «Missing role norm.»'
exit 0
