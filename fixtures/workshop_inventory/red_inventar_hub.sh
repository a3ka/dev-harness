  printf 'СЛОМ: проба недостоверна (живой запуск/батарея/транспорт; батарея: суждено %s из %s заявленных) — rc 2, не красное\n' "$BAT_S" "$BAT_Z" >&2
  exit 2
fi
exit "$live_rc"
