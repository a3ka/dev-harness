vivod w3   red   sudit_mini "$WORK/minis/w3" w3
vivod w4   green sudit_mini "$WORK/minis/w4" w4
vivod w5   green sudit_mini "$WORK/minis/w5" w5
vivod w6   green sudit_mini "$WORK/minis/w6" w6
derevo pos  green
derevo k1   red
derevo k2   red
derevo v1   red
derevo v2   red
derevo v3   red
derevo v4   green
derevo v5   red
derevo b1   red
derevo cr   red
derevo shape red
derevo a6    red

# ── живое предъявление: текущий workshop — главный суд, всецело динамический ──
# (к3-Б2: живой запуск исполняется всегда, любой формы workshop; И-1/И-2 —
# N случайных проходов случайного класса + тождество; статика оценена выше)
live_rc=0
sudit_live "$REPO" 'живой-workshop' >"$WORK/j-live.out" 2>"$WORK/j-live.err" || live_rc=$?
cat "$WORK/j-live.err" >&2
