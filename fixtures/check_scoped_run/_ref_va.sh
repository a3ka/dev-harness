#!/usr/bin/env bash
# Барьер не готов, пока не предъявлен КРАСНЫМ против обманной заглушки.
#
# Заведено потому, что «фикстуры есть» было утверждением сессии, а не репозитория: в
# HANDOFF.md стояло «шесть фикстур» для `overlay.sh`, и в дереве не лежало ни одной.
# Зелёный, которого никто не видел красным, не доказывает ничего — он одинаково зелен у
# барьера, который проверяет, и у барьера, который печатает `ok` и выходит.
#
# ПРОВЕРЯЕТСЯ ИСПОЛНЕНИЕМ. Наличие файла рядом с барьером проверкой не является: файл из одной
# строки `exit 1` удовлетворил бы её. Фикстура обязана предъявить барьер СНАЧАЛА ЗЕЛЁНЫМ на
# целом дереве, затем внести обманное состояние и получить не ноль с НАЗВАННОЙ причиной.
# Положительный контроль обязателен по измеренной причине: адверсарий предъявил заглушку,
# печатавшую «e» ВСЕГДА и объявлявшую «e» причиной. Причина, печатающаяся и на зелёном, не
# называет ни отказ, ни предмет.
#
# ═══ ИСТИНА ЖИВЁТ В ПАМЯТИ ПРОВЕРЯЮЩЕГО И В ЗАКОММИЧЕННОМ ИСХОДНИКЕ ═══
#
# Так решил арбитраж `verdicts/arbitration/oblast-i-porog.md`, вопрос 3, и решение отвергло мой
# собственный тезис, что подделку наблюдения внутри одного uid механизмом закрыть нельзя.
# Дорога к решению — две находки адверсария: сначала фикстура подделала запись о вызове,
# вычитав путь учёта из читаемой обёртки; потом, когда учёт стали вести по записанному
# окружению, она переписала и его — и повтор краснел только потому, что импортировал
# поддельный PATH, ни один настоящий вызов красным не был.
#
# Отсюда правило: всё, что лежит на диске между началом и концом прогона, — территория
# фикстуры, и перечитывать это как истину ЗАПРЕЩЕНО. Устроено так:
#
#   1. ВЫЗОВЫ БАРЬЕРА ИСПОЛНЯЕТ ПРОВЕРЯЮЩИЙ. `$BARRIER` у фикстуры — не барьер, а клиент: он
#      шлёт заявку по каналу (FIFO) и ждёт ответа. Барьер запускает проверяющий своим потомком
#      в момент заявки; argv, каталог, код возврата и вывод остаются в ЕГО ПАМЯТИ, куда
#      фикстуре хода нет при том же uid. Поддельный «вызов» мимо канала не рождает записи —
#      значит нет положительного контроля, и фикстура валится fail-closed. Этим же закрыт
#      класс, который объявленное окружение НЕ закрывает: поддельный `rc=0`, которым
#      сообщник-фикстура провела бы вечно-красный барьер.
#   2. ОКРУЖЕНИЕ — ТОЛЬКО ОБЪЯВЛЕННОЕ. Добавки берутся из шапки ИСХОДНИКА фикстуры
#      (`# ОКРУЖЕНИЕ: PATH=$WORK/bin:$PATH`), то есть из закоммиченного текста, который читают
#      адверсарий и ревьюер. Подставить инструмент можно только ЯВНО.
#   3. ГРУППА ПРОЦЕССОВ ФИКСТУРЫ ДОБИВАЕТСЯ ДО ПОВТОРА. Фикстура идёт в своей сессии
#      (`setsid`), и её группа снимается перед повторным прогоном: иначе оставленный фоновый
#      потомок правит барьер во время повтора и восстанавливает после, а слепок по содержимому
#      этого не видит.
#
# ОСТАТОЧНЫЙ РИСК, помечен `cognitive-only`: объявленное окружение — законный канал внести
# поддельный инструмент явно (`PATH=$WORK/bin` с подставным `git`). Держится чтением
# закоммиченного исходника фикстуры. Туда же прежний риск: механизм не судит, ОТНОСИТСЯ ли
# обманное состояние к предмету барьера — фикстура может ронять его посторонним. Против этого
# положительный контроль (отсекает вечно-красное) и чтение кода двумя ролями. Ложная мера
# дороже отсутствующей, поэтому риск назван, а не спрятан.
#
# ОБЛАСТЬ ВЫВЕДЕНА ИЗ ПРЕДМЕТА, А НЕ ЗАДАНА ПРЕФИКСОМ. План 005 §1 писал «каждый
# `verify_*.sh` и `drill_*.sh`» — список по префиксу молча упускал `check_ids.sh` и
# `check_protected.sh` из §2 и §4 ТОГО ЖЕ плана. Область — ВСЁ содержимое `scripts/` на любой
# глубине, а роль файла объявляет он сам ШАПКОЙ:
#
#   `Коды возврата: 0 — …, 1 — …, 2 — …`  барьер: нужна фикстура, и перечисленные коды —
#                                         ЕДИНСТВЕННЫЕ, с которыми он имеет право выходить;
#   `НЕ БАРЬЕР: <почему>`                 вне области явно и с записанной причиной.
#
# Шапка — первый непрерывный блок комментариев, и только он: адверсарий выдал барьер за «НЕ
# БАРЬЕР», спрятав маркер в строке ДАННЫХ here-document. Неразобранное объявление — отказ
# кодом 1 с названным местом и выходом; это норма всей системы, а не местное правило (арбитраж,
# вопрос 1). Код 2 (`NOT_IMPLEMENTED`) красным НЕ считается и считается провалом фикстуры:
# «нечем проверить» не равно «проверено», иначе внесённое нарушение прячется под нехватку
# инструмента — так адверсарий и заслонил настоящий отказ.
#
# Соглашение о фикстуре — `fixtures/<ключ барьера>/case_*.sh`, ключ есть путь внутри
# `scripts/` без расширения, `/` → `.` (`lib/verify_x.sh` → `lib.verify_x`):
#   `# ПРИЧИНА: <подстрока>`   что барьер печатает, краснея, и чего НЕ печатает на зелёном;
#   `# ОКРУЖЕНИЕ: NAME=VALUE`  необязательно, можно несколько; подстановка только `$WORK`,
#                              `$REPO`, `$PATH` (последний — PATH проверяющего);
#   $BARRIER                   клиент канала. Вызов барьера иным путём не считается вовсе;
#   $WORK                      пустой каталог фикстуры. Дерево репозитория трогать нельзя —
#                              слепок берётся по СОДЕРЖИМОМУ и держится в памяти;
#   $REPO                      корень, откуда можно копировать;
#   BARRIER_ROOT=$WORK         барьер, привязанный к своему каталогу: проверяющий положит туда
#                              его побайтовую копию и запустит её.
#
#   bash scripts/verify_antiplacebo.sh            проверить это дерево
#   bash scripts/verify_antiplacebo.sh <корень>   проверить подставное дерево (так этот барьер
#                                                 предъявляется красным сам)
#
# Коды возврата: 0 — у каждого барьера красное предъявлено, 1 — нет, 2 — нечем проверить.
set -euo pipefail

ROOT_ARG=""; SCOPE_MODE=""; SCOPE_BASE=""; SCOPE_KEYS=()
while [ "$#" -gt 0 ]; do
  case "$1" in
    --changed) SCOPE_MODE=changed; SCOPE_BASE="${2:-}"; shift 2 || shift ;;
    --scope)   SCOPE_MODE=scope; shift; while [ "$#" -gt 0 ] && [ "${1#--}" = "$1" ]; do SCOPE_KEYS+=("$1"); shift; done ;;
    *)         ROOT_ARG="$1"; shift ;;
  esac
done
ROOT="$(cd "${ROOT_ARG:-"$(dirname "${BASH_SOURCE[0]}")/.."}" && pwd)"
SCRIPTS="$ROOT/scripts"
FIXTURES="$ROOT/fixtures"

fails=0
ok()   { printf '  ok   %s\n' "$*" >&2; }
bad()  { fails=$((fails + 1)); printf '  FAIL %s\n' "$*" >&2; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

[ -d "$SCRIPTS" ] || skip "нет каталога $SCRIPTS — область проверки не выводится"

# Шапка: первый непрерывный блок комментариев. Любая строка кода её закрывает, поэтому данные
# here-document маркером быть не могут.
header_of() {
  awk 'NR == 1 && /^#!/                { print; next }
       /^[[:space:]]*$/                { print; next }
       /^[[:space:]]*(#|\/\/|\/\*|\*)/ { print; next }
       { exit }' "$1"
}

classify() {
  awk '/^[[:space:]#*\/]*Коды возврата:/ { b = 1 }
       /^[[:space:]#*\/]*НЕ БАРЬЕР:/     { p = 1 }
       END { print (b ? "b" : "") (p ? "p" : "") }' <<< "$1"
}

# Коды берутся из шапки в её же формате `N — смысл`: перечень объявляет сам барьер. Число без
# тире (например «60 строк» в тексте) кодом не считается.
codes_of() {
  grep -oE '[0-9]+[[:space:]]*—' <<< "$1" 2>/dev/null | tr -cd '0-9\n' | sort -u | tr '\n' ' ' || true
}

# ── 1. Область: каждый файл в scripts/ на любой глубине объявляет свою роль сам ─
barriers=(); keys=(); codes=()
while IFS= read -r f; do
  rel="${f#"$SCRIPTS"/}"
  if [ -L "$f" ] && [ ! -e "$f" ]; then
    bad "$rel: битая символическая ссылка — файл, которого нельзя прочесть, не выходит из области, а прячется в ней"
    continue
  fi
  if [ ! -r "$f" ]; then
    bad "$rel: не читается — роль файла не объявлена и не может быть прочитана"
    continue
  fi
  h="$(header_of "$f")"
  case "$(classify "$h")" in
    b)
      c="$(codes_of "$h")"
      if [ -z "${c// /}" ]; then
        bad "$rel: шапка не перечислила коды возврата в формате 'N — смысл' — тогда любая неудача запуска сойдёт за отказ"
        continue
      fi
      barriers+=("$f"); keys+=("$(printf '%s' "${rel%.*}" | tr '/' '.')"); codes+=("$c")
      ;;
    p)  ;;
    bp) bad "$rel: объявлен и барьером, и не барьером — роль файла обязана быть одна" ;;
    *)  bad "$rel: не классифицирован — объявите в шапке 'Коды возврата:' либо 'НЕ БАРЬЕР: <почему>'" ;;
  esac
done < <(find "$SCRIPTS" \( -type f -o -type l \) | sort)

[ "${#barriers[@]}" -gt 0 ] || skip "в $SCRIPTS нет ни одного барьера — предъявлять нечего"

# ── 2. Сверка в обе стороны: фикстура без барьера — тоже расхождение ───────────
if [ -d "$FIXTURES" ]; then
  for d in "$FIXTURES"/*; do
    [ -d "$d" ] || continue
    k="$(basename "$d")"
    found=0
    for kk in "${keys[@]}"; do
      if [ "$kk" = "$k" ]; then found=1; fi
    done
    [ "$found" -eq 1 ] || bad "fixtures/$k: фикстура без барьера — она ничего не держит"
  done
fi

# ── scoped-ФИЛЬТР над СУЩЕСТВУЮЩИМ циклом (контракт 006 §Предмет) ───────────────
# Логика ВЫБОРА — в scope_select (tier-1 красная). Здесь ТОЛЬКО применение: сузить массивы
# barriers/keys/codes до задетых. Цикл, учёт и слепок НЕ меняются → все ветви отказа сохранены.
# CASE-фильтр: при --scope <key>/<case> внутри барьерного цикла прогоняются только указанные
# case; <key> без /case — все case барьера; несуществующий case — пустой список → fail-closed.
is_barrier_selected() {
  local k="$1" w
  for w in "${SCOPE_KEYS[@]:-}"; do
    case "$w" in "$k"|"$k"/*) return 0 ;; esac
  done
  return 1
}
# case_short_name: имя case БЕЗ расширения, С префиксом "case_" — scope_select в KEY: пишет
# именно «key/case_name», где case_name — «case_xxx», не «xxx». Снимать префикс здесь — значит
# рассинхронизировать ключ фильтра с тем, что вернул scope_select.
case_short_name() {  # <путь-к-case.sh>
  printf '%s' "$(basename "$1" .sh)"
}
is_case_selected() {  # <key> <case_short_name>
  local k="$1" cs="$2" w
  for w in "${SCOPE_KEYS[@]:-}"; do
    case "$w" in
      "$k") return 0 ;;            # весь барьер
      "$k/$cs") return 0 ;;        # конкретный case
    esac
  done
  return 1
}
if [ -n "$SCOPE_MODE" ]; then
  if [ "$SCOPE_MODE" = changed ]; then
    sel_out="$("$SCRIPTS/scope_select.sh" "$ROOT" --changed "$SCOPE_BASE" 2>/dev/null)"; sel_rc=$?
  else
    sel_out="$("$SCRIPTS/scope_select.sh" "$ROOT" --scope "${SCOPE_KEYS[@]}" 2>/dev/null)"; sel_rc=$?
  fi
  mode="$(printf '%s\n' "$sel_out" | sed -n 's/^MODE: //p' | head -1)"
  if [ "$sel_rc" = 2 ] || [ "$mode" = needs-full ]; then
    printf 'SCOPED: 0 задетых — scoped ничего не доказал, полный гейт в CI\n' >&2
    printf 'MODE: needs-full\n'; exit 2
  fi
  [ "$sel_rc" = 0 ] || { bad "scope_select отказал (код $sel_rc): $sel_out"; exit 1; }
  if [ "$mode" = scoped ]; then
    mapfile -t want < <(printf '%s\n' "$sel_out" | sed -n 's/^KEY: //p')
    fb=(); fk=(); fc=(); i=-1
    for b in "${barriers[@]}"; do
      i=$((i + 1)); k="${keys[$i]}"
      # Матч barrier key против want[] — может быть «key» (из --changed/--scope key)
      # или «key/case» (только из --scope key/case). На барьерном уровне берём key-часть.
      match=0
      for w in "${want[@]}"; do
        if [ "$k" = "${w%%/*}" ]; then match=1; break; fi
      done
      [ "$match" -eq 1 ] && { fb+=("$b"); fk+=("$k"); fc+=("${codes[$i]}"); }
    done
    barriers=("${fb[@]}"); keys=("${fk[@]}"); codes=("${fc[@]}")
    if [ "${#barriers[@]}" -eq 0 ]; then
      bad "scope_select вернул scoped, но ни один барьер не попал в выборку (want=${want[*]})"
      exit 1
    fi
    printf 'SCOPED: барьеров %d из выборки — не для приёмки\n' "${#barriers[@]}" >&2
fi
fi

# ── 3. Прогон фикстур ─────────────────────────────────────────────────────────
RUN="$ROOT/tmp/antiplacebo/run-$$"
mkdir -p "$RUN"

# Запуск барьера — ЕДИНСТВЕННОЙ реализацией: её зовёт и обслуживание заявок, и повторный
# прогон. Две копии одного запуска разошлись бы молча, и повтор перестал бы быть той же мерой.
ap_run() {  # <барьер> <корень или пусто> <env-пары через NUL в файле или пусто> <argv...>
  local real="$1" root="$2" envfile="$3"; shift 3
  if [ -n "$root" ]; then
    mkdir -p "$root/scripts"
    cp "$real" "$root/scripts/$(basename "$real")"
    real="$root/scripts/$(basename "$real")"
  fi
  local cmd=()
  case "$real" in
    *.ts) cmd=(node "$real") ;;
    *)    if [ -x "$real" ]; then cmd=("$real"); else cmd=(bash "$real"); fi ;;
  esac
  local pairs=()
  [ -n "$envfile" ] && [ -s "$envfile" ] && mapfile -d '' -t pairs < "$envfile"
  env -i "${pairs[@]}" "${cmd[@]}" "$@"
}

# Слепок дерева по СОДЕРЖИМОМУ и В ПАМЯТИ. Прежняя редакция хешировала путь, размер и mtime, и
# адверсарий предъявил подмену байта с восстановленными метаданными; следующая держала список
# на диске, а диск — территория фикстуры.
snapshot_of() (
  cd "$ROOT"
  # ОБЛАСТЬ СЛЕПКА ВЫВЕДЕНА, А НЕ ЗАДАНА СПИСКОМ. Прежняя редакция перечисляла шесть каталогов —
  # `scripts fixtures roles config .omp plans` — и новые каталоги в неё не попадали. Критик
  # предъявил обход ЗАМЕРОМ: фикстура записала `$REPO/contracts/probe.txt`, прогон вернул 0, файл
  # остался. То есть обещание «дерево вне $WORK не изменилось» было ложью для всего, что появилось
  # в репозитории после того, как список писали. `contracts/` и `verdicts/` — ровно такие
  # каталоги. Список, набранный руками, отстаёт от предмета молча — в этом репозитории это
  # измерено уже трижды, и здесь третий случай.
  #   .git   — служебное состояние git меняется от любой законной команды (чтение обновляет индекс,
  #            упаковку, refs); это не содержимое репозитория;
  #   .zones — дом изолированных сессий лаунчера: туда пишет ЛЮБОЙ параллельный процесс, и это тоже
  #            не содержимое репозитория;
  #   run-$$ — ЧЕРНОВИК САМОГО ПРОВЕРЯЮЩЕГО, и путь он знает по себе: это не список, а его
  #            собственное имя.
  #
  # ПОЧЕМУ ИМЕННО `run-$$`, А НЕ `tmp` И НЕ `tmp/antiplacebo`. Дефект области закрывался трижды, и
  # каждый раз новой формой того же: сначала перечисление шести каталогов (обход через
  # `contracts/`), потом исключение всего `tmp` (обход через `tmp/probe.txt`), потом исключение
  # всего `tmp/antiplacebo` (обход через `tmp/antiplacebo/probe.txt` — нашёл арбитраж
  # `verdicts/arbitration/oblast-slepka.md`, замер 1). Каждое исключение обязано СОВПАДАТЬ со своим
  # обоснованием: обоснование было «наблюдать себя нельзя», а исключался целый каталог, где
  # проверяющий пишет один подкаталог. Теперь совпадает по построению.
  #
  # ОСТАТОЧНЫЙ РИСК, названный прямо: фикстура, пишущая в `.git` или `.zones`, останется
  # незамеченной. Оба не содержимое репозитория — правка там не меняет предмета ни одного барьера.
  # СИМВОЛЬНЫЕ ССЫЛКИ — ЧАСТЬ ДЕРЕВА, и слепок обязан их видеть. Адверсарий предъявил четвёртую
  # форму записи вне `$WORK` (после `contracts/`, `tmp/` и `tmp/antiplacebo/`): фикстура создала
  # `ln -s` в корне подставного дерева, `find -type f` ссылку не перечислил, прогон вернул 0.
  # Теперь две меры: имена и содержимое обычных файлов; имена и ЦЕЛИ ссылок. Цель берётся
  # `readlink`'ом — он работает и на битой ссылке, а `sha256sum` по ссылке следовал бы за ней и
  # молча хешировал чужой файл.
  {
    find . \( -path ./.git -o -path ./.zones -o -path "./tmp/antiplacebo/run-$$" \) -prune \
           -o -type f -print0 | sort -z | xargs -0 -r sha256sum
    find . \( -path ./.git -o -path ./.zones -o -path "./tmp/antiplacebo/run-$$" \) -prune \
           -o -type l -print0 | sort -z | xargs -0 -r readlink | sha256sum
    # ЛОКАЛЬНЫЙ GIT CONFIG — ТОЖЕ ДЕРЕВО. Фикстура, затирающая user.name инструмента, меняет
    # предмет ничуть не меньше правки файла: 12 коммитов этого репозитория подписаны именем
    # «Дрилл» именно так (NABLIUDENIA.md, Н-10). .git из слепка исключён — он меняется от любой
    # законной команды, — поэтому конфиг берится ОТДЕЛЬНОЙ мерой: хеш выписки локальных значений.
    # Не-репозиторий слепком не стал: пустая выписка стабильна и на зелёном не красит.
    git -C "$ROOT" config --local --list 2>/dev/null | sha256sum || true
  }
)
before="$(snapshot_of)"

in_list() { case " $2 " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }

cases_total=0; reds=0
i=-1
for b in "${barriers[@]}"; do
  i=$((i + 1))
  key="${keys[$i]}"; declared="${codes[$i]}"
  dir="$FIXTURES/$key"
  mapfile -t cases < <(find "$dir" -maxdepth 1 -type f -name 'case_*.sh' 2>/dev/null | sort)
  if [ "${#cases[@]}" -eq 0 ]; then
    bad "$(basename "$b"): нет фикстур — ожидается fixtures/$key/case_*.sh"
    continue
  fi
  # CASE-фильтр (контракт 006 §Предмет, тир 2 case-уровень): при --scope key/case прогоняем
  # только этот case; key без /case — все case. Несуществующий case даёт пустой список — это
  # fail-closed (scope_select уже отверг кодом 1; здесь дополнительная защита, если кто-то
  # минует scope_select).
  if [ "$SCOPE_MODE" = scope ]; then
    filtered=()
    for c in "${cases[@]}"; do
      is_case_selected "$key" "$(case_short_name "$c")" && filtered+=("$c")
    done
    cases=("${filtered[@]}")
  fi
  for c in "${cases[@]}"; do
    cases_total=$((cases_total + 1))
    cname="$key/$(basename "$c")"
    reason="$(awk 'sub(/^# ПРИЧИНА:[[:space:]]*/, "") { print; exit }' "$c")"
    if [ -z "$reason" ]; then
      bad "$cname: не объявила причину — нужна шапка '# ПРИЧИНА: <подстрока вывода барьера>'"
      continue
    fi
    # Прямое упоминание внутренних имён канала и учёта — лобовая подделка. Область — только
    # ИСПОЛНЯЕМЫЕ строки: первая редакция грепала файл целиком и завалила фикстуру за то, что
    # та ОБЪЯСНЯЛА, чего избегает. Документация обязана иметь право называть предмет.
    if awk '!/^[[:space:]]*#/ && /AP_REQ|AP_RESP|AP_INV|AP_REAL|AP_INVOKE|wrapper\.body/ { f = 1 }
            END { exit(f ? 0 : 1) }' "$c"; then
      bad "$cname: упоминает внутренности учёта вызовов — учёт не принадлежит тому, о ком ведётся"
      continue
    fi

    d="$RUN/$key.$(basename "$c" .sh)"
    # Находка 4 (адверсарий): per-fixture HOME — иначе артефакт зелёного контроля фикстуры a
    # (напр. seed-from-a) протекает в HOME фикстуры b, и b краснеет НА УТЕЧКЕ, а не на предмете.
    mkdir -p "$d/work/home" "$d/resp"

    # Объявленное окружение — из ИСХОДНИКА фикстуры. Подстановка только $WORK/$REPO/$PATH:
    # значение, которое фикстура могла бы вычислить в рантайме, снова стало бы её территорией.
    : > "$d/env"
    while IFS= read -r pair; do
      pair="${pair//\$WORK/$d/work}"
      pair="${pair//\$REPO/$ROOT}"
      pair="${pair//\$PATH/$PATH}"
      printf '%s\0' "$pair" >> "$d/env"
    done < <(awk 'sub(/^# ОКРУЖЕНИЕ:[[:space:]]*/, "") { print }' "$c")
    for base in "PATH=$PATH" "HOME=$d/work/home" "LC_ALL=${LC_ALL:-C.UTF-8}" "TMPDIR=$d/work"; do
      name="${base%%=*}"
      grep -qzF -e "$name=" "$d/env" 2>/dev/null || printf '%s\0' "$base" >> "$d/env"
    done

    # Клиент канала. Барьер он НЕ запускает: только просит и ждёт ответа.
    mkfifo "$d/req"
    wrap="$d/barrier"
    { printf '#!/usr/bin/env bash\nAP_REQ=%q\nAP_RESP=%q\n' "$d/req" "$d/resp"
      cat <<'WRAP'
set -uo pipefail
resp="$AP_RESP/r.$$.$RANDOM"
mkfifo "$resp"
enc=""
# Каждый аргумент кодируется с ВЕДУЩИМ маркером `x`. Без него ПУСТОЙ аргумент исчезал: его base64
# — пустая строка, а разбор `for a in $enc` пустые слова не выдаёт. Барьер получал аргументы
# сдвинутыми и краснел не по той причине, которую вносила фикстура. Найдено фикстурой
# `freeze_contract/case_prichina_pustaja` (заморозка с пустой причиной — ровно тот случай, где
# пустая строка и есть предмет проверки). Маркер снимается при декодировании ровно один раз.
for a in "$@"; do enc="$enc x$(printf '%s' "$a" | base64 -w0)"; done
# Разделитель полей — U+001F, а НЕ табуляция. Табуляция входит в IFS-пробелы, и пустое поле
# (фикстура без BARRIER_ROOT) схлопывалось: все поля съезжали на одно, барьер получал в
# качестве корня чужой путь и честно краснел. Дефект замера, найденный своим же журналом.
printf '%s\x1f%s\x1f%s\x1f%s\n' "$resp" "${BARRIER_ROOT:-}" "$PWD" "$enc" >> "$AP_REQ"
{ IFS= read -r rc; cat; } < "$resp"
rm -f "$resp"
exit "${rc:-125}"
WRAP
    } > "$wrap"
    chmod +x "$wrap"

    # ── обслуживание заявок; учёт — в массивах проверяющего ──
    exec {reqfd}<>"$d/req"
    setsid env -u BARRIER_ROOT -u AP_REQ -u AP_RESP \
      BARRIER="$wrap" WORK="$d/work" REPO="$ROOT" \
      bash "$c" > "$d/case.out" 2>&1 &
    case_pid=$!

    inv_rc=(); inv_out=(); inv_argv=(); inv_cwd=(); inv_root=()
    serve() {
      local resp root cwd enc a argv=() out rc
      IFS=$'\x1f' read -r -t 0.2 resp root cwd enc <&"$reqfd" || return 1
      # `${a#x}` снимает маркер, которым клиент канала защищает ПУСТОЙ аргумент от схлопывания.
      for a in $enc; do argv+=("$(printf '%s' "${a#x}" | base64 -d)"); done
      set +e
      out="$( cd "$cwd" 2>/dev/null && ap_run "$b" "$root" "$d/env" "${argv[@]}" 2>&1 )"
      rc=$?
      set -e
      inv_rc+=("$rc"); inv_out+=("$out"); inv_cwd+=("$cwd"); inv_root+=("$root")
      inv_argv+=("$enc")
      # Журнал — ДЛЯ ЧЕЛОВЕКА, а не для вердикта: вердикт считается по массивам в памяти, а
      # без записи на диск отладка чужого прогона превращается в угадывание.
      { printf '=== вызов %d: код %s, каталог %s, корень «%s»\n' \
          "${#inv_rc[@]}" "$rc" "$cwd" "$root"
        printf '%s\n' "$out" | sed 's/^/    /'; } >> "$d/invocations.log"
      { printf '%s\n' "$rc"; printf '%s\n' "$out"; } > "$resp"
      return 0
    }
    while :; do
      serve && continue
      kill -0 "$case_pid" 2>/dev/null || break
    done
    serve || true
    set +e
    wait "$case_pid"; case_rc=$?
    set -e
    # Группа процессов фикстуры добивается ДО повтора: оставленный фоновый потомок правил бы
    # барьер во время повторного прогона и восстанавливал после.
    kill -- -"$case_pid" 2>/dev/null || true
    exec {reqfd}>&-

    seen="${#inv_rc[@]}"; green=0; degenerate=0; tool=0; alien=''; cand=-1
    for ((n = 0; n < seen; n++)); do
      rc="${inv_rc[$n]}"
      if [ "$rc" = "0" ]; then
        if [[ "${inv_out[$n]}" == *"$reason"* ]]; then degenerate=1; else green=1; fi
      elif [ "$rc" = "2" ]; then
        tool=1
      elif ! in_list "$rc" "$declared"; then
        alien="$rc"
      elif [ "$cand" -lt 0 ]; then
        cand=$n
      fi
    done

    if [ "$seen" -eq 0 ]; then
      bad "$cname: не вызвала барьер через \$BARRIER (код фикстуры $case_rc) — вывод в $d/case.out"
    elif [ "$degenerate" -eq 1 ]; then
      bad "$cname: причина «$reason» печатается и на ЗЕЛЁНОМ прогоне — она не называет ни отказ, ни предмет"
    elif [ "$tool" -eq 1 ]; then
      bad "$cname: барьер ответил «нечем проверить» (код 2) — фикстура обязана дать ему инструменты, иначе нарушение прячется под NOT_IMPLEMENTED"
    elif [ -n "$alien" ]; then
      bad "$cname: барьер вышел кодом $alien, которого не объявлял (объявлены: ${declared% }) — это неудача запуска, а не отказ по предмету"
    elif [ "$green" -eq 0 ]; then
      bad "$cname: нет положительного контроля — фикстура обязана предъявить барьер ЗЕЛЁНЫМ до порчи, иначе вечно-красный барьер неотличим от работающего"
    elif [ "$cand" -lt 0 ]; then
      bad "$cname: барьер остался зелёным на обманном дереве — красное не предъявлено"
    else
      # Красное засчитывает ПОВТОРНЫЙ прогон проверяющего: он повторяет ровно те условия,
      # которые сам же и запомнил, — argv, каталог, подставной корень, объявленное окружение.
      rargv=(); for a in ${inv_argv[$cand]}; do rargv+=("$(printf '%s' "${a#x}" | base64 -d)"); done
      set +e
      rout="$( cd "${inv_cwd[$cand]}" 2>/dev/null && ap_run "$b" "${inv_root[$cand]}" "$d/env" "${rargv[@]}" 2>&1 )"
      rrc=$?
      set -e
      printf '%s\n' "$rout" > "$d/rerun.out"
      if [ "$rrc" = "0" ] || [ "$rrc" = "2" ] || ! in_list "$rrc" "$declared"; then
        bad "$cname: повторный прогон проверяющего дал код $rrc — запись о вызове не подтверждена, вывод в $d/rerun.out"
      elif [[ "$rout" != *"$reason"* ]]; then
        bad "$cname: повторный прогон покраснел, но не назвал причину «$reason» — вывод в $d/rerun.out"
      else
        reds=$((reds + 1))
        ok "$cname: зелёный контроль есть, повторный прогон красный кодом $rrc — «$reason»"
      fi
    fi
  done
done

after="$(snapshot_of)"
if [ "$before" != "$after" ]; then
  menjalis="$(diff <(printf '%s\n' "$before") <(printf '%s\n' "$after") \
              | awk '/^[<>]/ { print $3 }' | sort -u | tr '\n' ' ' || true)"
  # Прочерк и stdin — плейсхолдеры хеша конфига, не имена файлов: выкидываются до проверки
  # пустоты, иначе «файлы: -» выдаёт себя за названную причину.
  menjalis="$(printf '%s\n' "$menjalis" | tr ' ' '\n' | grep -vE '^(-|stdin)?$' | tr '\n' ' ' || true)"
  # ПУСТОЙ СПИСОК ФАЙЛОВ при расхождении слепков означает ЛОКАЛЬНЫЙ GIT CONFIG: файлы не
  # менялись, а хеш выписки конфига — да. Именуется прямо, а не прочерком: причина обязана
  # называть предмет (правило 7 нормы).
  if [ -z "${menjalis// /}" ]; then
    menjalis="локальный git config"
  fi
  bad "дерево изменилось вне \$WORK — файлы: ${menjalis% }"
  printf '       фикстура обязана жить в $WORK; если названные файлы правит кто-то другой\n' >&2
  printf '       (соседный агент, редактор) — прогон недостоверен целиком, а не в одной строке\n' >&2
fi

printf '\nбарьеров: %d · фикстур: %d · предъявлено красным повторным прогоном: %d\n' \
  "${#barriers[@]}" "$cases_total" "$reds" >&2
if [ "$fails" -gt 0 ]; then
  printf 'расхождений: %d · прогон оставлен в %s\n' "$fails" "$RUN" >&2
  exit 1
fi
rm -rf "$RUN"
