#!/usr/bin/env bash
# КРАСНОЕ 025-И-2 (пачка B-1): pipefail+141-маппинг — носитель rc-prefix.ts.
# СУБЪЕКТ: .omp/extensions/rc-prefix.ts — мини-модуль extension: его factory
# (загрузчик харнеса вызывает его при старте сессии) присваивает
# process.env.PI_SHELL_PREFIX. ДОКАЗАНО ЖИВЫМИ ПРОБАМИ этой пачки (§Зонд №1,
# пробы C2/C3/D): executor харнеса оборачивает КАЖДУЮ bash-команду значением
# этой переменной («Optional command prefix wrapper», environment-variables.md;
# bash-tool-runtime.md «If prefix is configured, it wraps the command»), и
# присвоение от extension доходит до ГЛАВНОЙ сессии и ДОЧЕРНИХ task-сессий.
# Схема настроек билда НЕ ИМЕЕТ ключа prefix (453 ключа, пробы bash.prefix /
# prefix / shell.prefix → rc 1 Unknown setting — замер круга 1): config-ключ
# как носитель невозможен, мёртвая строка «prefix: …» в .omp/config.yml —
# плацебо и умирает здесь (фикстура config.yml НЕ читает вовсе).
#
# ГРАММАТИКА (заморожена контрактом 025 §Пачка B-1, тег frozen/contracts/025/1):
# модуль экспортирует default-factory БЕЗ внешних зависимостей; вызов factory
# присваивает process.env.PI_SHELL_PREFIX побайтово. Оракул значения — в ЭТОЙ
# фикстуре (правило 8). Декой-формы вердикта 72049b0 (process.exit(0)-модуль,
# модуль-комментарий, мёртвый prefix: в config.yml) умирают на factory-присвоении.
#
# ТРИ ПОЛОСА СУДА (оракуль-правка 141-различения — Н-39, привязка по коду, не
# проза; остаток Р3 контракта + adversary 0e2ce58/B-025-3; форма кандидата —
# байт-точно из коммита имплементера 1922846, где названо «для различения нужна
# параллельная оракуль-правка в зоне architect»):
#   1. САМОТЕСТ ОРАКУЛА-КАНДИДАТА (тауто-страж): строка-кандидат обязана ЖИВО
#      различать SIGPIPE-канарейку (yes|head → 0) от честного exit 141 (→ 141),
#      не трогая exit 7 (→ 7) и pipefail-агрегат (false|true → 1). Ослабление
#      САМОЙ строки (снят сторож n>1) умирает rc 1 именованно здесь — красная
#      фикстура умирает от предмета, не от себя.
#   2. ЗАМОРОЖЕННАЯ ФОРМА (значение == оракул §B-1 побайтово): живая семантика
#      простого префикса — канарейка → 0, exit 7 → 7, false|true → 1, явный
#      exit 141 → 0 (ИМЕНОВАННЫЙ ОСТАТОК Р3, не красное; ловец — маркер B-2 +
#      детектор 024). Дрейф любой пробы — rc 1 именованно. Итог: rc 0.
#   3. КАНДИДАТНАЯ ФОРМА (значение ≠ оракул §B-1): любое отклонение от заморозки
#      судится ПОЛНЫМ 141-различением — канарейка → 0 И честный exit 141 → 141
#      И exit 7 → 7 И false|true → 1; провал пробы — rc 1 ИМЕНОВАННО по ней
#      (ослабленная форма «ловит простой exit-код, но различения нет» умирает на
#      «честный exit 141 проглочен»); все пробы зелёны — всё равно rc 1
#      именованно «не заморожена»: §B-1 действует, перевод на кандидата (Р3)
#      — слово владельца. Живая семантика в дочерних сессиях мерится зондом
#      probe025_dochernij_vector.sh (И-6/§B-3).
set -uo pipefail
ROOT="${1:-$(cd "$(dirname "$0")/../../.." && pwd)}"
SUBJ="$ROOT/.omp/extensions/rc-prefix.ts"

if [ ! -f "$SUBJ" ]; then
  printf 'КРАСНОЕ 025-И-2: механизм отсутствует — %s не существует; rc пайплайна остаётся кодом хвоста (форма Н-84 «false | true → rc 0») во всех сессиях, включая дочерние\n' "$SUBJ" >&2
  exit 1
fi

# ЕДИНОЕ ЗНАЧЕНИЕ (единый источник — код субъекта; оракул — здесь):
ORACLE='set -o pipefail; trap '\''[ "$?" -eq 141 ] && exit 0'\'' EXIT;'
# ОРАКУЛ-КАНДИДАТ 141-различения (Р3-очередь; байт-точно из 1922846):
CANDIDATE_141='set -o pipefail; trap '\''n=${#PIPESTATUS[@]} rc=$?; [ "$rc" -eq 141 ] && [ "$n" -gt 1 ] && exit 0; exit $rc'\'' EXIT;'

# Живой замер обёрнутой команды (документированная форма харнеса: префикс
# препендится к команде как один текст скрипта): $1=префикс, $2=команда.
wrc() {
  bash -c "$1 $2" >/dev/null 2>&1
  printf '%s' "$?"
}

# ── ПОЛОСА 1: самотест оракула-кандидата (предмет — сама строка фикстуры) ──
rc_can="$(wrc "$CANDIDATE_141" 'yes | head -1')"
rc_141="$(wrc "$CANDIDATE_141" 'exit 141')"
rc_7="$(wrc "$CANDIDATE_141" 'exit 7')"
rc_ft="$(wrc "$CANDIDATE_141" 'false | true')"
if [ "$rc_can" -ne 0 ]; then
  printf 'КРАСНОЕ 025-И-2 (самотест кандидата): канарейка yes|head под кандидатом даёт rc %s (ожидание 0) — строка-кандидат в фикстуре сломана\n' "$rc_can" >&2
  exit 1
fi
if [ "$rc_141" -ne 141 ]; then
  printf 'КРАСНОЕ 025-И-2 (самотест кандидата): честный exit 141 под кандидатом даёт rc %s (ожидание 141) — оракул-кандидат ОСЛАБЛЕН: 141-различения нет (сторож n>1 снят?)\n' "$rc_141" >&2
  exit 1
fi
if [ "$rc_7" -ne 7 ] || [ "$rc_ft" -ne 1 ]; then
  printf 'КРАСНОЕ 025-И-2 (самотест кандидата): коды не сохранены (exit 7 → %s, false|true → %s; ожидание 7 и 1)\n' "$rc_7" "$rc_ft" >&2
  exit 1
fi

# ── СУБЪЕКТ: factory-присвоение (декоям 72049b0 умирать здесь) ──
out="$(SUBJ="$SUBJ" node --input-type=module -e '
const { pathToFileURL } = await import("node:url");
// URL — ТОЛЬКО pathToFileURL: конкатенация "file://"+путь при ОТНОСИТЕЛЬНОМ корне
// (документированная форма вызова «. », §И-2) давала file://./… с хостом — Node 26
// отвергает (ERR_INVALID_FILE_URL_HOST, замер: попытка №4 Impl025e); pathToFileURL
// также процент-кодирует не-ASCII/пробелы в пути.
const mod = await import(pathToFileURL(process.env.SUBJ).href);
if (typeof mod.default !== "function") {
  console.error("КРАСНОЕ 025-И-2: модуль не экспортирует factory-функцию — присвоение префикса невозможно");
  process.exit(1);
}
mod.default();
const v = process.env.PI_SHELL_PREFIX;
if (v === undefined) {
  console.error("КРАСНОЕ 025-И-2: вызов factory не присвоил process.env.PI_SHELL_PREFIX — префикс мёртв (декой: модуль без присвоения)");
  process.exit(1);
}
console.log("prefix-ok");
console.log(Buffer.from(v, "utf8").toString("base64"));
' 2>&1)"; rc=$?

if [ "$rc" -ne 0 ] || [ "$(printf '%s\n' "$out" | sed -n 1p)" != "prefix-ok" ]; then
  printf '%s\n' "$out" >&2
  exit 1
fi
ACTUAL="$(printf '%s\n' "$out" | sed -n 2p | base64 -d)"

# ── ПОЛОСА 2: замороженная форма — живая семантика простого префикса ──
if [ "$ACTUAL" = "$ORACLE" ]; then
  rc_can="$(wrc "$ACTUAL" 'yes | head -1')"
  rc_7="$(wrc "$ACTUAL" 'exit 7')"
  rc_ft="$(wrc "$ACTUAL" 'false | true')"
  rc_x="$(wrc "$ACTUAL" 'exit 141')"
  if [ "$rc_can" -ne 0 ]; then
    printf 'КРАСНОЕ 025-И-2: замороженная форма сломала канарейку (yes|head → %s, ожидание 0) — семантический дрейф против §B-1\n' "$rc_can" >&2
    exit 1
  fi
  if [ "$rc_7" -ne 7 ] || [ "$rc_ft" -ne 1 ]; then
    printf 'КРАСНОЕ 025-И-2: замороженная форма трогает коды/pipefail (exit 7 → %s, false|true → %s; ожидание 7 и 1) — дрейф против §B-1\n' "$rc_7" "$rc_ft" >&2
    exit 1
  fi
  if [ "$rc_x" -ne 0 ]; then
    printf 'КРАСНОЕ 025-И-2: замороженная форма перестала маппить явный exit 141 (даёт %s, ожидание 0 по §B-1) — дрейф против §B-1\n' "$rc_x" >&2
    exit 1
  fi
  printf 'ИМЕНОВАННЫЙ ОСТАТОК Р3 (наблюдение, не красное): замороженная простая форма маппит и честный явный exit 141 в 0 (замер: exit 141 → %s); различение канарейка/честный-141 — Р3-очередь, ловец до перевода: маркер B-2 + детектор 024; оракул-кандидат уже судится полосой 3 этой фикстуры\n' "$rc_x"
  exit 0
fi

# ── ПОЛОСА 3: кандидатная форма — полное 141-различение ──
rc_can="$(wrc "$ACTUAL" 'yes | head -1')"
rc_141="$(wrc "$ACTUAL" 'exit 141')"
rc_7="$(wrc "$ACTUAL" 'exit 7')"
rc_ft="$(wrc "$ACTUAL" 'false | true')"
if [ "$rc_can" -ne 0 ]; then
  printf 'КРАСНОЕ 025-И-2: кандидатная форма сломала канарейку (yes|head → %s, ожидание 0) — легитимные grep -q/|head будут ложно-красными\n' "$rc_can" >&2
  exit 1
fi
if [ "$rc_141" -ne 141 ]; then
  printf 'КРАСНОЕ 025-И-2: 141-различения НЕТ — честный явный exit 141 проглочен (даёт %s, ожидание 141): форма ловит простой exit-код, но НЕ различает SIGPIPE-канарейку от честного 141\n' "$rc_141" >&2
  exit 1
fi
if [ "$rc_7" -ne 7 ] || [ "$rc_ft" -ne 1 ]; then
  printf 'КРАСНОЕ 025-И-2: кандидатная форма трогает коды (exit 7 → %s, false|true → %s; ожидание 7 и 1)\n' "$rc_7" "$rc_ft" >&2
  exit 1
fi
printf 'КРАСНОЕ 025-И-2: значение РАЗЛИЧАЕТ 141 (пробы: канарейка → 0, честный exit 141 → 141, exit 7 → 7, false|true → 1), но НЕ совпадает с замороженным оракулом §B-1 побайтово:\n  получено: %s\n  оракул:   %s\nЗаморозка §B-1 действует — перевод на кандидата (Р3-очередь) словом владельца\n' "$ACTUAL" "$ORACLE" >&2
exit 1
