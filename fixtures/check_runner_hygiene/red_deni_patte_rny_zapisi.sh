#!/usr/bin/env bash
# КРАСНОЕ 025-И-3 (пачка A-2): settings deny-паттерны баш-записи — единственный
# носитель стража, досягаемый для ДОЧЕРНИХ сессий (snapshot-цепь настроек).
# СЕГОДНЯ: секции нет → именованный отказ rc 1. ПОСЛЕ реализации: rc 0.
# Грамматика: маркер секции «# ── СТРАЖ ЗАПИСИ (контракт 025)» и НЕ МЕНЕЕ ТРЁХ
# правил с действием deny в bash.patterns .omp/config.yml. Точные паттерны —
# реализация с красно/зелёной батареей (ночные формы против легитимных); входы
# и их имена — в шапках фикстур (Н-39).
set -uo pipefail
ROOT="${1:-$(cd "$(dirname "$0")/../../.." && pwd)}"
CFG="$ROOT/.omp/config.yml"
[ -f "$CFG" ] || { printf 'КРАСНОЕ 025-И-3: %s отсутствует\n' "$CFG" >&2; exit 1; }
if ! grep -qF 'СТРАЖ ЗАПИСИ (контракт 025)' "$CFG"; then
  printf 'КРАСНОЕ 025-И-3: deny-паттерны записи отсутствуют — маркер секции не найден в %s; баш-канал записи (sed -i/printf >>/>) не стережётся ни в одной сессии, включая дочерние\n' "$CFG" >&2
  exit 1
fi
n="$(grep -c 'deny' "$CFG")"
if [ "$n" -lt 3 ]; then
  printf 'КРАСНОЕ 025-И-3: deny-правил меньше трёх (%d) — ночные формы sed -i/printf/перенаправление не покрыты раздельными правилами\n' "$n" >&2
  exit 1
fi
exit 0
