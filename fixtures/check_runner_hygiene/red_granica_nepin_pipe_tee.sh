#!/usr/bin/env bash
# КРАСНОЕ 025-B-5 (фикс-круг по вердикту адверсария 0e2ce58, блокер B-025-5,
# состояние unpinned-absolute-pipe-tee-silent): граница B НАЗВАНА замороженным
# текстом и потому обязана иметь ИСПОЛНЯЕМОЕ предъявление — вход absolute
# `pipe|tee` у НЕпиннованной сессии (worktree:null) обязан давать ИМЕНОВАННОЕ
# наблюдение «граница по спеке: непиннованный — абсолютные записи свободны»,
# а не молчание (ни один из пяти red_* её не вызывал, И-6 не требовал).
#
# ПРИВЯЗКА К ЗАМОРОЖЕННОМУ ТЕКСТУ (contracts/025-sreda-cwd-rc.md, тег
# frozen/contracts/025/1):
#   • C-1 (§Пачка C): «Сессия БЕЗ строки WORKTREE = главная: allowlist НЕ
#     сужается — главная сессия пишет по общим правилам проекта (Г1: страж
#     целит вектор, не тотальность записи; …)».
#   • Демаркация: НЕконформные — «запись в основной чекаут И чужие worktree
#     (в т.ч. абсолютным путём — следствие А-72)»; ДОПОЛНЕНИЕ этой строки —
#     абсолютная запись ВНЕ этих целей у непиннованной свободна (Г2 «запись
#     абсолют … таргетно»). Настоящий ред предъявляет именно границу
#     дополнения: цель mktemp в ${TMPDIR} вне repo/осн. чекаута/чужих worktree
#     и вне allowlist Г3 (не dev-harness-verify) — pass обязан быть следствием
#     семантики непинна, а не allowlist.
#
# СУБЪЕКТ: пин-ветвь .omp/extensions/path-guard.ts (judge-протокол И-1/И-5).
# Реальная запись НЕ исполняется: граница — именованное РЕШЕНИЕ судьи
# (прецедент формы И-1/И-5); реальное последствие того же входа измерено
# самим адверсарием (tee создал внешний файл).
#
# ВЕТВИ:
#   1 «граница-B-абсолют-pipe-tee-в-непинне» → pass  (именованное наблюдение
#     печатается; декои «сужение allowlist главной/blanket-блок абсолютов»
#     умирают здесь — нарушение C-1 «allowlist НЕ сужается»);
#   2 «тот-же-путь-под-пинном» → block Н-85  (контроль остроты: pass ветви 1 —
#     семантика непинна, а не дыра: тот же путь под пинном блокируется);
#   3 «относительный-вектор-и-в-главной» → block Н-85  (непинн НЕ освобождает
#     относительную запись — A-1 «и в главной — worktree:null»).
#
# ИЗМЕРЕННЫЙ ОСТАТОК (вне предмета реда, А-125): при worktree:null абсолют
# pipe|tee в ОСНОВНОЙ чекаут и в ЧУЖОЙ каталог тоже проходит (pass), хотя
# Демаркация называет их НЕконформными — семантика непиннованной главной на
# этих целях есть развилка владельца; ред эти входы НЕ утверждает.
set -uo pipefail
ROOT="${1:-$(cd "$(dirname "$0")/../../.." && pwd)}"
SUBJ="$ROOT/.omp/extensions/path-guard.ts"

if [ ! -f "$SUBJ" ]; then
  printf 'КРАСНОЕ 025-B-5: механизм отсутствует — %s не существует; граница B (непиннованный абсолют pipe|tee) не предъявлена и не стережётся\n' "$SUBJ" >&2
  exit 1
fi

PIN="$(mktemp -d "${TMPDIR:-/tmp}/pg025granica.XXXXXX")"
TGT_DIR="$(mktemp -d "${TMPDIR:-/tmp}/pg025cel.XXXXXX")"   # вне repo, вне allowlist Г3
TGT="$TGT_DIR/target-$RANDOM.txt"
trap 'rm -rf "$PIN" "$TGT_DIR"' EXIT

fail() {  # <ветвь> <детали>
  printf 'КРАСНОЕ 025-B-5: ветвь «%s» — %s\n' "$1" "$2" >&2
  exit 1
}

# expect <ветвь> <block|pass|refuse> <подстрока reason> <json> — форма И-1/И-5
expect() {
  local vetka="$1" want="$2" substr="$3" evt="$4" out rc dec
  out="$(node "$SUBJ" --judge "$evt")"; rc=$?
  if [ "$rc" -ne 0 ]; then
    fail "$vetka" "субъект не ответил решением (rc $rc, вывод: ${out:-<пусто>}) — декой/сломанный модуль"
  fi
  dec="$(printf '%s' "$out" | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{try{const j=JSON.parse(s);console.log(j.decision??"")}catch(e){console.log("BAD_JSON")}})')"
  if [ -z "$dec" ] || [ "$dec" = "BAD_JSON" ]; then
    fail "$vetka" "субъект не ответил решением-JSON (вывод: ${out:-<пусто>})"
  fi
  if [ "$dec" != "$want" ]; then
    fail "$vetka" "ожидалось $want, получено $dec (вывод: $out)"
  fi
  if [ -n "$substr" ]; then
    case "$out" in
      *"$substr"*) ;;
      *) fail "$vetka" "reason без «$substr»: $out" ;;
    esac
  fi
}

# 1: ГРАНИЦА B — именованное наблюдение, не молчание
expect "граница-B-абсолют-pipe-tee-в-непинне" pass "" \
  "{\"tool\":\"bash\",\"args\":{\"command\":\"printf X | tee $TGT\"},\"worktree\":null,\"actual\":null}"
printf 'КРАСНОЕ 025-B-5: граница по спеке: непиннованный (главная, worktree:null) — абсолютные записи свободны (C-1 «allowlist НЕ сужается»; Демаркация: неконформные абсолюты — только осн. чекаут/чужие worktree); вход pipe|tee → %s предъявлен, молчания нет\n' "$TGT" >&2

# 2: контроль остроты — тот же путь под пинном блокируется
expect "тот-же-путь-под-пинном" block "Н-85" \
  "{\"tool\":\"bash\",\"args\":{\"command\":\"printf X | tee $TGT\"},\"worktree\":\"$PIN\",\"actual\":\"$PIN\"}"

# 3: непинн НЕ освобождает относительный вектор (A-1: и в главной)
expect "относительный-вектор-и-в-главной" block "Н-85" \
  "{\"tool\":\"bash\",\"args\":{\"command\":\"printf X | tee rel$RANDOM.txt\"},\"worktree\":null,\"actual\":null}"

exit 0
