# ПРИЧИНА: по процедуре не принято
#
# Дрилл существует ради ЗЕЛЁНОЙ ветви, которую анти-плацебо доказать не умеет. Значит красным его
# предъявляет подставной барьер: `check_contract_frozen.sh`, который законной правки не признаёт и
# краснеет всегда. Так проверяется, что дрилл действительно СМОТРИТ на ответ барьеров, а не печатает
# «процедура принята» по факту собственного дохождения до конца.
#
# Зелёный контроль здесь — НАСТОЯЩИЕ барьеры рядом с копией дрилла: на них дрилл обязан вернуть
# ноль. Так фикстура разводит два случая: «дрилл работает» и «дрилл зелен всегда».
#
# Соседи копируются ПОИМЁННО, включая библиотеки: дрилл берёт барьеры рядом с собой, а те — свои
# библиотеки рядом с собой. Копия, собранная наугад, отставала бы от предмета при каждом новом
# соседе, поэтому список короткий и явный.
set -euo pipefail
mkdir -p "$WORK/scripts"
for f in freeze_contract.sh check_contract_frozen.sh check_charter.sh \
         next_id.sh lib_registry.sh lib_roles.sh; do
  cp "$REPO/scripts/$f" "$WORK/scripts/"
done

# Положительный контроль: настоящая пачка барьеров, дрилл обязан дать 0.
BARRIER_ROOT="$WORK" "$BARRIER"

# Обман: `check_contract_frozen.sh` подменён на всегда-красный. Процедура выполнена правильно, но
# барьер её не признаёт — дрилл обязан это заметить и отказать, а не дойти до конца и объявить
# приём.
{
  printf '#!/usr/bin/env bash\n'
  printf '# Подставной барьер: законной правки не признаёт.\n'
  printf '# Коды возврата: 0 — никогда, 1 — всегда.\n'
  printf 'printf "  FAIL изменён без новой заморозки: что-нибудь\\n" >&2\n'
  printf 'exit 1\n'
} > "$WORK/scripts/check_contract_frozen.sh"
chmod +x "$WORK/scripts/check_contract_frozen.sh"

BARRIER_ROOT="$WORK" "$BARRIER"
