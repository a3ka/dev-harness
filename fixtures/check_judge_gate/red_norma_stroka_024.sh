#!/usr/bin/env bash
# КРАСНОЕ контракта 024 — ветвь B (связка церемонии судьи с детектором),
# правка-круг 2: блокер 3 вердикта 4d1d265 — «у И-10 нет rc-команды, только
# чтение будущей норма-строки». Этот файл — rc-форма приёмки: дословность
# приземления норма-строки в roles/orchestrator.md проверяется ПРОГОНОМ
# (grep -F побайтово), а не чтением.
#
# Жизненный цикл (прецедент 023 (i), приземление 7df7483: норма-запрос
# исполнен оркестратором по замороженному тексту контракта, владелец-канал,
# REVIEWS: владелец):
#   СЕГОДНЯ (норма не приземлена)  → rc 1 «норма-строка 024 не приземлена»;
#   ПОСЛЕ приземления при done 024  → rc 0 «норма-строка 024 приземлена
#   дословно».
# Строка ниже — ЕДИНЫЙ источник (вторая копия — Демаркация/Ветвь B контракта
# 024, побайтово); владелец-канал приземляет её в roles/orchestrator.md
# дословно, сверка — эта (grep -F).
#
# Имя ВНЕ case_*-глоба раннера — НАМЕРЕННО (И-11 контракта 024).
# Коды возврата: 0 — строка приземлена дословно; 1 — именованный отказ.
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
ROLE="$REPO/roles/orchestrator.md"

NORM='- Детектор утечек основного чекаута (контракт 024, норма-запрос): снимок `bash scripts/check_no_leak.sh --snapshot <абс-корень>` до спавна пачки; `bash scripts/check_no_leak.sh --check <абс-корень>` перед каждым спавном судьи и перед событием (land/freeze/done), вызов и rc — строкой в задание судьи (стенограмма спавна); отказ детектора = СТОП и доклад, обходы = гейминг (норма 2026-09-08).'

[ -f "$ROLE" ] || {
  printf 'ОТКАЗ: норма-строка 024 не приземлена — roles/orchestrator.md отсутствует в %s\n' "$REPO" >&2
  exit 1
}
if grep -qF -- "$NORM" "$ROLE"; then
  printf 'норма-строка 024 приземлена дословно (grep -F, побайтово)\n' >&2
  exit 0
fi
printf 'ОТКАЗ: норма-строка 024 не приземлена — в roles/orchestrator.md нет дословной строки (владелец-канал при done 024, прецедент 7df7483): %s\n' "$NORM" >&2
exit 1
