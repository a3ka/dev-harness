#!/usr/bin/env bash
# Проба привязки слабых реализаций контракта 024 (Н-39: привязка стаба к входу —
# КОДОМ фикстур, не прозой контракта). Ожидания фаз СТАБИЛЬНЫ — и до, и после
# реализации 024; на живом дереве проба ничего не утверждает (его состояние —
# предмет «Красное сейчас» контракта, замер red-файлом напрямую).
#
# Каждая фаза подставляет в toy-корень scripts/check_no_leak.sh одну из форм
# детектора и гоняет red_detektor_utechek.sh ПРЯМЫМ запуском (как red_mera 021 —
# конверсии в case_* не подлежит до реализации):
#   фаза 1 — честная форма (stab_detektor_chestnyj.sh) → red rc 0: все 8 ворот
#             проходят против эталона договора целиком;
#   фаза 2 — слабая «всегда чисто» → red rc 1: умирает на воротах 1
#             «утечка после снимка» (дефект наблюдаем там, Н-39);
#   фаза 3 — слабая «без-снимка-пропускает» → red rc 1: умирает на воротах 5
#             «снимок отсутствует» (fail-closed церемониальной дыры);
#   фаза 4 — слабая «снимок-в-дереве» → red rc 1: умирает на воротах 8
#             «снятие/сверка не загрязняют» (байтовое сравнение porcelain);
#   фаза 5 — слабая «своя-cwd» → red rc 1: умирает на воротах 7
#             «cwd-независимость» (имя жертвы не названо, названа приманка);
#   фаза 6 — слабая «первый-снимок-навсегда» → red rc 1: умирает на воротах 6
#             «повторный снимок обновляет базу».
#
# Коды возврата: 0 — честная форма проходит, все слабые пойманы; 1 — именованный отказ
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
T="$(mktemp -d /tmp/probe024-detektor.XXXXXX)"
trap 'rm -rf "$T"' EXIT
fail() { printf 'ОТКАЗ: %s\n' "$*" >&2; exit 1; }

mk_toy() {  # <каталог> <файл-детектора>
  mkdir -p "$1/scripts" "$1/fixtures/check_judge_gate"
  cp "$2" "$1/scripts/check_no_leak.sh"
  cp "$HERE/red_detektor_utechek.sh" "$1/fixtures/check_judge_gate/"
}
run_red() {  # <каталог>
  bash "$1/fixtures/check_judge_gate/red_detektor_utechek.sh" 2>&1
}

# ── фаза 1: честная форма детектора ───────────────────────────────────────────
mk_toy "$T/r1" "$HERE/stab_detektor_chestnyj.sh"
out="$(run_red "$T/r1")" && rc=0 || rc=$?
[ "$rc" -eq 0 ] || fail "честная форма: red rc=$rc
$out"

# ── фаза 2: слабая «всегда чисто» (ворота 1) ─────────────────────────────────
mk_toy "$T/r2" "$HERE/stab_detektor_vsegda_chisto.sh"
out="$(run_red "$T/r2")" && rc=0 || rc=$?
[ "$rc" -ne 0 ] || fail "слабая «всегда чисто» не поймана: red rc=0
$out"

# ── фаза 3: слабая «без-снимка-пропускает» (ворота 5) ────────────────────────
mk_toy "$T/r3" "$HERE/stab_detektor_bez_snapshota_propuskaet.sh"
out="$(run_red "$T/r3")" && rc=0 || rc=$?
[ "$rc" -ne 0 ] || fail "слабая «без-снимка-пропускает» не поймана: red rc=0
$out"

# ── фаза 4: слабая «снимок-в-дереве» (ворота 8) ──────────────────────────────
mk_toy "$T/r4" "$HERE/stab_detektor_snimok_v_dereve.sh"
out="$(run_red "$T/r4")" && rc=0 || rc=$?
[ "$rc" -ne 0 ] || fail "слабая «снимок-в-дереве» не поймана: red rc=0
$out"

# ── фаза 5: слабая «своя-cwd» (ворота 7) ─────────────────────────────────────
mk_toy "$T/r5" "$HERE/stab_detektor_svoja_cwd.sh"
out="$(run_red "$T/r5")" && rc=0 || rc=$?
[ "$rc" -ne 0 ] || fail "слабая «своя-cwd» не поймана: red rc=0
$out"

# ── фаза 6: слабая «первый-снимок-навсегда» (ворота 6) ───────────────────────
mk_toy "$T/r6" "$HERE/stab_detektor_pervyj_snimok_navsegda.sh"
out="$(run_red "$T/r6")" && rc=0 || rc=$?
[ "$rc" -ne 0 ] || fail "слабая «первый-снимок-навсегда» не поймана: red rc=0
$out"

printf 'пойманы: всегда-чисто (в1), без-снимка-пропускает (в5), снимок-в-дереве (в8), своя-cwd (в7), первый-снимок-навсегда (в6); честная форма договора проходит все 8 ворот\n' >&2
exit 0
