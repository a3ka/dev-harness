#!/usr/bin/env bash
# Красный контрпример блокера Б4 адверсария к8 contracts-024-k8.md
# (правка-круг после 8748823, контракт 024):
#
#   Одна сверка (do_check) читает состояние НЕАТОМАРНО: `manifest()` внутри
#   зовёт `emit_manifest` (git status) и `emit_dotgit_manifest` (walk
#   .git/hooks+.git/info+.git/config) ДВУМЯ отдельными producer-вызовами.
#   Между ними — окно. До фикса Б4 do_check делал РОВНО ОДИН такой прочёт
#   (`cur="$(manifest "$CANON" '')"`, коммит c9f2797, диф 5a188af9
#   @@ -726,13 +757,50 @@). Атакующий кладёт в `.git/info/exclude` правило,
#   скрывающее утечку, дожидается, пока `emit_manifest` (git status) это
#   правило уже видит (утечка скрыта из porcelain), затем ВОССТАНАВЛИВАЕТ
#   exclude к байтам снимка ДО того, как `emit_dotgit_manifest`-walk дойдёт
#   до чтения `.git/info/exclude` (walk обходит `.git/info/*` в
#   алфавитном порядке — `exclude` читается ПОСЛЕДНИМ, после всех
#   паддинг-файлов `aNNNNN`, что и даёт наблюдаемое окно). porcelain не
#   видит утечку (правило действовало), walk не видит правку exclude
#   (байты уже восстановлены) — обе половины манифеста, ПО ОТДЕЛЬНОСТИ,
#   совпадают со снимком ⇒ дельта пуста ⇒ rc 0 «основной чекаут чист» при
#   физически живой утечке на диске. Репро адверсария (k8_toctou_repeat.py,
#   9000 паддинг-файлов, 5 попыток) — 5 из 5 ложных «чисто».
#
# ФИКСТУРА ПРЕДЪЯВЛЯЕТ ТРИ КОНТРОЛЯ:
#   * контроль 1 (честный вход, маленький toy, без паддинга) — rc 0 «чисто»:
#     фикс не сломал штатный путь без гонки.
#   * контроль 2 (паддинг не ослепляет — обычная видимая утечка на
#     паддинг-репо, БЕЗ гонки) — rc 1, имя утечки в выводе: паддинг-файлы
#     `.git/info/aNNNNN` сами по себе не мешают детекции, крас контроля 3 —
#     именно про гонку, не про объём `.git/info/`.
#   * контроль 3 (атака Б4, 5 независимых попыток — Е5/5 держит инвариант,
#     не однокадровая удача) — параллельный процесс мутирует exclude
#     (скрыть-утечку → восстановить-baseline) ВНУТРИ окна одной сверки;
#     КАЖДАЯ из 5 попыток обязана дать rc 1 с именной причиной
#     «мутировал»/«разошлось», НЕ ложное «чисто», утечка физически жива на
#     диске после завершения сверки.
#
# ЗАКРЫТИЕ КЛАССА (что делает контроль 3 зелёным): do_check в
# scripts/check_no_leak.sh (коммит 5a188af) вычисляет ПОЛНЫЙ манифест ДВАЖДЫ
# ПОДРЯД без другой работы между вызовами — `cur1="$(manifest "$CANON" '')"`
# (строка 784) и `cur2="$(manifest "$CANON" '')"` (строка 791). Если
# `[ "$cur1" != "$cur2" ]` (строка 798) — сам факт расхождения ЕСТЬ сигнал
# «дерево мутировало во время сверки»: именованный ОТКАЗ rc 1 с фразой
# «основной чекаут мутировал во время сверки — повторное чтение разошлось с
# первым» (строка 799), дальше делта против снимка НЕ считается (не «первое
# чтение решает», не «второе решает» — расхождение само есть отказ). При
# откате фикса (do_check вместо cur1/cur2/сравнения делает ОДИН вызов
# `cur="$(manifest "$CANON" '')"`, код c9f2797) окно гонки внутри ЭТОГО
# единственного вызова не ловится НИЧЕМ ⇒ rc 0 «чисто» ⇒ контроль 3 КРАСЕН
# (фикстура падает на первой же попытке) — регрессия ловится.
#
# ТАЙМИНГ (замерен на этой машине перед фиксацией параметров, не угадан):
# N=1500 паддинг-файлов даёт полный `--check` (два прочёта манифеста)
# порядка 4с, т.е. один walk доходит до чтения `exclude` (последней по
# алфавиту записи `.git/info/*`) примерно за ~1.9с; чтение `git status` в
# начале каждого прочёта укладывается в десятки мс. SLEEP_S=0.5 — с запасом
# ×3-5 над временем до статуса И с запасом ×3 под временем до чтения
# exclude в walk — окно «мутировал» держится детерминированно.
#
# Форма — по прецеденту red_dotgit_info_exclude_024.sh: собственный WORK вне
# дерева, TMPDIR редиректится в WORK, имена мусора случайны КАЖДЫЙ прогон,
# toy-репозиторий только `git init` (каталог .git — НЕ worktree-чекаут,
# узкая грань Н-95 вне предмета). Имя ВНЕ case_*-глоба раннера НАМЕРЕННО
# (И-11 контракта 024; тот же прецедент).
#
# Коды возврата: 0 — все три контроля прошли (фикс работает, 5/5 попыток
#               держат инвариант); 1 — именованный отказ (детектор
#               отсутствует, попытка дала ложное «чисто», ИЛИ именная
#               причина «мутировал»/«разошлось» не найдена в выводе).
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
SUBJ="$REPO/scripts/check_no_leak.sh"

[ -f "$SUBJ" ] || {
  printf 'ОТКАЗ: детектор отсутствует — scripts/check_no_leak.sh (реализация за implementer после заморозки 024)\n' >&2
  exit 1
}

# ЕДИНЫЙ источник фраз (Демаркация 024) — побайтово во всех проверках ниже.
P_ZAGR='основной чекаут загрязнён'
P_CHISTO='основной чекаут чист'

WORK="$(mktemp -d /tmp/red024-k8-b4-toctou.XXXXXX)"   # А-78: свежий WORK вне дерева
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/snaps"
export TMPDIR="$WORK/snaps"                       # снимки субъекта — в скратч прогона

ok()   { printf '  ok   %s (%s)\n' "$1" "$2" >&2; }
fail() { printf 'ОТКАЗ %s (%s): %s\n' "$1" "$2" "$3" >&2; exit 1; }

# Запуск субъекта (синхронный, для контролей 1-2): cwd=arg2, аргументы
# дальше — rc без пайпов (Н-84/Н-85).
run_subj() {
  local cwd="$1"; shift
  SUBJ_OUT="$( cd "$cwd" && bash "$SUBJ" "$@" 2>&1 )" && SUBJ_RC=0 || SUBJ_RC=$?
}
has() { printf '%s\n' "$SUBJ_OUT" | grep -qF -- "$1"; }

mk_main() {  # <каталог>
  mkdir -p "$1"
  printf 'toy content\n' > "$1/toy.txt"
  GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null \
    git init -q -b main "$1"
  GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null \
    git -C "$1" -c user.name=Фикстура -c user.email=fixture@local \
      -c commit.gpgsign=false -c core.hooksPath=/dev/null add -A
  GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null \
    git -C "$1" -c user.name=Фикстура -c user.email=fixture@local \
      -c commit.gpgsign=false -c core.hooksPath=/dev/null \
      commit -q -m 'toy main'
}

# ─── контроль 1: честный вход (маленький toy, без паддинга, без гонки) ───────
# Регрессионная защита: двойной прочёт манифеста НЕ должен ломать штатный
# путь без мутации между cur1/cur2.
K1="$WORK/v1_chestnyj_${RANDOM}"
mk_main "$K1"
run_subj "$K1" --snapshot "$K1"
[ "$SUBJ_RC" -eq 0 ] || fail контроль-1 "снимок" \
  "снимок отказал rc=$SUBJ_RC. Вывод: $SUBJ_OUT"
run_subj "$K1" --check "$K1"
[ "$SUBJ_RC" -eq 0 ] || fail контроль-1 "честный вход" \
  "rc=$SUBJ_RC (ожидался 0). Вывод: $SUBJ_OUT"
has "$P_CHISTO" || fail контроль-1 "честный вход" \
  "нет маркера «$P_CHISTO». Вывод: $SUBJ_OUT"
ok контроль-1 "честный вход, без паддинга, без гонки: rc 0 «чисто»"

# ─── подготовка паддинг-репо K2 (переиспользуется контролями 2 и 3) ──────────
K2="$WORK/v2v3_padding_${RANDOM}"
mk_main "$K2"
PAD_N=1500
n=1
while [ "$n" -le "$PAD_N" ]; do
  printf 'x\n' > "$K2/.git/info/$(printf 'a%05d' "$n")"
  n=$((n + 1))
done
run_subj "$K2" --snapshot "$K2"
[ "$SUBJ_RC" -eq 0 ] || fail контроль-2 "снимок паддинг-репо" \
  "снимок отказал rc=$SUBJ_RC (N=$PAD_N паддинг-файлов). Вывод: $SUBJ_OUT"

# ─── контроль 2: паддинг НЕ ослепляет — обычная видимая утечка без гонки ─────
VIDIMYJ="vidimyj_padding_${RANDOM}_${RANDOM}.tmp"
printf 'leak\n' > "$K2/$VIDIMYJ"
run_subj "$K2" --check "$K2"
[ "$SUBJ_RC" -eq 1 ] || fail контроль-2 "видимая утечка на паддинг-репо" \
  "rc=$SUBJ_RC (ожидался 1) — $PAD_N паддинг-файлов .git/info/aNNNNN сами по себе ослепили детектор для ОБЫЧНОЙ утечки (не та механика: класс Б4 про гонку, не про объём). Вывод: $SUBJ_OUT"
has "$P_ZAGR" || fail контроль-2 "видимая утечка на паддинг-репо" \
  "нет фразы «$P_ZAGR». Вывод: $SUBJ_OUT"
has "$VIDIMYJ" || fail контроль-2 "видимая утечка на паддинг-репо" \
  "имя $VIDIMYJ не названо. Вывод: $SUBJ_OUT"
ok контроль-2 "видимая утечка на паддинг-репо (N=$PAD_N, без гонки): rc 1, $VIDIMYJ назван"
rm -f "$K2/$VIDIMYJ"
# Состояние вернулось к снимку (снимок писался без $VIDIMYJ) — переснимок не
# нужен, атака контроля 3 идёт от той же базы.

# ─── контроль 3: атака Б4 — гонка между porcelain и dot-git walk, Е5/5 ────────
EXCLUDE="$K2/.git/info/exclude"
BASELINE_STASH="$WORK/exclude_baseline_stash"
cp "$EXCLUDE" "$BASELINE_STASH"
SLEEP_S="0.5"
LEAK="$K2/timing-leak"
ATTEMPTS=5
i=0
while [ "$i" -lt "$ATTEMPTS" ]; do
  # Правило скрывает ровно $LEAK (имя фиксировано — та же механика, что
  # репро k8_toctou_repeat.py адверсария).
  printf 'timing-leak\n' > "$EXCLUDE"
  printf 'leak\n' > "$LEAK"
  OUTF="$WORK/atk_out_${i}"
  ( cd "$K2" && bash "$SUBJ" --check "$K2" ) > "$OUTF" 2>&1 &
  BG=$!
  sleep "$SLEEP_S"
  cp "$BASELINE_STASH" "$EXCLUDE"    # восстановление ДО того, как walk дойдёт до exclude
  wait "$BG"
  ATK_RC=$?
  SUBJ_OUT="$(cat "$OUTF")"
  SUBJ_RC="$ATK_RC"
  [ "$ATK_RC" -eq 1 ] || fail контроль-3 "попытка $i" \
    "rc=$ATK_RC (ожидался 1) — гонка exclude между porcelain и dot-git walk дала ложное «чисто» при живой утечке (блокер Б4 к8). Вывод: $SUBJ_OUT"
  if has "$P_CHISTO"; then
    fail контроль-3 "попытка $i" \
      "ложный маркер «$P_CHISTO» при живой утечке $LEAK на диске. Вывод: $SUBJ_OUT"
  fi
  has "мутировал во время сверки" || fail контроль-3 "попытка $i" \
    "нет именной причины «мутировал во время сверки» — rc=1 получен, но НЕ через двойной прочёт (do_check:798-799), другая причина. Вывод: $SUBJ_OUT"
  has "разошлось с первым" || fail контроль-3 "попытка $i" \
    "нет фразы «разошлось с первым» (do_check:799). Вывод: $SUBJ_OUT"
  [ -f "$LEAK" ] || fail контроль-3 "попытка $i" \
    "утечка $LEAK физически исчезла с диска — сверка удалила чужой файл"
  ok контроль-3 "попытка $i/$((ATTEMPTS - 1)): rc 1, «мутировал во время сверки»/«разошлось с первым» назван, утечка жива на диске"
  rm -f "$LEAK"
  i=$((i + 1))
done

printf 'red_toctou_manifest_024: 3 контроля зелены (блокер Б4 к8 — гонка exclude между porcelain и dot-git walk ловится 5/5 попыток именной причиной)\n' >&2
exit 0
