#!/usr/bin/env bash
# Красная проба унаследованного TOCTOU v6 (контракт 024, правка v6 :322-325 —
# re-анкер за architect; вход восходит к блокеру Б4 адверсария к8
# contracts-024-k8.md, фикс 5a188af — двойное чтение do_check сохранён):
#
#   Одна сверка (do_check) читает состояние НЕАТОМАРНО и ДВАЖДЫ ПОДРЯД:
#   `cur1="$(manifest …)"` и `cur2="$(manifest …)"` (check_no_leak.sh:964-977),
#   и каждый прочёт сам состоит из трёх producer-ног (TRACKED, UNTRACKED,
#   DOTGIT-walk), между которыми окна. Двойное чтение ловит ТОЛЬКО
#   НЕСОГЛАСОВАННУЮ мутацию: cur1 ≠ cur2 ⇒ «мутировал во время сверки»
#   (:978-982) — отказ БЕЗ имени носителя.
#
#   STABLE-HIDE (прецедент: вердикт к9, раздел «Направленные атаки задания:
#   что УДЕРЖАЛОСЬ», абзац «Б4, обе мутации ВНУТРИ обоих чтений» —
#   contracts-024-k9.md:143-147; отличие re-анкера: подмена ЛЕТИТ В ОКНО
#   первого прочтёта, а не обкладывает сверку снаружи): атакующий подменяет
#   `.git/info/exclude` ОДНОКРАТНО И НАВСЕГДА ВНУТРИ окна первого прочтёта —
#   после того как cur1 прошёл ноги TRACKED/UNTRACKED (десятки мс), но ДО
#   того как DOTGIT-walk дочитал паддинг `.git/info/aNNNNN` до `exclude`
#   (последней по алфавиту записи .git/info — обход glob-порядком,
#   emit_dotgit_manifest_walk :603). Оба прочтёта видят ОДНО И ТО ЖЕ
#   подменённое состояние ⇒ cur1 = cur2 ⇒ двойное чтение НЕ расходится
#   (механизм Б4 к8 по построению слеп к согласованной подмене) ⇒ остаётся
#   ТОЛЬКО дельта против снимка: строка `DOTGIT:<sha>\t.git/info/exclude`
#   меняет sha ⇒ rc 1 «основной чекаут загрязнён: .git/info/exclude»
#   (+ имя утечки от ноги-2 UNTRACKED — она МИМО ignore-правил, скрытие
#   инертно для неё).
#
# ФИКСТУРА ПРЕДЪЯВЛЯЕТ ТРИ КОНТРОЛЯ:
#   * контроль 1 (честный вход, маленький toy, без паддинга) — rc 0 «чисто»:
#     двойной прочёт не ломает штатный путь без мутации между cur1/cur2.
#   * контроль 2 (паддинг не ослепляет — обычная видимая утечка на
#     паддинг-репо, БЕЗ гонки) — rc 1, имя утечки в выводе: паддинг-файлы
#     `.git/info/aNNNNN` сами по себе не мешают детекции, крас контроля 3 —
#     именно про окно двойного прочтёта, не про объём `.git/info/`.
#   * контроль 3 (stable-hide, 5 независимых попыток — Е5/5 держит инвариант,
#     не однокадровая удача) — подмена exclude летит ВНУТРИ окна первого
#     прочтёта (тайминг замерен, см. ниже) и остаётся стабильной до конца
#     сверки; КАЖДАЯ из 5 попыток обязана дать rc 1 с ИМЕНЕМ НОСИТЕЛЯ
#     `.git/info/exclude` в выводе — поймано дельтой (do_check :984-995,
#     имя = путь после таба). Фраза двойного прочтёта НЕ ожидается и НЕ
#     требуется: расхождение cur1/cur2 имени носителя не несёт, и его
#     появление краснеет ассертом носителя как дефект тайминга (подмена
#     легла ВНЕ окна первого прочтёта). Утечка и подменённый exclude
#     физически живы на диске после сверки.
#
# ЗАКРЫТИЕ (что делает контроль 3 зелёным): дельта против снимка в do_check
# (check_no_leak.sh:984-995) называет DOTGIT-строку путём после таба —
# `.git/info/exclude`. При регрессии (DOTGIT-walk по .git/info удалён либо
# дельта не считается) согласованная подмена не даёт НИ расхождения, ни
# дельты ⇒ rc 0 «чисто» при живой утечке и подменённом exclude ⇒ контроль 3
# КРАСЕН — регрессия ловится.
#
# ТАЙМИНГ (замерен зондом на этой машине ПЕРЕД фиксацией параметров, не
# угадан; N=1500): один полный прочёт + запись снимка 4.3-5.1 с, полная
# сверка (два прочтёта) 10.6-11.4 с ⇒ DOTGIT-walk первого прочтёта дочитывает
# до `exclude` (последняя запись .git/info) ≈ через 4-5 с от старта сверки;
# ноги TRACKED+UNTRACKED первого прочтёта укладываются в первые ~0.1 с.
# SLEEP_S=0.5 — ПОСЛЕ ног 1-2 (запас ×5) и ЗАДОЛГО до чтения exclude в cur1
# (запас ×8-10): подмена детерминированно летит внутри окна первого прочтёта.
#
# Форма — по прецеденту red_dotgit_info_exclude_024.sh: собственный WORK вне
# дерева, TMPDIR редиректится в WORK, имена мусора случайны КАЖДЫЙ прогон,
# toy-репозиторий только `git init` (каталог .git — НЕ worktree-чекаут,
# узкая грань Н-95 вне предмета). Имя ВНЕ case_*-глоба раннера НАМЕРЕННО
# (И-11 контракта 024; тот же прецедент).
#
# Коды возврата: 0 — все три контроля прошли (дельта называет носителя
#               стабильной подмены, 5/5); 1 — именованный отказ (детектор
#               отсутствует, попытка дала ложное «чисто», ИЛИ rc=1 получен
#               БЕЗ имени носителя — расхождением двойного прочтёта либо
#               слепотой DOTGIT-ноги).
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
SUBJ="$REPO/scripts/check_no_leak.sh"

[ -f "$SUBJ" ] || {
  printf 'ОТКАЗ: детектор отсутствует — scripts/check_no_leak.sh (реализация за implementer после заморозки 024)\n' >&2
  exit 1
}

# ЕДИНЫЙ источник фраз (Демаркация 024) — побайтово во всех проверках ниже.
P_ZAGR='основной чекаут загрязнён'
P_CHISTO='основной чекаут чист'

WORK="$(mktemp -d /tmp/red024-k8-b4-toctou.XXXXXX)"   # А-78: свежий WORK вне дерева
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/snaps"
export TMPDIR="$WORK/snaps"                       # снимки субъекта — в скратч прогона

ok()   { printf '  ok   %s (%s)\n' "$1" "$2" >&2; }
fail() { printf 'ОТКАЗ %s (%s): %s\n' "$1" "$2" "$3" >&2; exit 1; }

# Запуск субъекта (синхронный, для контролей 1-2): cwd=arg2, аргументы
# дальше — rc без пайпов (Н-84/Н-85).
run_subj() {
  local cwd="$1"; shift
  SUBJ_OUT="$( cd "$cwd" && bash "$SUBJ" "$@" 2>&1 )" && SUBJ_RC=0 || SUBJ_RC=$?
}
has() { printf '%s\n' "$SUBJ_OUT" | grep -qF -- "$1"; }

mk_main() {  # <каталог>
  mkdir -p "$1"
  printf 'toy content\n' > "$1/toy.txt"
  GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null \
    git init -q -b main "$1"
  GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null \
    git -C "$1" -c user.name=Фикстура -c user.email=fixture@local \
    -c commit.gpgsign=false -c core.hooksPath=/dev/null add -A
  GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null \
    git -C "$1" -c user.name=Фикстура -c user.email=fixture@local \
    -c commit.gpgsign=false -c core.hooksPath=/dev/null \
    commit -q -m 'toy main'
}

# ─── контроль 1: честный вход (маленький toy, без паддинга, без гонки) ───────
# Регрессионная защита: двойной прочёт манифеста НЕ должен ломать штатный
# путь без мутации между cur1/cur2.
K1="$WORK/v1_chestnyj_${RANDOM}"
mk_main "$K1"
run_subj "$K1" --snapshot "$K1"
[ "$SUBJ_RC" -eq 0 ] || fail контроль-1 "снимок" \
  "снимок отказал rc=$SUBJ_RC. Вывод: $SUBJ_OUT"
run_subj "$K1" --check "$K1"
[ "$SUBJ_RC" -eq 0 ] || fail контроль-1 "честный вход" \
  "rc=$SUBJ_RC (ожидался 0). Вывод: $SUBJ_OUT"
has "$P_CHISTO" || fail контроль-1 "честный вход" \
  "нет маркера «$P_CHISTO». Вывод: $SUBJ_OUT"
ok контроль-1 "честный вход, без паддинга, без гонки: rc 0 «чисто»"

# ─── подготовка паддинг-репо K2 (переиспользуется контролями 2 и 3) ──────────
K2="$WORK/v2v3_padding_${RANDOM}"
mk_main "$K2"
PAD_N=1500
n=1
while [ "$n" -le "$PAD_N" ]; do
  printf 'x\n' > "$K2/.git/info/$(printf 'a%05d' "$n")"
  n=$((n + 1))
done
run_subj "$K2" --snapshot "$K2"
[ "$SUBJ_RC" -eq 0 ] || fail контроль-2 "снимок паддинг-репо" \
  "снимок отказал rc=$SUBJ_RC (N=$PAD_N паддинг-файлов). Вывод: $SUBJ_OUT"

# ─── контроль 2: паддинг НЕ ослепляет — обычная видимая утечка без гонки ─────
VIDIMYJ="vidimyj_padding_${RANDOM}_${RANDOM}.tmp"
printf 'leak\n' > "$K2/$VIDIMYJ"
run_subj "$K2" --check "$K2"
[ "$SUBJ_RC" -eq 1 ] || fail контроль-2 "видимая утечка на паддинг-репо" \
  "rc=$SUBJ_RC (ожидался 1) — $PAD_N паддинг-файлов .git/info/aNNNNN сами по себе ослепили детектор для ОБЫЧНОЙ утечки (не та механика: контроль 3 про окно двойного прочтёта, не про объём). Вывод: $SUBJ_OUT"
has "$P_ZAGR" || fail контроль-2 "видимая утечка на паддинг-репо" \
  "нет фразы «$P_ZAGR». Вывод: $SUBJ_OUT"
has "$VIDIMYJ" || fail контроль-2 "видимая утечка на паддинг-репо" \
  "имя $VIDIMYJ не названо. Вывод: $SUBJ_OUT"
ok контроль-2 "видимая утечка на паддинг-репо (N=$PAD_N, без гонки): rc 1, $VIDIMYJ назван"
rm -f "$K2/$VIDIMYJ"
# Состояние вернулось к снимку (снимок писался без $VIDIMYJ) — переснимок не
# нужен, атака контроля 3 идёт от той же базы.

# ─── контроль 3: stable-hide — согласованная подмена exclude В ОКНЕ, Е5/5 ────
EXCLUDE="$K2/.git/info/exclude"
CARRIER='.git/info/exclude'   # имя DOTGIT-строки в дельте: путь после таба
BASELINE_STASH="$WORK/exclude_baseline_stash"
cp "$EXCLUDE" "$BASELINE_STASH"
SLEEP_S="0.5"
LEAK="$K2/timing-leak"
ATTEMPTS=5
i=0
while [ "$i" -lt "$ATTEMPTS" ]; do
  # Утечка создаётся ДО старта сверки (стабильна для обоих прочтётов — не
  # источник расхождения cur1/cur2); правило скрывает ровно $LEAK от
  # porcelain-наблюдателей (та же механика, что репро к8/к9).
  printf 'leak\n' > "$LEAK"
  OUTF="$WORK/atk_out_${i}"
  ( cd "$K2" && bash "$SUBJ" --check "$K2" ) > "$OUTF" 2>&1 &
  BG=$!
  # Подмена летит ВНУТРИ окна первого прочтёта: cur1 уже прошёл ноги
  # TRACKED/UNTRACKED и хеширует паддинг aNNNNN; до чтения exclude (последней
  # по алфавиту записи .git/info) остаётся ≥4 с (замер шапки). Однократно,
  # СТАБИЛЬНО, без восстановления — двойное чтение расходиться не обязано.
  sleep "$SLEEP_S"
  printf 'timing-leak\n' > "$EXCLUDE"
  wait "$BG"
  ATK_RC=$?
  SUBJ_OUT="$(cat "$OUTF")"
  SUBJ_RC="$ATK_RC"
  [ "$ATK_RC" -eq 1 ] || fail контроль-3 "попытка $i" \
    "rc=$ATK_RC (ожидался 1) — согласованная (stable) подмена exclude внутри окна двойного прочтёта дала ложное «чисто» при живой утечке. Вывод: $SUBJ_OUT"
  if has "$P_CHISTO"; then
    fail контроль-3 "попытка $i" \
      "ложный маркер «$P_CHISTO» при живой утечке $LEAK на диске. Вывод: $SUBJ_OUT"
  fi
  has "$CARRIER" || fail контроль-3 "попытка $i" \
    "носитель $CARRIER не назван — rc=1 получен НЕ дельтой по .git/info/*: либо расхождением двойного прочтёта (имени носителя не несёт — подмена легла ВНЕ окна первого прочтёта, дефект тайминга), либо слепотой DOTGIT-ноги. Вывод: $SUBJ_OUT"
  # Sanity (post-factum, exclude ещё подменён): правило ДЕЙСТВИТЕЛЬНО прячет
  # утечку от porcelain — вход воспроизводит механику скрытия; детектор при
  # этом видит утечку МИМО правила (нога-2 UNTRACKED).
  if GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null \
     git -C "$K2" status --porcelain -uall 2>/dev/null | grep -qF -- 'timing-leak'; then
    fail контроль-3 "попытка $i" \
      "правило из подменённого exclude НЕ применилось — porcelain видит утечку, вход не воспроизводит механику скрытия"
  fi
  [ -f "$LEAK" ] || fail контроль-3 "попытка $i" \
    "утечка $LEAK физически исчезла с диска — сверка удалила чужой файл"
  [ -f "$EXCLUDE" ] || fail контроль-3 "попытка $i" \
    "подменённый $EXCLUDE физически исчез — сверка тронула файлы проверяемого"
  ok контроль-3 "попытка $i/$((ATTEMPTS - 1)): rc 1, носитель $CARRIER назван (stable-hide пойман дельтой), утечка и exclude живы"
  # Возврат к базе снимка для следующей попытки.
  cp "$BASELINE_STASH" "$EXCLUDE"
  rm -f "$LEAK"
  i=$((i + 1))
done

printf 'red_toctou_manifest_024: 3 контроля зелены (stable-hide — согласованная подмена .git/info/exclude внутри окна двойного прочтёта ловится дельтой по имени носителя, 5/5 попыток; re-анкер v6 :322-325)\n' >&2
exit 0
