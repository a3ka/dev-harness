#!/usr/bin/env bash
# Живая канарейка контракта 028 (предъявление 4/4, Н-98): соло-сессия харнесcа
# больше НЕ валит детектор собственного основного чекаута.
#
# Форма — canary_zhivoj_024.sh (та же церемония, тот же предмет-свидетель
# scripts/check_no_leak.sh — НЕ предмет 028 и не правится). Запускается на
# ЗАММИГРИРОВАННОМ живом дереве после предмета:
#
#   bash fixtures/check_judge_gate/canary_solo_028.sh <абс-корень>
#
# Делает: --snapshot → --check → повторный --check; все rc фиксируются строками
# в stderr, итог — rc обёртки. До предмета красна самотрипом Н-98 (шесть
# последовательных rc=1 «мутировал во время сверки» при чистом git status,
# соло-режим; единственный вне-carve-out мутатор окна —
# .zones/…/cache/composer/<hash>/status.json). После предмета сессия пишет
# мимо дерева → rc 0.
#
# Стаб-паттерн №5 (именной carve-out composer) опровергается МЕРОЙ контракта,
# не этой канарейкой: NOT-COVERED-набор шире composer (welcome.json,
# .npm/_logs/*.log, agent.db-чекпойнт, autoqa.db — все мимо :642-647), каждый
# апдейт omp переоткрывает класс; потому предмет — топология, не имя.
#
# Снимок пишется в ${TMPDIR:-/tmp}/dev-harness-leak/<hash8>/porcelain
# (последний выигрывает — договор детектора); живое дерево не меняет.
# Имя ВНЕ case_*-глоба раннера — НАМЕРЕННО (дом красных/канареек детектора,
# check_no_leak.sh:3-7). Коды: 0 — канарейка чиста; 1 — именованный отказ.
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
SUBJ="$REPO/scripts/check_no_leak.sh"

[ -f "$SUBJ" ] || {
  printf 'ОТКАЗ: детектор отсутствует — scripts/check_no_leak.sh\n' >&2
  exit 1
}
ROOT_ARG="${1:-}"
[ -n "$ROOT_ARG" ] || {
  printf 'ОТКАЗ диспетчер: использование: canary_solo_028.sh <абс-корень живого дерева>\n' >&2
  exit 1
}

step() {  # <аргументы...> — rc без пайпов (Н-84/Н-85)
  local out rc
  out="$(bash "$SUBJ" "$@" 2>&1)" && rc=0 || rc=$?
  printf '  канарейка-028 %s → rc=%s: %s\n' "$1" "$rc" "$out" >&2
  [ "$rc" -eq 0 ]
}

step --snapshot "$ROOT_ARG" || exit 1
step --check    "$ROOT_ARG" || exit 1
step --check    "$ROOT_ARG" || exit 1
printf 'канарейка 028 чиста: снимок → сверка → повторная сверка, все rc 0 — сессия пишет мимо судимого дерева\n' >&2
exit 0
