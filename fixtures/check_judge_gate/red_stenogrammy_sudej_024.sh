#!/usr/bin/env bash
# КРАСНОЕ контракта 024 — (г)-якорь «стенограмма спавна» (консультация №1
# glm ночь 2026-09-11, agent://ArchConsult-binding, раздел v2; вердикт
# адверсария d67ac4b блокер 3: норма-строка зеленеет, детектор никто не
# вызывает — «исполнимая связка» без носителя).
#
# ЧТО ПРОВЕРЯЕТСЯ (спецификация В2 дословно): каждый вердикт-файл судьи
# (verdicts/critic|adversary|reviewer|arbitration/), закоммиченный после
# приземления норма-строки, несёт строку вызова check_no_leak --check <корень>
# с rc (стенограмма спавна). Спавн без сверки умирает на вердикте, а не
# проходит зелёным.
#
# ГРАММАТИКА стенограммы (единый источник — ЭТОТ файл): строка вердикта,
# содержащая В ОДНУ строку и `check_no_leak`, и `--check`, и `rc`
# (например: «check_no_leak --check /корень → rc=0»). Иного формата нет.
#
# ГРАНИЦА активации (спецификация В2 дословно): коммит приземления
# норма-строки — `git log -1 -- roles/orchestrator.md`. До приземления
# (проверка приземления — red_norma_stroka_024.sh, единый источник строки,
# НЕ вторая копия) файл ВАКУУМНО-ЗЕЛЁНЫЙ: судить вердикты о стенограммах
# нельзя, пока нормы нет. ОСТАТОК назван (сам атом В2): граница — последний
# коммит, тронувший roles/orchestrator.md; более поздняя правка роли по
# другому поводу сдвинет границу вперёд — при v+1 владелец может пинить
# точный sha. Также вне механизма: спавн, не давший вердикта (кап/таймаут),
# и сговор судьи (вписать строку, не вызвав детектор) — ловятся аудитом
# стенограмм харнесса, не этой фикстурой.
#
# Жизненный цикл:
#   СЕГОДНЯ (норма не приземлена) → rc 0 «вакуумно-зелёная»;
#   ПОСЛЕ приземления             → rc 0, пока каждый новый вердикт несёт
#                                   строку вызова с rc;
#                                   rc 1 именованный «вердикт без стенограммы
#                                   детектора: <файл>» на первом вердикте без
#                                   строки.
#
# Имя ВНЕ case_*-глоба раннера — НАМЕРЕННО (как red_norma_stroka_024.sh,
# И-11 контракта 024). Файл ЗЕЛЁНЫЙ сегодня, активируется приземлением нормы
# (v+1-слово владельца — утром; текст контракта этой пачкой НЕ трогается).
#
# Коды возврата: 0 — вакуумно-зелёная (нормы нет) ИЛИ все вердикты после
#               границы несут стенограмму; 1 — именованный отказ «вердикт без
#               стенограммы детектора: <файл>».
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"

fail() { printf 'ОТКАЗ: %s\n' "$*" >&2; exit 1; }

# ── активация: норма-строка приземлена? (единый источник — sibling-фикстура)
if ! bash "$HERE/red_norma_stroka_024.sh" >/dev/null 2>&1; then
  printf '(г)-якорь: вакуумно-зелёная — норма-строка 024 не приземлена, вердикты о стенограммах не судятся (активация: владелец-канал при done 024)\n' >&2
  exit 0
fi

# ── граница: коммит приземления норма-строки (В2 дословно)
BOUNDARY="$(git -C "$REPO" log -1 --format=%H -- roles/orchestrator.md)" \
  || fail "граница не читается: git log -1 -- roles/orchestrator.md в $REPO"
[ -n "$BOUNDARY" ] || fail "граница пуста: git log -1 -- roles/orchestrator.md в $REPO"

# ── вердикты, закоммиченные ПОСЛЕ границы (все четыре судейских каталога)
mapfile -t VERDICTS < <(
  git -C "$REPO" log --diff-filter=A --format= --name-only \
    "$BOUNDARY"..HEAD -- \
    verdicts/critic verdicts/adversary verdicts/reviewer verdicts/arbitration \
    | sort -u | sed '/^$/d'
)
# Пустая выборка законна сразу после приземления (ни одного вердикта ещё нет).

GUILTY=""
for v in "${VERDICTS[@]}"; do
  f="$REPO/$v"
  [ -f "$f" ] || continue
  grep -qE 'check_no_leak.*--check.*rc' "$f" || GUILTY="$GUILTY$v"$'\n'
done

if [ -n "$GUILTY" ]; then
  printf 'ОТКАЗ: вердикт без стенограммы детектора: %s(граница: %s, грамматика: строка с check_no_leak + --check + rc одной строкой)\n' \
    "$GUILTY" "$BOUNDARY" >&2
  exit 1
fi

printf 'стенограммы судей 024: все вердикты после границы %s несут строку вызова детектора с rc\n' \
  "${BOUNDARY:0:12}" >&2
exit 0
