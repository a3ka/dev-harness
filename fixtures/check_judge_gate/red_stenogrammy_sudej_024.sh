#!/usr/bin/env bash
# КРАСНОЕ контракта 024 — (г)-якорь «стенограмма спавна» (консультация №1
# glm ночь 2026-09-11, agent://ArchConsult-binding, раздел v2; вердикт
# адверсария d67ac4b блокер 3: норма-строка зеленеет, детектор никто не
# вызывает — «исполнимая связка» без носителя).
# Правка-круг 2 — FAIL критика b5cd67f (verdicts/critic/contracts-024-v1.md,
# ОБА блокирующих обхода закрыты):
#   (1) :105 обещает «каждый вердикт-файл, закоммиченный после приземления»,
#       а перечисление было --diff-filter=A — только впервые ДОБАВЛЕННЫЕ.
#       Конвенция: вердикт ОБНОВЛЯЕТСЯ НА МЕСТЕ (версия файла = версия
#       заморозки, круги — в истории git). Теперь множество = A+M
#       (добавленные И обновлённые на месте), доказано критиком живьём:
#       fc5dcf3 обновил существующий вердикт без стенограммы — старая
#       фикстура rc=0 (ложное зелёное).
#   (2) :299 называла границу «git log -1 -- roles/orchestrator.md» — это
#       ПОСЛЕДНИЙ коммит ПУТИ, а не коммит приземления нормы: правка роли
#       по другому поводу (3a74b19) сдвигала границу вперёд и вычёркивала
#       виновный вердикт из проверки. Теперь граница = САМЫЙ РАННИЙ коммит,
#       ВНЁСШИЙ норма-строку в roles/orchestrator.md по диффу СОДЕРЖАНИЯ
#       (pickaxe -S, литерал): раннее внесение несдвигаемо будущими
#       коммитами по построению.
#
# ЧТО ПРОВЕРЯЕТСЯ (спецификация В2 дословно): каждый вердикт-файл судьи
# (verdicts/critic|adversary|reviewer|arbitration/), закоммиченный после
# приземления норма-строки ДОБАВЛЕНИЕМ ИЛИ ОБНОВЛЕНИЕМ, несёт строку вызова
# check_no_leak --check <корень> с rc (стенограмма спавна). Спавн без сверки
# умирает на вердикте, а не проходит зелёным.
#
# ГРАММАТИКА стенограммы (единый источник — ЭТОТ файл): строка вердикта,
# содержащая В ОДНУ строку и `check_no_leak`, и `--check`, и `rc`
# (например: «check_no_leak --check /корень → rc=0»). Иного формата нет.
#
# ГРАНИЦА (механизм и его границы названы):
#   - норма-строка берётся ПОБАЙТОВО из red_norma_stroka_024.sh (единый
#     источник; извлечение строки-примитива при каждом прогоне — НЕ вторая
#     копия, дрейф невозможен по построению);
#   - граница = самый ранний коммит, изменивший число вхождений норма-строки
#     в roles/orchestrator.md: git log --reverse --full-history -S<норма>;
#   - раннее внесение НЕСДВИГАЕМО: будущий коммит не может изменить то,
#     какой коммит внёс строку первым (уязвимость «последний коммит пути»
#     закрыта по построению, не фильтром);
#   --full-history — история нелинейна (land-мерджи): без него упрощение
#     истории может спрятать внесение, пришедшее боковой веткой;
#   - удаление норма-строки с позднейшим повторным внесением НЕ двигает
#     границу: остаётся ПЕРВОЕ внесение (строго безопаснее — охватывает
#     больше вердиктов); намеренно поздняя граница (переприземление) —
#     пин sha владельцем, вне механизма;
#   - стенограмма проверяется по СОСТОЯНИЮ ДЕРЕВА (текущая версия файла):
#     историческая версия без строки, закрытая позднейшим обновлением СО
#     строкой, не преследуется;
#   - переименованный вердикт ловится как ДОБАВЛЕННЫЙ (--no-renames: новое
#     имя = A, детерминизм без эвристики похожести);
#   - спавн, не давший вердикта (кап/таймаут), и сговор судьи (вписать
#     строку, не вызвав детектор) — ловятся аудитом стенограмм харнесса,
#     не этой фикстурой.
#
# Жизненный цикл:
#   СЕГОДНЯ (норма не приземлена) → rc 0 «вакуумно-зелёная»;
#   ПОСЛЕ приземления             → rc 0, пока каждый вердикт (добавленный
#                                   ИЛИ обновлённый) после границы несёт
#                                   строку вызова с rc;
#                                   rc 1 именованный «вердикт без стенограммы
#                                   детектора: <файл>» на первом вердикте без
#                                   строки.
#
# Имя ВНЕ case_*-глоба раннера — НАМЕРЕННО (как red_norma_stroka_024.sh,
# И-11 контракта 024). Файл ЗЕЛЁНЫЙ сегодня, активируется приземлением нормы
# (v+1-слово владельца — 2026-09-11; правка :299 «форма границы» круга 2 —
# по FAIL критика, в рамках того же слова, прецедент 005).
#
# Коды возврата: 0 — вакуумно-зелёная (нормы нет) ИЛИ все вердикты после
#               границы несут стенограмму; 1 — именованный отказ «вердикт без
#               стенограммы детектора: <файл>».
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"

fail() { printf 'ОТКАЗ: %s\n' "$*" >&2; exit 1; }

# ── активация: норма-строка приземлена? (единый источник — sibling-фикстура)
if ! bash "$HERE/red_norma_stroka_024.sh" >/dev/null 2>&1; then
  printf '(г)-якорь: вакуумно-зелёная — норма-строка 024 не приземлена, вердикты о стенограммах не судятся (активация: владелец-канал при done 024)\n' >&2
  exit 0
fi

# ── норма-строка: ПОБАЙТОВО из red_norma_stroka_024.sh (строка-примитив
#    NORM='...' без внутренних одинарных кавычек — отрезание префикса/суффикса
#    даёт исходные байты; источник перечитывается при каждом прогоне)
norm_src="$HERE/red_norma_stroka_024.sh"
[ -f "$norm_src" ] || fail "единый источник норма-строки не найден: $norm_src"
norm_line="$(grep -m1 "^NORM='" "$norm_src")" \
  || fail "норма-строка не извлечена: в $norm_src нет строки NORM='...'"
NORM="${norm_line#NORM=\'}"
NORM="${NORM%\'}"
[ "${#NORM}" -gt 200 ] \
  || fail "норма-строка не извлечена (подозрительно коротка, ${#NORM} байт): $norm_src"

# ── граница: коммит ПРИЗЕМЛЕНИЯ норма-строки — самый ранний коммит, внёсший
#    её в roles/orchestrator.md по диффу СОДЕРЖАНИЯ (pickaxe -S, литерал).
#    НЕ «последний коммит пути» (FAIL критика, обход 2): правка роли по
#    другому поводу сдвигала границу и вычёркивала виновный вердикт.
if ! all_landings="$(git -C "$REPO" log --reverse --full-history \
    --format=%H -S"$NORM" -- roles/orchestrator.md)"; then
  fail "граница не читается: git log -S по roles/orchestrator.md в $REPO"
fi
BOUNDARY="${all_landings%%$'\n'*}"
[ -n "$BOUNDARY" ] || fail "граница пуста: норма-строка есть в дереве (активация прошла), но git log -S не нашёл коммит её внесения в истории $REPO (незакоммиченное приземление?)"

# ── вердикты, закоммиченные ПОСЛЕ границы (все четыре судейских каталога):
#    ДОБАВЛЕННЫЕ и ОБНОВЛЁННЫЕ на месте (--diff-filter=AM — FAIL критика,
#    обход 1: A пропускал обновление на месте, конвенция «версия файла =
#    версия заморозки, круги — в истории git»). --no-renames: переименованный
#    вердикт = A (новое имя), детерминизм без эвристики похожести.
#    Пустая выборка законна сразу после приземления (ни одного вердикта нет).
mapfile -t VERDICTS < <(
  git -C "$REPO" log --no-renames --full-history --diff-filter=AM \
    --format= --name-only "$BOUNDARY"..HEAD -- \
    verdicts/critic verdicts/adversary verdicts/reviewer verdicts/arbitration \
    | sort -u | sed '/^$/d'
)

GUILTY=""
for v in "${VERDICTS[@]}"; do
  f="$REPO/$v"
  [ -f "$f" ] || continue
  grep -qE 'check_no_leak.*--check.*rc' "$f" || GUILTY="$GUILTY$v"$'\n'
done

if [ -n "$GUILTY" ]; then
  printf 'ОТКАЗ: вердикт без стенограммы детектора: %s(граница: %s — самое раннее внесение норма-строки; грамматика: строка с check_no_leak + --check + rc одной строкой)\n' \
    "$GUILTY" "$BOUNDARY" >&2
  exit 1
fi

printf 'стенограммы судей 024: все вердикты после границы %s (самое раннее внесение норма-строки) несут строку вызова детектора с rc\n' \
  "$BOUNDARY" >&2
exit 0
