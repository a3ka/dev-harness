#!/usr/bin/env bash
# НЕ БАРЬЕР: слабая форма детектора контракта 024 — «всегда чисто». Любой режим
# отвечает rc 0 «основной чекаут чист», ничего не проверяя. На входах «чисто»,
# «мусор до снимка», «чистка», «повторный снимок», «снимок отсутствует»,
# «cwd», «само-чистота» ведёт себя как честная форма (rc 0); дефект наблюдаем
# на воротах 1 red_detektor_utechek.sh — «утечка после снимка»: живой мусор
# (новый файл + модификация tracked) объявляется чистым, rc 1 не ставится,
# имена не называются. Привязка — кодом этой шапки и кодом пробы (Н-39).
set -uo pipefail
case "${1:-}" in --snapshot|--check) ;; *) printf 'ОТКАЗ диспетчер: использование: --snapshot|--check <корень>\n' >&2; exit 1 ;; esac
printf 'основной чекаут чист\n'
exit 0
