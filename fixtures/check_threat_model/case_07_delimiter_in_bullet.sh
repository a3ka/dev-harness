#!/usr/bin/env bash
# ПРИЧИНА: модель угроз: буллет ниже порога формы: дефис-в-буллете
# Р7 (green) — буллет содержит байт `:` ВНУТРИ данных: короткий префикс ДО
# первого ':' ("мало-совсем", НИЖЕ порога формы сам по себе) + длинное
# продолжение ПОСЛЕ ':'. Ожидание — ЦЕЛЫЙ буллет (не только префикс до ':')
# проходит порог формы, rc 0 (Направление 3, инвариант ii: представление
# без переиспользования байта данных разделителем — построчные массивы, не
# join+split строкой). Дискриминирует Б1 (verdicts/critic/contracts-041-
# v1.md): усечение по первому ':' оставило бы ТОЛЬКО префикс "мало-совсем"
# (1 слово, 10 алфавитно-цифровых знаков — ниже порога 4 слов/24 знаков), и
# барьер ошибочно отказал бы, хотя честный полный текст выше порога.
#
# Красная половина (конверсия на протокол verify_antiplacebo.sh, находка Н1
# verdicts/review/contracts-041-k1.md) — тот же байт-разделитель `-` ВНУТРИ
# буллета, но КОРОТКИЙ целиком (один пробельно-неразрывный токен,
# однозначно ниже порога): доказывает, что представление байта-разделителя
# массивом (не join+split) НЕ инфлирует длину соседних буллетов через
# делимитер — короткий с дефисом остаётся коротким и честно отказан.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/_toy.sh"

if [ -z "${BARRIER:-}" ]; then
  BARRIER="$SUBJ"
  WORK="$(mktemp -d "${TMPDIR:-/tmp}/tm_case07.XXXXXX")"
  trap 'rm -rf "$WORK"' EXIT
fi

put_contract "$WORK/g.md" '# kontrakt

## Predmet
p

## Модель угроз

ЗАЩИЩАЕТ:
- мало-совсем: достаточно длинное продолжение которое нельзя терять при разборе

НЕ ЗАЩИЩАЕТ:
- враждебное окружение вызывающего процесса за пределами базового PATH-экспорта'
run_barrier "$WORK" 'g.md'
[ "${BARRIER:-x}" = "$SUBJ" ] && accept 'case_07 (зелёный: делимитер внутри длинного буллета)'

put_contract "$WORK/r.md" '# kontrakt

## Predmet
p

## Модель угроз

ЗАЩИЩАЕТ:
- дефис-в-буллете

НЕ ЗАЩИЩАЕТ:
- враждебное окружение вызывающего процесса за пределами базового PATH-экспорта'
run_barrier "$WORK" 'r.md'
[ "${BARRIER:-x}" = "$SUBJ" ] && refuse 'case_07 (красный: делимитер внутри короткого буллета)' 'модель угроз: буллет ниже порога формы: дефис-в-буллете'

exit 0
