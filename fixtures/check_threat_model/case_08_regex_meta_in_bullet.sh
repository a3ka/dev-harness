#!/usr/bin/env bash
# ПРИЧИНА: модель угроз: буллет ниже порога формы: . * + ? [ ] ( ) ^ $ |
# Р8 (green) — буллет содержит ERE-метасимволы буквально (`. * + ? [ ] ( ) ^
# $ |`) → не интерпретируются как regex (сравнение меток/префикса —
# литеральное; содержимое буллета вообще не участвует в построении
# паттерна), rc 0 (Направление 3, инвариант iii).
#
# Красная половина (конверсия на протокол verify_antiplacebo.sh, находка Н1
# verdicts/review/contracts-041-k1.md) — ТЕ ЖЕ метасимволы, но БЕЗ
# пояснительных слов (буллет короче порога): доказывает, что метасимволы не
# участвуют и в СЧЁТЕ длины буллета каким-то regex-эффектом (например,
# случайное совпадение `.*` с «остатком строки» и ложное «прохождение»
# порога) — короткий буллет из одних метасимволов честно отказан ТЕМ ЖЕ
# путём, что и любой другой короткий буллет.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/_toy.sh"

if [ -z "${BARRIER:-}" ]; then
  BARRIER="$SUBJ"
  WORK="$(mktemp -d "${TMPDIR:-/tmp}/tm_case08.XXXXXX")"
  trap 'rm -rf "$WORK"' EXIT
fi

put_contract "$WORK/g.md" '# kontrakt

## Predmet
p

## Модель угроз

ЗАЩИЩАЕТ:
- символы . * + ? [ ] ( ) ^ $ | остаются буквами буллета а не regex-командами

НЕ ЗАЩИЩАЕТ:
- смысловую адекватность границы которую судит критик а не механический барьер'
run_barrier "$WORK" 'g.md'
[ "${BARRIER:-x}" = "$SUBJ" ] && accept 'case_08 (зелёный: метасимволы в длинном буллете)'

put_contract "$WORK/r.md" '# kontrakt

## Predmet
p

## Модель угроз

ЗАЩИЩАЕТ:
- . * + ? [ ] ( ) ^ $ |

НЕ ЗАЩИЩАЕТ:
- враждебное окружение вызывающего процесса за пределами базового PATH-экспорта'
run_barrier "$WORK" 'r.md'
[ "${BARRIER:-x}" = "$SUBJ" ] && refuse 'case_08 (красный: метасимволы без пояснения, короткий буллет)' 'модель угроз: буллет ниже порога формы: . * + ? [ ] ( ) ^ $ |'

exit 0
