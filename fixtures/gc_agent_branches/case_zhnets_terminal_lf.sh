# ПРИЧИНА: не удалось удалить tmp/done021
#
# Постоянная фикстура жнеца ./tmp (контракт 026, круг к2 адверсария): done-запись
# с ХВОСТОВЫМ LF в имени. Имя tmp/$'done021\n' — допустимое POSIX-имя; тег
# done/contracts/021/1 жив, запись свежая (−1ч), квалифицирует ТОЛЬКО done-тег
# (инвариант 3а: done реапает независимо от возраста). Вердикт к2: транспорт
# пути через command substitution ($() сжимает хвостовые LF) коллапсировал
# tmp/$'done021\n' в несуществующее tmp/done021 — rm -rf по усечённому пути
# возвращал 0, apply завершался rc 0 «успехом», а исходная LF-запись ЖИЛА.
#
# ЗЕЛЁНЫЙ контроль: apply → rc 0, запись tmp/$'done021\n' ОТСУТСТВУЕТ — реап
# дошёл до фактического удаления именно LF-имени; список назвал причину
# «done 021». КРАСНОЕ: та же запись воссоздана, удаление закрыто (chmod 555 на
# tmp и запись) → apply обязан отказаться rc 1 «не удалось удалить», назвав
# запись; запись ЦЕЛА (fail-closed). Состояние персистентно для повторного
# прогона проверяющего.
#
# СТАБ-ПРИВЯЗКИ (Н-39, по коду): S-cmdsub/S-base64 (декод пути через $():
# tmp/$'done021\n' ≡ tmp/done021) краснеет ЗЕЛЁНЫМ контролем — rc 0 при живой
# LF-записи, список печатает ложный усечённый путь; краснеет и КРАСНОЙ ветвью —
# rm идёт по несуществующему усечённому пути, отказа «не удалось удалить» не
# возникает (rc 0). Дефект наблюдаем на ЛЮБОМ входе с хвостовым LF — привязка к
# обоим предъявлениям этой фикстуры.
#
# Прямой прогон (`bash fixtures/gc_agent_branches/case_zhnets_terminal_lf.sh`):
# каркас _zhnets.sh сам назначает WORK/BARRIER; фикстура зелёна на фикс-базе
# (merge wip/026/implementer, a2c8125) и красна на пред-фикс блобе (a2c8125^)
# именованным «пережила apply».
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_zhnets.sh"

R="$WORK/repo-case-terminal-lf"
zhnec_igrushka "$R"
LFZ="$R/tmp/done021"$'\n'          # запись с реальным хвостовым LF в имени
mkdir -p -- "$LFZ"
printf 'done-запись с хвостовым LF\n' > "$LFZ/f"
vozrast_chasov "$LFZ" 1            # свежая: реап возможен ТОЛЬКО по done-тегу

# Зелёный контроль: apply — LF-запись реально удалена по done-тегу 021.
rc=0; out="$("$BARRIER" --root "$R" --tmp-reap-apply 2>&1)" || rc=$?
[ "$rc" -eq 0 ] || { printf 'ОТКАЗ: apply rc %s, ожидался 0:\n%s\n' "$rc" "$out" >&2; exit 1; }
printf '%s\n' "$out" | grep -Fq -- 'done 021' \
  || { printf 'ОТКАЗ: список не назвал причину «done 021»:\n%s\n' "$out" >&2; exit 1; }
[ ! -e "$LFZ" ] \
  || { printf 'ОТКАЗ: запись tmp/done021+LF пережила apply при rc 0 — транспорт пути коллапсирует хвостовой LF (к2, обход 1)\n' >&2; exit 1; }

# Красное: удаление воссозданной LF-записи невозможно — именованный отказ.
mkdir -p -- "$LFZ"
printf 'воссоздана для красной ветви\n' > "$LFZ/f"
vozrast_chasov "$LFZ" 1
chmod 555 "$R/tmp" "$LFZ"
rc=0; out="$("$BARRIER" --root "$R" --tmp-reap-apply 2>&1)" || rc=$?
[ "$rc" -eq 1 ] || { printf 'ОТКАЗ: apply при закрытой LF-записи дал rc %s, ожидался 1:\n%s\n' "$rc" "$out" >&2; exit 1; }
printf '%s\n' "$out" | grep -Fq -- 'не удалось удалить' \
  || { printf 'ОТКАЗ: отказ не назван «не удалось удалить» (инвариант 6). Вывод gc:\n%s\n' "$out" >&2; exit 1; }
printf '%s\n' "$out" | grep -Fq -- 'tmp/done021' \
  || { printf 'ОТКАЗ: отказ не называет LF-запись (правило 7). Вывод gc:\n%s\n' "$out" >&2; exit 1; }
[ -e "$LFZ/f" ] \
  || { printf 'ОТКАЗ: LF-запись повреждена вопреки отказу — fail-closed нарушен\n' >&2; exit 1; }
