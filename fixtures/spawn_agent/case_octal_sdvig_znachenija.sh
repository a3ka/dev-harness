# ПРИЧИНА: уже существует
#
# Контракт 019 v2 (блокер 1 критика, :119): проба обязана пиновать ЗНАЧЕНИЕ ветки.
# Живой факт (измерен критиком на main): `--nnn 042` даёт rc 0 и BRANCH=wip/034/architect
# (042-октал = 34) — тихая съезжка; rc-последовательность «rc 0 → rc 1 повтор» НЕ
# отличала фикшенный код от сломанного. Красное предъявляется ПИНОМ ЗНАЧЕНИЯ, а не rc.
#
# Входы:
#   * зелёный контроль: `--nnn 19` → rc 0, BRANCH=wip/019/architect (работает и сегодня);
#   * предмет: `--nnn 042` → rc 0, BRANCH=wip/042/architect ДОСЛОВНО (после фикса;
#     сегодня значение съезжает в wip/034/architect — assert ранит фикстуру ДО
#     красного кандидата: раннер не судит rc самой фикстуры при состоявшихся вызовах,
#     прогон даёт «красное не предъявлено» — красное ДО правки кода, правило 3);
#   * повторный спавн того же номера → rc 1 «уже существует» — прежнее поведение
#     сохраняется; это красный кандидат, засчитываемый повторным прогоном.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

R="$WORK/repo"
make_repo "$R"

# ── зелёный контроль: спавн без ведущего нуля ───────────────────────────────────
out="$("$BARRIER" --root "$R" --author architect --nnn 19 || true)"
br="$(printf '%s\n' "$out" | awk -F= '/^BRANCH=/ {print $2; exit}')"
if [ "$br" != 'wip/019/architect' ]; then
  printf 'ОТКАЗ: --nnn 19 дал BRANCH=%s, ожидался wip/019/architect: %s\n' "${br:-<пусто>}" "$out" >&2
  exit 1
fi

# ── предмет: ведущий ноль даёт ЗНАЧЕНИЕ 042, а не октал-съезжку 034 ─────────────
out="$("$BARRIER" --root "$R" --author architect --nnn 042 || true)"
br="$(printf '%s\n' "$out" | awk -F= '/^BRANCH=/ {print $2; exit}')"
if [ "$br" != 'wip/042/architect' ]; then
  printf 'ОТКАЗ: --nnn 042 дал BRANCH=%s, ожидался дословно wip/042/architect — октал-съезжка значения: %s\n' "${br:-<пусто>}" "$out" >&2
  exit 1
fi
if ! git -C "$R" show-ref --verify --quiet refs/heads/wip/042/architect; then
  printf 'ОТКАЗ: ветки wip/042/architect нет в refs/heads — значение BRANCH не подтверждено предметом\n' >&2
  exit 1
fi

# ── повторный спавн того же номера → именованный отказ (прежнее поведение) ──────
"$BARRIER" --root "$R" --author architect --nnn 042 || true   # ожидание: rc 1 «уже существует»
