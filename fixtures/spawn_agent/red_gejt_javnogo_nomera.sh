#!/usr/bin/env bash
# ПРЕД-ЗАМОРОЗОЧНОЕ КРАСНОЕ контракта 023, ветвь (ii) — гейт явного номера в
# spawn_agent (Н-77(г), дверь спавна). Договор: `--nnn N` требует живого
# refs/tags/id/CONTRACT/N (show-ref --verify точного имени) И ПРОВЕНАНС =
# DUAL-CONTROL (слово владельца 2026-09-08, вердикт 57c8141 блокер 1) — ВМЕСТЕ:
# (а) тот же тег достижим на origin (ls-remote точного имени) ∧ (б) манифест
# registry/contracts.tsv по ЖИВОЙ шапке refs/heads/main НА origin несёт строку
# «N → <tag-object-sha>» ∧ (в) sha тега на origin == sha строки — та же
# верификация, что условие 3 двери (iii): self-mint и агентский origin-push без
# манифеста открывают спавну любую дверь не хуже, чем draft-пуску. Отказы rc 1
# именованные: «номер N не выдан — спавн мимо реестра» (тега нет вовсе), «тег N
# не выдан авторитетом» (на origin нет ИЛИ строки манифеста нет ИЛИ sha
# разошёлся), «авторитет недоступен» (origin не отвечает/не настроен —
# fail-closed: обрыв сети не есть санкция). Место — после разбора аргументов
# (spawn_agent.sh:52-63), до локальной нумерации (:108). Спавн БЕЗ `--nnn` не
# меняется: автонумерация wip/* (:108-121) жива.
#
# Имя ВНЕ case_*-глоба раннера — НАМЕРЕННО (А-82, прецедент red_mera 021): до
# реализации предмет предъявляется ПРЯМЫМ запуском этого файла; конверсия в
# case_* — следующая пачка architect ПОСЛЕ реализации.
#
# ПАРАМЕТРИЗАЦИЯ СЛУЧАЙНЫМИ ВХОДАМИ (вердикт 57c8141 блокер 2; А-88): NNN из
# НЕПЕРЕСЕКАЮЩИХСЯ поддиапазонов, basename toy-корней и каталог-копия субъекта
# случайны (BARRIER_ROOT-паттерн) — обёртка с константным dispatch не собирается;
# приёмка — ДВА прогона подряд с разными входами.
#
# ВХОДЫ (Н-39 — привязка к ветвям по коду; номера РАЗНЫ между воротами):
#   в1 мимо реестра (стаб С4 «spawn-без-гейта» — нынешний код): --nnn N1, тега
#      нет → честный rc 1 «не выдан» (условие реестра первично, origin воротами
#      не опрашивается). СЕГОДНЯ спавн ПРОХОДИТ (rc 0, worktree создан) —
#      КРАСНОЕ предъявлено;
#   в2 чужой класс (стаб С5 «гейт-не-того-класса»): жив id/PLAN/N2, id/CONTRACT/N2
#      нет → честный rc 1; стаб, матчащий id/*/N2, пускает — ловится здесь;
#   в3 выдан авторитетом — пускает (положительный контроль): резерв ПОЛНОЙ
#      церемонией mint_rezerv (тег И строка манифеста НА origin/main) → rc 0,
#      WORKTREE/BRANCH=wip/N3/architect напечатаны. ЗЕЛЁНОЕ ДО и ПОСЛЕ (гейт не
#      свёрхблокирующий);
#   в4 без --nnn (канарейка автонумерации): --author sonic → rc 0,
#      BRANCH=wip/001/sonic. ЗЕЛЁНОЕ ДО и ПОСЛЕ;
#   в5 self-mint (стаб С9 «локальный тег = выдан», боль Б6 — слово владельца
#      2026-09-08): --nnn N5, тег создан ЛОКАЛЬНО и НЕ запушен на toy-origin —
#      ровно то, что делает агент из своего worktree (`next_id --issue`; refs
#      общие). Честный гейт: rc 1 «тег N5 не выдан авторитетом». СЕГОДНЯ спавн
#      ПРОХОДИТ — КРАСНОЕ;
#   в6 origin недоступен (стаб С10 «fail-open по сети»): резерв mint_rezerv N6,
#      затем origin перенаправлен на несуществующий путь (сетевой отказ
#      моделируется файлом — детерминированно). Честный гейт: rc 1 «авторитет
#      недоступен» (fail-closed, имя ОТДЕЛЬНОЕ от «не выдан авторитетом»).
#      СЕГОДНЯ спавн ПРОХОДИТ — КРАСНОЕ;
#   в7 АГЕНТСКИЙ origin-push БЕЗ МАНИФЕСТА (dual-control стаб, вердикт 57c8141
#      блокер 1): тег N7 заминчен локально и запушен на origin ФИКСТУРОЙ от
#      лица агента, строки «N7 → sha» в манифесте origin/main НЕТ. Честный
#      гейт: rc 1 «тег N7 не выдан авторитетом» (достижимости мало — авторитет
#      санкционирует СТРОКОЙ манифеста; стаб «ls-remote непуст = выдан» умирает
#      здесь). СЕГОДНЯ спавн ПРОХОДИТ — КРАСНОЕ.
#   в8  строка манифеста ТОЛЬКО на локальном main (арбитраж 94f2c15 п. 3, вход
#       А — убивает слабую форму «манифест с локального main», замер 4): тег
#       заминчен и запушен на origin «агентом» (как в7), строка «N8 → sha» (с
#       честным sha этого тега) закоммичена в манифест ЛОКАЛЬНОГО main, main НЕ
#       запушен — origin/main строки не несёт. Честный гейт: rc 1 «тег N8 не
#       выдан авторитетом» (3б: источник — ЖИВАЯ шапка origin/main, не локальная
#       ветка). СЕГОДНЯ спавн ПРОХОДИТ — КРАСНОЕ;
#   в9  повторный минт поверх резерва — sha разошёлся (арбитраж 94f2c15 п. 3,
#       вход Б — убивает слабую форму «sha не сверяется», замер 4): полный
#       резерв mint_rezerv N9, затем «агент» переминчивает тег (tag -d + tag -a
#       — новый tag-object) и force-пушит его на origin; строка манифеста
#       origin/main несёт ПРЕЖНИЙ sha. Честный гейт: rc 1 «тег N9 не выдан
#       авторитетом» (3в). СЕГОДНЯ спавн ПРОХОДИТ — КРАСНОЕ.
# Побочный эффект спавна — каталог worktree ВНЕ игрушечного репо
# (${TMPDIR}/dev-harness-worktrees/<hash8 корня>): каждое успешное подспавнивание
# убирается разобранным WORKTREE= (сегодня успешны ВСЕ входы — гейта нет).
#
# СЕГОДНЯ (гейта в коде нет) файл красен именованной причиной на в1 — это и есть
# предъявляемое красное (в5–в9 — тем же классом: спавн без отказа проходит).
# ПОСЛЕ реализации все ворота дают rc 0.
#
# Коды возврата: 0 — ворота пройдены; 1 — именованный отказ (гейт отсутствует
#               либо нарушил договор на воротах).
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
WORK="$(mktemp -d /tmp/red023-gejt.XXXXXX)"   # А-78: свежий WORK вне дерева
trap 'rm -rf "$WORK"' EXIT

# ── случайные входы: ОДИН процесс awk; поддиапазоны непересекающиеся:
# N1 120-199 · N2 200-269 · N3 300-369 · N5 500-569 · N6 600-669 · N7 700-789 ·
# N8 800-869 (вход А) · N9 870-939 (вход Б) — арбитраж 94f2c15: новые
# поддиапазоны вне занятых в7-и-ранее и red_dver/red_priznanie.
mapfile -t RD < <(awk 'BEGIN{srand();
  printf "%03d\n", 120+int(rand()*80);
  printf "%03d\n", 200+int(rand()*70);
  printf "%03d\n", 300+int(rand()*70);
  printf "%03d\n", 500+int(rand()*70);
  printf "%03d\n", 600+int(rand()*70);
  printf "%03d\n", 700+int(rand()*90);
  for (i=0;i<9;i++) printf "%d\n", 10000000+int(rand()*89999999);
  printf "%03d\n", 800+int(rand()*70);
  printf "%03d\n", 870+int(rand()*70)}')
N1="${RD[0]}"; N2="${RD[1]}"; N3="${RD[2]}"; N5="${RD[3]}"; N6="${RD[4]}"; N7="${RD[5]}"
N8="${RD[15]}"; N9="${RD[16]}"

# Субъект — копия scripts/ под случайным именем (BARRIER_ROOT-паттерн).
SPAWN="$WORK/subj-${RD[6]}/spawn_agent.sh"
cp -r "$REPO/scripts" "$WORK/subj-${RD[6]}"
# shellcheck disable=SC1091
. "$HERE/_repo.sh"

# run_spawn <toy> <аргументы spawn>… → $out/$rc, worktree убран
run_spawn() {
  local toy="$1"; shift
  out="$(bash "$SPAWN" --root "$toy" "$@" 2>"$WORK/err")" && rc=0 || rc=$?
  local wt
  wt="$(printf '%s\n' "$out" | sed -n 's/^WORKTREE=//p' | head -1)"
  if [ -n "$wt" ] && [ -d "$wt" ]; then rm -rf "$wt"; fi
}

# ── в1: мимо реестра (стаб С4 — нынешний код, определяющая дельта) ────────────
T1="$WORK/kor-${RD[6]}"
make_repo "$T1"
run_spawn "$T1" --author architect --nnn "$N1"
if [ "$rc" -ne 1 ] || ! grep -qF 'не выдан' "$WORK/err"; then
  printf 'ОТКАЗ: гейт явного номера отсутствует (стаб С4): спавн --nnn %s без тега id/CONTRACT/%s ПРОШЁЛ (rc %s, ожидан rc 1 «номер %s не выдан»): %s\n' "$N1" "$N1" "$rc" "$N1" "$(cat "$WORK/err")" >&2
  exit 1
fi

# ── в2: чужой класс (стаб С5 «гейт-не-того-класса») ─────────────────────────────
T2="$WORK/kor-$((RD[6]+1))"
make_repo "$T2"
g "$T2" tag -a "id/PLAN/$N2" -m 'выдача механизмом другого класса (фикстура-приманка)'
run_spawn "$T2" --author architect --nnn "$N2"
if [ "$rc" -ne 1 ] || ! grep -qF 'не выдан' "$WORK/err"; then
  printf 'ОТКАЗ: гейт не того класса (стаб С5): спавн --nnn %s при живом id/PLAN/%s без id/CONTRACT/%s ПРОШЁЛ (rc %s, ожидан rc 1 «не выдан»): %s\n' "$N2" "$N2" "$N2" "$rc" "$(cat "$WORK/err")" >&2
  exit 1
fi

# ── в3: выдан авторитетом — пускает (положительный контроль) ───────────────────
T3="$WORK/kor-$((RD[6]+2))"
make_repo "$T3"
toy_origin "$T3" >/dev/null
mint_rezerv "$T3" "$N3"
run_spawn "$T3" --author architect --nnn "$N3"
if [ "$rc" -ne 0 ]; then
  printf 'ОТКАЗ: гейт свёрхблокирующий: спавн --nnn %s при полном резерве mint_rezerv (тег и строка манифеста на origin) отказан (rc %s, ожидан rc 0): %s\n' "$N3" "$rc" "$(cat "$WORK/err")" >&2
  exit 1
fi
if ! printf '%s\n' "$out" | grep -qF 'WORKTREE=' \
   || ! printf '%s\n' "$out" | grep -qxF "BRANCH=wip/$N3/architect"; then
  printf 'ОТКАЗ: контракт вывода спавна нарушен (WORKTREE/BRANCH=wip/%s/architect): %s\n' "$N3" "$out" >&2
  exit 1
fi

# ── в4: без --nnn — автонумерация жива (канарейка) ─────────────────────────────
T4="$WORK/kor-$((RD[6]+3))"
make_repo "$T4"
run_spawn "$T4" --author sonic
if [ "$rc" -ne 0 ] \
   || ! printf '%s\n' "$out" | grep -qxF 'BRANCH=wip/001/sonic'; then
  printf 'ОТКАЗ: автонумерация wip/* сломана (ожидан rc 0, BRANCH=wip/001/sonic): rc %s, %s\n' "$rc" "$out" >&2
  exit 1
fi

# ── в5: self-mint (стаб С9 «локальный тег = выдан», боль Б6) ───────────────────
# Тег id/CONTRACT/N5 создан ЛОКАЛЬНО, toy-origin жив (main запушен), тег НЕ
# запушен — модель self-mint агента. Честный гейт: rc 1 «тег N5 не выдан
# авторитетом». Стаб С9 пускает (локальное существование = выдача) — умирает
# здесь.
T5="$WORK/kor-$((RD[6]+4))"
make_repo "$T5"
g "$T5" tag -a "id/CONTRACT/$N5" -m 'выдача механизмом (фикстура: self-mint, НЕ запушен)'
toy_origin "$T5" >/dev/null
run_spawn "$T5" --author architect --nnn "$N5"
if [ "$rc" -ne 1 ] || ! grep -qF 'не выдан авторитетом' "$WORK/err"; then
  printf 'ОТКАЗ: стаб С9 «self-mint»: спавн --nnn %s по локальному (вне origin) тегу ПРОШЁЛ (rc %s, ожидан rc 1 «тег %s не выдан авторитетом»): %s\n' "$N5" "$rc" "$N5" "$(cat "$WORK/err")" >&2
  exit 1
fi

# ── в6: origin недоступен (стаб С10 «fail-open по сети») ───────────────────────
# Резерв mint_rezerv N6, затем origin перенаправлен на несуществующий путь.
# Честный гейт: rc 1 «авторитет недоступен» (fail-closed — обрыв сети не есть
# санкция; имя отдельное от «не выдан авторитетом»). Стаб С10 умирает здесь.
T6="$WORK/kor-$((RD[6]+5))"
make_repo "$T6"
toy_origin "$T6" >/dev/null
mint_rezerv "$T6" "$N6"
g "$T6" remote set-url origin "$WORK/net-missing.git"
run_spawn "$T6" --author architect --nnn "$N6"
if [ "$rc" -ne 1 ] || ! grep -qF 'авторитет недоступен' "$WORK/err"; then
  printf 'ОТКАЗ: стаб С10 «fail-open по сети»: спавн --nnn %s при недоступном origin ПРОШЁЛ/не назван (rc %s, ожидан rc 1 «авторитет недоступен»): %s\n' "$N6" "$rc" "$(cat "$WORK/err")" >&2
  exit 1
fi

# ── в7: агентский origin-push БЕЗ манифеста (dual-control стаб, блокер 1) ──────
# Тег N7 заминчен локально и запушен на origin САМИМ «агентом» (фикстурой) —
# обход вердикта 57c8141: ls-remote становится непустым. Строки «N7 → sha» в
# манифесте origin/main НЕТ. Честный гейт: rc 1 «тег N7 не выдан авторитетом»
# (3б). Стаб «ls-remote непуст = выдан» умирает здесь.
T7="$WORK/kor-$((RD[6]+6))"
make_repo "$T7"
toy_origin "$T7" >/dev/null
g "$T7" tag -a "id/CONTRACT/$N7" -m 'выдача (модель: агентский минт + агентский пуш тега)'
g "$T7" push -q origin "refs/tags/id/CONTRACT/$N7"
run_spawn "$T7" --author architect --nnn "$N7"
if [ "$rc" -ne 1 ] || ! grep -qF 'не выдан авторитетом' "$WORK/err"; then
  printf 'ОТКАЗ: dual-control (блокер 1): спавн --nnn %s по агентски запушенному (без строки манифеста) тегу ПРОШЁЛ/не назван (rc %s, ожидан rc 1 «тег %s не выдан авторитетом»): %s\n' "$N7" "$rc" "$N7" "$(cat "$WORK/err")" >&2
  exit 1
fi

# ── в8: строка манифеста ТОЛЬКО на локальном main (арбитраж 94f2c15, вход А) ───
# Тег N8 заминчен и запушен на origin «агентом» (как в7), НО строка «N8 → sha»
# (с честным sha ЭТОГО тега) закоммичена в манифест ЛОКАЛЬНОГО main — main НЕ
# запушен: origin/main строки не несёт. Расщепляет ИСТОЧНИК манифеста: честный
# гейт читает ЖИВУЮ шапку origin/main (3б) и отказывает «тег N8 не выдан
# авторитетом»; слабая форма «манифест с локального main» пускает — умирает
# здесь. Сегодня спавн проходит — красное по имени.
T8="$WORK/kor-$((RD[6]+7))"
make_repo "$T8"
toy_origin "$T8" >/dev/null
g "$T8" tag -a "id/CONTRACT/$N8" -m 'выдача (модель: агентский минт + агентский пуш тега)'
g "$T8" push -q origin "refs/tags/id/CONTRACT/$N8"
sha8="$(git -C "$T8" rev-parse "refs/tags/id/CONTRACT/$N8")"
mkdir -p "$T8/registry"
printf '%s → %s\n' "$N8" "$sha8" >> "$T8/registry/contracts.tsv"
g "$T8" add -A
g "$T8" commit -q -m "реестр: строка $N8 (модель: агент коммитит локальный main, НЕ пушит)"
run_spawn "$T8" --author architect --nnn "$N8"
if [ "$rc" -ne 1 ] || ! grep -qF 'не выдан авторитетом' "$WORK/err"; then
  printf 'ОТКАЗ: dual-control (94f2c15, вход А): спавн --nnn %s по строке манифеста ТОЛЬКО на локальном main ПРОШЁЛ/не назван (rc %s, ожидан rc 1 «тег %s не выдан авторитетом»): %s\n' "$N8" "$rc" "$N8" "$(cat "$WORK/err")" >&2
  exit 1
fi

# ── в9: повторный минт поверх резерва — sha разошёлся (арбитраж 94f2c15, вход Б)
# Полный резерв mint_rezerv N9 (тег + строка с прежним sha на origin/main), затем
# «агент» переминчивает тег (tag -d + tag -a — новый tag-object) и force-пушит
# его на origin: sha тега на origin ≠ sha строки манифеста. Расщепляет СВЕРКУ:
# честный гейт отказывает «тег N9 не выдан авторитетом» (3в); слабая форма «sha
# не сверяется» пускает — умирает здесь. Сегодня спавн проходит — красное по
# имени.
T9="$WORK/kor-$((RD[6]+8))"
make_repo "$T9"
toy_origin "$T9" >/dev/null
mint_rezerv "$T9" "$N9"
g "$T9" tag -d "id/CONTRACT/$N9"
g "$T9" tag -a "id/CONTRACT/$N9" -m 'выдача (модель: повторный минт поверх резерва — sha разошёлся)'
g "$T9" push -q -f origin "refs/tags/id/CONTRACT/$N9"
run_spawn "$T9" --author architect --nnn "$N9"
if [ "$rc" -ne 1 ] || ! grep -qF 'не выдан авторитетом' "$WORK/err"; then
  printf 'ОТКАЗ: dual-control (94f2c15, вход Б): спавн --nnn %s по переминченному поверх резерва тегу (sha разошёлся) ПРОШЁЛ/не назван (rc %s, ожидан rc 1 «тег %s не выдан авторитетом»): %s\n' "$N9" "$rc" "$N9" "$(cat "$WORK/err")" >&2
  exit 1
fi

exit 0
