# ПРИЧИНА: первая выдача
#
# Дефект «дрилл принимает контрафактную выдачу 421, 422» (находка 7 второго круга).
# Прежний дрилл требовал только «разные трёхзначные, оба с тегами», и подставной
# `next_id.sh`, игнорирующий максимум и всегда начинающий с 421, проходил зелёным.
# Зелёный дрилл переставал доказывать, что выдача отвечает на вопрос «следующий номер
# в пустом репозитории» — случайный старт или зашитая последовательность проходили.
#
# Теперь дрилл требует РОВНО: первая выдача = max+1, вторая = max+2 (max — состояние
# ДО первого вызова; на пустой стойке max=0, ожидаемая первая 001, вторая 002).
# Подставной скрипт ниже начинает с 421 — первая выдача 421, ожидалась 001, и дрилл
# краснеет с НАЗВАННОЙ причиной «первая выдача 421, ожидалась 001». Так зелёный дрилл
# снова доказывает то, что обещает.
#
# Положительный контроль — НАСТОЯЩИЙ `next_id.sh` рядом с дриллом: на нём дрилл обязан
# вернуть ноль (две выдачи подряд 001 и 002).
set -euo pipefail

mkdir -p "$WORK/scripts"
# Рядом обязана лежать и библиотека грамматики роли: `next_id.sh` подключает её от
# своего каталога, а каталог здесь подставной.
cp "$REPO/scripts/next_id.sh" "$REPO/scripts/lib_roles.sh" "$WORK/scripts/"

# Положительный контроль: настоящий `next_id.sh` даёт max+1 и max+2 — зелёный.
BARRIER_ROOT="$WORK" "$BARRIER"

# Подставной барьер: игнорирует регистр выдачи, всегда начинает с 421, вторая 422.
# Оба номера разные и трёхзначные, оба создают теги — прежний дрилл принимал это
# зелёным; теперь первая не равна 001 (max=0 на пустой стойке), дрилл краснеет.
{
  printf '#!/usr/bin/env bash\n'
  printf '# Forge next_id.sh: ignore registry, start at 421, then 422.\n'
  printf '# Коды возврата: 0 — номер выдан, 1 — отказ, 2 — нечем проверить.\n'
  printf 'root="${1:-.}"; class="${2:-PLAN}"\n'
  printf 'n=421\n'
  printf 'while :; do\n'
  printf '  tag="id/${class}/$(printf %%03d "$n")"\n'
  printf '  if git -C "$root" tag "$tag" -m "forge" 2>/dev/null; then\n'
  printf '    printf "%%03d\\n" "$n"; exit 0\n'
  printf '  fi\n'
  printf '  n=$((n+1))\n'
  printf 'done\n'
} > "$WORK/scripts/next_id.sh"
chmod +x "$WORK/scripts/next_id.sh"
BARRIER_ROOT="$WORK" "$BARRIER"