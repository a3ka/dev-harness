# ПРИЧИНА: оба вызова дали
# Дрилл `drill_next_id_race.sh` существует ради зелёной ветви атомарности выдачи, которую
# анти-плацебо доказать не умеет: следующий номер по построению отличается от предыдущего.
# Значит красным дрилл предъявляется подставным `next_id.sh`, который выдаёт один и тот же
# номер. Образец — `drill_protected_exception.sh` и его фикстура с подменой
# `check_protected.sh`.
#
# Зелёный контроль здесь — НАСТОЯЩИЙ `next_id.sh` рядом с дриллом: на нём дрилл обязан
# вернуть ноль (два вызова дают РАЗНЫЕ номера). Так фикстура разводит «дрилл работает» и
# «дрилл красен потому, что выдача сломана».
set -euo pipefail
mkdir -p "$WORK/scripts"
cp "$REPO/scripts/next_id.sh" "$WORK/scripts/"
BARRIER_ROOT="$WORK" "$BARRIER"

# Подставной барьер: всегда выдаёт «001», оба вызова совпадают — дрилл обязан отказать.
{
  printf '#!/usr/bin/env bash\n'
  printf '# Подставной next_id.sh: резервации нет, номер всегда один.\n'
  printf '# Коды возврата: 0 — номер выдан, 1 — отказ, 2 — нечем проверить.\n'
  printf 'printf "001\\n"\n'
} > "$WORK/scripts/next_id.sh"
chmod +x "$WORK/scripts/next_id.sh"
BARRIER_ROOT="$WORK" "$BARRIER"