#!/usr/bin/env bash
# СТАБ (Н-39 — привязка кодом) семьи case_push_proba, диагональный вход H_без_ref
# (РЕШЕНИЕ арбитража f712e6e, п.1: пер-полевая форма различения).
#
# Чистый диапазон проходит; красный отвергнут причиной с ПОЛНЫМ sha и путём —
# о ПОЛНОМ ref причина молчит. Дефект наблюдаем именно здесь: фаза 2 push-пробы
# обязана умереть с «назвал причину без полного refs/heads/main». Проба, не
# судящая поле ref, этот вход пропускает — пережить его способна только проба,
# ассертящая все три поля тройки (b43d7a0).
#
# Грамматика предмета копируется, не переизобретается: судится M/D, добавление
# свободно (--diff-filter=MD) — иначе стаб умер бы на БАЗОВОМ пуше пробы (добавление
# contracts/001-x.md) как «чистый пуш отклонён», и молчание о поле не наблюдалось бы.
: 'scripts/check_charter.sh'
zero=0000000000000000000000000000000000000000
while read -r lref lsha rref rsha; do
  [ -n "${rsha:-}" ] || rsha="$zero"
  [ "$rsha" != "$zero" ] || rsha="$(git hash-object -t tree /dev/null)"
  paths="$(git diff --name-only --diff-filter=MD "$rsha" "$lsha" 2>/dev/null | grep -E '^(AGENTS\.md|ROADMAP\.md|(contracts|plans)/)' || true)"
  [ -z "$paths" ] && continue
  p="$(printf '%s\n' "$paths" | head -n 1)"
  printf 'ОТКАЗ: устав-дельта без РАЗРЕШИЛ: коммит %s, путь %s\n' "$lsha" "$p" >&2
  exit 1
done
exit 0
