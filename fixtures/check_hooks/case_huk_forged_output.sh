# ПРИЧИНА: не упомянут
#
# Находка (в) адверсария (forged-форма): pre-commit — обёртка-судья, печатает
# КОНСТАНТНОЕ «ОТКАЗ: имя с control-символом…» (rc≠0) без вызова реального судьи
# scripts/check_staged.sh и без ссылки на конкретное имя с control-символом.
# Закрыто ФАЗОЙ 2 двухфазной пробы СО СЛУЧАЙНЫМ ТОКЕНОМ (РЕШЕНИЕ 67fb3b1, §(в) замер 6):
# имя с control-символом на стадии staging содержит случайный токен, барьер требует
# `grep -F` по нему в выводе; forged не знает токена → «случайный токен X не упомянут»
# (возможна подделка вывода). Каждый вход красен СВОИМ: forged ловится фазой 2
# (а sniffer в case_huk_sniffer_toy — фазой 1).
#
# Канарейка-мета: всегда-красная подделка (rc≠0 на любом входе, без мини-фазы 1)
# ловится той же фазой 1, не фазой 2 — здесь важна именно обёртка, пропускающая
# чистый staged (rc=0) и рубящая нарушение константой. Случайный токен — генерация
# на каждый вызов пробы ($RANDOM), не литерал в коде.
set -uo pipefail
R="$WORK/meh"
# shellcheck disable=SC1091
. "$(dirname "$0")/_mehanizm.sh"
mehanizm "$R"

# Зелёный контроль: полный честный механизм → rc 0
out_green="$("$BARRIER" "$R" 2>&1)"
if [ "$?" -ne 0 ]; then
  printf 'ОТКАЗ: зелёный контроль не зелёный: %s\n' "$out_green" >&2; exit 1
fi

# Порча: forged — обёртка-судья. На чистом (нет control-символов) — exit 0, фазой 1
# проходит; на нарушении — exit 1 + КОНСТАНТНАЯ причина «имя с control-символом»,
# РЕАЛЬНОГО судью не зовёт, ТОКЕНА в выводе нет (он сгенерирован на каждый вызов пробы,
# константа в коде forged не знает).
cat > "$R/.githooks/pre-commit" <<'FORG'
#!/usr/bin/env bash
exec_dummy_path=scripts/check_staged.sh   # намёк на связь — НЕ-КОММЕНТАРНАЯ строка для awk,
                                          # реального вызова судьи нет
set -uo pipefail
found=0
while IFS= read -r -d '' f; do
  case "$f" in
    *$'\n'*|*$'\r'*|*$'\t'*) found=1 ;;
  esac
done < <(git diff --cached --name-only -z 2>/dev/null)
if [ "$found" -eq 1 ]; then
  printf 'ОТКАЗ: имя с control-символом: контрольное_имя_с_переносом\n' >&2
  exit 1
fi
exit 0
FORG

# Красное предъявление: фаза 2 ловит forged (случайный токен не упомянут)
out_red="$("$BARRIER" "$R" 2>&1 || true)"
if ! printf '%s\n' "$out_red" | grep -q 'не упомянут'; then
  printf 'ОТКАЗ: фикстура forged-output не предъявила причину «случайный токен не упомянут»: %s\n' \
    "$out_red" >&2
  exit 1
fi
