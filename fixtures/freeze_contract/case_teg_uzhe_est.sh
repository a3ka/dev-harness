# Имя тега может быть ЗАНЯТО по причине, которой писатель не моделирует, и тогда отказывает сам
# git — а барьер обязан этот отказ передать, а не проглотить. Своя проверка «а есть ли тег» была бы
# вторым разбором того же предмета: между проверкой и созданием остаётся щель, и два одновременных
# писателя проскочили бы оба. Пусть отказывает тот, кто владеет реестром.
#
# Порча берётся ДЕТЕРМИНИРОВАННАЯ, а не гонка двух процессов: ссылка `refs/tags/frozen/contracts/001/2/pometka`
# делает имя `refs/tags/frozen/contracts/001/2` неполучаемым (в git ссылка не может быть
# одновременно файлом и каталогом). Гонку пришлось бы ловить таймингом, а фикстура с таймингом
# краснеет и зеленеет от загрузки машины — то есть врёт о предмете.
#
# Зелёный контроль: первая заморозка → v1. Красное: writer считает v2, а это имя занять нельзя.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" contracts/001-x.md "первая версия" "$R"

put_verdict "$R" 2 accept
commit_all "$R" 'вердикт v2'
g "$R" tag -a frozen/contracts/001/2/pometka -m 'ссылка, занимающая имя следующей версии'
"$BARRIER" contracts/001-x.md "вторая версия в занятое имя" "$R"
