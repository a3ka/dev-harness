# Контракт 154: единица счёта — платная позиция START роли critic. Арбитраж о
# конечной границе (строка ARBITRAZH журнала) покрывает позицию 4 и только, и
# доказывается ЗАКОММИЧЕННОЙ строкой в basisCommit:basisPath — политика несёт
# законный путь (Н-26), а механизм держит счёт.
# Зелёный контроль: четыре платные сессии, санкция оркестратора на позицию 3 и
# арбитраж на позицию 4 → заморозка проходит. Красное: без арбитража позиция 4
# не покрыта → именованный отказ.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
lock154
R="$WORK/repo"
make_repo "$R"
put_verdict "$R" 1 FAIL
commit_all "$R" 'вердикт: FAIL'
put_verdict "$R" 1 accept
commit_all "$R" 'вердикт: accept'
put_verdict "$R" 2 accept
commit_all "$R" 'вердикт v2: accept'
"$BARRIER" contracts/001-x.md "accept + арбитраж после третьей позиции" "$R" "$(state154 "$R" 001 4 1 1)"

# Красное: арбитраж не покрывает позицию — основания нет.
# [154] Предмет БЕЗ следа в реестре заморозок (след = прежний порядок, И-7):
# отдельный предмет 002, замораживаемый впервые.
printf 'предмет, критерий готовности, РАБОТА НЕ РАЗДАЁТСЯ: кодификация\n' > "$R/contracts/002-y.md"
put_verdict_nnn "$R" 002 1 accept
commit_all "$R" 'предмет 002'
"$BARRIER" contracts/002-y.md "заморозка: арбитраж не покрывает позицию 4" "$R" "$(state154 "$R" 002 4 1 0)"
