# ПРИЧИНА: вердикта арбитра по этому предмету нет
#
# Арбитр, созванный на третьем круге, РАЗРЕШАЕТ заморозку — политика несёт
# законный путь (Н-26). Привязка арбитра к предмету — ТИТУЛЬНОЙ ГРАММАТИКОЙ
# «(контракт NNN)»: первый живой прогон поймал ложное совпадение по проходному
# упоминанию пути в теле чужого арбитража. Круг = смена ПЕРВОЙ СТРОКИ вердикта
# (контракт 013 §Б, Н-57); база — реальные смены первой строки v1, завершающиеся
# accept (для зелёного вызова HEAD-вердикт обязан быть accept).
# Зелёный контроль: серия реальных кругов + арбитр с маркером предмета в титле →
# заморозка v1 проходит. Красное (два экземпляра одного класса): арбитраж
# с предметом только в теле, без маркера в титле, — НЕ спасает; арбитраж вовсе
# без предмета — тоже. Красный вызов №1 несёт `|| true`: код возврата пишет
# СЕРВЕР канала, а фикстуре нужно дойти до красного №2 (до правки контракта 013
# ветвь №2 была мёртвой — set -e обрывал случай на первом красном).
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
put_verdict "$R" 1 FAIL
commit_all "$R" 'круг: смена первой строки на FAIL'
put_verdict "$R" 1 accept
commit_all "$R" 'круг: обратно accept'
put_verdict "$R" 1 FAIL
commit_all "$R" 'круг: снова FAIL'
put_verdict "$R" 1 accept
commit_all "$R" 'круг: финальный accept'
mkdir -p "$R/verdicts/arbitration"
printf '# Арбитраж: кап кругов (контракт 001)\nРЕШЕНИЕ: спор автора с критиком закрыт, заморозка разрешена\n' \
  > "$R/verdicts/arbitration/kap-001.md"
commit_all "$R" 'арбитраж: кап 001'
"$BARRIER" contracts/001-x.md "accept + арбитр после трёх кругов" "$R"

# Красное №1 (класс живого улова): путь есть в ТЕЛЕ, маркера в титле нет.
printf '# Арбитраж: чужой предмет (контракт 002)\nРЕШЕНИЕ: спор закрыт; `contracts/001-x.md` без раздела — проигнорирован.\n' \
  > "$R/verdicts/arbitration/kap-001.md"
put_verdict "$R" 2 accept
commit_all "$R" 'проходное упоминание + вердикт v2: accept'
"$BARRIER" contracts/001-x.md "заморозка: арбитр лишь упоминает предмет" "$R" || true

# Красное №2: арбитраж без предмета вовсе.
printf '# Арбитраж: спор закрыт вообще\nРЕШЕНИЕ: без предмета\n' \
  > "$R/verdicts/arbitration/kap-001.md"
commit_all "$R" 'арбитраж без предмета'
"$BARRIER" contracts/001-x.md "заморозка: арбитра нет" "$R"
