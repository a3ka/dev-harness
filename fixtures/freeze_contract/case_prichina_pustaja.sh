# ПРИЧИНА: неотличима от опечатки
#
# Заморозка без записанной причины неотличима от опечатки: тег остаётся в истории навсегда, а
# зачем он поставлен — уже не спросить. Это тот же класс, что безымянное `ALLOW-ARTIFACT-DELETE`:
# разрешение без причины есть индульгенция.
#
# Зелёный контроль: причина названа → v1. Красное: пустая строка второго аргумента.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" contracts/001-x.md "причина названа" "$R"

put_verdict "$R" 2 accept
commit_all "$R" 'вердикт v2'
"$BARRIER" contracts/001-x.md "" "$R"
