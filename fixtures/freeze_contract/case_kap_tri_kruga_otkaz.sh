# Контракт 154: единица счёта — платная позиция START роли critic по предмету,
# а не круг вердикта. Позиции 1–2 свободны; позиция 3 требует адресного
# основания (SANKTSIYA/ISPOLZOVANO с закоммиченной строкой). Третья позиция без
# основания — именованный отказ, заморозка не проходит.
# Зелёный контроль: одна платная сессия (позиция 1) → заморозка v1 проходит.
# Красное: три платные сессии без основания на третью позицию → отказ.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
lock154
R="$WORK/repo"
make_repo "$R"
"$BARRIER" contracts/001-x.md "accept прочитан" "$R" "$(state154 "$R" 001 1)"

# Платные позиции START: третья позиция — без адресного основания.
put_verdict "$R" 1 FAIL
commit_all "$R" 'вердикт: FAIL'
put_verdict "$R" 1 accept
commit_all "$R" 'вердикт: accept'
# Вердикт v2: красный вызов замораживает v2, без него отказ был бы «без
# вердикта», а не «кап вызовов» — ложный диагноз (класс Н-39).
put_verdict "$R" 2 accept
commit_all "$R" 'вердикт v2: accept'
# [154] Красная клетка — предмет БЕЗ следа в реестре заморозок: след был бы
# прежним порядком (И-7: «уже был в реестре» — прежний §6в дословно). Поэтому
# красная клетка — отдельный предмет 002, замораживаемый впервые.
printf 'предмет, критерий готовности, РАБОТА НЕ РАЗДАЁТСЯ: кодификация\n' > "$R/contracts/002-y.md"
put_verdict_nnn "$R" 002 1 accept
commit_all "$R" 'предмет 002'
"$BARRIER" contracts/002-y.md "заморозка после трёх платных вызовов без основания" "$R" "$(state154 "$R" 002 3)"
