# ПРИЧИНА: вердикта арбитра по этому предмету нет
#
# Решение владельца 2026-08-20 (D3): третий круг обязан созывать арбитра, счёт
# держит механизм, а не роль. Круг = коммит вердикта критика по предмету.
# Зелёный контроль: один круг, accept → заморозка v1 проходит. Красное: три
# круга без арбитра и без слова владельца → заморозка отказана.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" contracts/001-x.md "accept прочитан" "$R"

# Три круга: файл вердикта перезаписан и закоммичен трижды — как вживую.
printf 'accept\nкруг 2\n' > "$R/verdicts/critic/contracts-001-v1.md"
commit_all "$R" 'круг 2 вердикта'
printf 'accept\nкруг 3\n' > "$R/verdicts/critic/contracts-001-v1.md"
commit_all "$R" 'круг 3 вердикта'
# Вердикт v2: красный вызов замораживает v2, без него отказ был бы «без
# вердикта», а не «кап кругов» — ложный диагноз (класс Н-39).
put_verdict "$R" 2 accept
commit_all "$R" 'вердикт v2: accept'
"$BARRIER" contracts/001-x.md "заморозка после трёх кругов без арбитра" "$R"
