# ПРИЧИНА: вердикта арбитра по этому предмету нет
#
# Решение владельца 2026-08-20 (D3): третий круг обязан созывать арбитра, счёт
# держит механизм, а не роль. Круг = смена ПЕРВОЙ СТРОКИ вердикта (контракт 013 §Б,
# Н-57): коммит без смены первой строки кругом не является. База перестроена с
# трёх коммитов одного accept (счёт по коммитам, ложный для событий) на реальные
# смены первой строки.
# Зелёный контроль: один круг, accept → заморозка v1 проходит. Красное: серия
# реальных кругов (FAIL→accept→FAIL) без арбитра и без слова владельца → отказ.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" contracts/001-x.md "accept прочитан" "$R"

# Реальные круги — сменами первой строки v1: accept → FAIL → accept → FAIL
# (события [accept, FAIL, accept, FAIL, accept]; первое появление — круг 1).
put_verdict "$R" 1 FAIL
commit_all "$R" 'круг: смена первой строки на FAIL'
put_verdict "$R" 1 accept
commit_all "$R" 'круг: обратно accept'
put_verdict "$R" 1 FAIL
commit_all "$R" 'круг: снова FAIL'
# Вердикт v2: красный вызов замораживает v2, без него отказ был бы «без
# вердикта», а не «кап кругов» — ложный диагноз (класс Н-39).
put_verdict "$R" 2 accept
commit_all "$R" 'вердикт v2: accept'
"$BARRIER" contracts/001-x.md "заморозка после трёх кругов без арбитра" "$R"
