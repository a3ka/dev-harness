# ПРИЧИНА: вердикта арбитра по этому предмету нет
#
# Слово владельца — второй законный выход из капа (Н-26: у политики обязан
# быть явный клапан). Круг = смена ПЕРВОЙ СТРОКИ вердикта (контракт 013 §Б,
# Н-57); база — реальные смены первой строки v1, завершающиеся accept
# (HEAD-вердикт зелёного вызова обязан быть accept).
# Зелёный контроль: серия реальных кругов без арбитра, причина заморозки несёт
# строку «РАЗРЕШИЛ-ВЛАДЕЛЕЦ:» → заморозка v1 проходит, строка остаётся
# в сообщении тега реестра. Красное: без строки владельца → отказ.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
put_verdict "$R" 1 FAIL
commit_all "$R" 'круг: смена первой строки на FAIL'
put_verdict "$R" 1 accept
commit_all "$R" 'круг: обратно accept'
put_verdict "$R" 1 FAIL
commit_all "$R" 'круг: снова FAIL'
put_verdict "$R" 1 accept
commit_all "$R" 'круг: финальный accept'
"$BARRIER" contracts/001-x.md "РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md три круга закрыты, слово владельца 2026-08-20" "$R"

# Красное: та же история, причина без строки владельца — кап отказывает.
# Вердикт v2 приложен, иначе отказ был бы «без вердикта», а не «кап кругов».
put_verdict "$R" 2 accept
commit_all "$R" 'вердикт v2: accept'
"$BARRIER" contracts/001-x.md "заморозка без арбитра и без слова владельца" "$R"
