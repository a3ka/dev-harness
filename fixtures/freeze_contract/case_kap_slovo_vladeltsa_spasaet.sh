# ПРИЧИНА: вердикта арбитра по этому предмету нет
#
# Слово владельца — второй законный выход из капа (Н-26: у политики обязан
# быть явный клапан). Зелёный контроль: три круга без арбитра, причина заморозки
# несёт строку «РАЗРЕШИЛ-ВЛАДЕЛЕЦ:» → заморозка v1 проходит, строка остаётся
# в сообщении тега реестра. Красное: без строки владельца → отказ.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
printf 'accept\nкруг 2\n' > "$R/verdicts/critic/contracts-001-v1.md"
commit_all "$R" 'круг 2 вердикта'
printf 'accept\nкруг 3\n' > "$R/verdicts/critic/contracts-001-v1.md"
commit_all "$R" 'круг 3 вердикта'
"$BARRIER" contracts/001-x.md "РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md три круга закрыты, слово владельца 2026-08-20" "$R"

# Красное: та же история, причина без строки владельца — кап отказывает.
# Вердикт v2 приложен, иначе отказ был бы «без вердикта», а не «кап кругов».
put_verdict "$R" 2 accept
commit_all "$R" 'вердикт v2: accept'
"$BARRIER" contracts/001-x.md "заморозка без арбитра и без слова владельца" "$R"
