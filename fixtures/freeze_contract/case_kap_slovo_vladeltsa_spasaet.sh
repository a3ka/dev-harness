# Контракт 154: слово владельца открывает НАЗВАННУЮ позицию адресной санкцией
# (SANKTSIYA, istochnik=vladelec) — владелец называет позицию и OBJECT; строка
# «РАЗРЕШИЛ-ВЛАДЕЛЕЦ:» в причине заморозки остаётся в истории реестра.
# Зелёный контроль: четыре платные сессии, санкция оркестратора на позицию 3 и
# слово владельца на позицию 4 → заморозка проходит. Красное: без слова
# владельца позиция 4 не покрыта → именованный отказ.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
lock154
R="$WORK/repo"
make_repo "$R"
put_verdict "$R" 1 FAIL
commit_all "$R" 'вердикт: FAIL'
put_verdict "$R" 1 accept
commit_all "$R" 'вердикт: accept'
put_verdict "$R" 2 accept
commit_all "$R" 'вердикт v2: accept'
"$BARRIER" contracts/001-x.md "РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md позиция 4 открыта, слово владельца 2026-08-20" "$R" "$(state154 "$R" 001 4 1 0 1)"

# Красное: то же положение, но санкции владельца нет — позиция 4 не покрыта.
# [154] Предмет БЕЗ следа в реестре заморозок (след = прежний порядок, И-7):
# отдельный предмет 002, замораживаемый впервые.
printf 'предмет, критерий готовности, РАБОТА НЕ РАЗДАЁТСЯ: кодификация\n' > "$R/contracts/002-y.md"
put_verdict_nnn "$R" 002 1 accept
commit_all "$R" 'предмет 002'
"$BARRIER" contracts/002-y.md "заморозка без санкции владельца" "$R" "$(state154 "$R" 002 4 1 0 0)"
