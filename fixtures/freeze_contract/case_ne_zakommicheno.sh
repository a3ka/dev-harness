# ПРИЧИНА: только закоммиченное состояние
#
# Заморозить рабочее дерево значило бы заморозить то, чего в истории нет: тег указывал бы на
# коммит с ДРУГИМ содержимым файла, и «блоб побайтово совпадает» у читателя
# (`check_contract_frozen.sh`) стало бы ложью с первой же минуты.
#
# Зелёный контроль: дерево совпадает с HEAD → v1. Красное: файл правлен и не закоммичен.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" contracts/001-x.md "состояние совпадает с HEAD" "$R"

put_verdict "$R" 2 accept
commit_all "$R" 'вердикт v2'
printf 'правка мимо коммита\n' >> "$R/contracts/001-x.md"
"$BARRIER" contracts/001-x.md "попытка заморозить незакоммиченное" "$R"
