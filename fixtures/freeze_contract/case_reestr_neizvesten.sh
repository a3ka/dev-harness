# ПРИЧИНА: unknown-remote
#
# Четвёртое слово библиотеки заведено находкой критика: прежняя редакция выдавала НЕДОСТУПНЫЙ
# origin за `full`, и писатель спокойно считал версию по локальному максимуму. Если на недоступном
# origin уже лежит `frozen/contracts/001/1`, он создаёт второй `v1`.
#
# Асимметрия обоснована и проверяется здесь же: читатели трактуют `unknown-remote` как `full`
# (барьер, краснеющий от обрыва связи, выключают), а ПИСАТЕЛЬ отказывает — выдача идентификатора
# необратима.
#
# Зелёный контроль: дерево без origin вовсе → `full` → v1 (локальная работа законна).
# Красное: origin объявлен и указывает в никуда — сравнить НЕ УДАЛОСЬ.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" contracts/001-x.md "origin не объявлен — сравнивать не с чем" "$R"

put_verdict "$R" 2 accept
commit_all "$R" 'вердикт v2'
g "$R" remote add origin "$WORK/net-i-katalog-takogo"
"$BARRIER" contracts/001-x.md "origin объявлен, но недоступен" "$R"
