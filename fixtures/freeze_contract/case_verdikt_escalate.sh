# ПРИЧИНА: передал вопрос владельцу
#
# `ESCALATE` — не отказ по инженерной сути, а вопрос воли владельца: цена, риск, «чего мы хотим».
# Диагноз обязан отличаться от `FAIL`, иначе автор прочитает «критик против» там, где написано
# «решает владелец», и пойдёт спорить с судьёй вместо того, чтобы спросить хозяина.
#
# Зелёный контроль: v1 с `accept` → v1. Красное: v2 с первой строкой `ESCALATE`.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" contracts/001-x.md "accept прочитан" "$R"

put_verdict "$R" 2 ESCALATE
commit_all "$R" 'вердикт v2: ESCALATE'
"$BARRIER" contracts/001-x.md "заморозка при вопросе к владельцу" "$R"
