# ПРИЧИНА: существовал и на HEAD его нет: plans/001-p.md
#
# Контрпример критика (контракт 039, круг 1, блокер Б1, dccde2d): копия защищённого пути
# создаётся ЗАРАНЕЕ, отдельным коммитом ДО коммита, который исходный путь убирает. §Семантика
# п.1 (третий пункт) требует, чтобы путь q появился статусом A ИМЕННО в удаляющем коммите c —
# здесь q (notes/001-p.md) появляется коммитом РАНЬШЕ, а удаляющий коммит несёт только D(p), ни
# одного A. Реализация, проверяющая лишь «блоб B жив на HEAD под каким-то путём» (четвёртое
# условие) и пропускающая «q появился ИМЕННО в c» (третье условие), называет это переносом и
# зеленеет — ровно контрпример Б1. Оба условия обязаны выполняться ОДНОВРЕМЕННО: это красная
# проба на их конъюнкцию, а не на любое из них по отдельности.
#
# Прогон после второго коммита (копия уже лежит в notes/, оригинал в plans/ ещё жив) —
# положительный контроль: ничего не пропало, барьер зелёный в любой реализации. Финальный вызов
# после удаления оригинала БЕЗ ALLOW — красный в ОБОИХ мирах: до фикса (переноса не существует
# вовсе) и после честного фикса (перенос не признан, потому что q появился не в c). Красным
# здесь ловится именно реализация, зеленеющая по одному лишь «блоб жив где-то на HEAD».
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"
mkdir -p "$R/notes"
cp "$R/plans/001-p.md" "$R/notes/001-p.md"
g "$R" add notes/001-p.md
g "$R" commit -q -m 'копия плана в заметках, заранее'
"$BARRIER" "$R"
g "$R" rm -q plans/001-p.md
g "$R" commit -q -m 'план убран, без разрешения и без добавлений'
"$BARRIER" "$R"
