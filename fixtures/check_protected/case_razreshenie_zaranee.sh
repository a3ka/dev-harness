# ПРИЧИНА: существовал и на HEAD его нет: verdicts/adversary/v-a.md
#
# Вторая половина той же находки: разрешение выдаётся СЕБЕ ВПЕРЁД. Строка лежит в коммите,
# к удалению не относящемся вовсе, а удаляющий коммит её не содержит. Прежняя редакция
# соглашалась, потому что искала строку во всей достижимой истории.
#
# Отдельная фикстура, а не вариант предыдущей: там разрешение было настоящим и устарело, здесь
# его никогда не связывали с удалением. Для правила это разные основания отказа, а фикстура
# обязана держать основание, а не симптом.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

printf 'посторонняя заметка\n' > "$R/notes.txt"
g "$R" add -A
g "$R" commit -q -F - <<'MSG'
Заметка, к удалению не относящаяся

ALLOW-ARTIFACT-DELETE: verdicts/adversary/v-a.md разрешение выдано заранее и ни к чему не привязано
MSG
"$BARRIER" "$R"

g "$R" rm -q verdicts/adversary/v-a.md
g "$R" commit -q -m 'удаление без разрешения в своём теле'
"$BARRIER" "$R"
