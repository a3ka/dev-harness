# ПРИЧИНА: существовал и на HEAD его нет: plans/001-p.md
# ОКРУЖЕНИЕ: BASH_FUNC_comm%%=() { local a; for a in "$@"; do if [ "$a" = "-23" ]; then return 0; fi; done; command comm "$@"; }
#
# Н-130 (NABLIUDENIA.md), контракт 046. Доверенный PATH этого барьера
# (`export PATH=/usr/bin:/bin`, шапка check_protected.sh — закрытие PATH-spy адверсария круга
# 1 контракта 039, где фейковый `comm` в подложенном каталоге делал ЛЮБОЕ удаление без ALLOW
# зелёным) закрывает ПОДЛОЖЕННЫЙ КАТАЛОГ, но НЕ ИМЕНОВАННУЮ ЭКСПОРТИРОВАННУЮ bash-функцию:
# bash разрешает функции РАНЬШЕ $PATH при старте ЛЮБОГО дочернего bash, и унаследованная
# `export -f comm` (здесь — байт-в-байт эквивалентный сырой env `BASH_FUNC_comm%%=…`, та же
# сериализация, что Shellshock) переживает `export PATH=…` целиком: `env` меняет ТОЛЬКО
# переданную переменную, а не остальное окружение. Тот же класс уже закрыт на соседнем
# барьере (`scripts/check_zones.sh`, контракт 040, `fixtures/check_zones/
# case_ten_funkcii_git.sh`) — здесь он предъявляется ЭТОМУ барьеру, своим входом.
#
# ПОЧЕМУ ИМЕННО `comm` (Н-39 — стаб привязан к той ветви, где его дефект НАБЛЮДАЕМ): вся
# решающая разность барьера — ОДНА строка `comm -23 "$TMP/existed" "$TMP/head" >
# "$TMP/missing"`, и шапка файла называет `comm` прямо («та самая утилита, чей подмен даёт
# зелёное без ALLOW»). Тень делегирует настоящей утилите ВСЮДУ, кроме формы `-23`: там
# отдаёт ПУСТО с rc=0, то есть «ничего не исчезло». Множества `existed`/`head` при этом
# собираются по-настоящему (git не тронут), `command -v comm` внутри барьера видит тень и
# не отказывает rc=2, ни одной строки `FAIL` не печатается — барьер отвечает rc=0 на дереве,
# где защищённый артефакт исчез БЕЗ строки ALLOW-ARTIFACT-DELETE. Это компрометация ВСЕГО
# барьера, а не одной его ветви.
#
# Зелёный контроль: чистое дерево сразу после `make_repo` — честная разность пуста и без
# всякой тени, стаб на ней инертен по построению → rc=0, причина в выводе не печатается.
# Красное: `plans/001-p.md` удалён коммитом без разрешения, тень `comm` присутствует в
# окружении вызывающего — барьер ОБЯЗАН назвать ИМЕННО «существовал и на HEAD его нет:
# plans/001-p.md» (rc=1), а не смолчать rc=0 из-за подменённой разности.
#
# Мутант, потерявший блок «ГЕРМЕТИЧНОЕ ОКРУЖЕНИЕ» (re-exec через `env -i`) в шапке
# check_protected.sh, оживляет тень: разность становится пустой, ни один исчезнувший путь не
# доходит до суда, барьер отвечает rc=0 — красный прогон этой фикстуры пропадает, что
# ловится антиплацебо-протоколом («барьер остался зелёным на обманном дереве»).
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

g "$R" rm -q plans/001-p.md
g "$R" commit -q -m 'план удалён без ALLOW при тени comm в окружении'

"$BARRIER" "$R"
