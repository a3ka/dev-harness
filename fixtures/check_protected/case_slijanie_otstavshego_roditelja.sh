# Способ пятый, Н-127 (не-ослабление). Настоящее удаление БЕЗ разрешения спрятано за
# non-ff слиянием ветки, отставшей от момента удаления: B форкнута ДО удаления и файл не
# трогает; слияние --no-ff в A происходит ПОСЛЕ настоящего (неразрешённого) удаления, и
# относительно «отставшего» родителя B сам мерж-коммит выглядит как удаляющий — ТА ЖЕ
# топология, что чинит фикс Н-127 (excuse_for пропускает мерж-артефакты и ищет дальше
# настоящий удаляющий коммит). Разница с зелёным репро (repro_n127_otstavshij_roditel.sh) —
# ровно в одной строке: здесь у настоящего удаляющего коммита НЕТ ALLOW-ARTIFACT-DELETE.
# Пропуск мерж-артефакта обязан находить настоящий удаляющий коммит ДЛЯ ПРОВЕРКИ разрешения,
# а не выдавать индульгенцию всей топологии: без строки разрешения путь остаётся красным
# независимо от того, какой из кандидатов (мерж или сам он) барьер рассматривает первым.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"
g "$R" checkout -q -b vetka
printf 'независимая правка ветки\n' > "$R/plans/002-vetka.md"
commit_all "$R" 'B: независимая правка, файл не трогает'
g "$R" checkout -q main
g "$R" rm -q verdicts/adversary/v-a.md
g "$R" commit -q -m 'вердикт удалён БЕЗ разрешения'
g "$R" merge -q --no-ff vetka -m 'слияние отставшей ветки B (ALLOW нет нигде)'
"$BARRIER" "$R"
