# ПРИЧИНА: существовал и на HEAD его нет: verdicts/adversary/v-a.md
# ОКРУЖЕНИЕ: BASH_FUNC_unset%%=() { if [ "${1:-}" = "-f" ]; then return 0; fi; builtin unset "$@"; }
# ОКРУЖЕНИЕ: BASH_FUNC_comm%%=() { local a; for a in "$@"; do if [ "$a" = "-23" ]; then return 0; fi; done; command comm "$@"; }
#
# РЕКУРСИВНОЕ продолжение `case_ten_funkcii_comm.sh` (см. тот файл за объяснением базовой
# тени `comm` и почему PATH-пин её не ловит). Эта фикстура закрывает ОЧЕВИДНЫЙ НЕВЕРНЫЙ ФИКС
# — `unset -f <перечень доверенных имён>` сразу после `export PATH=…`, ту самую редакцию,
# которой контракт 040 лечил близнеца на кругах v5 и которая ПАЛА кругом позже
# (verdicts/adversary/contracts-040-v5-circle.md, `d46a615`): экспортированная функция
# `unset`, no-op'ящая ИМЕННО `-f`-форму и честная на `unset VAR` (чтобы не выдать себя
# крахом чистки `GIT_DIR`/`GIT_WORK_TREE`/… в шапке барьера), нейтрализует такую защиту
# целиком, а сам `unset` в перечень войти не может: перечень есть то, ЧЕМ снимают, самого
# себя им не снимешь. Следующее «ещё одно имя» ждала бы та же рекурсия — перечисление
# структурно не сходится.
#
# ПОЧЕМУ ЭТА ФИКСТУРА ОТДЕЛЬНА ОТ ПРЕДЫДУЩЕЙ (Н-39: свой вход на каждое предъявление): обе
# красны на СЕГОДНЯШНЕМ барьере, но различают РАЗНЫЕ реализации. `case_ten_funkcii_comm.sh`
# зеленеет от ЛЮБОГО из двух лечений (перечисление `unset -f` либо структурный re-exec);
# ЭТА — только от структурного, потому что перечисление здесь нейтрализовано. Без неё в
# дерево прошёл бы «фикс», зелёный на первой фикстуре и дырявый ровно тем же классом.
#
# Вход другой намеренно: исчезает `verdicts/adversary/v-a.md` — путь из области, ВЫВЕДЕННОЙ
# из поля `verdict:` роли, а не объявленной литералом `plans/`. Так красное предъявляется на
# ОБЕИХ ветвях сборки области, а не дважды на одной.
#
# Зелёный контроль: чистое дерево сразу после `make_repo` — честная разность пуста, обе тени
# инертны по построению → rc=0, причина в выводе не печатается.
# Красное: `verdicts/adversary/v-a.md` удалён коммитом без разрешения, ОБЕ тени в окружении
# вызывающего — барьер ОБЯЗАН назвать ИМЕННО «существовал и на HEAD его нет:
# verdicts/adversary/v-a.md» (rc=1), а не смолчать rc=0 из-за нейтрализованного `unset -f` и
# подменённой разности.
#
# Мутант, заменивший блок «ГЕРМЕТИЧНОЕ ОКРУЖЕНИЕ» (re-exec через `env -i`) на перечисление
# `unset -f …`, оживляет обе тени и отвечает rc=0 — красный прогон этой фикстуры пропадает,
# что ловится антиплацебо-протоколом («барьер остался зелёным на обманном дереве»).
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

g "$R" rm -q verdicts/adversary/v-a.md
g "$R" commit -q -m 'вердикт удалён без ALLOW при тенях unset и comm в окружении'

"$BARRIER" "$R"
