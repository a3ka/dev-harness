# ПРИЧИНА: нет поля verdict во фронтматтере
#
# Пятая форма, и самая тихая: поля нет вовсе. Прежняя редакция считала это «роль без
# вердиктов» и шла дальше — то есть завести роль без поля было способом не защищать её
# артефакты. Арбитраж: отсутствие поля — тоже неразобранное объявление.
#
# Законный способ сказать «вердиктов не предписано» остался и проверяется зелёным контролем:
# `verdict: null` грамматике соответствует.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
printf -- '---\nname: quiet\nverdict: null\n---\nроль без вердиктов, но по грамматике\n' > "$R/roles/quiet.md"
commit_all "$R" 'роль объявила null — это законно'
"$BARRIER" "$R"
printf -- '---\nname: quiet\n---\nроль без поля вовсе\n' > "$R/roles/quiet.md"
commit_all "$R" 'у роли отобрали поле verdict'
"$BARRIER" "$R"
