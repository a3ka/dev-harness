# ПРИЧИНА: роль вне объявленной грамматики
#
# Находка круга 2, предписанная арбитражем к закрытию отказом: `verdict: verdicts/*/` не
# превращается в префикс, и прежняя редакция МОЛЧА выводила каталог из области — то есть
# объявление служило выключателем собственной защиты.
#
# Проверяется не форма, а класс: любое значение вне объявленной грамматики даёт красное.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"
printf -- '---\nname: glob\nverdict: verdicts/*/\n---\nроль с шаблоном\n' > "$R/roles/glob.md"
commit_all "$R" 'роль объявила каталог вердиктов шаблоном'
"$BARRIER" "$R"
