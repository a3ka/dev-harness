# Способ восьмой, Н-127/арбитраж 042 (не-ослабление оракула, З2 таблицы арбитра). Criss-cross
# топология, построенная `commit-tree` (не обычным merge — нужна ИМЕННО эта форма DAG,
# недостижимая через checkout/merge): O создаёт путь; A = O с путём, удалённым разрешённо
# (D1, ALLOW); B — «молчащий» брат A (commit-tree с деревом O, родитель O, путь не трогает);
# P1 = merge(A,B) с ДЕРЕВОМ O (путь вручную ВОССТАНОВЛЕН, commit-tree); P2 = merge(B,A) с
# деревом A (путь отсутствует — то, что дал бы честный авто-мерж); M = merge(P1,P2) с деревом
# A (путь отсутствует) и БЕЗ ALLOW. У P1 и P2 ДВЕ общих базы (A и B, ни одна не предок другой)
# — `git merge-base` БЕЗ `--all` возвращает ОДНУ, произвольную. Оракул `git merge-tree
# --write-tree` считает виртуальную базу рекурсивно (merge(A,B) сам бесконфликтен: B молчит,
# A удалил → путь отсутствует) и честно мержит P1 (добавил путь относительно виртуальной базы)
# против P2 (молчит относительно виртуальной базы) — ПУТЬ ПРИСУТСТВУЕТ в результате: то, что
# унаследовал бы честный мерж, — присутствие, а не отсутствие M. M поэтому НЕ артефакт: он
# убрал путь САМ, ручным решением, и обязан нести собственный ALLOW — его нет. Прежняя ручная
# аппроксимация брала ОДНУ (любую) `git merge-base` — при ином историческом построении того же
# класса дерева она давала «путь у молчащего родителя == база, у другого пусто» и ложно
# извиняла M (измерено арбитром живым прогоном, verdicts/arbitration/042-dostatochnost-
# merge-base-semantiki.md, З2); оракул не читает единственную базу вовсе, устойчив к любому
# выбору git между двумя равноправными базами.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"
O=$(g "$R" rev-parse HEAD)
O_TREE=$(g "$R" rev-parse "$O^{tree}")
g "$R" rm -q verdicts/adversary/v-a.md
g "$R" commit -q -F - <<'MSG'
A: D1 разрешённое удаление

ALLOW-ARTIFACT-DELETE: verdicts/adversary/v-a.md первое, законное удаление
MSG
A=$(g "$R" rev-parse HEAD)
A_TREE=$(g "$R" rev-parse "$A^{tree}")
B=$(g "$R" commit-tree "$O_TREE" -p "$O" -m 'B: молчащий брат A, дерево = O')
P1=$(g "$R" commit-tree "$O_TREE" -p "$A" -p "$B" -m 'P1: путь восстановлен вручную (дерево = O)')
P2=$(g "$R" commit-tree "$A_TREE" -p "$B" -p "$A" -m 'P2: путь отсутствует (как честный авто-мерж)')
M=$(g "$R" commit-tree "$A_TREE" -p "$P1" -p "$P2" -m 'M: путь убран, ALLOW нет нигде')
g "$R" update-ref refs/heads/main "$M"
g "$R" checkout -q main
"$BARRIER" "$R"
