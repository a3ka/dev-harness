# ПРИЧИНА: существовал и на HEAD его нет: plans/001-p.md
# ОКРУЖЕНИЕ: BASH_FUNC_exec%%=() { return 0; }
# ОКРУЖЕНИЕ: BASH_FUNC_comm%%=() { local a; for a in "$@"; do if [ "$a" = "-23" ]; then return 0; fi; done; command comm "$@"; }
#
# ТЕНЬ САМОГО ПЕРЕХОДА. Две соседние фикстуры (`case_ten_funkcii_comm.sh`,
# `case_ten_funkcii_unset_comm.sh`) предъявляют барьеру отравленную таблицу функций и требуют,
# чтобы он ушёл из неё re-exec'ом. Эта требует, чтобы он ушёл И ТОГДА, когда отравлено САМО
# СРЕДСТВО УХОДА: `exec` — не ключевое слово, bash разрешает одноимённую функцию, и
# унаследованная `BASH_FUNC_exec%%=() { return 0; }` съедает строку перехода молча, с кодом 0.
# Дальше файл исполняется в ТОМ ЖЕ отравленном процессе, тень `comm` жива, разность
# `existed`\`head` пуста — исчезнувший без ALLOW артефакт принимается rc=0.
#
# ЧТО ИМЕННО РАЗЛИЧАЕТ ЭТА ФИКСТУРА (Н-39 — стаб привязан к той ветви, где его дефект
# НАБЛЮДАЕМ, а не к той, где он просто объявлен). Различима здесь РОВНО строка
# `POSIXLY_CORRECT=1` над `exec` (§Инварианты п.4 контракта 046): присваивание тенью не
# перехватывается и немедленно включает POSIX-режим, где `exec` резолвится как SPECIAL BUILTIN
# РАНЬШЕ пользовательской функции (арбитраж 040-III, вектор H). Соседние фикстуры этого не
# ловят ПО ПОСТРОЕНИЮ: без тени `exec` переход исполняет настоящий builtin, и реализация БЕЗ
# `POSIXLY_CORRECT` для них неотличима от полной — измерено прямым опытом на этом же входе
# (честный барьер rc=1 с названной причиной; тот же файл без одной строки `POSIXLY_CORRECT=1` —
# rc=0 и ни одной строки FAIL).
#
# ПОЧЕМУ ДВЕ ТЕНИ, А НЕ ОДНА. Тень `exec` в одиночку обхода НЕ даёт, и требовать от неё
# красноты значило бы врать о диагнозе: съеденный переход оставляет барьер в отравленном
# процессе, но травить в нём нечего — разность считает НАСТОЯЩИЙ `comm`, барьер честно
# краснеет. Обход существует только у ПАРЫ: `exec` держит процесс в отравленном окружении,
# `comm` прячет в нём пропажу. Поэтому вход — пара, и он один.
#
# Зелёный контроль: чистое дерево сразу после `make_repo` — честная разность пуста, обе тени на
# ней инертны по построению → rc=0, причина в выводе не печатается.
# Красное: `plans/001-p.md` удалён коммитом без разрешения, обе тени в окружении вызывающего —
# барьер ОБЯЗАН назвать ИМЕННО «существовал и на HEAD его нет: plans/001-p.md» (rc=1), а не
# смолчать rc=0 из-за съеденного перехода и подменённой разности.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

g "$R" rm -q plans/001-p.md
g "$R" commit -q -m 'план удалён без ALLOW при тенях exec и comm в окружении'

"$BARRIER" "$R"
