# ПРИЧИНА: существовал и на HEAD его нет: plans/002-vetka.md
#
# Способ третий, самый коварный: слияние `-s ours`. Файл добавлен в ветке, ветка ВЛИТА, а
# дерево слияния взято от «нашей» стороны — файла на HEAD нет, и ни одного коммита с его
# удалением в истории тоже нет. Именно на этом способе правило переписывали в третий раз.
#
# Ловится достижимостью: коммит ветки достижим через второго родителя слияния, значит файл
# существовал.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"
g "$R" checkout -q -b vetka
printf 'план из ветки\n' > "$R/plans/002-vetka.md"
commit_all "$R" 'план добавлен в ветке'
g "$R" checkout -q main
g "$R" merge -q -s ours vetka -m 'ветка влита стратегией ours'
"$BARRIER" "$R"
