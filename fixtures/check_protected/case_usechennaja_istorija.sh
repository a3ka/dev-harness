# ПРИЧИНА: история усечена (shallow)
#
# Самая опасная из всех дыр этого барьера, потому что она делает его ПУСТО-ЗЕЛЁНЫМ, а не
# красным: на клоне глубиной 1 объединение достижимых коммитов равно самому HEAD, и инвариант
# «существовал → есть» подтверждается сам собой. `actions/checkout` берёт именно такую
# глубину по умолчанию, то есть в CI барьер молчал бы, а не защищал.
#
# Молчаливо зелёному гейту верят — поэтому он хуже красного. Здесь предъявляется, что
# усечённая история для барьера отказ, а не особенность окружения.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
printf 'второй план\n' > "$R/plans/002-p.md"
commit_all "$R" 'второй план'
"$BARRIER" "$R"
git clone -q --depth 1 "file://$R" "$WORK/shallow"
"$BARRIER" "$WORK/shallow"
