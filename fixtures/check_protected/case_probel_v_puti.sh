# ПРИЧИНА: существовал и на HEAD его нет: verdicts/adversary/v a.md
#
# Способ девятый, Н-127/арбитраж 042 (робастность разбора путей, З3 таблицы арбитра, ОБЕ
# полярности). Защищённый путь СОДЕРЖИТ ПРОБЕЛ («verdicts/adversary/v a.md»). Прежний
# `blob_at` резал `git ls-tree` awk-полем `$4==pth`: пробел в имени разносит путь на несколько
# awk-полей, сравнение с целым `pth` никогда не совпадает, и «пути нет» получается ВСЕГДА —
# для ЛЮБОГО коммита, ЛЮБОГО состояния пути. Это опасно СИММЕТРИЧНО, и обе половины ниже
# держат обе стороны: легитимный Н-127-мерж с пробельным путём обязан остаться ЗЕЛЁНЫМ
# (половина 1, второй вызов `$BARRIER`), а настоящее повторное удаление того же пробельного
# пути БЕЗ разрешения обязано остаться КРАСНЫМ (половина 2, третий вызов) — вакуумная пустота
# старого разбора давала «артефакт» ВСЕГДА вне зависимости от реального состояния: на половине
# 1 это СЛУЧАЙНО совпадало с правильным ответом, но на половине 2 ложно извиняло D2 разрешением
# D1 (измерено живым прогоном против `625e61e^:scripts/check_protected.sh` на итоговом дереве
# этой же фикстуры: rc=0, WRONG — «исчез с явного разрешения», хотя разрешения на ЭТО удаление
# нет). Новый `state_at` снимает пару mode+oid через `--format`, без awk по пробелам — устойчив
# к пробелу при любом состоянии, в любую сторону.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

# ── половина 1: легитимная Н-127-топология с пробельным путём — обязана остаться ЗЕЛЁНОЙ ──
printf 'путь с пробелом\n' > "$R/verdicts/adversary/v a.md"
commit_all "$R" 'добавлен путь с пробелом'
g "$R" checkout -q -b vetka
printf 'независимая правка\n' > "$R/plans/002-vetka.md"
commit_all "$R" 'B: независимая правка, пробельный путь не трогает'
g "$R" checkout -q main
g "$R" rm -q "verdicts/adversary/v a.md"
g "$R" commit -q -F - <<'MSG'
D1: разрешённое удаление пробельного пути

ALLOW-ARTIFACT-DELETE: "verdicts/adversary/v a.md" первое, законное удаление
MSG
g "$R" merge -q --no-ff vetka -m 'слияние отставшей ветки (ALLOW не повторяется)'
"$BARRIER" "$R"

# ── половина 2: то же дерево, повторное удаление БЕЗ разрешения — обязана дать КРАСНОЕ ──
g "$R" checkout -q -b side2
printf 'независимая правка side2\n' > "$R/plans/003-side2.md"
commit_all "$R" 'side2: независимая правка, пробельный путь не трогает'
g "$R" checkout -q main
printf 'путь восстановлен\n' > "$R/verdicts/adversary/v a.md"
commit_all "$R" 'R: пробельный путь восстановлен'
g "$R" merge -q --no-ff --no-commit side2
g "$R" rm -q "verdicts/adversary/v a.md"
g "$R" commit -q -m 'D2: путь убран заново в мерже, ALLOW нет'
"$BARRIER" "$R"
