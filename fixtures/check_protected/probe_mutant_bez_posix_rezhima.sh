#!/usr/bin/env bash
# МУТАЦИОННОЕ ПРЕДЪЯВЛЕНИЕ ИНВАРИАНТА 4 контракта 046: `POSIXLY_CORRECT=1` отдельной строкой
# ВЫШЕ `exec` — не украшение, а единственное, что делает сам переход неперехватываемым.
#
# ПОЧЕМУ ОТДЕЛЬНАЯ ПРОБА, А НЕ ОДНА ФИКСТУРА. `case_ten_funkcii_exec_comm.sh` держит вход
# (тени `exec`+`comm`) постоянным красным в семье анти-плацебо, но анти-плацебо-протокол судит
# СЕГОДНЯШНИЙ барьер: он показывает, что на этом входе барьер краснеет, и не показывает, ЧТО
# ИМЕННО в барьере за это отвечает. Различие делает мутация, и она обязана быть исполнимой, а
# не обещанием в прозе (§Приёмка контракта 046, находка Б2 критика круга 1).
#
# ОПЫТ. Две копии субъекта в скратче пробы: честная и мутант без строки `  POSIXLY_CORRECT=1`.
# Ничего больше не меняется — ни дерево, ни аргументы, ни окружение. Вход один и тот же:
# защищённый `plans/001-p.md` удалён коммитом БЕЗ строки ALLOW-ARTIFACT-DELETE, в окружении
# вызывающего экспортированы ДВЕ тени — `exec`, глотающая переход с кодом 0, и `comm`,
# отдающая пусто на форме `-23` (разность `existed`\`head`).
#
# ОЖИДАНИЯ — В ПАМЯТИ ЭТОЙ ПРОБЫ (правило 8), не на диске субъекта:
#   честный  + обе тени → rc=1 И напечатана причина «существовал и на HEAD его нет: …»
#   мутант   + обе тени → rc=0 И причина НЕ напечатана          ← обход, который и закрывает п.4
#   мутант   без теней  → rc=1                                   ← контроль: мутант не сломан
#                                                                   вообще, он дыряв РОВНО средой
# Совпадение честного и мутанта означает одно из двух, и оба — отказ: либо строка
# `POSIXLY_CORRECT=1` перестала быть решающей (переход перехватывается — инвариант 4 мёртв),
# либо она исчезла из файла (мутация не применилась — ловится отдельной причиной ниже).
#
# Коды возврата: 0 — инвариант 4 различим мутацией; 1 — именованный отказ; 2 — NOT_IMPLEMENTED.
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
CP="$REPO/scripts/check_protected.sh"
[ -f "$CP" ] || { printf 'NOT_IMPLEMENTED: субъект не найден: %s\n' "$CP" >&2; exit 2; }
[ -f "$HERE/_repo.sh" ] || { printf 'NOT_IMPLEMENTED: нет каркаса _repo.sh\n' >&2; exit 2; }
command -v git >/dev/null 2>&1 || { printf 'NOT_IMPLEMENTED: нет git\n' >&2; exit 2; }

W="$(mktemp -d "${TMPDIR:-/tmp}/probe046-posix.XXXXXX")"
trap 'rm -rf "$W"' EXIT
fail() { printf 'ОТКАЗ: %s\n' "$*" >&2; exit 1; }

HONEST="$W/honest.sh"
MUTANT="$W/mutant.sh"
cp "$CP" "$HONEST"
awk '!/^  POSIXLY_CORRECT=1$/' "$HONEST" > "$MUTANT"
cmp -s "$HONEST" "$MUTANT" \
  && fail "мутация не применилась: строки «  POSIXLY_CORRECT=1» в субъекте нет — инвариант 4 контракта 046 требует её ПОБАЙТОВО, отдельной строкой выше exec"

. "$HERE/_repo.sh"
R="$W/repo"
make_repo "$R"
g "$R" rm -q plans/001-p.md
g "$R" commit -q -m 'план удалён без ALLOW'

PRICHINA='существовал и на HEAD его нет: plans/001-p.md'
# Тени подаются СЫРОЙ сериализацией окружения (`BASH_FUNC_<имя>%%`), той же, что переживает
# старт любого дочернего bash (механизм Shellshock) — а не `export -f` из этой оболочки: проба
# обязана подать вход так, как его подаёт вызывающий, а не так, как ей удобнее.
otravlen() { # <барьер> — прогон под ДВУМЯ тенями
  env -i PATH=/usr/bin:/bin LC_ALL=C.UTF-8 \
    'BASH_FUNC_exec%%=() { return 0; }' \
    'BASH_FUNC_comm%%=() { local a; for a in "$@"; do if [ "$a" = "-23" ]; then return 0; fi; done; command comm "$@"; }' \
    /usr/bin/bash "$1" "$R" 2>&1
}
chisto() { # <барьер> — прогон без единой тени (контроль исправности мутанта)
  env -i PATH=/usr/bin:/bin LC_ALL=C.UTF-8 /usr/bin/bash "$1" "$R" 2>&1
}
nazvana() { case "$1" in *"$PRICHINA"*) printf 1 ;; *) printf 0 ;; esac; }

OUT_H="$(otravlen "$HONEST")"; RC_H=$?
OUT_M="$(otravlen "$MUTANT")"; RC_M=$?
OUT_C="$(chisto "$MUTANT")";   RC_C=$?

printf 'честный + тени exec,comm : rc=%s причина_напечатана=%s\n' "$RC_H" "$(nazvana "$OUT_H")" >&2
printf 'мутант  + тени exec,comm : rc=%s причина_напечатана=%s\n' "$RC_M" "$(nazvana "$OUT_M")" >&2
printf 'мутант  без теней        : rc=%s причина_напечатана=%s\n' "$RC_C" "$(nazvana "$OUT_C")" >&2

[ "$RC_C" = 1 ] && [ "$(nazvana "$OUT_C")" = 1 ] \
  || fail "контроль: мутант без теней обязан краснеть штатно (rc=1 с причиной), получено rc=$RC_C — опыт судит не то, что заявлено"
[ "$RC_H" = 1 ] && [ "$(nazvana "$OUT_H")" = 1 ] \
  || fail "честный субъект под тенями exec+comm не отказал (rc=$RC_H) — переход съеден, инвариант 4 не держит: $OUT_H"
[ "$RC_M" = 0 ] && [ "$(nazvana "$OUT_M")" = 0 ] \
  || fail "мутант без строки POSIXLY_CORRECT=1 отказал (rc=$RC_M) — мутация НЕ различает предмет: либо защита переехала в другое место (тогда инвариант 4 контракта 046 устарел и правится ТЕКСТОМ контракта), либо опыт не воспроизводит вход"

printf 'ИНВАРИАНТ 4 РАЗЛИЧИМ: строка POSIXLY_CORRECT=1 решает исход на входе «тени exec+comm» (честный rc=1, мутант rc=0)\n' >&2
exit 0
