# Инвариант по БЛОБУ на HEAD, не по истории пути (контракт 039): путь уезжал и возвращался —
# после возврата состояние зелёное в обоих мирах (путь на HEAD). Удаление после возврата —
# НОВОЕ исчезновение: прошлый перенос не индульгенция. Реализация, зеленеющая по признаку
# «путь когда-то переносился», ловится здесь финальным вызовом.
#
# Прогон после первого коммита — узел развилки двух миров: до фикса красный (путь исчез),
# после фикса зелёный (перенос распознан).
