# ПРИЧИНА: существовал и на HEAD его нет: verdicts/adversary/v-a.md
#
# Находка адверсария: разрешения собирались из тел ВСЕХ достижимых коммитов в один вечный
# список, поэтому разрешение годилось ПОВТОРНО. Здесь артефакт удаляют с разрешением, потом
# возвращают, потом удаляют СНОВА — уже без разрешения, — и прежняя редакция соглашалась.
#
# Разрешение обосновывает конкретное удаление, а не выдаёт право на путь навсегда: иначе
# однажды написанная строка становится индульгенцией, которую уже не отозвать, потому что тело
# коммита не переписать.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

g "$R" rm -q verdicts/adversary/v-a.md
g "$R" commit -q -F - <<'MSG'
Вердикт снят осознанно

ALLOW-ARTIFACT-DELETE: verdicts/adversary/v-a.md заменён на выпущенный под выданным номером
MSG
"$BARRIER" "$R"

# `git rm` убирает и опустевший каталог — восстанавливать надо вместе с ним.
mkdir -p "$R/verdicts/adversary"
printf 'вердикт вернулся\n' > "$R/verdicts/adversary/v-a.md"
commit_all "$R" 'вердикт восстановлен'
"$BARRIER" "$R"

g "$R" rm -q verdicts/adversary/v-a.md
g "$R" commit -q -m 'второе удаление, разрешения в этом коммите нет'
"$BARRIER" "$R"
