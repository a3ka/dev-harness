# ПРИЧИНА: нет поля verdict во фронтматтере
#
# Вторая форма того же класса: поле есть, но лежит ПОСЛЕ закрытого фронтматтера. Прежняя
# редакция читала первые 20 строк и не находила его — область молча сужалась. Арбитраж
# предписал читать фронтматтер целиком и отказывать, если поля в нём нет.
#
# Числовой лимит строк убран намеренно: он и был причиной второй формы. Порог, взятый из
# головы, отстаёт от предмета — здесь границу задаёт структура файла, а не число.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"
{
  printf -- '---\nname: deep\n---\n'
  for i in $(seq 1 25); do printf 'строка тела номер %s\n' "$i"; done
  printf 'verdict: verdicts/deep/\n'
} > "$R/roles/deep.md"
commit_all "$R" 'поле verdict вынесено за фронтматтер'
"$BARRIER" "$R"
