#!/usr/bin/env bash
# s13_zhestkie_40.sh — ОБМАННЫЙ СТАБ: класс «жёсткие 40 hex» (находка Б-3
# ревьюера круг 1: фильтр `[ "${#__ch_c}" -eq 40 ]` в быстром пути — в
# репозитории --object-format=sha256 каждый SHA 64 hex, ВСЕ совпадения
# отбрасываются молча → тихий rc 0 при живом нарушении, обход инварианта 1
# «на любом дереве»). Наблюдаемая ложь: d12_sha256_narushenie — оракул
# (честный) видит нарушение (rc 1), быстрый путь стаба совпадений не видит
# (rc 0). Честен на d0_chistoe: в sha1-репозитории фильтр прозрачен (40 hex
# проходит), стаб неотличим от каркаса (Н-39: ровно одна точка лжи).
st113_sha_zhestkie_40() { [ "${#1}" -eq 40 ] && printf '%s\n' "$1" || true; }
ST113_SHA_DLINA=st113_sha_zhestkie_40
. "$(dirname "${BASH_SOURCE[0]}")/../_karkas_staba.sh"
