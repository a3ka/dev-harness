#!/usr/bin/env bash
# s10_finish_konca.sh — ОБМАННЫЙ СТАБ: зелёный incr-прогон пишет в кеш HEAD КОНЦА
# (перечитывает HEAD в момент записи), а не проверенный HEAD начала — отметка
# обгоняет проверенный объём (дефект каркаса круга 3, воспроизведён критиком
# (race.py) и арбитром (race/run.py): нарушение, пришедшее после снимка, второй
# --incr-прогон не видит никогда). Ровно одна точка лжи — ST113_FINISH.
# Наблюдаемая ложь: ТОЛЬКО клетка гонки (обёртка расписания gonka-bin/git):
# конкурентный коммит после снимка попадает в кеш непроверенным — кеш == HEAD
# конца при rc 0, второй --incr-прогон нарушение не видит (расходится с полным
# обходом). Вне расписания гонки HEAD конца == HEAD начала — стаб честен
# (контроль честности на d8_kesh_valid).
st113_finish_konec() { git -C "$ROOT" rev-parse HEAD > "$INCR_CACHE" 2>/dev/null || true; }
ST113_FINISH=st113_finish_konec
. "$(dirname "${BASH_SOURCE[0]}")/../_karkas_staba.sh"
