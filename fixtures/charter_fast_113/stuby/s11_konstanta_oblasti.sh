#!/usr/bin/env bash
# s11_konstanta_oblasti.sh — ОБМАННЫЙ СТАБ: класс «зашитая константа» (вердикт
# адверсария круг 1: единственная строка `[ "$__ch_p" = "contracts/777-secret.md" ]
# && continue` в быстром пути проходила батарею 22/0). Исполнимая форма класса:
# область устава быстрого пути — ЗАШИТЫЙ перечень известных батарее имён, а не
# вывод из ls-tree+тегов; документ вне списка не судится вообще. ЛИТЕРАЛЬНЫЙ
# skip единичного имени, отсутствующего во всех корпусах, — НЕ частный случай
# этого класса: батарея его НЕ ловит (арбитраж 113 З2/З3, остаток А-1,
# cognitive-only); ловец — судьи замороженного main (чтение диффа барьера) + В2.
# Наблюдаемая ложь: d10_novoe_imja — имя генерируется раннером по nonce, в этом
# перечне его нет и быть не может: оракул (честный) видит нарушение, быстрый
# путь стаба — нет.
# Честен на d8_kesh_valid (как s7/s9/s10): документы корпуса в перечне,
# единственная правка БЕЗ строки; корпус с законной правкой (d2_merge)
# непригоден для контроля честности — sourced-razreshil в процессе стаба теряет
# тела на честной модели круга 1 (объявление кеша после return библиотеки), и
# контроль красил бы чужой дефект, не ложь стаба (Н-39).
st113_par_konstanta() {  # область = зашитый перечень известных батарее имён
  grep -F -e $'AGENTS.md\t' -e $'ROADMAP.md\t' -e $'plans/001-p.md\t' \
      "$TMP/pairs" > "$TMP/parts.k" || true
  mv "$TMP/parts.k" "$TMP/pairs"
}
ST113_PAR_FILTER=st113_par_konstanta
. "$(dirname "${BASH_SOURCE[0]}")/../_karkas_staba.sh"
