#!/usr/bin/env bash
# Мини-ядро 078 «лимит активных контрактов» — честная реализация инвариантов
# И-1…И-9 контракта 078 в миниатюре, носитель стаб-пака батареи
# fixtures/limit_aktivnyh/red_limit_aktivnyh_078.sh.
#
# НЕ БАРЬЕР и НЕ субъект: предмет контракта 078 — ветви лимита в scripts/next_id.sh,
# scripts/mint_line.sh, scripts/freeze_contract.sh (реализация — отдельная раздача после
# заморозки). Это ядро доказывает, что обманные стабы (мутантные копии ЭТОГО файла, одна
# замена одной строки по маркеру «# ВЕТВЬ:…») расходятся с честным поведением ровно на
# входе, где их дефект наблюдаем (Н-39) — и потому стаб-пак зелен ДО и ПОСЛЕ реализации
# субъекта, не завися от него.
#
# CLI: mini_core_078.sh <корень> [исключение-NNN|-] [причина|-]
#   <корень>       git-репо с remote origin (bare, локальный путь — конвенция семей 068)
#   исключение     NNN замораживаемого (И-4: freeze не считает сам предмет), «-» — нет
#   причина        свободный текст (И-5: литеральная подстрока владельца снимает отказ)
#
# rc 0 — лимит прошёл; rc 1 — ЛИМИТ (≥2 активных); rc 3 — авторитет недоступен
# (fail-closed, И-2). Печать — только именованные строки в stderr (И-9: молчание
# запрещено на отказе/недоступности/снятии; прохождение ниже порога молчит).
#
# Каждая судимая ветвь — РОВНО ОДНА строка с маркером «# ВЕТВЬ:…» в конце: стаб-генератор
# батареи заменяет строку с маркером целиком (замена всегда одним актом, применение
# проверяется двумя мерами — cmp с оригиналом ∧ grep -F маркер стаба; прецедент 068).
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_TEMPLATE_DIR GIT_CEILING_DIRECTORIES
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null

# И-5: единственная константа исключения; сравнение — литеральная подстрока (норма 037:
# никогда regex/glob из значения).
OWNER_MARK='РАЗРЕШИЛ-ВЛАДЕЛЕЦ: сверх лимита'

root="${1:?использование: mini_core_078.sh <корень> [исключение-NNN|-] [причина|-]}"
except="${2:--}"
reason="${3:--}"

# И-2: авторитет обязан существовать; отказ — fail-closed rc 3, имя отдельно от ЛИМИТ.
git -C "$root" remote get-url origin >/dev/null 2>&1 || { printf 'ОТКАЗ: лимит активных контрактов: авторитет недоступен (remote origin не настроен), данные неизвестны — fail-closed\n' >&2; exit 3; }
ls_rc=0
refs="$(git -C "$root" ls-remote origin 'refs/tags/frozen/contracts/*' 'refs/tags/done/contracts/*' 'refs/heads/wip/*' 2>/dev/null)" || ls_rc=$? # ВЕТВЬ:LSREMOTE
[ "$ls_rc" -eq 0 ] || { printf 'ОТКАЗ: лимит активных контрактов: авторитет недоступен (ls-remote origin rc=%s), данные неизвестны — fail-closed\n' "$ls_rc" >&2; exit 3; } # ВЕТВЬ:NETFAIL

# И-1/И-6: разбор трёх пространств и счёт активных — один awk, множества внутри;
# NNN — ровно три цифры, прочие ref-компоненты молча вне счёта (не активны).
# Индексы split — С ПРЕФИКСОМ refs/: frozen/done NNN = a[5] (refs, tags, frozen|done,
# contracts, NNN, v), wip NNN = a[4] (refs, heads, wip, NNN, автор). Сдвиг индекса —
# измеренный дефект первой редакции (клетка нарушА ловила «активных 0» живым прогоном).
# ДЕДУП пересечения (обход double_namespace, критик 078 к2): act — МНОЖЕСТВО, оба
# пространства пишут ОДИН ключ act[k]=1 (не инкремент, не отдельные ключи) — NNN,
# лежащий и в frozen, и в wip, активен ОДИН раз; стаб-Ж батареи ломает именно это.
active="$(printf '%s\n' "$refs" | awk '
  $2 ~ /^refs\/tags\/frozen\/contracts\/[0-9][0-9][0-9]\// { split($2, a, "/"); f[a[5]]=1 }
  $2 ~ /^refs\/tags\/done\/contracts\/[0-9][0-9][0-9]\//   { split($2, a, "/"); d[a[5]]=1 }
  $2 ~ /^refs\/heads\/wip\/[0-9][0-9][0-9]\//              { split($2, a, "/"); w[a[4]]=1 }
  END {
    for (k in f) act[k]=1
    for (k in w) act[k]=1      # ВЕТВЬ:WIP
    for (k in d) delete act[k] # ВЕТВЬ:DONE
    for (k in act) print k
  }' | sort -u)"

# И-4: замораживаемый вычитается ровно один раз (литеральное значение, не шаблон).
[ "$except" = "-" ] || active="$(printf '%s\n' "$active" | grep -vxF -- "$except" || true)" # ВЕТВЬ:EXCEPT

n="$(printf '%s\n' "$active" | grep -c . || true)"

# И-5: снятие — ТОЛЬКО литеральная подстрока OWNER_MARK; иная причина не снимает.
[ "$reason" = "-" ] || case "$reason" in *"$OWNER_MARK"*) printf '  ok   лимит активных контрактов: активных %s, снято строкой владельца\n' "$n" >&2; exit 0 ;; esac # ВЕТВЬ:REASON

# И-3: порог ≥2 — отказ с числом и списком NNN.
if [ "$n" -ge 2 ]; then
  list="$(printf '%s\n' "$active" | paste -sd, -)"
  printf 'ОТКАЗ: лимит активных контрактов: активных %s ≥ 2: %s\n' "$n" "$list" >&2
  exit 1
fi
exit 0
