#!/usr/bin/env bash
# Проба контракта 015, механизм 1 / rc=2-ветвь (арбитраж 3, спор 3): красная ДО
# реализации (дрилла нет), зелёная ПОСЛЕ — дрилл строит собственный песочничный корень
# вне дерева, зелёным контролем прогоняет барьер рядом с собой, затем chmod 000
# существующего файла и требует rc=2 + строку «нечем проверить: <файл>». rc=2 барьера
# фикстурой не выражается (раннер трактует любой rc=2 как NOT_IMPLEMENTED) — потому
# предъявление дриллом, а красное дрилла — подставным барьером в этом каталоге.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
D="$ROOT/scripts/drill_nabludenia_nechitaemo.sh"

if [ ! -f "$D" ]; then
  printf 'ОТКАЗ: дрилла нет — %s (реализация за implementer после заморозки)\n' "$D" >&2
  exit 1
fi
if bash "$D" >/dev/null 2>&1; then
  printf 'ok: дрилл nabludenia-nechitaemo зелёный на живом дереве\n'
  exit 0
fi
rc=$?
printf 'ОТКАЗ: дрилл nabludenia-nechitaemo красен (rc=%d)\n' "$rc" >&2
exit 1
