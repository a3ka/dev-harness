#!/usr/bin/env bash
# СТАБ 142 v2: NUL-предпроверка удалена целиком — текущая реализация OBJECT
# 5f7649de (вердикт adv contracts-142-impl-v2, блокер 2/2): bash `read` молча
# удаляет NUL, строка `FOO_URL\0=<значение>` нормализуется в адресное имя
# класса И-3 и запускает сессию при значении в индексируемом файле.
# Привязка к клеткам — source.json:.stab_vhod["stab_nul-normalizuet-read"]
# (Н-39, по коду): n1–n10 (запуск вместо именованного отказа до workshop),
# r3 (канон NUL-предпроверки исчез из субъекта).
# Генератор: $1 = каталог честной модели, $2 = путь субъекта-стаба.
set -eu
python3 - "$1/connect_project.sh" "$2" <<'PY'
import sys
src = open(sys.argv[1], encoding="utf-8").read()
a0 = r'''  # 142 v2 (слово владельца 2026-10-27 ~15:10 UTC, вариант (а)): ЛЮБОЙ байт
  # NUL (0x00) в СЫРОМ файле дома секретов — именованный отказ sekret-v-dereve
  # ДО разбора парсером и ДО workshop: bash `read` молча удаляет NUL (замер
  # арбитража contracts-142-impl-arbitraz: единственный удаляемый байт из 256),
  # и строка `FOO_URL\0=<значение>` нормализовалась бы в адресное имя класса
  # И-3 — без нормализации и без исключения И-3 для строки с NUL. Отказ — на
  # ЛЮБОЙ строке с NUL (имя, значение, комментарий, пропускаемая, без
  # хвостового LF); в отказе — имя файла и категория «NUL», не значение.
  # Ошибка инструмента предпроверки (grep rc ≥ 2) — отказ, не пропуск.
  if LC_ALL=C grep -qaP '\x00' -- "$DOM_SEKRETOV"; then
    otkaz "sekret-v-dereve: NUL (байт 0x00) в доме секретов «$DOM_SEKRETOV» — файл не читается как KEY=VALUE; сессия не запускается"
  elif [ "$?" -ne 1 ]; then
    otkaz "sekret-v-dereve: предпроверка NUL дома секретов не исполнилась — сессия не запускается"
  fi
'''
assert src.count(a0) == 1, "точка правки модели не найдена: блок NUL-предпроверки"
open(sys.argv[2], "w", encoding="utf-8").write(src.replace(a0, ""))
PY
