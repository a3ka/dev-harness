#!/usr/bin/env bash
# СТАБ 142 v4: канон userinfo БЕЗ токен-ветви (одна двоеточие-ветвь) —
# `https://<токен>@host` под адресным именем пропускается (живой замер
# R142-S1: OBJECT rc 0 при утечке). Слово владельца 2026-10-28 расширило
# канон; этот стаб — дверь v3, не реализовавшая расширение.
# v4-правка (арбитраж contracts-142-v4-arbitraz): якорь перепривязан на
# канон-строку v4 (двоеточие-ветвь — строка v1/v3 байт в байт; дефект
# прежний: токен-ветвь снята). R142v4-B1 (rev contracts-142-impl-v4):
# значение токен-URL в кавычках и со схемой вне RFC судится ТОЛЬКО
# токен-ветвью (двоеточие-ветвь рвётся об `//`) — красен на k125–k127,
# привязка расширена по замеру.
# Привязка к клеткам — source.json:.stab_vhod["stab_bez-token-vetvi"] (Н-39, по коду).
# Генератор: $1 = каталог честной модели, $2 = путь субъекта-стаба.
set -eu
python3 - "$1/connect_project.sh" "$2" <<'PY'
import sys
src = open(sys.argv[1], encoding="utf-8").read()
old = r'''  USERINFO_RE='(^([^/?#[:space:]]*:)?//[^/?#[:space:]]+@|[^/@[:space:]]*:[^/@[:space:]]*@)'
'''
new = r'''  USERINFO_RE='[^/@[:space:]]*:[^/@[:space:]]*@'
'''
assert src.count(old) == 1, "точка правки модели не найдена: канон userinfo без токен-ветви"
open(sys.argv[2], "w", encoding="utf-8").write(src.replace(old, new))
PY
