#!/usr/bin/env python3
# Обманный вариант s1 «гейт вызван, rc игнорируется» (159, уровень
# проводки; правка по Crit159: выброшенный результат проверяется
# ДЕЙСТВИТЕЛЬНЫМ вызовом и наблюдаемым игнорированием rc, не строкой,
# напечатанной субъектом). Состав: argv[1] — путь гейта; гейт
# ВЫЗЫВАЕТСЯ как процесс (трасса пишется самим гейтом), его вывод
# печатается, но rc выбрасывается — возврат всегда 0, остаток батареи
# зелён и на пустом продукте.
# Демаркация: на конформном продукте ведёт себя как честный состав
# (rc 0); расхождение — на пустых входах: честный гейт даёт rc 1, этот
# состав — rc 0. Батарея требует трассу вызова на каждом заявленном
# входе (действительный вызов) и ловит rc-расхождение.
import subprocess
import sys


def main():
    if len(sys.argv) != 3:
        sys.stderr.write('использование: %s <гейт> <корень продукта>\n'
                         % sys.argv[0])
        return 2
    p = subprocess.run(['bash', sys.argv[1], sys.argv[2]],
                       capture_output=True, text=True, timeout=60)
    sys.stdout.write(p.stdout)
    sys.stderr.write(p.stderr)
    # rc гейта ВЫЧИСЛЕН (вызов был действительным — трасса пишется
    # гейтом) и выброшен
    return 0


if __name__ == '__main__':
    sys.exit(main())
