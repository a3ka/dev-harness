"""Стаб s21 (literal-maska-edinicy): маска дайджеста — обособленное
hex-слово 16+ с буквой a–f БЕЗ увода со словоформы «цифры + единица
1–4 букв» (реализация эталона до блокера 1 вердикта adv-132 дословно):
0000000000000001fa (число + единица fa из букв a–f) маскируется как
дайджест — размерный литерал проходит."""
import re

from _model import m, run

m.RE_HEX_ZHIST = re.compile(
    r'(?<![0-9a-zA-Z])(?=[0-9a-fA-F]{16,}(?![0-9a-zA-Z]))'
    r'(?=[0-9]*[a-fA-F])[0-9a-fA-F]{16,}')
run()
