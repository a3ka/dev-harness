#!/usr/bin/env bash
# обманка «краснит старые предметы»: границу обязательности (замороженный текст
# без листа) не признаёт, требует лист всегда (батарея 193).
set -uo pipefail
ROOT="$1"; CONTRACT="$2"
if grep -q '^СДАЧА: ' "$ROOT/$CONTRACT"; then
    printf 'СДАЧА: лист зелёный (двери=1 карта=17/17 дельта=0)\n'
    exit 0
fi
printf 'ОТКАЗ: строка СДАЧА: обязательна всегда\n' >&2
exit 1
