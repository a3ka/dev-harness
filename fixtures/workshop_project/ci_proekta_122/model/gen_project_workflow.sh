#!/usr/bin/env bash
# ЧЕСТНАЯ МОДЕЛЬ генератора workflow проекта — контракт 122 «CI проекта» (Г1).
# Субъект-интерфейс: gen_project_workflow.sh --repo R (--check|--write).
# Источник — .harness/ci.json (проектный CI-манифест, замкнутый алфавит);
# projectId манифеста обязан литерально равняться effective projectId, который вернул резолвер
# (модель: env CI_PROEKTA_122_RESOLVER; реализация — scripts/profile_resolver.sh установки);
# отказ резолвера → profil-rashozhdenie с его первой строкой дословно, до записи. Raw-разбор
# профиля и слоя здесь — ТОЛЬКО материал мутанта stabs/stab_gen_raw_profil.sh (маркер rezolver).
# А10 (184): заголовок вывода не называет путь вспомогательного каталога инструмента
# (мутант stabs/stab_gen_zagolovok_harness.sh, маркер zagolovok, возвращает прежний заголовок).
# Вывод — детерминированные байты .github/workflows/ci.yml; --check — побайтовое сравнение
# (переводы строк — тоже байты: CRLF/CR вместо LF — дрейф). Строку с маркером мутации вырезает
# мутант stabs/ (текстовый режим чтения нормализует переводы строк).
set -u
R=
MODE=
while [ $# -gt 0 ]; do
  case "$1" in
    --repo) R=$2; shift ;;
    --check) MODE=check ;;
    --write) MODE=write ;;
    *) printf 'gen ОТКАЗ: неизвестный ключ: %s\n' "$1" >&2; exit 2 ;;
  esac
  shift
done
if [ -z "$R" ] || [ -z "$MODE" ]; then
  printf 'gen ОТКАЗ: usage: gen_project_workflow.sh --repo R (--check|--write)\n' >&2
  exit 2
fi
export PYTHONDONTWRITEBYTECODE=1
python3 - "$R" "$MODE" <<'PY'
import json, os, subprocess, sys
R, mode = sys.argv[1], sys.argv[2]
mp = os.path.join(R, '.harness', 'ci.json')
if not os.path.isfile(mp):
    print('gen ОТКАЗ: manifest-otsutstvuet'); sys.exit(1)
try:
    m = json.load(open(mp))
except Exception:
    print('gen ОТКАЗ: manifest-nevaliden'); sys.exit(1)
def bad():
    print('gen ОТКАЗ: manifest-nevaliden'); sys.exit(1)
if not isinstance(m, dict) or set(m) - {'schemaVersion', 'projectId', 'jobs'}:
    bad()
if m.get('schemaVersion') != 1 or not isinstance(m.get('projectId'), str) or not m['projectId']:
    bad()
jobs = m.get('jobs')
if not isinstance(jobs, dict) or not jobs:
    bad()
for k, j in jobs.items():
    if not isinstance(k, str) or not k or not isinstance(j, dict):
        bad()
    if set(j) - {'class', 'workdir', 'steps'}:
        bad()
    if j.get('class') not in ('local', 'station'):
        bad()
    wd = j.get('workdir', '.')
    if not isinstance(wd, str) or not wd or '\n' in wd or '\t' in wd:
        bad()
    st = j.get('steps')
    if not isinstance(st, list) or not st:
        bad()
    for s in st:
        if not isinstance(s, dict) or set(s) - {'key', 'run'}:
            bad()
        if not isinstance(s.get('key'), str) or not s['key']:
            bad()
        if not isinstance(s.get('run'), str) or '\n' in s['run']:
            bad()
hp = os.path.join(R, '.harness', 'harness.project.json')
if not os.path.lexists(hp):
    print('gen ОТКАЗ: profil-otsutstvuet'); sys.exit(1)
def raw_project_id():
    # второй парсер профиля и слоя — запрещён Г1; жив только в мутанте
    try:
        pin = json.load(open(hp))['projectLayer']
        lr = os.environ.get('HARNESS_PROJECT_LAYER_ROOT', '')
        layer = json.load(open(os.path.join(lr, pin['profilePath'])))
        return layer.get('projectId') if layer.get('version') == pin.get('version') else None
    except (OSError, KeyError, ValueError, TypeError):
        return None
def resolver_project_id():
    res = subprocess.run(['bash', os.environ['CI_PROEKTA_122_RESOLVER'], '--repo', R],
                         capture_output=True, text=True)
    if res.returncode != 0:
        first = ([l for l in res.stderr.splitlines() if l.strip()] or ['<пусто>'])[0]
        print('gen ОТКАЗ: profil-rashozhdenie: ' + first); sys.exit(1)
    return json.loads(res.stdout)['projectId']['value']
pid = raw_project_id()
pid = resolver_project_id()  # МУТАЦИЯ-122:rezolver
if pid != m['projectId']:
    print('gen ОТКАЗ: profil-rashozhdenie: projectId манифеста %r != effective %r' % (m['projectId'], pid)); sys.exit(1)
HEADER = '# GENERATED by dev-harness gen_project_workflow — не править руками; источник — .harness/ci.json'
HEADER = '# GENERATED by dev-harness gen_project_workflow — не править руками'  # МУТАЦИЯ-122:zagolovok
out = [
    HEADER,
    'name: ci-project',
    'on:',
    '  push:',
    '  pull_request:',
    'concurrency:',
    '  group: ci-project-${{ github.ref }}',
    '  cancel-in-progress: true',
    'jobs:',
]
for k in jobs:
    j = jobs[k]
    out.append('  %s:' % k)
    out.append('    runs-on: ubuntu-latest')
    if j.get('workdir', '.') != '.':
        out += ['    defaults:', '      run:', '        working-directory: %s' % j['workdir']]
    out.append('    env:')
    out.append('      PREFLIGHT_CLASS: %s' % j['class'])
    out.append('    steps:')
    out.append('      - uses: actions/checkout@v4')
    for s in j['steps']:
        out.append('      - name: %s' % s['key'])
        out.append('        run: %s' % s['run'])
text = '\n'.join(out) + '\n'
wp = os.path.join(R, '.github', 'workflows', 'ci.yml')
raw = text.encode('utf-8')
if mode == 'write':
    os.makedirs(os.path.dirname(wp), exist_ok=True)
    with open(wp, 'wb') as f:
        f.write(raw)
    print('gen OK: write'); sys.exit(0)
if not os.path.isfile(wp):
    print('gen ОТКАЗ: workflow-otsutstvuet'); sys.exit(1)
with open(wp, encoding='utf-8', errors='replace') as f:
    cur = f.read().encode('utf-8')  # текстовый режим: universal newlines (узкая мера)
with open(wp, 'rb') as f: cur = f.read()  # МУТАЦИЯ-122:bajty
if cur != raw:
    print('gen ОТКАЗ: workflow-ruchnoj'); sys.exit(1)
print('gen OK: check'); sys.exit(0)
PY
