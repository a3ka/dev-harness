# ПРИЧИНА: не разрешается в истории
#
# Основание обязано называть существующий в истории коммит (`git cat-file -e`).
# Запись с фантазийным хешом — подделка прецедента: текст «основано на решении
# X» есть, а коммита нет, и сверка `git cat-file -e` падает. Это и есть тот
# «прецедент, который не находится, не существует», о котором предмет контракта.
#
# Зелёный контроль: основания существуют → 0. Красное: 005 ссылается на хеш,
# которого в истории нет.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

# Подмена хеша: `0000000` — синтаксически валидная hex-строка, но в истории
# её нет. Барьер красит «не разрешается в истории».
printf 'основание: 0000000\n' > "$R/decisions/005-kritik-na-top.md.tmp"
{
  printf '# 005 — критик на ВЕРХНЕМ уровне чужого семейства\n\n'
  printf 'дата: 2026-08-17\n'
  printf 'вопрос: каким семейством закрыт критик\n'
  printf 'решение: верхний уровень чужого семейства\n'
  printf 'основание: 0000000\n'
  printf 'область: роль critic\n'
  printf 'условие пересмотра: смена семейства\n'
} > "$R/decisions/005-kritik-na-top.md"
rm -f "$R/decisions/005-kritik-na-top.md.tmp"
commit_all "$R" 'основание 005 подменено несуществующим хешем'
"$BARRIER" "$R"
