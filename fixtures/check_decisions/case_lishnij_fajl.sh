# ПРИЧИНА: имя файла не разбирается как NNN
#
# Лишняя запись в реестре — путь к подмене прецедента: добавленная без вердикта
# круга, она проходит под именем зарегистрированной и читается steward'ом как
# «решение владельца». Поэтому лишний файл — отказ с НАЗВАННЫМ путём, а не
# молчаливое расширение области.
#
# Зелёный контроль: ровно семь → 0. Красное: восьмой без номера (нет разборного
# имени) — барьер красит «имя файла не разбирается как NNN-<имя>».
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

# Файл без номера в имени — единый разбор имени (next_id.sh) откажет.
printf 'лишняя запись\n' > "$R/decisions/extra-bez-nomera.md"
commit_all "$R" 'лишний файл в реестре'
"$BARRIER" "$R"
