# ПРИЧИНА: коммит вне зоны
# ОКРУЖЕНИЕ: PATH=$WORK/bin:$PATH
#
# Контракт 040, арбитраж 040-II (verdicts/arbitration/contracts-040-batching-
# dostatochnost-oraculu.md, Граница v4 п.5, НОВАЯ фикстура на находку (б) круга 3
# адверсария — verdicts/adversary/contracts-040-oracle-a2-diff-tree-v2.md). После
# доверенного PATH инъекция спая ниже МЕРТВА — та же полярность-переворот, что у
# case_batch_avtorov_otkaz.sh (см. тот файл за общим объяснением пина). Этот спай
# воспроизводит находку (б) круга 3 / замер З-F арбитра: batched `git diff-tree
# --stdin` (paths_raw, `:509`) обрезан ПОСЛЕ ПЕРВОГО блока (заголовок + пути первого
# SHA) — второй, нарушающий коммит МОЛЧА теряет запись путей, rc=0. С Границей v4 п.2
# (`--always` + сверка множеств заголовков) этот КОНКРЕТНЫЙ спай уже закрывается
# структурно (missing=1 в сверке paths_raw) — фикстура здесь permanent-регрессия ОБОИХ
# защит разом (пин И сверка), а не демонстрация того, что защищает исключительно пин:
# находка (б) была НАЗВАНА (НЕ закрыта) architect'ом в круге 2 (чек-лист А-223) и
# обязана остаться закрытой навсегда, каким бы из двух механизмов это ни доказывалось.
#
# Зелёный контроль: чистое дерево сразу после заморозки (окно ещё без коммитов) → 0;
# легитимный коммит объявленного автора в своей зоне под честным git → 0. Красное: тот
# же автор коммитит ВТОРЫМ вне своей зоны, спай присутствует в PATH-окружении
# вызывающего и обрезает batched-поток путей после первого блока — барьер ОБЯЗАН
# назвать ИМЕННО «коммит вне зоны» (rc=1), а не смолчать rc=0 из-за потерянного блока
# путей второго коммита.
#
# Мутант, потерявший ЛИБО `export PATH=/usr/bin:/bin` в check_zones.sh, ЛИБО сверку
# множеств заголовков paths_raw (Граница v4 п.2), оживляет обрезку: пути второго
# (нарушающего) коммита пропадают БЕЗ следа — нарушитель ИСЧЕЗАЕТ из суда зон, барьер
# отвечает rc=0 — красный прогон этой фикстуры пропадает, что ловится антиплацебо-
# протоколом («барьер остался зелёным на обманном дереве»).
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'
"$BARRIER" "$R"

printf 'легитимная правка в зоне\n' >> "$R/scripts/a.sh"
commit_as "$R" agent-x 'легитимный коммит в зоне — сохранённый первый блок diff-tree'
"$BARRIER" "$R"

mkdir -p "$R/plans"
printf 'forbidden\n' > "$R/plans/002-outside.md"
commit_as "$R" agent-x 'нарушающий коммит вне зоны — обрезанный второй блок diff-tree'

REALGIT="$(command -v git)"
mkdir -p "$WORK/bin"
cat > "$WORK/bin/git" <<EOF
#!/bin/sh
is_difftree=0
for arg in "\$@"; do [ "\$arg" = diff-tree ] && is_difftree=1; done
if [ "\$is_difftree" = 1 ]; then
  "$REALGIT" "\$@" | awk '
    /^[0-9a-f]{40}\$/ { n++; if (n > 1) exit }
    { print }
  '
  exit 0
fi
exec "$REALGIT" "\$@"
EOF
chmod +x "$WORK/bin/git"
"$BARRIER" "$R"
