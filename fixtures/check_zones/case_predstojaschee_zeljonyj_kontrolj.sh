#
# Предстоящее v+1 (слово владельца 2026-10-22 ~21:20 UTC, пункт 1→2 — цикл 130 × zones,
# та же форма, что у contract-frozen): тег v+1 публикуется ПОСЛЕ ленда текста, и до
# публикации валидное v+1 проходит по конъюнкции (а)∧(б) — сводка зон ОБЯЗАНА назвать
# контракт с указанием «предстоящее v2»: зелёное называется, иначе молчаливый барьер
# неотличим от не видящего файл. Мир — синтетический двойник 055: ЗОНА-строка v1 с
# пояснением в «авторе» и путём на следующей строке (та же поломка, что в
# contracts/055 v1), v2 приводит строку к грамматике. Рабочий файл судится целиком:
# стереть объявления («ни ЗОНА, ни РАБОТА НЕ РАЗДАЁТСЯ») — отказ, той же нормой, что
# и у замороженной ветви.
#
# Зелёный контроль: валидное v+1 чинит грамматику v1 → 0, вывод называет «предстоящее
# v2». Красное: v2-текст стёр все объявления (с вердиктом и РАЗРЕШИЛ в носителе) → 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x (до-заморозочная батарея):
fixtures/red_055.sh'

# Предстоящее v2: текст без тега, вердикт критика v2 на HEAD, разрешение в носителе —
# форма правки та же, что у 055 v2 (пояснение перенесено в скобки после пути).
printf '# контракт 001 v2\n\nЗОНА agent-x: fixtures/red_055.sh (до-заморозочная батарея — примечание в скобках после пути, не грамматика)\n' > "$R/contracts/001-x.md"
printf 'accept\nвердикт критика v2\n' > "$R/verdicts/critic/contracts-001-v2.md"
g "$R" add -A
g "$R" commit -q -m 'текст v2 чинит грамматику' -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: v2'
out="$("$BARRIER" "$R" 2>&1)"
printf '%s\n' "$out" | grep -q 'предстоящее v2'   # сводка зон называет контракт

# Порча: v2-текст стёр все объявления — молчание не годится и для рабочего файла v+1.
printf '# контракт 001 v2 без объявлений\n\nтолько предмет\n' > "$R/contracts/001-x.md"
g "$R" add -A
g "$R" commit -q -m 'v2 без объявлений' -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: стёрли'
"$BARRIER" "$R"
