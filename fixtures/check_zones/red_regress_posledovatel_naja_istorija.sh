#!/usr/bin/env bash
# ПРЕД-ЗАМОРОЗОЧНОЕ КРАСНОЕ контракта 021, ветвь Г — инвариант регресса
# (усиление 2 владельца): оконная модель — СТРОГОЕ обобщение линейной, суд
# 013–020 неизменен.
#
# Имя ВНЕ case_*-глоба раннера — НАМЕРЕННО (правка 2, та же причина, что у
# red_mera_parallelnosti_okon.sh: раннер судит стандарт-А и краснит на каждом
# пуше — CI-факт cc1ac79). До реализации предмет (текущий линейный код
# scripts/check_zones.sh) вызывается ПРЯМЫМ запуском этого файла; конверсия в
# case_* с протоколом раннера (зелёный контроль + красный повтор) — пачкой
# architect ПОСЛЕ реализации, вместе с И-1…И-7.
#
# Линейная сторона — ожидания, записанные в ЭТОМ файле (toy-истории построены
# по документированной семантике: rev-list --no-merges диапазона, автор
# объявлен, путь вне зоны → нарушение); оконная сторона — сам барьер.
# «Линейная» и «оконная» стороны НЕ сходятся в одном вычислителе —
# тождественное сравнение исключено по построению (обход круга 1 критика).
#
# Порядок входов не случаен: различающий вход «чужой land-merge» стоит ПЕРВЫМ.
# Сегодня (линейная модель) он красен — это красное пачки; слабая реализация
# «хвост до HEAD» даёт на нём тот же исход и умирает здесь. Слабая реализация
# «теряет merge-принесённые» умирает на входе 3, где единственное нарушение
# принесено merge СВОЕЙ ветки (фаза 4 probe_slabye_realizacii.sh, Н-39).
#
# Коды возврата: 0 — все три входа по договору (после реализации); 1 —
#               именованный отказ (сегодня — вход 1).
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
WORK="$(mktemp -d /tmp/red021-regress.XXXXXX)"   # А-78: прямой прогон — свежий WORK вне дерева
trap 'rm -rf "$WORK"' EXIT
. "$HERE/_repo.sh"

BZ="$REPO/scripts/check_zones.sh"

# ── вход 1 (различающий): чужой land-merge в открытом окне → rc 0 ─────────────
# Маркер merge говорит wip/002, окно открыто у 001: принесённый коммит
# объявленного автора на пути вне зон ЛИНЕЙНОЙ моделью судится (боль Н-66),
# оконной — нет.
A="$WORK/toya_chuzhoj_land"
make_repo "$A" 'ЗОНА agent-x: scripts/'
mkdir -p "$A/plans"
printf 'чужой след окна 002\n' > "$A/plans/chuzoj.md"
g "$A" checkout -q -b wip/002/agent-x
commit_as "$A" agent-x 'работа окна 002'
g "$A" checkout -q main
g "$A" merge --no-ff -q -m 'land: wip/002/agent-x' wip/002/agent-x
out="$("$BZ" "$A" 2>&1)" && rc=0 || rc=$?
[ "$rc" -eq 0 ] || {
  printf 'ОТКАЗ: чужой land-merge (маркер wip/002) судится окном 001 — линейная модель на входе, где оконная обязана быть зелёной (Н-66):\n%s\n' "$out" >&2
  exit 1
}

# ── вход 2: чистая последовательная история со своим merge → rc 0 ─────────────
B="$WORK/toyb_chistyj"
make_repo "$B" 'ЗОНА agent-x: scripts/'
printf 'в зоне через ветку\n' >> "$B/scripts/a.sh"
g "$B" checkout -q -b wip/001/agent-x
commit_as "$B" agent-x 'свой коммит в зоне'
g "$B" checkout -q main
g "$B" merge --no-ff -q -m 'land: wip/001/agent-x' wip/001/agent-x
out="$("$BZ" "$B" 2>&1)" && rc=0 || rc=$?
[ "$rc" -eq 0 ] || {
  printf 'ОТКАЗ: чистая последовательная история со своим merge красна: rc=%s\n%s\n' "$rc" "$out" >&2
  exit 1
}

# ── вход 3: единственное нарушение принесено merge своей ветки → rc 1 ────────
# Линейная модель ловит его сегодня (rev-list --no-merges видит коммит ветки);
# оконная обязана ловить как свою merge-дельту. Потеря = расхождение с линейной
# на последовательной истории = красное этого файла.
C="$WORK/toyc_merge_prinesjonnoe"
make_repo "$C" 'ЗОНА agent-x: scripts/'
mkdir -p "$C/docs"
printf 'вне зоны, принесено merge своей ветки\n' > "$C/docs/merge-brought.md"
g "$C" checkout -q -b wip/001/agent-x
commit_as "$C" agent-x 'нарушение в своей ветке'
g "$C" checkout -q main
g "$C" merge --no-ff -q -m 'land: wip/001/agent-x' wip/001/agent-x
out="$("$BZ" "$C" 2>&1)" && rc=0 || rc=$?
[ "$rc" -ne 0 ] || {
  printf 'ОТКАЗ: нарушение, принесённое merge своей ветки, потеряно: rc=0\n' >&2
  exit 1
}
if ! printf '%s\n' "$out" | grep -qF 'docs/merge-brought.md'; then
  printf 'ОТКАЗ: красное не назвало merge-принесённый путь docs/merge-brought.md:\n%s\n' "$out" >&2
  exit 1
fi
printf '%s\n' "$out" >&2
exit 0
