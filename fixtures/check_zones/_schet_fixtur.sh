#!/usr/bin/env bash
# Независимая сверка счёта фикстур с §Приёмочным критерием контракта 013 — находка 5
# вердикта contracts-013-v1: счётное утверждение проверяется ДРУГОЙ мерой. Scoped-команда
# раннера печатает счёт тем же способом, каким его сама и насчитывает, — сверка с ней
# самосогласована и удаления фикстуры не поймает. Эта сверка — прямой инвентарь каталогов
# (find по case_*.sh) против чисел, записанных в критерии; расхождение — rc 1.
#
# rc 0 — сейчас и после реализации: мера о составе пачки, не о предмете.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
rc=0
for para in 'check_zones 13' 'freeze_contract 14'; do
  d="${para% *}"; want="${para#* }"
  got="$(find "$ROOT/fixtures/$d" -maxdepth 1 -type f -name 'case_*.sh' | wc -l | tr -d ' ')"
  [ "$got" -eq "$want" ] || {
    printf '%s: case-фикстур %s, критерий контракта 013 называет %s\n' "$d" "$got" "$want" >&2
    rc=1
  }
done
exit "$rc"
