#!/usr/bin/env bash
# ПРЕД-ЗАМОРОЗОЧНОЕ КРАСНОЕ контракта 021, ветвь В — мера параллельности §10
# (усиление 1 владельца). Анти-плацебо адресовано ПРЕДМЕТУ меры —
# scripts/measure_parallel_windows.sh: ниже «ворота» — прямые вызовы меры с
# договорёнными исходами на четырёх toy-парах окон (правка 3 по решению
# арбитража fda7bbe: ворота 4 — последовательная пара со СМЕШАННЫМИ timezone
# offset; времена — МОМЕНТЫ, не %ci-строки).
#
# Имя ВНЕ case_*-глоба раннера — НАМЕРЕННО (правка 2). Раннер судит каждый
# case по стандарт-А (зелёный контроль + красный повтор) и не имеет режима
# «видеть красный кейс нереализованного предмета, не уронив CI»: оба case
# правки 1 краснели по протоколу на каждом пуше (CI-факт cc1ac79, шаг
# «Анти-плацебо»: «не вызвала барьер через $BARRIER» / «нет положительного
# контроля»). До реализации предмет предъявляется ПРЯМЫМ запуском этого файла
# (команда — контракт 021, «Красное сейчас»); конверсия в case_* с протоколом
# раннера — пачкой architect ПОСЛЕ реализации, вместе с И-1…И-7.
#
# Договор меры (ветвь В контракта 021): вход <корень> <A> <B>; окна
# перекрылись ⟺ frozen/contracts/A/1 раньше done/contracts/B/1 И
# frozen/contracts/B/1 раньше done/contracts/A/1 по времени коммиттера коммита
# тега; rc 0 — перекрытие доказано; rc 1 — «не параллельно» с именами и
# временами ЛИБО «недостающий тег» с именем тега. Времена в toy пинуются
# GIT_COMMITTER_DATE — порядок не зависит от скорости машины.
#
# СЕГОДНЯ (меры в дереве нет) файл красен именованным отсутствием предмета —
# это и есть предъявляемое красное. После реализации те же ворота дают rc 0 на
# живом дереве; в подставных корнях — на честной форме меры (фаза 1 пробы
# probe_slabye_realizacii.sh: ожидания фаз стабильны до и после реализации).
#
# Коды возврата: 0 — ворота пройдены; 1 — именованный отказ (мера отсутствует
#               либо нарушила договор на воротах).
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
WORK="$(mktemp -d /tmp/red021-mera.XXXXXX)"   # А-78: прямой прогон — свежий WORK вне дерева
trap 'rm -rf "$WORK"' EXIT

MER="$REPO/scripts/measure_parallel_windows.sh"
[ -f "$MER" ] || {
  printf 'ОТКАЗ: меры нет — scripts/measure_parallel_windows.sh (реализация за implementer после заморозки 021)\n' >&2
  exit 1
}

# Лёгкий тег на пустом коммите с ПИНОВАННЫМ временем коммиттера: мера читает
# время коммита тега, история toy не зависит от часов.
mk_window_repo() {  # <каталог>
  mkdir -p "$1"
  GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null git init -q -b main "$1"
}
tag_at() {  # <каталог> <время> <тег>
  GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null \
  GIT_COMMITTER_DATE="$2" GIT_AUTHOR_DATE="$2" \
  git -C "$1" -c user.name=Фикстура -c user.email=fixture@local \
      -c commit.gpgsign=false -c core.hooksPath=/dev/null \
      commit -q --allow-empty -m "окно $3"
  GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null \
  git -C "$1" -c user.name=Фикстура -c user.email=fixture@local tag "$3"
}

# ── ворота 1: перекрывшаяся пара → rc 0 ────────────────────────────────────────
P="$WORK/toyp_perekrytie"
mk_window_repo "$P"
tag_at "$P" '2026-01-01T00:00:01 +0000' frozen/contracts/001/1
tag_at "$P" '2026-01-01T00:00:02 +0000' frozen/contracts/002/1
tag_at "$P" '2026-01-01T00:00:03 +0000' done/contracts/001/1
tag_at "$P" '2026-01-01T00:00:04 +0000' done/contracts/002/1
out="$("$MER" "$P" 001 002 2>&1)" && rc=0 || rc=$?
[ "$rc" -eq 0 ] || {
  printf 'ОТКАЗ: перекрывшаяся пара окон не признана параллельной: rc=%s\n%s\n' "$rc" "$out" >&2
  exit 1
}

# ── ворота 2: последовательная пара → rc 1 «не параллельно» ───────────────────
S="$WORK/toys_posledovatelnoe"
mk_window_repo "$S"
tag_at "$S" '2026-02-01T00:00:01 +0000' frozen/contracts/001/1
tag_at "$S" '2026-02-01T00:00:02 +0000' done/contracts/001/1
tag_at "$S" '2026-02-01T00:00:03 +0000' frozen/contracts/002/1
tag_at "$S" '2026-02-01T00:00:04 +0000' done/contracts/002/1
out="$("$MER" "$S" 001 002 2>&1)" && rc=0 || rc=$?
[ "$rc" -eq 1 ] || {
  printf 'ОТКАЗ: последовательная пара принята за параллельную: rc=%s\n%s\n' "$rc" "$out" >&2
  exit 1
}
if ! printf '%s\n' "$out" | grep -qF 'не параллельно'; then
  printf 'ОТКАЗ: последовательная пара красна, но причина «не параллельно» не названа:\n%s\n' "$out" >&2
  exit 1
fi

# ── ворота 3: недостающий done-тег → rc 1 с именем тега ──────────────────────
X="$WORK/toyx_net_tega"
mk_window_repo "$X"
tag_at "$X" '2026-03-01T00:00:01 +0000' frozen/contracts/001/1
tag_at "$X" '2026-03-01T00:00:02 +0000' frozen/contracts/002/1
tag_at "$X" '2026-03-01T00:00:03 +0000' done/contracts/001/1
out="$("$MER" "$X" 001 002 2>&1)" && rc=0 || rc=$?
[ "$rc" -eq 1 ] || {
  printf 'ОТКАЗ: недостающий тег дал rc=%s (пустая выборка обязана быть красной):\n%s\n' "$rc" "$out" >&2
  exit 1
}
if ! printf '%s\n' "$out" | grep -qF 'done/contracts/002/1'; then
  printf 'ОТКАЗ: недостающий тег не назван по имени done/contracts/002/1:\n%s\n' "$out" >&2
  exit 1
fi
# ── ворота 4: последовательная пара со СМЕШАННЫМИ offset → rc 1 ──────────────
# Правка 3 по решению арбитража fda7bbe (замер 2): абсолютные моменты строго
# возрастают — done/contracts/001/1 раньше frozen/contracts/002/1, окна
# последовательны; %ci-строки при этом лексикографически «перекрываются»
# (2026-01-31 15:00:00 -1100 < 2026-02-01 15:00:00 +1400). Честная (моментная)
# мера обязана ответить rc 1, лексикографическая отвечает rc 0 и умирает здесь.
# Времена пинуются raw-форматом GIT_COMMITTER_DATE «<unix> <offset>».
M="$WORK/toym_smeshannye_offset"
mk_window_repo "$M"
tag_at "$M" '1769904000 +0000' frozen/contracts/001/1
tag_at "$M" '1769907600 +1400' done/contracts/001/1
tag_at "$M" '1769911200 -1100' frozen/contracts/002/1
tag_at "$M" '1769914800 +0000' done/contracts/002/1
out="$("$MER" "$M" 001 002 2>&1)" && rc=0 || rc=$?
[ "$rc" -eq 1 ] || {
  printf 'ОТКАЗ: последовательная пара со смешанными offset принята за параллельную (времена — моменты, не %%ci-строки): rc=%s\n%s\n' "$rc" "$out" >&2
  exit 1
}
if ! printf '%s\n' "$out" | grep -qF 'не параллельно'; then
  printf 'ОТКАЗ: смешанные offset красны, но причина «не параллельно» не названа:\n%s\n' "$out" >&2
  exit 1
fi

exit 0
