# ПРИЧИНА: коммит вне зоны
#
# И-3 контракта 021 (охрана §9): прямой (без merge) коммит объявленного автора
# в main на путь вне зон его ОТКРЫТОГО контракта — красный ДО и ПОСЛЕ 021.
# В истории окна живёт свой land-merge (в зоне): прямые коммиты первого-родителя
# остаются судимыми и при merge-семантике окна.
#   зелёный: прямой коммит в зоне → 0; красное: прямой коммит вне зоны → 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'

# окно с живым land-сведением в зоне — прямые коммиты идут ПОВЕРХ него
printf 'в зоне через ветку\n' >> "$R/scripts/a.sh"
g "$R" checkout -q -b wip/001/agent-x
commit_as "$R" agent-x 'свой коммит в зоне'
g "$R" checkout -q main
g "$R" merge --no-ff -q -m 'land: wip/001/agent-x' wip/001/agent-x

# ── зелёный контроль: прямой коммит в зоне ────────────────────────────────────
printf 'прямая правка в зоне\n' >> "$R/scripts/a.sh"
commit_as "$R" agent-x 'прямой коммит в зоне'
"$BARRIER" "$R"

# ── красное: прямой коммит вне зоны ───────────────────────────────────────────
mkdir -p "$R/plans"
printf 'прямой коммит вне зоны\n' > "$R/plans/prjamoj.md"
commit_as "$R" agent-x 'прямой коммит вне зоны'
"$BARRIER" "$R"
