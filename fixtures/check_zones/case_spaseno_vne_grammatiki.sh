# ПРИЧИНА: СПАСЕНО вне объявленной грамматики
#
# Грамматика СПАСЕНО судит форму: автор объявлен, хеши полные 40-hex, причина непуста,
# хеши существуют и лежат в диапазоне контракта. Красное: короткий хеш — код 1.
# Зелёный контроль: та же история с валидной строкой — 0.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'

printf 'правка в зоне\n' >> "$R/scripts/a.sh"
commit_as "$R" agent-x 'в зоне'
printf 'нарушение\n' > "$R/plans/narushenie.md"
commit_as "$R" agent-x 'вне зоны'
SAVED="$(git -C "$R" rev-list -n1 HEAD -- plans/narushenie.md)"

# Зелёный контроль: валидная строка — спасён, барьер 0
freeze_v2 "$R" "ЗОНА agent-x: scripts/
СПАСЕНО agent-x: $SAVED — причина валидная"
"$BARRIER" "$R"

# Порча: короткий хеш вместо полного 40-hex — объявление вне грамматики.
# Барьер читает блоб ВЫСШЕЙ заморозки — порча едет СЛЕДУЮЩЕЙ версией (v3).
freeze_ver "$R" 3 "ЗОНА agent-x: scripts/
СПАСЕНО agent-x: ${SAVED:0:8} — причина валидная"
"$BARRIER" "$R"
