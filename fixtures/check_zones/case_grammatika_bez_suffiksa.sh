# ПРИЧИНА: contracts/123 — зона автора
#
# Контракт 047, Н-149 (близнец блокера Б7б контракта 044). Третья форма той же
# половины дефекта: четвёртого байта basename НЕТ ВОВСЕ (`contracts/123`).
#
# ПОЧЕМУ ОТДЕЛЬНАЯ КЛЕТКА (Н-39 — по коду): здесь `${base:3:1}` раскрывается в
# ПУСТУЮ строку, а не в символ. «Фикс» через отрицание (`[ "${base:3:1}" != "_" ]`,
# `case "$base" in [0-9][0-9][0-9][a-z]*) return 1 ;; esac`) оставляет голый
# трёхцифровой basename признанным: ни одно отрицаемое множество пустой строки
# не содержит. Умирает тут только положительная форма «четвёртый байт РАВЕН
# дефису».
#
# ПРИЧИНА якорится хвостом строки отказа (`— зона автора`), а не одним префиксом
# пути: подстрока `contracts/123` лежит и внутри `contracts/123-chernovik.md`,
# и клетка без якоря засчитала бы зелёный контроль за красное.
#
# ЗЕЛЁНЫЙ КОНТРОЛЬ: конформный `contracts/123-chernovik.md` остаётся признанным.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'

g "$R" tag -a id/CONTRACT/123 -m 'выдача механизмом: резерв номера 123'

# ── зелёный контроль: конформный черновик признаётся ──────────────────────────
printf '# контракт 123\n\n## Предмет\nчестный черновик\n' > "$R/contracts/123-chernovik.md"
commit_as "$R" agent-x 'draft: честный черновик 123'
"$BARRIER" "$R"

# ── красное: basename — РОВНО три цифры, четвёртого байта нет ────────────────
printf 'не черновик: basename — ровно три цифры\n' > "$R/contracts/123"
commit_as "$R" agent-x 'подкидыш под видом черновика 123'
"$BARRIER" "$R"
