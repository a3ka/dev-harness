# ПРИЧИНА: вне объявленной грамматики
#
# Предстоящее v+1 (слово владельца 2026-10-22 ~21:20 UTC, пункт 1→2 — цикл 130 × zones):
# ЗОНА-строки контракта читаются из рабочего файла ветки ТОЛЬКО при (а) accept-вердикте
# критика v+1 на HEAD (грамматика freeze_contract). Без вердикта это не предстоящая
# заморозка, а правка замороженного — и судит прежний дословно ЗАМОРОЖЕННЫЙ блоб v1:
# его поломанная ЗОНА красит барьер той же строкой, что и до правки.
#
# Зелёный контроль: v2-текст чинит грамматику + accept-вердикт v2 + РАЗРЕШИЛ-ВЛАДЕЛЕЦ
# в коммите-носителе → 0. Красное: вердикт v2 исчез → судит блоб v1 → 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x'

# Предстоящее v2: текст без тега, вердикт критика v2 на HEAD, разрешение в носителе.
printf '# контракт 001 v2\n\nЗОНА agent-x: scripts/a.sh\n' > "$R/contracts/001-x.md"
printf 'accept\nвердикт критика v2\n' > "$R/verdicts/critic/contracts-001-v2.md"
g "$R" add -A
g "$R" commit -q -m 'текст v2 чинит грамматику' -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: v2'
"$BARRIER" "$R"

# Порча: вердикт v2 исчез — предстоящее v+1 осталось без разрешения критика,
# барьер судит замороженный блоб v1 с его поломанной ЗОНА-строкой.
rm "$R/verdicts/critic/contracts-001-v2.md"
commit_all "$R" 'вердикт v2 забран'
"$BARRIER" "$R"
