# ПРИЧИНА: коммит вне зоны
# ОКРУЖЕНИЕ: PATH=$WORK/bin:$PATH
#
# Контракт 040, арбитраж 040-II (verdicts/arbitration/contracts-040-batching-
# dostatochnost-oraculu.md, Граница v4 п.5). После доверенного PATH (check_zones.sh
# теперь делает `export PATH=/usr/bin:/bin` до первой внешней команды, Граница v4 п.1)
# инъекция спая ниже МЕРТВА: барьер резолвит `git` исключительно через /usr/bin:/bin,
# унаследованный $PATH (с $WORK/bin спереди) не смотрит вовсе. Полярность ПЕРЕВЁРНУТА
# относительно исходной формы круга 1 (`dd2befe`): раньше спай МЕНЯЛ исход прогона,
# теперь он — страж пина, присутствующий, но обезвреженный. Спай воспроизводит замер
# З-C арбитра («константный автор»): делегирует настоящему git и подменяет ТОЛЬКО поле
# автора на "not-an-announced-author" в ПОЛНОМ, синтаксически валидном NUL-потоке —
# rc=0, каждый SHA получает РОВНО одну запись. Это КЛАСС, который НЕ ловится ни круг-1
# (rc-проверка: команда успешна), ни круг-2 (sha-множество-сверка: каждый SHA всё ещё
# получает ровно одну запись, просто с лживым содержимым) гардами — единственная защита
# от него это ПИН, и барьер ОБЯЗАН выдать rc=1 «коммит вне зоны», ту же причину, что дал
# бы честный git без спая вовсе.
#
# Зелёный контроль: чистое дерево сразу после заморозки, окно ещё без коммитов, честный
# git → 0. Красное: объявленный agent-x коммитит вне своей зоны (в plans/, зона — только
# scripts/), спай присутствует в PATH-окружении вызывающего — барьер ОБЯЗАН назвать
# ИМЕННО «коммит вне зоны» (rc=1), а не смолчать rc=0 из-за подменённого автора.
#
# Мутант, потерявший `export PATH=/usr/bin:/bin` в check_zones.sh, оживляет спай: автор
# ВСЕХ коммитов становится "not-an-announced-author" (не объявлен ни в одной зоне),
# нарушитель ИСЧЕЗАЕТ из суда зон целиком, барьер отвечает rc=0 — красный прогон этой
# фикстуры пропадает, что ловится антиплацебо-протоколом («барьер остался зелёным на
# обманном дереве»).
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'
"$BARRIER" "$R"

printf 'forbidden\n' > "$R/plans/002-outside.md"
commit_as "$R" agent-x 'declared agent writes outside zone'

REALGIT="$(command -v git)"
mkdir -p "$WORK/bin"
cat > "$WORK/bin/git" <<EOF
#!/bin/sh
no_walk=0
for arg in "\$@"; do [ "\$arg" = --no-walk ] && no_walk=1; done
if [ "\$no_walk" = 1 ]; then
  "$REALGIT" "\$@" | tr -d '\n' | awk -v RS='\0' -v ORS='\0' '
    NR % 2 == 1 { print; next }
    { print "not-an-announced-author" }
  '
  exit 0
fi
exec "$REALGIT" "\$@"
EOF
chmod +x "$WORK/bin/git"
"$BARRIER" "$R"
