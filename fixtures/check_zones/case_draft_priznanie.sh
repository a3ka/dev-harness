# ПРИЧИНА: коммит вне зоны
#
# И-4 контракта 021 (ветвь Б, Н-77(б)): draft-признание. Не-merge коммит с
# дельтой по пути contracts/<NNN>-<slug>.md и тегом выдачи id/CONTRACT/<NNN> на
# САМОМ коммите — этот путь из суда зон выводится; ТА ЖЕ дельта без тега судится
# как обычное касание вне зон. Тег — не индульгенция на весь коммит: здесь
# коммит несёт дельту только по этому пути.
#   зелёный: draft-коммит с тегом id/CONTRACT/001 → 0;
#   красное: тот же коммит, тег снят → 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'

# ── зелёный контроль: draft-дельта с тегом выдачи ─────────────────────────────
printf '\n## Правка v2 (draft)\nтело правки\n' >> "$R/contracts/001-x.md"
commit_as "$R" agent-x 'draft: правка своего контракта'
g "$R" tag -a id/CONTRACT/001 -m 'выдача: draft-пуск контракта 001'
"$BARRIER" "$R"

# ── красное: та же дельта без тега выдачи ────────────────────────────────────
g "$R" tag -d id/CONTRACT/001 >/dev/null
"$BARRIER" "$R"
