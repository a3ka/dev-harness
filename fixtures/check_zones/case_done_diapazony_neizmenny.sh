# ПРИЧИНА: коммит вне зоны
#
# И-5 контракта 021 (Н-14): done-диапазоны неизменны — суд 013–020 не тронут
# occupations 021, коснувшейся ТОЛЬКО открытого окна. Закрытый контракт не судит
# коммиты после своего done-тега. agent-x объявлен в закрытом 001 (scripts/) и в
# открытом 002 (plans/): прямой коммит в plans/ после done 001 судится только
# окном 002 — зелёный.
#   красное: done-тег снят → хвост 001 снова накрывает коммит (окно без done) → 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'

# окно 001 закрыто ПОСЛЕ работы в зоне
printf 'работа в зоне до закрытия\n' >> "$R/scripts/a.sh"
commit_as "$R" agent-x 'в зоне до done'
g "$R" tag -a done/contracts/001/1 -m 'контракт 001 закрыт'

# окно 002 открывается ПОСЛЕ done 001 и объявляет тому же автору plans/
add_contract "$R" 002 'ЗОНА agent-x: plans/'

# ── зелёный контроль: коммит после done не судится закрытым окном ────────────
mkdir -p "$R/plans"
printf 'работа окна 002 после done 001\n' > "$R/plans/posle-done.md"
commit_as "$R" agent-x 'после done чужого окна, в зоне своего'
"$BARRIER" "$R"

# ── красное: done снят — хвост 001 накрывает чужое окно ──────────────────────
g "$R" tag -d done/contracts/001/1 >/dev/null
"$BARRIER" "$R"
