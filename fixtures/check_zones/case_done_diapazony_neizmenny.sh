# ПРИЧИНА: коммит вне зоны
#
# И-5 контракта 021 (Н-14): done-диапазоны неизменны — суд 013–020 не тронут
# occupations 021, коснувшейся ТОЛЬКО открытого окна. Закрытый контракт не судит
# коммиты после своего done-тега.
#
# Н-100 (зона автора — ОБЪЕДИНЕНИЕ путей всех замороженных контрактов): определяющий
# вход — автор agent-y, объявленный ТОЛЬКО в закрытом окне 001 (scripts/). Его коммит
# в plans/ после done 001 при живом done не судит НИКТО: окно 001 закрыто, окно 002
# его не объявляло — зелёный. Снятие done накрывает хвост: окно 001 судит коммит
# объединением зон agent-y ({scripts/}), plans/ вне его — красное. Вход прежней
# редакции (plans/ автора, объявленного в 002) объединением накрыт с обеих сторон
# и красным быть не может — он фиксировал per-contract выбор путей, а не done-границу.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/
ЗОНА agent-y: scripts/'

# окно 001 закрыто ПОСЛЕ работы в зоне (agent-y — автор закрытого окна)
printf 'работа в зоне до закрытия\n' >> "$R/scripts/a.sh"
commit_as "$R" agent-y 'в зоне до done'
g "$R" tag -a done/contracts/001/1 -m 'контракт 001 закрыт'

# окно 002 открывается ПОСЛЕ done 001 и объявляет ДРУГОГО автора в plans/
add_contract "$R" 002 'ЗОНА agent-x: plans/'

# ── зелёный контроль (определяющий): после done 001 коммит автора закрытого ────
#    окна вне его зоны не судится никаким окном — done держит хвост закрытым
mkdir -p "$R/plans"
printf 'после done своего окна, вне зоны\n' > "$R/plans/posle-done.md"
commit_as "$R" agent-y 'после done своего окна, вне зоны'
out="$("$BARRIER" "$R" 2>&1)" && rc=0 || rc=$?
[ "$rc" -eq 0 ] || {
  printf 'ОТКАЗ: закрытое окно судит коммит после своего done (Н-14/И-5):\n%s\n' "$out" >&2
  exit 1
}

# ── красное: done снят — хвост 001 снова накрывает коммит (окно без done) ──────
g "$R" tag -d done/contracts/001/1 >/dev/null
"$BARRIER" "$R"
