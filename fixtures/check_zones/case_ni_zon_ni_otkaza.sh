# ПРИЧИНА: ни зон, ни отказа от раздачи
#
# Молчание не годится: «зон нет, потому что работа не раздаётся» и «зоны забыли» выглядят в файле
# ОДИНАКОВО, а это разные предметы. Контракт обязан объявить одно из двух явно — так требование,
# которое у критика было когнитивным, стало механическим.
#
# Зелёный контроль: контракт с явным отказом от раздачи → 0. Красное: контракт без обоих объявлений.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'РАБОТА НЕ РАЗДАЁТСЯ: кодифицирует действующее соглашение'
"$BARRIER" "$R"

printf '# контракт 002\n\nразделы есть, объявления о раздаче нет\n' > "$R/contracts/002-y.md"
printf 'accept\nвердикт\n' > "$R/verdicts/critic/contracts-002-v1.md"
commit_all "$R" 'контракт 002 без объявления о раздаче'
g "$R" tag -a frozen/contracts/002/1 -m 'заморожен'
"$BARRIER" "$R"
