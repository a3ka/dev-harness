#!/usr/bin/env bash
# Красное предъявление 034, боль 2 (Б2 вердикта 348b108) — АУТЕНТИЧНОСТЬ
# ИСТОЧНИКА ЗАМЕРА: счётчик «проверено по зонам» обязан приходить из
# фактического исполнения check_zones, и это доказуемо ИЗВЕСТНЫМ ОТВЕТОМ.
#
# ЗАМЕР БОЛИ (исполнен адверсарием 348b108, Б2): ветка в check_zones.sh на
# аргумент '.' печатает константу «…проверено по зонам: 1» и выходит rc 0 —
# гвард «sed-выборка ∧ N>0» (Непустота-выборки-033-проверка, frozen 033 :95)
# ПРИНИМАЕТ подмену: все проверки зелёные при нулевой фактической работе.
# Гвард сверяет regex и порог, не связывая счётчик с исполнением.
#
# МЕТОД (норма 034 для замер-гвардов): известный ответ + живой запуск.
# Оракул живёт в памяти предъявления (правило 8): предъявление САМО строит
# toy-дерево и САМО делает K коммитов объявленным автором в своей зоне —
# честный check_zones обязан напечатать ровно K. Подставной счётчик на том же
# входе даёт N≠K — и красный исход доказан исполнением, а не текстом.
#
# ВОРОТА:
#   1 (граница) живое дерево: счётчик N>0 всегда; rc-ветвь честна (rc 0) либо
#     ИМЕНОВАННО пропущена — переходник 031-v3 (5 case ждёт owner-скрипта,
#     Н-113/А-183): громкий пропуск, не молчание (прецедент «пропущен» 030);
#   2 (граница) toy K=3: честный запуск rc 0 ∧ счётчик == 3 (известный ответ);
#   3 (плацебо, показано исполнением) подмена 348b108 ДОСЛОВНО на toy K=5:
#     старый N>0-гвард принимает (N=1) — дыра жива, не пересказана;
#   4 (красное) та же подмена против известного ответа: N=1 ≠ K=5 → гвард
#     известного ответа КРАСЕН именем «подставной счётчик»;
#   5 (Н-39-привязка) та же подмена на вызове с АБСОЛЮТНЫМ корнем ведёт себя
#     честно (rc 0, счётчик == K): дефект подмены наблюдаем ровно на
#     приёмочной форме вызова '.', потому гвард обязан звать предмет этой
#     формой (SELF_DIR подмены несёт библиотеки — честная ветвь доходит до
#     счётчика, как у стаба case_union).
#
# СЕГОДНЯ ворота 1–2 зелёные (check_zones честен), ворота 3–4 демонстрируют
# ловлю ИСПОЛНЕННОЙ подмены: предъявление зелёно на честном дереве и КРАСНО
# на подменённом (в копии с веткой 348b108 ворота 2/4 падают: счётчик
# перестаёт сходиться с известным ответом). Отсюда приёмка 034: прогон этого
# файла — часть стандартной поверхности суда замеров.
#
# ОТВЕРГНУТЫЕ альтернативы (frontier 034): sha1-сверка git-объекта не ловит
# ЗАКОММИЧЕННУЮ подмену (замер исполняет «этот файл» — но «этот файл» и есть
# подменённый); независимый rev-list-пересчёт живого дерева — вторая семантика
# зон рядом с единственным читателем lib_zones (анти-норма 016) и дрейф двух
# реализаций. Известный ответ свободен от обоих: семантика не дублируется,
# ответ известен построением.
set -uo pipefail
. "$(dirname "$0")/_repo.sh"
REPO="$(cd "$(dirname "$0")/../.." && pwd -P)"
CZ="$REPO/scripts/check_zones.sh"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/zamer034.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
command -v git >/dev/null 2>&1 || { printf 'NOT_IMPLEMENTED: нет git\n' >&2; exit 2; }
[ -f "$CZ" ] || { printf 'NOT_IMPLEMENTED: субъект не найден: %s\n' "$CZ" >&2; exit 2; }

otkaz() { printf 'ОТКАЗ: %s\n' "$1" >&2; exit 1; }
counter_of() { printf '%s' "$1" | sed -n 's/.*проверено по зонам: \([0-9][0-9]*\).*/\1/p' | tail -n 1; }
schetchik() {  # <каталог> <арг>: живой запуск из каталога; вывод, rc и счётчик — в память предъявления
  local d="$1" a="$2" out rc
  out="$(cd "$d" && bash "$CZ" "$a" 2>&1)"; rc=$?
  LAST_OUT="$out"; LAST_RC="$rc"; LAST_N="$(counter_of "$out")"
}

# toy-дерево с ИЗВЕСТНЫМ ответом: контракт 001 (agent-x: scripts/) заморожен
# make_repo; K коммитов agent-x в зоне — оракул K построен самим предъявлением.
mk_toy() {  # <каталог> <K>
  local r="$1" K="$2" i
  make_repo "$r" 'ЗОНА agent-x: scripts/'
  for i in $(seq 1 "$K"); do
    printf 'файл зоны %d\n' "$i" > "$r/scripts/f$i.sh"
    commit_as "$r" agent-x "коммит зоны $i/$K (известный ответ)"
  done
}

# ── ворота 1: живое дерево — счётчик непуст; rc-ветвь честна либо именована ────
schetchik "$REPO" "."
[ -n "$LAST_N" ] && [ "$LAST_N" -gt 0 ] \
  || otkaz "ворота 1: живой счётчик пуст/не извлечён — непустота 033 не держится"
if [ "$LAST_RC" -eq 0 ]; then
  printf 'ворота 1: живое дерево rc 0, проверено по зонам: %s — непустота держится\n' "$LAST_N" >&2
else
  printf '%s\n' "$LAST_OUT" | grep -qF 'case_dver_minta_priznanie' \
    || otkaz "ворота 1: живое дерево красно БЕЗ именованного переходника 031-v3 (rc $LAST_RC) — не предмет 034, но и не переходник"
  printf 'ворота 1: живое дерево в переходнике 031-v3 (изъятие case ждёт owner-скрипта, Н-113) — именованный пропуск rc-ветви; счётчик жив: %s\n' "$LAST_N" >&2
fi

# ── ворота 2: известный ответ K=3 — честный предмет сходится ровно с ответом ──
T1="$WORK/t1"; mk_toy "$T1" 3
schetchik "$T1" "."
[ "$LAST_RC" -eq 0 ] || otkaz "ворота 2: честный check_zones красен на чистом toy (rc $LAST_RC)"
[ "$LAST_N" = "3" ] || otkaz "ворота 2: известный ответ 3, получено «$LAST_N» — метод не сходится на честном предмете"
printf 'ворота 2: toy K=3, счётчик %s == известному ответу\n' "$LAST_N" >&2

# ── подмена 348b108 ДОСЛОВНО: копия субъекта КАТАЛОГОМ (SELF_DIR-библиотеки
# рядом, как у обманного стаба case_union), ветка — сразу после шапки ──────────
SUBJ="$WORK/subj-$$"
cp -r "$REPO/scripts" "$SUBJ"
FAKE="$SUBJ/check_zones.sh"
ln="$(grep -n -m1 -F 'set -euo pipefail' "$FAKE" | cut -d: -f1)"
[ -n "$ln" ] || { printf 'NOT_IMPLEMENTED: якорь шапки не найден — стаб строить не из чего\n' >&2; exit 2; }
head -n "$ln" "$FAKE" > "$FAKE.nov"
cat >> "$FAKE.nov" <<'POD MENA'
if [ "${1:-}" = "." ]; then
  printf 'замороженных контрактов: 31 · объявленных авторов: 1 · коммитов в диапазонах: 0 · проверено по зонам: 1\n' >&2
  exit 0
fi
POD MENA
tail -n +"$((ln + 1))" "$FAKE" >> "$FAKE.nov"
mv "$FAKE.nov" "$FAKE"
grep -qF 'проверено по зонам: 1' "$FAKE" || { printf 'NOT_IMPLEMENTED: подмена не применилась\n' >&2; exit 2; }
CZ="$FAKE"

# ── ворота 3: плацебо старого гварда показано ИСПОЛНЕНИЕМ на toy K=5 ──────────
T2="$WORK/t2"; mk_toy "$T2" 5
schetchik "$T2" "."
[ "$LAST_RC" -eq 0 ] || otkaz "ворота 3: подмена ведёт себя не как в 348b108 (rc $LAST_RC) — демо устарело"
[ "$LAST_N" = "1" ] || otkaz "ворота 3: подмена печатает «$LAST_N», а не константу 1 — демо устарело"
test -n "$LAST_N" && test "$LAST_N" -gt 0 \
  || otkaz "ворота 3: старый гвард отклонил подмену — дыра закрылась сама, предъявление устарело"
printf 'ворота 3: старый N>0-гвард ПРИНИМАЕТ подмену (N=%s>0) — плацебо показано исполнением\n' "$LAST_N" >&2

# ── ворота 4: известный ответ красит подмену именованной причиной ────────────
[ "$LAST_N" = "5" ] \
  && otkaz "ворота 4: подменённый счётчик совпал с известным ответом — предъявление не различает"
printf 'ворота 4: известный ответ 5 ≠ подменённый %s — гвард КРАСЕН: подставной счётчик\n' "$LAST_N" >&2

# ── ворота 5: Н-39 — вне приёмочной формы вызова подмена честна ──────────────
schetchik "$WORK" "$T2"
[ "$LAST_RC" -eq 0 ] || otkaz "ворота 5: подмена на абсолютном корне красна (rc $LAST_RC) — дефект шире заявленного"
[ "$LAST_N" = "5" ] || otkaz "ворота 5: подмена на абсолютном корне даёт «$LAST_N» ≠ 5 — дефект шире заявленного"
printf 'ворота 5: на абсолютном корне подмена честна (счётчик %s) — дефект наблюдаем ровно на «.»\n' "$LAST_N" >&2

exit 0
