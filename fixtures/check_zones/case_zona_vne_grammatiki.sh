# ПРИЧИНА: вне объявленной грамматики
#
# Неразобранное объявление — отказ с названным местом (правило 7 нормы). Шаблон в пути особенно
# опасен: `scripts/*` читается человеком как «весь каталог», а механизмом — как буквальное имя со
# звёздочкой, и зона молча оказывается либо шире, либо пустой. Ровно этот класс — молчаливое
# сужение области — закрывался в этом репозитории трижды, по одной форме за раз.
#
# Зелёный контроль: валидная зона → 0. Красное: путь со звёздочкой в замороженном контракте.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/a.sh'
"$BARRIER" "$R"

# Второй контракт с шаблоном: сам предмет заморожен, значит правка файла зону не расширяет — её
# читают из блоба заморозки.
mkdir -p "$R/contracts"
printf '# контракт 002\n\nЗОНА agent-x: scripts/*\n' > "$R/contracts/002-y.md"
printf 'accept\nвердикт\n' > "$R/verdicts/critic/contracts-002-v1.md"
commit_all "$R" 'контракт 002 с шаблоном в пути'
g "$R" tag -a frozen/contracts/002/1 -m 'заморожен'
"$BARRIER" "$R"
