# ПРИЧИНА: не назван ни один путь
#
# Предстоящее v+1 (слово владельца 2026-10-22 ~21:20 UTC, пункт 1→2): accept-вердикт
# критика v+1 необходим, но НЕ достаточен — КАЖДЫЙ коммит, меняющий contracts/<NNN>-*.md
# после заморозки v$vmax, обязан нести валидную РАЗРЕШИЛ-ВЛАДЕЛЕЦ этого пути (грамматика
# razreshil из check_charter.sh). Иначе критик разрешил бы текст, который владелец
# не разрешал, — и суд обязан вернуться к замороженному блобу v1 дословно.
#
# Зелёный контроль: v2-текст + accept-вердикт v2 + РАЗРЕШИЛ в носителе → 0. Красное:
# ещё одна правка текста коммитом БЕЗ строки владельца → судит блоб v1 → 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x:'

printf '# контракт 001 v2\n\nЗОНА agent-x: scripts/a.sh\n' > "$R/contracts/001-x.md"
printf 'accept\nвердикт критика v2\n' > "$R/verdicts/critic/contracts-001-v2.md"
g "$R" add -A
g "$R" commit -q -m 'текст v2 чинит грамматику' -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: v2'
"$BARRIER" "$R"

# Порча: дозаметка в текст коммитом без разрешения владельца — вердикт v2 не спасает.
printf 'уточнение по ходу\n' >> "$R/contracts/001-x.md"
commit_all "$R" 'мелкая правка поверх v2 без строки владельца'
"$BARRIER" "$R"
