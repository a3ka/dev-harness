# ПРИЧИНА: коммит вне зоны
#
# Н-14, четвёртый укус — структурный: зоны закрытого майлстоина судят диапазон без конца и
# заперли файлы следующего. Механизм: тег done/contracts/<NNN>/1 сужает диапазон до
# <первая>..<done>; недостижимый done — отказ (тег из будущего молча расширил бы диапазон).
#
# Зелёный контроль: коммит автора ВНУТРИ зоны до done → 0. Красное: тот же автор, тот же файл
# вне зоны — но ПОСЛЕ done: тег закончил диапазон, и правка будущего больше не судится зонами
# закрытого майлстоина... НЕТ — красное здесь: коммит вне зоны ДО done; после done зелёный
# контроль два: правка того же автора вне зоны → 0, потому что диапазон закрыт.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'
printf 'правка в зоне\n' >> "$R/scripts/a.sh"
commit_as "$R" agent-x 'в зоне'
printf 'правка вне зоны до закрытия\n' > "$R/plans/chuzhoe-do.md"
commit_as "$R" agent-x 'вне зоны до done'
g "$R" tag -a done/contracts/001/1 -m 'майлстоин закрыт'
printf 'правка вне зоны после закрытия\n' > "$R/plans/chuzhoe-posle.md"
commit_as "$R" agent-x 'вне зоны после done'
"$BARRIER" "$R"

# Порча: сместим done НАЗАД, до нарушающего коммита — диапазон снова судит его.
g "$R" tag -d done/contracts/001/1 >/dev/null
BAD="$(git -C "$R" rev-list -n1 HEAD -- plans/chuzhoe-do.md)"
git -C "$R" -c user.name=Фикстура -c user.email=f@l tag -a done/contracts/001/1 -m 'смещён назад' "$BAD"
"$BARRIER" "$R"
