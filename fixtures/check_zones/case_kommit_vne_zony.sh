# ПРИЧИНА: коммит вне зоны
#
# Предмет барьера целиком: исполнитель коммитит только туда, где ему объявлена зона. Молчаливое
# расширение зоны — самый дорогой вид услужливости: «попутно поправил, что попалось» оставляет
# дифф, который нечем ревьюить.
#
# Зелёный контроль: тот же автор правит файл ВНУТРИ зоны → 0. Красное: он же правит plans/, которого
# в его зоне нет.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/a.sh fixtures/a/'
"$BARRIER" "$R"

printf 'правка в своей зоне\n' >> "$R/scripts/a.sh"
printf 'новая фикстура в своей зоне\n' > "$R/fixtures/a/case_novaja.sh"
commit_as "$R" agent-x 'работа внутри объявленной зоны'
"$BARRIER" "$R"

printf 'правка чужого предмета\n' > "$R/plans/chuzhoe.md"
commit_as "$R" agent-x 'попутно поправил план'
"$BARRIER" "$R"
