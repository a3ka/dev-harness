# ПРИЧИНА: contracts/123_not_a_draft.md — зона автора
#
# Контракт 047, Н-149 (близнец блокера Б7б контракта 044). Та же половина
# дефекта, что у клетки `case_grammatika_bukva_posle_nomera.sh`, но ДРУГОЙ вход:
# четвёртый байт basename — ПОДЧЁРКИВАНИЕ (`123_not_a_draft.md`).
#
# ПОЧЕМУ ОТДЕЛЬНАЯ КЛЕТКА (Н-39 — по коду, не по прозе): подчёркивание отличимо
# от буквы ровно тем классом «фиксов», которые проверяют не дефис, а «разделитель
# вообще» — `[0-9][0-9][0-9][-_]*`, `[0-9][0-9][0-9][[:punct:]]*`, `[!a-zA-Z]`.
# На такой правке клетка-буква зеленеет, а эта остаётся красной; объединённый
# вход этого различия не даёт. Грамматика контракта 023 — ЛИТЕРАЛЬНЫЙ дефис,
# а не «какой-нибудь разделитель».
#
# ЗЕЛЁНЫЙ КОНТРОЛЬ: конформный `contracts/123-chernovik.md` остаётся признанным.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'

g "$R" tag -a id/CONTRACT/123 -m 'выдача механизмом: резерв номера 123'

# ── зелёный контроль: конформный черновик признаётся ──────────────────────────
printf '# контракт 123\n\n## Предмет\nчестный черновик\n' > "$R/contracts/123-chernovik.md"
commit_as "$R" agent-x 'draft: честный черновик 123'
"$BARRIER" "$R"

# ── красное: разделитель не дефис ────────────────────────────────────────────
printf 'не черновик: четвёртый байт basename — подчёркивание\n' > "$R/contracts/123_not_a_draft.md"
commit_as "$R" agent-x 'подкидыш под видом черновика 123'
"$BARRIER" "$R"
