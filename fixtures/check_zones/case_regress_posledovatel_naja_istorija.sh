# ПРИЧИНА: коммит вне зоны
#
# Контракт 021, ветвь Г — инвариант регресса (усиление 2 владельца): оконная
# модель — СТРОГОЕ обобщение линейной, суд 013–020 неизменен. Линейная сторона —
# ожидания, записанные в ЭТОМ файле (toy-истории построены по документированной
# линейной семантике: rev-list --no-merges диапазона, автор объявлен, путь вне
# зоны → нарушение); оконная сторона — сам барьер. «Линейная» и «оконная»
# стороны НЕ сходятся в одном вычислителе — тождественное сравнение исключено
# по построению (обход круга 1 критика).
#
# Порядок вызовов не случаен: различающий вход «чужой land-merge» стоит ПЕРВЫМ.
# Сегодня (линейная модель) он красен — это красное пачки; слабая реализация
# «хвост до HEAD» даёт на нём тот же исход и умирает до зелёного контроля.
# Слабая реализация «теряет merge-принесённые» умирает на входе, где единственное
# нарушение принесено merge СВОЕЙ ветки: барьер обязан ответить rc 1 — иначе
# протокол раннера не получает красного и scoped-прогон красен поимённо.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"

# ── вход 1 (различающий): чужой land-merge в открытом окне → rc 0 ─────────────
# Маркер merge говорит wip/002, окно открыто у 001: принесённый коммит объявленного
# автора на пути вне зон ЛИНЕЙНОЙ моделью судится (боль Н-66), оконной — нет.
A="$WORK/toya_chuzhoj_land"
make_repo "$A" 'ЗОНА agent-x: scripts/'
mkdir -p "$A/plans"
printf 'чужой след окна 002\n' > "$A/plans/chuzoj.md"
g "$A" checkout -q -b wip/002/agent-x
commit_as "$A" agent-x 'работа окна 002'
g "$A" checkout -q main
g "$A" merge --no-ff -q -m 'land: wip/002/agent-x' wip/002/agent-x
out="$("$BARRIER" "$A" 2>&1)" && rc=0 || rc=$?
[ "$rc" -eq 0 ] || {
  printf 'ОТКАЗ: чужой land-merge (маркер wip/002) судится окном 001: rc=%s\n%s\n' "$rc" "$out" >&2
  exit 1
}

# ── вход 2: чистая последовательная история со своим merge → rc 0 ─────────────
B="$WORK/toyb_chistyj"
make_repo "$B" 'ЗОНА agent-x: scripts/'
printf 'в зоне через ветку\n' >> "$B/scripts/a.sh"
g "$B" checkout -q -b wip/001/agent-x
commit_as "$B" agent-x 'свой коммит в зоне'
g "$B" checkout -q main
g "$B" merge --no-ff -q -m 'land: wip/001/agent-x' wip/001/agent-x
"$BARRIER" "$B"

# ── вход 3: единственное нарушение принесено merge своей ветки → rc 1 ────────
# Линейная модель ловит его сегодня (rev-list --no-merges видит коммит ветки);
# оконная обязана ловить как свою merge-дельту. Потеря = расхождение с линейной
# на последовательной истории = красное scoped-прогона «красное не предъявлено».
C="$WORK/toyc_merge_prinesjonnoe"
make_repo "$C" 'ЗОНА agent-x: scripts/'
mkdir -p "$C/docs"
printf 'вне зоны, принесено merge своей ветки\n' > "$C/docs/merge-brought.md"
g "$C" checkout -q -b wip/001/agent-x
commit_as "$C" agent-x 'нарушение в своей ветке'
g "$C" checkout -q main
g "$C" merge --no-ff -q -m 'land: wip/001/agent-x' wip/001/agent-x
out="$("$BARRIER" "$C" 2>&1)" && rc=0 || rc=$?
[ "$rc" -ne 0 ] || {
  printf 'ОТКАЗ: нарушение, принесённое merge своей ветки, потеряно: rc=0\n' >&2
  exit 1
}
if ! printf '%s\n' "$out" | grep -qF 'docs/merge-brought.md'; then
  printf 'ОТКАЗ: красное не назвало merge-принесённый путь docs/merge-brought.md:\n%s\n' "$out" >&2
  exit 1
fi
printf '%s\n' "$out" >&2
exit 1
