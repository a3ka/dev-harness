# ПРИЧИНА: коммит вне зоны
#
# И-6 контракта 021 (ветвь Г): оконная модель — СТРОГОЕ обобщение линейной,
# суд 013–020 неизменен. Конверсия пред-заморозочного red-файла в case по
# протоколу раннера (А-82): ≥1 зелёный контроль, ≥1 красный повторным
# прогоном с именованной причиной, различающие ассерты ДО первой
# зелёно-красной пары.
#
# Порядок входов не случаен: входы 1–2 — различающие ЗЕЛЁНЫЕ (ворота до
# первой пары): слабая реализация «хвост до HEAD» краснеет на входе 1
# (чужой land-merge в открытом окне — боль Н-66), «теряет merge-принесённые»
# умирает на входе 3 не предъявив красного. Красное — вход 3: единственное
# нарушение принесено merge СВОЕЙ ветки.
#   вход 1: чужой land-merge (маркер wip/002) в открытом окне 001 → 0;
#   вход 2: чистая последовательная история со своим merge → 0;
#   вход 3: нарушение, принесённое merge своей ветки → 1.
# Линейная сторона — ожидания, записанные в ЭТОМ файле (toy-истории построены
# по документированной линейной семантике); оконная — сам барьер:
# тождественное сравнение одного вычислителя исключено по построению.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"

# ── вход 1 (ворота, до пары): чужой land-merge — обязан быть зелёным ────────
A="$WORK/toya_chuzhoj_land"
make_repo "$A" 'ЗОНА agent-x: scripts/'
add_contract "$A" 002 'ЗОНА agent-x: plans/'
mkdir -p "$A/plans"
printf 'чужой след окна 002\n' > "$A/plans/chuzoj.md"
g "$A" checkout -q -b wip/002/agent-x
commit_as "$A" agent-x 'работа окна 002'
g "$A" checkout -q main
g "$A" merge --no-ff -q -m 'land: wip/002/agent-x' wip/002/agent-x
out="$("$BARRIER" "$A" 2>&1)" && rc=0 || rc=$?
[ "$rc" -eq 0 ] || {
  printf 'ОТКАЗ: чужой land-merge (маркер wip/002) судится окном 001 — хвост до HEAD, вход, где оконная обязана быть зелёной (Н-66):\n%s\n' "$out" >&2
  exit 1
}

# ── вход 2 (ворота, до пары): чистая последовательная история → зелёный ─────
B="$WORK/toyb_chistyj"
make_repo "$B" 'ЗОНА agent-x: scripts/'
printf 'в зоне через ветку\n' >> "$B/scripts/a.sh"
g "$B" checkout -q -b wip/001/agent-x
commit_as "$B" agent-x 'свой коммит в зоне'
g "$B" checkout -q main
g "$B" merge --no-ff -q -m 'land: wip/001/agent-x' wip/001/agent-x
out="$("$BARRIER" "$B" 2>&1)" && rc=0 || rc=$?
[ "$rc" -eq 0 ] || {
  printf 'ОТКАЗ: чистая последовательная история со своим merge красна: rc=%s\n%s\n' "$rc" "$out" >&2
  exit 1
}

# ── вход 3 (красное предъявление): нарушение принесено merge своей ветки ────
# Линейная модель ловит его (rev-list --no-merges видит коммит ветки); оконная
# обязана ловить как свою merge-дельту. Потеря = расхождение с линейной на
# последовательной истории = красное этого файла.
C="$WORK/toyc_merge_prinesjonnoe"
make_repo "$C" 'ЗОНА agent-x: scripts/'
mkdir -p "$C/docs"
printf 'вне зоны, принесено merge своей ветки\n' > "$C/docs/merge-brought.md"
g "$C" checkout -q -b wip/001/agent-x
commit_as "$C" agent-x 'нарушение в своей ветке'
g "$C" checkout -q main
g "$C" merge --no-ff -q -m 'land: wip/001/agent-x' wip/001/agent-x
out="$("$BARRIER" "$C" 2>&1)" && rc=0 || rc=$?
[ "$rc" -ne 0 ] || {
  printf 'ОТКАЗ: нарушение, принесённое merge своей ветки, потеряно: rc=0\n' >&2
  exit 1
}
printf '%s\n' "$out" >&2
