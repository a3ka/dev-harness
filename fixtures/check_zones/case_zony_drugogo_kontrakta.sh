# ПРИЧИНА: коммит вне зоны
#
# Находка критика по контракту 002: зоны действовали РЕТРОАКТИВНО через все контракты. Автор,
# объявленный контрактом B, судился зонами B и в диапазоне контракта A — вплоть до красного на
# истории, написанной до объявления. Зона — обещание КОНКРЕКТНОГО контракта: судит она только
# свой диапазон, и только авторов, объявленных в ней самой.
#
# Зелёный контроль: автор agent-x коммитит ВНЕ зоны контракта 002, но контракт 001 зон не
# объявлял и диапазон его не судит → 0. Красное: тот же автор коммитит вне зоны контракта 002,
# который его объявил → код 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'РАБОТА НЕ РАЗДАЁТСЯ: кодифицирует действующее соглашение'
"$BARRIER" "$R"

printf '# контракт 002\n\nЗОНА agent-x: scripts/\n' > "$R/contracts/002-y.md"
printf 'accept\nвердикт\n' > "$R/verdicts/critic/contracts-002-v1.md"
commit_all "$R" 'контракт 002 объявляет зону agent-x'
g "$R" tag -a frozen/contracts/002/1 -m 'заморожен'

printf 'правка до объявления судилась бы зонами 002\n' > "$R/plans/chuzhoe-do.md"
commit_as "$R" agent-x 'коммит в диапазоне контракта 001, который зон не объявлял'
"$BARRIER" "$R"

printf 'правка после объявления вне зоны 002\n' > "$R/plans/chuzhoe-posle.md"
commit_as "$R" agent-x 'коммит в диапазоне контракта 002 вне его зоны'
"$BARRIER" "$R"
