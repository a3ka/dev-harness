# ПРИЧИНА: ПОЛОМАННАЯ-СТРОКА-V2
#
# Предстоящее v+1 (слово владельца 2026-10-22 ~21:20 UTC, пункт 1→2): при (а)∧(б)
# ЗОНА-строки читаются из РАБОЧЕГО файла ветки — значит, и грамматика судится по
# НОВОМУ файлу: поломанная ЗОНА в рабочем тексте v+1 (при живом вердикте и строке
# РАЗРЕШИЛ в носителе) красит барьер по НОВОЙ строке, а не проходит молча мимо
# валидного замороженного блоба v1.
#
# Зелёный контроль: валидное v+1 (текст + accept-вердикт + РАЗРЕШИЛ в носителе) → 0.
# Красное: ЗОНА рабочего файла сломана (носитель с РАЗРЕШИЛ, вердикт на HEAD) → 1
# с названием той самой новой строки.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/a.sh'

printf '# контракт 001 v2\n\nЗОНА agent-x: scripts/a.sh scripts/b.sh\n' > "$R/contracts/001-x.md"
printf 'accept\nвердикт критика v2\n' > "$R/verdicts/critic/contracts-001-v2.md"
g "$R" add -A
g "$R" commit -q -m 'текст v2 расширяет зону' -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: v2'
"$BARRIER" "$R"

# Порча: ЗОНА рабочего файла сломана — красное обязано назвать НОВУЮ строку.
printf '# контракт 001 v2\n\nЗОНА agent-x ПОЛОМАННАЯ-СТРОКА-V2\n' > "$R/contracts/001-x.md"
g "$R" add -A
g "$R" commit -q -m 'поломанная ЗОНА в v2' -m 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md слово владельца: порча'
"$BARRIER" "$R"
