#!/usr/bin/env bash
# Проба предмета А контракта 013 — находка 3 вердикта contracts-013-v1: счётчик
# сводной строки обязан быть наблюдаем. Молчаливый skip запрещён: барьер,
# отфильтровавший процессные пути, обязан НАЗВАТЬ число исключённых файлов — точным
# числом, а не «N=0 всегда» и не молчанием. Проба строит историю с известным составом
# и требует подстроку «процессных вне суда: N» с точным N (N = исключённые ФАЙЛЫ:
# смешанный коммит отдаёт процессный файл счётчику, а предметную половину — суду).
#
# Ветви ΔN=2 (круг 2 + РЕШЕНИЕ арбитража kontrakt-013-edinitsa-scheta + круг 3:
# точка ΔN=2 обязана стоять в ОБЕИХ ветвях реализации, и в КАЖДОЙ пара
# процессных файлов ОДНОГО вида — иначе подменённая ПО ВЕТВЯМ единица
# (файлы в чистой, виды/коммиты в смешанной) проходит всё; точки N=1/2
# вырождены: там коммит несёт ровно один процессный файл, и счёт файлов,
# коммитов, видов фильтра и префиксов путей совпадает):
#  ЧИСТАЯ — два файла ОДНОГО вида (оба в verdicts/critic/) одним коммитом,
#    rc 0, прирост ровно +2 (2 → 4): коммитосчётчик даст 3, счёт видов или
#    префиксов — 2;
#  СМЕШАННАЯ — два процессных ОДНОГО вида (оба корневые NABLIUDENIA*.md:
#    HANDOFF.md в паре дал бы ВТОРОЙ вид, и по-ветвевой гибрид «файлы в
#    чистой / виды в смешанной» прошёл бы N=6 как 2 вида — круг 3) плюс
#    предметный вне зоны: rc 1 по предметной половине, прирост ровно +2
#    (4 → 6): коммитосчётчик, счёт видов и префиксов дадут 5. Смешанная
#    ветвь последняя: её красный необратим.
#
# Сейчас (счётчика нет): первая же сверка строки расходит → rc 1.
# После реализации: rc 0 ровно когда счётчик печатается и точен.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck disable=SC1091
. "$HERE/_repo.sh"
S="$(cd "$HERE/../.." && pwd)/scripts"
W="$(mktemp -d "${TMPDIR:-/tmp}/probe-svod.XXXXXX")"
trap 'rm -rf "$W"' EXIT
R="$W/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/a.sh'

fails=0
sud() {
  set +e
  OUT="$(bash "$S/check_zones.sh" "$R" 2>&1)"
  RC=$?
  set -e
}
zap() {  # <ожидаемый rc> <ожидаемый N или -> <имя ветви>
  local want="$1" n="$2" name="$3"
  if [ "$RC" -ne "$want" ]; then
    printf 'ветвь «%s»: барьер вернул rc=%s, ожидается %s\n' "$name" "$RC" "$want" >&2
    printf '%s\n' "$OUT" | sed 's/^/    /' >&2
    fails=$((fails + 1))
  fi
  if [ "$n" != "-" ] && ! grep -qF "процессных вне суда: $n" <<<"$OUT"; then
    printf 'ветвь «%s»: в выводе нет точного счёта «процессных вне суда: %s»\n' "$name" "$n" >&2
    printf '%s\n' "$OUT" | sed 's/^/    /' >&2
    fails=$((fails + 1))
  fi
}

printf 'правка в своей зоне\n' >> "$R/scripts/a.sh"
commit_as "$R" agent-x 'работа внутри объявленной зоны'
sud; zap 0 - 'положительный контроль: правка в зоне'

printf 'accept\nпроцессный вердикт критика\n' > "$R/verdicts/critic/process-001.md"
commit_as "$R" agent-x 'процессный: вердикт критика'
sud; zap 0 1 'чисто процессный коммит: вне суда целиком, счётчик 1'

printf 'наблюдение архитектора\n' > "$R/NABLIUDENIA_ARCHITECT.md"
commit_as "$R" agent-x 'процессный: наблюдение'
sud; zap 0 2 'второй процессный файл: счётчик 2'

printf 'вердикт ревьюера\n' > "$R/verdicts/critic/process-006.md"
printf 'ещё вердикт ревьюера\n' > "$R/verdicts/critic/process-007.md"
commit_as "$R" agent-x 'чисто процессный: два файла одного вида одним коммитом'
sud; zap 0 4 'чистая ΔN=2: два файла verdicts/critic/ одним коммитом, прирост ровно 2 (2 → 4)'

printf 'наблюдение судьи\n' > "$R/NABLIUDENIA_SUDJA.md"
printf 'наблюдение арбитра\n' > "$R/NABLIUDENIA_ARBITRA.md"
printf 'предметный файл вне зоны\n' > "$R/scripts/c.sh"
commit_as "$R" agent-x 'смешанный: два процессных одного вида и предметное одним коммитом'
sud; zap 1 6 'смешанная ΔN=2: два корневых NABLIUDENIA*.md ОДНОГО вида — по-ветвевой гибрид (файлы в чистой / виды в смешанной) краснеет здесь; прирост ровно 2 (4 → 6)'

[ "$fails" -eq 0 ] || exit 1
