# ПРИЧИНА: contracts/123‐homoglyph.md — зона автора
#
# Контракт 047, Н-149; закрывает FAIL `verdicts/adversary/contracts-047-v1-adversary.md`.
# Та же половина дефекта, что у клеток `case_grammatika_bukva_posle_nomera.sh` и
# `case_grammatika_podcherkivanie_posle_nomera.sh`, но ДРУГОЙ вход: четвёртый символ
# basename — U+2010 HYPHEN (байты e2 80 90), визуальный двойник ASCII-дефиса U+002D.
#
# ПОЧЕМУ ОТДЕЛЬНАЯ КЛЕТКА (Н-39 — по коду, не по прозе): мутант адверсария
# `[ "${base:3:1}" = "-" ] || [ "${base:3:1}" = "‐" ]` зеленит клетки буквы и
# подчёркивания (их четвёртый символ не равен ни одной альтернативе) и проходил
# весь набор 32/32. На этом входе он признаёт неконформный путь черновиком и
# выводит его из суда зон — барьер отвечает rc=0 вместо отказа. Грамматика
# контракта 023 — ЛИТЕРАЛЬНЫЙ ASCII-дефис, а не «что-то похожее на дефис».
#
# ДЕМАРКАЦИЯ: конформен только basename `<три ASCII-цифры>-*` (U+002D). U+2010
# вне грамматики по документированной форме — расхождение на нём валидно.
#
# ЗЕЛЁНЫЙ КОНТРОЛЬ: конформный `contracts/123-chernovik.md` остаётся признанным.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'

g "$R" tag -a id/CONTRACT/123 -m 'выдача механизмом: резерв номера 123'

# ── зелёный контроль: конформный черновик признаётся ──────────────────────────
printf '# контракт 123\n\n## Предмет\nчестный черновик\n' > "$R/contracts/123-chernovik.md"
commit_as "$R" agent-x 'draft: честный черновик 123'
"$BARRIER" "$R"

# ── красное: четвёртый символ — U+2010, не ASCII-дефис ────────────────────────
printf 'не черновик: четвёртый символ basename — U+2010 HYPHEN\n' > "$R/contracts/123"$'\xe2\x80\x90'"homoglyph.md"
commit_as "$R" agent-x 'подкидыш под видом черновика 123'
"$BARRIER" "$R"
