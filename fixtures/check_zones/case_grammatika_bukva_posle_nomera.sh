#
# Контракт 047, Н-149 (близнец блокера Б7б контракта 044). И-3 признание (iv)
# контракта 023 признаёт ТОЛЬКО путь грамматики `contracts/<M>-*`: три цифры И
# ЛИТЕРАЛЬНЫЙ дефис четвёртым байтом basename. `check_zones.sh` проверял ровно
# первые ТРИ символа — и признавал черновиком ЛЮБОЙ путь под `contracts/` с
# цифровым префиксом, выводя его из суда зон при живом теге `id/CONTRACT/<M>`.
#
# ВХОД ЭТОЙ КЛЕТКИ (Н-39 — вход, на котором дефект НАБЛЮДАЕМ): четвёртый байт
# basename — БУКВА (`123not-a-draft.md`). Отдельная клетка от «без суффикса
# вовсе» и от «подчёркивание»: правка вида `[0-9][0-9][0-9][!a-zA-Z]*` пустила
# бы подчёркивание, правка вида «длина basename больше трёх» пустила бы букву —
# каждая форма умирает на СВОЕЙ клетке, объединённая клетка засчиталась бы по
# первой красной точке и две другие формы остались бы непредъявленными.
#
# ЗЕЛЁНЫЙ КОНТРОЛЬ — не декорация, а канарея противоположной ошибки: честный
# черновик `contracts/123-chernovik.md` при живом резерве обязан остаться
# признанным. «Фикс», убивший признание целиком, красит зелёную ветвь здесь же.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'

# Резерв номера 123 на коммите основания (рука Б: тег — предок судимого).
g "$R" tag -a id/CONTRACT/123 -m 'выдача механизмом: резерв номера 123'

# ── зелёный контроль: конформный черновик признаётся ──────────────────────────
printf '# контракт 123\n\n## Предмет\nчестный черновик\n' > "$R/contracts/123-chernovik.md"
commit_as "$R" agent-x 'draft: честный черновик 123'
"$BARRIER" "$R"

# ── красное: basename с цифровым префиксом ВНЕ грамматики contracts/<M>-* ─────
printf 'не черновик: четвёртый байт basename — буква\n' > "$R/contracts/123not-a-draft.md"
commit_as "$R" agent-x 'подкидыш под видом черновика 123'
"$BARRIER" "$R"
