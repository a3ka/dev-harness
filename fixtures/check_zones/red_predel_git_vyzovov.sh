#!/usr/bin/env bash
# Красное 040 (Н-126, вариант A2) — СТРУКТУРНЫЙ (без wall-clock) предел числа
# git-подпроцессов, порождаемых check_zones.sh на toy-дереве с K перекрывающихся
# окон поверх M+M2 общих фоновых коммитов ДВУХ РАЗНЫХ КЛАССОВ (круг 2, критик
# contracts-040-v1, находка 1: одной только нагрузки на автора-фильтр мало —
# см. п.2б/п.4 ниже).
#
# Конструкция (frontier agent://Arch126Frontier, variant_a_odnoprohodnyj, п.1-6;
# п.2б добавлен кругом 2 закрытием critic-находки 1):
#  1. K контрактов, у каждого СВОЙ автор agentNN и НЕПЕРЕСЕКАЮЩАЯСЯ зона
#     zones/agentNN/; ВСЕ K заморожены РАНО (до фоновых коммитов) — их окна
#     frozen_NNN..HEAD ВСЕ покрывают одни и те же фоновые коммиты, то есть
#     Σ(размер окна) растёт вместе с (M+M2) на физически различных коммитах.
#  2а. M фоновых коммитов --allow-empty от НЕОБЪЯВЛЕННОГО автора «Фон»: каждый
#     входит в судимое множество (не merge), но не матчит ни одного заявленного
#     автора — check_zones безусловно печатает `git log -1 --format=%an` на
#     КАЖДЫЙ (:333), затем `continue` (без diff-tree). Линейный по M вызов на
#     каждое ИЗ K окон — Θ(K×M) подпроцессов на этом узком месте (author-lookup
#     половина A2). Нагружает ТОЛЬКО batching автора — половину diff-tree НЕ
#     нагружает вовсе (все M отсекаются ДО diff-tree), что и было измеренным
#     обходом круга 1 (critic contracts-040-v1, находка 1): батчинг ТОЛЬКО
#     авторов давал 130 <= 452 — зелёным на неполной реализации.
#  2б. M2 коммитов ОТ ОБЪЯВЛЕННОГО автора «agent01» (тот же автор, что владеет
#     zones/agent01/ — контракт 001), каждый легитимно трогает СВОЙ ФАЙЛ внутри
#     zones/agent01/ (не violation). Эти коммиты МАТЧАТ author-фильтр РОВНО
#     окна 001 (для остальных K-1 окон — тот же необъявленный-для-них случай,
#     что и «Фон») — и потому доходят до `git diff-tree -r --no-commit-id
#     --name-only --no-renames "$c"` (:472) БЕЗУСЛОВНО, один вызов НА КАЖДЫЙ
#     совпавший коммит в сегодняшней (по-коммитной) реализации. Это нагружает
#     ИМЕННО diff-tree-половину A2 (§Инварианты 1, второй буллит контракта):
#     реализация, батчащая ТОЛЬКО авторов (первую половину) и оставляющая
#     diff-tree по-коммитно, тратит ЛИНЕЙНО M2 git-вызовов на ЭТОМ узком месте
#     — измерено живьём (см. §Приёмка Р1 контракта): mutant с батчингом ТОЛЬКО
#     авторов даёт ровно 130+M2 вызовов на этом toy (130 — тот же baseline,
#     что и при M2=0, плюс ровно 1 доп. вызов на каждый ИЗ M2 коммитов).
#  3. git-шпион (приём fixtures/check_runner_hygiene/red_pin_spawn_zadanie.sh:
#     `exec РЕАЛЬНЫЙ_git "$@"`) считает КАЖДЫЙ git-подпроцесс, порождённый ЛЮБЫМ
#     местом check_zones.sh/lib_zones.sh/lib_registry.sh за весь прогон.
#  4. Граница a·(K+M)+b — ЛИНЕЙНАЯ по (K+M), M2 В НЕЁ НЕ ВХОДИТ (сознательно, не
#     упущение). Честная batched-реализация (ОБЕИХ половин A2) тратит O(1)
#     git-вызовов НА ОКНО НЕЗАВИСИМО от того, сколько коммитов совпало по
#     автору внутри окна — один batched diff-tree-запрос на ВСЕ совпавшие
#     коммиты окна заменяет M2 отдельных вызовов ОДНИМ, поэтому цена честной
#     реализации НЕ растёт вместе с M2 вовсе (оценка: 4-6 вызовов/окно × K,
#     тот же порядок, что и при M2=0). Половинчатая реализация (батчит ТОЛЬКО
#     авторы) растёт линейно с M2 коэффициентом ~1 (измерено: 130, 190, 280,
#     430, 530 вызовов на M2 = 0, 60, 150, 300, 400 — ровно 130+M2). Если бы
#     граница ТОЖЕ росла вместе с M2 (например a·(K+M+M2)+b), половинчатая
#     реализация НИКОГДА не превысила бы её при a>1 — граница росла бы быстрее
#     половинчатой цены, и сама возможность отличить половинчатую от честной
#     реализации терялась бы СТРУКТУРНО, а не по недосмотру числа. Поэтому
#     M2 — величина ТОЛЬКО toy-нагрузки, не параметр границы. a=6, b=20 — те
#     же щедрые константы, что и до этого круга (452 для K=12, M=60);
#     M2=400 выбрана так, что половинчатая (только-авторы) реализация даёт
#     130+400=530 > 452 (запас ~17%), а честная (обе половины) остаётся сильно
#     ниже 452 — измерено, не пересчитано в уме (см. §Риски-4 контракта: право
#     architect на правку ЧИСЛА границы при обоснованном превышении честной
#     реализацией сохраняется; здесь превышения честной реализацией не измерено
#     — оценка по конструкции, к A2 implementer'а применится живой замер Р5/Р7).
#  5. Гарантия от «быстрой, но неправильной» заглушки (Н-39): ОДИН коммит —
#     agent03 пишет в zones/agent07/ (чужая зона) — check_zones ОБЯЗАН дать rc=1
#     с «коммит вне зоны» И на сегодняшней (медленной) версии, И на будущей
#     (быстрой): тест ловит производительность, а не потерю проверки. M2-
#     коммиты agent01 НЕ создают новых нарушений (легитимно внутри СВОЕЙ зоны)
#     — единственное нарушение остаётся тем же самым agent03-коммитом.
#  6. Регресс-гарантия (не-ослабление) — ОТДЕЛЬНО от этого файла: все
#     существующие 21 файл fixtures/check_zones/case_*.sh (не 33 — уточнено
#     кругом 2, critic contracts-040-v1 находка 2: red_*/probe_*/stab_*/
#     _repo.sh/_schet_fixtur.sh — НЕ case_*.sh, verify_antiplacebo.sh:585
#     сканирует только case_*.sh) обязаны остаться зелёными БЕЗ правки их
#     текста — предъявляется отдельной командой (см. контракт §Приёмка Р3/Р8).
#
# Коды возврата: 0 — вызовов ≤ границы И нарушение поймано; 1 — граница
#                превышена ЛИБО нарушение не поймано (сегодня: превышена).
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
CZ="$REPO/scripts/check_zones.sh"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/red040-predel.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
[ -f "$CZ" ] || { printf 'NOT_IMPLEMENTED: субъект не найден: %s\n' "$CZ" >&2; exit 2; }
command -v git >/dev/null 2>&1 || { printf 'NOT_IMPLEMENTED: нет git\n' >&2; exit 2; }

fail() { printf 'ОТКАЗ: %s\n' "$*" >&2; exit 1; }

# ── git-шпион: PATH-шим, инкремент счётчика ДО передачи управления git ────────
GITREAL="$(command -v git)"
SPY="$WORK/spy"; mkdir -p "$SPY"
COUNTFILE="$WORK/git_calls.count"
: > "$COUNTFILE"
cat > "$SPY/git" <<EOF
#!/bin/sh
printf 'x' >> "$COUNTFILE"
exec "$GITREAL" "\$@"
EOF
chmod 755 "$SPY/git"

# ── toy-дерево: K контрактов / M фоновых (Фон) + M2 фоновых (agent01) / 1 нарушение ──
R="$WORK/repo"
K=12
M=60
M2=400
mkdir -p "$R"
g() { GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null git -C "$R" \
      -c commit.gpgsign=false -c core.hooksPath=/dev/null "$@"; }
GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null git init -q -b main "$R"

mkdir -p "$R/contracts" "$R/verdicts/critic"
{
  printf '# контракт 001\n\n## Предмет\nподставной предмет KxM\n\n## Критерий готовности\nкоманда с кодом возврата\n\n## Исполнители и зоны\n'
  printf 'ЗОНА agent01: zones/agent01/\n'
} > "$R/contracts/001-x.md"
printf 'accept\nвердикт критика\n' > "$R/verdicts/critic/contracts-001-v1.md"
mkdir -p "$R/zones/agent01"
printf 'исходный\n' > "$R/zones/agent01/seed.md"
g -c user.name=Фикстура -c user.email=fixture@local add -A
g -c user.name=Фикстура -c user.email=fixture@local commit -q -m 'основание'
g -c user.name=Фикстура -c user.email=fixture@local tag -a frozen/contracts/001/1 -m 'контракт 001 утверждён'

i=2
while [ "$i" -le "$K" ]; do
  nnn=$(printf '%03d' "$i")
  an=$(printf 'agent%02d' "$i")
  printf '# контракт %s\n\n## Предмет\nподставной предмет KxM\n\n## Критерий готовности\nкоманда с кодом возврата\n\n## Исполнители и зоны\nЗОНА %s: zones/%s/\n' \
    "$nnn" "$an" "$an" > "$R/contracts/$nnn-y.md"
  mkdir -p "$R/zones/$an"
  printf 'исходный\n' > "$R/zones/$an/seed.md"
  g -c user.name=Фикстура -c user.email=fixture@local add -A
  g -c user.name=Фикстура -c user.email=fixture@local commit -q -m "основание: контракт $nnn"
  g -c user.name=Фикстура -c user.email=fixture@local tag -a "frozen/contracts/$nnn/1" -m "контракт $nnn утверждён"
  i=$((i + 1))
done

j=1
while [ "$j" -le "$M" ]; do
  g -c user.name=Фон -c user.email=fon@local commit -q --allow-empty -m "фон $j"
  j=$((j + 1))
done

# M2 коммитов ОБЪЯВЛЕННОГО автора agent01 — нагрузка ЧЕРЕЗ diff-tree (см. п.2б
# заголовка): каждый легитимно трогает СВОЙ файл внутри zones/agent01/ (СВОЙ
# зоны, не violation), матчит author-фильтр окна 001 и доходит до diff-tree
# безусловно в сегодняшней по-коммитной реализации.
j=1
while [ "$j" -le "$M2" ]; do
  printf 'bg-%d\n' "$j" > "$R/zones/agent01/bg-$j.md"
  g -c user.name=agent01 -c user.email=agent01@local add -A
  g -c user.name=agent01 -c user.email=agent01@local commit -q -m "agent01 фон $j"
  j=$((j + 1))
done

# Нарушение (гарантия Н-39, п.5): agent03 коммитит в ЧУЖУЮ зону (agent07) —
# ОБЯЗАН остаться пойман И сегодня, И после батчинга.
mkdir -p "$R/zones/agent07"
printf 'вторжение\n' > "$R/zones/agent07/x.md"
g -c user.name=agent03 -c user.email=agent03@local add -A
g -c user.name=agent03 -c user.email=agent03@local commit -q -m 'agent03 пишет в чужую зону'

# ── прогон check_zones.sh через git-шпиона ─────────────────────────────────────
out="$(PATH="$SPY:$PATH" bash "$CZ" "$R" 2>&1)"; rc=$?
calls="$(wc -c < "$COUNTFILE" | tr -d ' ')"

# ── ассерт 1: нарушение ОБЯЗАНО быть поймано (Н-39, гарантия от быстрой-неверной) ──
printf '%s\n' "$out" | grep -qF 'коммит вне зоны: agent03' \
  || fail "нарушение agent03->zones/agent07/ НЕ поймано (rc=$rc) — тест ловил бы потерю проверки, не производительность:
$out"
[ "$rc" -eq 1 ] || fail "check_zones rc=$rc, ожидался 1 (нарушение объявлено выше поймано, общий rc обязан быть 1)"

# ── ассерт 2 (СТРУКТУРНЫЙ ПРЕДЕЛ, без wall-clock): a·(K+M)+b, M2 НЕ входит (см. п.4) ──
A=6; B=20
bound=$((A * (K + M) + B))
printf 'toy: K=%d контрактов, M=%d фоновых(Фон) + M2=%d фоновых(agent01, через diff-tree), нарушение поймано (rc=1)\n' "$K" "$M" "$M2" >&2
printf 'git-подпроцессов на прогон: %d - граница a*(K+M)+b = %d*(%d+%d)+%d = %d (M2 сознательно не в формуле — см. п.4)\n' \
  "$calls" "$A" "$K" "$M" "$B" "$bound" >&2
[ "$calls" -le "$bound" ] \
  || fail "git-вызовов $calls > границы $bound — неполный/отсутствующий батчинг (Н-126): либо author-lookup, либо diff-tree (либо оба) остались по-коммитными вместо batched-запроса на окно"

printf 'ПРЕДЕЛ ДЕРЖИТСЯ: %d <= %d\n' "$calls" "$bound" >&2
exit 0
