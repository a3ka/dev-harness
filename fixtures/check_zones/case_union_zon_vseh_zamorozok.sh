# ПРИЧИНА: коммит вне зоны
#
# Н-100: зона автора — ОБЪЕДИНЕНИЕ путей, объявленных имени во ВСЕХ замороженных контрактах
# (шапка check_zones.sh «ЗОНЫ ЧИТАЮТСЯ…»), и так же судит check_staged — единый читатель
# lib_zones. Per-contract выбор путей (`$1 == a && $3 == n`) красил легальные коммиты
# перекрывающихся окон (норма §10, 026∥027): путь зоны B, закоммиченный объявленным автором
# внутри открытого диапазона окна A, выходил «вне зоны» у второго потребителя зон.
#
# Игрушка: контракт 001 (agent-x: scripts/) и контракт 002 (agent-x: fixtures/b/) заморожены,
# done-тегов нет — оба диапазона открыты до HEAD. Положительный контроль — ПЕРВЫЙ вызов
# барьера (ворота до пары, прецедент case_regress): agent-x коммитит путь зоны 002, коммит
# лежит и в диапазоне 001 → объединение обязано дать 0. Обманный стаб ниже возвращает
# per-contract фильтр в КОПИЮ барьера и на ТОМ ЖЕ дереве обязан redнуть именем этого пути —
# положительный контроль не пуст: зеленеет объединение, а не «всё подряд». Красное: путь
# вне ОБЪЕДИНЕНИЯ обеих зон (plans/) → 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/'
# Второй контракт замораживает ТОМУ ЖЕ автору ДРУГУЮ зону — перекрывающиеся окна.
printf 'accept\nвердикт\n' > "$R/verdicts/critic/contracts-002-v1.md"
add_contract "$R" 002 'ЗОНА agent-x: fixtures/b/'

# ── положительный контроль (первый вызов, определяющий): путь зоны 002 в диапазоне 001 ──
mkdir -p "$R/fixtures/b"
printf 'легальная работа окна 002\n' > "$R/fixtures/b/union.md"
commit_as "$R" agent-x 'работа окна 002 по пути своей зоны в нём (Н-100: объединение)'
out="$("$BARRIER" "$R" 2>&1)" && rc=0 || rc=$?
[ "$rc" -eq 0 ] || {
  printf 'ОТКАЗ: коммит пути зоны 002 внутри диапазона 001 красный — зона автора не объединение (Н-100):\n%s\n' "$out" >&2
  exit 1
}

# ── обманный стаб: per-contract фильтр возвращён — на том же дереве обязан redнуть ─────
# Копия субъекта под случайным именем (BARRIER_ROOT-паттерн); подмена — двумя заменами
# ровно тех строк, которые меняет фикс Н-100. Не применилась — стаб лжет, отказ до прогона.
SUBJ="$WORK/subj-$$"
cp -r "$REPO/scripts" "$SUBJ"
STUB="$SUBJ/check_zones.sh"
grep -qF -- '$1 == a { print $2 }' "$STUB" || {
  printf 'ОТКАЗ: в барьере нет union-формы выбора зон — стаб строить не из чего\n' >&2
  exit 1
}
sed -i \
  -e "s/-v a=\"\$an\" '\$1 == a /-v a=\"\$an\" -v n=\"\$nnn\" '\$1 == a \&\& \$3 == n /" \
  -e 's/— зона автора (объединение всех замороженных):/— зона контракта $nnn:/' \
  "$STUB"
grep -qF -- '$1 == a && $3 == n { print $2 }' "$STUB" || {
  printf 'ОТКАЗ: подмена стаба не применилась — патч и стаб разошлись\n' >&2
  exit 1
}
out="$(bash "$STUB" "$R" 2>&1)" && src=0 || src=$?
[ "$src" -eq 1 ] || {
  printf 'ОТКАЗ: стаб с per-contract фильтром зелён на union-входе — положительный контроль пуст:\n%s\n' "$out" >&2
  exit 1
}
printf '%s\n' "$out" | grep -qF 'fixtures/b/union.md' || {
  printf 'ОТКАЗ: стаб redнул, но не именем union-пути:\n%s\n' "$out" >&2
  exit 1
}

# ── красное: путь вне ОБЪЕДИНЕНИЯ обеих зон автора → 1 ────────────────────────────────
printf 'вне объединения зон\n' > "$R/plans/vne-obedinenija.md"
commit_as "$R" agent-x 'попутно поправил план — вне обеих зон'
"$BARRIER" "$R"
