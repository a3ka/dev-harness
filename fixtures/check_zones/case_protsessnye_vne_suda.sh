# ПРИЧИНА: коммит вне зоны
#
# Н-53 (контракт 013 §Предмет А): процессные артефакты регламента — verdicts/ ЦЕЛИКОМ
# (все четыре подкаталога: critic/, adversary/, review/, arbitration/ — находка 2
# вердикта 013-v1: частный фильтр «только verdicts/critic/*» обязан краснеть),
# NABLIUDENIA*.md КОРНЕВОГО уровня, HANDOFF.md — не являются конструкцией контракта
# и под суд зон не попадают: каждый судейский круг коммитит их ПО ОПРЕДЕЛЕНИЮ, и суд
# над ними порождает рекурсию carve-out (замерено ×1 на 011, ×2 на 012).
#
# Ветви — 10 вызовов барьера; обманные стабы привязаны к входу, где их дефект НАБЛЮДАЕМ:
# 1. зелёный контроль сразу после make_repo: зонных коммитов ещё нет → 0;
# 2. правка scripts/a.sh в зоне → 0 (положительный контроль: барьер жив,
#    анти-вечно-красное);
# 3–6. процессный коммит verdicts/<pod>/… отдельным коммитом для КАЖДОГО из четырёх
#    подкаталогов → сейчас 1, после §А → 0 (стаб «исключает только verdicts/critic/*»
#    красен ровно на трёх из них: adversary/, review/, arbitration/);
# 7. процессный коммит NABLIUDENIA_ARCHITECT.md → сейчас 1, после §А → 0
#    (стаб «исключает только verdicts/» красен ровно здесь);
# 8. процессный коммит HANDOFF.md → сейчас 1, после §А → 0;
# 9. смешанный коммит HANDOFF.md + scripts/c.sh одним коммитом → 1 ВСЕГДА:
#    фильтруются ФАЙЛЫ, не коммиты (стаб «глотает коммит целиком при любом процессном
#    файле» красен ровно здесь; прецедент e62bc2fe — суд по предметной половине);
# 10. охранная: scripts/b.sh без процессных файлов → 1 ВСЕГДА — исключение не шире
#     трёх путей (стаб «исключает слишком широко» красен здесь и в case_kommit_vne_zony
#     на plans/chuzhoe.md, который обязан остаться красным).
# Каждый процессный путь — ОТДЕЛЬНЫЙ коммит: каждый наблюдаем на своём входе.
# Файл case выходит rc=1 ВСЕГДА (ветвь 10 охранная, последняя): раннер судит фикстуру
# ПОВЫЗОВНО по своим массивам и пофигурных ожиданий не держит, поэтому переход
# «красное → зелёное» предмета несут пробы probe_protsessnye_vne_suda.sh и
# probe_svod_protsessnyh.sh с собственным кодом возврата (находка 1 вердикта 013-v1).
# Серийные вызовы несут `|| true`: код возврата пишет СЕРВЕР канала, а фикстуре
# нужно дойти до следующих ветвей (конвенция check_ceilings/case_razmer_nechitaem).
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/a.sh fixtures/a/'
"$BARRIER" "$R"

printf 'правка в своей зоне\n' >> "$R/scripts/a.sh"
commit_as "$R" agent-x 'работа внутри объявленной зоны'
"$BARRIER" "$R"

for pod in critic adversary review arbitration; do
  mkdir -p "$R/verdicts/$pod"
  printf 'accept\nпроцессный вердикт роли %s — вне суда зон\n' "$pod" > "$R/verdicts/$pod/process-001.md"
  commit_as "$R" agent-x "процессный: вердикт $pod"
  "$BARRIER" "$R" || true
done

printf 'наблюдение архитектора\n' > "$R/NABLIUDENIA_ARCHITECT.md"
commit_as "$R" agent-x 'процессный: наблюдение'
"$BARRIER" "$R" || true

printf 'передача контекста\n' > "$R/HANDOFF.md"
commit_as "$R" agent-x 'процессный: передача контекста'
"$BARRIER" "$R" || true

printf 'передача контекста ещё раз\n' > "$R/HANDOFF.md"
printf 'предметный файл вне зоны\n' > "$R/scripts/c.sh"
commit_as "$R" agent-x 'смешанный: процессное и предметное одним коммитом'
"$BARRIER" "$R" || true

printf 'второй предметный файл вне зоны\n' > "$R/scripts/b.sh"
commit_as "$R" agent-x 'предметный коммит без процессных файлов'
"$BARRIER" "$R"
