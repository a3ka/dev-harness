# ПРИЧИНА: коммит вне зоны
#
# Н-53 (контракт 013 §Предмет А): процессные артефакты регламента — verdicts/ ЦЕЛИКОМ,
# NABLIUDENIA*.md КОРНЕВОГО уровня, HANDOFF.md — не являются конструкцией контракта и
# под суд зон не попадают: каждый судейский круг коммитит их ПО ОПРЕДЕЛЕНИЮ, и суд над
# ними порождает рекурсию carve-out (замерено ×1 на 011, ×2 на 012).
#
# Ветви — 7 вызовов барьера; обманные стабы привязаны к входу, где их дефект НАБЛЮДАЕМ:
# 1. зелёный контроль сразу после make_repo: зонных коммитов ещё нет → 0;
# 2. правка scripts/a.sh в зоне → 0 (положительный контроль: барьер жив,
#    анти-вечно-красное);
# 3. процессный коммит verdicts/critic/… отдельным коммитом → сейчас 1, после §А → 0
#    (стаб «исключает только корневые *.md» красен ровно здесь: verdicts/ остаётся
#    судимым);
# 4. процессный коммит NABLIUDENIA_ARCHITECT.md → сейчас 1, после §А → 0
#    (стаб «исключает только verdicts/» красен ровно здесь);
# 5. процессный коммит HANDOFF.md → сейчас 1, после §А → 0;
# 6. смешанный коммит HANDOFF.md + scripts/c.sh одним коммитом → 1 ВСЕГДА:
#    фильтруются ФАЙЛЫ, не коммиты (стаб «глотает коммит целиком при любом процессном
#    файле» красен ровно здесь; прецедент e62bc2fe — суд по предметной половине);
# 7. охранная: scripts/b.sh без процессных файлов → 1 ВСЕГДА — исключение не шире
#    трёх путей (стаб «исключает слишком широко» красен здесь и в case_kommit_vne_zony
#    на plans/chuzhoe.md, который обязан остаться красным).
# Три процессных коммита — ОТДЕЛЬНЫЕ: каждый путь наблюдаем на своём входе.
# Серийные вызовы несут `|| true`: код возврата пишет СЕРВЕР канала, а фикстуре
# нужно дойти до следующих ветвей (конвенция check_ceilings/case_razmer_nechitaem).
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА agent-x: scripts/a.sh fixtures/a/'
"$BARRIER" "$R"

printf 'правка в своей зоне\n' >> "$R/scripts/a.sh"
commit_as "$R" agent-x 'работа внутри объявленной зоны'
"$BARRIER" "$R"

printf 'accept\nвердикт критика вне суда зон\n' > "$R/verdicts/critic/contracts-001-v2.md"
commit_as "$R" agent-x 'процессный: вердикт критика'
"$BARRIER" "$R" || true

printf 'наблюдение архитектора\n' > "$R/NABLIUDENIA_ARCHITECT.md"
commit_as "$R" agent-x 'процессный: наблюдение'
"$BARRIER" "$R" || true

printf 'передача контекста\n' > "$R/HANDOFF.md"
commit_as "$R" agent-x 'процессный: передача контекста'
"$BARRIER" "$R" || true

printf 'передача контекста ещё раз\n' > "$R/HANDOFF.md"
printf 'предметный файл вне зоны\n' > "$R/scripts/c.sh"
commit_as "$R" agent-x 'смешанный: процессное и предметное одним коммитом'
"$BARRIER" "$R" || true

printf 'второй предметный файл вне зоны\n' > "$R/scripts/b.sh"
commit_as "$R" agent-x 'предметный коммит без процессных файлов'
"$BARRIER" "$R"
