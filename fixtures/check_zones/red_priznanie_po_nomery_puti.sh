#!/usr/bin/env bash
# ПРЕД-ЗАМОРОЗОЧНОЕ КРАСНОЕ контракта 023, ветвь (iv) — признание draft-дельт по
# НОМЕРУ ПУТИ в check_zones (обобщение 021, чинит А-89). Договор: для судимого
# не-merge коммита C и дельта-пути contracts/<M>-<slug>.md:
#   рука А — тег id/CONTRACT/<M> указывает НА САМОМ C → путь исключён из суда
#   (нынешний код check_zones.sh:328-332 судит тег номера ОКНА id/CONTRACT/$nnn —
#   А-89: признание чужого окна кодом не держится);
#   рука Б — тег жив ∧ его коммит is-ancestor C ∧ НЕТ frozen/contracts/<M>/* в
#   предках C → путь исключён (итерации; после заморозки M не признаётся — путь
#   судится зонами);
#   исключается ТОЛЬКО путь contracts/<M>-*; прочие пути коммита судятся обычным
#   порядком — тег не индульгенция (инвариант 021 check_zones.sh:336-343).
# Ретро-стабильно: предикат — по предкам коммита, не по текущему HEAD.
#
# Имя ВНЕ case_*-глоба раннера — НАМЕРЕННО (А-82, прецедент red_mera 021): до
# реализации предмет предъявляется ПРЯМЫМ запуском; конверсия в case_* — следующая
# пачка architect ПОСЛЕ реализации.
#
# ВХОДЫ (Н-39 — по коду; номера РАЗНЫ между воротами; окно везде 001, автор
# agent-x зонирован ТОЛЬКО в scripts/ — contracts/ вне зон, зелёный исход возможен
# ТОЛЬКО через признание, не через зону):
#   в1 чужое окно, тег на коммите (стаб С6 «признание-по-окну» — нынешний код,
#      живая проба А-89/Б4): draft contracts/002-y.md в открытом окне 001, тег
#      id/CONTRACT/002 НА коммите → честное rc 0. СЕГОДНЯ «вне зоны» — КРАСНОЕ;
#   в2 резерв на базе, тег на предке (новая форма резерва Варианта 1): тег
#      id/CONTRACT/005 на коммите основания, draft после него → честное rc 0
#      (рука Б: is-ancestor, заморозки 005 нет). СЕГОДНЯ красно;
#   в3 итерация (многоразовость аудита, боль Б2): второй draft-коммит правит
#      contracts/005-y.md, тег остаётся на основании → честное rc 0. СЕГОДНЯ
#      красно;
#   в4 пост-freeze (стаб С7 «признание-без-границы», канарея перехода): тег 019 на
#      основании, draft, затем frozen/contracts/019/1, затем правка → честный
#      отказ, называющий contracts/019-y.md (рука Б закрыта заморозкой → зонный
#      суд). Сегодня отказывает тоже (окном 001) — совпадение; стаб С7, пустивший
#      пост-freeze итерацию, даёт rc 0 — умирает здесь;
#   в5 смешанный коммит (стаб С8 «тег-индульгенция»): contracts/002-y.md (тег на
#      основании — признаваем) + plans/foo.md (вне зон) → честный отказ называет
#      plans/foo.md и НЕ называет contracts/002-y.md. СЕГОДНЯ отказ называет ОБА —
#      КРАСНОЕ (дельта признания в смешанной форме); стаб С8, исключивший весь
#      коммит, даёт rc 0 — ловится здесь.
#
# СЕГОДНЯ (признания по номеру пути в коде нет) файл красен именованной причиной
# на в1 — это и есть предъявляемое красное (живая проба А-89). ПОСЛЕ реализации
# все ворота дают rc 0.
#
# Коды возврата: 0 — ворота пройдены; 1 — именованный отказ (признание
#               отсутствует либо нарушило договор на воротах).
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
BARRIER="$REPO/scripts/check_zones.sh"
# shellcheck disable=SC1091
. "$HERE/_repo.sh"
WORK="$(mktemp -d /tmp/red023-prizn.XXXXXX)"   # А-78: свежий WORK вне дерева
trap 'rm -rf "$WORK"' EXIT

# ── в1: чужое окно, тег на коммите (стаб С6 — А-89, определяющая дельта) ───────
R1="$WORK/repo_chuzhoe_okno"
make_repo "$R1" 'ЗОНА agent-x: scripts/'
printf '# контракт 002\n\n## Предмет\ndraft чужого номера в открытом окне 001\n' > "$R1/contracts/002-y.md"
commit_as "$R1" agent-x 'draft: чужой номер 002 в окне 001'
g "$R1" tag -a id/CONTRACT/002 -m 'выдача механизмом (фикстура: тег на самом коммите)'
if "$BARRIER" "$R1" 2>"$WORK/err1"; then
  :
else
  rc=$?
  printf 'ОТКАЗ: признание судит тег ОКНА, не номер пути (стаб С6, А-89): draft contracts/002-y.md в открытом окне 001 с тегом id/CONTRACT/002 на самом коммите красен «вне зоны» (rc %s): %s\n' "$rc" "$(grep -h 'вне зоны' "$WORK/err1" | head -2)" >&2
  exit 1
fi

# ── в2: резерв на базе — тег на предке (новая форма резерва, рука Б) ───────────
R2="$WORK/repo_rezerv_na_baze"
make_repo "$R2" 'ЗОНА agent-x: scripts/'
g "$R2" tag -a id/CONTRACT/005 -m 'выдача механизмом (фикстура: резерв до спавна, тег на tip main)'
printf '# контракт 005\n\n## Предмет\ndraft от резерва на базе\n' > "$R2/contracts/005-y.md"
commit_as "$R2" agent-x 'draft: 005 от резерва на основании'
if "$BARRIER" "$R2" 2>"$WORK/err2"; then
  :
else
  rc=$?
  printf 'ОТКАЗ: резерв-на-базе не признан (рука Б отсутствует): draft contracts/005-y.md с живым тегом id/CONTRACT/005 на предке красен «вне зоны» (rc %s): %s\n' "$rc" "$(grep -h 'вне зоны' "$WORK/err2" | head -2)" >&2
  exit 1
fi

# ── в3: итерация — второй draft-коммит (многоразовость аудита, боль Б2) ────────
printf '\nитерация драфта кругом критика\n' >> "$R2/contracts/005-y.md"
commit_as "$R2" agent-x 'итерация: правка драфта 005'
if "$BARRIER" "$R2" 2>"$WORK/err3"; then
  :
else
  rc=$?
  printf 'ОТКАЗ: итерация драфта не признана (дверь одноразова в аудите): второй draft-коммит contracts/005-y.md красен «вне зоны» (rc %s): %s\n' "$rc" "$(grep -h 'вне зоны' "$WORK/err3" | head -2)" >&2
  exit 1
fi

# ── в4: пост-freeze правка (стаб С7 — канарея перехода) ────────────────────────
# Draft-файл несёт грамматику зон: окно 019 (frozen/contracts/019/1..HEAD)
# открывается заморозкой и судит своим объявлением; замораживающий коммит несёт
# путь в зоне (scripts/), чтобы красным был ТОЛЬКО пост-freeze violating-путь.
R4="$WORK/repo_post_freeze"
make_repo "$R4" 'ЗОНА agent-x: scripts/'
g "$R4" tag -a id/CONTRACT/019 -m 'выдача механизмом (фикстура: резерв до спавна)'
{
  printf '# контракт 019\n\n## Предмет\nподставной предмет\n\n## Критерий готовности\nкоманда с кодом возврата\n\n## Исполнители и зоны\n'
  printf 'ЗОНА agent-x: scripts/\n'
} > "$R4/contracts/019-y.md"
commit_as "$R4" agent-x 'draft: 019 от резерва'
printf 'маркер заморозки в зоне\n' > "$R4/scripts/freeze19.txt"
commit_as "$R4" agent-x 'заморозка 019'
g "$R4" tag -a frozen/contracts/019/1 -m 'контракт 019 утверждён'
printf '\nпост-freeze правка драфта\n' >> "$R4/contracts/019-y.md"
commit_as "$R4" agent-x 'правка после заморозки 019'
if "$BARRIER" "$R4" 2>"$WORK/err4"; then
  printf 'ОТКАЗ: признание-без-границы (стаб С7): пост-freeze правка contracts/019-y.md ЗЕЛЕНА (ожидан отказ, называющий путь — рука Б закрыта заморозкой)\n' >&2
  exit 1
else
  rc=$?
  if ! grep -qF 'contracts/019-y.md' "$WORK/err4"; then
    printf 'ОТКАЗ: пост-freeze отказ не называет путь contracts/019-y.md (rc %s): %s\n' "$rc" "$(cat "$WORK/err4")" >&2
    exit 1
  fi
fi

# ── в5: смешанный коммит (стаб С8 «тег-индульгенция») ──────────────────────────
R5="$WORK/repo_smeshannyj"
make_repo "$R5" 'ЗОНА agent-x: scripts/'
g "$R5" tag -a id/CONTRACT/002 -m 'выдача механизмом (фикстура: резерв до спавна)'
printf '# контракт 002\n\n## Предмет\ndraft вместе с нарушением\n' > "$R5/contracts/002-y.md"
printf 'нарушение вне зоны\n' > "$R5/plans/foo.md"
commit_as "$R5" agent-x 'смешанный: draft 002 + plans/foo.md вне зоны'
if "$BARRIER" "$R5" 2>"$WORK/err5"; then
  printf 'ОТКАЗ: тег-индульгенция (стаб С8): смешанный коммит (contracts/002-y.md + plans/foo.md вне зоны) ЗЕЛЕН целиком (ожидан отказ по plans/foo.md)\n' >&2
  exit 1
else
  rc=$?
  if ! grep -qF 'plans/foo.md' "$WORK/err5"; then
    printf 'ОТКАЗ: смешанный коммит: отказ не называет нарушающий путь plans/foo.md (rc %s): %s\n' "$rc" "$(grep -h 'вне зоны' "$WORK/err5" | head -2)" >&2
    exit 1
  fi
  if grep -qF 'contracts/002-y.md' "$WORK/err5"; then
    printf 'ОТКАЗ: смешанный коммит: признаваемый draft-путь contracts/002-y.md судится вместе с нарушением (тег не индульгенция — инвариант 021): %s\n' "$(grep -h 'вне зоны' "$WORK/err5" | head -2)" >&2
    exit 1
  fi
fi

exit 0
