#!/usr/bin/env bash
# ПРЕД-ЗАМОРОЗОЧНОЕ КРАСНОЕ контракта 023, ветвь (iv) — признание draft-дельт по
# НОМЕРУ ПУТИ в check_zones (обобщение 021, чинит А-89) + граница исключительной
# зоны манифеста (dual-control, вердикт 57c8141 блокер 1, грань (б)). Договор:
# для судимого не-merge коммита C и дельта-пути contracts/<M>-<slug>.md:
#   рука А — тег id/CONTRACT/<M> указывает НА САМОМ C → путь исключён из суда
#   (нынешний код check_zones.sh:328-332 судит тег номера ОКНА id/CONTRACT/$nnn —
#   А-89: признание чужого окна кодом не держится);
#   рука Б — тег жив ∧ его коммит is-ancestor C ∧ НЕТ frozen/contracts/<M>/* в
#   предках C → путь исключён (итерации; после заморозки M не признаётся — путь
#   судится зонами);
#   исключается ТОЛЬКО путь contracts/<M>-*; прочие пути коммита судятся обычным
#   порядком — тег не индульгенция (инвариант 021 check_zones.sh:336-343).
# Ретро-стабильно: предикат — по предкам коммита, не по текущему HEAD.
#
# Имя ВНЕ case_*-глоба раннера — НАМЕРЕННО (А-82, прецедент red_mera 021): до
# реализации предмет предъявляется ПРЯМЫМ запуском; конверсия в case_* —
# следующая пачка architect ПОСЛЕ реализации.
#
# ПАРАМЕТРИЗАЦИЯ СЛУЧАЙНЫМИ ВХОДАМИ (вердикт 57c8141 блокер 2; А-88): M из
# НЕПЕРЕСЕКАЮЩИХСЯ поддиапазонов, basename toy-корней и каталог-копия субъекта
# случайны (BARRIER_ROOT-паттерн) — обёртка с константным dispatch не
# собирается; приёмка — ДВА прогона подряд с разными входами.
#
# ВХОДЫ (Н-39 — по коду; номера РАЗНЫ между воротами; окно везде 001, автор
# agent-x зонирован ТОЛЬКО в scripts/ — contracts/ вне зон, зелёный исход возможен
# ТОЛЬКО через признание, не через зону):
#   в1 чужое окно, тег на коммите (стаб С6 «признание-по-окну» — нынешний код,
#      живая проба А-89/Б4): draft contracts/<M1>-y.md в открытом окне 001, тег
#      id/CONTRACT/<M1> НА коммите → честное rc 0. СЕГОДНЯ «вне зоны» — КРАСНОЕ;
#   в2 резерв на базе, тег на предке (новая форма резерва Варианта 1): тег
#      id/CONTRACT/<M2> на коммите основания, draft после него → честное rc 0
#      (рука Б: is-ancestor, заморозки M2 нет). СЕГОДНЯ красно;
#   в3 итерация (многоразовость аудита, боль Б2): второй draft-коммит правит
#      contracts/<M2>-y.md, тег остаётся на основании → честное rc 0. СЕГОДНЯ
#      красно;
#   в4 пост-freeze (стаб С7 «признание-без-границы», канарея перехода): тег <M4> на
#      основании, draft, затем frozen/contracts/<M4>/1, затем правка → честный
#      отказ, называющий contracts/<M4>-y.md (рука Б закрыта заморозкой → зонный
#      суд). Сегодня отказывает тоже (окном 001) — совпадение; стаб С7, пустивший
#      пост-freeze итерацию, даёт rc 0 — умирает здесь;
#   в5 смешанный коммит (стаб С8 «тег-индульгенция»): contracts/<M5>-y.md (тег на
#      основании — признаваем) + plans/foo.md (вне зон) → честный отказ называет
#      plans/foo.md и НЕ называет contracts/<M5>-y.md. СЕГОДНЯ отказ называет
#      ОБА — КРАСНОЕ (дельта признания в смешанной форме); стаб С8, исключивший
#      весь коммит, даёт rc 0 — ловится здесь;
#   в6 АГЕНТСКАЯ СТРОКА МАНИФЕСТА НА WIP (dual-control стаб, грань (б) рамки
#      2026-09-08): registry/contracts.tsv — исключительная зона оркестратора
#      (ни в одной агентской зоне); на main — авторитетная строка «<M6> → sha»
#      (коммит вне суда), агент на wip/001/agent-x минтит СВОЙ тег <M6b> и
#      дописывает СВОЮ строку в реестр, ветка приземляется merge «land:» →
#      честный check_zones КРАСНИТ land именем пути registry/contracts.tsv.
#      ОХРАНА: зелёное и ДО (внезонность — существующая семантика), и ПОСЛЕ;
#      умирает здесь слабая форма, объявившая манифест в агентской зоне или
#      исключившая его из суда (процессное исключение) — агентская строка
#      перестанет краснить land.
#
# СЕГОДНЯ (признания по номеру пути в коде нет) файл красен именованной причиной
# на в1 — это и есть предъявляемое красное (живая проба А-89). ПОСЛЕ реализации
# все ворота дают rc 0.
#
# Коды возврата: 0 — ворота пройдены; 1 — именованный отказ (признание
#               отсутствует либо нарушило договор на воротах).
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
WORK="$(mktemp -d /tmp/red023-prizn.XXXXXX)"   # А-78: свежий WORK вне дерева
trap 'rm -rf "$WORK"' EXIT

# ── случайные входы: ОДИН процесс awk; поддиапазоны непересекающиеся:
# M1 120-189 · M2 200-269 · M4 300-369 · M5 400-469 · M6 500-569 · M6b 570-639.
mapfile -t RD < <(awk 'BEGIN{srand();
  printf "%03d\n", 120+int(rand()*70);
  printf "%03d\n", 200+int(rand()*70);
  printf "%03d\n", 300+int(rand()*70);
  printf "%03d\n", 400+int(rand()*70);
  printf "%03d\n", 500+int(rand()*70);
  printf "%03d\n", 570+int(rand()*70);
  for (i=0;i<7;i++) printf "%d\n", 10000000+int(rand()*89999999)}')
M1="${RD[0]}"; M2="${RD[1]}"; M4="${RD[2]}"; M5="${RD[3]}"; M6="${RD[4]}"; M6b="${RD[5]}"

# Субъект — копия scripts/ под случайным именем (BARRIER_ROOT-паттерн): у судьи
# нет константного пути; соседство sourcing'а (lib_zones/lib_roles/lib_registry/
# next_id) сохранено копией КАТАЛОГА.
BARRIER="$WORK/subj-${RD[6]}/check_zones.sh"
cp -r "$REPO/scripts" "$WORK/subj-${RD[6]}"
# shellcheck disable=SC1091
. "$HERE/_repo.sh"

# ── в1: чужое окно, тег на коммите (стаб С6 — А-89, определяющая дельта) ───────
R1="$WORK/kor-${RD[6]}"
make_repo "$R1" 'ЗОНА agent-x: scripts/'
printf '# контракт %s\n\n## Предмет\ndraft чужого номера в открытом окне 001\n' "$M1" > "$R1/contracts/$M1-y.md"
commit_as "$R1" agent-x "draft: чужой номер $M1 в окне 001"
g "$R1" tag -a "id/CONTRACT/$M1" -m 'выдача механизмом (фикстура: тег на самом коммите)'
if "$BARRIER" "$R1" 2>"$WORK/err1"; then
  :
else
  rc=$?
  printf 'ОТКАЗ: признание судит тег ОКНА, не номер пути (стаб С6, А-89): draft contracts/%s-y.md в открытом окне 001 с тегом id/CONTRACT/%s на самом коммите красен «вне зоны» (rc %s): %s\n' "$M1" "$M1" "$rc" "$(grep -h 'вне зоны' "$WORK/err1" | head -2)" >&2
  exit 1
fi

# ── в2: резерв на базе — тег на предке (новая форма резерва, рука Б) ───────────
R2="$WORK/kor-$((RD[6]+1))"
make_repo "$R2" 'ЗОНА agent-x: scripts/'
g "$R2" tag -a "id/CONTRACT/$M2" -m 'выдача механизмом (фикстура: резерв до спавна, тег на tip main)'
printf '# контракт %s\n\n## Предмет\ndraft от резерва на базе\n' "$M2" > "$R2/contracts/$M2-y.md"
commit_as "$R2" agent-x "draft: $M2 от резерва на основании"
if "$BARRIER" "$R2" 2>"$WORK/err2"; then
  :
else
  rc=$?
  printf 'ОТКАЗ: резерв-на-базе не признан (рука Б отсутствует): draft contracts/%s-y.md с живым тегом id/CONTRACT/%s на предке красен «вне зоны» (rc %s): %s\n' "$M2" "$M2" "$rc" "$(grep -h 'вне зоны' "$WORK/err2" | head -2)" >&2
  exit 1
fi

# ── в3: итерация — второй draft-коммит (многоразовость аудита, боль Б2) ────────
printf '\nитерация драфта кругом критика\n' >> "$R2/contracts/$M2-y.md"
commit_as "$R2" agent-x "итерация: правка драфта $M2"
if "$BARRIER" "$R2" 2>"$WORK/err3"; then
  :
else
  rc=$?
  printf 'ОТКАЗ: итерация драфта не признана (дверь одноразова в аудите): второй draft-коммит contracts/%s-y.md красен «вне зоны» (rc %s): %s\n' "$M2" "$rc" "$(grep -h 'вне зоны' "$WORK/err3" | head -2)" >&2
  exit 1
fi

# ── в4: пост-freeze правка (стаб С7 — канарея перехода) ────────────────────────
# Draft-файл несёт грамматику зон: окно <M4> (frozen/contracts/<M4>/1..HEAD)
# открывается заморозкой и судит своим объявлением; замораживающий коммит несёт
# путь в зоне (scripts/), чтобы красным был ТОЛЬКО пост-freeze violating-путь.
R4="$WORK/kor-$((RD[6]+2))"
make_repo "$R4" 'ЗОНА agent-x: scripts/'
g "$R4" tag -a "id/CONTRACT/$M4" -m 'выдача механизмом (фикстура: резерв до спавна)'
{
  printf '# контракт %s\n\n## Предмет\ndraft под заморозку\n\n## Исполнители и зоны\n' "$M4"
  printf 'ЗОНА agent-x: scripts/\n'
} > "$R4/contracts/$M4-y.md"
commit_as "$R4" agent-x "draft: $M4 от резерва"
printf 'маркер заморозки в зоне\n' > "$R4/scripts/freeze.txt"
commit_as "$R4" agent-x "заморозка $M4"
g "$R4" tag -a "frozen/contracts/$M4/1" -m "контракт $M4 утверждён"
printf '\nпост-freeze правка драфта\n' >> "$R4/contracts/$M4-y.md"
commit_as "$R4" agent-x "правка после заморозки $M4"
if "$BARRIER" "$R4" 2>"$WORK/err4"; then
  printf 'ОТКАЗ: признание-без-границы (стаб С7): пост-freeze правка contracts/%s-y.md ЗЕЛЕНА (ожидан отказ, называющий путь — рука Б закрыта заморозкой)\n' "$M4" >&2
  exit 1
else
  rc=$?
  if ! grep -qF "contracts/$M4-y.md" "$WORK/err4"; then
    printf 'ОТКАЗ: пост-freeze отказ не называет путь contracts/%s-y.md (rc %s): %s\n' "$M4" "$rc" "$(cat "$WORK/err4")" >&2
    exit 1
  fi
fi

# ── в5: смешанный коммит (стаб С8 «тег-индульгенция») ──────────────────────────
R5="$WORK/kor-$((RD[6]+3))"
make_repo "$R5" 'ЗОНА agent-x: scripts/'
g "$R5" tag -a "id/CONTRACT/$M5" -m 'выдача механизмом (фикстура: резерв до спавна)'
printf '# контракт %s\n\n## Предмет\ndraft вместе с нарушением\n' "$M5" > "$R5/contracts/$M5-y.md"
printf 'нарушение вне зоны\n' > "$R5/plans/foo.md"
commit_as "$R5" agent-x "смешанный: draft $M5 + plans/foo.md вне зоны"
if "$BARRIER" "$R5" 2>"$WORK/err5"; then
  printf 'ОТКАЗ: тег-индульгенция (стаб С8): смешанный коммит (contracts/%s-y.md + plans/foo.md вне зоны) ЗЕЛЕН целиком (ожидан отказ по plans/foo.md)\n' "$M5" >&2
  exit 1
else
  rc=$?
  if ! grep -qF 'plans/foo.md' "$WORK/err5"; then
    printf 'ОТКАЗ: смешанный коммит: отказ не называет нарушающий путь plans/foo.md (rc %s): %s\n' "$rc" "$(grep -h 'вне зоны' "$WORK/err5" | head -2)" >&2
    exit 1
  fi
  if grep -qF "contracts/$M5-y.md" "$WORK/err5"; then
    printf 'ОТКАЗ: смешанный коммит: признаваемый draft-путь contracts/%s-y.md судится вместе с нарушением (тег не индульгенция — инвариант 021): %s\n' "$M5" "$(grep -h 'вне зоны' "$WORK/err5" | head -2)" >&2
    exit 1
  fi
fi

# ── в6: агентская строка манифеста на wip (dual-control стаб, грань (б)) ───────
# registry/contracts.tsv — исключительная зона оркестратора: на main авторитетная
# строка «<M6> → <tag-object-sha>» (коммит Фикстуры — автор не объявлен, вне
# суда); агент на wip/001/agent-x минтит СВОЙ тег <M6b> и дописывает СВОЮ строку
# в реестр, land.merge «land: wip/001/agent-x» приносит коммит в окно 001 →
# честный суд КРАСНИТ именем пути. Грамматика строки — ДОСЛОВНО из контракта 023.
R6="$WORK/kor-$((RD[6]+4))"
make_repo "$R6" 'ЗОНА agent-x: scripts/'
g "$R6" tag -a "id/CONTRACT/$M6" -m 'выдача механизмом (фикстура: резерв до спавна)'
sha6="$(git -C "$R6" rev-parse "refs/tags/id/CONTRACT/$M6")"
mkdir -p "$R6/registry"
printf '%s → %s\n' "$M6" "$sha6" > "$R6/registry/contracts.tsv"
commit_as "$R6" Фикстура 'реестр: резерв (авторитетная церемония)'
g "$R6" checkout -q -b wip/001/agent-x main
g "$R6" tag -a "id/CONTRACT/$M6b" -m 'выдача (модель: агентский минт в чужом реестре)'
sha6b="$(git -C "$R6" rev-parse "refs/tags/id/CONTRACT/$M6b")"
printf '%s → %s\n' "$M6b" "$sha6b" >> "$R6/registry/contracts.tsv"
commit_as "$R6" agent-x 'реестр: вписал свой номер (подделка)'
g "$R6" checkout -q main
g "$R6" merge --no-ff -q wip/001/agent-x -m 'land: wip/001/agent-x'
if "$BARRIER" "$R6" 2>"$WORK/err6"; then
  printf 'ОТКАЗ: dual-control (грань (б)): агентская строка манифеста на wip ПРОШЛА land — registry/contracts.tsv обязан краснить вне-зонным судом (исключительная зона оркестратора)\n' >&2
  exit 1
else
  rc=$?
  if ! grep -qF 'registry/contracts.tsv' "$WORK/err6"; then
    printf 'ОТКАЗ: агентская строка манифеста краснит land, но отказ НЕ называет registry/contracts.tsv (rc %s): %s\n' "$rc" "$(cat "$WORK/err6")" >&2
    exit 1
  fi
fi

exit 0
