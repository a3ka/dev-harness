# ОКРУЖЕНИЕ: BASH_FUNC_unset%%=() { if [ "${1:-}" = '-f' ]; then return 0; fi; builtin unset "$@"; }
# ОКРУЖЕНИЕ: BASH_FUNC_git%%=() { local a nw=0; for a in "$@"; do [ "$a" = --no-walk ] && nw=1; done; if [ "$nw" = 1 ]; then command git "$@" | tr -d '\n' | awk -v RS='\0' -v ORS='\0' 'NR%2==1{print;next}{print "not-an-announced-author"}'; else command git "$@"; fi; }
#
# Круг-после-v5 адверсария (verdicts/adversary/contracts-040-v5-circle.md, `d46a615`):
# РЕКУРСИВНОЕ продолжение case_ten_funkcii_git.sh (см. тот файл за объяснением базовой
# git-функции-тени и почему PATH-пин её не ловит). v5 закрывала функцию-тень `git`
# `unset -f dirname git awk sed grep sort tr wc mktemp mkdir cp rm mv comm` сразу после
# пина — но САМА эта строка разрешается bash как голое имя `unset`, и экспортированная
# функция `unset`, no-op'ящая ИМЕННО `-f`-форму (сохраняя честный `unset VAR` для чистки
# GIT_DIR/GIT_WORK_TREE/… в шапке, чтобы не выдать себя явным крахом), нейтрализует v5
# целиком: `unset -f …` после этого ничего не снимает, функция-тень `git` из
# `case_ten_funkcii_git.sh` выживает, автор ВСЕХ коммитов окна подменяется на константу
# "not-an-announced-author", нарушитель исчезает из суда зон, барьер отвечает rc=0.
#
# v6 закрывает ЭТОТ КЛАСС ЦЕЛИКОМ (не добавлением `unset` в список 14 имён — список,
# перечисляющий сам механизм своего снятия, рекурсивно уязвим к следующему отравленному
# имени тем же приёмом): `env -i` re-exec ДО первой строки кода строит дочернему процессу
# окружение ИЗ ПУСТОГО множества — ни `BASH_FUNC_unset%%`, ни `BASH_FUNC_git%%` (никакое
# `BASH_FUNC_*` вообще) не переживают границу, дочернему bash нечего импортировать.
# `unset -f` в дочернем процессе — гарантированный no-op над УЖЕ пустой таблицей функций,
# а не отказавшая защита: обе функции-тени просто никогда не существуют там, где барьер
# читает свои данные.
#
# Зелёный контроль: чистое дерево сразу после заморозки — судимое окно пусто, batched
# author-lookup вообще не вызывается, обе функции-тени инертны по построению → 0.
# Красное: объявленный agent-x коммитит вне своей зоны (в plans/, зона — только
# scripts/), ОБЕ функции-тени присутствуют в окружении вызывающего — барьер ОБЯЗАН
# назвать ИМЕННО «коммит вне зоны» (rc=1), а не смолчать rc=0 из-за нейтрализованного
# `unset -f` и подменённого автора.
#
# Мутант, потерявший блок «ГЕРМЕТИЧНОЕ ОКРУЖЕНИЕ» (re-exec) в check_zones.sh — вернувшийся
# к v5 (`unset -f` без re-exec) — оживляет ОБЕ функции-тени: `unset -f` становится
# no-op'ом функции `unset`, `git`-тень выживает, автор ВСЕХ коммитов окна становится
# "not-an-announced-author", нарушитель ИСЧЕЗАЕТ из суда зон, барьер отвечает rc=0 —
# красный прогон этой фикстуры пропадает, что ловится антиплацебо-протоколом («барьер
# остался зелёным на обманном дереве»).
