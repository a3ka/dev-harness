# ПРИЧИНА: табуляцию
#
# Адверсарий предъявил: git принимает `user.name` с табуляцией, а зоны сериализуются TSV — имя
# рвалось надвое, `cut -f1` сравнивал усечённое, и ОБЪЯВЛЕННЫЙ исполнитель становился
# «необъявленным»: его коммит вне зоны проходил с кодом 0. Имя — идентификатор для механизма, и
# носитель разделителя грамматикой не покрывается.
#
# Зелёный контроль: обычное имя, коммит в зоне → 0. Красное: имя с табуляцией в контракте → код 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R" 'ЗОНА Жора: scripts/a.sh'
printf 'правка в зоне\n' >> "$R/scripts/a.sh"
commit_as "$R" Жора 'работа внутри зоны'
"$BARRIER" "$R"

printf '# контракт 002\n\nЗОНА alice\tevil: scripts/\n' > "$R/contracts/002-y.md"
printf 'accept\nвердикт\n' > "$R/verdicts/critic/contracts-002-v1.md"
commit_all "$R" 'контракт 002 с табуляцией в имени автора'
g "$R" tag -a frozen/contracts/002/1 -m 'заморожен'
"$BARRIER" "$R"
