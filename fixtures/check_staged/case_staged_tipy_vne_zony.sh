# ПРИЧИНА: вне зоны: offzone_T.link
#
# КЛАССОВАЯ фикстура закрытия F-2/F-3 (018 пост-заморозочно; вердикты адверсария кругов 2-3,
# eaafada и da5af96). Заменяет case_staged_udalenie_vne_zony.sh (29116ba): её D-вход — частный
# случай класса. КЛАСС: слабое чтение staged с `--diff-filter=…` судит лишь ЧАСТЬ
# staged-множества — AM теряет D/T/R (форма F-2), AMDR теряет T (форма F-3). Инвариант:
# check_staged обязан судить staged-множество ЦЕЛИКОМ, без исключения типа изменения.
#
# НАБЛЮДАЕМЫЕ ТИПЫ ЭТОГО ЧТЕНИЯ (Н-39: единый источник — эта шапка). Честное чтение —
# `git diff --cached --name-only -z` без фильтров; конфиг global/system нейтрализует сам
# барьер. Замер в такой среде (git 2.55.0): A, M, D, T, R — R100 виден БЕЗ -M/-C:
# rename-детект порцелайна включён по умолчанию, предпосылка «R только с --find-renames»
# опровергнута измерением, R включён в серию. ВНЕ наблюдаемых: C (только с --find-copies,
# которого чтение не передаёт), U (только конфликтный индекс), X/B (штатное staged-состояние
# их не порождает).
#
# ПРОКЛЯТИЕ НАИВНОЙ КОНСТРУКЦИИ: вход с НЕСКОЛЬКИМИ вне-зонными путями разных типов НЕ
# дискриминирует — порча всё равно краснит «вне зоны» по выжившим путям. Поэтому каждый
# серийный вход — ОТДЕЛЬНЫЙ репо с ЕДИНСТВЕННОЙ staged-записью: вне-зонным путём типа t;
# порча, исключающая t, видит на этом входе пустой staged → rc 0 «нечего судить: staged
# пуст» — красное теряется ровно на нём.
#
# СЕНТИНЕЛЬ T: первый красный вызов — T-вход, ПРИЧИНА называет его путь; после своего
# вызова красные репо НЕ мутируются. Красное засчитывает повторный прогон ПЕРВОГО
# красного вызова на финальном состоянии диска: порча, исключающая T, либо глушит T-вход
# (красного нет вовсе — «красное не предъявлено»), либо сдвигает первый красный на
# выживший вход, чей путь не совпадает с ПРИЧИНО («повторный прогон не назвал причину»).
# Обе измеренные формы (AM и AMDR) исключают T — обе обязаны давать scoped rc 1.
#
# ГРАНИЦА ОДНОЙ ФИКСТУРЫ (измерена и названа, не молчаливое сужение): порча, СОХРАНЯЮЩАЯ T,
# но теряющая другой наблюдаемый тип (фильтр AMT теряет D и R — измерено прогоном: до
# набора порча проходила 12/12 rc 0), этой фикстурой не ловится — проверяющий судит только
# первый красный вызов, а он T. Одной фикстурой ловятся ровно порчи, исключающие тип
# ПРИЧИНЫ. Граница закрыта ПОЛНЫМ СЕНТИНЕЛЬ-НАБОРОМ: сентинели A/M/D/R несут
# case_staged_sentr_<T>.sh (у каждой первый красный — её тип), эта фикстура — сентинель T
# набора; порча, роняющая хотя бы один наблюдаемый тип, роняет чужую сентинель → scoped rc 1.
#
# Зелёный контроль: все пять наблюдаемых типов, все пути В зоне (scripts/), один вызов →
# rc 0 «ok: staged в зоне автора implementer (5 путь/путей)».
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

# ── зелёный репо: все наблюдаемые типы, все пути В зоне ────────────────────────
GREEN="$WORK/repo_green"
make_repo "$GREEN"
stage "$GREEN" scripts/green_D.sh     'основание — коммитится, затем staged-удаление'
stage "$GREEN" scripts/green_T.bin    'основание — коммитится файлом, затем staged-типосмена'
stage "$GREEN" scripts/green_R_old.sh 'основание — коммитится, затем staged-переименование'
g "$GREEN" commit -q -m 'основания для D/T/R-записей зелёного контроля'
g "$GREEN" rm -q -- scripts/green_D.sh                                   # D в зоне
rm "$GREEN/scripts/green_T.bin"; ln -s t "$GREEN/scripts/green_T.bin"
g "$GREEN" add -- scripts/green_T.bin                                    # T в зоне
g "$GREEN" mv scripts/green_R_old.sh scripts/green_R_new.sh              # R в зоне
printf 'правка основания' >> "$GREEN/scripts/a.sh"
g "$GREEN" add -- scripts/a.sh                                           # M в зоне
stage "$GREEN" scripts/green_A.sh 'добавление в зоне'                     # A в зоне

# ── красные репо: ЕДИНСТВЕННАЯ staged-запись — вне-зонный путь типа t ──────────
# T (сентинель): путь в HEAD — обычный файл, в индексе — симлинк (типосмена)
RED_T="$WORK/repo_red_T"
make_repo "$RED_T"
stage "$RED_T" offzone_T.link 'файл-основание: в HEAD путь — обычный файл'
g "$RED_T" commit -q -m 'внесение offzone_T.link в HEAD — основание для типосмены'
rm "$RED_T/offzone_T.link"; ln -s t "$RED_T/offzone_T.link"
g "$RED_T" add -- offzone_T.link

# A: новый путь вне зоны
RED_A="$WORK/repo_red_A"
make_repo "$RED_A"
stage "$RED_A" offzone_A.txt 'единственная staged-запись — добавление вне зоны'

# M: путь в HEAD вне зоны, staged-правка
RED_M="$WORK/repo_red_M"
make_repo "$RED_M"
stage "$RED_M" offzone_M.txt 'файл-основание'
g "$RED_M" commit -q -m 'внесение offzone_M.txt в HEAD — основание для правки'
stage "$RED_M" offzone_M.txt 'правка — единственная staged-запись, вне зоны'

# D: путь в HEAD вне зоны, staged-удаление (наследие F-2)
RED_D="$WORK/repo_red_D"
make_repo "$RED_D"
stage "$RED_D" offzone_D.txt 'файл-основание'
g "$RED_D" commit -q -m 'внесение offzone_D.txt в HEAD — основание для удаления'
g "$RED_D" rm -q -- offzone_D.txt

# R: переименование из зоны в корень — name-only несёт только новый путь
RED_R="$WORK/repo_red_R"
make_repo "$RED_R"
stage "$RED_R" scripts/r_old.sh 'содержимое переносится без изменений — чтение без -M видит R100'
g "$RED_R" commit -q -m 'внесение scripts/r_old.sh — основание для переименования'
g "$RED_R" mv scripts/r_old.sh offzone_R.txt

# ── вызовы барьера: серийные, через || true (А-32); репо после вызова не мутируются ──
"$BARRIER" "$GREEN" || true  # ожидание: rc 0 «ok: staged в зоне автора implementer (5 путь/путей)»
"$BARRIER" "$RED_T"  || true # ожидание: rc 1 «ОТКАЗ: вне зоны: offzone_T.link» — сентинель (ПРИЧИНА);
                             # порча с исключением T: rc 0 «нечего судить: staged пуст»
"$BARRIER" "$RED_A"  || true # ожидание: rc 1 «ОТКАЗ: вне зоны: offzone_A.txt»
"$BARRIER" "$RED_M"  || true # ожидание: rc 1 «ОТКАЗ: вне зоны: offzone_M.txt»
"$BARRIER" "$RED_D"  || true # ожидание: rc 1 «ОТКАЗ: вне зоны: offzone_D.txt»;
                             # порча AM (F-2): rc 0 «нечего судить: staged пуст»
"$BARRIER" "$RED_R"  || true # ожидание: rc 1 «ОТКАЗ: вне зоны: offzone_R.txt»;
                             # порча AM теряет и R: rc 0 «нечего судить: staged пуст»
