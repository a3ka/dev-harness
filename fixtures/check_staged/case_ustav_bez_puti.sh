# ПРИЧИНА: не назвала путь
#
# Контракт 019, Н-72: делегирование устава наследует НЕ только итог check_charter,
# но и ГРАММАТИКУ строки РАЗРЕШИЛ-ВЛАДЕЛЕЦ (единый источник — razreshil() в
# check_charter.sh, фикстура грамматику не переизобретает). Ветвь «строка не назвала
# путь»: тело коммита несёт «РАЗРЕШИЛ-ВЛАДЕЛЕЦ:» без пути — безымянное разрешение
# снимает защиту со всего устава навсегда и разрешением считаться не может.
#
# Вход (Н-39): коммит в истории меняет ROADMAP.md, его тело несёт строку РАЗРЕШИЛ
# БЕЗ пути; staged уставного пути у зонированного автора → после 019 делегирование
# возвращает отказ «строка РАЗРЕШИЛ-ВЛАДЕЛЕЦ … не назвала путь». Сегодня причина
# зонная («вне зоны») — грамматика через делегирование не предъявляется.
#
# Зелёный контроль: та же форма с разрешённой правкой (строка с путём и причиной) →
# rc 0 — делегирование различает строку в грамматике от строки вне грамматики, а не
# краснит любую правку устава в истории.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

# ── зелёный контроль: разрешённая правка (путь + причина) в истории ─────────────
GREEN="$WORK/repo_razreshenie_polnoe"
make_repo_ustav "$GREEN"
ustav_change "$GREEN" AGENTS.md 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: AGENTS.md уточнение нормы по прямому слову владельца'
stage "$GREEN" AGENTS.md 'рабочая правка устава зонированным автором'
"$BARRIER" "$GREEN" || true                  # ожидание: rc 0 (строка в грамматике — правка разрешена)

# ── красное: строка РАЗРЕШИЛ БЕЗ пути в теле коммита, меняющего устав ───────────
RED="$WORK/repo_razreshenie_bez_puti"
make_repo_ustav "$RED"
ustav_change "$RED" ROADMAP.md 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ:'
stage "$RED" ROADMAP.md 'staged уставного пути при безымянной строке в истории'
"$BARRIER" "$RED" || true                    # ожидание: rc 1 «не назвала путь»
