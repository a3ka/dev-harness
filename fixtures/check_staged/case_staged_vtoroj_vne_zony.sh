# ПРИЧИНА: вне зоны: zz_offzone.txt
#
# КЛАССОВАЯ фикстура закрытия F-4 (018 пост-заморозочно; вердикт адверсария круга 4,
# c0764ab, «зона судится только у первого staged-пути»). Слабая реализация читает staged
# полностью (не F-1), без --diff-filter (не F-2/F-3), грамматику имени применяет ко всем
# путям — но зонный вопрос задаёт ТОЛЬКО первому элементу списка. Инвариант контракта 018:
# check_staged судит staged-множество ЦЕЛИКОМ.
#
# НАБЛЮДАЕМЫЙ ВХОД (Н-39: единый источник — эта шапка): двухпутевой staged-вход дословно
# как у адверсария (круг 4, «Наблюдающий вход»): `scripts/a_safe.sh` — лексически первый
# в `git diff --cached --name-only -z`, В зоне implementer: scripts/; `zz_offzone.txt` —
# второй, ВНЕ зоны (s < z — порядок устойчив). Автор — implementer, зонирован, wip-веток
# нет → страж среза 1 молчит. Честный барьер: rc 1 «ОТКАЗ: вне зоны: zz_offzone.txt»;
# порча K=1: rc 0 «ok: …» → «красное не предъявлено».
#
# ══ КОНТРАКТ ПЕЧАТИ (единый источник — Н-39; implementer выдаёт ТОЧНО-В-ТОЧЬ) ══
# На КАЖДЫЙ путь, дошедший до зонной точки суда, check_staged печатает строку
#     judged: <путь>
# в stdout, НЕПОСРЕДСТВЕННО ПЕРЕД вызовом zones_match_path, в ТОЙ ЖЕ итерации главного
# цикла — напечатано ⟺ судимо. Свойства формата:
#   * точный префикс `judged: ` — строка извлекается якорем ^judged: , не подстрокой;
#   * <путь> — тот же токен, что получен из staged-чтения, без кавычек/%q, один на строке;
#   * ДОПОЛНИТЕЛЬНАЯ строка: существующий вывод («ok: …», «ОТКАЗ: …») не меняется;
#   * печать ТОЛЬКО в зонной точке: путь, отказанный грамматикой имени (control-символ),
#     до зонной точки не доходит и judged:-строки не получает (он судим грамматикой —
#     case_imja_*); дублей в judging-loop грамматики не добавлять.
#
# Зелёный контроль: двухпутевой вход, ОБА пути в зоне → rc 0 «ok: staged в зоне автора
# implementer (2 путь/путей)».
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

# ── зелёный репо: два пути, оба в зоне ─────────────────────────────────────────
GREEN="$WORK/repo_green"
make_repo "$GREEN"
stage "$GREEN" scripts/a_safe.sh  'первый путь — в зоне'
stage "$GREEN" scripts/b_second.sh 'второй путь — тоже в зоне'

# ── красный репо: первый в зоне, второй ВНЕ зоны (вход F-4) ─────────────────────
RED="$WORK/repo_red"
make_repo "$RED"
stage "$RED" scripts/a_safe.sh 'первый путь — в зоне'
stage "$RED" zz_offzone.txt    'второй путь — вне зоны'

# ── вызовы барьера: серийные, через || true (А-32); репо после вызова не мутируются ──
"$BARRIER" "$GREEN" || true  # ожидание: rc 0 «ok: staged в зоне автора implementer (2 путь/путей)»
"$BARRIER" "$RED"   || true  # ожидание: rc 1 «ОТКАЗ: вне зоны: zz_offzone.txt» — ПРИЧИНА;
                             # порча K=1 (зона только у первого пути): rc 0 — красное не предъявлено
