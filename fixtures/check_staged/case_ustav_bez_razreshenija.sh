# ПРИЧИНА: изменён без разрешения владельца
#
# Контракт 019, Н-72 (развилка (б), решение владельца 2026-08-31): staged-путь
# УСТАВНОГО класса (AGENTS.md/ROADMAP.md при живом теге ustav/1; замороженные
# plans//contracts/) у зонированного автора больше НЕ судится зонами check_staged —
# ворота устава check_charter, ключ — строка РАЗРЕШИЛ-ВЛАДЕЛЕЦ в теле коммита,
# меняющего файл.
#
# Вход различим ДВАЖДЫ (Н-39, по коду обоих судей):
#   * зелёный контроль (сегодня КРАСЕН — измеренная боль Н-72): зонированный автор
#     (implementer, зона scripts/) стадит ROADMAP.md при ЧИСТОЙ истории устава
#     (одно разрешённое изменение со строкой РАЗРЕШИЛ) → после 019 rc 0. Сегодня
#     страж 016 отказывает «вне зоны: ROADMAP.md» — сессия не может закоммитить
#     устав даже по прямому слову владельца;
#   * красное: в истории ПОСЛЕ ustav/1 живёт коммит, меняющий ROADMAP.md БЕЗ строки
#     РАЗРЕШИЛ-ВЛАДЕЛЕЦ; следующий staged уставного пути обязан наследовать вердикт
#     check_charter — отказ с именованной причиной «изменён без разрешения
#     владельца». Сегодня отказ есть, но причина зонная («вне зоны») — вердикт
#     уставного судьи не предъявляется вовсе.
#
# Граница (измерено прогоном 2026-09-01): pre-commit не видит тела КОММЯЩЕГОСЯ
# коммита (COMMIT_EDITMSG отсутствует на входе хука) — ключ РАЗРЕШИЛ текущего
# коммита судится check_charter по истории (CI check:charter + каждое следующее
# делегирование), а не до создания коммита. Фикстура предъявляет ровно эту механику.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

# ── зелёный контроль: история устава чиста (разрешённая правка со строкой) ──────
GREEN="$WORK/repo_chistyj_ustav"
make_repo_ustav "$GREEN"
ustav_change "$GREEN" ROADMAP.md 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: ROADMAP.md вписание майлстоуна по прямому слову владельца'
stage "$GREEN" ROADMAP.md 'рабочая правка устава зонированным автором'
"$BARRIER" "$GREEN" || true                  # ожидание: rc 0 (устав судится check_charter, история чиста)

# ── красное: коммит устава БЕЗ строки РАЗРЕШИЛ в истории + staged уставного пути ─
RED="$WORK/repo_bez_razreshenija"
make_repo_ustav "$RED"
ustav_change "$RED" ROADMAP.md 'правка устава без ключа владельца'
stage "$RED" ROADMAP.md 'следующая правка — делегирование обязано увидеть нарушение в истории'
"$BARRIER" "$RED" || true                    # ожидание: rc 1 «изменён без разрешения владельца»
