# ПРИЧИНА: вне зоны
#
# Контракт 019 v2 (блокер 2 критика, :123): кольцо уставного класса доказано входами
# на ОБЕИХ половинах области, не только AGENTS/ROADMAP:
#   * frozen+ (положительные, серийные входы А-32): замороженный contracts/NNN и
#     замороженный plans/NNN (живой тег первой заморозки) с разрешённой правкой в
#     истории (строка РАЗРЕШИЛ) → делегирование rc 0. Сегодня оба КРАСНЫ (боль Н-72):
#     «вне зоны: contracts/001-x.md» / «вне зоны: plans/001-p.md» — положительного
#     контроля нет, case красен ДО правки кода (правило 3);
#   * frozen− (охрана): contracts/005 и plans/009 БЕЗ тега первой заморозки → НЕ
#     уставного класса → прежний зонный суд: отказ «вне зоны» ДО и ПОСЛЕ 019. Ловит
#     переусердие предиката: безтеговый путь, делегированный check_charter, позеленел
#     бы — assert ранит фикстуру ДО красного кандидата (раннер засчитывает красным
#     ПЕРВЫЙ ненулевой вызов и не судит rc самой фикстуры при состоявшихся вызовах,
#     поэтому порядок входов обязан быть: зелёные → охрана → красное);
#   * ключ владельца на замороженном: правка plans/001-p.md в истории БЕЗ строки
#     → наследованный отказ «изменён без разрешения владельца» (после 019; сегодня
#     «вне зоны» — отказ есть, вердикт уставного судьи не предъявляется).
#
# Обход «предикат только для AGENTS/ROADMAP» (вердикт критика :123) краснит ЭТОТ case
# scoped: обе frozen+-половины уходят в «вне зоны» → «нет положительного контроля».
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

# ── frozen+ контракт: заморожен, история чиста (разрешённая правка со строкой) ───
GREEN_C="$WORK/repo_zamorozhennyj_kontrakt"
make_repo_koltso "$GREEN_C"
ustav_change "$GREEN_C" contracts/001-x.md 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: contracts/001-x.md вписание границы по прямому слову владельца'
stage "$GREEN_C" contracts/001-x.md 'рабочая правка замороженного контракта зонированным автором'
"$BARRIER" "$GREEN_C" || true              # ожидание: rc 0 (после 019; сегодня rc 1 «вне зоны»)

# ── frozen+ план: тот же класс артефакта через plans/ (серийный вход, А-32) ──────
GREEN_P="$WORK/repo_zamorozhennyj_plan"
make_repo_koltso "$GREEN_P"
ustav_change "$GREEN_P" plans/001-p.md 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: plans/001-p.md уточнение критерия по прямому слову владельца'
stage "$GREEN_P" plans/001-p.md 'рабочая правка замороженного плана зонированным автором'
"$BARRIER" "$GREEN_P" || true              # ожидание: rc 0 (после 019; сегодня rc 1 «вне зоны»)

# ── frozen− охрана: БЕЗ тега первой заморозки → черновик → прежний зонный суд ────
# Порядок обязателен: охрана ДО красного кандидата (см. шапку). Номер 005/009 выбран
# ЗАВЕДОМО не следующим свободным CONTRACT (следующий — 002): путь не подпадает и под
# draft-ветку 019, судится только зонами.
OHRANA="$WORK/repo_bez_zamorozki"
make_repo_koltso "$OHRANA"
stage "$OHRANA" contracts/005-bez-tega.md 'тега первой заморозки нет — черновик, судится зонами'
out="$("$BARRIER" "$OHRANA" || true)"
if ! printf '%s\n' "$out" | grep -q 'вне зоны'; then
  printf 'ОТКАЗ: безтеговый contracts/005 не судится зонами — предикат уставного класса переусердствовал: %s\n' "$out" >&2
  exit 1
fi
stage "$OHRANA" plans/009-bez-tega.md 'тега первой заморозки нет — черновик, судится зонами'
out="$("$BARRIER" "$OHRANA" || true)"
if ! printf '%s\n' "$out" | grep -q 'вне зоны'; then
  printf 'ОТКАЗ: безтеговый plans/009 не судится зонами — предикат уставного класса переусердствовал: %s\n' "$out" >&2
  exit 1
fi

# ── красное: замороженный план правлен в истории БЕЗ строки РАЗРЕШИЛ + staged ────
RED="$WORK/repo_zamorozhennyj_plan_narushenie"
make_repo_koltso "$RED"
ustav_change "$RED" plans/001-p.md 'правка замороженного плана без ключа владельца'
stage "$RED" plans/001-p.md 'следующая правка — делегирование обязано увидеть нарушение в истории'
"$BARRIER" "$RED" || true                  # ожидание: rc 1 «изменён без разрешения владельца» (после 019)
