# ПРИЧИНА: вне своей ветки wip/
#
# Срез 1 контракта 018, несущая ветвь: рабочий агент (зонированный автор со СВОЕЙ живой
# веткой wip/<NNN>/<автор>), коммитящий в основной чекаут main вместо своего worktree —
# именованный отказ ДО коммита. Вход различает страж «ветка, не main» от branch-слепого
# барьера (Н-39): на текущем check_staged (стража ветки ещё нет) этот вход ЗЕЛЁН — красное
# не предъявлено, раннер краснит пачку; после среза 1 — rc 1 с причиной.
#
# Зелёный контроль: тот же автор НА своей wip/*-ветке (в своём worktree) → rc 0. Он же
# ловит переусердие: барьер, краснящий зонированного автора НА wip/* тоже, убил бы этот
# контроль.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

# ── зелёный контроль: рабочий агент на СВОЕЙ ветке wip/018/implementer ───────────
GREEN="$WORK/repo_wip"
make_repo "$GREEN"
co_wip "$GREEN" wip/018/implementer          # агент в своём worktree, на своей ветке
stage "$GREEN" scripts/b.sh 'работа исполнителя в зоне scripts/'
"$BARRIER" "$GREEN" || true                  # ожидание: rc 0 (коммит в свою ветку — норма)

# ── красный: тот же зонированный автор коммитит в основной чекаут main, а его ветка
#    wip/018/implementer ЖИВА (его спавнили — cwd-промах Н-74/Р2b) ────────────────
RED="$WORK/repo_main"
make_repo "$RED"
mk_wip "$RED" wip/018/implementer            # ветка жива, но репо остаётся на main
stage "$RED" scripts/b.sh 'та же работа, но мимо worktree — в основной чекаут'
"$BARRIER" "$RED" || true                    # ожидание: rc 1 «вне своей ветки wip/»
