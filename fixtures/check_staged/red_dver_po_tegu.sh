#!/usr/bin/env bash
# ПРЕД-ЗАМОРОЗОЧНОЕ КРАСНОЕ контракта 023, ветвь (iii) — дверь draft-пуска по тегу
# выдачи в check_staged (Н-77(г)). Договор двери: staged-путь
# contracts/<NNN>-<slug>.md под architect пропускается ⟺ ПЯТЬ условий ВМЕСТЕ:
# (1) грамматика пути contracts/[0-9][0-9][0-9]-*; (2) тег id/CONTRACT/<NNN> жив
# локально; (3) ПРОВЕНАНС = DUAL-CONTROL (слово владельца 2026-09-08, вердикт
# 57c8141 блокер 1) — ВМЕСТЕ: (3а) тот же тег достижим на origin (ls-remote
# точного имени) ∧ (3б) манифест registry/contracts.tsv, прочитанный по ЖИВОЙ
# шапке refs/heads/main НА origin (сетевое чтение ls-remote→fetch→show; НЕ
# локальная ветка/remote-tracking/рабочая копия — ими владеет агент), несёт
# строку «<NNN> → <tag-object-sha>» ∧ (3в) sha тега на origin == sha строки;
# (4) текущая ветка wip/<NNN>/<автор>; (5) contracts/<NNN>-* нет в
# refs/heads/main. Нарушение любого из (3а)/(3б)/(3в) — «тег <NNN> не выдан
# авторитетом»: и self-mint (тега нет на origin), и агентский origin-push тега
# без строки манифеста, и минт поверх с расходящимся sha (аннотированный
# tag-object включает tagger/время/сообщение — подделка до бита не сходится).
# Дверь многоразова до приземления. Каждый отказ именован причиной нарушенного
# условия; порядок: грамматика → реестр (2) → провенанс (3) → ветка (4) →
# приземление (5); мёртвый тег → «номер <NNN> не выдан» прежде отказа по ветке
# (реестр первичен); self-mint и агентский пуш без манифеста → «не выдан
# авторитетом» прежде отказа по ветке (гейминг реестра глубже дисциплины ветки);
# недоступный origin → «авторитет недоступен» (fail-closed: обрыв сети НЕ
# открывает дверь; имя отдельное — сетевой сбой не клеветлет геймингом и
# наоборот).
#
# Имя ВНЕ case_*-глоба раннера — НАМЕРЕННО (А-82, прецедент red_mera 021): раннер
# судит каждый case по стандарт-А и не имеет режима «видеть красный кейс
# нереализованного предмета, не уронив CI». До реализации предмет предъявляется
# ПРЯМЫМ запуском этого файла; конверсия в case_* — следующая пачка architect ПОСЛЕ
# реализации (протокол раннера: зелёный контроль + красный повтор).
#
# ПАРАМЕТРИЗАЦИЯ СЛУЧАЙНЫМИ ВХОДАМИ (вердикт 57c8141 блокер 2; А-88 — константа
# фикстуры не есть инвариантность): каждый прогон черпает NNN из НЕПЕРЕСЕКАЮЩИХСЯ
# широких поддиапазонов (номера разных ворот не совпадают и не повторяются между
# прогонами), basename toy-корней случаен, субъект — КОПИЯ scripts/ под случайным
# именем (BARRIER_ROOT-паттерн check_scoped_run.sh: судья не имеет константного
# пути; копия каталога сохраняет соседство sourcing'а lib_zones/next_id/
# check_charter). Обёртка с константным dispatch по именам/номерам входов не
# собирается ни на одном прогоне; приёмка — ДВА прогона подряд с разными входами.
#
# ВХОДЫ (Н-39 — привязка к ветвям по коду, шапки ворот; номера РАЗНЫ между
# воротами — форма, ключующаяся на константу одного входа, умирает на соседних):
#   в0  положительный контроль резерва, ветвь (i): next_id issue-режим в подставном
#       корне печатает NNN и создаёт аннотированный id/CONTRACT/<NNN>
#       (next_id.sh:477-511) — ЗЕЛЁНОЕ и ДО, и ПОСЛЕ (нового кода в (i) нет);
#   в1  многоразовость (определяющая дельта, боль Б2): резерв ПОЛНОЙ церемонией
#       mint_rezerv (тег + строка манифеста на origin/main + оба пуша), ветка
#       своя, первый draft-коммит уже в ветке, staged ПРАВКА драфта → честное rc 0
#       (main файла не несёт). СЕГОДНЯ peek ушёл на N+1 → «вне зоны» — КРАСНОЕ;
#   в2  peek-номер без резерва (стаб С3 «номер-по-peek» — нынешний код): ветка
#       wip/Z/architect занимает Z, staged contracts/P-x.md, P = Z+1 — следующий
#       свободный по max+1 (источник 2 видит ветку Z; staged путь в источники не
#       входит), тега id/CONTRACT/P НЕТ → честный отказ «номер P не выдан»
#       (порядок двери: мёртвый тег прежде ветки — реестр первичен; origin
#       воротами НЕ опрашивается — отказ на условии 2). СЕГОДНЯ peek-дверь путь
#       ПУСКАЕТ — КРАСНОЕ (дельта вычисление→реестр);
#   в3  приземлённый номер (стаб С1 «тег-есть-пропуск»): резерв mint_rezerv, файл
#       В main → честный отказ (условие 5). Сегодня отказывает
#       peek-несовпадением — совпадение, ворота-канарея (стаб, позеленевший вход,
#       умирает здесь);
#   в4  чужая ветка (стаб С2 «дверь-без-ветки»): путь Na (резерв mint_rezerv) на
#       ветке wip/Nb/architect, Na ≠ Nb → честный отказ (условие 4). Сегодня
#       совпадение — канарея;
#   в5  не-architect при полном резерве (канарейка двери): implementer на своей
#       wip/N/implementer → отказ зонным судом («вне зоны», не сетью — провенанс
#       зелёный, чтобы отказ был именем автора). ДО и ПОСЛЕ — красный вход;
#   в6  self-mint (стаб С9 «локальный тег = выдан», боль Б6 — слово владельца
#       2026-09-08): тег id/CONTRACT/N создан ЛОКАЛЬНО и НЕ запушен — ровно то,
#       что делает агент из своего worktree (`next_id --issue`; refs общие).
#       Честная дверь: отказ «тег N не выдан авторитетом» (3а, прежде ветки).
#       СЕГОДНЯ peek-дверь даёт «вне зоны» БЕЗ имени провенанса — КРАСНОЕ ПО
#       ИМЕНИ;
#   в7  origin недоступен (стаб С10 «fail-open по сети»): резерв mint_rezerv,
#       затем origin перенаправлен на несуществующий путь — честная дверь
#       ОТКАЗЫВАЕТ fail-closed «авторитет недоступен» (обрыв сети не есть
#       санкция; стаб, пускающий при недоступности, умирает здесь). СЕГОДНЯ
#       «вне зоны» без имени — КРАСНОЕ ПО ИМЕНИ;
#   в8  АГЕНТСКИЙ origin-push БЕЗ МАНИФЕСТА (dual-control стаб, вердикт 57c8141
#       блокер 1 — обход «тот же процесс создаёт тег и сам пушит его в
#       настроенный origin»): тег заминчен локально И запушен на origin ФИКСТУРОЙ
#       от лица агента, строки «N → sha» в манифесте origin/main НЕТ. Честная
#       дверь: отказ «тег N не выдан авторитетом» (3б — достижимости мало,
#       авторитет санкционирует СТРОКОЙ манифеста). СЕГОДНЯ peek-дверь даёт
#       «вне зоны» без имени — КРАСНОЕ ПО ИМЕНИ.
# Охрана «судья не создаёт тег id/*» (мера не меняет предмет): снимок id-тегов ДО
# вызова против ПОСЛЕ на каждом судимом репо (правило 8 — ожидание в памяти).
#
# СЕГОДНЯ (двери по тегу в коде нет) файл красен именованной причиной на первых же
# воротах с дельтой (в1/в2; в6/в7/в8 — тем же классом: отказ без требуемого имени)
# — это и есть предъявляемое красное. ПОСЛЕ реализации все ворота дают rc 0.
#
# Коды возврата: 0 — ворота пройдены; 1 — именованный отказ (дверь отсутствует
#               либо нарушила договор на воротах).
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
WORK="$(mktemp -d /tmp/red023-dver.XXXXXX)"   # А-78: свежий WORK вне дерева
trap 'rm -rf "$WORK"' EXIT

# ── случайные входы: ОДИН процесс awk (srand от времени; два вызова в одну
# секунду дали бы ОДИНАКОВЫЕ ряды — числа черпаются разом). Поддиапазоны
# непересекающиеся: N1 120-199 · Z2 200-289 (P=Z+1 ≤ 290) · N3 300-369 ·
# Na 370-439 · Nb 440-499 · N5 500-559 · N6 560-629 · N7 630-699 · N8 700-789.
mapfile -t RD < <(awk 'BEGIN{srand();
  printf "%03d\n", 120+int(rand()*80);
  printf "%03d\n", 200+int(rand()*90);
  printf "%03d\n", 300+int(rand()*70);
  printf "%03d\n", 370+int(rand()*70);
  printf "%03d\n", 440+int(rand()*60);
  printf "%03d\n", 500+int(rand()*60);
  printf "%03d\n", 560+int(rand()*70);
  printf "%03d\n", 630+int(rand()*70);
  printf "%03d\n", 700+int(rand()*90);
  for (i=0;i<9;i++) printf "%d\n", 10000000+int(rand()*89999999)}')
N1="${RD[0]}"; Z2="${RD[1]}"; P2="$(printf '%03d' "$((10#${RD[1]} + 1))")"
N3="${RD[2]}"; Na="${RD[3]}"; Nb="${RD[4]}"
N5="${RD[5]}"; N6="${RD[6]}"; N7="${RD[7]}"; N8="${RD[8]}"

# Субъект — копия scripts/ под случайным именем (BARRIER_ROOT-паттерн): у судьи
# нет константного пути; соседство sourcing'а сохранено копией КАТАЛОГА.
BARRIER="$WORK/subj-${RD[9]}"
cp -r "$REPO/scripts" "$BARRIER"
# shellcheck disable=SC1091
. "$HERE/_repo.sh"

id_tags_of() { git -C "$1" for-each-ref --format='%(refname)' 'refs/tags/id/'; }
assert_no_new_id_tags() {  # <корень> <снимок-до>
  novye="$(comm -13 <(printf '%s\n' "$2" | sort) <(printf '%s\n' "$(id_tags_of "$1")" | sort))"
  if [ -n "${novye//$'\n'/}" ]; then
    printf 'ОТКАЗ: судья создал тег выдачи id/* — мера изменила предмет (%s): %s\n' "$1" "$novye" >&2
    exit 1
  fi
}

# ── в0: положительный контроль резерва (ветвь (i), стабильное зелёное) ────────
T0="$WORK/kor-${RD[9]}"
make_repo_archzone "$T0"
out="$(bash "$REPO/scripts/next_id.sh" "$T0" CONTRACT 2>"$WORK/err0")" && rc=0 || rc=$?
if [ "$rc" -ne 0 ]; then
  printf 'ОТКАЗ: ветвь (i): issue-режим next_id не выдал номер в подставном корне (rc %s): %s\n' "$rc" "$(cat "$WORK/err0")" >&2
  exit 1
fi
case "$out" in
  [0-9][0-9][0-9]) ;;
  *) printf 'ОТКАЗ: ветвь (i): next_id напечатал не трёхзначный номер: «%s»\n' "$out" >&2; exit 1 ;;
esac
if ! git -C "$T0" show-ref --verify --quiet "refs/tags/id/CONTRACT/$out"; then
  printf 'ОТКАЗ: ветвь (i): номер %s напечатан, тег id/CONTRACT/%s не создан\n' "$out" "$out" >&2
  exit 1
fi

# ── в1: многоразовость двери (определяющая дельта, боль Б2) ────────────────────
# Резерв — ПОЛНОЙ церемонией mint_rezerv (тег + манифест на origin/main + пуши),
# ветка wip/N1/architect, первый draft-коммит УЖЕ в ветке, staged — ПРАВКА
# драфта. Честная дверь: rc 0. Сегодня: peek=N1+1 → «вне зоны» rc 1 — красное
# предъявлено.
T1="$WORK/kor-${RD[10]}"
make_repo_archzone "$T1"
toy_origin "$T1" >/dev/null
mint_rezerv "$T1" "$N1"
co_wip "$T1" "wip/$N1/architect"
set_author "$T1" architect
mkdir -p "$T1/contracts"
printf '# контракт %s\n\n## Предмет\nпервый draft-коммит уже в ветке\n' "$N1" > "$T1/contracts/$N1-y.md"
g "$T1" add -A
g "$T1" commit -q -m 'draft: первая посадка'
printf '\nправка драфта кругом критика\n' >> "$T1/contracts/$N1-y.md"
g "$T1" add -A
t1_id0="$(id_tags_of "$T1")"
out="$("$BARRIER/check_staged.sh" "$T1" 2>"$WORK/err1")" && rc=0 || rc=$?
assert_no_new_id_tags "$T1" "$t1_id0"
if [ "$rc" -ne 0 ]; then
  printf 'ОТКАЗ: дверь по тегу отсутствует — многоразовость: правка собственного драфта %s (резерв mint_rezerv: тег и строка манифеста на origin) отказана «вне зоны» (peek одноразов, боль Б2): %s\n' "$N1" "$(cat "$WORK/err1")" >&2
  exit 1
fi

# ── в2: peek-номер без резерва (стаб С3 «номер-по-peek» — нынешний код) ────────
# Ветка wip/Z2/architect занимает Z2, staged contracts/P2-x.md, P2 = Z2+1 —
# следующий свободный по max+1, тега id/CONTRACT/P2 НЕТ. Честная дверь: отказ
# «номер P2 не выдан» (условие 2, origin не опрашивается — реестр первичен).
# Сегодня peek-дверь путь ПУСКАЕТ — красное предъявлено (дельта вычисление→реестр).
T2="$WORK/kor-${RD[11]}"
make_repo_archzone "$T2"
co_wip "$T2" "wip/$Z2/architect"
set_author "$T2" architect
stage "$T2" "contracts/$P2-x.md" 'черновик по peek без резерва'
t2_id0="$(id_tags_of "$T2")"
out="$("$BARRIER/check_staged.sh" "$T2" 2>"$WORK/err2")" && rc=0 || rc=$?
assert_no_new_id_tags "$T2" "$t2_id0"
if [ "$rc" -ne 1 ] || ! grep -qF 'не выдан' "$WORK/err2"; then
  printf 'ОТКАЗ: стаб С3 «номер-по-peek»: contracts/%s-x.md без тега id/CONTRACT/%s ПУЩЕН (rc %s, ожидан rc 1 «номер %s не выдан»): %s\n' "$P2" "$P2" "$rc" "$P2" "$(cat "$WORK/err2")" >&2
  exit 1
fi

# ── в3: приземлённый номер (стаб С1 «тег-есть-пропуск» — канарея перехода) ─────
# Файл УЖЕ в main, резерв mint_rezerv, ветка своя. Честная дверь: отказ
# (условие 5). Стаб С1 (нет условия «файла нет в main») пускает — умирает здесь.
T3="$WORK/kor-${RD[12]}"
make_repo_archzone "$T3"
mkdir -p "$T3/contracts"
printf '# контракт %s (приземлён)\n' "$N3" > "$T3/contracts/$N3-x.md"
g "$T3" add -A
g "$T3" commit -q -m 'посадка в main'
toy_origin "$T3" >/dev/null
mint_rezerv "$T3" "$N3"
co_wip "$T3" "wip/$N3/architect"
set_author "$T3" architect
printf '\nправка приземлённого\n' >> "$T3/contracts/$N3-x.md"
g "$T3" add -A
t3_id0="$(id_tags_of "$T3")"
out="$("$BARRIER/check_staged.sh" "$T3" 2>"$WORK/err3")" && rc=0 || rc=$?
assert_no_new_id_tags "$T3" "$t3_id0"
if [ "$rc" -ne 1 ]; then
  printf 'ОТКАЗ: стаб С1 «тег-есть-пропуск»: правка приземлённого %s (файл в main) ПУЩЕНА (rc %s, ожидан отказ): %s\n' "$N3" "$rc" "$(cat "$WORK/err3")" >&2
  exit 1
fi

# ── в4: чужая ветка (стаб С2 «дверь-без-ветки» — канарея перехода) ────────────
# Путь Na (резерв mint_rezerv), текущая ветка wip/Nb/architect — номер ветки ≠
# номер пути. Честная дверь: отказ (условие 4). Стаб С2 пускает — умирает здесь.
T4="$WORK/kor-${RD[13]}"
make_repo_archzone "$T4"
toy_origin "$T4" >/dev/null
mint_rezerv "$T4" "$Na"
co_wip "$T4" "wip/$Nb/architect"
set_author "$T4" architect
stage "$T4" "contracts/$Na-x.md" 'draft с чужой ветки'
t4_id0="$(id_tags_of "$T4")"
out="$("$BARRIER/check_staged.sh" "$T4" 2>"$WORK/err4")" && rc=0 || rc=$?
assert_no_new_id_tags "$T4" "$t4_id0"
if [ "$rc" -ne 1 ]; then
  printf 'ОТКАЗ: стаб С2 «дверь-без-ветки»: draft %s с чужой ветки wip/%s/architect ПУЩЕН (rc %s, ожидан отказ): %s\n' "$Na" "$Nb" "$rc" "$(cat "$WORK/err4")" >&2
  exit 1
fi

# ── в5: не-architect при полном резерве (канарейка: дверь не расширяет прав) ───
# implementer на СВОЕЙ wip/N5/implementer, резерв mint_rezerv (провенанс зелёный
# — отказ обязан быть именем автора/зоны, не сетью): дверь только для architect →
# зонный суд → «вне зоны». ДО и ПОСЛЕ — красный вход.
T5="$WORK/kor-${RD[14]}"
make_repo "$T5"
toy_origin "$T5" >/dev/null
mint_rezerv "$T5" "$N5"
co_wip "$T5" "wip/$N5/implementer"
set_author "$T5" implementer
stage "$T5" "contracts/$N5-x.md" 'draft под чужим автором'
t5_id0="$(id_tags_of "$T5")"
out="$("$BARRIER/check_staged.sh" "$T5" 2>"$WORK/err5")" && rc=0 || rc=$?
assert_no_new_id_tags "$T5" "$t5_id0"
if [ "$rc" -ne 1 ]; then
  printf 'ОТКАЗ: не-architect при живом резерве %s ПУЩЕН дверью (rc %s, ожидан «вне зоны»): %s\n' "$N5" "$rc" "$(cat "$WORK/err5")" >&2
  exit 1
fi

# ── в6: self-mint (стаб С9 «локальный тег = выдан», боль Б6) ───────────────────
# Тег id/CONTRACT/N6 создан ЛОКАЛЬНО, toy-origin жив (main запушен), тег НЕ
# запушен — модель self-mint агента (next_id --issue из worktree; refs общие).
# Ветка своя, файла нет в main, грамматика верна — ЕДИНСТВЕННОЕ нарушенное
# условие 3а. Честная дверь: отказ «тег N6 не выдан авторитетом» ДО разбора
# ветки. Стаб С9 (локальное существование = выдача) пускает — умирает здесь.
# Сегодня: peek=N6+1 → «вне зоны» БЕЗ имени провенанса — красное по имени.
T6="$WORK/kor-${RD[15]}"
make_repo_archzone "$T6"
toy_origin "$T6" >/dev/null
g "$T6" tag -a "id/CONTRACT/$N6" -m 'выдача механизмом (фикстура: self-mint, НЕ запушен)'
co_wip "$T6" "wip/$N6/architect"
set_author "$T6" architect
stage "$T6" "contracts/$N6-x.md" 'draft по self-mint тегу'
t6_id0="$(id_tags_of "$T6")"
out="$("$BARRIER/check_staged.sh" "$T6" 2>"$WORK/err6")" && rc=0 || rc=$?
assert_no_new_id_tags "$T6" "$t6_id0"
if [ "$rc" -ne 1 ] || ! grep -qF 'не выдан авторитетом' "$WORK/err6"; then
  printf 'ОТКАЗ: стаб С9 «self-mint»: draft %s по локальному (вне origin) тегу ПУЩЕН/не назван (rc %s, ожидан rc 1 «тег %s не выдан авторитетом»): %s\n' "$N6" "$rc" "$N6" "$(cat "$WORK/err6")" >&2
  exit 1
fi

# ── в7: origin недоступен (стаб С10 «fail-open по сети») ───────────────────────
# Резерв mint_rezerv N7, затем origin перенаправлен на несуществующий путь
# (сетевой отказ моделируется файлом — детерминированно, DNS не касается).
# Честная дверь: отказ «авторитет недоступен» (fail-closed — обрыв сети не есть
# санкция; имя ОТДЕЛЬНОЕ от «не выдан авторитетом»: различаются стабы, путающие
# недоступность с отсутствием тега). Стаб С10 умирает здесь. Сегодня: peek=N7+1
# → «вне зоны» без имени — красное по имени.
T7="$WORK/kor-${RD[16]}"
make_repo_archzone "$T7"
toy_origin "$T7" >/dev/null
mint_rezerv "$T7" "$N7"
g "$T7" remote set-url origin "$WORK/net-missing.git"
co_wip "$T7" "wip/$N7/architect"
set_author "$T7" architect
stage "$T7" "contracts/$N7-x.md" 'draft при недоступном авторитете'
t7_id0="$(id_tags_of "$T7")"
out="$("$BARRIER/check_staged.sh" "$T7" 2>"$WORK/err7")" && rc=0 || rc=$?
assert_no_new_id_tags "$T7" "$t7_id0"
if [ "$rc" -ne 1 ] || ! grep -qF 'авторитет недоступен' "$WORK/err7"; then
  printf 'ОТКАЗ: стаб С10 «fail-open по сети»: draft %s при недоступном origin ПУЩЕН/не назван (rc %s, ожидан rc 1 «авторитет недоступен»): %s\n' "$N7" "$rc" "$(cat "$WORK/err7")" >&2
  exit 1
fi

# ── в8: агентский origin-push БЕЗ манифеста (dual-control стаб, блокер 1) ──────
# Тег N8 заминчен локально и запушен на origin САМИМ «агентом» (фикстурой) —
# ровно обход вердикта 57c8141: ls-remote становится непустым. Строки
# «N8 → sha» в манифесте origin/main НЕТ: авторитет выдачу не санкционировал.
# Честная дверь: отказ «тег N8 не выдан авторитетом» (3б: достижимости мало).
# Стаб «ls-remote непуст = выдан» умирает здесь. Сегодня: peek=N8+1 → «вне
# зоны» без имени — красное по имени.
T8="$WORK/kor-${RD[17]}"
make_repo_archzone "$T8"
toy_origin "$T8" >/dev/null
g "$T8" tag -a "id/CONTRACT/$N8" -m 'выдача (модель: агентский минт + агентский пуш тега)'
g "$T8" push -q origin "refs/tags/id/CONTRACT/$N8"
co_wip "$T8" "wip/$N8/architect"
set_author "$T8" architect
stage "$T8" "contracts/$N8-x.md" 'draft по агентскому origin-push без манифеста'
t8_id0="$(id_tags_of "$T8")"
out="$("$BARRIER/check_staged.sh" "$T8" 2>"$WORK/err8")" && rc=0 || rc=$?
assert_no_new_id_tags "$T8" "$t8_id0"
if [ "$rc" -ne 1 ] || ! grep -qF 'не выдан авторитетом' "$WORK/err8"; then
  printf 'ОТКАЗ: dual-control (блокер 1): draft %s по агентски запушенному (без строки манифеста) тегу ПУЩЕН/не назван (rc %s, ожидан rc 1 «тег %s не выдан авторитетом»): %s\n' "$N8" "$rc" "$N8" "$(cat "$WORK/err8")" >&2
  exit 1
fi

exit 0
