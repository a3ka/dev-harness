#!/usr/bin/env bash
# ПРЕД-ЗАМОРОЗОЧНОЕ КРАСНОЕ контракта 023, ветвь (iii) — дверь draft-пуска по тегу
# выдачи в check_staged (Н-77(г)). Договор двери: staged-путь
# contracts/<NNN>-<slug>.md под architect пропускается ⟺ ПЯТЬ условий ВМЕСТЕ:
# (1) грамматика пути contracts/[0-9][0-9][0-9]-*; (2) тег id/CONTRACT/<NNN> жив
# локально; (3) ПРОВЕНАНС — тот же тег достижим на origin (ls-remote точного имени;
# слово владельца 2026-09-08: тег минтится тем, кого агент НЕ контролирует — refs
# общей связки worktree агент минтит сам, на origin тег попадает только пушем
# оркестратора/владельца); (4) текущая ветка wip/<NNN>/<автор>;
# (5) contracts/<NNN>-* нет в refs/heads/main.
# Дверь многоразова до приземления. Каждый отказ именован причиной нарушенного
# условия; порядок: грамматика → реестр (2) → провенанс (3) → ветка (4) →
# приземление (5); мёртвый тег → «номер <NNN> не выдан» прежде отказа по ветке
# (реестр первичен; эти ворота пиняют строку «не выдан» для случая мёртвого тега);
# self-mint → «тег <NNN> не выдан авторитетом» прежде отказа по ветке (гейминг
# реестра глубже дисциплины ветки); недоступный origin → «авторитет недоступен»
# (fail-closed: обрыв сети НЕ открывает дверь; имя отдельное — сетевой сбой не
# клеветлет геймингом и наоборот).
#
# Имя ВНЕ case_*-глоба раннера — НАМЕРЕННО (А-82, прецедент red_mera 021): раннер
# судит каждый case по стандарт-А и не имеет режима «видеть красный кейс
# нереализованного предмета, не уронив CI». До реализации предмет предъявляется
# ПРЯМЫМ запуском этого файла; конверсия в case_* — следующая пачка architect ПОСЛЕ
# реализации (протокол раннера: зелёный контроль + красный повтор).
#
# ВХОДЫ (Н-39 — привязка к ветвям по коду, шапки ворот; номера РАЗНЫ между
# воротами — форма, ключующаяся на константу одного входа, умирает на соседних):
#   в0  положительный контроль резерва, ветвь (i): next_id issue-режим в подставном
#       корне печатает NNN и создаёт аннотированный id/CONTRACT/<NNN>
#       (next_id.sh:477-511) — ЗЕЛЁНОЕ и ДО, и ПОСЛЕ (нового кода в (i) нет);
#   в1  многоразовость (определяющая дельта, боль Б2): N=031, тег жив НА origin
#       (toy-origin bare, тег запушен — авторитетная половина церемонии (i)), ветка
#       своя, первый draft-коммит уже в ветке, staged ПРАВКА драфта → честное rc 0
#       (main файла не несёт). СЕГОДНЯ peek ушёл на 032 → «вне зоны» — КРАСНОЕ;
#   в2  peek-номер без резерва (стаб С3 «номер-по-peek» — нынешний код): ветка
#       wip/031/architect, staged contracts/032-x.md — следующий свободный по
#       max+1 (источник 2 видит ветку 031; staged путь в источники не входит),
#       тега id/CONTRACT/032 НЕТ → честный отказ «номер 032 не выдан» (порядок
#       двери: мёртвый тег прежде ветки — реестр первичен; origin воротами НЕ
#       опрашивается — отказ на условии 2). СЕГОДНЯ peek-дверь путь ПУСКАЕТ —
#       КРАСНОЕ (дельта вычисление→реестр);
#   в3  приземлённый номер (стаб С1 «тег-есть-пропуск»): N=019, тег жив НА origin,
#       файл В main → честный отказ (условие 5). Сегодня отказывает
#       peek-несовпадением — совпадение, ворота-канарея (стаб, позеленевший вход,
#       умирает здесь);
#   в4  чужая ветка (стаб С2 «дверь-без-ветки»): путь 033 (тег жив НА origin) на
#       ветке wip/045/architect → честный отказ (условие 4). Сегодня совпадение —
#       канарея;
#   в5  не-architect при живом теге НА origin (канарейка двери): implementer на
#       своей wip/031/implementer → отказ зонным судом («вне зоны», не сетью —
#       провенанс зелёный, чтобы отказ был именем автора). ДО и ПОСЛЕ — красный
#       вход;
#   в6  self-mint (стаб С9 «локальный тег = выдан», боль Б6 — слово владельца
#       2026-09-08): N=035, toy-origin жив (main запушен), тег id/CONTRACT/035
#       создан ЛОКАЛЬНО и НЕ запушен — ровно то, что делает агент из своего
#       worktree (`next_id --issue`; refs общие). Честная дверь: отказ
#       «тег 035 не выдан авторитетом» (условие 3, прежде ветки). СЕГОДНЯ
#       peek-дверь даёт «вне зоны» БЕЗ имени провенанса — КРАСНОЕ ПО ИМЕНИ;
#   в7  origin недоступен (стаб С10 «fail-open по сети»): N=037, тег запушен на
#       toy-origin, затем origin перенаправлен на несуществующий путь — честная
#       дверь ОТКАЗЫВАЕТ fail-closed «авторитет недоступен» (обрыв сети не есть
#       санкция; стаб, пускающий при недоступности, умирает здесь). СЕГОДНЯ
#       «вне зоны» без имени — КРАСНОЕ ПО ИМЕНИ.
# Охрана «судья не создаёт тег id/*» (мера не меняет предмет): снимок id-тегов ДО
# вызова против ПОСЛЕ на каждом судимом репо (правило 8 — ожидание в памяти).
#
# СЕГОДНЯ (двери по тегу в коде нет) файл красен именованной причиной на первых же
# воротах с дельтой (в1/в2; в6/в7 — тем же классом: отказ без требуемого имени) —
# это и есть предъявляемое красное. ПОСЛЕ реализации все ворота дают rc 0.
#
# Коды возврата: 0 — ворота пройдены; 1 — именованный отказ (дверь отсутствует
#               либо нарушила договор на воротах).
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
BARRIER="$REPO/scripts/check_staged.sh"
# shellcheck disable=SC1091
. "$HERE/_repo.sh"
WORK="$(mktemp -d /tmp/red023-dver.XXXXXX)"   # А-78: свежий WORK вне дерева
trap 'rm -rf "$WORK"' EXIT

id_tags_of() { git -C "$1" for-each-ref --format='%(refname)' 'refs/tags/id/'; }
assert_no_new_id_tags() {  # <корень> <снимок-до>
  novye="$(comm -13 <(printf '%s\n' "$2" | sort) <(printf '%s\n' "$(id_tags_of "$1")" | sort))"
  if [ -n "${novye//$'\n'/}" ]; then
    printf 'ОТКАЗ: судья создал тег выдачи id/* — мера изменила предмет (%s): %s\n' "$1" "$novye" >&2
    exit 1
  fi
}

# ── в0: положительный контроль резерва (ветвь (i), стабильное зелёное) ────────
T0="$WORK/repo_rezerv"
make_repo_archzone "$T0"
out="$(bash "$REPO/scripts/next_id.sh" "$T0" CONTRACT 2>"$WORK/err0")" && rc=0 || rc=$?
if [ "$rc" -ne 0 ]; then
  printf 'ОТКАЗ: ветвь (i): issue-режим next_id не выдал номер в подставном корне (rc %s): %s\n' "$rc" "$(cat "$WORK/err0")" >&2
  exit 1
fi
case "$out" in
  [0-9][0-9][0-9]) ;;
  *) printf 'ОТКАЗ: ветвь (i): next_id напечатал не трёхзначный номер: «%s»\n' "$out" >&2; exit 1 ;;
esac
if ! git -C "$T0" show-ref --verify --quiet "refs/tags/id/CONTRACT/$out"; then
  printf 'ОТКАЗ: ветвь (i): номер %s напечатан, тег id/CONTRACT/%s не создан\n' "$out" "$out" >&2
  exit 1
fi

# ── в1: многоразовость двери (определяющая дельта, боль Б2) ────────────────────
# N=031: тег жив (аннотированный, форма выдачи) И НА origin (toy-origin bare, тег
# запушен), ветка wip/031/architect, первый draft-коммит УЖЕ в ветке (HEAD ветки
# несёт contracts/031-y.md, main — нет), staged — ПРАВКА драфта. Честная дверь:
# rc 0. Сегодня: peek=032 (источники 1/2/3 видят 031) → «вне зоны» rc 1 — красное
# предъявлено.
T1="$WORK/repo_mnogorazovo"
make_repo_archzone "$T1"
toy_origin "$T1" >/dev/null
g "$T1" tag -a id/CONTRACT/031 -m 'выдача механизмом (фикстура: резерв до спавна)'
push_id_tag "$T1" 031
co_wip "$T1" wip/031/architect
set_author "$T1" architect
mkdir -p "$T1/contracts"
printf '# контракт 031\n\n## Предмет\nпервый draft-коммит уже в ветке\n' > "$T1/contracts/031-y.md"
g "$T1" add -A
g "$T1" commit -q -m 'draft: первая посадка 031'
printf '\nправка драфта кругом критика\n' >> "$T1/contracts/031-y.md"
g "$T1" add -A
t1_id0="$(id_tags_of "$T1")"
out="$("$BARRIER" "$T1" 2>"$WORK/err1")" && rc=0 || rc=$?
assert_no_new_id_tags "$T1" "$t1_id0"
if [ "$rc" -ne 0 ]; then
  printf 'ОТКАЗ: дверь по тегу отсутствует — многоразовость: правка собственного драфта 031 (тег жив на origin, ветка своя, файла нет в main) отказана «вне зоны» (peek одноразов, боль Б2): %s\n' "$(cat "$WORK/err1")" >&2
  exit 1
fi

# ── в2: peek-номер без резерва (стаб С3 «номер-по-peek» — нынешний код) ────────
# N=032 — следующий свободный по max+1 (заняты 001-файл и ветка wip/031; staged
# путь в источники max не входит), тега id/CONTRACT/032 НЕТ. Честная дверь: отказ
# «номер 032 не выдан» (условие 2, origin не опрашивается — реестр первичен).
# Сегодня peek-дверь путь ПУСКАЕТ — красное предъявлено (дельта вычисление→реестр).
T2="$WORK/repo_peek_bez_tega"
make_repo_archzone "$T2"
co_wip "$T2" wip/031/architect
set_author "$T2" architect
stage "$T2" contracts/032-x.md 'черновик по peek без резерва'
t2_id0="$(id_tags_of "$T2")"
out="$("$BARRIER" "$T2" 2>"$WORK/err2")" && rc=0 || rc=$?
assert_no_new_id_tags "$T2" "$t2_id0"
if [ "$rc" -ne 1 ] || ! grep -qF 'не выдан' "$WORK/err2"; then
  printf 'ОТКАЗ: стаб С3 «номер-по-peek»: contracts/032-x.md без тега id/CONTRACT/032 ПУЩЕН (rc %s, ожидан rc 1 «номер 032 не выдан»): %s\n' "$rc" "$(cat "$WORK/err2")" >&2
  exit 1
fi

# ── в3: приземлённый номер (стаб С1 «тег-есть-пропуск» — канарея перехода) ─────
# N=019: файл УЖЕ в main, тег жив НА origin, ветка своя. Честная дверь: отказ
# (условие 5). Стаб С1 (нет условия «файла нет в main») пускает — умирает здесь.
T3="$WORK/repo_prizemljon"
make_repo_archzone "$T3"
mkdir -p "$T3/contracts"
printf '# контракт 019 (приземлён)\n' > "$T3/contracts/019-x.md"
g "$T3" add -A
g "$T3" commit -q -m 'посадка 019 в main'
g "$T3" tag -a id/CONTRACT/019 -m 'выдача механизмом (фикстура)'
toy_origin "$T3" >/dev/null
push_id_tag "$T3" 019
co_wip "$T3" wip/019/architect
set_author "$T3" architect
printf '\nправка приземлённого\n' >> "$T3/contracts/019-x.md"
g "$T3" add -A
t3_id0="$(id_tags_of "$T3")"
out="$("$BARRIER" "$T3" 2>"$WORK/err3")" && rc=0 || rc=$?
assert_no_new_id_tags "$T3" "$t3_id0"
if [ "$rc" -ne 1 ]; then
  printf 'ОТКАЗ: стаб С1 «тег-есть-пропуск»: правка приземлённого 019 (файл в main) ПУЩЕНА (rc %s, ожидан отказ): %s\n' "$rc" "$(cat "$WORK/err3")" >&2
  exit 1
fi

# ── в4: чужая ветка (стаб С2 «дверь-без-ветки» — канарея перехода) ────────────
# Путь 033 (тег жив НА origin), текущая ветка wip/045/architect — номер ветки ≠
# номер пути. Честная дверь: отказ (условие 4). Стаб С2 пускает — умирает здесь.
T4="$WORK/repo_chuzhaja_vetka"
make_repo_archzone "$T4"
g "$T4" tag -a id/CONTRACT/033 -m 'выдача механизмом (фикстура)'
toy_origin "$T4" >/dev/null
push_id_tag "$T4" 033
co_wip "$T4" wip/045/architect
set_author "$T4" architect
stage "$T4" contracts/033-x.md 'draft с чужой ветки'
t4_id0="$(id_tags_of "$T4")"
out="$("$BARRIER" "$T4" 2>"$WORK/err4")" && rc=0 || rc=$?
assert_no_new_id_tags "$T4" "$t4_id0"
if [ "$rc" -ne 1 ]; then
  printf 'ОТКАЗ: стаб С2 «дверь-без-ветки»: contracts/033-x.md на ветке wip/045/architect ПУЩЕН (rc 0, ожидан отказ): %s\n' "$out" >&2
  exit 1
fi

# ── в5: не-architect при живом теге (канарейка: дверь не расширяет прав) ───────
# implementer на СВОЕЙ wip/031/implementer, тег 031 жив НА origin (провенанс
# зелёный — отказ обязан быть именем автора/зоны, не сетью): дверь только для
# architect → зонный суд → «вне зоны». ДО и ПОСЛЕ — красный вход.
T5="$WORK/repo_ne_architect"
make_repo "$T5"
g "$T5" tag -a id/CONTRACT/031 -m 'выдача механизмом (фикстура)'
toy_origin "$T5" >/dev/null
push_id_tag "$T5" 031
co_wip "$T5" wip/031/implementer
set_author "$T5" implementer
stage "$T5" contracts/031-x.md 'draft под чужим автором'
t5_id0="$(id_tags_of "$T5")"
out="$("$BARRIER" "$T5" 2>"$WORK/err5")" && rc=0 || rc=$?
assert_no_new_id_tags "$T5" "$t5_id0"
if [ "$rc" -ne 1 ]; then
  printf 'ОТКАЗ: дверь расширила права: contracts/031-x.md под implementer ПУЩЕН (rc 0, ожидан отказ «вне зоны»): %s\n' "$out" >&2
  exit 1
fi

# ── в6: self-mint (стаб С9 «локальный тег = выдан», боль Б6) ───────────────────
# N=035: toy-origin жив (main запушен), тег id/CONTRACT/035 создан ЛОКАЛЬНО и НЕ
# запушен — модель self-mint агента (next_id --issue из worktree; refs общие).
# Ветка своя, файла нет в main, грамматика верна — ЕДИНСТВЕННОЕ нарушенное условие
# 3 (провенанс). Честная дверь: отказ «тег 035 не выдан авторитетом» ДО разбора
# ветки. Стаб С9 (локальное существование = выдача) пускает — умирает здесь.
# Сегодня: peek=036 → «вне зоны» БЕЗ имени провенанса — красное по имени.
T6="$WORK/repo_self_mint"
make_repo_archzone "$T6"
toy_origin "$T6" >/dev/null
g "$T6" tag -a id/CONTRACT/035 -m 'выдача механизмом (фикстура: self-mint, НЕ запушен)'
co_wip "$T6" wip/035/architect
set_author "$T6" architect
stage "$T6" contracts/035-x.md 'draft по self-mint тегу'
t6_id0="$(id_tags_of "$T6")"
out="$("$BARRIER" "$T6" 2>"$WORK/err6")" && rc=0 || rc=$?
assert_no_new_id_tags "$T6" "$t6_id0"
if [ "$rc" -ne 1 ] || ! grep -qF 'не выдан авторитетом' "$WORK/err6"; then
  printf 'ОТКАЗ: стаб С9 «self-mint»: локальный тег id/CONTRACT/035 вне origin ПУЩЕН (rc %s, ожидан rc 1 «тег 035 не выдан авторитетом»): %s\n' "$rc" "$(cat "$WORK/err6")" >&2
  exit 1
fi

# ── в7: origin недоступен (стаб С10 «fail-open по сети») ───────────────────────
# N=037: тег запушен на toy-origin, затем origin перенаправлен на несуществующий
# путь (сетевой отказ моделируется файлом — детерминированно, DNS не касается).
# Честная дверь: отказ «авторитет недоступен» (fail-closed — обрыв сети не есть
# санкция; имя ОТДЕЛЬНОЕ от «не выдан авторитетом»: различаются стабы, путающие
# недоступность с отсутствием тега). Стаб С10 (недоступность = пропуск) умирает
# здесь. Сегодня: peek=038 → «вне зоны» без имени — красное по имени.
T7="$WORK/repo_origin_nedostupen"
make_repo_archzone "$T7"
g "$T7" tag -a id/CONTRACT/037 -m 'выдача механизмом (фикстура)'
toy_origin "$T7" >/dev/null
push_id_tag "$T7" 037
g "$T7" remote set-url origin "$WORK/net-missing.git"
co_wip "$T7" wip/037/architect
set_author "$T7" architect
stage "$T7" contracts/037-x.md 'draft при недоступном авторитете'
t7_id0="$(id_tags_of "$T7")"
out="$("$BARRIER" "$T7" 2>"$WORK/err7")" && rc=0 || rc=$?
assert_no_new_id_tags "$T7" "$t7_id0"
if [ "$rc" -ne 1 ] || ! grep -qF 'авторитет недоступен' "$WORK/err7"; then
  printf 'ОТКАЗ: стаб С10 «fail-open по сети»: staged 037 при недоступном origin ПУЩЕН/не назван (rc %s, ожидан rc 1 «авторитет недоступен»): %s\n' "$rc" "$(cat "$WORK/err7")" >&2
  exit 1
fi

exit 0
