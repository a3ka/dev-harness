# ПРИЧИНА: вне зоны
#
# Контракт 019, Н-72 (расширение владельца ~14:00): ПЕРВЫЙ коммит draft-контракта
# следующего свободного номера (contracts/<next>-*.md, next — следующий свободный
# номер класса CONTRACT по next_id БЕЗ резерва тега) пускается под автором
# architect ДО заморозки: зоны нового контракта живут в его собственном файле и
# неактивны до заморозки (самоссылка), поэтому сегодня страж отбивает «вне зоны»
# даже архитектору — авторство пачки (измерено на 017: контракт-файл сажал
# владелец-канал 0e6b5f7, авторство «Alex K» вместо architect).
#
# Входы (Н-39, по коду):
#   * зелёный контроль (сегодня КРАСЕН — боль Н-72): автор architect (зонирован в
#     этом репо зоной plans/ — иначе прошёл бы «не судится» ДО суда путей, плацебо)
#     стадит contracts/002-draft.md, где 002 — следующий свободный номер CONTRACT
#     ЭТОГО репо (заморожен 001, тегов выдачи нет, файлов с номером 2 нет) →
#     после 019 rc 0;
#   * красное-охрана: тот же класс пути у ЧУЖОГО автора (implementer) → «вне зоны»
#     ДО и ПОСЛЕ 019: ветка draft-пуска открывает путь ТОЛЬКО архитектору, чужой
#     автор судится зонами как прежде. Охрана требует, чтобы 019 этот вход НЕ
#     позеленел.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

# ── зелёный контроль: architect стадит draft следующего свободного номера ──────
GREEN="$WORK/repo_draft_architekt"
make_repo_archzone "$GREEN"
set_author "$GREEN" architect
stage "$GREEN" contracts/002-draft.md 'черновик контракта 002 — авторство пачки architect'
"$BARRIER" "$GREEN" || true                  # ожидание: rc 0 (draft next-id пущен под architect)

# ── охрана: судья не резервирует номер тегом выдачи (мера не меняет предмет) ────
# Пуск draft-пути обязан читать следующий свободный номер БЕЗ создания тега
# id/CONTRACT/*: резервация — побочный эффект выдачи next_id, а не суда. Судья,
# создающий тег на каждом прогоне, занимал бы номера и менял предмет, который
# проверяет. Сегодня (peek нет вовсе) тегов тоже нет — охрана зелёная и до, и после.
if git -C "$GREEN" for-each-ref --format='%(refname)' 'refs/tags/id/' | grep -q .; then
  printf 'ОТКАЗ: судья зарезервировал номер тегом id/* — мера изменила предмет\n' >&2
  exit 1
fi

# ── красное-охрана: тот же класс пути у чужого автора — зонный отказ ────────────
RED="$WORK/repo_draft_chuzhoj_avtor"
make_repo_archzone "$RED"
set_author "$RED" implementer
stage "$RED" contracts/002-chuzhoj.md 'draft-путь не архитектора — судится зонами'
"$BARRIER" "$RED" || true                    # ожидание: rc 1 «вне зоны» (до и после 019)
