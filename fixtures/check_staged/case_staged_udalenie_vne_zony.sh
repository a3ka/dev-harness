# ПРИЧИНА: вне зоны: offzone.txt
#
# Пост-заморозочное усиление 018 по находке F-2 адверсария (verdicts/adversary/contracts-018.md
# «## Круг 2», вердикт eaafada; код check_staged.sh НЕ правится — честный 84fae04 на этом входе
# прав): слабое чтение staged с добавленным `--diff-filter=AM` исключает D-записи из ответа
# `git diff --cached --name-only -z`. staged-УДАЛЕНИЕ пути вне зоны тогда даёт пустой stdout,
# неотличимый от пустого staged → «нечего судить: staged пуст», rc 0 — судимый путь есть
# (D-запись в индексе), а суда нет. Предмет судит staged-пути БЕЗ исключения типа изменения;
# замер адверсария: такая слабость проходила scoped 11/11 — D-вход не предъявлен ни одной
# прежней фикстурой.
#
# Механика входа — как у адверсария: подставной репо (make_repo: автор implementer, зонирован
# scripts/ подставного контракта), БЕЗ живой wip-ветки — страж среза 1 молчит, вход изолирован
# под ветвь зон. Файл offzone.txt вне зоны закоммичен, затем удалён, удаление в индексе:
# git diff --cached несёт D offzone.txt.
#
# Зелёный контроль: staged-УДАЛЕНИЕ пути В зоне (scripts/a.sh из основания) → rc 0
# «ok: staged в зоне автора implementer» — D-записи читаются и судятся, вход живой (Н-39:
# заглушка AM слепа ровно к D-записям — её дефект наблюдаем на D-входе, на A/M она честна).
#
# Красное: staged-УДАЛЕНИЕ offzone.txt → честный барьер rc 1 «ОТКАЗ: вне зоны: offzone.txt»
# (засчитывает повторный прогон проверяющего, не строка фикстуры о себе); слабое чтение с
# --diff-filter=AM на том же входе — rc 0 «нечего судить: staged пуст», красное не предъявлено,
# раннер краснит. Вызовы серийные, через || true (А-32).
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

# ── зелёный репо: staged-УДАЛЕНИЕ пути В зоне — D-запись судится зелёным ────────
GREEN="$WORK/repo_green"
make_repo "$GREEN"
g "$GREEN" rm -q -- scripts/a.sh   # D-запись в индексе; зона покрывает — rc 0

# ── красный репо: staged-УДАЛЕНИЕ пути ВНЕ зоны ─────────────────────────────────
RED="$WORK/repo_red"
make_repo "$RED"
stage "$RED" offzone.txt 'файл вне зоны — попадает в HEAD, чтобы удаление стало D-записью'
g "$RED" commit -q -m 'внесение offzone.txt в HEAD — основание для staged-удаления'
g "$RED" rm -q -- offzone.txt      # D-запись в индексе; вне зоны — rc 1

# ── вызовы барьера: серийные, через || true (А-32) ──────────────────────────────
"$BARRIER" "$GREEN" || true   # ожидание: rc 0 «ok: staged в зоне автора implementer»
"$BARRIER" "$RED" || true     # ожидание: rc 1 «ОТКАЗ: вне зоны: offzone.txt»;
                              # слабое чтение (--diff-filter=AM): rc 0 «нечего судить: staged пуст»
