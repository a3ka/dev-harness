# ПРИЧИНА: без причины
#
# Контракт 019, Н-72: вторая ветвь грамматики строки РАЗРЕШИЛ-ВЛАДЕЛЕЦ, наследуемая
# делегированием (единый источник — razreshil() в check_charter.sh): строка назвала
# путь, но НЕ назвала причину — разрешение без записанной причины неотличимо от
# опечатки и разрешением считаться не может.
#
# Вход (Н-39): коммит в истории меняет ROADMAP.md, его тело несёт
# «РАЗРЕШИЛ-ВЛАДЕЛЕЦ: ROADMAP.md» без причины; staged уставного пути у зонированного
# автора → после 019 делегирование возвращает отказ «разрешение … без причины».
# Сегодня причина зонная («вне зоны») — ветвь грамматики не предъявляется.
#
# Зелёный контроль: та же форма с полной строкой (путь + причина) → rc 0 — вход
# различает «строка без причины» от «строка в грамматике», а не любую строку
# РАЗРЕШИЛ подряд.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

# ── зелёный контроль: полная строка (путь + причина) в истории ──────────────────
GREEN="$WORK/repo_razreshenie_s_prichinoj"
make_repo_ustav "$GREEN"
ustav_change "$GREEN" ROADMAP.md 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: ROADMAP.md вписание майлстоуна по прямому слову владельца'
stage "$GREEN" ROADMAP.md 'рабочая правка устава зонированным автором'
"$BARRIER" "$GREEN" || true                  # ожидание: rc 0 (строка в грамматике — правка разрешена)

# ── красное: строка РАЗРЕШИЛ назвала путь, но НЕ причину ────────────────────────
RED="$WORK/repo_razreshenie_bez_prichiny"
make_repo_ustav "$RED"
ustav_change "$RED" ROADMAP.md 'РАЗРЕШИЛ-ВЛАДЕЛЕЦ: ROADMAP.md'
stage "$RED" ROADMAP.md 'staged уставного пути при строке без причины в истории'
"$BARRIER" "$RED" || true                    # ожидание: rc 1 «без причины»
