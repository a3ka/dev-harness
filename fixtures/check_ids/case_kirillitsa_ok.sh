# ПРИЧИНА: назначен рукой, а не механизмом
#
# Дефект «разбор имени отбрасывал русское имя артефакта» (находка 5 второго круга).
# Прежняя `next_id.sh` принимала `^[0-9]{3}-` (любой символ после дефиса), а
# `check_ids.sh` — только `^[0-9]+-[a-zA-Z]` (буква ASCII). `007-план.md` —
# нормальное русское имя в русском репозитории — one-way проходил выдачу как номер 7
# (max+1=008), но НЕ проходил сверку как нумерованный: сверка молчала о ручном
# номере без тега. Это дефект области в русском репозитории, не лексическое
# предпочтение.
#
# Теперь `parse_artifact_basename` (единая реализация в `next_id.sh`, импортируется
# и в `check_ids.sh`) принимает любую не-цифру после дефиса: `007-план.md` → номер 7,
# валидный, кириллица в области. ОБА скрипта используют одну функцию и соглашаются.
#
# Положительный контроль: `007-план.md` С тегом — зелёный (выдан механизмом,
# согласовано с регистром). Красное: `007-план.md` БЕЗ тега — сверка видит номер 7
# и говорит «номер назначен рукой», как для любого ненумерованного файла. Прежняя
# `check_ids.sh` в обоих случаях молчала, потому что отбрасывала кириллицу как
# «не буква» — и ручной номер оставался незамеченным.
set -euo pipefail

cd "$WORK"
# `check_ids.sh` импортирует разбор имени из `next_id.sh` через `NEXT_ID_LIB=1 source`.
# Копируем `next_id.sh` рядом: обёртка `verify_antiplacebo` копирует в `$WORK/scripts/`
# только сам вызванный барьер.
mkdir -p "$WORK/scripts"
cp "$REPO/scripts/next_id.sh" "$WORK/scripts/"
git init -q .
git config user.email "fixture@test"
git config user.name "fixture"
git config commit.gpgsign false
git config core.hooksPath /dev/null
mkdir -p plans
# Русское имя артефакта: `007-план.md`. Репозиторий по-русски, кириллица в области.
printf '# план на русском\n' > plans/007-план.md
git add plans/
git commit -q -m "план с русским именем"
git tag id/PLAN/007 -m "выдача механизмом"

# Положительный контроль: `007-план.md` с тегом — зелёный.
BARRIER_ROOT="$WORK" "$BARRIER"

# Обман: убираем тег, оставляем артефакт. Сверка должна увидеть «номер 7 назначен
# рукой» — как для любого ненумерованного файла. Прежняя `check_ids.sh` молчала,
# потому что отбрасывала кириллицу как «не буква»; теперь парсер общий, и барьер
# видит тот же номер 7, что и `next_id.sh`.
git tag -d id/PLAN/007

BARRIER_ROOT="$WORK" "$BARRIER"