# ПРИЧИНА: неправильный формат
#
# Дефект «формат номера»: трёхзначный формат обязателен в ОБЕ стороны (находка 4 второго
# круга). Прежняя `check_ids.sh` принимала `^[0-9]+-[a-zA-Z]`, и `0007-x.md` при существующем
# `id/PLAN/007` становился «тем же» 007. Теперь `parse_artifact_basename` возвращает 2
# для неправильного формата (1 или 4+ цифр), и барьер сообщает «номер N в <путь> имеет
# неправильный формат».
#
# Положительный контроль: один план 007 с тегом — зелёный. Красное: добавлен файл
# `plans/7-x.md` (одна цифра, тот же номер 7) — барьер видит неправильный формат и
# называет путь.
set -euo pipefail

cd "$WORK"
# Корень передаётся АРГУМЕНТОМ: барьер бежит из своего каталога и находит рядом свою
# библиотеку. Прежняя редакция подменяла каталог барьера и копировала соседей руками —
# копия отставала от предмета при каждом новом соседе.
git init -q .
git config user.email "fixture@test"
git config user.name "fixture"
git config commit.gpgsign false
git config core.hooksPath /dev/null
mkdir -p plans
printf '# план с правильным номером\n' > plans/007-y.md
git add plans/
git commit -q -m "first plan with valid 007"
git tag id/PLAN/007 -m "выдача механизмом"

# Положительный контроль: один план, тег есть, формат правильный.
"$BARRIER" "$WORK"

# Вносим обман: файл с тем же номером 7, но БЕЗ ведущего нуля — `plans/7-x.md`.
# Это «номер 7 в неправильном формате» (1 цифра): тот же идентификатор в другой записи.
# Прежняя сверка нормализовала бы к «7» и ловила как дубль; теперь — отдельное красное
# о формате, и владелец видит, ЧТО чинить.
printf '# план с коротким номером\n' > plans/7-x.md
git add plans/
git commit -q -m "ручной 7-x.md без тега выдачи"

"$BARRIER" "$WORK"