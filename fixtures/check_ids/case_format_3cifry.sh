# ПРИЧИНА: одинаковый номер
#
# Дефект «формат номера»: прежняя `next_id.sh` после `006` печатала `7` без ведущего
# нуля, и `plans/7-x.md` (набранный рукой, без тега) становился «тем же» идентификатором,
# что и `plans/007-y.md` (выданный механизмом). После правки формат — ровно три цифры, и
# `plans/7-x.md` уже не матчится как `007-...`, но ЭТА фикстура держит ветку: файл с
# коротким именем существует, и барьер ОБЯЗАН отказать, назвав ОБА пути, — иначе правило
# «ручной номер без тега» не покрывает случай неправильного написания.
#
# Положительный контроль: один план 007 с тегом — зелёный. Красное: добавлен файл
# `plans/7-x.md` (тот же номер 7 без ведущих нулей) БЕЗ тега — барьер видит дубль.
set -euo pipefail

cd "$WORK"
git init -q .
git config user.email "fixture@test"
git config user.name "fixture"
git config commit.gpgsign false
git config core.hooksPath /dev/null
mkdir -p plans
printf '# план с правильным номером\n' > plans/007-y.md
git add plans/
git commit -q -m "first plan with valid 007"
git tag id/PLAN/007 -m "выдача механизмом"

# Положительный контроль: один план, тег есть, формат правильный.
BARRIER_ROOT="$WORK" "$BARRIER"

# Вносим обман: файл с тем же номером 7, но БЕЗ ведущего нуля — `plans/7-x.md`.
# Прежняя выдача печатала бы «7» и `git mv` подкладывал файл, который `check_ids`
# нормализовал к «7» и ловил как «одинаковый номер». Теперь выдача даёт три цифры, но
# файл с однозначным номером, набранный рукой, всё равно обязан быть назван.
printf '# план с коротким номером\n' > plans/7-x.md
git add plans/
git commit -q -m "ручной 7-x.md без тега выдачи"

BARRIER_ROOT="$WORK" "$BARRIER"