# Класс `CONTRACT` заведён планом 007: контракт майлстоуна — уставной документ, и номер с двумя
# смыслами в истории нечем развести (правило 5 нормы). Область сверки проверяется, а не
# предполагается: не включи `CONTRACT` в перечень обходимых классов — барьер молча пропустит
# дубликат. Ровно этот класс дефекта в репозитории дважды находили добавлением области.
#
# Положительный контроль: один контракт 001 с тегом выдачи — зелёный. Красное: второй файл под
# тем же номером, закоммиченный рукой, без тега.
set -euo pipefail

cd "$WORK"
# Корень передаётся АРГУМЕНТОМ: барьер бежит из своего каталога и находит рядом свои библиотеки
# (`lib_roles.sh`, `lib_registry.sh`). Подмена каталога барьера копировала бы соседей руками, и
# копия отставала бы от предмета при каждом новом соседе.
git init -q -b main .
git config user.email "fixture@test"
git config user.name "fixture"
git config commit.gpgsign false
git config core.hooksPath /dev/null
mkdir -p contracts
printf '# первый контракт\n' > contracts/001-fikstura.md
git add contracts/
git commit -q -m "первый контракт"
# Выдан механизмом — резервация тегом есть.
git tag id/CONTRACT/001 -m "выдача механизмом"

"$BARRIER" "$WORK"

# Обман: второй контракт под тем же номером, закоммичен рукой — без тега. Номер занят, значит
# этот файл механизмом выдан не был и обязан быть назван.
printf '# второй контракт\n' > contracts/001-drugoj.md
git add contracts/
git commit -q -m "второй контракт под тем же номером, без тега"

