# ПРИЧИНА: одинаковый номер
#
# Дефект «два файла одного класса с одним номером»: история выдачи — теги, и артефакт
# без тега — «номер назначен рукой». Фикстура строит дерево, где ОДИН файл получил тег
# (выдан механизмом), а ВТОРОЙ с тем же номером закоммичен рукой — без тега. Это и есть
# та «гонка выдачи», что прежняя редакция порождала сама: два файла под одним номером.
#
# Положительный контроль: один план 001 с тегом — зелёный. Красное: добавлен второй план
# под тем же номером без тега — барьер называет ОБА пути, как требует план 005 §2 дословно.
set -euo pipefail

cd "$WORK"
# Корень передаётся АРГУМЕНТОМ: барьер бежит из своего каталога и находит рядом свою
# библиотеку. Прежняя редакция подменяла каталог барьера и копировала соседей руками —
# копия отставала от предмета при каждом новом соседе.
git init -q .
git config user.email "fixture@test"
git config user.name "fixture"
git config commit.gpgsign false
git config core.hooksPath /dev/null
mkdir -p plans
printf '# первый план\n' > plans/001-foo.md
git add plans/
git commit -q -m "first plan"
# Первый план выдан механизмом — резервация тегом есть.
git tag id/PLAN/001 -m "выдача механизмом"

# Положительный контроль: один план, тег есть, дубликатов нет.
"$BARRIER" "$WORK"

# Вносим обман: второй план под тем же номером 001, закоммичен рукой — без тега.
# Это и есть та гонка, которую теперь ловит реестр выдачи: номер занят тегом, новый файл
# не мог быть выдан механизмом и обязан быть назван.
printf '# второй план\n' > plans/001-bar.md
git add plans/
git commit -q -m "second plan with duplicate number, no tag"

"$BARRIER" "$WORK"