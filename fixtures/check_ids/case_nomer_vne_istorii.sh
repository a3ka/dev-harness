# ПРИЧИНА: назначен рукой, а не механизмом
# Дефект «номер, которому нет тега выдачи»: история выдачи — это `refs/tags/id/<КЛАСС>/*`,
# и артефакт, закоммиченный БЕЗ такого тега, считается «назначенным рукой». Прежняя
# редакция читала `git log --diff-filter=A` и считала любой закоммиченный номер «в истории
# выдачи» — поэтому на честном дереве обещанная красная ветвь была недостижима (вердикт
# `verdicts/adversary/mech-2-ids.md`, находка 4). Теперь ручной номер, добавленный и
# закоммиченный, сам себя НЕ легализует.
#
# Положительный контроль: план 001 с тегом — зелёный. Красное: добавлен план 999 с тегом
# `id/PLAN/001` — а самого `id/PLAN/999` нет: барьер называет файл как «номер назначен
# рукой».
set -euo pipefail

cd "$WORK"
git init -q .
git config user.email "fixture@test"
git config user.name "fixture"
git config commit.gpgsign false
git config core.hooksPath /dev/null
mkdir -p plans
printf '# первый план\n' > plans/001-foo.md
git add plans/
git commit -q -m "first plan"
# Только этот тег — номер 001 выдан механизмом.
git tag id/PLAN/001 -m "выдача механизмом"

# Положительный контроль: один план, тег есть, номер согласован с регистром.
BARRIER_ROOT="$WORK" "$BARRIER"

# Вносим обман: план 999 закоммичен, но `id/PLAN/999` НЕТ — номер назначен рукой, а не
# механизмом. Прежняя редакция не ловила этот случай, потому что коммит файла добавлял
# путь в «историю выдачи» и условие «n > max+1» не срабатывало. С тегами такого самообмана
# нет: тег — это и есть акт выдачи.
printf '# ручной номер\n' > plans/999-manual.md
git add plans/
git commit -q -m "ручной номер 999 без тега выдачи"

BARRIER_ROOT="$WORK" "$BARRIER"