# ПРИЧИНА: реестр устава
#
# На усечённой истории барьер стал бы ПУСТО-ЗЕЛЁНЫМ: диапазон `ustav/1..HEAD` в shallow-клоне
# короче настоящего, и правки устава, лежащие глубже обрезки, не видны вовсе. Молчаливо зелёный
# гейт хуже красного: красному ищут причину, а зелёному верят. Поэтому код 1 с названной причиной
# и лечением, а не 2 — лечится это одной строкой `fetch-depth: 0` в проводке.
#
# Зелёный контроль: полное дерево → 0. Красное: shallow-клон того же дерева. Тег `ustav/1` стоит на
# последнем коммите основания, поэтому клон его подхватывает — иначе барьер честно ответил бы «устав
# не введён» (код 2), и фикстура проверяла бы не тот предмет.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
S="$WORK/source"
make_repo "$S"
"$BARRIER" "$S"

GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null \
  git clone -q --depth 1 --single-branch "file://$S" "$WORK/shallow"
"$BARRIER" "$WORK/shallow"
