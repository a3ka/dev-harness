# ПРИЧИНА: вне грамматики
#
# Адверсарий предъявил: строка `"ROADMAP.md"причина` — путь в кавычках, причина приклеена БЕЗ
# пробела-разделителя — принималась как законное разрешение. Грамматика объявлена как
# `РАЗРЕШИЛ-ВЛАДЕЛЕЦ: <путь> <непустая причина>`, и склеенная форма ею не покрыта; принять её
# значило расширить язык разрешения молча (правило 7 нормы).
#
# Зелёный контроль: разрешение с разделителем → 0. Красное: без разделителя → код 1.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
printf 'шаг 9 начат\n' >> "$R/ROADMAP.md"
commit_body "$R" <<'MSG'
правка по разрешению с разделителем

РАЗРЕШИЛ-ВЛАДЕЛЕЦ: "ROADMAP.md" проба процедуры
MSG
"$BARRIER" "$R"

printf 'шаг 9 продолжен\n' >> "$R/ROADMAP.md"
commit_body "$R" <<'MSG'
правка по склеенному разрешению

РАЗРЕШИЛ-ВЛАДЕЛЕЦ: "ROADMAP.md"склеенная причина без пробела
MSG
"$BARRIER" "$R"
