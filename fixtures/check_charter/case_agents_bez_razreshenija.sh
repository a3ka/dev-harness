# ПРИЧИНА: изменён без разрешения владельца
#
# Требование владельца дословно: уставные документы после утверждения не меняются без его
# разрешения. Норма — первый из них: механизм можно переписать за час, а норма, ослабленная тихо,
# наследуется всем, что построят по ней потом.
#
# Зелёный контроль двойной, и второе важнее первого: устав не тронут → 0, и ДОБАВЛЕНИЕ нового
# плана — тоже 0. `--diff-filter=MD` намеренно пропускает добавление: черновики пишет архитектор, и
# гейт, требующий слова владельца на каждый новый файл, остановил бы работу целиком.
#
# Красное: одна строка дописана в AGENTS.md коммитом без строки разрешения.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

printf 'черновик нового плана\n' > "$R/plans/002-novyj.md"
commit_all "$R" 'добавлен черновик плана 002 — добавление свободно'
"$BARRIER" "$R"

printf 'правило 11: добавлено тихо\n' >> "$R/AGENTS.md"
commit_all "$R" 'уточнение нормы по ходу'
"$BARRIER" "$R"
