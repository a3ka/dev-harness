# ПРИЧИНА: изменён без разрешения владельца
#
# Контракт 019 v2 (блокер 3 критика, :130): merge-дыра истории. check_charter читает
# историю `rev-list --no-merges` (строка ~169): merge-коммит, вносящий уставную дельту
# ТОЛЬКО в результат слияния (родители устав не трогают), невидим судье — обход CI
# check:charter и делегирования check_staged. После 019 (И-7) уставная дельта
# merge-коммита судится по diff с ПЕРВЫМ родителем.
#
# Входы (порядок обязателен: положительный контроль ДО первого красного кандидата,
# А-73; серийный вызов — `|| true`, А-32):
#   * зелёный контроль = положительная merge-ветвь (блокер круга 2 критика, :125):
#     история основания чиста (make_repo), затем merge-коммит вносит уставную дельту
#     ROADMAP.md только в merge-результат (родители файл не трогают) и несёт корректную
#     строку РАЗРЕШИЛ в теле merge-коммита → rc 0. Сегодня rc 0 потому, что merge не
#     судится вовсе (та самая дыра); после 019 — потому, что дельта судима и разрешена
#     той же грамматикой razreshil(), что и на не-merge коммитах. Это ПЕРВЫЙ вызов
#     фикстуры и единственный зелёный: обход «отвергать каждый merge с уставной
#     дельтой ДО проверки строки» убивает его → «нет положительного контроля»;
#   * красное (обход критика дословно): второй merge меняет файл ВНЕ устава; merge
#     --no-commit; ROADMAP.md правится в merge-результате; merge-коммит без строки
#     РАЗРЕШИЛ. Ни один родитель ROADMAP.md не трогает. Сегодня rc 0 — дыра; прогон
#     даёт «барьер остался зелёным на обманном дереве» — красное ДО правки кода
#     (правило 3). После 019 rc 1 «изменён без разрешения владельца».
set -euo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

R="$WORK/repo"
make_repo "$R"

# ── зелёный контроль: разрешённая уставная дельта merge-коммита (круг 2, :125) ───
g "$R" checkout -q -b razreshennyj
mkdir -p "$R/scripts"
printf 'боковая правка вне устава (разрешённое слияние)\n' > "$R/scripts/razreshenie.sh"
commit_all "$R" 'боковая ветка: файл вне устава'
g "$R" checkout -q main
g "$R" merge --no-commit --no-ff razreshennyj >/dev/null 2>&1 || true
printf 'строка ROADMAP из разрешённого merge-коммита\n' >> "$R/ROADMAP.md"
g "$R" add -- ROADMAP.md
commit_body "$R" <<'MSG'
слияние боковой ветки с уставной дельтой

РАЗРЕШИЛ-ВЛАДЕЛЕЦ: ROADMAP.md роадмап расширен по прямому слову владельца
MSG
"$BARRIER" "$R" || true   # ожидание: rc 0 — сегодня merge не судится вовсе; после 019 судима и разрешена

# ── обход критика: уставная дельта живёт ТОЛЬКО в merge-результате, БЕЗ строки ────
g "$R" checkout -q -b side
printf 'боковая правка вне устава\n' > "$R/scripts/side.sh"
commit_all "$R" 'боковая ветка: файл вне устава'
g "$R" checkout -q main
g "$R" merge --no-commit --no-ff side >/dev/null 2>&1 || true
printf 'строка ROADMAP из merge-коммита\n' >> "$R/ROADMAP.md"
g "$R" add -- ROADMAP.md
g "$R" commit -q -m 'слияние боковой ветки'
"$BARRIER" "$R"
