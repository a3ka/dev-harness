#
# Контракт 019 v2 (блокер 3 критика, :130): merge-дыра истории. check_charter читает
# историю `rev-list --no-merges` (строка ~169): merge-коммит, вносящий уставную дельту
# ТОЛЬКО в результат слияния (родители устав не трогают), невидим судье — обход CI
# check:charter и делегирования check_staged. После 019 (И-7) уставная дельта
# merge-коммита судится по diff с ПЕРВЫМ родителем.
#
# Входы:
#   * зелёный контроль: чистая история устава → rc 0;
#   * красное (обход критика дословно): боковая ветка меняет файл ВНЕ устава; merge
#     --no-commit; ROADMAP.md правится в merge-результате; merge-коммит без строки
#     РАЗРЕШИЛ. Ни один родитель ROADMAP.md не трогает. Сегодня rc 0 — дыра; прогон
#     даёт «барьер остался зелёным на обманном дереве» — красное ДО правки кода
#     (правило 3). После 019 rc 1 «изменён без разрешения владельца».
set -euo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_repo.sh"

R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

# ── обход критика: уставная дельта живёт ТОЛЬКО в merge-результате ───────────────
g "$R" checkout -q -b side
mkdir -p "$R/scripts"
printf 'боковая правка вне устава\n' > "$R/scripts/side.sh"
commit_all "$R" 'боковая ветка: файл вне устава'
g "$R" checkout -q main
g "$R" merge --no-commit --no-ff side >/dev/null 2>&1 || true
printf 'строка ROADMAP из merge-коммита\n' >> "$R/ROADMAP.md"
g "$R" add -- ROADMAP.md
g "$R" commit -q -m 'слияние боковой ветки'
"$BARRIER" "$R"
