# Безымянное разрешение снимает защиту со ВСЕГО устава навсегда: тело коммита уже не переписать, а
# «я разрешаю» без имени файла годится для любого. Разрешение на один документ и разрешение на все
# — разные предметы, и в истории их нечем развести. Усиление того же класса, что у
# `ALLOW-ARTIFACT-DELETE` в `check_protected.sh`.
#
# Зелёный контроль: устав не тронут → 0. Красное: строка есть, путь не назван.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

printf 'правило 12: добавлено с безымянного разрешения\n' >> "$R/AGENTS.md"
commit_body "$R" <<'MSG'
правка нормы с безымянным разрешением

РАЗРЕШИЛ-ВЛАДЕЛЕЦ:
MSG
"$BARRIER" "$R"
