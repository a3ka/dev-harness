# ПРИЧИНА: изменён без разрешения владельца
#
# Разрешение обязано лежать в ТОМ ЖЕ коммите, который меняет файл. Урок круга 2 по
# `ALLOW-ARTIFACT-DELETE`: разрешение, выданное заранее или задним числом, есть индульгенция — оно
# годится повторно, и его можно положить в посторонний коммит, а потом изменить устав молча.
#
# Зелёный контроль: устав не тронут → 0. Красное: строка владельца лежит в СОСЕДНЕМ коммите, а
# изменяющий её не несёт.
set -euo pipefail
. "$(dirname "$0")/_repo.sh"
R="$WORK/repo"
make_repo "$R"
"$BARRIER" "$R"

printf 'посторонняя правка\n' > "$R/plans/003-postoronnij.md"
commit_body "$R" <<'MSG'
разрешение выдано заранее

РАЗРЕШИЛ-ВЛАДЕЛЕЦ: ROADMAP.md правь роадмап когда понадобится
MSG

printf 'шаг 6 начат\n' >> "$R/ROADMAP.md"
commit_all "$R" 'правка роадмапа по выданному заранее разрешению'
"$BARRIER" "$R"
