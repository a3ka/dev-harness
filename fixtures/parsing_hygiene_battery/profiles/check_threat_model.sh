# Профиль батареи для scripts/check_threat_model.sh (041) — DOGFOOD: НОВЫЙ
# гард, введённый ЭТИМ ЖЕ контрактом, проверен ТОЙ ЖЕ реиспользуемой батареей,
# которую его контракт вводит как норму для будущих гардов.
TM_REPO="$(cd "$HERE/../.." && pwd -P)"
TM_SUBJ="$TM_REPO/scripts/check_threat_model.sh"

_tm_write() {  # <файл> <тело-после-заголовка-или-пусто>
  local f="$1" body="$2"
  {
    printf '# toy kontrakt\n\n## Predmet\np\n\n'
    if [ -n "$body" ]; then
      printf '## Модель угроз\n\n%s\n' "$body"
    fi
  } > "$f"
}

battery_delimiter_collision() {
  # (а, Б1 verdicts/critic/contracts-041-v1.md) Буллет содержит байт `:`
  # ВНУТРИ данных: короткий префикс ДО первого ':' ("мало-совсем", НИЖЕ
  # порога формы сам по себе) + длинное продолжение ПОСЛЕ. Ожидание —
  # ЦЕЛЫЙ буллет проходит порог формы (rc 0, счётчик буллетов подтверждает
  # целостность). Дискриминирует усечение по первому ':' (оставило бы
  # только префикс "мало-совсем" — ниже порога — и барьер отказал бы
  # ошибочно).
  local w f out rc
  w="$(mktemp -d "${TMPDIR:-/tmp}/battery_tm_dc.XXXXXX")"; f="$w/c.md"
  _tm_write "$f" 'ЗАЩИЩАЕТ:
- мало-совсем: достаточно длинное продолжение которое нельзя терять при разборе

НЕ ЗАЩИЩАЕТ:
- враждебное окружение вызывающего процесса за пределами базового PATH-экспорта'
  out="$(bash "$TM_SUBJ" "$w" "c.md" 2>&1)"; rc=$?
  rm -rf "$w"
  if [ "$rc" -ne 0 ] || ! printf '%s' "$out" | grep -Fq 'ЗАЩИЩАЕТ 1 буллет(ов)'; then
    return 1
  fi

  # (б, verdicts/adversary/contracts-041-parsing-hygiene.md, коммит
  # ed9fc25 — АДВЕРСАРИЙ КРУГ 1) ДВА буллета в ОДНОМ списке, КАЖДЫЙ с
  # внутренним '-' в СОБСТВЕННОМ тексте (не в префиксе "- ", а внутри
  # данных буллета). Обманная реализация из находки хранит буллеты списка
  # ОДНОЙ join'еной строкой с разделителем '-' и восстанавливает count
  # через `IFS=- read -r -a split`: с ОДНИМ буллетом байт-коллизия не
  # проявляется (нечего join'ить между записями — ровно случай (а) выше),
  # с ДВУМЯ И БОЛЕЕ — дефис-разделитель join'а неотличим от дефисов
  # ВНУТРИ буллетов, и count завышается (живой репро находки: 2 честных
  # буллета → 4 у стаба). Наблюдаемое доказательство — ТОЧНЫЙ печатаемый
  # счёт буллетов в выводе гарда (не только rc самого гарда): честный
  # построчный массив (Направление 3 инвариант ii, контракт 041) не
  # подвержен join+split нигде — счёт остаётся РОВНО 2 независимо от
  # байтов внутри буллетов.
  w="$(mktemp -d "${TMPDIR:-/tmp}/battery_tm_dc2.XXXXXX")"; f="$w/c.md"
  _tm_write "$f" 'ЗАЩИЩАЕТ:
- буллет-один содержит дефис внутри собственного текста первого пункта
- буллет-два содержит другой дефис внутри собственного текста второго пункта

НЕ ЗАЩИЩАЕТ:
- смысловую адекватность содержимого буллетов решает критик а не механизм'
  out="$(bash "$TM_SUBJ" "$w" "c.md" 2>&1)"; rc=$?
  rm -rf "$w"
  [ "$rc" -eq 0 ] && printf '%s' "$out" | grep -Fq 'ЗАЩИЩАЕТ 2 буллет(ов), НЕ ЗАЩИЩАЕТ 1 буллет(ов)'
}

battery_regex_injection() {
  # Буллет содержит ERE-метасимволы буквально — сравнение меток/префикса
  # литеральное, содержимое буллета вообще не участвует в построении
  # паттерна → rc 0, метасимволы не интерпретированы.
  local w f out rc
  w="$(mktemp -d "${TMPDIR:-/tmp}/battery_tm_ri.XXXXXX")"; f="$w/c.md"
  _tm_write "$f" 'ЗАЩИЩАЕТ:
- символы . * + ? [ ] ( ) ^ $ | остаются буквами буллета а не regex-командами

НЕ ЗАЩИЩАЕТ:
- смысловую адекватность границы которую судит критик а не механический барьер'
  out="$(bash "$TM_SUBJ" "$w" "c.md" 2>&1)"; rc=$?
  rm -rf "$w"
  [ "$rc" -eq 0 ]
}

battery_silent_drop() {
  # Список ЗАЩИЩАЕТ: присутствует, но без единого буллета — ожидание:
  # ИМЕНОВАННЫЙ отказ, не тихий проход.
  local w f out rc
  w="$(mktemp -d "${TMPDIR:-/tmp}/battery_tm_sd.XXXXXX")"; f="$w/c.md"
  _tm_write "$f" 'ЗАЩИЩАЕТ:

НЕ ЗАЩИЩАЕТ:
- враждебное окружение вызывающего процесса за пределами базового PATH-экспорта'
  out="$(bash "$TM_SUBJ" "$w" "c.md" 2>&1)"; rc=$?
  rm -rf "$w"
  [ "$rc" -eq 1 ] && printf '%s' "$out" | grep -Fq 'модель угроз: список ЗАЩИЩАЕТ: пуст (нет буллета)'
}

