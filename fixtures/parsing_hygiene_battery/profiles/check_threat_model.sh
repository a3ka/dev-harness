# Профиль батареи для scripts/check_threat_model.sh (041) — DOGFOOD: НОВЫЙ
# гард, введённый ЭТИМ ЖЕ контрактом, проверен ТОЙ ЖЕ реиспользуемой батареей,
# которую его контракт вводит как норму для будущих гардов.
TM_REPO="$(cd "$HERE/../.." && pwd -P)"
TM_SUBJ="$TM_REPO/scripts/check_threat_model.sh"

_tm_write() {  # <файл> <тело-после-заголовка-или-пусто>
  local f="$1" body="$2"
  {
    printf '# toy kontrakt\n\n## Predmet\np\n\n'
    if [ -n "$body" ]; then
      printf '## Модель угроз\n\n%s\n' "$body"
    fi
  } > "$f"
}

battery_delimiter_collision() {
  # (а, Б1 verdicts/critic/contracts-041-v1.md) Буллет содержит байт `:`
  # ВНУТРИ данных: короткий префикс ДО первого ':' ("мало-совсем", НИЖЕ
  # порога формы сам по себе) + длинное продолжение ПОСЛЕ. Ожидание —
  # ЦЕЛЫЙ буллет проходит порог формы (rc 0, счётчик буллетов подтверждает
  # целостность). Дискриминирует усечение по первому ':' (оставило бы
  # только префикс "мало-совсем" — ниже порога — и барьер отказал бы
  # ошибочно).
  local w f out rc
  w="$(mktemp -d "${TMPDIR:-/tmp}/battery_tm_dc.XXXXXX")"; f="$w/c.md"
  _tm_write "$f" 'ЗАЩИЩАЕТ:
- мало-совсем: достаточно длинное продолжение которое нельзя терять при разборе

НЕ ЗАЩИЩАЕТ:
- враждебное окружение вызывающего процесса за пределами базового PATH-экспорта'
  out="$(bash "$TM_SUBJ" "$w" "c.md" 2>&1)"; rc=$?
  rm -rf "$w"
  if [ "$rc" -ne 0 ] || ! printf '%s' "$out" | grep -Fq 'ЗАЩИЩАЕТ 1 буллет(ов)'; then
    return 1
  fi

  # (б, генерализация verdicts/adversary/contracts-041-parsing-hygiene.md
  # круга 1 (ed9fc25) + verdicts/adversary/contracts-041-parsing-hygiene-v2.md
  # круга 2 (f89c5e2, АДВЕРСАРИЙ КРУГ 2). Круг 1 закрыл РОВНО N=2 (два
  # буллета, счёт вписан в grep-строку руками — "2"); круг 2 предъявил
  # обманную реализацию, которая ЧЕСТНО хранит буллеты СПИСКОМ (не
  # join+split), но ОБРЕЗАЕТ итоговый count через `n=min(n, 2)` — на N=2
  # неотличима от честной (граница стаба СОВПАДАЛА со значением, зашитым в
  # тест круга 1), а на N=3+ отчёт count ЛОЖЕН («2» вместо реального
  # числа), причём старая батарея такой вход не предъявляла вовсе. Просто
  # поднять "2" до другого хардкода (скажем "7", заранее известного
  # адверсарию из файла) — НЕ структурный фикс: тот же класс уязвимости,
  # отложенный на следующий круг (вариант (a) отчёта architect круга 3,
  # явно отвергнутый заданием как «не решает, просто откладывает»).
  # СТРУКТУРНЫЙ фикс — ДВА независимых списка строятся ЦИКЛОМ на РАЗНОЕ
  # число буллетов (n=6 для ЗАЩИЩАЕТ, m=5 для НЕ ЗАЩИЩАЕТ — разные
  # значения исключают ложный проход реализации, которая молча смешивает
  # счётчики двух списков), и ОЖИДАЕМАЯ строка итога СОБРАНА printf'ом ИЗ
  # ТЕХ ЖЕ переменных $n/$m — не переписана вторым числом руками.
  # Генератор и проверка делят ОДИН источник счёта: дрейф «что записано»
  # vs «что проверяется» структурно невозможен (та же дисциплина, что
  # §Инварианты п.2 контракта требует от САМОГО гарда, применена теперь и
  # к батарее, которая его проверяет). n=6/m=5 — числа, НЕ встречавшиеся
  # ни в одном из вердиктов (1, 2, 3 уже «засвечены» как кандидаты
  # хардкода для читающего этот файл стаба). ЛЮБОЙ cap < 6 (в частности
  # cap=2 круга 2) детерминированно ловится КАЖДЫЙ прогон, не
  # вероятностно. Честная scripts/check_threat_model.sh (mapfile+for,
  # строки 79-128) уже структурно корректна для произвольного N —
  # подтверждено независимо чтением её кода, не только этой батареей;
  # полной защиты от адверсария, читающего ИМЕННО этот файл и заранее
  # подбирающего cap=6, конечный example-based тест дать не может —
  # фундаментальный предел (тот же, что у Р9/Р13 и любой конечной
  # батареи, см. отчёт architect круга 3) — это признано прямо, не
  # скрыто.
  local n m i zbody nbody
  n=6
  m=5
  zbody=""
  for ((i = 1; i <= n; i++)); do
    zbody+="- буллет номер ${i} несёт собственный внутренний дефис-разделитель-${i} внутри текста"$'\n'
  done
  nbody=""
  for ((i = 1; i <= m; i++)); do
    nbody+="- пункт номер ${i} тоже несёт внутренний дефис-разделитель-${i} но в другом списке"$'\n'
  done
  w="$(mktemp -d "${TMPDIR:-/tmp}/battery_tm_dc2.XXXXXX")"; f="$w/c.md"
  _tm_write "$f" "ЗАЩИЩАЕТ:
${zbody}
НЕ ЗАЩИЩАЕТ:
${nbody}"
  out="$(bash "$TM_SUBJ" "$w" "c.md" 2>&1)"; rc=$?
  rm -rf "$w"
  [ "$rc" -eq 0 ] && printf '%s' "$out" | grep -Fq "$(printf 'ЗАЩИЩАЕТ %d буллет(ов), НЕ ЗАЩИЩАЕТ %d буллет(ов)' "$n" "$m")"
}

battery_regex_injection() {
  # Буллет содержит ERE-метасимволы буквально — сравнение меток/префикса
  # литеральное, содержимое буллета вообще не участвует в построении
  # паттерна → rc 0, метасимволы не интерпретированы.
  local w f out rc
  w="$(mktemp -d "${TMPDIR:-/tmp}/battery_tm_ri.XXXXXX")"; f="$w/c.md"
  _tm_write "$f" 'ЗАЩИЩАЕТ:
- символы . * + ? [ ] ( ) ^ $ | остаются буквами буллета а не regex-командами

НЕ ЗАЩИЩАЕТ:
- смысловую адекватность границы которую судит критик а не механический барьер'
  out="$(bash "$TM_SUBJ" "$w" "c.md" 2>&1)"; rc=$?
  rm -rf "$w"
  [ "$rc" -eq 0 ]
}

battery_silent_drop() {
  # Список ЗАЩИЩАЕТ: присутствует, но без единого буллета — ожидание:
  # ИМЕНОВАННЫЙ отказ, не тихий проход.
  local w f out rc
  w="$(mktemp -d "${TMPDIR:-/tmp}/battery_tm_sd.XXXXXX")"; f="$w/c.md"
  _tm_write "$f" 'ЗАЩИЩАЕТ:

НЕ ЗАЩИЩАЕТ:
- враждебное окружение вызывающего процесса за пределами базового PATH-экспорта'
  out="$(bash "$TM_SUBJ" "$w" "c.md" 2>&1)"; rc=$?
  rm -rf "$w"
  [ "$rc" -eq 1 ] && printf '%s' "$out" | grep -Fq 'модель угроз: список ЗАЩИЩАЕТ: пуст (нет буллета)'
}

