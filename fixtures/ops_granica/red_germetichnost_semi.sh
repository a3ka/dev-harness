#!/usr/bin/env bash
# Клетка 8 (И-8, «Выход» п.1 — фикстурная половина) контракта 093.
# ПРЕДМЕТ (дословно; арбитраж 093 РЕШЕНИЕ п.1/П6а — граница УНАСЛЕДОВАНА):
#   вход-Б (граница унаследована): клетка НЕ строит namespace и НЕ
#     переключает uid; первой ступенью, ДО любых попыток чтения, меряет
#     УНАСЛЕДОВАННОЕ: euid процесса ≠ uid владельца станции (владелец =
#     uid-owner корня чекаута $OPS093_ROOT); запуск под владельцем станции →
#     rc 1 «раннер запущен под uid владельца станции: граница не установлена
#     снаружи»; под uid агента — попытки ТОЛЬКО ЧТЕНИЯ (без записи — Н-219)
#     реальных путей списка И-3 → каждая неуспешна (EACCES на живой станции);
#     успех чтения любого пути → rc 1 с именем пути; ни одна не успешна →
#     половина-Б зелёна.
#   вход-А (запись под множество чтения orch-peak — починка А-5 круга 2:
#     прежняя редакция после половины-Б безусловно печатала NOT_IMPLEMENTED
#     и rc 2 — ни один путь субъекта в этом не участвовал, полный guard не
#     имел ДОСТИЖИМОГО зелёного позитивного контроля): под унаследованной
#     границей недостижимость записи для ВСЕЙ семьи (каждая клетка — потомок
#     раннера с тем же uid) доказывается ЖИВЫМИ пробами: access(2)-проба
#     `test -w` каждого СУЩЕСТВУЮЩЕГО пути перечня И-8 — SESS-корень
#     $OWNER_HOME/.local/state/dev-harness-sessions, каждый перечислимый
#     каталог сессий и его глубокий подпуть
#     zones/dev/.omp/profiles/dev/agent/sessions/--home-harness-dev-harness--,
#     /var/lib/orch-peak — и БЛИЖАЙШЕГО СУЩЕСТВУЮЩЕГО ПРЕДКА несуществующих
#     корней (создание дерева требует w на существующем предке — проба не
#     вакуумна и в CI), плюс РЕАЛЬНАЯ touch-проба в каждом опробованном
#     каталоге: отказ ОС обязателен; успех = красное именованное +
#     немедленная вычистка своего следа (файл создан этим же uid — убрать
#     можно). Доступность записи ЛЮБОГО пути перечня → rc 1 с именем пути.
#     Н-219 («только чтение») здесь НЕ нарушена: под границей отказ записи
#     не создаёт ничего, а успех сам есть нарушение и вычищается; mtime-
#     наблюдатель 090-класса под границей НЕИСПОЛНИМ по построению — uid,
#     которому запрещено ЧИТАТЬ перечень (ступень 2 это доказывает), не
#     может его и сканировать; ДО границы (запуск под владельцем) семья
#     красна ступенью 1 независимо от записи, наблюдатель избыточен.
#     Классификация именована в этом тексте, не молчаливый rc 2.
# Обманные стабы клетки 8 (в её коде, прецедент 090), два: (i) запись под
#     множество чтения реального orch-peak — наблюдаема под границей как
#     ДОСТУПНОСТЬ записи: живые touch-пробы этой клетки и есть её ловец
#     (успешная запись любой клетки семьи в перечень = успешная touch-проба
#     = красное именованное с путём); (ii) самопереключение uid внутри
#     раннера/клетки — на входе euid владельца станции, первый же замер
#     клетки 8 ДО любого переключения даёт именованный rc 1; собственное
#     переключение раннера — отказ, не способ позеленеть (арбитраж 093 П3).
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${OPS093_ROOT:-$(cd "$HERE/../.." && pwd)}"
[ -d "$ROOT" ] || { printf 'ОТКАЗ: корень %s не каталог\n' "$ROOT" >&2; exit 2; }

# ── Половина-Б, ступень 1: УНАСЛЕДОВАННЫЙ euid (до любых чтений) ─────────────
EUID_NOW="$(id -u)"
OWNER_UID="$(stat -c %u "$ROOT")" || { printf 'ОТКАЗ: не прочитан uid владельца %s\n' "$ROOT" >&2; exit 2; }
if [ "$EUID_NOW" = "$OWNER_UID" ]; then
  printf 'раннер запущен под uid владельца станции: граница не установлена снаружи (И-8б, арбитраж 093)\n' >&2
  exit 1
fi

# ── Половина-Б, ступень 2: попытки ТОЛЬКО ЧТЕНИЯ (Н-219) реальных путей И-3 ──
# HOME владельца станции — из passwd по OWNER_UID; абсолютный /var/lib/orch-peak
# входит в перечень безусловно (≥1 попытка всегда — пустая выборка красна).
OWNER_HOME="$(getent passwd "$OWNER_UID" | cut -d: -f6)"
[ -n "$OWNER_HOME" ] || { printf 'NOT_IMPLEMENTED: не определён HOME владельца станции (uid %s) — список И-3 неполон\n' "$OWNER_UID" >&2; exit 2; }
PYTII="${OWNER_HOME}/.ssh
${OWNER_HOME}/.ssh/authorized_keys
${OWNER_HOME}/.ssh/config
${OWNER_HOME}/.config
${OWNER_HOME}/.local/state/dev-harness-sessions
/var/lib/orch-peak"
popytki=0
utechki=''
while IFS= read -r p; do
  [ -n "$p" ] || continue
  popytki=$((popytki + 1))
  if [ -d "$p" ]; then
    ls "$p" >/dev/null 2>&1 && utechki="$utechki $p"
  else
    cat "$p" >/dev/null 2>&1 && utechki="$utechki $p"
  fi
done <<<"$PYTII"
if [ "$popytki" -eq 0 ]; then
  printf 'ОТКАЗ: ни одной попытки чтения — пустая выборка красна (И-8б)\n' >&2
  exit 1
fi
if [ -n "$utechki" ]; then
  printf 'контрольный путь станции прочитан под uid агента:%s (И-8б)\n' "$utechki" >&2
  exit 1
fi
printf 'половина-Б: граница унаследована (euid=%s ≠ владельца=%s), попыток чтения %s, утечек нет\n' "$EUID_NOW" "$OWNER_UID" "$popytki" >&2

# ── Половина-А: ЖИВЫЕ пробы записи под множество чтения orch-peak ────────────
# Перечень И-8: SESS-подпуть (глубокий фиксированный хвост под каждым
# каталогом сессий) + /var/lib/orch-peak. Каждая проба — живой ответ ОС для
# ЭТОГО uid (access(2) в test -w; touch — реальный openat). Пустая выборка
# красна; доступность любой записи → именованное rc 1 с путём.
DEEP="zones/dev/.omp/profiles/dev/agent/sessions/--home-harness-dev-harness--"
SESS_ROOT="$OWNER_HOME/.local/state/dev-harness-sessions"
popytki_zapisi=0
dostupno=''
probe_dirs=''

nearest_existing() { # $1=путь → ближайший существующий предок, иначе код 1
  local p="$1"
  while [ "$p" != "/" ]; do
    [ -e "$p" ] && { printf '%s\n' "$p"; return 0; }
    p="$(dirname -- "$p")"
  done
  [ -e "$p" ] && { printf '%s\n' "$p"; return 0; }
  return 1
}

zap_probe() { # $1=каталог перечня — access(2)-проба + кандидат touch-пробы
  local p="$1"
  popytki_zapisi=$((popytki_zapisi + 1))
  probe_dirs="$probe_dirs $p"
  if [ -w "$p" ]; then
    dostupno="$dostupno $p"
  fi
}

# SESS-часть: корень (или ближайший существующий предок), каждый
# перечислимый каталог сессий, его глубокий подпуть.
if [ -e "$SESS_ROOT" ]; then
  zap_probe "$SESS_ROOT"
  # Перечисление: отказ листинга — сам по себе граница чтения (ступень 2).
  # ОСТАТОЧНЫЙ РИСК (назван, не скрыт): существующий каталог сессий с
  # аномальными правами (group/other-writable), недостижимный для листинга
  # этим uid, точечной пробой не накрывается — создаваемые пути накрыты
  # пробой корня, существующие требуют знания имени.
  while IFS= read -r sd; do
    [ -n "$sd" ] || continue
    case "$sd" in */*) continue ;; esac
    [ -d "$SESS_ROOT/$sd" ] || continue
    zap_probe "$SESS_ROOT/$sd"
    [ -d "$SESS_ROOT/$sd/$DEEP" ] && zap_probe "$SESS_ROOT/$sd/$DEEP"
  done < <(ls -1 "$SESS_ROOT" 2>/dev/null)
else
  NEAREST="$(nearest_existing "$SESS_ROOT")" && zap_probe "$NEAREST"
fi

# /var/lib/orch-peak — второй корень перечня (создание требует w на предке).
if [ -e /var/lib/orch-peak ]; then
  zap_probe /var/lib/orch-peak
else
  NEAREST="$(nearest_existing /var/lib/orch-peak)" && zap_probe "$NEAREST"
fi

if [ "$popytki_zapisi" -eq 0 ]; then
  printf 'ОТКАЗ: ни одной пробы записи — пустая выборка красна (И-8а)\n' >&2
  exit 1
fi
if [ -n "$dostupno" ]; then
  printf 'граница не держит запись: путь перечня И-8 доступен на запись uid семьи:%s (И-8а)\n' "$dostupno" >&2
  exit 1
fi

# Реальные touch-пробы (А-5: исполнимый позитивный контроль, не только
# access(2)): отказ ОС обязателен; успех = красное + вычистка своего следа.
for d in $probe_dirs; do
  t="$d/.ops093-8a-$RANDOM.$$"
  popytki_zapisi=$((popytki_zapisi + 1))
  if touch "$t" 2>/dev/null; then
    rm -f -- "$t"
    printf 'граница не держит запись: создан файл под перечнем И-8 (%s), вычищен — граница не установлена (И-8а)\n' "$t" >&2
    exit 1
  fi
done

printf 'половина-А: запись под множество чтения orch-peak отказана ОС (проб %s, доступно 0, создано 0) — семья под унаследованным uid не может изменить перечень (И-8а)\n' "$popytki_zapisi" >&2
printf 'ЗЕЛЁНО(093-8): граница унаследована (euid=%s ≠ владельца=%s), чтение и запись перечня станции отказаны ОС (И-8а+б)\n' "$EUID_NOW" "$OWNER_UID" >&2
exit 0
