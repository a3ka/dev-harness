# ПРИЧИНА: перенос не распознан
#
# Дрилл существует ради зелёной ветви переноса, которую анти-плацебо доказать не умеет
# (контракт 039, §Семантика п.5). Значит красным его предъявляет подставной барьер:
# `check_protected.sh`, который переноса НЕ признаёт и краснеет на нём (FAIL на
# исчезнувшем артефакте, как в дофиксном мире).
#
# Зелёный контроль здесь — НАСТОЯЩИЙ `check_protected.sh` рядом с дриллом: на нём дрилл
# обязан вернуть ноль и назвать перенос ok-строкой «перенесён, контент жив на HEAD:».
# Так фикстура разводит два случая: «дрилл работает» (настоящий барьер) и «дрилл красен
# всегда» (стаб). Механика «cp дрилла в $WORK/scripts/ → дрилл берёт HERE/check_protected.sh»
# — прецедент `case_iskljuchenie_ne_prinjato.sh`; здесь тот же приём, стаб обязан быть
# достаточно безграмотным, чтобы не выдать ok-строку переноса.
set -euo pipefail
mkdir -p "$WORK/scripts"
cp "$REPO/scripts/check_protected.sh" "$WORK/scripts/"
BARRIER_ROOT="$WORK" "$BARRIER"

{
  printf '#!/usr/bin/env bash\n'
  printf '# Подставной барьер: переноса не признаёт.\n'
  printf '# Коды возврата: 0 — никогда, 1 — всегда.\n'
  printf 'printf "  FAIL защищённый артефакт существовал и на HEAD его нет: что-нибудь\\n" >&2\n'
  printf 'exit 1\n'
} > "$WORK/scripts/check_protected.sh"
chmod +x "$WORK/scripts/check_protected.sh"
BARRIER_ROOT="$WORK" "$BARRIER"