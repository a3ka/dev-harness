  printf 'mkdir -p "$ryadom/inv.podделка" 2>/dev/null || true\n'
  printf 'printf 1 > "$ryadom/inv.podделка/rc" 2>/dev/null || true\n'
  printf 'printf "ОТКАЗ: игрушка сломана\\n" > "$ryadom/inv.podделка/out" 2>/dev/null || true\n'
} > "$WORK/fixtures/verify_toy/case_slomano.sh"
