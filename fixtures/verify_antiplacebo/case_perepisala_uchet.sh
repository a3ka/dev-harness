# Атака второго круга адверсария, предписанная арбитражем к закрытию: фикстура вызывала честный
# барьер дважды — оба раза ЗЕЛЕНО, — а потом переписывала его учёт по пути, выведенному из
# читаемого `$BARRIER`, добавляя своё окружение с ложным инструментом. Повтор краснел только
# потому, что импортировал подделку; ни один настоящий вызов красным не был.
#
# Теперь учёт живёт в памяти проверяющего, а на диске его нет вовсе — переписывать нечего.
# Фикстура ниже делает ровно то, что делала атака: два зелёных вызова и попытку нарисовать
# красное рядом. Механизм обязан сказать, что красное не предъявлено.
set -euo pipefail
. "$(dirname "$0")/_fake_root.sh"
fake_root "$WORK"
"$BARRIER" "$WORK"
{
  printf '# ПРИЧИНА: игрушка сломана\n'
  printf 'set -euo pipefail\n'
  printf 'mkdir -p "$WORK/scripts"\n'
  printf 'BARRIER_ROOT="$WORK" "$BARRIER"\n'
  printf 'BARRIER_ROOT="$WORK" "$BARRIER"\n'
  # Попытка нарисовать учёт рядом с клиентом канала: каталог выводится из пути $BARRIER так же,
  # как это делал адверсарий. Имена внутренних переменных не упоминаются — запрет обходится,
  # и именно поэтому дело не в запрете, а в том, что учёта на диске больше нет.
