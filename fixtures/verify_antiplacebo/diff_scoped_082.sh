#!/usr/bin/env bash
# Машинный дифференциал А2 контракта 082 (инвариант 7: вердикты живых семей не меняются).
# Заморожен по блокеру-4 круга v2: «сам измеряемый прогон — не проверка дифференциала».
#
# СРАВНИВАЕТ два файла, каждый — полный вывод
#   bash scripts/verify_antiplacebo.sh --scope check_spec_ready (stdout+stderr),
# последней строкой «rc=<N>». Извлечение СТРУКТУРНОЕ: строки вердиктов — это строки
# вида «  ok   …» / «  FAIL …» (печать раннера scripts/verify_antiplacebo.sh:130-131),
# сравниваются как СОРТИРОВАННОЕ МНОЖЕСТВО целиком; плюс оба rc.
#
# Эталон ДО — закоммиченный файл do_check_spec_ready_082.txt, снятый живым прогоном ДО
# реализации: он НЕ является результатом ПОСЛЕ и не перезаписывается прогоном (требование
# круга v2: эталон независим от проверяемого результата).
#
# Коды возврата: 0 — множество ok/FAIL и rc совпали; 1 — именованное расхождение;
#                2 — нечего сравнивать (пустая выборка / нет строки rc= / плохие аргументы).
# Самопредъявление (совпадение→0, подмена строки→1, подмена rc→1) — клетки ДФк батареи
# red_watchdog_082.sh: вечно-нулевой компаратор там красен.
set -uo pipefail

[ "$#" -eq 2 ] || { printf 'NOT_IMPLEMENTED: использование: diff_scoped_082.sh <файл-ДО> <файл-ПОСЛЕ>\n' >&2; exit 2; }
[ -f "$1" ] || { printf 'NOT_IMPLEMENTED: файла ДО нет: %s\n' "$1" >&2; exit 2; }
[ -f "$2" ] || { printf 'NOT_IMPLEMENTED: файла ПОСЛЕ нет: %s\n' "$2" >&2; exit 2; }

izvlec() { grep -E '^  (ok|FAIL) ' "$1" | sort; }
rc_iz()  { awk -F= '$1 == "rc" { print $2; exit }' "$1"; }

a="$(izvlec "$1")"; b="$(izvlec "$2")"
ra="$(rc_iz "$1")"; rb="$(rc_iz "$2")"
[ -n "$a" ] || { printf 'NOT_IMPLEMENTED: в файле ДО нет строк вердиктов «  ok / FAIL » — пустая выборка не зелёная\n' >&2; exit 2; }
[ -n "$b" ] || { printf 'NOT_IMPLEMENTED: в файле ПОСЛЕ нет строк вердиктов «  ok / FAIL » — пустая выборка не зелёная\n' >&2; exit 2; }
[ -n "$ra" ] || { printf 'NOT_IMPLEMENTED: в файле ДО нет строки rc=\n' >&2; exit 2; }
[ -n "$rb" ] || { printf 'NOT_IMPLEMENTED: в файле ПОСЛЕ нет строки rc=\n' >&2; exit 2; }

st=0
if [ "$a" != "$b" ]; then
  printf 'FAIL diff_scoped_082: множество строк ok/FAIL разошлось с эталоном ДО (инв. 7)\n' >&2
  diff <(printf '%s\n' "$a") <(printf '%s\n' "$b") | sed 's/^/    /' >&2
  st=1
fi
if [ "$ra" != "$rb" ]; then
  printf 'FAIL diff_scoped_082: rc разошлись: ДО=%s, ПОСЛЕ=%s (инв. 7)\n' "$ra" "$rb" >&2
  st=1
fi
if [ "$st" -eq 0 ]; then
  printf '  ok   diff_scoped_082: множество вердиктов (%s строк) и rc=%s совпали с эталоном ДО\n' \
    "$(printf '%s\n' "$a" | wc -l)" "$ra" >&2
fi
exit "$st"
