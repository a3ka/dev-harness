# ПРИЧИНА: дерево изменилось вне $WORK
#
# ЧЕТВЁРТАЯ форма записи вне $WORK, предъявленная адверсарием: символьная ссылка. `find -type f`
# ссылок не перечисляет, и фикстура создавала `ln -s` в корне подставного дерева — прогон
# возвращал 0, ссылка оставалась. Теперь слепок видит ссылки отдельной мерой: имена и ЦЕЛИ через
# `readlink`, работающий и на битых.
#
# Зелёный контроль: честная фикстура игрушечного барьера → 0. Красное: та же фикстура, дописанная
# созданием битой ссылки в КОРНЕ подставного дерева ($REPO её собственного прогона), → код 1:
# ссылка появляется ВО ВРЕМЯ прогона, между снимками слепка.
#
# ТРИ измеренных грабля этой фикстуры, все мои, все записаны затем, чтобы четвёртый не появился:
# 1. НИЧЕГО не запекается: каждый уровень прогона даёт своей фикстуре СВОИ $BARRIER/$WORK/$REPO.
#    Запечённый на запись путь оказывался либо пуст, либо уровнем выше — `porcha` в корне дерева
#    красил зелёный контроль.
# 2. `$BARRIER` с нераскрытым heredoc разворачивался в обёртку ВНЕШНЕГО прогона — вложенный запрос
#    уходил в тот же канал, дедлок на 300 секунд.
# 3. Ссылка дописывается ТОЛЬКО ПОСЛЕ зелёного вызова: созданная сразу, она красила и его, и
#    положительного контроля не было вовсе.
set -euo pipefail
mkdir -p "$WORK/scripts" "$WORK/fixtures/igrushka" "$WORK/tmp"
cat > "$WORK/scripts/igrushka.sh" <<'EOF'
#!/usr/bin/env bash
# Игрушечный барьер пробы слепка.
# Коды возврата: 0 — порчи нет, 1 — порча есть.
set -euo pipefail
[ -f "${1:-.}/porcha" ] && { printf 'FAIL порча найдена\n' >&2; exit 1; }
printf '  ok   порчи нет\n' >&2
EOF
cat > "$WORK/fixtures/igrushka/case_porcha.sh" <<'EOF'
# ПРИЧИНА: порча найдена
set -euo pipefail
"$BARRIER" "$WORK"
touch "$WORK/porcha"
"$BARRIER" "$WORK"
EOF
"$BARRIER" "$WORK"

# Фаза порчи: файл ПЕРЕПИСАН ЦЕЛИКОМ, ссылка — ДО финального красного вызова. Дописывать её
# ПОСЛЕ бессмысленно: `set -e` убивает фикстуру на красном вызове игрушки, и дописанная строка
# не выполняется вовсе — три мои правки не доходили до этой причины.
cat > "$WORK/fixtures/igrushka/case_porcha.sh" <<'EOF'
# ПРИЧИНА: порча найдена
set -euo pipefail
"$BARRIER" "$WORK"
# Имя ссылки уникально за прогон ($$): повторный прогон проверяющего не исполняет мой сценарий,
# а гоняет барьер на дереве, где ссылка первого прогона УЖЕ лежит. Фиксированное имя делало
# повтор зелёным — «запись о вызове не подтверждена»; уникальное оставляет дерево меняться
# при каждом прогоне, и красное предъявляется всякий раз.
ln -sfn porcha "$REPO/nesankcionirovannaja-ssylka-$$"
"$BARRIER" "$WORK"
EOF
rm -rf "$WORK/tmp/antiplacebo"
"$BARRIER" "$WORK"
