# ПРИЧИНА: клапан не транслирует флаг
#
# Контракт 002 v5, критерий 1: единственный сниматель always-ask. Без этой
# ветки владелец не мог снять политику — режим был замком без ключа, и
# первое живое действие политики было то, что снять её нечем. Зелёная
# ветвь КРАСНЕЕТ, если сломать любую из двух частей клапана: трансляцию
# флага или объявление в баннере. Красная фикстура ловит обход трансляции
# (правка по метке — присваивание пустого массива вместо «--approval-mode
# yolo»): баннер при этом остаётся, и без инъекции раздел 4 барьера
# находит «клапан не транслирует флаг». Баннер без инъекции не спасает;
# инъекция без баннера — тот же обход в обратную сторону.
#
# Зелёный контроль: копия дерева как есть → 0. Красное: в лаунчере
# присваивание YOLO_ARGS заменено на пустой массив, и `--yolo` уже
# не форвардится — баннер при этом остаётся, и раздел 4 барьера
# находит клапан не работающим (нет `--approval-mode yolo` в argv omp).
set -euo pipefail
. "$(dirname "$0")/_tree.sh"
T="$WORK/tree"
make_tree "$T"
"$BARRIER" "$T"

# Поломка: в строке с `YOLO_ARGS=(--approval-mode yolo)` присваивание
# заменяется на пустой массив. Баннер при этом остаётся (его правка не
# трогается), и без инъекции раздел 4 барьера находит «клапан не
# транслирует флаг». Поломка точечная: фикстура обязана вносить ОДНУ
# правку, а не перепечатывать разбор (правило 3).
sed -i 's|YOLO_ARGS=(--approval-mode yolo)|YOLO_ARGS=()|' "$T/workshop"
"$BARRIER" "$T"
