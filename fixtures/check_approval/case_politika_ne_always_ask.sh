# ПРИЧИНА: tools.approvalMode
#
# Режим входа держится значением политики, а не наличием ключа: `never` снимает
# спрашивание с каждого инструмента, и сессия правит дерево без слова владельца.
# Барьер обязан назвать прочитанное значение, а не «политика не та».
#
# Зелёный контроль: копия дерева как есть → 0. Красное: значение политики заменено
# на `never`.
set -euo pipefail
. "$(dirname "$0")/_tree.sh"
T="$WORK/tree"
make_tree "$T"
"$BARRIER" "$T"

sed -i 's/^\([[:space:]]*\)approvalMode:.*/\1approvalMode: never/' "$T/.omp/config.yml"
"$BARRIER" "$T"
