# ПРИЧИНА: не наследует конфиг проекта
#
# Конфиг проекта omp читает от своего РАБОЧЕГО КАТАЛОГА, поэтому запуск из чужого
# каталога равносилен запуску без политики: строка `always-ask` остаётся лежать в
# файле, которого живой процесс не читает. Именно этот класс назвал адверсарий
# находкой 3 — «конфигурация может лежать в файле, который живой запуск не читает».
#
# Зелёный контроль: копия дерева как есть → 0. Красное: из лаунчера удалён переход
# в каталог инструмента перед запуском omp.
set -euo pipefail
. "$(dirname "$0")/_tree.sh"
T="$WORK/tree"
make_tree "$T"
"$BARRIER" "$T"

# Каталог без конфига — там и окажется omp, когда лаунчер перестанет переходить в
# дерево инструмента: барьер запускает лаунчер из своего рабочего каталога.
drop_lines "$T/workshop" '^[[:space:]]*cd "\$HERE"$'
"$BARRIER" "$T"
