# Каркас подставного дерева для фикстур `check_approval`.
#
# Имя НЕ `case_*.sh`: сам он фикстурой не считается и в прогон не попадает.
#
# `make_tree <каталог>` кладёт КОПИЮ проверяемого дерева: барьер запускает
# настоящий лаунчер, а тот порождает промпт роли через `scripts/gen-harness.ts`
# из `roles/` и читает `.omp/config.yml` и `.omp/agents/`. Урезанная выборка
# файлов красила бы зелёную основу нехваткой артефакта, а не внесённой поломкой —
# положительный контроль обязателен (правило 3 нормой).
#
# Копируется из `$REPO` (объявленный проверяющим корень, откуда можно копировать),
# без `.git`, `.zones` и `tmp`: история барьеру не нужна, а `.zones` и `tmp` —
# черновики прошлых запусков, и перенос их в подставное дерево смешал бы чужой
# мусор с предметом.

make_tree() {
  local t="$1"
  mkdir -p "$t"
  tar -C "${REPO:?нужен \$REPO — корень, откуда копируется дерево}" \
      --exclude=./.git --exclude=./.zones --exclude=./tmp \
      -cf - . | tar -C "$t" -xf -
}

# Удаление строк по метке — обманная правка ЛАУНЧЕРА. Метка объявлена в самом
# лаунчере комментарием, потому что фикстура обязана вносить ОДНУ поломку, а не
# перепечатывать разбор аргументов целиком: перепечатанный лаунчер краснел бы
# любым своим отличием, и внесённая поломка была бы неотличима от опечатки.
drop_lines() {  # <файл> <ERE>
  local f="$1" re="$2" tmpf
  tmpf="$(mktemp "${TMPDIR:-/tmp}/drop.XXXXXX")"
  grep -vE "$re" "$f" > "$tmpf"
  cmp -s "$f" "$tmpf" && { printf 'фикстура не нашла что удалять: %s\n' "$re" >&2; exit 3; }
  cat "$tmpf" > "$f"
  rm -f "$tmpf"
}
