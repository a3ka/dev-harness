# Красное предъявление 1/7 контракта 029: МАРШРУТ (а) — инженерный форк → консультант,
# КЛАССИФИКАТОР DEFAULT-OPEN (решение владельца Q1: всё НЕПРОМАРКИРОВАННОЕ инженерное
# форк-решение уходит консультанту, а не владельцу) + ИСЧЕРПАЕМОСТЬ области значений
# КЛАСС: четвёртый исход — присутствующее НЕИЗВЕСТНОЕ/ПУСТОЕ значение. Круг 4 добавил
# инв. 10 в ЭТУ пробу (входы 7–9): rc prereq-пробы инструмента, «нечем проверить».
#
# ВХОД: игрушечный журнал forks/ из трёх записей:
#   metering-porog  — БЕЗ поля КЛАСС (непромаркированная), МАРШРУТ: батч → передаточное;
#   ci-waiver       — КЛАСС: инженерный,  МАРШРУТ: батч → передаточное;
#   union-fiks      — КЛАСС: инженерный,  МАРШРУТ: консультант → законно.
#
# ПОЧЕМУ входы 5–6 отдельны от входа 1: default-open закрывает МОЛЧАНИЕ разметки
# (поля нет), а не мусор в поле. Реализация, разбирающая три известных токена и молча
# пропускающая четвёртый, неотличима от исчерпывающей на входах 1–4; различает её ровно
# присутствующее неизвестное значение. Отказ обязан быть ИМЕНОВАННЫМ («неизвестный
# класс»), а не молчаливым отнесением к инженерному.
#
# ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА (порядок ассертов = порядок инвариантов §Предмет):
#   1) журнал с передаточной непромаркированной → rc 1, отказ называет «передаточное
#      касание» И имя записи (инв. 1);
#   2) КЛАСС: инженерный + батч → тот же отказ с именем ci-waiver (инв. 1);
#   3) законный инженерный → консультант → rc 0 (позитивный контроль: барьер не
#      краснеет на конформном входе);
#   4) инженерный, адресованный СОревью → rc 1 «инженерный форк вне консультанта»
#      (инв. 1: маршрут (а) не подменяется маршрутом (в));
#   5) КЛАСС: иной (присутствует, неизвестен) при КОНФОРМНОМ во всём прочем МАРШРУТ:
#      консультант → rc 1 «неизвестный класс» + имя записи: иной причины отказать здесь
#      нет, поэтому ассерт различает отказ от молчаливого default-инженерного;
#   6) КЛАСС: пустой (поле есть, значение отсутствует) + МАРШРУТ: консультант → тот же
#      именованный отказ (инв. 1-исчерпаемость: пустое значение ≠ отсутствующее поле).
#   7) СЛОМАННЫЙ ИНСТРУМЕНТ, exit 1: обёртка `sha256sum` первой в PATH печатает
#      КОРРЕКТНЫЙ текст пустого хеша и выходит в 1 → rc 2 «нечем проверить» (инв. 10).
#      Дерево — то же конформное, что зелено на входе 3 настоящим инструментом, поэтому
#      различие вердикта создаёт РОВНО непривязанный rc, а не содержимое журнала;
#   8) тот же класс, exit 127 (инструмента фактически нет, текст всё равно верен) →
#      rc 2 (инв. 10: успех пробы = верный ТЕКСТ И нулевой rc);
#   9) ПОЗИТИВНЫЙ КОНТРОЛЬ ЗАТЕНЕНИЯ: то же дерево БЕЗ обёртки → снова rc 0. Ловец
#      пробы, сломавшей саму себя: утекло бы затенение за пределы вызова — зелёный
#      входа 3 не воспроизвёлся бы, и краснота 7–8 не доказывала бы ничего.
#
# СТАБ-ПРИВЯЗКИ (Н-39: привязка живёт в КОДЕ пробы; каждый стаб назван у того входа,
# где его дефект НАБЛЮДАЕМ):
#   S-optin   — классификатор судит только ЯВНО помеченное `КЛАСС: инженерный`
#               (default-closed вместо default-open): вход 1 (запись БЕЗ КЛАСС) проходит
#               зелёным → краснеет ассертом 1; на входе 2 этот стаб честен.
#   S-onlyclass — судит КЛАСС, не сверяя его с МАРШРУТ: вход 2 проходит зелёным →
#               краснеет ассертом 2.
#   S-threeclass — разбирает ТРИ известных токена, присутствующий неизвестный молча
#               пропускает: входы 1–4 честны, наблюдаем ТОЛЬКО на входе 5 → ассерт 5.
#   S-emptyclass — пустое значение приравнивает к отсутствию поля (default-open):
#               на входе 5 честен, наблюдаем ТОЛЬКО на входе 6 → ассерт 6.
#   S-allred  — «всё красное» (тотальный отказ): различим ТОЛЬКО на конформном входе →
#               краснеет ассертом 3.
#   S-tekstsha — prereq-проба сверяет ТОЛЬКО ТЕКСТ вывода sha256sum, rc конвейера не
#               привязан (состояние HEAD круга 3, замер M1 арбитража): на входах 1–6 и 9
#               инструмент настоящий и стаб честен, наблюдаем ТОЛЬКО на входах 7 и 8 →
#               ассерты 7, 8 (rc 0 вместо 2).
#   S-commandv — наличие инструмента проверяется `command -v` без реального вызова:
#               обёртка находится и «работает», наблюдаем на входах 7 и 8 → ассерты 7, 8.
# HEAD написания проб (барьера не было): rc 127 → ассерт 1. HEAD круга 4 (барьер есть,
# rc prereq-пробы не привязан): входы 1–6 и 9 зелены, входы 7–8 КРАСНЫ — измерено.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_forks.sh"

# 1) непромаркированная запись, адресованная владельцу.
R1="$WORK/a-neprom"; igrushka "$R1"
zapis "$R1" metering-porog "МАРШРУТ: батч" "ЗАВЕДЁН: $(iso_nazad 600)"
zapusk --root "$R1"
zhdu_rc 1 'непромаркированный форк адресован владельцу (default-open, инв. 1)'
zhdu_text 'передаточное касание' 'отказ обязан быть ПОИМЁННЫМ классом (инв. 1)'
zhdu_text 'metering-porog' 'отказ обязан называть запись (инв. 1)'

# 2) явно инженерная запись, адресованная владельцу.
R2="$WORK/a-inzh"; igrushka "$R2"
zapis "$R2" ci-waiver "КЛАСС: инженерный" "МАРШРУТ: батч" "ЗАВЕДЁН: $(iso_nazad 600)"
zapusk --root "$R2"
zhdu_rc 1 'инженерный форк адресован владельцу (инв. 1)'
zhdu_text 'ci-waiver' 'отказ обязан называть запись (инв. 1)'

# 3) позитивный контроль: инженерный → консультант, и непромаркированный туда же.
R3="$WORK/a-ok"; igrushka "$R3"
zapis "$R3" union-fiks "КЛАСС: инженерный" "МАРШРУТ: консультант" "ЗАВЕДЁН: $(iso_nazad 600)"
zapis "$R3" ascii-konvencija "МАРШРУТ: консультант" "ЗАВЕДЁН: $(iso_nazad 60)"
zapusk --root "$R3"
zhdu_rc 0 'конформный журнал маршрута (а) — барьер обязан молчать'

# 4) инженерный, уведённый в маршрут (в).
R4="$WORK/a-v-soreview"; igrushka "$R4"
zapis "$R4" perenos-poroga "КЛАСС: инженерный" "МАРШРУТ: со-ревью" "ЗАВЕДЁН: $(iso_nazad 600)"
zapusk --root "$R4"
zhdu_rc 1 'инженерный форк уведён в маршрут СОревью (инв. 1)'
zhdu_text 'perenos-poroga' 'отказ обязан называть запись (инв. 1)'

# 5) присутствующий НЕИЗВЕСТНЫЙ класс при конформном во всём прочем маршруте.
R5="$WORK/a-klass-inoj"; igrushka "$R5"
zapis "$R5" fourth-klass "КЛАСС: иной" "ПРИЗНАК: норма" "МАРШРУТ: консультант" \
      "ЗАВЕДЁН: $(iso_nazad 600)"
zapusk --root "$R5"
zhdu_rc 1 'присутствующее неизвестное значение КЛАСС обязано быть ИМЕНОВАННЫМ отказом (инв. 1)'
zhdu_text 'fourth-klass' 'отказ обязан называть запись (инв. 1)'
zhdu_text 'неизвестный класс' 'отказ обязан называть класс нарушения, а не молчать (инв. 1)'

# 6) присутствующий ПУСТОЙ класс — не то же, что отсутствие поля.
R6="$WORK/a-klass-pustoj"; igrushka "$R6"
zapis "$R6" klass-pustoj "КЛАСС:" "МАРШРУТ: консультант" "ЗАВЕДЁН: $(iso_nazad 600)"
zapusk --root "$R6"
zhdu_rc 1 'пустое значение КЛАСС — неразобранное объявление, а не default-open (инв. 1)'
zhdu_text 'klass-pustoj' 'отказ обязан называть запись (инв. 1)'
zhdu_text 'неизвестный класс' 'отказ обязан называть класс нарушения (инв. 1)'

# 7) СЛОМАННЫЙ ИНСТРУМЕНТ, exit 1 при КОРРЕКТНОМ тексте. PATH-затенение — СИМУЛЯЦИЯ
#    неработоспособного sha256sum (инв. 10), НЕ защита от враждебного PATH: среда вызова
#    есть TCB (арбитраж tcb-granica-put-029.md §2), недоверенные входы — ответ и дерево.
#    Тот же класс даёт busybox-вариант, битый диск, частичная установка — атакующий не
#    нужен. Дерево R3 — конформное, зелёное на входе 3 настоящим инструментом.
OB1="$WORK/obertka-sha-exit1"; slomannyj_sha256sum "$OB1" 1
zapusk_pod_obertkoj "$OB1" --root "$R3"
zhdu_rc 2 'sha256sum печатает верный текст и выходит в 1 — проверить нечем (инв. 10)'
zhdu_text 'sha256sum' 'отказ обязан называть неработоспособный инструмент (инв. 10)'

# 8) тот же класс, exit 127: инструмента фактически нет, текст всё равно верен.
OB2="$WORK/obertka-sha-exit127"; slomannyj_sha256sum "$OB2" 127
zapusk_pod_obertkoj "$OB2" --root "$R3"
zhdu_rc 2 'sha256sum печатает верный текст и выходит в 127 — проверить нечем (инв. 10)'
zhdu_text 'sha256sum' 'отказ обязан называть неработоспособный инструмент (инв. 10)'

# 9) позитивный контроль ЗАТЕНЕНИЯ: то же дерево на настоящем инструменте — снова rc 0.
zapusk --root "$R3"
zhdu_rc 0 'на настоящем sha256sum конформный журнал обязан остаться зелёным (инв. 10)'
