# ПРИЧИНА: передаточное касание
#
# 051, клетка владельца 1: открытая передаточная запись → rc 1. Зелёный
# контроль — журнал из конформной открытой записи по маршруту (а). Красное —
# ОДНА открытая инженерная запись с явным `ОТВЕЧЕНО: нет`, уведённая владельцу
# (МАРШРУТ: батч): барьер обязан назвать «передаточное касание» и предмет.
set -euo pipefail

WORK="${WORK:-$(mktemp -d "${TMPDIR:-/tmp}/v051-case.XXXXXX")}"
ROOT="$WORK/root"
mkdir -p "$ROOT/forks"

NOW="$(date -u +%s)"
iso_nazad() { date -u -d "@$(( NOW - $1 ))" +%Y-%m-%dT%H:%M:%SZ; }

zapis() {
  local id="$1"; shift
  {
    printf 'ФОРК: %s\n' "$id"
    printf 'ВОПРОС: подставной вопрос предмета %s\n' "$id"
    for f in "$@"; do printf '%s\n' "$f"; done
  } > "$ROOT/forks/$id.md"
}

# Зелёный контроль: конформная открытая запись по маршруту (а).
zapis konformnyj-inzh "КЛАСС: инженерный" "МАРШРУТ: консультант" \
      "ЗАВЕДЁН: $(iso_nazad 600)" "ОТВЕЧЕНО: нет"

"$BARRIER" --root "$ROOT"

# Красное: открытая передаточная (инженерный + батч + ОТВЕЧЕНО: нет) → rc 1.
zapis ci-open-pered "КЛАСС: инженерный" "МАРШРУТ: батч" \
      "ЗАВЕДЁН: $(iso_nazad 300)" "ОТВЕЧЕНО: нет"
"$BARRIER" --root "$ROOT"