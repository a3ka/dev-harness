# Каркас красных проб классификатора форков (контракт 029, Н-104).
#
# Имя НЕ case_*.sh и НЕ red_*.sh намеренно: каркас пробой не считается, в мета-прогон
# verify_antiplacebo не попадает и в счёт проб не входит (прецедент _repo.sh, _zhnets.sh).
#
# ДВА РЕЖИМА, один двоичный контракт вызова «$BARRIER --root <корень> [--flush|--schet]»:
#  * мета-прогон: WORK/BARRIER/REPO назначает проверяющий (verify_antiplacebo);
#  * прямой прогон (`bash fixtures/check_fork_route/<проба>.sh`): проба назначает их
#    сама — каждая проба красна на текущем HEAD БЕЗ раннера (красное = исполненный факт,
#    а не обещание прозы контракта).
#
# ГРАММАТИКА ЗАПИСИ ЖУРНАЛА — ЕДИНЫЙ источник: строит только `zapis`, потребители несут
# её побайтово; переизобретение полей в теле пробы запрещено. Пути ASCII (Н-99: кириллица
# в ПУТЯХ не матчится побайтовым сравнением барьеров; кириллица — в содержимом).
if [ -z "${WORK:-}" ]; then
  REPO="$(cd "$(dirname "$0")/../.." && pwd -P)"
  WORK="$(mktemp -d "${TMPDIR:-/tmp}/forks029.XXXXXX")"
  BARRIER="$REPO/scripts/check_fork_route.sh"
  trap 'chmod -R u+w "$WORK" 2>/dev/null || true; rm -rf "$WORK"' EXIT
fi
export LC_ALL=C.UTF-8

NOW="$(date -u +%s)"

# ISO-время «N секунд назад» — форма полей ЗАВЕДЁН/ВЫЗВАН.
iso_nazad() {  # <секунд назад>
  date -u -d "@$(( NOW - $1 ))" +%Y-%m-%dT%H:%M:%SZ
}

# Пустая игрушка: журнал форков + каталоги вердиктов.
igrushka() {  # <корень>
  local r="$1"
  mkdir -p "$r/forks" "$r/verdicts/consultant" "$r/verdicts/critic" "$r/verdicts/arbitration"
}

# Запись журнала. Обязательные поля кладёт каркас, прочие — аргументами дословно.
zapis() {  # <корень> <id> [поле…]
  local r="$1" id="$2" f
  shift 2
  {
    printf 'ФОРК: %s\n' "$id"
    printf 'ВОПРОС: подставной вопрос предмета %s\n' "$id"
    for f in "$@"; do printf '%s\n' "$f"; done
  } > "$r/forks/$id.md"
}

# Ответ роли (СОревью/консультация/арбитраж): МОДЕЛЬ пишется, если не «-».
otvet() {  # <корень> <путь от корня> <модель|-> [строка тела…]
  local r="$1" p="$2" m="$3" l
  shift 3
  mkdir -p "$(dirname "$r/$p")"
  {
    printf 'ПРЕДМЕТ: %s\n' "$(basename "$p" .md)"
    [ "$m" = '-' ] || printf 'МОДЕЛЬ: %s\n' "$m"
    for l in "$@"; do printf '%s\n' "$l"; done
  } > "$r/$p"
}

# Вызов барьера: ставит rc и out. Без конвейера — `$?` конвейера лжёт о первой команде.
zapusk() {  # <аргументы барьера…>
  rc=0
  out="$("$BARRIER" "$@" 2>&1)" || rc=$?
}

zhdu_rc() {  # <ожидаемый rc> <что предъявляется>
  [ "$rc" -eq "$1" ] || {
    printf 'ОТКАЗ: %s — барьер вернул rc %s, ожидался %s. Вывод:\n%s\n' "$2" "$rc" "$1" "$out" >&2
    exit 1; }
}

zhdu_text() {  # <подстрока> <что предъявляется>
  printf '%s\n' "$out" | grep -Fq -- "$1" || {
    printf 'ОТКАЗ: %s — в выводе нет «%s». Вывод:\n%s\n' "$2" "$1" "$out" >&2
    exit 1; }
}

net_texta() {  # <подстрока> <что предъявляется>
  if printf '%s\n' "$out" | grep -Fq -- "$1"; then
    printf 'ОТКАЗ: %s — в выводе ЕСТЬ «%s», а его быть не должно. Вывод:\n%s\n' "$2" "$1" "$out" >&2
    exit 1
  fi
}
