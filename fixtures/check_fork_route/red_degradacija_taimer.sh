# Красное предъявление 7/7 семьи check_fork_route (контракт 029): ДЕГРАДАЦИЯ при
# недоступном консультанте (решение владельца Q5: ручная эскалация владельцу по таймеру
# ~30 мин; АВТО-подмена модели — только после механизма Н-50, в этом контракте не-цель).
#
# Деградация — СИГНАЛ, а не отказ: rc остаётся 0, барьер печатает именованную строку
# «ДЕГРАДАЦИЯ: <предмет>». Отказ здесь был бы вреден — он остановил бы конвейер ровно
# там, где владельцу нужно дать ход руками. Эскалация по деградации передаточной НЕ
# считается (маршрут записи — консультант, счётчик её не берёт).
#
# ВХОД / ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА:
#   1) ВЫЗВАН 35 минут назад, ответа консультанта нет → печать «ДЕГРАДАЦИЯ» с именем
#      предмета, rc 0 (инв. 7);
#   2) ВЫЗВАН 10 минут назад, ответа нет → строки нет (таймер не истёк) — ловец
#      преждевременной эскалации, которая и есть боль Н-104 (инв. 7);
#   3) ВЫЗВАН 35 минут назад, ответ ЕСТЬ → строки нет (инв. 7);
#   4) запись без поля ВЫЗВАН (консультант ещё не звался) → строки нет, rc 0 (инв. 7:
#      таймер считает от ВЫЗОВА, не от заведения записи — иначе деградацией объявляется
#      всякий несделанный вызов);
#   5) счётчик не считает деградацию передаточной: `--schet` на входе 1 печатает
#      «передаточных 0» (инв. 5+7).
#
# СТАБ-ПРИВЯЗКИ (Н-39):
#   S-nodegr   — деградации нет вовсе: наблюдаем на входе 1 → ассерт 1;
#   S-always   — печатает деградацию для всякой консультантской записи: на входе 1
#                честен, наблюдаем на входах 2/3/4 → ассерты 2, 3, 4;
#   S-zavedjon — таймер считает от ЗАВЕДЁН, а не от ВЫЗВАН: наблюдаем на входе 4
#                (заведена 2 часа назад, не вызывалась) → ассерт 4;
#   S-fail     — деградация отдаётся ОТКАЗОМ rc 1: наблюдаем на входе 1 → ассерт 1 (rc);
#   S-degrbatch— записывает деградацию в передаточные: наблюдаем на входе 5 → ассерт 5.
# На текущем HEAD (барьера нет): rc 127 → ассерт 1.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_forks.sh"

# 1) таймер истёк, ответа нет.
R1="$WORK/g-prosrochen"; igrushka "$R1"
zapis "$R1" konsultant-molchit "КЛАСС: инженерный" "МАРШРУТ: консультант" \
      "ЗАВЕДЁН: $(iso_nazad 3000)" "ВЫЗВАН: $(iso_nazad 2100)"
zapusk --root "$R1"
zhdu_rc 0 'деградация — сигнал, а не отказ (инв. 7)'
zhdu_text 'ДЕГРАДАЦИЯ' 'просроченный вызов консультанта обязан дать сигнал эскалации (инв. 7)'
zhdu_text 'konsultant-molchit' 'сигнал обязан называть предмет (инв. 7)'

# 2) таймер не истёк.
R2="$WORK/g-svezhij"; igrushka "$R2"
zapis "$R2" vyzvan-nedavno "КЛАСС: инженерный" "МАРШРУТ: консультант" \
      "ЗАВЕДЁН: $(iso_nazad 900)" "ВЫЗВАН: $(iso_nazad 600)"
zapusk --root "$R2"
zhdu_rc 0 'свежий вызов — барьер обязан молчать'
net_texta 'ДЕГРАДАЦИЯ' 'эскалация до истечения таймера — та самая боль Н-104 (инв. 7)'

# 3) ответ пришёл.
R3="$WORK/g-otvechen"; igrushka "$R3"
zapis "$R3" otvet-est "КЛАСС: инженерный" "МАРШРУТ: консультант" \
      "ЗАВЕДЁН: $(iso_nazad 3000)" "ВЫЗВАН: $(iso_nazad 2100)"
otvet "$R3" verdicts/consultant/otvet-est-v1.md anthropic/claude-fable-5 'РЕКОМЕНДАЦИЯ: вариант б.'
zapusk --root "$R3"
zhdu_rc 0 'отвеченный вызов — барьер обязан молчать'
net_texta 'ДЕГРАДАЦИЯ' 'ответ получен, деградации нет (инв. 7)'

# 4) консультант ещё не вызывался.
R4="$WORK/g-ne-vyzyvalsja"; igrushka "$R4"
zapis "$R4" ochered-vyzova "КЛАСС: инженерный" "МАРШРУТ: консультант" "ЗАВЕДЁН: $(iso_nazad 7200)"
zapusk --root "$R4"
zhdu_rc 0 'невызванный консультант — не деградация'
net_texta 'ДЕГРАДАЦИЯ' 'таймер обязан считать от ВЫЗВАН, а не от ЗАВЕДЁН (инв. 7)'

# 5) деградация не попадает в счёт передаточных.
zapusk --root "$R1" --schet
zhdu_rc 0 'счёт на журнале с деградацией'
zhdu_text 'передаточных 0' 'деградация не есть передаточное касание (инв. 5+7)'
