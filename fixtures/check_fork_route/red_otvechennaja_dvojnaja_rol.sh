# Красное предъявление 051, инвариант 1 (суд 4а): ЗАКРЫТАЯ двойная роль не красит
# обычный режим. Решение владельца 2026-09-27 — фильтр `ОТВЕЧЕНО: да` ТОЛЬКО в циклах
# судов 4а/4в обычного режима. Суд 4а «двойная роль» (инв. 6 контракта 029) применяется
# ТОЛЬКО к открытым записям; закрытая запись не красит rc обычного режима.
#
# Граница от уже существующих проб:
#   - `red_zapret_dvojnoj_roli.sh` (контракт 029, инв. 6) судит ОТКРЫТУЮ двойную роль
#     (поле ОТВЕЧЕНО отсутствует) на РАЗНЫХ предметах/моделях. Здесь — ЗАКРЫТАЯ
#     двойная роль с одинаковой моделью; пробел между ними закрывает 051;
#   - `red_marshrut_a_inzhenernyj.sh` вход 4 — инженерный, уведённый в СОревью.
#     Здесь — инженерный по МАРШРУТУ консультант с одинаковой МОДЕЛЬ в обеих ролях
#     и явным `ОТВЕЧЕНО: да`.
#
# ВХОД / ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА:
#   1) закрытая двойная роль (`ci-dual`: КЛАСС инженерный + МАРШРУТ консультант +
#      `ОТВЕЧЕНО: да` + verdict-файлы consultant/arbitration с одинаковой МОДЕЛЬ
#      anthropic/claude-fable-5) → rc 0: суд 4а обходит запись (фильтр 4а);
#   2) положительный контроль — та же запись БЕЗ `ОТВЕЧЕНО` (default-open):
#      rc 1 «двойная роль на предмете ci-dual: модель …» (фильтр НЕ применяется к
#      открытой, поведение 029 сохранено).
#
# СТАБ-ПРИВЯЗКИ (Н-39, круг 2; пара для суда 4а):
#   S-4afilter — фильтр внесён только в 4в, суд 4а судит все записи (обход
#                Б2 критика круга 1): вход 1 даёт rc 1 «двойная роль на предмете
#                ci-dual» → краснеет ассертом 1 (вход 2 при стабе честен);
#   S-onlya4a  — фильтр внесён только в 4а, 4в судит закрытые записи: вход 1 честен
#                (rc 0), наблюдаем ТОЛЬКО на red_otvechennaja_peredatochnaja ассерт 1.
# На текущем HEAD без фикса: вход 1 rc=1 → ассерт 1.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_forks.sh"

FABLE=anthropic/claude-fable-5

# 1) закрытая двойная роль — суд 4а обходит, rc 0.
R1="$WORK/d-zakrytaja-dvojnaja"; igrushka "$R1"
zapis "$R1" ci-dual "КЛАСС: инженерный" "МАРШРУТ: консультант" "ОТВЕЧЕНО: да" \
      "ЗАВЕДЁН: $(iso_nazad 3600)" "ВЫЗВАН: $(iso_nazad 3500)"
otvet "$R1" verdicts/consultant/ci-dual-v1.md   "$FABLE" 'РЕКОМЕНДАЦИЯ: поднять порог до 3.'
otvet "$R1" verdicts/arbitration/ci-dual-v1.md  "$FABLE" 'РЕШЕНИЕ: порог 3.'
zapusk --root "$R1"
zhdu_rc 0 'закрытая двойная роль не красит обычный режим (инв. 1, фильтр 4а)'

# 2) положительный контроль: та же запись открытая (default-open, поле ОТВЕЧЕНО отсутствует)
#    — барьер судит по 029: rc 1 «двойная роль на предмете ci-dual».
zapis "$R1" ci-dual "КЛАСС: инженерный" "МАРШРУТ: консультант" \
      "ЗАВЕДЁН: $(iso_nazad 3600)" "ВЫЗВАН: $(iso_nazad 3500)"
zapusk --root "$R1"
zhdu_rc 1 'открытая двойная роль ВСЁ ЕЩЁ красит обычный режим — поведение 029 сохранено'
zhdu_text 'двойная роль' 'отказ обязан называть класс нарушения (инв. 6 контракта 029)'
zhdu_text 'ci-dual' 'отказ обязан называть предмет'