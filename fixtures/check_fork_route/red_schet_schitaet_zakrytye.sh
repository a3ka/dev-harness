# Красное предъявление 051, инвариант 2/3: `--schet` СЧИТАЕТ ЗАКРЫТЫЕ записи.
# Слово владельца 2026-09-27 — `--schet` не фильтруется: «просмотрено N» — все файлы
# каталога forks/, «передаточных M» — все батч-записи без засвидетельствованной воли,
# независимо от ОТВЕЧЕНО. Числа фиксом не меняются: живое ДО «просмотрено 9 /
# передаточных 2», живое ПОСЛЕ — те же.
#
# Ловец стаба S-schetfilter (фильтр протёк в --schet, закрытые вычитаются из счёта):
# при таком стабе `--schet` на входе 1 напечатал бы «передаточных 0» — мера
# закрытия Н-104 выполнена, а владельца по-прежнему будят. Независимое основание
# (вторая подпись НЕТ) держит M=1.
#
# ВХОД / ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА:
#   1) `--schet` на ОДНОЙ закрытой передаточной (`ci-closed-schet`: КЛАСС инженерный +
#      МАРШРУТ батч + `ОТВЕЧЕНО: да` + НЕТ свидетельства) → rc 0, «просмотрено 1»,
#      «передаточных 1» (--schet считает закрытые);
#   2) `--schet` на смешанном каталоге (закрытая передаточная + закрытая
#      засвидетельствованная воля) → rc 0, «просмотрено 2», «передаточных 1»
#      (закрытая воля с независимой подписью вычитается, как и открытая).
#
# СТАБ-ПРИВЯЗКИ (Н-39):
#   S-schetfilter — фильтр протёк в --schet (закрытые вычитаются из счёта): вход 1
#                  даёт «передаточных 0» → краснеет ассертом 1 (вход 2 при стабе
#                  даёт «передаточных 0» — тоже краснеет, ассерт 2);
#   S-classonly   — --schet считает по самодекларации класса (воля-владельца без подписи
#                  вычитается): вход 1 честен, вход 2 даёт «передаточных 0» → краснеет
#                  ассертом 2.
# На текущем HEAD без фикса: rc 0, числа совпадают (--schet уже считает закрытые);
# стабы ловятся АССЕРТАМИ «передаточных 1» на входах 1 и 2.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_forks.sh"

# 1) одна закрытая передаточная — --schet обязан её посчитать.
R1="$WORK/s-zakrytaja-peredatochnaja"; igrushka "$R1"
zapis "$R1" ci-closed-schet "КЛАСС: инженерный" "МАРШРУТ: батч" "ОТВЕЧЕНО: да" \
      "ЗАВЕДЁН: $(iso_nazad 600)"
zapusk --root "$R1" --schet
zhdu_rc 0 '--schet на непустом каталоге'
zhdu_text 'просмотрено 1' '--schet считает ВСЕ файлы (инв. 2)'
zhdu_text 'передаточных 1' 'закрытая передаточная остаётся передаточной без подписи (инв. 2)'

# 2) смешанный каталог: закрытая передаточная + закрытая ЗАСВИДЕТЕЛЬСТВОВАННАЯ воля.
R2="$WORK/s-smeshannyj"; igrushka "$R2"
zapis "$R2" ci-closed-pered "КЛАСС: инженерный" "МАРШРУТ: батч" "ОТВЕЧЕНО: да" \
      "ЗАВЕДЁН: $(iso_nazad 600)"
volja "$R2" ci-closed-volja норма "ЗАВЕДЁН: $(iso_nazad 600)" "ОТВЕЧЕНО: да"
zapusk --root "$R2" --schet
zhdu_rc 0 '--schet на смешанном каталоге'
zhdu_text 'просмотрено 2' '--schet считает ВСЕ файлы, включая закрытые (инв. 2)'
zhdu_text 'передаточных 1' 'закрытая засвидетельствованная воля вычитается так же, как открытая (инв. 2)'