# Красное предъявление 4/7 контракта 029: ФЛАШ батч-очереди владельцу (решение владельца Q3
# дословно — «по блокировке ∨ N=3–4 накопленных ∨ возраст головы очереди ~2ч, что раньше»).
#
# Дизъюнкция из трёх условий предъявляется ПОКОМПОНЕНТНО: объединённый вход засчитался бы
# по первой сработавшей ветви и скрыл две остальные.
#
# ВХОД / ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА (`--flush` печатает решение, rc 0):
#   1) две свежие неблокирующие записи (10 и 2 минуты) → «ЖДЁМ», НЕ «ФЛАШ» (инв. 4);
#   2) третья такая же запись → «ФЛАШ» с причиной счёта (порог N=3, инв. 4);
#   3) ОДНА запись возрастом 2ч05м → «ФЛАШ» по возрасту головы (инв. 4);
#   4) ОДНА свежая запись с «БЛОКИРУЕТ: да» → «ФЛАШ» по блокировке (инв. 4);
#   5) отвеченные записи (ОТВЕЧЕНО: да) в очереди НЕ считаются: три отвеченных + одна
#      свежая → «ЖДЁМ» (инв. 4 — иначе очередь флашится собственной историей);
#   6) батч-запись БЕЗ поля ЗАВЕДЁН → rc 1 «батч-запись без времени» (возраст головы
#      неизмерим; пустая мера — красное, а не молчаливое «ждём»).
#
# СТАБ-ПРИВЯЗКИ (Н-39; стаб назван у того входа, где он НАБЛЮДАЕМ):
#   S-count     — только порог счёта: наблюдаем на входах 3 и 4 → ассерты 3, 4;
#   S-age       — только возраст: наблюдаем на входах 2 и 4 → ассерты 2, 4;
#   S-blockonly — только блокировка: наблюдаем на входах 2 и 3 → ассерты 2, 3;
#   S-always    — «всегда ФЛАШ»: наблюдаем на входах 1 и 5 → ассерты 1, 5;
#   S-all       — считает и отвеченные: наблюдаем только на входе 5 → ассерт 5.
# На текущем HEAD (барьера нет): rc 127 → ассерт 1.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_forks.sh"

volja() {  # <корень> <id> <секунд назад> [доп. поле…]
  local r="$1" id="$2" age="$3"
  shift 3
  zapis "$r" "$id" "КЛАСС: воля-владельца" "ПРИЗНАК: риск" "МАРШРУТ: батч" \
        "ЗАВЕДЁН: $(iso_nazad "$age")" "$@"
}

# 1) две свежие — ждём.
R1="$WORK/f-zhdjom"; igrushka "$R1"
volja "$R1" cena-tira 600
volja "$R1" norma-waiver 120
zapusk --root "$R1" --flush
zhdu_rc 0 'опрос флаша на здоровой очереди'
zhdu_text 'ЖДЁМ' 'две свежие неблокирующие записи — порог не достигнут (инв. 4)'
net_texta 'ФЛАШ' 'флаш при двух свежих записях — преждевременное касание владельца (инв. 4)'

# 2) три записи — порог счёта.
volja "$R1" prioritet-ocheredi 60
zapusk --root "$R1" --flush
zhdu_rc 0 'опрос флаша при трёх записях'
zhdu_text 'ФЛАШ' 'третья запись обязана дать флаш по счёту (инв. 4)'

# 3) одна старая голова — порог возраста.
R3="$WORK/f-vozrast"; igrushka "$R3"
volja "$R3" staraja-golova 7500
zapusk --root "$R3" --flush
zhdu_rc 0 'опрос флаша по возрасту головы'
zhdu_text 'ФЛАШ' 'голова очереди старше 2ч обязана дать флаш (инв. 4)'

# 4) одна свежая блокирующая.
R4="$WORK/f-blok"; igrushka "$R4"
volja "$R4" blokiruet-konvejer 60 "БЛОКИРУЕТ: да"
zapusk --root "$R4" --flush
zhdu_rc 0 'опрос флаша по блокировке'
zhdu_text 'ФЛАШ' 'блокирующая запись обязана дать флаш немедленно (инв. 4)'

# 5) отвеченные записи не наполняют очередь.
R5="$WORK/f-otvecheno"; igrushka "$R5"
volja "$R5" zakryt-1 9000 "ОТВЕЧЕНО: да"
volja "$R5" zakryt-2 9000 "ОТВЕЧЕНО: да"
volja "$R5" zakryt-3 9000 "ОТВЕЧЕНО: да"
volja "$R5" svezhij-vopros 60
zapusk --root "$R5" --flush
zhdu_rc 0 'опрос флаша при отвеченной истории'
zhdu_text 'ЖДЁМ' 'отвеченные записи не считаются очередью (инв. 4)'
net_texta 'ФЛАШ' 'очередь флашится собственной историей (инв. 4)'

# 6) батч-запись без времени — мера возраста невозможна.
R6="$WORK/f-bez-vremeni"; igrushka "$R6"
zapis "$R6" bez-zavedjon "КЛАСС: воля-владельца" "ПРИЗНАК: деньги" "МАРШРУТ: батч"
zapusk --root "$R6" --flush
zhdu_rc 1 'батч-запись без поля ЗАВЕДЁН — возраст головы неизмерим (инв. 4)'
zhdu_text 'bez-zavedjon' 'отказ обязан называть запись (инв. 4)'
