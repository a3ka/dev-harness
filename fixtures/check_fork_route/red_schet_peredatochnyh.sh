# Красное предъявление 5/7 контракта 029: СЧЁТЧИК ПЕРЕДАТОЧНЫХ КАСАНИЙ — механическая
# МЕРА ЗАКРЫТИЯ Н-104 (5 передаточных за сессию → цель 0–1). Пока число считает человек
# по трейсу, «стало лучше» есть мнение; мера обязана печататься командой.
#
# Передаточное касание = запись, адресованная владельцу (МАРШРУТ: батч), которая НЕ
# является ЗАСВИДЕТЕЛЬСТВОВАННОЙ волей владельца в смысле инв. 2: признак из закрытого
# перечня И вторая подпись (`verdicts/consultant/<id>-klass-v<N>.md` со строкой
# `ПОДТВЕРЖДЕНО: воля-владельца` от модели, отличной от АВТОР записи). Определение ОДНО
# с маршрутами (а)/(б), но здесь оно СЧИТАЕТСЯ, а не отвергается: счёт нужен и на
# грязном журнале, иначе мера доступна только на журнале, уже прошедшем барьер.
#
# ВХОД 1 — ре-инсценировка ИЗМЕРЕННОГО дня Н-104: восемь касаний, из них пять
# передаточных (минт номера, канал union-фикса, CI-waiver, РАЗРЕШИЛ-строки, ASCII-конвенция)
# и три по существу воли (метеринг а/б/в — деньги, продление waiver — риск, 028-v2 — норма).
#
# ВХОД 4 — ОБХОД, предъявленный критиком в круге 1: те же восемь записей, но пять
# передаточных ПЕРЕМАРКИРОВАНЫ в `КЛАСС: воля-владельца` с ЛЕГАЛЬНЫМИ признаками
# (норма/риск/приоритет) и остались в батче. Счётчик, считающий по САМОДЕКЛАРАЦИИ
# класса, напечатал бы «передаточных 0» — мера закрытия Н-104 выполнена, а владельца
# по-прежнему будят пять раз. Независимое основание (второй подписи НЕТ) держит M=5.
#
# ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА:
#   1) `--schet` на этом журнале → rc 0 и печать ОБОИХ чисел: «просмотрено 8»,
#      «передаточных 5» (инв. 5);
#   2) тот же журнал после маршрутизации пяти к консультанту → «просмотрено 8»,
#      «передаточных 0» — цель Н-104 наблюдаема той же командой (инв. 5);
#   3) ПУСТАЯ ВЫБОРКА — КРАСНОЕ: журнала нет вовсе → rc 1, печать «просмотрено 0»
#      (инв. 5: «нечего проверять» ≠ «проверено»; молчаливый ноль выдал бы
#      невключённый механизм за достигнутую цель);
#   4) ПЕРЕМАРКИРОВАННЫЙ день → rc 0, «просмотрено 8» и «передаточных 5»: легальная
#      перемаркировка меру НЕ обнуляет (инв. 5 через инв. 2).
#
# СТАБ-ПРИВЯЗКИ (Н-39):
#   S-zeroquiet — пустой журнал даёт rc 0 «передаточных 0»: наблюдаем ТОЛЬКО на входе 3
#                 → краснеет ассертом 3 (на входах 1/2/4 стаб честен);
#   S-allbatch  — считает передаточной ЛЮБУЮ батч-запись (воля не вычитается):
#                 наблюдаем на входе 1 (напечатал бы 8) → ассерт 1;
#   S-onlytotal — печатает одно число (просмотрено), второго нет: наблюдаем на входах
#                 1 и 2 → ассерты 1 и 2;
#   S-selfdecl  — вычитает волю по САМОДЕКЛАРАЦИИ класса и признака, второй подписи не
#                 требует: на входах 1–3 честен (там воля засвидетельствована, а признаки
#                 перечня законны), наблюдаем ТОЛЬКО на входе 4 (напечатал бы 0) →
#                 ассерт 4.
# На текущем HEAD (барьера нет): rc 127 → ассерт 1.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_forks.sh"

# Три касания ПО СУЩЕСТВУ воли — законный батч со второй подписью, в передаточные не входят.
tri_voli() {  # <корень>
  local r="$1"
  volja "$r" metering-abv     деньги "ЗАВЕДЁН: $(iso_nazad 20000)"
  volja "$r" waiver-prodlenie риск   "ЗАВЕДЁН: $(iso_nazad 18000)"
  volja "$r" put-respek-028   норма  "ЗАВЕДЁН: $(iso_nazad 16000)"
}

den_n104() {  # <корень> <маршрут для пяти передаточных>
  local r="$1" m="$2"
  igrushka "$r"
  # Пять передаточных дня (инженерные/формальные — воли владельца не требуют).
  zapis "$r" mint-028         "КЛАСС: инженерный" "МАРШРУТ: $m" "ЗАВЕДЁН: $(iso_nazad 30000)"
  zapis "$r" kanal-union-fiks "МАРШРУТ: $m"                      "ЗАВЕДЁН: $(iso_nazad 28000)"
  zapis "$r" ci-waiver-kritik "КЛАСС: инженерный" "МАРШРУТ: $m" "ЗАВЕДЁН: $(iso_nazad 26000)"
  zapis "$r" razreshil-026027 "КЛАСС: инженерный" "МАРШРУТ: $m" "ЗАВЕДЁН: $(iso_nazad 24000)"
  zapis "$r" ascii-vs-mini    "МАРШРУТ: $m"                      "ЗАВЕДЁН: $(iso_nazad 22000)"
  tri_voli "$r"
}

# Тот же день, но пять передаточных ПЕРЕМАРКИРОВАНЫ в волю владельца: класс и признак
# законны, маршрут батч законен, второй подписи НЕТ ни у одной из пяти.
den_peremarkirovannyj() {  # <корень>
  local r="$1" p
  igrushka "$r"
  for p in 'mint-028 приоритет 30000' 'kanal-union-fiks риск 28000' \
           'ci-waiver-kritik риск 26000' 'razreshil-026027 норма 24000' \
           'ascii-vs-mini норма 22000'; do
    # shellcheck disable=SC2086
    set -- $p
    zapis "$r" "$1" "КЛАСС: воля-владельца" "ПРИЗНАК: $2" "МАРШРУТ: батч" \
          "АВТОР: $AVTOR_ZAPISI" "ЗАВЕДЁН: $(iso_nazad "$3")"
  done
  tri_voli "$r"
}

# 1) измеренный день: 8 касаний, 5 передаточных.
R1="$WORK/s-den-izmerennyj"; den_n104 "$R1" батч
zapusk --root "$R1" --schet
zhdu_rc 0 'счёт на непустом журнале'
zhdu_text 'просмотрено 8' 'счётчик обязан печатать число просмотренного (инв. 5)'
zhdu_text 'передаточных 5' 'счётчик обязан печатать число передаточных касаний (инв. 5)'

# 2) тот же день после маршрутизации: цель Н-104 наблюдаема.
R2="$WORK/s-den-posle"; den_n104 "$R2" консультант
zapusk --root "$R2" --schet
zhdu_rc 0 'счёт после маршрутизации к консультанту'
zhdu_text 'просмотрено 8' 'счётчик обязан печатать число просмотренного (инв. 5)'
zhdu_text 'передаточных 0' 'после маршрутизации передаточных не остаётся (инв. 5)'

# 3) пустая выборка — красное.
R3="$WORK/s-pusto"; mkdir -p "$R3"
zapusk --root "$R3" --schet
zhdu_rc 1 'пустая выборка обязана быть КРАСНОЙ, а не молчаливым нулём (инв. 5)'
zhdu_text 'просмотрено 0' 'отказ обязан называть число просмотренного (инв. 5)'

# 4) ЛЕГАЛЬНАЯ ПЕРЕМАРКИРОВКА: мера не обнуляется сменой класса без второй подписи.
R4="$WORK/s-den-peremarkirovannyj"; den_peremarkirovannyj "$R4"
zapusk --root "$R4" --schet
zhdu_rc 0 'счёт на перемаркированном журнале'
zhdu_text 'просмотрено 8' 'счётчик обязан печатать число просмотренного (инв. 5)'
