# ПРИЧИНА: грамматика записи
#
# 051, клетка владельца 3: закрытая запись с битой грамматикой → rc 1
# (инвариант 2: грамматика судит ВСЕ записи, закрытость не лазейка). Зелёный
# контроль — конформная закрытая запись по маршруту (а). Красное — закрытая
# запись с не-ISO `ЗАВЕДЁН`: барьер обязан назвать «грамматика записи».
set -euo pipefail

WORK="${WORK:-$(mktemp -d "${TMPDIR:-/tmp}/v051-case.XXXXXX")}"
ROOT="$WORK/root"
mkdir -p "$ROOT/forks"

NOW="$(date -u +%s)"
iso_nazad() { date -u -d "@$(( NOW - $1 ))" +%Y-%m-%dT%H:%M:%SZ; }

zapis() {
  local id="$1"; shift
  {
    printf 'ФОРК: %s\n' "$id"
    printf 'ВОПРОС: подставной вопрос предмета %s\n' "$id"
    for f in "$@"; do printf '%s\n' "$f"; done
  } > "$ROOT/forks/$id.md"
}

# Зелёный контроль: конформная закрытая запись по маршруту (а).
zapis ci-closed-ok "КЛАСС: инженерный" "МАРШРУТ: консультант" \
      "ЗАВЕДЁН: $(iso_nazad 600)" "ОТВЕЧЕНО: да"

"$BARRIER" --root "$ROOT"

# Красное: закрытая запись с не-ISO ЗАВЕДЁН → rc 1 «грамматика записи».
zapis ci-closed-bad "КЛАСС: инженерный" "МАРШРУТ: консультант" \
      "ЗАВЕДЁН: 18-09-2026 not-ISO" "ОТВЕЧЕНО: да"

"$BARRIER" --root "$ROOT"