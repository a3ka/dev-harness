# Красное предъявление 051, инвариант 1 (суд 4в): ЗАКРЫТАЯ передаточная запись НЕ красит
# обычный режим. Решение владельца 2026-09-27 — фильтр `ОТВЕЧЕНО: да` ТОЛЬКО в циклах судов
# 4а/4в обычного режима; грамматика секции 0 судит все записи без разделения.
#
# Демаркация от уже существующих проб:
#   - `red_marshrut_a_inzhenernyj.sh` (вход 2) судит ИНЖЕНЕРНЫЙ+БАТЧ → «передаточное
#     касание»; запись там БЕЗ поля ОТВЕЧЕНО (default-open по контракту 029), а здесь —
#     закрытая запись с явным `ОТВЕЧЕНО: да`. Граница: default-open (поле отсутствует)
#     НЕ закрывает, явное «да» — закрывает. Этот пробел закрывает 051;
#   - `red_flush_batcha.sh` уже использует `ОТВЕЧЕНО: да` для СКИПА очереди `--flush`
#     (строки 235/255 барьера) — здесь применяется та же логика в судах 4а/4в обычного
#     режима. Граница: --flush не меняется (инв. 4), меняются только суды 4а/4в.
#
# ВХОД / ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА:
#   1) закрытая передаточная (`ci-closed`: КЛАСС инженерный + МАРШРУТ батч +
#      `ОТВЕЧЕНО: да` + валидный ISO ЗАВЕДЁН) → rc 0: суд 4в обходит запись
#      (инв. 1, фильтр 4в);
#   2) закрытая запись с битой грамматикой (`ci-closed-bad`: `ОТВЕЧЕНО: да` +
#      не-ISO ЗАВЕДЁН) → rc 1, отказ называет «грамматика записи»: грамматика
#      секции 0 судит ВСЕ записи без разделения (инв. 2);
#   3) положительный контроль — та же запись открытая (`ci-closed`: `ОТВЕЧЕНО: нет`):
#      rc 1, отказ называет «передаточное касание» И имя записи (фильтр 4в НЕ
#      применяется к открытой — поведение 029 сохранено).
#
# СТАБ-ПРИВЯЗКИ (Н-39: стаб назван у того входа, где он НАБЛЮДАЕМ):
#   S-nofilter     — фикс не внесён/откат (фильтр отсутствует, суд судит закрытые записи):
#                    вход 1 даёт rc 1 → краснеет ассертом 1 (входы 2/3 при стабе честны);
#   S-grammarscope — грамматика секции 0 скипает закрытые под предлогом фильтра: вход 2
#                    даёт rc 0 → краснеет ассертом 2 (входы 1/3 при стабе честны).
# На текущем HEAD без фикса: вход 1 rc=1 → ассерт 1.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_forks.sh"

# 1) закрытая передаточная — суд 4в обходит, rc 0.
R1="$WORK/p-zakrytaja"; igrushka "$R1"
zapis "$R1" ci-closed "КЛАСС: инженерный" "МАРШРУТ: батч" "ОТВЕЧЕНО: да" \
      "ЗАВЕДЁН: $(iso_nazad 600)"
zapusk --root "$R1"
zhdu_rc 0 'закрытая передаточная не красит обычный режим (инв. 1, фильтр 4в)'

# 2) закрытая запись с битой грамматикой — секция 0 судит и закрытые, rc 1.
zapis "$R1" ci-closed-bad "КЛАСС: инженерный" "МАРШРУТ: консультант" "ОТВЕЧЕНО: да" \
      "ЗАВЕДЁН: 18-09-2026 not-ISO"
zapusk --root "$R1"
zhdu_rc 1 'закрытая запись с не-ISO ЗАВЕДЁН всё равно судится грамматикой (инв. 2)'
zhdu_text 'грамматика записи' 'отказ обязан называть «грамматика записи» (инв. 2)'

# 3) положительный контроль: та же запись открытая — убираем битый файл и пишем открытую.
rm -f "$R1/forks/ci-closed-bad.md"
zapis "$R1" ci-closed "КЛАСС: инженерный" "МАРШРУТ: батч" "ОТВЕЧЕНО: нет" \
      "ЗАВЕДЁН: $(iso_nazad 600)"
zapusk --root "$R1"
zhdu_rc 1 'открытая передаточная красит обычный режим — поведение 029 сохранено'
zhdu_text 'передаточное касание' 'отказ обязан быть ПОИМЁННЫМ (инв. 1 контракта 029)'
zhdu_text 'ci-closed' 'отказ обязан называть запись'