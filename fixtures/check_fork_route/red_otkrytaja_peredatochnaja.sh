# Красное предъявление 051, инвариант 1 (суд 4в): ОТКРЫТАЯ передаточная запись ВСЁ ЕЩЁ
# красит обычный режим. Слово владельца 2026-09-27 — фильтр «ОТВЕЧЕНО: да» только в
# судах 4а/4в, открытые записи судятся по-старому. Это ловец стаба S-overfilter
# (фильтр глушит и открытые: скипает любую запись с полем ОТВЕЧЕНО либо инвертирует
# да/нет) — при таком стабе вход 1 пройдёт зелёным, и ассерт 1 краснеет.
#
# Граница от других проб семьи:
#   - `red_marshrut_a_inzhenernyj.sh` вход 2 — открытая передаточная по default-open
#     (поле ОТВЕЧЕНО отсутствует). Здесь поле `ОТВЕЧЕНО: нет` присутствует ЯВНО —
#     стаб, различающий «нет поля» и «явное нет», обязан проявиться;
#   - `red_otvechennaja_peredatochnaja.sh` вход 2 — та же запись открытая, здесь это
#     её «положительный контроль». На стабе S-overfilter обе пробы зелены, но здесь
#     клетка красна по АССЕРТУ 1 (фильтр глушит и явное «нет»).
#
# ВХОД / ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА:
#   1) открытая передаточная с явным `ОТВЕЧЕНО: нет` (`ci-open`): rc 1, отказ
#      называет «передаточное касание» И имя записи (фильтр не глушит открытые);
#   2) положительный контроль — запись по маршруту (а): rc 0.
#
# СТАБ-ПРИВЯЗКИ (Н-39):
#   S-overfilter — фильтр глушит и открытые (скипает любую запись с полем ОТВЕЧЕНО
#                 либо инвертирует да/нет): вход 1 даёт rc 0 → краснеет ассертом 1
#                 (вход 2 при стабе честен);
#   S-notneg     — фильтр пропускает только записи БЕЗ поля ОТВЕЧЕНО, явное «нет»
#                 обрабатывается как «да»: вход 1 даёт rc 0 → краснеет ассертом 1.
# На текущем HEAD без фикса: вход 1 rc=1 → ассерт 1 честен (стабы ловятся этим
# ассертом только на фиксе, и это — предмет приёмки).
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_forks.sh"

# 1) открытая передаточная с явным `ОТВЕЧЕНО: нет` — суд 4в судит, rc 1.
R1="$WORK/p-otkrytaja"; igrushka "$R1"
zapis "$R1" ci-open "КЛАСС: инженерный" "МАРШРУТ: батч" "ОТВЕЧЕНО: нет" \
      "ЗАВЕДЁН: $(iso_nazad 600)"
zapusk --root "$R1"
zhdu_rc 1 'открытая передаточная с явным `ОТВЕЧЕНО: нет` обязана красить (инв. 1)'
zhdu_text 'передаточное касание' 'отказ обязан быть ПОИМЁННЫМ (инв. 1 контракта 029)'
zhdu_text 'ci-open' 'отказ обязан называть запись'

# 2) положительный контроль: та же запись по маршруту (а).
zapis "$R1" ci-open "КЛАСС: инженерный" "МАРШРУТ: консультант" "ОТВЕЧЕНО: нет" \
      "ЗАВЕДЁН: $(iso_nazad 600)"
zapusk --root "$R1"
zhdu_rc 0 'конформная открытая запись по маршруту (а) — барьер обязан молчать'