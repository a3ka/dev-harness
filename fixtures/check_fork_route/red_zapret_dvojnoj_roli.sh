# Красное предъявление 6/7 контракта 029: ЗАПРЕТ ДВОЙНОЙ РОЛИ консультант/арбитр НА ОДНОМ
# ПРЕДМЕТЕ (решение владельца Q4: запрет ПРОЦЕДУРНЫЙ, не модельный — fable годится как
# модель обеих ролей, но не как роль в одном и том же споре).
#
# Наблюдаемость запрета: оба артефакта несут строку МОДЕЛЬ. Совпадение моделей на ОДНОМ
# предмете = один и тот же голос сначала советует, потом судит свой же совет — арбитраж
# вырождается в самоподтверждение. Реестр даёт выход: тир plan несёт фолбек
# anthropic/claude-opus-5, консультант — anthropic/claude-fable-5.
#
# ВХОД / ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА:
#   1) консультация и арбитраж по одному предмету, обе МОДЕЛЬ: anthropic/claude-fable-5 →
#      rc 1, отказ называет «двойная роль», предмет и модель (инв. 6);
#   2) тот же предмет, арбитраж на anthropic/claude-opus-5 → rc 0 (позитивный контроль:
#      запрет процедурный, не запрет модели как таковой);
#   3) арбитраж БЕЗ строки МОДЕЛЬ → rc 1 «ответ без строки МОДЕЛЬ» (различить нечем;
#      пустая мера — красное, а не зелёное);
#   4) fable и там, и там, но на РАЗНЫХ предметах → rc 0 (запрет привязан к предмету —
#      иначе консультант выключается из работы целиком).
#
# СТАБ-ПРИВЯЗКИ (Н-39):
#   S-modelban  — запрещает fable в арбитраже ВСЕГДА (модельный запрет вместо
#                 процедурного): на входе 1 честен, наблюдаем на входе 4 → ассерт 4;
#   S-nomodel   — не требует строки МОДЕЛЬ, сверяя только наличие файлов: наблюдаем на
#                 входе 3 → ассерт 3;
#   S-nevercheck— сверки нет вовсе: наблюдаем на входе 1 → ассерт 1;
#   S-allred    — тотальный отказ: наблюдаем на входах 2 и 4 → ассерты 2 и 4.
# На текущем HEAD (барьера нет): rc 127 → ассерт 1.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_forks.sh"

FABLE=anthropic/claude-fable-5
OPUS=anthropic/claude-opus-5

spor() {  # <корень> <id>
  local r="$1" id="$2"
  igrushka "$r"
  zapis "$r" "$id" "КЛАСС: инженерный" "МАРШРУТ: консультант" "ЗАВЕДЁН: $(iso_nazad 3600)" \
        "ВЫЗВАН: $(iso_nazad 3500)"
}

# 1) один предмет, один голос в двух ролях.
R1="$WORK/d-dvojnaja"; spor "$R1" porog-gejta
otvet "$R1" verdicts/consultant/porog-gejta-v1.md   "$FABLE" 'РЕКОМЕНДАЦИЯ: поднять порог до 3.'
otvet "$R1" verdicts/arbitration/porog-gejta-v1.md  "$FABLE" 'РЕШЕНИЕ: порог 3.'
zapusk --root "$R1"
zhdu_rc 1 'один голос советует и судит свой совет (инв. 6)'
zhdu_text 'двойная роль' 'отказ обязан называть класс нарушения (инв. 6)'
zhdu_text 'porog-gejta' 'отказ обязан называть предмет (инв. 6)'
zhdu_text "$FABLE" 'отказ обязан называть совпавшую модель (инв. 6)'

# 2) позитивный контроль: арбитр ушёл на другую модель.
otvet "$R1" verdicts/arbitration/porog-gejta-v1.md "$OPUS" 'РЕШЕНИЕ: порог 3.'
zapusk --root "$R1"
zhdu_rc 0 'разные модели в двух ролях — законно (инв. 6)'

# 3) арбитраж без строки МОДЕЛЬ — различить нечем.
otvet "$R1" verdicts/arbitration/porog-gejta-v1.md '-' 'РЕШЕНИЕ: порог 3.'
zapusk --root "$R1"
zhdu_rc 1 'артефакт без строки МОДЕЛЬ — запрет ненаблюдаем (инв. 6)'
zhdu_text 'МОДЕЛЬ' 'отказ обязан называть отсутствующее поле (инв. 6)'

# 4) одна модель, но РАЗНЫЕ предметы.
R4="$WORK/d-raznye-predmety"; spor "$R4" predmet-odin
zapis "$R4" predmet-dva "КЛАСС: инженерный" "МАРШРУТ: консультант" "ЗАВЕДЁН: $(iso_nazad 3600)" \
      "ВЫЗВАН: $(iso_nazad 3500)"
otvet "$R4" verdicts/consultant/predmet-odin-v1.md  "$FABLE" 'РЕКОМЕНДАЦИЯ: вариант б.'
otvet "$R4" verdicts/arbitration/predmet-dva-v1.md  "$FABLE" 'РЕШЕНИЕ: вариант а.'
zapusk --root "$R4"
zhdu_rc 0 'одна модель на РАЗНЫХ предметах — запрет привязан к предмету (инв. 6)'
