# Красное предъявление 2/7 контракта 029: МАРШРУТ (б) — зона воли владельца → БАТЧ-ОЧЕРЕДЬ.
#
# Маршрут (б) — единственный, где касание владельца законно, поэтому исключение стоит на
# ДВУХ подписях: `КЛАСС: воля-владельца` обязан нести ПРИЗНАК из {деньги, риск, норма,
# приоритет} И НЕЗАВИСИМОЕ ОСНОВАНИЕ — свидетельство роли, НЕ являющейся автором записи
# (`verdicts/consultant/<id>-klass-v<N>.md`: строка МОДЕЛЬ + самостоятельная строка
# `ПОДТВЕРЖДЕНО: воля-владельца`), причём МОДЕЛЬ свидетеля ≠ АВТОР записи.
#
# ПОЧЕМУ перечня признаков НЕДОСТАТОЧНО (обход, предъявленный критиком в круге 1):
# закрытый перечень ловит ЧУЖОЙ токен и НЕ ловит ЛЕГАЛЬНЫЙ. Инженерный форк маркируется
# `КЛАСС: воля-владельца` + `ПРИЗНАК: норма` — признак законен, маршрут батч законен,
# и барьер по самодекларации молчит, хотя владельца по-прежнему будят. Вход 5 ниже —
# ровно эта перемаркировка; она обязана быть rc 1 БЕЗ суждения о смысле вопроса, по
# отсутствию второй подписи.
#
# ВХОД / ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА:
#   1) воля-владельца + ПРИЗНАК: деньги/норма + АВТОР + свидетельство ДРУГОЙ модели →
#      rc 0 (позитивный контроль: засвидетельствованная воля законна);
#   2) воля-владельца + ПРИЗНАК: инженерно-очевидно (ВНЕ перечня) → rc 1, отказ называет
#      «признак вне перечня» и запись (инв. 2) — ловец грубой маскировки;
#   3) воля-владельца БЕЗ поля ПРИЗНАК → rc 1 «воля владельца без признака» (инв. 2);
#   4) воля-владельца + МАРШРУТ: консультант → rc 1 «воля владельца вне батча» (инв. 2:
#      волю нельзя отдать консультанту — это не инженерный вопрос);
#   5) ПЕРЕМАРКИРОВКА: легальный ПРИЗНАК: норма, АВТОР на месте, свидетельства НЕТ →
#      rc 1 «без подтверждения класса» + имя записи (инв. 2);
#   6) свидетельство ЕСТЬ, но его МОДЕЛЬ равна АВТОР записи (автор подписал себя сам) →
#      rc 1 «самоподтверждение класса» + имя записи (инв. 2);
#   7) свидетельство ЕСТЬ, от другой модели, но БЕЗ строки «ПОДТВЕРЖДЕНО: воля-владельца»
#      (свидетель ОТКЛОНИЛ класс) → rc 1 «класс не подтверждён» + имя записи (инв. 2);
#   8) воля-владельца со свидетельством, но БЕЗ поля АВТОР → rc 1 «воля без автора»
#      (инв. 2: подпись неизмерима, немеримая мера красная, а не молчаливая).
#
# СТАБ-ПРИВЯЗКИ (Н-39; каждый стаб назван у входа, где его дефект НАБЛЮДАЕМ):
#   S-openlist  — ПРИЗНАК принимается любой непустой строкой: вход 3 (поля нет) честен,
#                 наблюдаем ТОЛЬКО на входе 2 → краснеет ассертом 2;
#   S-presence  — проверяется лишь НАЛИЧИЕ поля ПРИЗНАК: наблюдаем на входе 2 → тот же
#                 ассерт 2; на входе 3 стаб честен;
#   S-classonly — КЛАСС не сверяется с МАРШРУТом: наблюдаем на входе 4 → ассерт 4;
#   S-selfdecl  — вторая подпись не требуется вовсе (старая редакция инв. 2): входы 1–4
#                 честны, наблюдаем ТОЛЬКО на входе 5 → ассерт 5;
#   S-filethere — засчитывает ЛЮБОЙ файл свидетельства: на входах 1–5 честен, наблюдаем
#                 на входе 6 (модель не сверяется с автором) и на входе 7 (строка
#                 подтверждения не читается) → ассерты 6 и 7;
#   S-modelonly — сверяет МОДЕЛЬ≠АВТОР, но строку подтверждения не читает: на входе 6
#                 честен, наблюдаем ТОЛЬКО на входе 7 → ассерт 7;
#   S-noauthor  — поле АВТОР не требует (сверку молча пропускает при его отсутствии):
#                 наблюдаем ТОЛЬКО на входе 8 → ассерт 8;
#   S-allred    — тотальный отказ: наблюдаем на входе 1 → ассерт 1.
# На текущем HEAD (барьера нет): rc 127 → ассерт 1.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_forks.sh"

# 1) позитивный контроль — законная ЗАСВИДЕТЕЛЬСТВОВАННАЯ воля владельца в батче.
R1="$WORK/b-ok"; igrushka "$R1"
volja "$R1" metering-cena деньги "ЗАВЕДЁН: $(iso_nazad 300)"
volja "$R1" oslablenie-gejta норма "ЗАВЕДЁН: $(iso_nazad 120)"
zapusk --root "$R1"
zhdu_rc 0 'законная воля владельца в батче — барьер обязан молчать (инв. 2)'

# 2) признак вне закрытого перечня — грубая маскировка инженерного форка под волю.
R2="$WORK/b-chuzhoj-priznak"; igrushka "$R2"
volja "$R2" ci-waiver-prodlenie инженерно-очевидно "ЗАВЕДЁН: $(iso_nazad 300)"
zapusk --root "$R2"
zhdu_rc 1 'признак вне перечня {деньги,риск,норма,приоритет} (инв. 2)'
zhdu_text 'ci-waiver-prodlenie' 'отказ обязан называть запись (инв. 2)'
zhdu_text 'признак' 'отказ обязан называть класс нарушения (инв. 2)'

# 3) воля владельца без признака вовсе.
R3="$WORK/b-bez-priznaka"; igrushka "$R3"
zapis "$R3" razreshil-stroka "КЛАСС: воля-владельца" "МАРШРУТ: батч" \
      "АВТОР: $AVTOR_ZAPISI" "ЗАВЕДЁН: $(iso_nazad 300)"
svidetelstvo "$R3" razreshil-stroka
zapusk --root "$R3"
zhdu_rc 1 'воля владельца без признака (инв. 2)'
zhdu_text 'razreshil-stroka' 'отказ обязан называть запись (инв. 2)'

# 4) воля владельца, уведённая консультанту.
R4="$WORK/b-v-konsultanta"; igrushka "$R4"
zapis "$R4" cena-apex-tira "КЛАСС: воля-владельца" "ПРИЗНАК: деньги" "МАРШРУТ: консультант" \
      "АВТОР: $AVTOR_ZAPISI" "ЗАВЕДЁН: $(iso_nazad 300)"
svidetelstvo "$R4" cena-apex-tira
zapusk --root "$R4"
zhdu_rc 1 'воля владельца отдана консультанту (инв. 2)'
zhdu_text 'cena-apex-tira' 'отказ обязан называть запись (инв. 2)'

# 5) ПЕРЕМАРКИРОВКА С ЛЕГАЛЬНЫМ ПРИЗНАКОМ — обход круга 1: инженерная конвенция объявлена
#    нормой. Токены все законны; незаконно ОТСУТСТВИЕ независимого основания.
R5="$WORK/b-peremarkirovka"; igrushka "$R5"
zapis "$R5" ascii-vs-mini "КЛАСС: воля-владельца" "ПРИЗНАК: норма" "МАРШРУТ: батч" \
      "АВТОР: $AVTOR_ZAPISI" "ЗАВЕДЁН: $(iso_nazad 300)"
zapusk --root "$R5"
zhdu_rc 1 'инженерный форк перемаркирован в волю с ЛЕГАЛЬНЫМ признаком и без второй подписи (инв. 2)'
zhdu_text 'ascii-vs-mini' 'отказ обязан называть запись (инв. 2)'
zhdu_text 'без подтверждения класса' 'отказ обязан называть класс нарушения (инв. 2)'

# 6) самоподтверждение: свидетельство подписано ТОЙ ЖЕ моделью, что завела запись.
R6="$WORK/b-samopodtverzhdenie"; igrushka "$R6"
zapis "$R6" razreshil-026027 "КЛАСС: воля-владельца" "ПРИЗНАК: норма" "МАРШРУТ: батч" \
      "АВТОР: $AVTOR_ZAPISI" "ЗАВЕДЁН: $(iso_nazad 300)"
svidetelstvo "$R6" razreshil-026027 "$AVTOR_ZAPISI"
zapusk --root "$R6"
zhdu_rc 1 'автор записи подписал исключение сам — основание не независимо (инв. 2)'
zhdu_text 'razreshil-026027' 'отказ обязан называть запись (инв. 2)'
zhdu_text 'самоподтверждение класса' 'отказ обязан называть класс нарушения (инв. 2)'

# 7) свидетель ОТКЛОНИЛ класс, а запись всё равно маркирована волей.
R7="$WORK/b-otklonjon"; igrushka "$R7"
zapis "$R7" kanal-union-fiks "КЛАСС: воля-владельца" "ПРИЗНАК: риск" "МАРШРУТ: батч" \
      "АВТОР: $AVTOR_ZAPISI" "ЗАВЕДЁН: $(iso_nazad 300)"
svidetelstvo "$R7" kanal-union-fiks "$SVIDETEL" 'ОТКЛОНЕНО: вопрос инженерный, решает консультант'
zapusk --root "$R7"
zhdu_rc 1 'свидетель класс не подтвердил, а запись маркирована волей (инв. 2)'
zhdu_text 'kanal-union-fiks' 'отказ обязан называть запись (инв. 2)'
zhdu_text 'класс не подтверждён' 'отказ обязан называть класс нарушения (инв. 2)'

# 8) воля со свидетельством, но автор записи не назван — сверить подписи нечем.
R8="$WORK/b-bez-avtora"; igrushka "$R8"
zapis "$R8" mint-028 "КЛАСС: воля-владельца" "ПРИЗНАК: приоритет" "МАРШРУТ: батч" \
      "ЗАВЕДЁН: $(iso_nazad 300)"
svidetelstvo "$R8" mint-028
zapusk --root "$R8"
zhdu_rc 1 'воля без поля АВТОР — независимость подписи неизмерима (инв. 2)'
zhdu_text 'mint-028' 'отказ обязан называть запись (инв. 2)'
zhdu_text 'воля без автора' 'отказ обязан называть класс нарушения (инв. 2)'
