# Красное предъявление 3/7 контракта 029: МАРШРУТ (в) — ВЫСОКОСТАВОЧНЫЙ дизайн-выбор →
# дизайн-СОревью архитектора (РАСШИРЕНИЕ Н-104 от 2026-09-18, слово владельца Q1).
#
# Три названные владельцем пробы расширения оформлены здесь как входы, а не проза:
#   (I)   СОревью ВЫЗЫВАЕТСЯ на высокоставочном (признак из закрытого перечня);
#   (II)  СОревью МОЛЧИТ на рутине — ловец over-триггера (цена: вызов сильной модели);
#   (III) выход СОревью — ПРЕДЛОЖЕНИЯ, не вердикт-гейт, и он ДО круга критика.
#
# ВХОД / ПОВЕДЕНИЕ ПОСЛЕ ПРЕДМЕТА:
#   1) КЛАСС: дизайн, ПРИЗНАК: новый-механизм, МАРШРУТ: со-ревью, файла СОревью НЕТ →
#      rc 1 «СОревью не вызван» + имя записи (инв. 3-I);
#   2) тот же вход + verdicts/consultant/<id>-soreview-v1.md с предложениями → rc 0
#      (позитивный контроль I);
#   3) КЛАСС: дизайн, ПРИЗНАК: рутина, МАРШРУТ: со-ревью → rc 1 «СОревью на рутине»
#      (инв. 3-II, ловец over-триггера); та же рутина с МАРШРУТ: свой → rc 0;
#   4) высокоставочный с СОревью, чей файл содержит САМОСТОЯТЕЛЬНУЮ строку `accept` →
#      rc 1 «СОревью вынес вердикт» (инв. 3-III: гейтит критик, СОревью не подменяет);
#   5) высокоставочный, где вердикт критика СТАРШЕ файла СОревью (mtime) → rc 1
#      «СОревью после критика» (инв. 3-III: один обзор ДО круга критика);
#   6) два файла СОревью на один предмет → rc 1 «второй СОревью» (инв. 3-I: ОДИН обзор).
#
# СТАБ-ПРИВЯЗКИ (Н-39; каждый стаб назван у входа, где его дефект НАБЛЮДАЕМ):
#   S-always   — СОревью требуется на ЛЮБОМ дизайне (перечень признаков игнорируется):
#                на входах 1/2 честен, наблюдаем на входе 3 → краснеет ассертом 3;
#   S-presence — засчитывает ЛЮБОЙ файл СОревью, не читая его содержимое: наблюдаем
#                только на входе 4 → краснеет ассертом 4;
#   S-nosort   — не сверяет порядок с кругом критика: наблюдаем на входе 5 → ассерт 5;
#   S-atleast1 — «хотя бы один» вместо «ровно один»: наблюдаем на входе 6 → ассерт 6;
#   S-allred   — тотальный отказ: наблюдаем на входах 2/3-свой → ассерты 2 и 3б.
# На текущем HEAD (барьера нет): rc 127 → ассерт 1.
set -uo pipefail
# shellcheck disable=SC1091
. "$(dirname "$0")/_forks.sh"

PREDLOZH='Предложение 1: развести грамматику и исполнение. Предложение 2: оракул в память.'

# 1) высокоставочный дизайн без СОревью.
R1="$WORK/v-net-soreview"; igrushka "$R1"
zapis "$R1" konsultant-barrier "КЛАСС: дизайн" "ПРИЗНАК: новый-механизм" \
      "МАРШРУТ: со-ревью" "ЗАВЕДЁН: $(iso_nazad 900)"
zapusk --root "$R1"
zhdu_rc 1 'высокоставочный дизайн без СОревью (инв. 3-I)'
zhdu_text 'konsultant-barrier' 'отказ обязан называть запись (инв. 3-I)'

# 2) позитивный контроль: СОревью есть, содержит предложения, вердикта не выносит.
R2="$WORK/v-est-soreview"; igrushka "$R2"
zapis "$R2" konsultant-barrier "КЛАСС: дизайн" "ПРИЗНАК: граница-безопасности" \
      "МАРШРУТ: со-ревью" "ЗАВЕДЁН: $(iso_nazad 900)"
otvet "$R2" verdicts/consultant/konsultant-barrier-soreview-v1.md anthropic/claude-fable-5 \
      "$PREDLOZH"
zapusk --root "$R2"
zhdu_rc 0 'конформный высокоставочный дизайн с одним СОревью — барьер обязан молчать'

# 3) ловец over-триггера: рутина не зовёт сильную модель.
R3="$WORK/v-rutina"; igrushka "$R3"
zapis "$R3" pereimenovanie-polja "КЛАСС: дизайн" "ПРИЗНАК: рутина" "МАРШРУТ: со-ревью" \
      "ЗАВЕДЁН: $(iso_nazad 900)"
zapusk --root "$R3"
zhdu_rc 1 'СОревью вызван на рутинном дизайне (инв. 3-II, over-триггер)'
zhdu_text 'pereimenovanie-polja' 'отказ обязан называть запись (инв. 3-II)'
zapis "$R3" pereimenovanie-polja "КЛАСС: дизайн" "ПРИЗНАК: рутина" "МАРШРУТ: свой" \
      "ЗАВЕДЁН: $(iso_nazad 900)"
zapusk --root "$R3"
zhdu_rc 0 'рутинный дизайн решается архитектором сам — барьер обязан молчать (инв. 3-II)'

# 4) СОревью, вынесший вердикт вместо предложений.
R4="$WORK/v-verdikt"; igrushka "$R4"
zapis "$R4" portirovanie-kontura "КЛАСС: дизайн" "ПРИЗНАК: портирование-контура" \
      "МАРШРУТ: со-ревью" "ЗАВЕДЁН: $(iso_nazad 900)"
otvet "$R4" verdicts/consultant/portirovanie-kontura-soreview-v1.md anthropic/claude-fable-5 \
      "$PREDLOZH" "accept"
zapusk --root "$R4"
zhdu_rc 1 'СОревью вынес вердикт accept вместо предложений (инв. 3-III)'
zhdu_text 'portirovanie-kontura' 'отказ обязан называть предмет (инв. 3-III)'

# 5) СОревью ПОСЛЕ круга критика — порядок по mtime.
R5="$WORK/v-posle-kritika"; igrushka "$R5"
zapis "$R5" neobratimyj-shag "КЛАСС: дизайн" "ПРИЗНАК: необратимость" "МАРШРУТ: со-ревью" \
      "ЗАВЕДЁН: $(iso_nazad 7200)"
otvet "$R5" verdicts/critic/neobratimyj-shag-v1.md '-' "reject"
otvet "$R5" verdicts/consultant/neobratimyj-shag-soreview-v1.md anthropic/claude-fable-5 "$PREDLOZH"
touch -d "@$(( NOW - 3600 ))" "$R5/verdicts/critic/neobratimyj-shag-v1.md"
touch -d "@$(( NOW - 60 ))"   "$R5/verdicts/consultant/neobratimyj-shag-soreview-v1.md"
zapusk --root "$R5"
zhdu_rc 1 'СОревью написан ПОСЛЕ вердикта критика (инв. 3-III)'
zhdu_text 'neobratimyj-shag' 'отказ обязан называть предмет (инв. 3-III)'

# 6) второй СОревью на тот же предмет.
R6="$WORK/v-dva-soreview"; igrushka "$R6"
zapis "$R6" kross-repo-port "КЛАСС: дизайн" "ПРИЗНАК: кросс-репо" "МАРШРУТ: со-ревью" \
      "ЗАВЕДЁН: $(iso_nazad 900)"
otvet "$R6" verdicts/consultant/kross-repo-port-soreview-v1.md anthropic/claude-fable-5 "$PREDLOZH"
otvet "$R6" verdicts/consultant/kross-repo-port-soreview-v2.md anthropic/claude-fable-5 "$PREDLOZH"
zapusk --root "$R6"
zhdu_rc 1 'второй СОревью на одном предмете — обзор ОДИН (инв. 3-I)'
zhdu_text 'kross-repo-port' 'отказ обязан называть предмет (инв. 3-I)'
