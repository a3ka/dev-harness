# ПРИЧИНА: передаточное касание
#
# 051, клетка владельца 2: та же передаточная запись с `ОТВЕЧЕНО: да` → rc 0.
# Положительный контроль — закрытая передаточная НЕ красит обычный режим
# (предмет 051): клетка обязана убедиться в нулевом коде сама, иначе в ДО
# (фильтра нет) первый вызов красен и контроля нет. Красное предъявление —
# та же запись, открытая (`ОТВЕЧЕНО: нет`): «передаточное касание».
set -euo pipefail

WORK="${WORK:-$(mktemp -d "${TMPDIR:-/tmp}/v051-case.XXXXXX")}"
ROOT="$WORK/root"
mkdir -p "$ROOT/forks"

NOW="$(date -u +%s)"
iso_nazad() { date -u -d "@$(( NOW - $1 ))" +%Y-%m-%dT%H:%M:%SZ; }

zapis() {
  local id="$1"; shift
  {
    printf 'ФОРК: %s\n' "$id"
    printf 'ВОПРОС: подставной вопрос предмета %s\n' "$id"
    for f in "$@"; do printf '%s\n' "$f"; done
  } > "$ROOT/forks/$id.md"
}

zapis ci-dual-pered "КЛАСС: инженерный" "МАРШРУТ: батч" \
      "ЗАВЕДЁН: $(iso_nazad 300)" "ОТВЕЧЕНО: да"

# Положительный контроль и предмет клетки: закрытая передаточная → rc 0.
if ! "$BARRIER" --root "$ROOT"; then
  printf 'закрытая передаточная красит обычный режим — ожидался rc 0: ci-dual-pered\n' >&2
  exit 1
fi

# Красное предъявление: та же запись открытая → rc 1 «передаточное касание».
zapis ci-dual-pered "КЛАСС: инженерный" "МАРШРУТ: батч" \
      "ЗАВЕДЁН: $(iso_nazad 300)" "ОТВЕЧЕНО: нет"

"$BARRIER" --root "$ROOT"