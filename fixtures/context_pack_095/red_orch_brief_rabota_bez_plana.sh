#!/usr/bin/env bash
# Клетка И-19 «работа без plan.tsv видна; предмет — цепочка носителей с
# прецеденсом; настоящий сбой остаётся отказом» (095, followup-1112).
# Реальный бэкенд (клон /tmp/dev-harness-verify/back-brief-1112): план.tsv
# НЕТ, contracts/ несёт договоры в нескольких форматах — секция «## Предмет»
# (большинство), секция «## Обещание и граница» (класс 167/168/169), inline
# «Предмет:» в строке (149-заглушка буд. задачи, 160), только H1 (класс
# harness 154/157/184). Прежний сборщик умирал «брифинг: контракт без
# предмета» на первом неудобном формате — черновик будущей задачи блокировал
# ВСЕ прочие работы.
#
# КОНСТРУКЦИЯ РАЗЛИЧЕНИЯ (ядро followup):
#   ДАННЫЕ — «карта работы описывает черновик/другой формат»: бриф строится
#   rc 0, работа ВИДНА (скоуп без plan.tsv = ВСЕ контракты, не «план пуст»);
#   предмет — ЦЕПОЧКА носителей с ПРЕЦЕДЕНСОМ: первая непустая строка
#   «## Предмет…» → «## Обещание и граница» → inline «Предмет:» (Н-436) →
#   фактический H1 — реальное описание, не placeholder; H1 с явной пометкой
#   ЧЕРНОВИК сохраняет метку «черновик: » у не-заголовочного носителя
#   (обзор не объявляет черновик реализованным);
#   СБОЙ СБОРЩИКА — «настоящая невозможность собрать»: полностью пустой
#   контракт (ни одного носителя) — rc 1 «брифинг: контракт без предмета»,
#   пустой stdout; обязательный источник карты недоступен — rc 1 «источник
#   недоступен: <путь>», stdout БЕЗ пака. Незнакомый заголовок — НЕ отказ.
# Вход каждой ветви — СВОЙ; оракулы — литералы в памяти ДО вызова (правило 8);
# сверки структурные (grep -Fx полными WORK-строками). Суффикс имени причины
# после пути отказа НЕ пинится (полная строка — wording-only): проверяются
# rc, пустой stdout и имя причины.
# Обманы (s31: без plan.tsv всё «вне плана»; s32: обещание/inline выпали из
# цепочки; s33: отказ обязательного источника проглочен; s34: придуманный
# placeholder вместо отказа на пустом контракте) → клетка красна.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/_toy.sh"
SUBJ="$(_t95_subject)"
[ -f "$SUBJ" ] || { printf 'КРАСНО: orch-brief-rabota-bez-plana: предмет отсутствует: scripts/make_task.sh\n' >&2; exit 1; }

red() { printf 'КРАСНО: И-19 %s\n' "$*" >&2; exit 1; }

W="$(_t95_world bezplana)" || exit 2
trap '_t95_cleanup "$W"' EXIT
R="$W/repo"
_t95_trace "$W/trace.tsv" orchestrator glm-4.7 allowed

# ── мир бэкенда: плана НЕТ; форматы носителей предмета ──────────────────────
# 700 — секция «## Предмет» (живой стандарт); 710 — inline «Предмет:»
# СЕРЕДИНОЙ строки, H1 несёт явную ЧЕРНОВИК-пометку (класс 149/160); 720 —
# «## Обещание и граница» (класс 167/168/169); 730/731 — ПРЕЦЕДЕНС (несколько
# носителей разом: секция бьёт обещание и inline; обещание бьёт inline);
# 732 — только фактический H1 (класс harness 154/157/184).
rm "$R/registry/plan.tsv"
printf '# Контракт 700 — секция toy\n\n## Предмет\n\nпредмет-700-секция.\n' >"$R/contracts/700-sekcija-toy.md"
printf '# 710 inline toy — ЧЕРНОВИК-ЗАГЛУШКА (architect перезаписывает целиком)\n\nКласс задачи: КОДОВЫЙ. Направление: бэкенд. Предмет: tools/check-x.py — барьер y. Спека: docs/owner/toy.md §3.\n' >"$R/contracts/710-inline-toy.md"
printf '# Контракт 720 — другой формат toy\n\n## Обещание и граница\n\ntoy-обещание-секцией-обещания.\n' >"$R/contracts/720-format-toy.md"
printf '# Контракт 730 — прецеденс toy\n\nПредмет: inline-значение-730.\n\n## Обещание и граница\n\nобещание-730.\n\n## Предмет\n\nпредмет-730-секция.\n' >"$R/contracts/730-pretsedens-toy.md"
printf '# Контракт 731 — прецеденс обещания toy\n\nПредмет: inline-значение-731.\n\n## Обещание и граница\n\nобещание-731.\n' >"$R/contracts/731-pretsedens-obeshanie-toy.md"
printf '# Контракт 732 — только заголовок toy\n' >"$R/contracts/732-tolko-zagolovok-toy.md"
git -C "$R" add -A && git -C "$R" commit -qm 'bezplana: мир без реестра плана, все форматы носителей'

# оракулы ДО вызова (правило 8): литералы предметов — победители цепочки
# носителей по файлам, которые мир только что записал
WANT_700='WORK: 700 :: предмет-700-секция.'
WANT_710='WORK: 710 :: черновик: tools/check-x.py — барьер y. Спека: docs/owner/toy.md §3.'
WANT_720='WORK: 720 :: toy-обещание-секцией-обещания.'
WANT_730='WORK: 730 :: предмет-730-секция.'
WANT_731='WORK: 731 :: обещание-731.'
WANT_732='WORK: 732 :: Контракт 732 — только заголовок toy'
WANT_777='WORK: 777 :: toy-предмет.'
ORACLE_WORK=7  # 700/710/720/730/731/732/777 — все контракты мира, ни один не скрыт

# (а) работа без plan.tsv ВИДНА; все форматы несут предмет; прецеденс держится
out="$(bash "$SUBJ" --repo "$R" --role orchestrator --kind brief --model-trace "$W/trace.tsv" 2>"$W/err.a")"; rc=$?
[ "$rc" -eq 0 ] || red "(а) бриф без plan.tsv не строится (черновик/формат блокирует): rc=$rc, stderr: $(cat "$W/err.a")"
printf '%s\n' "$out" | grep -q '^WORK: 777 ::' || red "(а) базовый 777 невиден: без plan.tsv скоуп НЕ «все контракты» — работа скрыта"
for w in "$WANT_700" "$WANT_710" "$WANT_720" "$WANT_730" "$WANT_731" "$WANT_732" "$WANT_777"; do
  printf '%s\n' "$out" | grep -Fxq -- "$w" || red "(а) предмет по цепочке носителей не доставлен/не тот победитель: нет строки «$w»"
done
nwork="$(printf '%s\n' "$out" | grep -c '^WORK: [0-9]')"
[ "$nwork" = "$ORACLE_WORK" ] || red "(а) WORK-строк $nwork, ожидалось ровно $ORACLE_WORK — молчаливое сужение карты (И-0)"

# (б) бюджет честен: BUDGET = пересчёт проверяющего, ≤ 40000
vk="$(printf '%s\n' "$out" | sed -n 's/^BUDGET: vklejka=\([0-9]*\)\/40000$/\1/p')"
fact="$(printf '%s\n' "$out" | awk '/^=== MANIFEST ===$/{exit} {print}' | wc -c | tr -d ' ')"
{ [ -n "$vk" ] && [ "$vk" = "$fact" ] && [ "$fact" -le 40000 ]; } || red "(б) BUDGET «$vk» != пересчёт «$fact» или > 40000"

# (г) полностью пустой контракт — НАСТОЯЩИЙ сбой: отказ, не placeholder
: >"$R/contracts/740-pustoj-toy.md"
outp="$(bash "$SUBJ" --repo "$R" --role orchestrator --kind brief --model-trace "$W/trace.tsv" 2>"$W/err.d")"; rcp=$?
[ "$rcp" -eq 1 ] || red "(г) полностью пустой контракт не отказал: rc=$rcp (невозможность собрать ≠ непривычный заголовок)"
[ -z "$outp" ] || red "(г) отказ пустого контракта выдал stdout: «$outp»"
grep -Fq "брифинг: контракт без предмета: $R/contracts/740-pustoj-toy.md" "$W/err.d" || red "(г) отказ не именем «брифинг: контракт без предмета: <путь>»: $(cat "$W/err.d")"

# (в) СБОЙ СБОРЩИКА ≠ данные: обязательный источник карты недоступен — ОТКАЗ
rm "$R/PROJECT.md"
outg="$(bash "$SUBJ" --repo "$R" --role orchestrator --kind brief --model-trace "$W/trace.tsv" 2>"$W/err.c")"; rcg=$?
[ "$rcg" -eq 1 ] || red "(в) потеря mandatory-источника не отказала: rc=$rcg (бриф не имеет права маскировать отказ доверия)"
[ -z "$outg" ] || red "(в) отказ выдал stdout: «$outg»"
grep -Fq "ОТКАЗ: источник недоступен: PROJECT.md" "$W/err.c" || red "(в) отказ не именем «источник недоступен: PROJECT.md»: $(cat "$W/err.c")"
exit 0
