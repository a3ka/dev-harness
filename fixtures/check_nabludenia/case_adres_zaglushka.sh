# ПРИЧИНА: Н-8: адрес не называет цель
#
# Непустого хвоста недостаточно (круг 1: миграция «ОТКРЫТО — адрес: .» прошла бы порог),
# и лексической категории недостаточно (круг 2 / арбитраж 3, спор 2: хвосты
# «адрес: очередь» и «адрес: правило роли» проходят стемы старого regex, цель не называя)
# — якорь = категория + обязательный идентификатор, ERE «# ГРАММАТИКА:» контракта.
# Стаб-заглушка наблюдаема только на входе с непустым хвостом БЕЗ якоря: пустой хвост —
# ветвь case_adres_pustoj, честный адрес якорь несёт (зелёный контроль ниже).
set -euo pipefail
R="$WORK/repo"
mkdir -p "$R"

# Зелёный контроль: хвост называет цель (категория + идентификатор)
printf '### Н-8. Боль `ОТКРЫТО — адрес: очередь автономности: пачка Н-60`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R"

# Красное: хвост непуст, но цель не названа — заглушка-точка
printf '### Н-8. Боль `ОТКРЫТО — адрес: .`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true

# Красное: голая категория без идентификатора — стабы критика круга 2 (арбитраж 3)
printf '### Н-8. Боль `ОТКРЫТО — адрес: очередь`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true
printf '### Н-8. Боль `ОТКРЫТО — адрес: правило роли`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true
