# ПРИЧИНА: Н-3: открыта без адреса
#
# Инвариант 1: каталог без NABLIUDENIA*.md — rc=0 с печатью «неприменимо» (не молчит,
# не краснеет; прецедент check_ceilings). Печать «неприменимо» фиксируется самим кейсом
# по выводу зелёного вызова. Красное — файл появился с нарушителем: барьер обязан
# переключиться с «неприменимо» на именованный отказ.
set -euo pipefail
R="$WORK/repo"
mkdir -p "$R"

# Зелёный контроль: файлов нет — ноль с печатью «неприменимо»
out="$("$BARRIER" "$R" 2>&1)"
printf '%s\n' "$out" | grep -q 'неприменимо' || {
  printf 'ОТКАЗ: пустой каталог — барьер вернул 0, но «неприменимо» не напечатал:\n%s\n' "$out" >&2
  exit 1
}

# Красное: файл появился с открытой записью без адреса
printf '### Н-3. Боль `ОТКРЫТО`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true
