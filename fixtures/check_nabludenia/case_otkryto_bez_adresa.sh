# ПРИЧИНА: Н-1: открыта без адреса
#
# Механизм 1, инвариант 3: статусный маркер, начинающийся со слова ОТКРЫТО, обязан
# нести `адрес:` с непустым хвостом в ТОМ ЖЕ маркере заголовка. Зелёный контроль —
# та же запись с адресом; красное — маркер без адреса, отказ называет ИМЯ записи.
# Файл — NABLIUDENIA.md (ветвь Н-файла; А-файл — отдельным кейсом).
set -euo pipefail
R="$WORK/repo"
mkdir -p "$R"

# Зелёный контроль: открытая запись с непустым адресом
printf '### Н-1. Боль `ОТКРЫТО — адрес: очередь автономности`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R"

# Красное: адреса нет — отказ обязан назвать Н-1
printf '### Н-1. Боль `ОТКРЫТО`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true
