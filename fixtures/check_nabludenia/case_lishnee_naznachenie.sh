# «контракт 015 контракт 016» — обход класса «лишнее назначение». ФОРМА валидна
# (голова «контракт 015» + разделитель-пробел + хвост), но набор адресатных
# ключей значения {K:015, K:016} шире набора строки §Материал {K:015} — лишний
# ключ меняет назначение. Постоянный стаб (требование владельца 2026-08-27:
# пойманный обход = собственный case). Н-39: дефект наблюдаем ТОЛЬКО мерой
# назначения — миграционной пробой (равенство наборов), не формой; мера
# назначения и этот case умирают вместе с таблицей в коммите введения
# (закрытая форма грамматики, пункт 2 — контракт). До реализации барьера
# красное предъявляется адаптер-барьером (образец — реестр стабов круга 5,
# вердикт критика): для каждого входа case собирается полный корень
# build_root.py и зовётся неизменённая миграционная проба.
set -euo pipefail
R="$WORK/repo"
mkdir -p "$R"

# Зелёный контроль: голова называет цель, посторонних ключей нет (Н-36, §Материал)
