# ПРИЧИНА: Н-7: открыта без адреса
#
# Охрана от цитат-стабов (развилка 2: блок-поиск-ветвь остаётся как охрана):
# `адрес:` в ТЕЛЕ чужой записи не считается адресом открытой. Зелёный контроль —
# закрытая цитирует чужой адрес в теле, открытая несёт адрес в заголовке; красное —
# закрытая цитирует, открытая БЕЗ адреса: блок-поиск по телу прошёл бы это зелёным
# (ложно-зелёное), заголовочная грамматика обязана краснеть и назвать Н-7.
set -euo pipefail
R="$WORK/repo"
mkdir -p "$R"

# Зелёный контроль: цитата в теле закрытой + адрес в заголовке открытой
{
  printf '### Н-6. Старое `ЗАКРЫТО 005 (f81c0)`\n\n'
  printf 'Закрыто по контракту 005; соседняя тема (адрес: контракт 019) туда не вошла.\n\n'
  printf '### Н-7. Живая `ОТКРЫТО — адрес: очередь автономности`\n\nтело\n'
} > "$R/NABLIUDENIA.md"
"$BARRIER" "$R"

# Красное: цитата чужого адреса в теле НЕ закрывает открытую без адреса
{
  printf '### Н-6. Старое `ЗАКРЫТО 005 (f81c0)`\n\n'
  printf 'Закрыто по контракту 005; тема записи (адрес: контракт 019) осталась рядом.\n\n'
  printf '### Н-7. Живая `ОТКРЫТО`\n\nтело цитирует чужой адрес: контракт 019\n'
} > "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true
