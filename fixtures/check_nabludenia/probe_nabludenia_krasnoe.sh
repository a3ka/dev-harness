#!/usr/bin/env bash
# Проба контракта 015, механизм 1 (Н-62): красная ДО реализации (барьера нет либо
# дерево не мигрировано), зелёная ПОСЛЕ — барьер и миграционная пачка приезжают ОДНИМ
# коммитом введения (развилка 1а). Запускается из корня дерева.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
B="$ROOT/scripts/check_nabludenia.sh"

if [ ! -f "$B" ]; then
  printf 'ОТКАЗ: барьера нет — %s (реализация за implementer после заморозки)\n' "$B" >&2
  exit 1
fi
if bash "$B" "$ROOT" >/dev/null 2>&1; then
  printf 'ok: барьер зелёный на живом дереве — миграционная пачка в коммите введения\n'
  exit 0
fi
rc=$?
printf 'ОТКАЗ: барьер красен на живом дереве (rc=%d) — миграционная пачка не в коммите введения\n' "$rc" >&2
exit 1
