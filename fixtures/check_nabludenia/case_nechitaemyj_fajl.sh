# ПРИЧИНА: нечем проверить
#
# Существующий, но нечитаемый файл — rc=2 именованной строкой «нечем проверить:
# <файл>», а НЕ «неприменимо»: отсутствие (rc=0) и нечитаемость (rc=2) — разные
# исходы. Стаб «считаю нечитаемое отсутствующим» наблюдаем только на входе с
# существующим недоступным файлом: на отсутствующем он честен (case_net_fajlov).
set -euo pipefail
R="$WORK/repo"
mkdir -p "$R"

# Зелёный контроль: читаемый файл с адресом-якорем
printf '### Н-6. Боль `ОТКРЫТО — адрес: контракт 015`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R"

# Красное: файл существует, но не читается — rc=2, не «неприменимо».
# Состояние НЕ восстанавливаем: повторный прогон проверяющего должен увидеть тот же отказ.
chmod 000 "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true
