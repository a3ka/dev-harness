# ПРИЧИНА: Н-8: адрес не называет цель
#
# Стаб круга 2 (арбитраж 3, спор 2): голая категория «очередь» проходит стемы старого
# regex (`очеред`), цель не называя — якорь = категория + обязательный идентификатор
# («очередь автономности»). Круг 3, блокер 1: вход обязан жить в собственном case —
# раннер верифицирует повторным прогоном один красный вызов на case; в объединённом
# case уже-красная точка засчитывалась и за этот вход.
set -euo pipefail
R="$WORK/repo"
mkdir -p "$R"

# Зелёный контроль: категория с идентификатором
printf '### Н-8. Боль `ОТКРЫТО — адрес: очередь автономности`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R"

# Красное: голая категория без идентификатора
printf '### Н-8. Боль `ОТКРЫТО — адрес: очередь`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true
