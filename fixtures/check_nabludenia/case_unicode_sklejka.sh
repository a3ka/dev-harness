# ПРИЧИНА: Н-39-рецидив: unicode-склейка к якорю — круг 4 критик, круг 5 блокер 1
#
# Греческие α/β и латинская p-гомоглифа склеиваются с якорной категорией
# (`αконтракт`, `контрактβ`, `контракт01p`). Буква вне перечисленных алфавитов
# НЕ разделитель: значение не матчится с начала строки, адресатный ключ
# не извлекается. Постоянный стаб (требование владельца 2026-08-27):
# пойманный обход = собственный case — раннер верифицирует повторным
# прогоном ОДИН красный вызов на case.
set -euo pipefail
R="$WORK/repo"
mkdir -p "$R"

# Зелёный контроль: валидный якорь «контракт 015» (Н-36, Н-62 — §Материал)
printf '### Н-36. Боль `ОТКРЫТО — адрес: контракт 015`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R"

# Красное: греческая α-склейка слева
printf '### Н-36. Боль `ОТКРЫТО — адрес: αконтракт 015`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true

# Красное: греческая β-склейка справа
printf '### Н-36. Боль `ОТКРЫТО — адрес: контракт 015β`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true

# Красное: латинская p-гомоглифа в номере
printf '### Н-36. Боль `ОТКРЫТО — адрес: контракт 01p`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true
