# ПРИЧИНА: Н-9: открыта без адреса
#
# Правило НЕ обратной силы: закрытые записи без адреса зелены (миграционная цена
# для закрытых = 0). Зелёный контроль — пачка закрытых без адреса + одна открытая
# С адресом; красное — появление открытой БЕЗ адреса среди них.
set -euo pipefail
R="$WORK/repo"
mkdir -p "$R"

# Зелёный контроль: закрытые без адреса не судятся, открытая адресована
{
  printf '### Н-3. Старое `ЗАКРЫТО 005 (f81c0)`\n\nтело\n'
  printf '### Н-4. Старое `ЗАКРЫТО (механизмом 008)`\n\nтело\n'
  printf '### Н-5. Старое `ЧАСТИЧНО ЗАКРЫТО`\n\nтело\n'
  printf '### Н-6. Старое `СПАСЕНО (серией 014)`\n\nтело\n'
  printf '### Н-8. Живая `ОТКРЫТО — адрес: контракт 015`\n\nтело\n'
} > "$R/NABLIUDENIA.md"
"$BARRIER" "$R"

# Красное: открытая без адреса среди закрытых — названа по имени
printf '### Н-9. Живая `ОТКРЫТО`\n\nтело\n' >> "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true
