# ПРИЧИНА: Н-2: адрес пуст
#
# Отделяет «слово есть» от «адрес назван» (урок charter: разрешение без причины).
# Маркер `ОТКРЫТО — адрес: ` — слово «адрес:» есть, хвост пуст: это то же нарушение,
# что и отсутствие адреса, с отдельной формулировкой «адрес пуст».
set -euo pipefail
R="$WORK/repo"
mkdir -p "$R"

# Зелёный контроль: непустой хвост адреса
printf '### Н-2. Боль `ОТКРЫТО — адрес: контракт 019`\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R"

# Красное: пустой хвост — слово есть, адреса нет
printf '### Н-2. Боль `ОТКРЫТО — адрес: `\n' > "$R/NABLIUDENIA.md"
"$BARRIER" "$R" || true
