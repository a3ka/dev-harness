#!/usr/bin/env bash
# Раннер красной/зелёной пачки 113 «быстрый check_charter при коммите устав-пути» —
# агрегатор ОДНОЙ семьи: fixtures/charter_fast_113/red_113.sh (probe-only каталог,
# см. .probe-only; имя каталога — вне чужих glob'ов раннеров).
#
# Использование:
#   bash fixtures/_krasnye_113.sh                # быстрый прогон (без В2)
#   RED_113_FULL=1 bash fixtures/_krasnye_113.sh # приёмка: + дифференциал на ВСЕЙ
#                                               # живой истории (оракул ~полчаса,
#                                               # запускать с timeout >= 3600)
#
# Семантика: rc 0 — батарея зелёная (быстрый режим неотличим от оракула на корпусе,
# бюджет 60 с в свежем worktree держится, все обманные стабы пойманы поимённо);
# rc 1 — красное. ДО реализации (база) красны по умыслу Д-клетки (--oracle
# отсутствует → именованный отказ компаратора) и В-клетка (полный обход пробивает
# 60 с — Н-380); стаб-пак ловится уже на базе — доказательная сила батареи
# проверяема до реализации. Подключение в CI — реализационной пачкой
# (контракт 113 §ПРОВОДКА; прецедент 083).
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BATTERY="$HERE/charter_fast_113/red_113.sh"
[ -f "$BATTERY" ] || { printf 'ОТКАЗ: нет батареи: %s\n' "$BATTERY" >&2; exit 2; }
bash "$BATTERY" "$@"
exit $?
