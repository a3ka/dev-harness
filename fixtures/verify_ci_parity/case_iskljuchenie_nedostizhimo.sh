# ПРИЧИНА: исключение «check:existing» недостижимо: скрипт запускается в CI — запись ничего не разрешает
#
# Находка 4б: исключение, названное для скрипта, который CI И ТАК ЗАПУСКАЕТ, — не
# разрешение, а повторение. Оно не достигает цели: пункт уже покрыт, и запись в
# файле исключений ничего не разрешает. Она засоряет файл и держит выбор, которого
# не делали. Барьер обязан назвать запись и встать в 1, иначе недостижимое
# исключение выглядит как «объявлено» и создаёт видимость работы.
set -euo pipefail
. "$(dirname "$0")/_fake_root.sh"
fake_root "$WORK"
"$BARRIER" "$WORK"
# `check:existing` запускается CI в минимальной основе, и при этом же объявляется
# исключением — это та недостижимая запись, которую барьер обязан отвергнуть.
cat >> "$WORK/config/ci_parity_exceptions.txt" <<'TXT'
check:existing = подставная запись фикстуры: скрипт `check:existing` уже запускается в CI, исключение для него ничего не разрешает — запись недостижима
TXT
"$BARRIER" "$WORK"
