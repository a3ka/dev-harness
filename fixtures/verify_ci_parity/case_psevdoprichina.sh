# ПРИЧИНА: псевдопричина у исключения «check:phantom»: «.» — причина обязана называть, что мешает исполнять пункт в CI
#
# Находка 4в: исключение с причиной-точкой (`= .`) — мнимая отметка. «Объявлено»
# без содержания неотличимо от опечатки: причина обязана назвать две вещи — что
# мешает исполнять пункт в CI и чем это заменено. Точка — ноль слов и ноль букв, и
# это ниже порога осмысленности, который назначен в шапке барьера. Здесь
# подставной `check:phantom` есть в приёмке, не в CI, и «объявлен» с причиной-точкой;
# барьер обязан назвать причину и встать в 1, иначе псевдопричина проходит молча.
set -euo pipefail
. "$(dirname "$0")/_fake_root.sh"
fake_root "$WORK"
"$BARRIER" "$WORK"
python3 -c '
import json, sys
pkg = json.load(open(sys.argv[1]))
pkg["scripts"]["check:phantom"] = "echo phantom"
json.dump(pkg, open(sys.argv[1], "w"), indent=2, ensure_ascii=False)
' "$WORK/package.json"
cat > "$WORK/config/ci_parity_exceptions.txt" <<'TXT'
# Подставные исключения для фикстуры: одна запись с настоящей причиной, одна — с псевдопричиной.
check:unused = подставное дерево: скрипт не в CI и не используется в подставном workflow; объявлен исключением, чтобы барьер был зелёным на минимальной основе
check:phantom = .
TXT
"$BARRIER" "$WORK"
