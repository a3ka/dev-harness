# ПРИЧИНА: исключение «check:ghost» названо для скрипта, которого нет в приёмке — мёртвая запись
#
# Находка 4а: исключение, названное для скрипта, которого в приёмке НЕТ, — мёртвая
# запись. Она создаёт ВИД объявленной работы и маскирует изменение состава приёмки:
# скрипт переименовали или удалили, а строка осталась, и читатель верит, что решение
# про него принято. Барьер обязан назвать запись и встать в 1, иначе мёртвая запись
# проходит молча, а «объявлено» становится отметкой, неотличимой от опечатки.
set -euo pipefail
. "$(dirname "$0")/_fake_root.sh"
fake_root "$WORK"
"$BARRIER" "$WORK"
# Добавить мёртвую запись к подставным исключениям. Имя «check:ghost» НИГДЕ в
# приёмке не встречается — именно это делает запись мёртвой.
cat >> "$WORK/config/ci_parity_exceptions.txt" <<'TXT'
check:ghost = подставная запись фикстуры: проверяет, что мёртвое исключение (скрипта, которого нет в приёмке) барьер отвергает с названной записью
TXT
"$BARRIER" "$WORK"
