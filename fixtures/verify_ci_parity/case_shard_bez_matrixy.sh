# Зеркальная ветвь полноты инварианта 3 (контракт 020, обход №1 вердикта критика v1):
# фикстуры есть, а шардного запуска НЕТ — предмет вынут из CI целиком, и слабый барьер
# (три проверки: выпавшие ключи, дубли, отсутствие --scope) возвращал 0. Стаб
# воспроизводит ИСПОЛНЕННОЕ критиком состояние «no-shard-job»: matrix-джоба вырезается,
# в главную джобу возвращается прежний единый --changed-шаг. Проводка остаётся легальной
# для правила 6 (команда покрыта пунктом check:antiplacebo, скрипт в CI используется),
# поэтому красное обязан предъявить именно ветвь полноты, а не посторонний отказ.
# До предмета 020 барьер не сверяет полноту и зеленеет — проба красна ДО реализации
# («красное не предъявлено»).
set -euo pipefail
. "$(dirname "$0")/_fake_root.sh"
. "$(dirname "$0")/_shard_tree.sh"
shard_tree "$WORK"
"$BARRIER" "$WORK"
# Стаб: matrix-джоба вырезана, в главную джобу возвращён прежний --changed-шаг —
# форма исполненного обхода критика (controls/no-shard-job). Правка python3-скриптом:
# split+append нельзя выразить однострочным sed без риска порезать соседние строки.
python3 - "$WORK/.github/workflows/ci.yml" <<'PY'
import sys, pathlib
p = pathlib.Path(sys.argv[1])
text = p.read_text().split('  antiplacebo:')[0]
text += '      - name: Анти-плацебо\n        run: npm run check:antiplacebo -- --changed ${{ github.event.before }}\n'
p.write_text(text)
PY
"$BARRIER" "$WORK"
