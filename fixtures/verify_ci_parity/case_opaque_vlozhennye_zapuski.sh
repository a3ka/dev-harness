# ПРИЧИНА: шаг вне разбираемого подмножества: подстановка команды $(...)
#
# Находка 1 круга 2, и закрыта она НЕ так, как её закрыли сначала. Первая правка извлекала
# вложенный скрипт и проверяла его — а ревьюер предъявил, что при ПОКРЫТОМ вложенном скрипте и
# объявленном исключении на внешнюю команду шаг проходил молча: `$(...)` работал выключателем
# сверки. Арбитраж `verdicts/arbitration/oblast-i-porog.md` (вопрос 1) предписал отказывать на
# самой ФОРМЕ, независимо от того, покрыт ли вложенный запуск.
#
# Поэтому подставное дерево здесь — САМЫЙ выгодный для обмана случай: вложенный скрипт
# существует в приёмке, внешняя команда объявлена исключением с настоящей причиной. Механизм
# обязан всё равно сказать правду: этот шаг он не разбирает, и вот выход.
set -euo pipefail
. "$(dirname "$0")/_fake_root.sh"
fake_root "$WORK"
"$BARRIER" "$WORK"
cat > "$WORK/.github/workflows/ci.yml" <<'YAML'
name: CI
on: [push]
jobs:
  ci:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Внешняя команда прячет вложенный запуск
        run: echo "$(npm run check:existing)"
YAML
{
  printf '# Подставные исключения: внешняя команда объявлена, вложенный запуск покрыт приёмкой.\n'
  printf 'check:unused = подставное дерево: скрипт не в CI и не используется в подставном workflow; объявлен исключением, чтобы барьер был зелёным на минимальной основе\n'
  printf 'echo = внешняя команда намеренно печатает результат вложенного проверочного сценария и пунктом приёмки не является\n'
} > "$WORK/config/ci_parity_exceptions.txt"
"$BARRIER" "$WORK"
