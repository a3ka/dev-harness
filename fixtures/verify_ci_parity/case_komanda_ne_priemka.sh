# ПРИЧИНА: команда «set -e» есть в CI, но нет пункта в приёмке и не объявлена исключением
#
# Находка 1, обратная сторона: `run:` — ЭТО SHELL-СЦЕНАРИЙ, и в нём законно стоит
# команда, не являющаяся приёмкой (`cd`, `echo`, `set`, `export`, …). Прежняя редакция
# таких команд не разбирала; новая сверяет КАЖДУЮ команду, а отказ объявляется через
# канал исключений — `команда: <текст> = <причина>` в `config/ci_parity_exceptions.txt`.
# Здесь `set -e` в workflow объявлено исключением с записанной причиной, и зелёный
# прогон это подтверждает. Без объявления барьер обязан назвать команду и встать в 1 —
# иначе канал исключений был бы мёртвым.
set -euo pipefail
. "$(dirname "$0")/_fake_root.sh"
fake_root "$WORK"
# Сначала объявить исключение, чтобы зелёный прогон прошёл: именно он доказывает, что
# канал исключений РАБОТАЕТ, а не просто не падает.
cat >> "$WORK/config/ci_parity_exceptions.txt" <<'TXT'
команда: set -e = служебная команда shell: задаёт режим остановки при ошибке, пункт приёмки не нуждается в отдельной записи в scripts; в CI стоит как инициализация сценария
TXT
cat > "$WORK/.github/workflows/ci.yml" <<'YAML'
name: CI
on: [push]
jobs:
  ci:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Existing check
        run: |
          set -e
          npm run check:existing
YAML
"$BARRIER" "$WORK"
# Теперь убрать объявление исключения — барьер обязан назвать `set -e` и встать в 1.
# Без этого шага фикстура была бы зелёной на зелёном дереве и не предъявила красного.
sed -i '/^команда: set -e /d' "$WORK/config/ci_parity_exceptions.txt"
"$BARRIER" "$WORK"
