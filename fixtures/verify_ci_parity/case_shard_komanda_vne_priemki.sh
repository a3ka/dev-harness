# ПРИЧИНА: есть в CI, но нет пункта в приёмке и не объявлена исключением
#
# Правило 6 на форме шардинга (контракт 020): run-шаг шарда получает ШАБЛОННОЕ имя
# скрипта `npm run ${{ matrix.cmd }}`, а в matrix.include добавляется поле
# `cmd: check:antiplacebo` — приманка для неверной реализации: если матричное
# разрешение когда-нибудь начнёт легализовать шаблонное ИМЯ (грамматика контракта
# п.1: имя статично, шаблон только в аргументах), команда станет «покрытой» и проба
# это поймает — красное исчезнет. Сегодня дефект наблюдаем на этом входе СУЩЕСТВУЮЩЕЙ
# ветвью правила 6 (находка адверсария про &&-хвосты): имя после `npm run` — `${{`,
# пункта приёмки с таким именем нет. Проба зелёна и до, и после предмета — её ветвь
# уже живёт; это регрессионная защита, а не красное до реализации (Н-39: требовать
# красноты там, где дефект уже ловится, — требовать лжи в диагнозе).
set -euo pipefail
. "$(dirname "$0")/_fake_root.sh"
. "$(dirname "$0")/_shard_tree.sh"
shard_tree "$WORK"
"$BARRIER" "$WORK"
# Стаб: имя скрипта в run-шаге становится шаблоном; поле cmd в include — приманка
# для матричного разрешения имён (легализация сделала бы пробу красной — и пойманной).
sed -i -e 's/- shard: ap1/- shard: ap1\n            cmd: check:antiplacebo/' \
       -e 's/- shard: ap2/- shard: ap2\n            cmd: check:antiplacebo/' \
       -e 's|run: npm run check:antiplacebo -- --scope ${{ matrix.keys }}|run: npm run ${{ matrix.cmd }} -- --scope ${{ matrix.keys }}|' \
  "$WORK/.github/workflows/ci.yml"
"$BARRIER" "$WORK"
