# ПРИЧИНА: шаг несёт нерасширенную индирекцию рядом с npm run (переменная MYSTERY_SCRIPT)
#
# Дополняет к2-пробы «переменное имя» и «переменный бинарник»: там переменная
# статически разрешалась литеральным `env:` того же шага, и барьер видел
# ПОДСТАВЛЕННЫЙ запуск check:antiplacebo. Здесь у `$MYSTERY_SCRIPT` НЕТ ни одного
# литерального объявления (ни на шаге, ни в джобе, ни в workflow) — значение
# неизвестно барьеру и неизвестно ЕМУ В ПРИНЦИПЕ без исполнения (задача
# неразрешима в общем виде). Проверяется fail-closed ветвь `_resolve_npm_indirection`:
# неразрешённая переменная рядом с `npm run` — красное С ИМЕНЕМ переменной,
# БЕЗУСЛОВНО (не растворяется command-exception'ом, симметрично heredoc/xargs/eval).
# До фикса к2 эта форма проходила мимо совпадения по подстроке точно так же, как
# разрешимые формы, — и была бы зелёной по той же причине.
set -euo pipefail
. "$(dirname "$0")/_fake_root.sh"
. "$(dirname "$0")/_shard_tree.sh"
shard_tree "$WORK"
"$BARRIER" "$WORK"
# Стаб: прежний --changed-шаг через переменную БЕЗ единого статического
# объявления — не $ANTI_SCRIPT/$NPM_BIN (те заведены отдельными пробами), а новое
# имя, чтобы никакой env: этого дерева случайно её не разрешил.
sed -i 's|^  antiplacebo:|      - name: Анти-плацебо прежний (нерасширенная индирекция)\n        run: npm run "$MYSTERY_SCRIPT" -- --changed ${{ github.event.before }}\n  antiplacebo:|' \
  "$WORK/.github/workflows/ci.yml"
"$BARRIER" "$WORK"
