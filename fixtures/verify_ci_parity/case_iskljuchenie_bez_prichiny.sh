# ПРИЧИНА: строка исключения без «=»: check:overlay
#
# Правило паритета из AGENTS.md: приёмка не имеет права быть богаче CI молча. Исключение
# БЕЗ записанной причины — это та же молчаливая дыра, только с формальной отметкой:
# «объявлено» ≠ «объявлено с причиной». Подставной файл исключений содержит имя скрипта
# без `=` — барьер обязан отказать с названной строкой, иначе правило «причина обязательна»
# превращается в совет.
set -euo pipefail
. "$(dirname "$0")/_fake_root.sh"
fake_root "$WORK"
"$BARRIER" "$WORK"
# Перезаписать исключения: одна валидная запись + одна без причины.
cat > "$WORK/config/ci_parity_exceptions.txt" <<'TXT'
# Подставные исключения для фикстуры: одна запись с причиной, одна — без.
check:unused = подставное дерево: скрипт не в CI и не используется в подставном workflow; объявлен исключением, чтобы барьер был зелёным на минимальной основе
check:overlay
TXT
"$BARRIER" "$WORK"
