# (вчерашняя форма единого шага). Дефект наблюдаем на этом входе: выбор фикстур шарда
# перестаёт быть определён проводкой, шард может выйти зелёным, ничего не прогнав
# (класс Н-63: «0 задетых — зелёное»), и сумма шардов перестаёт проверяться. До
# предмета 020 барьер зеленеет на такой строке (имя скрипта статично и покрыто) —
# проба красна ДО реализации («красное не предъявлено»).
