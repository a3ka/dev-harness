# ПРИЧИНА: команда «npm run check:sneaky» есть в CI, но нет пункта в приёмке
#
# Находка 1: `run:` — ЭТО SHELL-СЦЕНАРИЙ, а не одна команда. Прежняя редакция брала
# значение `run:` целиком, и `npm run check:existing && npm run check:sneaky`
# считалось ОДНОЙ покрытой командой: хвост после первого имени принимался за
# аргументы. Вторая самостоятельная команда не разбиралась, и пункт, который CI
# действительно исполняет, оставался неопределённым. Здесь `&&` стоит в СЕРЕДИНЕ
# строки (не на переводе), и вторая команда в приёмке отсутствует — барьер обязан
# назвать её и встать в 1.
set -euo pipefail
. "$(dirname "$0")/_fake_root.sh"
fake_root "$WORK"
"$BARRIER" "$WORK"
# Перезаписать workflow одной строкой, в которой два вызова склеены `&&`. Первая
# команда легитимна, вторая — отсутствующий пункт приёмки, и она ОБЯЗАНА быть названа
# отдельно: сценарий, в котором `&&` соединяет команды, разбирается на части.
cat > "$WORK/.github/workflows/ci.yml" <<'YAML'
name: CI
on: [push]
jobs:
  ci:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Chain
        run: npm run check:existing && npm run check:sneaky
YAML
"$BARRIER" "$WORK"
