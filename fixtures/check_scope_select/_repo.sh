# Общий помощник фикстур `check_scope_select`.
#
# Имя НЕ case_*.sh намеренно: сам каркас фикстурой не считается.
#
# Фикстура строит подставной корень с scripts/scope_select.sh (тело — со stdin), затем зовёт
# `$BARRIER <корень> <ветвь>`. Барьер check_scope_select строит свои игрушечные git-деревья и
# гоняет этот scope_select по ОДНОЙ ветви. Зелёный контроль — честный для ветви стаб (барьер 0);
# красное — обманный стаб (барьер не-ноль с причиной ветви). Обманный стаб-БАРЬЕР (всегда 0)
# красноты не даст — фикстура его убивает.
sel() {  # <корень>   тело scope_select — со stdin
  local r="$1"; mkdir -p "$r/scripts"
  cat > "$r/scripts/scope_select.sh"; chmod +x "$r/scripts/scope_select.sh"
}
