# ПРИЧИНА: (120 байт): нет раздела
#
# Полная матрица раздела (контракт 004 v1). Зелёные исходы — НЕМАСКИРОВАННЫЕ
# (стаб, отвергающий валидный список, обязан краснеть на зелёной стадии списка).
# Красное повторяет ПЕРВЫЙ красный — черновик C3 фиксИРОВАННОГО размера 120 байт,
# потому ПРИЧИНА несёт и размер: стаб-константа без имени/размера не проходит.
set -euo pipefail
. "$(dirname "$0")/_gen.sh"
R="$WORK/repo"
mkdir -p "$R/contracts"

pad() { # <файл> <целевой-размер> — дописка комментария до ровного размера
  local f="$1" n="$2" have add
  have=$(wc -c < "$f"); add=$((n - have))
  [ "$add" -gt 0 ] && { head -c "$add" /dev/zero | tr '\0' '#' | sed "s/^\(.\{1\}\)/#/" >> "$f"; }
}

# Зелёный 1: тело «нет»
C1="$(rnd_nnn kontrakt-net)"
printf '# Черновик\n\n## Предмет\nпроба\n\n## Незаполненные требования:\nнет\n' > "$R/contracts/$C1.md"
"$BARRIER" "$R"

# Зелёный 2: валидный список — БЕЗ маскировки: стаб «только нет» здесь краснеет
rm "$R/contracts/$C1.md"
C2="$(rnd_nnn kontrakt-spisok)"
printf '# Черновик\n\n## Предмет\nпроба\n\n## Незаполненные требования:\n- первое\n- второе\n' > "$R/contracts/$C2.md"
"$BARRIER" "$R"

# Красные: все три плохих черновика — в дереве ДО ЕДИНСТВЕННОГО красного вызова.
# Повторный прогон проверяющего исполняет финальное дерево: все три отказа
# присутствуют в каждом состоянии, причина стабильна. C3 — РОВНО 120 байт (в ПРИЧИНЕ).
rm "$R/contracts/$C2.md"
C3="$(rnd_nnn kontrakt-bez-razdela)"
printf '# Черновик\n\n## Предмет\nпроба\n' > "$R/contracts/$C3.md"
pad "$R/contracts/$C3.md" 120
[ "$(wc -c < "$R/contracts/$C3.md")" -eq 120 ] || { printf 'фикстура сломана: C3 не 120 байт\n' >&2; exit 2; }
C4="$(rnd_nnn kontrakt-pustoj)"
printf '# Черновик\n\n## Предмет\nпроба\n\n## Незаполненные требования:\n' > "$R/contracts/$C4.md"
C5="$(rnd_nnn kontrakt-vne-grammatiki)"
printf '# Черновик\n\n## Предмет\nпроба\n\n## Незаполненные требования:\nпока не решили\n' > "$R/contracts/$C5.md"
"$BARRIER" "$R"
