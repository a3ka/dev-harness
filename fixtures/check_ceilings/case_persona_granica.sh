# ПРИЧИНА: 51201 байт
#
# Ветвь персон, пара границы (контракт 004 v1): РОВНО 51200 байт → 0; 51201 байт → 1.
# Имя файла порождается при каждом прогоне — барьер, зашитый на известные имена,
# матрицу не проходит. Отказ обязан назвать имя и размер.
set -euo pipefail
. "$(dirname "$0")/_gen.sh"
R="$WORK/repo"
mkdir -p "$R/roles"
P="$(rnd pers)"
make_bytes "$R/roles/$P.md" 51200
"$BARRIER" "$R"

make_bytes "$R/roles/$P.md" 51201
"$BARRIER" "$R"
