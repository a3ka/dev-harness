#
# make_bytes <файл> <байты> [kir] — файл ТОЧНО указанного размера в БАЙТАХ.
# Латиницей по умолчанию; с аргументом kir — кириллицей (символ = 2 байта в UTF-8;
# sed заменяет каждый NUL-байт на двухбайтовую «ф» — tr для этого непригоден,
# он байтовый и молча портит размер).
make_bytes() { # <файл> <байты> [kir]
  local f="$1" n="$2" kir="${3:-}"
  if [ "$kir" = kir ]; then
    local chars=$((n / 2)) have sz
    head -c "$chars" /dev/zero | sed 's/\x00/ф/g' > "$f"
    have=$(wc -c < "$f"); sz=$((n - have))
    [ "$sz" -gt 0 ] && head -c "$sz" /dev/zero | tr '\0' 'a' >> "$f"
  else
    head -c "$n" /dev/zero | tr '\0' 'a' > "$f"
  fi
}

# rnd <префикс> — порождаемое при каждом прогоне имя без фиксированной части.
rnd() { printf '%s-%s' "$1" "$RANDOM$RANDOM"; }

# rnd_nnn <слог> — порождаемое ИМЯ ЧЕРНОВИКА КОНТРАКТА: грамматика барьера требует
# ровно три цифры и дефис в начале (NNN-slug.md) — как настоящие contracts/NNN-*.md.
rnd_nnn() { printf '%03d-%s-%s' $((RANDOM % 900 + 100)) "$1" "$RANDOM"; }
