# ПРИЧИНА: > потолка
#
# Различающая кириллическая фикстура (контракт 004 v1, арбитраж potolki-granica-pokrytie):
# 26000 кириллических символов = 52000 байт при 26000 символов — символов МЕНЬШЕ
# потолка 51200, байтов БОЛЬШЕ. Барьер на wc -m проходит красным требованием,
# барьер на wc -c — отказ. Имя порождается при каждом прогоне.
set -euo pipefail
. "$(dirname "$0")/_gen.sh"
R="$WORK/repo"
mkdir -p "$R/roles"

# Зелёный контроль: малая персона — потолок не задет
G="$(rnd kir-ok)"
printf '# малая персона\n' > "$R/roles/$G.md"
"$BARRIER" "$R"
rm "$R/roles/$G.md"

# 26000 символов кириллицы = 52000 байт > 51200; символов 26000 < 51200.
# sed, не tr: tr байтовый и молча портит размер кириллицы.
P="$(rnd kir)"
head -c 26000 /dev/zero | sed 's/\x00/ф/g' > "$R/roles/$P.md"
[ "$(wc -c < "$R/roles/$P.md")" -eq 52000 ] || { printf 'фикстура сломана: размер не 52000\n' >&2; exit 2; }
"$BARRIER" "$R"
