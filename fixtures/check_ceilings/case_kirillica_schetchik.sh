# ПРИЧИНА: 62000 байт
#
# Различающая кириллическая фикстура (контракт 004 v1, арбитраж potolki-granica-pokrytie):
# 31000 кириллических символов = 62000 байт при 31000 символов — символов МЕНЬШЕ
# потолка 61440, байтов БОЛЬШЕ. Барьер на wc -m проходит красным требованием,
# барьер на wc -c — отказ. Имя порождается при каждом прогоне.
set -euo pipefail
. "$(dirname "$0")/_gen.sh"
R="$WORK/repo"
mkdir -p "$R/roles"

# Зелёный контроль: малая персона — потолок не задет
G="$(rnd kir-ok)"
printf '# малая персона\n' > "$R/roles/$G.md"
"$BARRIER" "$R"
rm "$R/roles/$G.md"

# 31000 символов кириллицы = 62000 байт > 61440; символов 31000 < 61440.
# sed, не tr: tr байтовый и молча портит размер кириллицы.
P="$(rnd kir)"
head -c 31000 /dev/zero | sed 's/\x00/ф/g' > "$R/roles/$P.md"
[ "$(wc -c < "$R/roles/$P.md")" -eq 62000 ] || { printf 'фикстура сломана: размер не 62000\n' >&2; exit 2; }
"$BARRIER" "$R"
