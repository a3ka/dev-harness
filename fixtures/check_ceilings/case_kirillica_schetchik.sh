# ПРИЧИНА: 74000 байт
#
# Различающая кириллическая фикстура (контракт 004 v1, арбитраж potolki-granica-pokrytie):
# 37000 кириллических символов = 74000 байт при 37000 символов — символов МЕНЬШЕ
# потолка 73728, байтов БОЛЬШЕ. Барьер на wc -m проходит красным требованием,
# барьер на wc -c — отказ. Имя порождается при каждом прогоне.
set -euo pipefail
. "$(dirname "$0")/_gen.sh"
R="$WORK/repo"
mkdir -p "$R/roles"

# Зелёный контроль: малая персона — потолок не задет
G="$(rnd kir-ok)"
printf '# малая персона\n' > "$R/roles/$G.md"
"$BARRIER" "$R"
rm "$R/roles/$G.md"

# 37000 символов кириллицы = 74000 байт > 73728; символов 37000 < 73728.
# sed, не tr: tr байтовый и молча портит размер кириллицы.
P="$(rnd kir)"
head -c 37000 /dev/zero | sed 's/\x00/ф/g' > "$R/roles/$P.md"
[ "$(wc -c < "$R/roles/$P.md")" -eq 74000 ] || { printf 'фикстура сломана: размер не 74000\n' >&2; exit 2; }
"$BARRIER" "$R"
