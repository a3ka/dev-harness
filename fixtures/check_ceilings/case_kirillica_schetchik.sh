# ПРИЧИНА: 54000 байт
#
# Различающая кириллическая фикстура (контракт 004 v1, арбитраж potolki-granica-pokrytie):
# 27000 кириллических символов = 54000 байт при 27000 символов — символов МЕНЬШЕ
# потолка 53248, байтов БОЛЬШЕ. Барьер на wc -m проходит красным требованием,
# барьер на wc -c — отказ. Имя порождается при каждом прогоне.
set -euo pipefail
. "$(dirname "$0")/_gen.sh"
R="$WORK/repo"
mkdir -p "$R/roles"

# Зелёный контроль: малая персона — потолок не задет
G="$(rnd kir-ok)"
printf '# малая персона\n' > "$R/roles/$G.md"
"$BARRIER" "$R"
rm "$R/roles/$G.md"

# 27000 символов кириллицы = 54000 байт > 53248; символов 27000 < 53248.
# sed, не tr: tr байтовый и молча портит размер кириллицы.
P="$(rnd kir)"
head -c 27000 /dev/zero | sed 's/\x00/ф/g' > "$R/roles/$P.md"
[ "$(wc -c < "$R/roles/$P.md")" -eq 54000 ] || { printf 'фикстура сломана: размер не 54000\n' >&2; exit 2; }
"$BARRIER" "$R"
