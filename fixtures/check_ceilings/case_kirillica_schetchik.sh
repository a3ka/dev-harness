# ПРИЧИНА: 82000 байт
#
# Различающая кириллическая фикстура (контракт 004 v1, арбитраж potolki-granica-pokrytie):
# 41000 кириллических символов = 82000 байт при 41000 символов — символов МЕНЬШЕ
# потолка 81920, байтов БОЛЬШЕ. Барьер на wc -m проходит красным требованием,
# барьер на wc -c — отказ. Имя порождается при каждом прогоне.
set -euo pipefail
. "$(dirname "$0")/_gen.sh"
R="$WORK/repo"
mkdir -p "$R/roles"

# Зелёный контроль: малая персона — потолок не задет
G="$(rnd kir-ok)"
printf '# малая персона\n' > "$R/roles/$G.md"
"$BARRIER" "$R"
rm "$R/roles/$G.md"

# 41000 символов кириллицы = 82000 байт > 81920; символов 41000 < 81920.
# sed, не tr: tr байтовый и молча портит размер кириллицы.
P="$(rnd kir)"
head -c 41000 /dev/zero | sed 's/\x00/ф/g' > "$R/roles/$P.md"
[ "$(wc -c < "$R/roles/$P.md")" -eq 82000 ] || { printf 'фикстура сломана: размер не 82000\n' >&2; exit 2; }
"$BARRIER" "$R"
