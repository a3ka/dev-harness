# ПРИЧИНА: размер нечитаем
#
# Нечитаемый размер (битая символическая ссылка) — ОТКАЗ с именем файла, не молчание
# и не rc=0 (находка замера закрытия 004: действующий барьер держал, но ни одна
# фикстура не предъявляла — регрессия прошла бы незамеченной). Обе ветви: персона
# и файл-правило. Имена порождаются при каждом прогоне.
set -euo pipefail
. "$(dirname "$0")/_gen.sh"
R="$WORK/repo"
mkdir -p "$R/roles" "$R/.omp/rules"

# Зелёный контроль: обычные файлы под потолком
G1="$(rnd pers-ok)"; G2="$(rnd rule-ok)"
printf '# малая персона\n' > "$R/roles/$G1.md"
printf '# малое правило\n' > "$R/.omp/rules/$G2.md"
"$BARRIER" "$R"

# Порча: битые ссылки в обеих ветвях — размер нечитаем, отказ обязан назвать имена
P="$(rnd pers-broken)"; Q="$(rnd rule-broken)"
ln -s /nonexistent-target "$R/roles/$P.md"
ln -s /nonexistent-target "$R/.omp/rules/$Q.md"
"$BARRIER" "$R"
