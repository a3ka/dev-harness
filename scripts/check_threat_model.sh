#!/usr/bin/env bash
# Барьер формы секции «## Модель угроз» (контракт 041, Направление 1: обязательная
# модель угроз для контрактов, вводящих гард, парсящий/исполняющий чужой ввод).
#
# Грамматика — ЕДИНЫЙ источник контракт 041 §Инварианты 3-4; реализация несёт фразы
# ПОБАЙТОВО (фикстуры сверяют дословно через grep -Fq). Маркеры ищутся ВНУТРИ
# секции «## Модель угроз» (от заголовка до следующего заголовка ТОГО ЖЕ или
# БОЛЕЕ ВЫСОКОГО уровня — канон 038 §Инварианты 1) — НЕ по всему файлу: секция
# может повторно упоминаться прозой в других разделах контракта (разбор
# грамматики, примеры), и такие упоминания не обязаны участвовать в проверке
# формы. Первое вхождение строки, побайтово равной `## Модель угроз`, — начало
# секции; парсинг — построчный по МАССИВАМ (Направление 3, инвариант ii: байт
# `-`, встречающийся в буллете, никогда не используется как внутренний
# разделитель — нет join+split одной строкой нигде в этом файле).
#
# ГРАНИЦА ПРАВИЛА 8: барьер судит ФОРМУ (наличие обоих списков, наличие ≥1
# буллета в каждом, порог формы буллета) — НЕ судит: (а) обязана ли КОНКРЕТНАЯ
# секция существовать в конкретном контракте (cognitive-only критика,
# roles/critic.md — отсутствие секции здесь rc0, не сигнал тревоги); (б)
# смысловую адекватность границы ЗАЩИЩАЕТ/НЕ ЗАЩИЩАЕТ (прямой перенос решённого
# verdicts/arbitration/oblast-i-porog.md §Вопрос2 — та же доктрина: механизм
# видит отметку формы, не предложение по смыслу).
#
# Модель угроз ЭТОГО барьера (дословно — контракт 041 несёт тот же текст в
# своей секции «## Модель угроз», это её self-application-green экземпляр):
#   ЗАЩИЩАЕТ: честный разбор независимо от содержимого буллетов (включая байты
#     `-`, `:`, кавычки внутри буллета — построчные массивы, не join+split);
#     различение «секции нет» (rc0) от «секция неполна» (rc1, именованная
#     причина); литеральное (НЕ regex/glob) сравнение меток и буллет-префикса.
#   НЕ ЗАЩИЩАЕТ: враждебное окружение вызывающего процесса сверх `export
#     PATH=/usr/bin:/bin` (sourced-исполнение, экспортированные функции,
#     локаль — отдельный класс ENV-TRUST/SOURCED-EXEC, вне предмета 041);
#     смысловую адекватность буллетов (судит критик, не барьер); решение,
#     обязана ли секция существовать в данном контракте (cognitive-only
#     критика); заголовок-подобный текст внутри markdown code-fence, ошибочно
#     принятый за настоящий заголовок секции (известный класс — 038, круг 15;
#     именованный остаточный риск, не закрыт этим барьером).
#
# Контракт API:
#   bash scripts/check_threat_model.sh <корень> <отн-путь-контракта>
#   rc 0 — секции «## Модель угроз» нет ВООБЩЕ (вне применимости этого барьера,
#          присутствие — отдельный cognitive-only вопрос критика) ЛИБО секция
#          есть и форма валидна: оба списка ЗАЩИЩАЕТ:/НЕ ЗАЩИЩАЕТ: присутствуют,
#          в каждом ≥1 буллет, каждый буллет — НЕ НИЖЕ порога формы (4 слова
#          длиной ≥2 алфавитно-цифровых символа И ≥24 алфавитно-цифровых
#          символа суммарно — ТОТ ЖЕ порог, что verify_ci_parity.sh:986-990
#          `reason_weak`, verdicts/arbitration/oblast-i-porog.md §Вопрос2);
#   rc 1 — секция есть, форма невалидна: ИМЕНОВАННАЯ причина первой красной
#          проверки (порядок: ЗАЩИЩАЕТ-отсутствует → НЕ_ЗАЩИЩАЕТ-отсутствует →
#          ЗАЩИЩАЕТ-пуст → НЕ_ЗАЩИЩАЕТ-пуст → первый буллет ниже порога, в
#          порядке ЗАЩИЩАЕТ затем НЕ ЗАЩИЩАЕТ);
#   rc 2 — нечем проверить (корня нет / контракта нет / тело контракта пусто /
#          нет python3 — порог формы измеряется им, Unicode-корректно: `tr
#          -dc '[:alnum:]'` под C/C.UTF-8 локалью НЕ классифицирует кириллицу
#          как alnum — измерено живьём при написании этого барьера, python3
#          `str.isalnum()` корректен для Unicode).
# Коды возврата: 0 — секции «## Модель угроз» нет ВООБЩЕ либо форма валидна, 1 — секция есть и форма невалидна (именованная причина), 2 — нечем проверить.
set -uo pipefail

# ДОВЕРЕННЫЙ PATH — ДО ПЕРВОЙ ВНЕШНЕЙ КОМАНДЫ (прецедент check_provodka.sh:138,
# check_consumers.sh:41, check_protected.sh:81 — ровно тот же класс обхода).
export PATH=/usr/bin:/bin

die()  { printf '%s\n' "$*" >&2; exit 1; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

ROOT="${1:?использование: $0 <корень-дерева> <отн-путь-контракта>}"
CONTRACT_PATH="${2:?использование: $0 <корень-дерева> <отн-путь-контракта>}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd -P)" || skip "корня нет: $ROOT"
case "$CONTRACT_PATH" in
  /*) CONTRACT_PATH="${CONTRACT_PATH#$ROOT/}" ;;
esac
CONTRACT_PATH="$(printf '%s' "$CONTRACT_PATH" | sed 's|^\./||; s|//|/|g')"
[ -f "$ROOT/$CONTRACT_PATH" ] || skip "контракта нет: $ROOT/$CONTRACT_PATH"
body="$(cat "$ROOT/$CONTRACT_PATH" 2>/dev/null || true)"
[ -n "$body" ] || skip "тело контракта пусто: $ROOT/$CONTRACT_PATH"
command -v python3 >/dev/null 2>&1 || skip "нет python3 — порог формы нечем измерить"

mapfile -t all_lines < <(printf '%s\n' "$body")

# ── найти ПЕРВОЕ вхождение заголовка секции (побайтовое равенство строки) ────
heading_idx=-1
for ((i = 0; i < ${#all_lines[@]}; i++)); do
  if [ "${all_lines[$i]}" = "## Модель угроз" ]; then
    heading_idx=$i
    break
  fi
done
if [ "$heading_idx" -lt 0 ]; then
  printf 'модель угроз: секция отсутствует (вне применимости барьера; присутствие — cognitive-only критика)\n' >&2
  exit 0
fi

# ── тело секции: от заголовка+1 до следующего `# `/`## ` (точечный якорь по
# семантической единице — уровень заголовка, не суммарная длина совпадения) ──
section_lines=()
for ((i = heading_idx + 1; i < ${#all_lines[@]}; i++)); do
  ln="${all_lines[$i]}"
  case "$ln" in
    "## "*|"# "*) break ;;
    *) section_lines+=("$ln") ;;
  esac
done

# collect_bullets <метка> — заполняет глобальный массив BULLETS буллетами,
# идущими НЕПОСРЕДСТВЕННО (без разрыва) за строкой-меткой; возвращает 0, если
# метка найдена (даже с нулём буллетов), 1 — если метки нет вовсе.
collect_bullets() {
  local label="$1"
  local found=0 j k cur
  BULLETS=()
  for ((j = 0; j < ${#section_lines[@]}; j++)); do
    if [ "${section_lines[$j]}" = "$label" ]; then
      found=1
      k=$((j + 1))
      while [ "$k" -lt "${#section_lines[@]}" ]; do
        cur="${section_lines[$k]}"
        case "$cur" in
          "- "*) BULLETS+=("${cur#- }") ;;
          *) break ;;
        esac
        k=$((k + 1))
      done
      break
    fi
  done
  [ "$found" -eq 1 ]
}

# bullet_below_threshold <текст> — rc0, если буллет НИЖЕ порога формы (плохо).
# Делегировано python3: `tr -dc '[:alnum:]'` под C/C.UTF-8 локалью не считает
# кириллицу алфавитно-цифровой (измерено живьём), а python3 str.isalnum()
# корректен для Unicode — та же формула, что verify_ci_parity.sh:986-990.
bullet_below_threshold() {
  printf '%s' "$1" | python3 -c '
import sys, re
text = sys.stdin.read()
wre = re.compile(r"\w", re.UNICODE)
words = [t for t in text.split() if len([c for c in t if wre.match(c)]) >= 2]
letters = sum(1 for c in text if c.isalnum())
sys.exit(0 if (len(words) < 4 or letters < 24) else 1)
'
}

collect_bullets 'ЗАЩИЩАЕТ:' || die "модель угроз: список ЗАЩИЩАЕТ: отсутствует"
zashita_bullets=("${BULLETS[@]}")

collect_bullets 'НЕ ЗАЩИЩАЕТ:' || die "модель угроз: список НЕ ЗАЩИЩАЕТ: отсутствует"
ne_zashita_bullets=("${BULLETS[@]}")

[ "${#zashita_bullets[@]}" -gt 0 ] || die "модель угроз: список ЗАЩИЩАЕТ: пуст (нет буллета)"
[ "${#ne_zashita_bullets[@]}" -gt 0 ] || die "модель угроз: список НЕ ЗАЩИЩАЕТ: пуст (нет буллета)"

for b in "${zashita_bullets[@]}"; do
  bullet_below_threshold "$b" && die "модель угроз: буллет ниже порога формы: $b"
done
for b in "${ne_zashita_bullets[@]}"; do
  bullet_below_threshold "$b" && die "модель угроз: буллет ниже порога формы: $b"
done

printf 'модель угроз: секция валидна (ЗАЩИЩАЕТ %d буллет(ов), НЕ ЗАЩИЩАЕТ %d буллет(ов))\n' \
  "${#zashita_bullets[@]}" "${#ne_zashita_bullets[@]}" >&2
exit 0
