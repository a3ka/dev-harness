#!/usr/bin/env bash
# Наложение НАШЕГО слоя поверх omp — одной командой.
#
# Заведено потому, что «помнить три команды после обновления» механизмом не является.
# Порядок был: распаковать харнес, перегенерировать роли, вернуть назначения моделей — и
# любой пропущенный шаг оставлял назначение до следующего обновления, после чего оно молча
# исчезало.
#
# Обновление харнеса — смена ОСНОВАНИЯ контура. Оно требует записанной причины, иначе
# основание меняется без следа. Поэтому расхождение с пином по умолчанию ОТКАЗ, а согласие
# выражается флагом с причиной, а не молчанием.
#
#   bash scripts/overlay.sh                        наложить слой, сверив пин
#   bash scripts/overlay.sh --check                только сверить, ничего не менять
#   bash scripts/overlay.sh --accept-new "причина"  принять новую версию и переписать пин
#
# Коды возврата: 0 — слой наложен и сверен, 1 — расхождение, 2 — нечем проверить.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PIN="$HERE/config/harness_pin.json"

die()  { printf 'ОТКАЗ: %s\n' "$*" >&2; exit 1; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }
ok()   { printf '  ok   %s\n' "$*" >&2; }

CHECK=0; ACCEPT=""; ACCEPT_SEEN=0
while [ $# -gt 0 ]; do
  case "$1" in
    --check)      CHECK=1 ;;
    # Значение берётся ЯВНОЙ проверкой, а не `shift` вслепую: `shift` при пустом списке
    # возвращает не ноль и под `set -e` убивал скрипт молча — отказ без названной причины
    # это тот же тихий провал, против которого написано правило про код возврата.
    --accept-new) ACCEPT_SEEN=1; ACCEPT="${2:-}"; [ $# -ge 2 ] && shift ;;
    *)            die "неизвестный аргумент: $1" ;;
  esac
  shift
done
[ "$ACCEPT_SEEN" -eq 0 ] || [ -n "$ACCEPT" ] \
  || die "--accept-new требует причину: обновление контура без записанной причины — смена основания без следа"

command -v omp >/dev/null 2>&1 || skip "omp не установлен — накладывать не на что"
command -v jq  >/dev/null 2>&1 || skip "нет jq — пин не прочитать"
[ -f "$PIN" ] || skip "нет пина $PIN"

BIN="$(readlink -f "$(command -v omp)")"
got_ver="$(omp --version 2>/dev/null | sed 's|^omp/||')"
got_sha="$(sha256sum "$BIN" | cut -d' ' -f1)"
want_ver="$(jq -r '.version' "$PIN")"
want_sha="$(jq -r '.sha256' "$PIN")"

[ -n "$want_sha" ] && [ "$want_sha" != "null" ] \
  || die "в пине пуста контрольная сумма — пин без неё пином не является"

# ── сверка пина ──────────────────────────────────────────────────────────────
if [ "$got_ver" = "$want_ver" ] && [ "$got_sha" = "$want_sha" ]; then
  ok "пин совпал: omp/$got_ver"
elif [ -n "$ACCEPT" ]; then
  # Принятие новой версии — запись, а не правка одного числа: причина уходит в пин, чтобы
  # через месяц было видно, ЧТО именно приняли и зачем.
  [ "$CHECK" -eq 0 ] || die "--check и --accept-new вместе бессмысленны: первый ничего не меняет"
  tmp="$(mktemp)"
  jq --arg v "$got_ver" --arg s "$got_sha" --arg b "$(stat -c%s "$BIN")" \
     --arg why "$ACCEPT" --arg when "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
     '.version=$v | .sha256=$s | .bytes=($b|tonumber)
      | ._accepted = ((._accepted // []) + [{when:$when, version:$v, why:$why}])' \
     "$PIN" > "$tmp" && mv "$tmp" "$PIN"
  ok "принята новая версия omp/$got_ver, причина записана в пин"
else
  printf 'ОТКАЗ: харнес разошёлся с пином.\n' >&2
  printf '  версия:  установлена %s, пин %s\n' "$got_ver" "$want_ver" >&2
  printf '  sha256:  установлена %s\n           пин        %s\n' "$got_sha" "$want_sha" >&2
  printf '\nСовпадение версий при разной сумме означает переопубликованный тег: содержимое\n' >&2
  printf 'изменилось, номер нет. Принять осознанно:\n' >&2
  printf '  bash scripts/overlay.sh --accept-new "<почему обновляемся>"\n' >&2
  exit 1
fi

# ── наш слой ─────────────────────────────────────────────────────────────────
# Слой невелик намеренно: роли моделей в `.omp/config.yml` и агенты, порождённые из
# `roles/`. Всё, что можно породить, порождается, а не хранится дважды.
if [ "$CHECK" -eq 1 ]; then
  node "$HERE/scripts/gen-harness.ts" --check >/dev/null || die "агенты разошлись с roles/ — наложите слой"
  ok "агенты соответствуют roles/"
else
  node "$HERE/scripts/gen-harness.ts" >/dev/null || die "не удалось породить агентов из roles/"
  node "$HERE/scripts/gen-harness.ts" --check >/dev/null \
    || die "агенты разошлись с roles/ СРАЗУ после порождения — дефект генератора, не слоя"
  ok "агенты порождены из roles/ и сверены"
fi

[ -f "$HERE/.omp/config.yml" ] || die "нет .omp/config.yml — роли моделей не объявлены"

# Перечень ролей моделей ВЫВОДИТСЯ из порождённых агентов, а не задан списком. Прежняя
# редакция проверяла три захардкоженных имени, и появление пятой роли привело четвёртое имя
# (`default`), которого проверка не видела вовсе. Область проверки важнее её порога: список,
# набранный руками, отстаёт от предмета молча.
needed="$(grep -hoE '^model: \["@[a-z]+"\]' "$HERE"/.omp/agents/*.md | sed 's/.*@//;s/"\]//' | sort -u)"
[ -n "$needed" ] || die "ни один агент не объявил роль модели — порождение сломано"
missing=0
for role in $needed; do
  grep -qE "^\s+${role}:" "$HERE/.omp/config.yml" \
    || { printf '  FAIL роль модели не объявлена в .omp/config.yml: %s\n' "$role" >&2; missing=1; }
done
[ "$missing" -eq 0 ] || die "слой неполон: роль без модели означает работу на умолчании харнеса"

# ── соответствие модели задаче ───────────────────────────────────────────────
# Правило против записанного инцидента: MiniMax без vision «тестировал» интерфейс — модель
# не соответствовала задаче, и об этом никто не сообщил. Здесь проверяется механизмом.
#
# Спрашивается у самого omp (`omp models list`, колонка images), а не берётся из нашего
# конфига: конфиг говорит, что мы назначили, а список моделей — что модель умеет.
caps="$(omp models list 2>/dev/null | awk -F'│' 'NF>4 {gsub(/^ +| +$/,"",$2); gsub(/^ +| +$/,"",$6); if ($2!="model" && $2!="") print $2"\t"$6}')"
# `[ -n "$caps" ] && { … }` здесь стояло списком верхнего уровня, и при пустом `caps` весь
# список возвращал не ноль: под `set -e` барьер выходил кодом 1 БЕЗ НАЗВАННОЙ ПРИЧИНЫ.
# Найдено механизмом анти-плацебо: его фикстура обязана предъявить барьер сначала зелёным, и
# зелёного не получилось. Пустой `caps` означает, что omp не перечислил модели, то есть
# соответствие модели задаче НЕ ПРОВЕРЕНО, — а «нечем проверить» не равно «проверено».
if [ -n "$caps" ]; then
  vis=0
  # Живая сессия несёт `inspect_image` в инвентаре обоих режимов, и работает она на роли
  # `default`. Модель без картинок здесь означает «смотри кадры глазами» без глаз.
  dm="$(grep -oE '^\s+default:\s*"[^"]+"' "$HERE/.omp/config.yml" | sed 's/.*"\(.*\)"/\1/' | sed 's|.*/||')"
  if [ -n "$dm" ] && printf '%s\n' "$caps" | grep -qP "^\Q$dm\E\t" ; then
    [ "$(printf '%s\n' "$caps" | grep -P "^\Q$dm\E\t" | cut -f2)" = "yes" ] \
      || { printf '  FAIL модель живой сессии %s не умеет картинки, а инвентарь несёт inspect_image\n' "$dm" >&2; vis=1; }
  fi
  # Роль, которой картинки нужны по инвентарю, не должна стоять на модели без них.
  for f in "$HERE"/.omp/agents/*.md; do
    grep -q 'inspect_image' "$f" || continue
    mr="$(grep -oE '^model: \["@[a-z]+"\]' "$f" | sed 's/.*@//;s/"\]//')"
    m="$(grep -oE "^\s+${mr}:\s*\"[^\"]+\"" "$HERE/.omp/config.yml" | sed 's/.*"\(.*\)"/\1/' | sed 's|.*/||')"
    [ -n "$m" ] || continue
    printf '%s\n' "$caps" | grep -qP "^\Q$m\E\t" || continue
    [ "$(printf '%s\n' "$caps" | grep -P "^\Q$m\E\t" | cut -f2)" = "yes" ] \
      || { printf '  FAIL роль %s требует картинки, модель %s их не умеет\n' "$(basename "$f" .md)" "$m" >&2; vis=1; }
  done
  [ "$vis" -eq 0 ] || die "модель не соответствует задаче: запуск на ней даёт тихий брак, а не отказ"
  ok "модели соответствуют задачам: где нужны картинки, они есть"
else
  skip "omp не перечислил модели — соответствие модели задаче не проверено"
fi

# ── учёт расхода: провайдер с ключом обязан идти через прокси ─────────────────
# Пробел, найденный при назначении модели исполнителю: у фабрики записано прямо — все
# провайдеры с ключевой аутентификацией имеют baseUrl прокси учёта, — а у инструмента,
# которым её строят, `models.yml` не было вовсе. Вызовы шли бы напрямую: без потолка и без
# строки в гроссбухе. Квота MiniMax общая на текст и синтез речи, то есть работа исполнителя
# и озвучка выпуска едят один остаток.
#
# ОБЛАСТЬ ВЫВЕДЕНА, А НЕ ЗАДАНА СПИСКОМ. Прежняя редакция держала `KEYED='minimax'`, и z.ai,
# назначенный позже, прошёл мимо проверки МОЛЧА — четвёртый экземпляр одного дефекта за пачку
# (каталоги слепка, `tmp/`, `tmp/antiplacebo/`, теперь KEYED): список, набранный руками,
# отстаёт от предмета. Выводится так: провайдер считается НАЗНАЧЕННЫМ, если он упомянут в
# значении любой роли моделей конфига (`minimax/MiniMax-M3`, `zai/glm-5.2`, …). Каждый
# назначенный провайдер обязан либо идти через прокси учёта, либо иметь ЗАПИСАННОЕ исключение.
#
# ИСКЛЮЧЕНИЯ ЖИВУТ В `config/metering_exceptions.txt` — `<провайдер> = <причина>`, как у
# исключений паритета: молчаливая дыра запрещена, причина обязательна. Это не ослабление, а
# перенос решения с памяти автора на читаемый файл: следующий назначенный провайдер без
# маршрута или записи покраснеет сам, чьё бы назначение это ни было.
assigned_providers="$(grep -oE '"[a-z0-9-]+/[^"]+"' "$HERE/.omp/config.yml" | sed 's/"//g; s|/.*||' | sort -u)"
[ -n "$assigned_providers" ] || die "ни один провайдер не назначен — сверять учёт не с чем"
EXC="$HERE/config/metering_exceptions.txt"
for prov in $assigned_providers; do
  # OAuth-подписки — не ключевые: расход по ним лежит в консоли провайдера, потолок ставит сам
  # провайдер, и прокси фабрики их маршрутом не владеет. Список ОГРАНИЧЕН именами схем
  # аутентификации, а не провайдеров: появление нового ключевого провайдера сюда не попадёт
  # само — и это проверяется человеком при добавлении, а не молчанием механизма.
  case "$prov" in
    anthropic|openai-codex) continue ;;
  esac
  assigned="$(grep -oE "\"${prov}/[^\"]+\"" "$HERE/.omp/config.yml" | head -1 || true)"
  [ -n "$assigned" ] || continue
  if [ -f "$EXC" ] && grep -qE "^${prov} =" "$EXC"; then
    ok "провайдер $prov — записанное исключение: $(grep -E "^${prov} =" "$EXC" | head -1 | sed "s/^${prov} = //")"
    continue
  fi
  [ -f "$HERE/.omp/models.yml" ] \
    || die "провайдер $prov назначен ($assigned), но .omp/models.yml нет — вызов пойдёт прямо, без потолка"
  grep -qE "^\s+${prov}:" "$HERE/.omp/models.yml" \
    || die "провайдер $prov назначен ($assigned), но в .omp/models.yml не объявлен и исключения в config/metering_exceptions.txt нет — маршрут учёта отсутствует"
  grep -A2 -E "^\s+${prov}:" "$HERE/.omp/models.yml" | grep -q 'METERING_PROXY_URL' \
    || die "провайдер $prov идёт не через прокси учёта и не объявлен исключением: потолок расхода не выполняет своей работы"
  ok "провайдер $prov маршрутизирован через прокси учёта"
  [ -n "${METERING_PROXY_URL:-}" ] \
    || printf '  ВНИМАНИЕ: METERING_PROXY_URL не задана — прокси поднимает ПРОЕКТ, до запуска расход не считается\n' >&2
done
ok "роли моделей объявлены: $(printf '%s' "$needed" | tr '\n' ' ')"

printf '\nслой наложен поверх omp/%s\n' "$got_ver" >&2
