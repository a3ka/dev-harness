#!/usr/bin/env bash
# Барьер проводки контракта (контракт 038, Н-116 ПРОВОДКА done-gate): читает поле
# ПРОВОДКА контракта, судит «каждый канал нормы существует и подключён» и
# возвращает rc 0/1/2. Правило 8: «то ли правило» судит ревьюер по целям поля;
# механика — наличие/грамматика/подключение/строка.
#
# Грамматика — ЕДИНЫЙ источник контракт 038 §Инварианты 1–3; реализация несёт
# фразы ПОБАЙТОВО (фикстуры сверяют дословно через grep -Fq). Маркеры ищутся по
# ВСЕМУ файлу контракта (канон 008), парсинг — anchored `sed -nE` (прецедент
# check_spec_ready.sh:93–94).
#
# ПОРЯДОК ДИАГНОСТИКИ (v3, контракт §Инварианты 3): г0 → г0-доп → г1..г6;
# строки поля судятся слева направо, побеждает ПЕРВАЯ красная строка своего
# канала. Вход «guard-only ∧ guard-призрак» краснеет г0-доп, а не г1.
#
# Валидация пути role= — двухстадийный белый список Л+К (решение арбитра
# 9cea9c3, круг 4). Блоклист-патчинг исчерпан на кругах 1–3; закрывает ВСЕ
# классы обхода ОДНИМ свойством канонической цели на ФС.
#
# Круг 5 — закрыты два дефекта исполнения Л+К (адверсарий круга 4, Б1/Б2):
#   Б1 (TOCTOU): г4 теперь читает норму из УЖЕ канонизированного `$resolved`,
#       а не заново из `$ROOT/$path` (тот же объект между К и г4 не гарантирован).
#   Б2 (parser-laxity): extract_quoted заякорен на ВСЮ входную строку после
#       тримминга — ровно `«<содержимое>»`, без мусора до/после и без вложенных
#       пар; общий для role и charter каналов.
#
# Круг 6 — закрыт РЕЦИДИВ TOCTOU (адверсарий postk5, Б1) + два новых класса
# в charter-канале (Б2а, Б2б) + Б3 (delimiter):
#   Б1 — атомарный open через ИМЕНОВАННЫЙ дескриптор (`exec {fd}<...`); все
#       последующие проверки и чтение идут ЧЕРЕЗ `/proc/self/fd/$fd`, не через
#       повторное открытие по имени. Дескриптор биндится к inode на уровне
#       ядра — подмена файла по пути ПОСЛЕ открытия уже не меняет содержимого,
#       которое видит grep/awk через fd. Общий для role и charter.
#   Б2а — target pinning: charter= обязан ссылаться ровно на `AGENTS.md`
#       (грамматика контракта литерально); любая другая цель — вне грамматики.
#   Б2б — единственная легитимная цель charter — сам `$ROOT/AGENTS.md`: канон
#       через дескриптор обязан совпасть байт-в-байт (никакой alias/symlink-
#       индирекции). Тело секции читается через `/proc/self/fd/$fd`.
#   Б3 — обязательный пробельный разделитель между заголовком и открывающей
#       `«`: грамматика `§<полный заголовок секции> «<норма>»` — без пробела
#       строка вне грамматики.
#
# Круг 7 — фикс БАГА `exec N<&- 2>/dev/null`: `exec` без команды применяет
#   СВОИ редиректы К ТЕКУЩЕМУ ШЕЛЛУ ПЕРМАНЕНТНО. `2>/dev/null` на close-строке
#   НЕ scoped на «подавить ошибку именно этого close», а ПЕРЕНАПРАВЛЯЕТ STDERR
#   ВСЕГО скрипта в /dev/null навсегда. Из-за этого любой последующий die()
#   (`>&2`) молча проваливается, а `bash -x` обрывается на первой такой строке.
#   Удалена `2>/dev/null` из ВСЕХ 9 close-строк (4 для fd 9, 5 для fd 11); сами
#   close-вызовы (`exec N<&-`) безопасны на практике — закрытие уже-открытого,
#   только что использованного дескриптора практически никогда не отказывает,
#   а в файле нет `set -e` даже НЕ-ноль от голого `exec N<&-` не убьёт скрипт.
# Круг 8 — закрыты ЧЕТЫРЕ новых обхода на финальном атомарном fd-коде круга 7
#   (адверсарий postk7-final, forged-readlink-repro). Атомарная fd-техника
#   (круги 6-7) НЕ переоткрывается — она верно защищает ЧТЕНИЕ от TOCTOU.
#   Новые дыры — ДРУГОЙ класс:
#   Б1-Б3 (PATH-tool spoofing): барьер доверял readlink/grep/awk из
#       НАСЛЕДОВАННОГО PATH. Подложный шим, который ВЫГЛЯДИТ как успешный
#       инструмент и ВОЗВРАЩАЕТ правдоподобный ответ (readlink на /proc/self/fd
#       отдаёт каноническую цель, но ЛОЖНО объявляет её легитимной; grep всегда
#       rc 0; awk фабрикует тело секции), проходит К/г4/г5 без сопротивления.
#       Фикс — `export PATH=/usr/bin:/bin` РАНЬШЕ любого вызова внешнего
#       инструмента: доверенный PATH недостижим для подмены из вызывающего
#       окружения. Тот же паттерн, что уже в `check_consumers.sh:41` /
#       `check_protected.sh:81` (установленный прецедент проекта для ровно этого
#       класса — закрывает readlink/grep/awk ОДНОЙ строкой).
#   Б4 (FIFO блокирует exec-open): `exec N<"$ROOT/$path"` открывает FIFO НА
#       ЧТЕНИЕ и БЛОКИРУЕТСЯ (ядро ждёт писателя), если у файла нет открытого
#       на запись конца — барьер зависает вместо именованного rc 1, нарушая
#       контракт API (rc 0/1/2). Затронуты ОБЕ арм (role fd 9, charter fd 11).
#       Фикс — ПЕРЕД `exec N<"$ROOT/$path"` дешёвый не-блокирующий `[ -f ]`
#       тип-чек с тем же сообщением, что несёт г3-фолбэк для этой арм (для
#       role — «role-файл не существует: $path»; для charter — «секция устава
#       не найдена: §${header_text}»). Это ТОЛЬКО фильтр очевидно-не-того
#       типа (FIFO/устройство/каталог): атомарный exec-open и пост-open
#       `[ -f "/proc/self/fd/N" ]` — ОБА остаются на месте (двойная проверка
#       дешевле возможного зависания).
# Круг 9 — гард враждебного environ (РЕШЕНИЕ второго арбитража 3792de7,
#   verdicts/arbitration/038-vrazhdebnaja-sreda-zapuska.md): ПЕРЕД всем
#   остальным кодом файла (включая `set -uo pipefail` и `export PATH=...`
#   круга 8) проверяется точное побайтовое равенство environ канону
#   `PATH=/usr/bin:/bin\nLC_ALL=C.UTF-8`; любое расхождение (экспортированные
#   bash-функции, IFS, локаль, BASH_ENV, SHELLOPTS, PATH-шимы) триггерит
#   re-exec через `env -i` в ЧИСТЫЙ канонический environ. Закрывает ВЕСЬ
#   класс «унаследованное окружение процесса» СТРУКТУРНО — `export PATH`
#   круга 8 становится вторичной защитой (после re-exec PATH уже канон);
#   прецедент `check_consumers.sh:41` / `check_protected.sh:81` сохранён
#   для diff-сравнения. Маскирование `exit` внутри `die()` закрыто ТЕМ ЖЕ
#   механизмом — отдельного фикса не требуется. Граница модели угроз
#   РАСШИРЕНА (РЕШЕНИЕ третьего арбитража 41f4884,
#   verdicts/arbitration/038-sourced-ispolnenie-granica.md §3, дословно):
#   «барьер защищается от всего, что действует ЧЕРЕЗ честное исполнение
#   его собственного текста в процессе, который этот текст получил
#   СВЕЖИМ. Барьер НЕ защищается от враждебного состояния, СУЩЕСТВОВАВШЕГО
#   В ИНТЕРПРЕТАТОРЕ ДО ТОГО, как первая строка барьера получила
#   управление». Под расширенную границу попадает (поимённо): sourced-
#   исполнение барьера (`source` / `.`) в оболочку с предсуществующим
#   враждебным состоянием — локальные (неэкспортированные) функции,
#   перекрывающие ЛЮБОЕ имя (включая имена самого детектора), `trap …
#   DEBUG/RETURN/ERR`, `shopt -s extdebug`, `enable -n`, алиасы; любое
#   состояние, не представимое в `/proc/$$/environ`. Разделительный
#   признак — момент начала враждебного контроля, а не состав не
#   тронутых ресурсов.

# Контракт API:
#   вход: $1 = <отн-путь-контракта> (относительно cwd — канон барьеров дерева);
#   rc 0 — проводка зелёная;
#   rc 1 — отказ с ИМЕНОВАННОЙ причиной первой красной строки;
#   rc 2 — нечем проверить: контракта нет / нет git / пустое тело контракта.
#
#   bash scripts/check_provodka.sh <отн-путь-контракта>
#
# Коды возврата: 0 — проводка зелёная, 1 — отказ, 2 — нечем проверить.
# Круг 10 — проба `( return 0 2>/dev/null )` в формуле НИЖЕ НЕ является защитой
#   от враждебного sourced-исполнения (см. §3
#   verdicts/arbitration/038-sourced-ispolnenie-granica.md). Класс sourced-
#   исполнения барьера в оболочку с предсуществующим враждебным состоянием
#   ВНЕ расширенной границы и этой пробой НЕ закрывается. Проба — ГИГИЕНА
#   ЧЕСТНОГО ВЫЗОВА: честный сорсинг барьера по ошибке (без враждебного
#   состояния) через `( return 0 2>/dev/null )` корректно уходит в re-exec
#   вместо засорения оболочки вызывающего и ложного rc. Дальнейшие находки
#   sourced-исполнения (DEBUG-trap, перекрытие имён, enable -n и т.п.) FAIL'ом
#   предмета НЕ являются — отклоняются ссылкой на §3 указанного арбитража.
if ( return 0 2>/dev/null ) || [[ "$(/usr/bin/tr '\0' '\n' < /proc/$$/environ)" != $'PATH=/usr/bin:/bin\nLC_ALL=C.UTF-8' ]]; then
  POSIXLY_CORRECT=1
  exec /usr/bin/env -i PATH=/usr/bin:/bin LC_ALL=C.UTF-8 /usr/bin/bash "${BASH_SOURCE[0]}" "$@"
fi
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_TEMPLATE_DIR GIT_CEILING_DIRECTORIES
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null
# ДОВЕРЕННЫЙ PATH — ДО ПЕРВОЙ ВНЕШНЕЙ КОМАНДЫ. Прецедент scripts/check_consumers.sh:41
# / scripts/check_protected.sh:81: ровно этот же класс обхода (PATH-shim
# успешного readlink/grep/awk), для role и charter каналов. Все инструменты,
# которым барьер доверяет (readlink, grep, awk), резолвятся из $PATH —
# фиксируем PATH в /usr/bin:/bin и отрезаем любой подложенный каталог из
# вызывающего окружения.
export PATH=/usr/bin:/bin

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

die()  { printf '%s\n' "$*" >&2; exit 1; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

ROOT="${1:?использование: $0 <корень-дерева> <отн-путь-контракта>}"
CONTRACT_PATH="${2:?использование: $0 <корень-дерева> <отн-путь-контракта>}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd -P)" || skip "корня нет: $ROOT"
# CONTRACT_PATH: если абсолютный — отрезать ROOT-префикс; иначе — относительно ROOT.
case "$CONTRACT_PATH" in
  /*) CONTRACT_PATH="${CONTRACT_PATH#$ROOT/}" ;;
esac
CONTRACT_PATH="$(printf '%s' "$CONTRACT_PATH" | sed 's|^\./||; s|//|/|g')"
[ -f "$ROOT/$CONTRACT_PATH" ] || skip "контракта нет: $ROOT/$CONTRACT_PATH"
body="$(cat "$ROOT/$CONTRACT_PATH" 2>/dev/null || true)"
[ -n "$body" ] || skip "тело контракта пусто: $ROOT/$CONTRACT_PATH"

# ── г0: поле ПРОВОДКА + канальные строки ──────────────────────────────────────
# Шапка `ПРОВОДКА:` обязательна; под ней — 1..N строк, начинающихся с `- ` и
# описывающих каналы. Каждая такая строка должна матчиться ровно одним из трёх
# каналов; иначе — «вне грамматики» с САМОЙ строкой.
header_line="$(printf '%s\n' "$body" | sed -nE '/^ПРОВОДКА:[[:space:]]*$/ {p}' | head -n 1)"
[ -n "$header_line" ] || die "проводка: поле ПРОВОДКА отсутствует"

mapfile -t all_lines < <(printf '%s\n' "$body")
header_idx=-1
for ((i=0; i<${#all_lines[@]}; i++)); do
  if [ "${all_lines[$i]}" = "$header_line" ]; then
    header_idx=$i
    break
  fi
done
[ "$header_idx" -ge 0 ] || die "проводка: поле ПРОВОДКА отсутствует"

channel_lines=()
for ((i=header_idx+1; i<${#all_lines[@]}; i++)); do
  ln="${all_lines[$i]}"
  case "$ln" in
    "#"*) break ;;
  esac
  case "$ln" in
    "- "*) channel_lines+=("$ln") ;;
  esac
done

[ "${#channel_lines[@]}" -gt 0 ] || die "проводка: поле пусто"

# ── Классификация каналов (г0 структура) ─────────────────────────────────────
# Каждая строка разбирается ровно один раз; неизвестный формат → отказ
# «строка вне грамматики» с САМОЙ строкой дословно.
channels=()
for ln in "${channel_lines[@]}"; do
  body_part="${ln#- }"
  kind=""
  case "$body_part" in
    guard=*)  kind="guard"  ;;
    role=*)   kind="role"   ;;
    charter=*) kind="charter" ;;
    *) die "проводка: строка вне грамматики: $ln" ;;
  esac
  rest="${body_part#*=}"
  channels+=("$kind|$rest|$ln")
done

# ── г0-доп (В1): guard-only без обоснования ──────────────────────────────────
# Без role/charter-канала и без непустой строки «ПРОВОДКА-ЭНФОРСМЕНТ:» —
# отказ ДО проверки каналов (контракт §Инварианты 3, В1).
has_role=0; has_charter=0; has_enf=0
for ch in "${channels[@]}"; do
  case "${ch%%|*}" in
    role)    has_role=1 ;;
    charter) has_charter=1 ;;
  esac
done
enf_line="$(printf '%s\n' "$body" | sed -nE '/^ПРОВОДКА-ЭНФОРСМЕНТ:[[:space:]]*(.*)$/{s//\1/p;q}')"
case "$enf_line" in
  '') ;;
  *)  [ -n "${enf_line//[[:space:]]/}" ] && has_enf=1 ;;
esac
if [ "$has_role" -eq 0 ] && [ "$has_charter" -eq 0 ] && [ "$has_enf" -eq 0 ]; then
  die "проводка: guard-only поле без предметного канала и строки ПРОВОДКА-ЭНФОРСМЕНТ"
fi

# ── г1..г6: проверка каналов (первая красная строка своего канала) ────────────
# Парсинг role/charter: путь + норма-строка. Кавычки «…» — СТРОГО обрамляют
# норма-строку ЦЕЛИКОМ (контракт §Инварианты 1, круг 5 Б2). Вход extract_quoted
# ОБЯЗАН после trim'а ведущих/хвостовых ASCII-пробелов быть ровно `«<содержимое>»`,
# где содержимое не содержит ни « ни ». Этим закрыты: мусор до первой «, мусор
# после последней » и вложенные «…» внутри норма-строки. Любое отклонение → rc 1
# «строка вне грамматики» с самой строкой канала (новую фразу причины НЕ вводим).
extract_quoted() {
  local s="$1"
  # Trim ведущих ASCII-пробелов.
  s="${s#"${s%%[![:space:]]*}"}"
  # Trim хвостовых ASCII-пробелов.
  s="${s%"${s##*[![:space:]]}"}"
  # Вход ОБЯЗАН начинаться на « и заканчиваться на » (после trim'а).
  case "$s" in
    «*) ;;
    *) printf ''; return 1 ;;
  esac
  case "$s" in
    *») ;;
    *) printf ''; return 1 ;;
  esac
  # Содержимое — между первой « и последней »; в нём НЕ должно быть ни « ни »
  # (вложенные пары запрещены, контракт §Инварианты 1).
  local content="${s#«}"
  content="${content%»}"
  case "$content" in
    *«*|*"»"*) printf ''; return 1 ;;
  esac
  printf '%s' "$content"
}

# Компонент role-пути после снятия литерального префикса `roles/` (Л) или
# `$ROOT/roles/` (К): остаток обязан быть НЕПУСТ, не содержать '/', иметь
# суффикс `.md`, и оставшаяся база — НЕПУСТА. Общий предикат Л+К (решение
# арбитра 9cea9c3); используется в обоих местах, чтобы поведение Л и К
# было ПОБАЙТОВО эквивалентно.
role_component_ok() {
  local r="$1"
  # «нет /» — ЛИТЕРАЛЬНЫЙ паттерн */* (безопасная форма, §3 Н-39: не
  # использовать `[...]`-классы в `case`-паттернах).
  case "$r" in
    */*) return 1 ;;
  esac
  # «суффикс .md снят» — требует НАЛИЧИЯ суффикса; путь типа `roles`
  # отсекается раньше (на стороне Л префикс `roles/` обязан сниматься).
  case "$r" in
    *.md) ;;
    *) return 1 ;;
  esac
  # «база непуста» — после снятия `.md` остаток ненулевой длины; закрывает
  # `roles/.md` (база = «»).
  local base="${r%.md}"
  [ -n "$base" ]
}

# Подключение guard-имени: имя скрипта (без .sh) матчится как СЛОВО в не-
# закомментированной строке вызова в `.githooks/*` или `.github/workflows/*.yml`.
# Комментарий sh (`#`-строки) и закомментированный yml-шаг (строки, чей
# первый не-пробельный символ `#`) НЕ считаются (контракт §Инварианты 3, г2).
guard_is_wired() {
  local root="$1" guard="$2"
  local bname="${guard##*/}"; bname="${bname%.sh}"
  local githooks_dir="$root/.githooks" wf_dir="$root/.github/workflows"
  local found=0
  if [ -d "$githooks_dir" ]; then
    while IFS= read -r -d '' f; do
      while IFS= read -r line; do
        trimmed="${line#"${line%%[![:space:]]*}"}"
        case "$trimmed" in '#'*) continue ;; esac
        case "$trimmed" in
          *"$bname"*)
            if printf '%s' "$line" | grep -Eq "(^|[^[:alnum:]_])${bname}([^[:alnum:]_]|$)"; then
              found=1
              break 2
            fi
            ;;
        esac
      done < "$f"
    done < <(find "$githooks_dir" -maxdepth 1 -type f -print0 2>/dev/null)
  fi
  if [ "$found" -eq 0 ] && [ -d "$wf_dir" ]; then
    while IFS= read -r -d '' f; do
      case "$f" in *.yml|*.yaml) ;; *) continue ;; esac
      while IFS= read -r line; do
        trimmed="${line#"${line%%[![:space:]]*}"}"
        case "$trimmed" in '#'*) continue ;; esac
        case "$trimmed" in
          *"$bname"*)
            if printf '%s' "$line" | grep -Eq "(^|[^[:alnum:]_])${bname}([^[:alnum:]_]|$)"; then
              found=1
              break 2
            fi
            ;;
        esac
      done < "$f"
    done < <(find "$wf_dir" -type f \( -name '*.yml' -o -name '*.yaml' \) -print0 2>/dev/null)
  fi
  [ "$found" -eq 1 ]
}

# Тело секции устава: точный матч заголовка (`^#+ <текст>$`, побайтовое
# равенство); тело — от строки заголовка до следующего заголовка ТОГО ЖЕ или
# БОЛЕЕ высокого уровня (`#` или то же число `#` и менее).
# Аргумент $1 — путь К ФАЙЛУ устава; в круге 6 это `/proc/self/fd/11`
# (atomic-fd реад, Б2б — повторное открытие по имени запрещено).
charter_section_body() {
  local file="$1" header_text="$2"
  awk -v h="$header_text" '
    {
      if (match($0, /^#+[[:space:]]+/)) {
        cur_lvl = RLENGTH - 1
        cur_text = substr($0, RSTART+RLENGTH)
        if (cur_text == h && !in_body) { start_lvl = cur_lvl; in_body = 1; next }
        if (in_body && cur_lvl <= start_lvl) { in_body = 0; next }
      }
      if (in_body) print
    }
  ' "$file"
}

for ch in "${channels[@]}"; do
  kind="${ch%%|*}"
  rest="${ch#*|}"; rest="${rest%%|*}"
  orig="${ch##*|}"
  case "$kind" in
    guard)
      guard="$rest"
      [ -f "$ROOT/$guard" ] || die "проводка: guard-файл не существует: $guard"
      guard_is_wired "$ROOT" "$guard" \
        || die "проводка: guard не подключён: $guard не вызывается в .githooks/ или .github/workflows/"
      ;;
    role)
      path="${rest%% *}"
      rest_after_path="${rest#* }"
      norm="$(extract_quoted "$rest_after_path")" \
        || die "проводка: строка вне грамматики: $orig"
      [ -n "$norm" ] || die "проводка: строка вне грамматики: $orig"
      # Л — лексическая форма role-канала (контракт 038 §Инварианты 1, круг 4):
      # литеральный префикс `roles/` обязан сниматься, остаток не содержит '/',
      # суффикс `.md` обязан быть, база после снятия `.md` НЕПУСТА. Закрывает
      # круги 1 (не-roles/), 2 (traversal) и Б2 круга 3 (пустая база). Сравнение
      # `[ "$path" != "$role_lex_rest" ]` — безопасная проверка снятия
      # литерального префикса (без glob-ловушки §3 Н-39).
      role_lex_rest="${path#roles/}"
      if [ "$path" = "$role_lex_rest" ] || ! role_component_ok "$role_lex_rest"; then
        die "проводка: role-канал обязан ссылаться строго на roles/<роль>.md, получено: $path"
      fi
      # Круг 6 Б1 — ОДИН атомарный open через ИМЕНОВАННЫЙ дескриптор: неуспешный
      # open ЕСТЬ несуществование файла (заменяет отдельный `[ -f ]`). Дескриптор
      # биндится к inode на уровне ядра — подмена объекта по имени `$ROOT/$path`
      # ПОСЛЕ открытия уже не меняет содержимого, читаемого через
      # `/proc/self/fd/9`. Закрывает РЕЦИДИВ TOCTOU postk5-репро.
      # Круг 8 Б4 — дешёвый не-блокирующий тип-чек ПЕРЕД exec-open: `[ -f ]` ложен
      # на FIFO/устройстве/каталоге, и `exec 9<"$ROOT/$path"` блокировался бы на
      # FIFO без открытого на запись конца (ядро ждёт писателя). Возвращаем
      # именной rc 1 ТЕМ ЖЕ сообщением, что несёт г3-фолбэк (fail-closed, без
      # новых фраз; атомарный exec-open и пост-open `[ -f "/proc/self/fd/9" ]`
      # ОБА остаются на месте, двойная проверка дешевле возможного зависания).
      [ -f "$ROOT/$path" ] || die "проводка: role-файл не существует: $path"
      if ! { exec 9<"$ROOT/$path"; }; then
        die "проводка: role-файл не существует: $path"
      fi
      # Г3-фолбэк: на некоторых системах `exec <` на каталоге возвращает валидный
      # fd (read даёт EISDIR). Явная проверка типа через тот же /proc/self/fd —
      # fail-closed для не-регулярных файлов.
      [ -f "/proc/self/fd/9" ] || {
        exec 9<&- || true
        die "проводка: role-файл не существует: $path"
      }
      # К — канонизация через дескриптор: `readlink -f /proc/self/fd/9`
      # даёт канонический путь ТОГО, что РЕАЛЬНО открыто (не пересчёт по имени).
      # Та же проверка «резолв лежит плоско под $ROOT/roles/» через тот же
      # предикат role_component_ok — fail-closed. Пустой/неуспешный readlink —
      # отказ.
      resolved="$(readlink -f -- "/proc/self/fd/9" 2>/dev/null || true)"
      if [ -z "$resolved" ] || ! role_component_ok "${resolved#"$ROOT"/roles/}"; then
        exec 9<&- || true
        die "проводка: role-канал обязан ссылаться строго на roles/<роль>.md, получено: $path (резолв: $resolved)"
      fi
      # г4 — норма-строка ищется через ТОТ ЖЕ дескриптор (круг 6 Б1, закрывает
      # рецидив TOCTOU): grep читает `/proc/self/fd/9`, не `$resolved`
      # и не `$ROOT/$path` — повторного открытия по имени НЕТ. Подмена файла по
      # пути ПОСЛЕ открытия не меняет содержимого, которое видит grep.
      if ! grep -Fxq -- "$norm" "/proc/self/fd/9"; then
        exec 9<&- || true
        die "проводка: норма-строка не найдена в role-файле: $path"
      fi
      exec 9<&- || true
      ;;
    charter)
      path="${rest%% *}"
      rest_after_path="${rest#* }"
      case "$rest_after_path" in
        '§'*) ;;
        *) die "проводка: строка вне грамматики: $orig" ;;
      esac
      rest_after_section="${rest_after_path#§}"
      # header_text: от § до ПЕРВОГО « (норма-строка обрамлена кавычками; вложенные «»
      # внутри норма-строки запрещены, контракт §Инварианты 1).
      header_text="${rest_after_section%%«*}"
      # Круг 6 Б3 — ОБЯЗАТЕЛЬНЫЙ пробельный разделитель между заголовком и
      # открывающей «. Грамматика: `§<полный заголовок секции> «<норма>»`,
      # ровно один (или более) ASCII-пробел перед «. Без пробела — строка
      # вне грамматики. Проверка ДО тримминга хвостовых пробелов (закреплена
      # на КОНКРЕТНОЙ позиции — конец header_text — anchored character-class
      # на «пробел», не открытый `[^/]*`-баг Н-39: класс фиксирован, не
      # pattern с подстановкой).
      case "$header_text" in
        *[[:space:]]) ;;
        *) die "проводка: строка вне грамматики: $orig" ;;
      esac
      # trim trailing whitespace — для матча заголовка в awk
      header_text="${header_text%"${header_text##*[![:space:]]}"}"
      # norm-пара: от ПЕРВОГО « до конца строки (норма-строка обязан
      # заканчиваться на »). Здесь extract_quoted получает вход, который
      # после trim'а начинается с « — ровно та форма, которую ждёт строгая
      # грамматика «ровно «<содержимое>»». Без этого шага вход содержал бы
      # header_text ДО «, и строгая extract_quoted отказала бы легитимным
      # charter-строкам; канал и роль передают в extract_quoted одну форму.
      norm_part="${rest_after_section#*«}"
      norm_part="«${norm_part}"
      norm="$(extract_quoted "$norm_part")" \
        || die "проводка: строка вне грамматики: $orig"
      [ -n "$norm" ] || die "проводка: строка вне грамматики: $orig"
      # Круг 6 Б2а — target pinning: charter-канал обязан ссылаться РОВНО на
      # `AGENTS.md` (грамматика контракта литерально). Любая другая цель —
      # вне грамматики (тот же класс причины, что и parser-laxity). Проверка
      # ПЕРЕД любым ФС-доступом (fail-fast, без лишних вызовов open/readlink).
      [ "$path" = "AGENTS.md" ] || die "проводка: строка вне грамматики: $orig"
      # Круг 6 Б2б — ОДИН атомарный open через ИМЕНОВАННЫЙ дескриптор: дескриптор
      # биндится к inode AGENTS.md на момент открытия. Подмена файла по имени
      # ПОСЛЕ открытия (PATH-shim на awk в postk5-репро) уже не меняет
      # содержимого, читаемого через `/proc/self/fd/11`. Г3-фолбэк —
      # явная проверка типа через тот же /proc/self/fd (fail-closed).
      # Круг 8 Б4 — дешёвый не-блокирующий тип-чек ПЕРЕД exec-open: `[ -f ]` ложен
      # на FIFO/устройстве/каталоге, и `exec 11<"$ROOT/$path"` блокировался бы на
      # FIFO без открытого на запись конца (ядро ждёт писателя). Возвращаем
      # именной rc 1 ТЕМ ЖЕ сообщением, что несёт г3-фолбэк (fail-closed, без
      # новых фраз; атомарный exec-open и пост-open `[ -f "/proc/self/fd/11" ]`
      # ОБА остаются на месте, двойная проверка дешевле возможного зависания).
      [ -f "$ROOT/$path" ] || die "проводка: секция устава не найдена: §${header_text}"
      if ! { exec 11<"$ROOT/$path"; }; then
        die "проводка: секция устава не найдена: §${header_text}"
      fi
      [ -f "/proc/self/fd/11" ] || {
        exec 11<&- || true
        die "проводка: секция устава не найдена: §${header_text}"
      }
      # Канонизация через дескриптор. У charter ЕДИНСТВЕННАЯ легитимная цель —
      # сам `$ROOT/AGENTS.md` (byte-в-byte, без alias/symlink-индирекции).
      # Несовпадение — переиспользуем существующую фразу «секция устава не
      # найдена» (тот же класс причины, что «файла нет» / «секции в файле
      # нет»; новую фразу НЕ вводим, канон §0).
      resolved="$(readlink -f -- "/proc/self/fd/11" 2>/dev/null || true)"
      if [ "$resolved" != "$ROOT/AGENTS.md" ]; then
        exec 11<&- || true
        die "проводка: секция устава не найдена: §${header_text}"
      fi
      # Тело секции через ТОТ ЖЕ дескриптор: awk получает `/proc/self/fd/11`
      # вместо `$ROOT/$path` — повторного открытия по имени нет. Закрывает
      # awk-PATH-shim из postk5-репро (Б2б): даже если внешний awk был подменён
      # и подменил файл ПОСЛЕ exec — fd по-прежнему указывает на СТАРЫЙ inode.
      section_body="$(charter_section_body "/proc/self/fd/11" "$header_text")"
      if [ -z "$section_body" ]; then
        exec 11<&- || true
        die "проводка: секция устава не найдена: §${header_text}"
      fi
      if ! printf '%s\n' "$section_body" | grep -Fxq -- "$norm"; then
        exec 11<&- || true
        die "проводка: норма-строка не найдена в теле секции §${header_text}"
      fi
      exec 11<&- || true
      ;;
  esac
done

exit 0
