#!/usr/bin/env bash
# Защищённый артефакт: СУЩЕСТВОВАЛ — обязан существовать на HEAD.
#
# Инвариант от РЕЗУЛЬТАТА, а не от способа. На соседнем проекте это правило переписывали
# трижды, и каждый раз по одной причине: прежние редакции гонялись за СПОСОБОМ исчезновения
# файла. Запретили удаление — нашлось переименование. Запретили переименование — нашлось
# слияние `-s ours`, где файл исчезает без единого diff'а с удалением. Запретили и его —
# нашлось добавление-и-удаление внутри одной ветки, где на кончиках истории файла нет вовсе.
# Способов исчезнуть больше, чем можно перечислить; результат один, и правило от результата
# ловит их все одним предложением.
#
# КАК СЧИТАЕТСЯ «СУЩЕСТВОВАЛ». Объединение деревьев ВСЕХ коммитов, достижимых от HEAD.
# Именно достижимость закрывает `-s ours`: коммиты влитой стороны достижимы через второго
# родителя слияния, их деревья содержат файл, а HEAD — нет. Она же закрывает
# добавление-и-удаление: промежуточный коммит достижим, хотя на кончиках файла не видно.
#
# ОБЛАСТЬ ВЫВЕДЕНА, А НЕ ЗАДАНА СПИСКОМ. Каталоги вердиктов берутся из `roles/*.md`, поля
# `verdict:`: новая роль защищается сама, без правки этого файла. Список, набранный руками,
# отстал бы ровно на одну роль и молча — за одну сессию в этом репозитории добавление
# области дважды сразу находило необъявленное. `plans/` объявлен здесь явно и с причиной:
# план — единственный защищаемый артефакт, который не принадлежит ни одной роли, его пишет
# живая сессия.
#
# ИСКЛЮЧЕНИЕ ТОЛЬКО ЯВНОЕ И ТОЛЬКО ИМЕННОЕ:
#
#   ALLOW-ARTIFACT-DELETE: <путь> <причина>
#
# в теле любого коммита, достижимого от HEAD. План 005 §4 требовал лишь наличия строки в
# теле; здесь строка ОБЯЗАНА назвать путь и причину, и вот почему: безымянная строка — это
# индульгенция, она снимает защиту со всего дерева навсегда, потому что тело коммита уже не
# переписать. Разрешение на один файл и разрешение на все — разные предметы, и в истории их
# нечем развести. Усиление против плана записано здесь намеренно: норма, изменённая молча,
# наследуется всем, что построят по ней потом.
#
# Обратная сверка (исключение есть, а файл на месте) НЕ делается намеренно: файл могли
# вернуть, а тело коммита не переписать. Гейт, краснеющий на прошлом, которое уже нельзя
# исправить, отучает себе верить.
#
# Зелёная ветвь — принятое исключение — проверяется не фикстурой, а
# `scripts/drill_protected_exception.sh`: анти-плацебо доказывает только КРАСНОЕ, и
# непроверенное зелёное ветвление означало бы, что единственный законный способ удалить
# артефакт закрыт, а правило начнут обходить, а не соблюдать.
#
# ГРАНИЦА ЭТОГО БАРЬЕРА, названная прямо. «Существовал» здесь означает «существовал в графе,
# достижимом от HEAD». Перезапись истории (`reset --hard` назад, `amend`, `rebase`,
# `filter-branch`) выносит коммит из этого графа, и барьеру просто не дают доказательств.
# Гнаться за этим здесь нельзя: измерено — `git fsck --unreachable --no-reflogs` в этом
# репозитории показывает 3 недостижимых коммита от обычной работы, то есть такая область
# краснела бы на честном дереве. Исчезновение ИСТОРИИ — отдельный предмет, и у него отдельный
# барьер: `scripts/check_no_rewrite.sh`, которому проводка сообщает прежнюю вершину ветки.
#
# УСЕЧЁННАЯ ИСТОРИЯ — ОТКАЗ, А НЕ «НЕЧЕМ ПРОВЕРИТЬ». `actions/checkout` по умолчанию берёт
# глубину 1, и на таком дереве объединение достижимых коммитов равно самому HEAD: барьер стал
# бы ПУСТО-ЗЕЛЁНЫМ и подтверждал бы инвариант, ничего не проверив. Молчаливо зелёный гейт
# хуже красного, потому что красному ищут причину, а зелёному верят. Поэтому здесь код 1 с
# названной причиной, а не 2: 2 означало бы «нечем проверить» и в CI выглядело бы как
# особенность окружения, тогда как лечится это одной строкой `fetch-depth: 0`.
#
#   bash scripts/check_protected.sh            проверить это дерево
#   bash scripts/check_protected.sh <корень>   проверить другое дерево (так он предъявляется
#                                              красным против обманных заглушек)
#
# Коды возврата: 0 — ни один защищённый артефакт не исчез, 1 — исчез, 2 — нечем проверить.
# ГЕРМЕТИЧНОЕ ОКРУЖЕНИЕ — RE-EXEC ЧЕРЕЗ `env -i` (контракт 046, Н-130). ДО ЛЮБОЙ ДРУГОЙ СТРОКИ
# КОДА, даже до `set -euo pipefail` и `unset GIT_DIR …` ниже: экспортированная bash-функция с
# ИМЕНЕМ ЛЮБОЙ утилиты переживает старт этого процесса через сериализацию
# `BASH_FUNC_<имя>%%=() {…}` в окружении (механизм Shellshock) и резолвится РАНЬШЕ $PATH при
# каждом голом вызове имени. Доверенный PATH ниже закрывает ПОДЛОЖЕННЫЙ КАТАЛОГ, но не таблицу
# функций процесса: живой замер контракта 046 на ЭТОМ файле — унаследованная тень `comm`,
# отдающая пусто на `-23` (разность `existed`\`head`), делает исчезновение защищённого
# артефакта БЕЗ единой строки ALLOW молча зелёным (rc=0, ни одного `FAIL` в выводе).
#
# ЛЕЧЕНИЕ ПО ПРЕЦЕДЕНТУ, НЕ ИЗОБРЕТАЕТСЯ ЗАНОВО. `scripts/check_zones.sh` прошёл этот класс до
# конца (контракт 040, круги v5-v7): ПЕРЕЧИСЛЕНИЕ (`unset -f <14 имён>`) там ПАЛО — экспорти-
# рованная функция `unset`, no-op'ящая ИМЕННО `-f`-форму и честная на `unset VAR`, снимает
# такую защиту целиком, а сам `unset` в список войти не может, потому что список есть то, ЧЕМ
# снимают (verdicts/adversary/contracts-040-v5-circle.md, `d46a615`). Поэтому здесь СРАЗУ
# структурная форма, без промежуточной ступени: `env -i` строит дочернему процессу окружение
# из ПУСТОГО множества плюс явный allowlist — ни один `BASH_FUNC_<имя>%%` не переживает
# границу, независимо от имени утилиты и от того, откуда её зовут.
#
# ПРОВЕРКА — ПО ФАКТИЧЕСКОМУ ОКРУЖЕНИЮ ПРОЦЕССА (`/proc/$$/environ`), НЕ ПО ФЛАГУ-ЧАСОВОМУ.
# Часовой вида `[ -z "$REEXECED" ] || …` подделывается: вызывающий заранее выставляет флаг в
# своей отравленной среде, и остаток файла исполняется БЕЗ re-exec вовсе (тот же класс дыры
# закрыт на соседнем барьере: `scripts/check_no_leak.sh`, адверсарий к5, `4dfc0ff`). Сверка с
# КАНОНИЧЕСКИМ БАЙТОВЫМ содержимым всего окружения не подделывается тем же движением: чтобы
# пройти «окружение РОВНО {PATH, LC_ALL}», атакующему пришлось бы не иметь своего
# `BASH_FUNC_*` вовсе. Порядок переменных в строке сравнения обязан совпадать с порядком
# аргументов `env -i` — `env` кладёт их в environ в порядке аргументов; расхождение дало бы
# вечный re-exec. `$(…)` обрезает хвостовые переводы строк, поэтому сравнение с
# `$'PATH=…\nLC_ALL=…'` корректно и после `tr '\0' '\n'`.
#
# ДВЕ ПЕРЕМЕННЫЕ В ALLOWLIST, НИ ОДНОЙ ЛИШНЕЙ (каждая протащенная непроверенной — канал
# протаскивания отравы, например `GIT_CONFIG_GLOBAL` вызывающего вместо `/dev/null` ниже):
#   PATH   — доверенный резолв git/comm/mkdir/mktemp/sort/awk/grep/wc/tr/sed/rm/dirname; та же
#            доктрина, что `export PATH=/usr/bin:/bin` ниже. Та строка сохранена намеренно:
#            вторичная защита и побайтовое diff-сравнение с прецедентом (`check_zones.sh`
#            держит свой `export PATH=…` рядом со своим re-exec по той же причине).
#   LC_ALL — отказы и `ok`-строки этого барьера несут кириллицу, а пути в защищаемой области
#            могут быть многобайтовыми; под C-локалью символьные классы на UTF-8 небезопасны
#            (прецедент `scripts/check_decisions.sh`). Значение взято дословно из
#            `check_zones.sh`/`check_provodka.sh`, не изобретается заново.
#   HOME и TMPDIR НЕ протаскиваются: ни одна строка этого файла не читает `$HOME` (сверено
#   grep'ом), а скратч — явный путь С каталогом (`$ROOT/tmp/protected.XXXXXX`), для которого
#   `mktemp` `$TMPDIR` не читает. Не протащенный TMPDIR закрывает канал, которым вызывающий
#   подсунул бы барьеру подконтрольный каталог скратча.
#
# CWD НЕ ТРОГАЕТСЯ: ни `env`, ни `bash` не делают `chdir` — дочерний процесс наследует рабочий
# каталог через `fork`, а не через переменную `PWD` (её `env -i` стирает). Относительный
# аргумент-корень (`${1:-…}` ниже) резолвится в ROOT ТОЧНО так же, как до re-exec.
#
# `POSIXLY_CORRECT=1` СТРОКОЙ ВЫШЕ `exec` — присваивание, а не команда: тенью-функцией не
# перехватывается и немедленно включает POSIX-режим, в котором `exec` резолвится как SPECIAL
# BUILTIN раньше пользовательской функции с тем же именем (арбитраж 040-III, вектор H:
# `exec() { return 0; }` в окружении не съедает переход). Абсолютные пути у `env` и `bash`
# ОБЯЗАТЕЛЬНЫ, но НЕ ДОСТАТОЧНЫ: bash допускает функцию с ЛИТЕРАЛЬНЫМ слэшем в имени
# (`function /usr/bin/env { …; }`), объявленную через сорсинг `BASH_ENV` ДО первой строки
# файла, и она перехватывает вызов по абсолютному пути. Это НАЗВАННЫЙ ОСТАТОК — класс
# «враждебное ОКРУЖЕНИЕ ВЫЗОВА» (`BASH_ENV`/`ENV`, slash-функции, `SHELLOPTS`, сорсинг),
# структурно незакрываемый изнутри скрипта (verdicts/arbitration/
# contracts-040-vrazhdebnoe-okruzhenie-predel.md): точки исполнения раньше отравителя у
# скрипта нет в принципе. Блок снижает класс до РЕАЛИСТИЧНОГО — честный вызывающий с
# засорённым унаследованным окружением; полное закрытие существует РОВНО в одной точке —
# ВЫЗОВЕ барьера доверенной стороной как
# `env -i PATH=/usr/bin:/bin LC_ALL=C.UTF-8 bash scripts/check_protected.sh …` — это цена и
# воля ВЛАДЕЛЬЦА, а не предмет этого контракта.
#
# ИЗМЕРИТЕЛЬНОЕ СЛЕДСТВИЕ, ЗАКРЫТОЕ ТЕМ ЖЕ КОНТРАКТОМ: re-exec стирает и ИЗМЕРИТЕЛЬНЫЕ
# переменные вызывающего (`SHELLOPTS=xtrace`, `BASH_XTRACEFD`), поэтому счётчик git-вызовов
# `fixtures/check_protected/red_predel_git_vyzovov_ours.sh` (постоянный CI-страж контракта
# 040, §Приёмка Р2) переведён на ВНЕШНЮЮ `strace -f -e trace=execve` — канал ядра, который
# субъект не может стереть ничем, что делает со своими переменными. Тот же переход на
# близнеце уже сделан ревью-кругом 040 (`b38e78a`); без него страж считал бы НОЛЬ вызовов на
# любом входе и был бы ЗЕЛЕНЕЕ предмета.
#
# ОСТАТОЧНОЕ: `/proc/$$/environ` — Linux/procfs, тот же прецедент и тот же принятый риск, что
# уже несут `check_zones.sh` и `check_provodka.sh` (окружение исполнения проекта — Linux, CI и
# рабочая станция).
if ( return 0 2>/dev/null ) || [[ "$(/usr/bin/tr '\0' '\n' < /proc/$$/environ)" != $'PATH=/usr/bin:/bin\nLC_ALL=C.UTF-8' ]]; then
  POSIXLY_CORRECT=1
  exec /usr/bin/env -i PATH=/usr/bin:/bin LC_ALL=C.UTF-8 /usr/bin/bash "${BASH_SOURCE[0]}" "$@"
fi
set -euo pipefail

# Унаследованные git-переменные ПОДМЕНЯЮТ предмет до первой команды: адверсарий предъявил
# ложное ЗЕЛЁНОЕ через `GIT_DIR` и `GIT_WORK_TREE` на механизме 2 и неустойчивость дрилла на
# механизме 4. Барьер обязан смотреть на дерево, которое ему назвали аргументом, а не на то,
# которое подсунуло окружение.
unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_TEMPLATE_DIR GIT_CEILING_DIRECTORIES
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null

# ДОВЕРЕННЫЙ PATH — ДО ПЕРВОЙ ВНЕШНЕЙ КОМАНДЫ. Адверсарий круга 1 контракта 039 предъявил,
# что `comm -23 …` (разность `existed` и `head` → `missing`) резолвится через унаследованный
# $PATH: фейковый `comm` с rc0 и пустым выводом делает ЛЮБОЕ удаление без ALLOW зелёным
# (компрометация ВСЕГО барьера, не только новой фичи переноса). Тот же вектор закрывает
# git, mkdir, mktemp, sort, awk и пр., потому что все они внешние. Фиксируем PATH здесь и
# ниже проверяем наличие нужных утилит по именам — отсутствие даёт именной rc=2, а не
# молчаливый зелёный «нечем отказать».
export PATH=/usr/bin:/bin

ROOT="$(cd "${1:-"$(dirname "${BASH_SOURCE[0]}")/.."}" && pwd)"
cd "$ROOT"

fails=0
ok()   { printf '  ok   %s\n' "$*" >&2; }
bad()  { fails=$((fails + 1)); printf '  FAIL %s\n' "$*" >&2; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }
command -v git >/dev/null 2>&1  || skip "нет git в доверенном PATH — истории нет"
# comm — та самая утилита, чей подмен даёт зелёное без ALLOW. Если её нет в доверенном
# PATH, барьер ОБЯЗАН отказать с именным rc=2, а не считать пустую разность зелёной.
command -v comm >/dev/null 2>&1 || skip "нет comm в доверенном PATH — разность множеств нечем считать"
git rev-parse --git-dir >/dev/null 2>&1 || skip "$ROOT не репозиторий git — истории нет"
git rev-parse --verify HEAD >/dev/null 2>&1 || skip "в $ROOT нет ни одного коммита"
if [ "$(git rev-parse --is-shallow-repository)" = "true" ]; then
  printf 'ОТКАЗ: история усечена (shallow) — на глубине 1 инвариант подтверждается сам собой\n' >&2
  printf 'Лечится в проводке: actions/checkout с fetch-depth: 0.\n' >&2
  exit 1
fi

# ОРАКУЛ Н-127/арбитраж 042 (verdicts/arbitration/042-dostatochnost-merge-base-semantiki.md)
# — `git merge-tree --write-tree`, доступен с git ≥ 2.38 (2022). Проба на HEAD HEAD: слияние
# коммита с самим собой бесконфликтно на ЛЮБОЙ версии, которая опознаёт --write-tree/
# --no-messages/-z; более старый git не опознаёт эти флаги и завершается не rc 0/1. Молчаливый
# обход здесь хуже отказа: без оракула классифицировать мерж-артефакты нечем, а тихо считать
# каждый мерж настоящим кандидатом — это не «безопасная» деградация, а другая, не объявленная
# контрактом семантика. Отказ — именной rc=2, тот же класс, что «нет comm в PATH» выше.
git merge-tree --write-tree --no-messages -z HEAD HEAD >/dev/null 2>&1 \
  || skip "git merge-tree --write-tree недоступен (нужен git ≥ 2.38) — оракул мерж-семантики Н-127/арбитраж 042 нечем вычислить"

mkdir -p "$ROOT/tmp"
TMP="$(mktemp -d "$ROOT/tmp/protected.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT

# ── область ───────────────────────────────────────────────────────────────────
# Каталоги вердиктов берутся из ролей ВО ВСЕХ достижимых коммитах, а не только на HEAD:
# область, взятая с HEAD, служила ВЫКЛЮЧАТЕЛЕМ защиты — удали файл роли вместе с её
# вердиктами (или замени поле на `null`), и каталог перестаёт входить в область. Защита,
# которую снимает тот же коммит, что и удаляет предмет, защитой не является.
#
# НЕРАЗОБРАННОЕ ОБЪЯВЛЕНИЕ — ОТКАЗ, А НЕ ТИШИНА. Так решил арбитраж
# `verdicts/arbitration/oblast-i-porog.md`, вопрос 1, и созван он был потому, что молчаливое
# сужение области — это КЛАСС, а не форма: `null`, затем шаблон `verdicts/*/`, затем поле ниже
# 20-й строки — каждая новая непонятная форма давала тишину, и закрывалась по одной. Отказ
# переворачивает знак: любая новая форма даёт красное.
#
# Грамматика поля объявлена здесь и проверяется целиком: поле `verdict:` обязано лежать во
# ФРОНТМАТТЕРЕ (первый блок между `---`), читаемом без числового лимита строк; значение —
# `null` либо буквальный относительный префикс каталога: завершается `/`, без `*?[`, без
# ведущего `/`, без `..`, без пробелов. Всё иное — код 1 с именем файла, блобом и значением.
# Валидированное значение уходит в git как БУКВАЛЬНЫЙ pathspec (`:(literal)`), чтобы проверка
# и употребление не разошлись: прежняя редакция валидировала одно, а передавала другое.
#
# ОСТАТОЧНЫЙ РИСК, записан прямо: блоб, уже вросший в историю, переписью не лечится. На
# нынешнем main таких нет (арбитраж, замер 5), будущие ловятся этим же гейтом на push до
# врастания. Если всё же врастёт — именное исключение того же класса, что удаление артефакта:
# строка `ALLOW-UNPARSED-ROLE: <блоб> <причина>` в теле любого достижимого коммита.
: > "$TMP/roleblobs"
# ОСТАТОЧНЫЙ РИСК, записан прямо: блоб, уже вросший в историю, переписью не лечится. На
# нынешнем main таких нет (арбитраж, замер 5), будущие ловятся этим же гейтом на push до
# врастания. Если всё же врастёт — именное исключение того же класса, что удаление артефакта:
# строка `ALLOW-UNPARSED-ROLE: <блоб> <причина>` в теле любого достижимого коммита.

# ── BATCHED roleblobs (контракт 040, §Инварианты п.5 — техника diff-tree --stdin) ─
# Старая форма: per-commit `git ls-tree -r "$c" -- roles/` (≈N процессов; 23.538 с
# на реальном дереве 1944 коммито-окон). Заменена на ОДИН конвейер
#   git rev-list HEAD | git diff-tree -r --root -m --no-renames --raw --stdin \
#     -- ':(literal)roles/'
# `--root` обязателен (§Инварианты п.5): без него теряется путь, живущий с
# корневого коммита и никогда не менявшийся (замер арбитра З2). `-m` обязателен:
# без него merge-коммиты не диффятся (замер З2). `--no-renames` обязателен —
# иначе результат зависит от `diff.renames` конфига машины читателя (та же причина,
# что уже записана для `excuse_for`/`moved_for`). `--raw` — отдаёт mode И dst-blob
# одной строкой, mode прямо нужен для условия «жив КАК регулярный файл». Цена —
# ОДИН git-процесс на употребление вместо ≈1944.
#
# Разбор строки --raw при `--stdin` с `--root -m`: каждая запись имеет ЗАГОЛОВОК-коммит
# (40-hex SHA одной строкой) перед блоком raw-строк `:old_mode SP new_mode SP old_blob
# SP new_blob SP status<TAB>path`. Фильтр по `$1 ~ /^:/` отсекает SHA-заголовки.
# Из оставшихся полей `$2` — новая mode (100644/100755 — регулярный файл; 120000/
# 160000/040000 — симлинк/сабмодуль/каталог, отбрасываются), `$4` — new_blob, `$6` —
# path. Остаются блобы с mode 100644/100755, имя пути матчит `\.md$` (как и в исходной
# форме).
: > "$TMP/roleblobs"
git rev-list HEAD \
  | git diff-tree -r --root -m --no-renames --raw --stdin -- ':(literal)roles/' \
  | awk '
      $1 ~ /^:/ && $2 ~ /^(100644|100755)$/ {
        path = $6
        if (path ~ /\.md$/) {
          printf("%s\t%s\n", $4, path)
        }
      }
    ' >> "$TMP/roleblobs"
sort -u "$TMP/roleblobs" -o "$TMP/roleblobs"

# Прощённые блобы — по той же форме, что разрешение на удаление: путь-в-истории плюс причина.
: > "$TMP/unparsed_ok"
git log HEAD --pretty=format:%B \
  | awk 'sub(/^ALLOW-UNPARSED-ROLE:[[:space:]]*/, "") { print $1 }' >> "$TMP/unparsed_ok" || true

prefixes=()
while IFS= read -r line; do
  [ -n "$line" ] || continue
  blob="${line%%$'\t'*}"; path="${line#*$'\t'}"
  body="$(git cat-file blob "$blob" 2>/dev/null || true)"
  # Фронтматтер: первый блок между `---`, целиком.
  fm="$(awk 'NR==1 && $0 == "---" { inside = 1; next }
             inside && $0 == "---" { exit }
             inside { print }' <<<"$body")"
  v="$(awk 'sub(/^verdict:[[:space:]]*/, "") { sub(/[[:space:]]+$/, ""); print; exit }' <<<"$fm")"
  ok=0
  if [ "$v" = "null" ]; then
    ok=1
  elif [ -n "$v" ]; then
    case "$v" in
      /*|*..*|*\**|*\?*|*\[*|*[[:space:]]*) ok=0 ;;
      */)                                   ok=1 ;;
      *)                                    ok=0 ;;
    esac
  fi
  if [ "$ok" -eq 1 ]; then
    [ "$v" = "null" ] || prefixes+=(":(literal)$v")
  elif grep -qxF -e "$blob" "$TMP/unparsed_ok"; then
    ok "неразобранная роль прощена явно: $path ($blob)"
  else
    bad "роль вне объявленной грамматики: $path блоб $blob значение «${v:-нет поля verdict во фронтматтере}» — префикс обязан завершаться /, быть относительным, без шаблонов и ..; выход: привести к грамматике либо ALLOW-UNPARSED-ROLE: $blob <причина>"
  fi
done < "$TMP/roleblobs"
prefixes+=(":(literal)plans/")
mapfile -t prefixes < <(printf '%s\n' "${prefixes[@]}" | sort -u)

# ── что существовало хоть в одном достижимом коммите ──────────────────────────
# BATCHED existed.raw (§Инварианты п.5): ОДИН конвейер вместо per-commit ls-tree.
#   git rev-list HEAD | git diff-tree -r --root -m --no-renames --name-only --stdin
#     -- "${prefixes[@]}"
# Те же обязательные флаги `--root -m --no-renames`. `--name-only` достаточно — для
# `existed` нужны только пути (блобы не нужны на этом шаге; они появятся в
# `head_blobs` ниже через `ls-tree -r HEAD`). `--stdin` сорсы явных вызовов и
# снимает классический класс O(коммитов) пере-скана.
#
# Формат вывода `--name-only --stdin` при `--root -m`: SHA-заголовок перед блоком,
# затем пути блока; пустые коммиты (без дельты) ПРОПУСКАЮТСЯ целиком. Фильтруем
# SHA-строки (40 hex) перед `sort -u`, чтобы они НЕ попали в `$TMP/existed` —
# иначе `comm -23` сольёт их с `$TMP/head` (путями) и `missing` засорится блобами
# (наблюдалось на этом дереве; см. также риск 2 §Приёмка Р2 — лишнее про «без
# --root» — там же).
commits="$(git rev-list HEAD | wc -l | tr -d ' ')"
git rev-list HEAD \
  | git diff-tree -r --root -m --no-renames --name-only --stdin -- "${prefixes[@]}" \
  | grep -v '^[0-9a-f]\{40\}$' \
  > "$TMP/existed.raw"
sort -u "$TMP/existed.raw" > "$TMP/existed"
git ls-tree -r --name-only HEAD -- "${prefixes[@]}" | sort -u > "$TMP/head"
# Множество блобов на HEAD — для проверки «блоб B жив на HEAD хотя бы под одним путём КАК
# РЕГУЛЯРНЫЙ ФАЙЛ» (контракт 039, §Семантика п.1, условие Б, усиление круга 1). Снимается
# здесь ОДИН РАЗ, а не в цикле по каждому исчезнувшему пути: `git ls-tree -r HEAD` повторять
# N раз дорого, и перевычисление от ветки цикла одно и то же. `$TMP/head_blobs` — отсорти-
# рованное множество блобов всего дерева HEAD, не только защищённой области: путь q носителя
# перенесённого артефакта может жить и ВНЕ области защиты, и его блоб обязан считаться.
#
# РЕГУЛЯРНЫЙ ФАЙЛ, А НЕ ЛЮБОЙ НОСИТЕЛЬ. Адверсарий круга 1 предъявил, что чистый OID-матч
# принимает dangling symlink: git хранит цель симлинка как блоб, и тот же блоб уживается с
# mode 120000 на пути q — это непригодный носитель. Условие «жив на HEAD» здесь читается
# как «жив на HEAD КАК регулярный файл (mode 100644/100755)»; 120000/160000/040000
# отброшены фильтром ниже. mode — первое поле `git ls-tree`.
: > "$TMP/head_blobs.raw"
git ls-tree -r HEAD | awk '$1 ~ /^(100644|100755)$/ {print $3}' >> "$TMP/head_blobs.raw"
sort -u "$TMP/head_blobs.raw" > "$TMP/head_blobs"
rm -f "$TMP/head_blobs.raw"

# Разность считается `comm`, а не циклом на bash: это ДРУГАЯ мера, и она не повторяет способ,
# которым собраны оба множества.
comm -23 "$TMP/existed" "$TMP/head" > "$TMP/missing"

# ── исключение обязано лежать в ТОМ КОММИТЕ, который артефакт и убрал ─────────
# Прежняя редакция собирала разрешения из тел ВСЕХ достижимых коммитов в один вечный список.
# Адверсарий предъявил два следствия: разрешение годилось ПОВТОРНО после восстановления файла,
# и его можно было положить ЗАРАНЕЕ в посторонний коммит, а потом удалить артефакт молча.
# Разрешение обосновывает КОНКРЕТНОЕ удаление, а не выдаёт право на путь навсегда.
#
# Удаляющий коммит — последний достижимый, в котором путь исчез из дерева. `--no-renames`
# стоит намеренно: иначе результат зависел бы от `diff.renames` в конфиге машины, то есть мера
# меняла бы вердикт от настроек читателя. `-m` добавлен по находке круга 2: при конфликте
# modify/delete удаление окончательно решается в ТЕЛЕ мерж-коммита, и без `-m` такой коммит не
# рассматривается как удаляющий — законное удаление получало отказ.
#
# Строка разрешения обязана начинаться с ПЕРВОЙ КОЛОНКИ. Прежняя редакция отбрасывала любой
# отступ, и адверсарий предъявил, что цитата или фрагмент кода в теле коммита становились
# настоящим разрешением. Расширять язык разрешения молча нельзя: синтаксис объявлен в шапке,
# и мера обязана совпадать с объявлением.
#
# Путь в кавычках поддержан потому, что защищаемый путь может содержать пробел, а форма
# `<путь> <причина>` его не назовёт: тогда законное удаление получало отказ.
#
# Н-127 (contracts/042-excuse-for-otstavshij-roditel.md). `-m` показывает диф МЕРЖ-коммита
# ОТДЕЛЬНО против КАЖДОГО родителя. Если один родитель уже не содержит путь (удаление уже
# случилось РАНЬШЕ в истории, сведённой этим мержем), а другой родитель — «отставший», ещё не
# видевший удаления, — то относительно отставшего родителя сам мерж-коммит выглядит как D
# (путь исчез), хотя мерж ничего не удалял: он лишь унаследовал уже-отсутствующее состояние от
# НЕ-отстающего родителя. Мерж новее настоящего удаляющего коммита, и `sed -n 1p` брал именно
# его — тело мержа не несёт ALLOW-строку (её незачем повторять: разрешение уже сказано в
# настоящем удаляющем коммите), и легитимное удаление читалось как нарушение.
#
# ДВЕ РУЧНЫЕ АППРОКСИМАЦИИ ОКАЗАЛИСЬ НЕДОСТАТОЧНЫ КАК КЛАСС, А НЕ ТРЕМЯ ДЫРАМИ (круг 2 критика
# + арбитраж `verdicts/arbitration/042-dostatochnost-merge-base-semantiki.md`, разобравший обе
# и запретивший к ним возвращаться). Первая («путь отсутствует хотя бы у одного родителя»)
# путала «у родителя пути нет» с «мерж унаследовал его отсутствие»: путь, восстановленный и
# убранный ЗАНОВО поверх бесконфликтного слияния, читался как унаследованный. Вторая
# (сравнение OID пути с `git merge-base` двух родителей) чинила этот случай, но отвечала на
# ДРУГОЙ вопрос, чем нужно, и разошлась с реальным git по двум независимым осям: state пути —
# это (mode, oid), а не голый oid (git различает modify/delete-конфликт по РЕЖИМУ даже при
# неизменном содержимом — сравнение по одному oid молчало); баз слияния бывает больше одной
# (`git merge-base` без `--all` не сообщает о неоднозначности), и criss-cross-топология
# получала ПРОИЗВОЛЬНЫЙ, а не корректный ответ. Гоняться за следующим расхождением ручной
# аппроксимации с git по одному — та же бесконечная игра, что Б1 арбитража 040; следующие
# члены того же класса (D/F-конфликты, rename-поведение, submodule-состояния) известны заранее.
#
# ОРАКУЛ, А НЕ АППРОКСИМАЦИЯ. Доктрина этого барьера (шапка файла): «Инвариант от РЕЗУЛЬТАТА,
# а не от способа». Вопрос «решил ли мерж хоть что-то по пути p сам, или получил бы то же
# самое БЕЗ единого ручного действия» имеет авторитетный вычислитель — сам git. Мерж-коммит
# `c` с РОВНО двумя родителями `P1`,`P2` — артефакт по пути `p` (унаследованное отсутствие,
# `excuse_for` пропускает и ищет настоящий удаляющий коммит дальше), ЕСЛИ И ТОЛЬКО ЕСЛИ все
# три условия сразу:
#   1. `git merge-tree --write-tree --no-messages -z P1 P2` завершился rc=0 (чисто) ИЛИ rc=1
#      (есть конфликты); rc>1 или сбой запуска — FAIL-CLOSED, НЕ артефакт (мерж остаётся
#      кандидатом на общих основаниях, требует собственный ALLOW);
#   2. `p` НЕ входит в секцию конфликтных путей вывода (сравнение путей побайтовое, через
#      `-z`-форму: имя файла — всё ПОСЛЕ первого TAB записи `<mode> <object> <stage>\t<path>`,
#      mode/oid/stage его никогда не содержат — устойчиво к пробелу в пути; при rc=0 эта
#      секция пуста по построению);
#   3. в результирующем дереве авто-мержа `p` ОТСУТСТВУЕТ (state снимается той же робастной
#      формой, что и везде в этом файле — mode+oid ПАРОЙ, не голым oid, без awk-разбора по
#      пробельным полям: класс дефекта «путь с пробелом превращается в отсутствие» закрыт при
#      ЛЮБОЙ семантике предиката, не только этой — арбитраж 042, З3).
# Во ВСЕХ прочих случаях (rc>1, `p` в конфликтах, `p` присутствует в результате) — мерж
# остаётся кандидатом на «удаляющий коммит» и обязан нести собственную строку ALLOW.
#
# `excuse_for` пропускает такие артефакты по порядку `git log` (от HEAD) и останавливается на
# ПЕРВОМ кандидате, который артефактом не является, — это и есть настоящий удаляющий коммит.
# Только его тело проверяется на ALLOW-строку; поиск НЕ продолжается дальше вглубь истории.
# Это принципиально: если бы после первого «настоящего» кандидата поиск шёл ЕЩЁ дальше и
# принимал ALLOW из более старого коммита, вернулась бы ИМЕННО та дыра, которую антигейминг
# выше уже закрыл (реюз старого разрешения после restore-и-повторного-удаления, разрешение,
# заранее положенное в посторонний коммит) — Н-127 чинит топологию мержа, не расширяет то,
# ЧЬЁ тело считается разрешением.
#
# ЦЕНА ОРАКУЛА, НАЗВАННАЯ ПРЯМО (арбитраж 042, «Цена решения», риски 2 и 3 контракта). Версия
# git — проба на старте файла (рядом с `comm`) даёт именной rc=2 при недоступности, здесь
# ничего не решается заново. `merge-tree --write-tree` пишет деревья в object DB — барьер уже
# пишет в `$ROOT/tmp`, осиротевшие деревья собираются gc, именованный остаток, не дыра.
# Вердикт «артефакт/нет» теперь совпадает с тем, что сделал бы `git merge` ЭТОЙ версии git —
# сознательно: предмет барьера — «наследование против ручного действия», и авторитет здесь
# git, а не наша реконструкция (полный текст рисков — §Риски contracts/042).
#
# Октопус-мержи (3+ родителя) — fail-closed без изменений: НЕ признаются артефактом
# (return 1 сразу), мерж остаётся кандидатом на общих основаниях. Живых октопус-мержей на
# этом дереве нет (риск назван в контракте), и ошибаться здесь безопаснее в сторону «требует
# ALLOW», а не в сторону «прощает».
#
# ГРАНДФАЗЕР-АЛЛОУЛИСТ (контракт 046, ветвь 1 — образец в `check_charter.sh:razreshil`,
# экстраполяция на ALLOW-ARTIFACT-DELETE) — 2 пары (SHA, путь), санкционированных владельцем
# текстом в сессии 2026-09-25, Н-69-консолидация вердиктов. Эти коммиты удаляют защищённый
# артефакт, но не несут строки ALLOW-ARTIFACT-DELETE в теле (процедурный пробел, не обход):
# контент перенесён без изменений, история имён сохранена в git. История неприкосновенна —
# коммиты НЕ редактируются задним числом, разрешение записано здесь как статическое
# допущение, и ТОЛЬКО для ровно этих 2 SHA. «узкий non-rewriteable grandfather». case матчит
# ТОЛЬКО exact-SHA+exact-path пару (правило 3 владельца: НЕ бланкет), иначе — падение в
# основную грамматику.
#
# Ровно 2 SHA:
#   31fcb46bd3e6e9faf11868ea766e083ea7b32069  verdicts/critic/contracts-043-v2-spaseno-draft.md
#   aace01dd1f1b4959bcea061fc54c3e5e485934ba  verdicts/critic/contracts-044-v2.md
#
# НЕ добавлять новые записи без прямого слова владельца в НОВОМ коммите с обоснованием.
state_at() {  # <коммит-или-дерево> <путь> → "<mode> <oid>" на stdout, пусто — пути там нет.
              # РОБАСТНАЯ форма (арбитраж 042, п.2 границы): `--format` вместо awk-разбора по
              # пробельным полям, `:(literal)` — путь не толкуется как pathspec-шаблон, пара
              # mode+oid — не голый oid (git различает modify/delete-конфликт по режиму даже
              # при неизменном oid). Присутствие судится по непустой строке целиком — дальше
              # содержимое пары здесь не разбирается, разбирать нечего.
  git ls-tree --format='%(objectmode) %(objectname)' "$1" -- ":(literal)$2" 2>/dev/null
}

is_lagging_merge_artifact() {  # <коммит> <путь> → 0, если бесконфликтный трёхсторонний мерж
                                # родителей дал бы то же самое отсутствие пути без единого
                                # ручного действия (три условия оракула — блок комментариев
                                # выше)
  local c="$1" p="$2" mt_rc rec first tree_seen state
  local -a parents=()
  read -r -a parents < <(git log -1 --format=%P "$c")
  [ "${#parents[@]}" -eq 2 ] || return 1

  set +e
  git merge-tree --write-tree --no-messages -z "${parents[0]}" "${parents[1]}" > "$TMP/mt_out" 2>/dev/null
  mt_rc=$?
  set -e
  [ "$mt_rc" -eq 0 ] || [ "$mt_rc" -eq 1 ] || return 1

  first=1; tree_seen=""
  while IFS= read -r -d '' rec; do
    if [ "$first" -eq 1 ]; then
      tree_seen="$rec"; first=0; continue
    fi
    [ "${rec#*$'\t'}" = "$p" ] && return 1
  done < "$TMP/mt_out"

  state="$(state_at "$tree_seen" "$p")"
  [ -z "$state" ] && return 0
  return 1
}

excuse_for() {  # <путь> → 0, если удаление разрешено ИМЕННО в удаляющем коммите
  local p="$1" c body line path reason
  while IFS= read -r c; do
    [ -n "$c" ] || continue
    # ── ГРАНДФАЗЕР-АЛЛОУЛИСТ (см. шапку функции, контракт 046, ветвь 1) ──────────
    # Проверяется ДО обычного разбора тела коммита и ДО is_lagging_merge_artifact.
    # Возврат 0, если пара (SHA, путь) входит в ровно эти 2 строки; иначе — падение
    # в основную грамматику (не бланкет: тот же SHA с другим путём идёт в ALLOW-проверку).
    case "$c" in
      31fcb46bd3e6e9faf11868ea766e083ea7b32069)
        [ "$p" = "verdicts/critic/contracts-043-v2-spaseno-draft.md" ] && return 0 ;;
      aace01dd1f1b4959bcea061fc54c3e5e485934ba)
        [ "$p" = "verdicts/critic/contracts-044-v2.md" ] && return 0 ;;
    esac
    is_lagging_merge_artifact "$c" "$p" && continue
    body="$(git log -1 --format=%B "$c")"
    while IFS= read -r line; do
      if [ "${line:0:1}" = '"' ]; then
        path="${line:1}"; path="${path%%\"*}"
        reason="${line#\"$path\"}"
      else
        path="${line%%[[:space:]]*}"
        reason="${line#"$path"}"
      fi
      reason="${reason#"${reason%%[![:space:]]*}"}"
      if [ -z "$path" ]; then
        bad "в коммите ${c:0:8} исключение ALLOW-ARTIFACT-DELETE не назвало путь — безымянное разрешение снимает защиту со всего дерева навсегда"
      elif [ "$path" != "$p" ]; then
        continue
      elif [ -z "$reason" ]; then
        bad "исключение ALLOW-ARTIFACT-DELETE для $path без причины — разрешение без записанной причины неотличимо от опечатки"
      else
        return 0
      fi
    done < <(printf '%s\n' "$body" \
             | awk 'sub(/^ALLOW-ARTIFACT-DELETE:[[:space:]]*/, "") { print }')
    return 1
  done < <(git log HEAD --full-history --no-renames -m --diff-filter=D --format=%H -- "$p")
  return 1
}

# ПЕРЕНОС (контракт 039, §Семантика п.1). Путь p из missing считается перенесённым, если
# выполнены ОБА условия ОДНОВРЕМЕННО:
#   А) в удаляющем коммите c (той же мерой `--no-renames -m --diff-filter=D`) появился путь
#      q ≠ p (статус A той же мерой) с блобом РОВНО B;
#   Б) блоб B присутствует в `git ls-tree -r HEAD` хотя бы под одним путём.
# Merge с РАЗНЫМИ блобами p в родителях — переноса нет, fail-closed (требуется ALLOW).
# Реализация, проверяющая только (Б) и пропускающая (А), зеленеет по одному следу блоба
# на HEAD — блокер Б1 (verdicts/critic/contracts-039-v1.md, dccde2d); проба R7 держит
# конъюнкцию.
moved_for() {  # <путь> → 0, если перенос признан (оба условия выполнены)
  local p="$1" c parent_blob_b blob q_blob unique_blobs
  c="$(git log HEAD --full-history --no-renames -m --diff-filter=D --format=%H -- "$p" | sed -n 1p)"
  [ -n "$c" ] || return 1

  # Б — блоб p в родителе c; разные блобы в нескольких родителях → переноса нет, fail-closed.
  # `git log -1 --format=%P` отдаёт всех родителей ОДНОЙ СТРОКОЙ через пробел: до фикса `while
  # read` трактовал её как ОДИН object name, и octopus-merge (3+ родителя с одним и тем же
  # блобом у всех) давал ложный rc=1 — false-red, не дыра безопасности, но отказ на честном
  # переносе через merge. Разбиваем строку на слова ПЕРЕД обходом.
  local -a parent_blobs=()
  local -a parents=()
  read -r -a parents < <(git log -1 --format=%P "$c")
  local parent blob
  for parent in "${parents[@]}"; do
    [ -n "$parent" ] || continue
    blob="$(git ls-tree "$parent" -- "$p" 2>/dev/null | awk -v pth="$p" '$4 == pth { print $3; exit }')"
    [ -n "$blob" ] && parent_blobs+=("$blob")
  done
  [ "${#parent_blobs[@]}" -ge 1 ] || return 1
  unique_blobs="$(printf '%s\n' "${parent_blobs[@]}" | sort -u | wc -l | tr -d ' ')"
  [ "$unique_blobs" = "1" ] || return 1
  parent_blob_b="${parent_blobs[0]}"
  # Условие Б: блоб B жив на HEAD хотя бы под одним путём КАК РЕГУЛЯРНЫЙ ФАЙЛ. Множество
  # блобов снято выше одним прогоном `git ls-tree -r HEAD` (включая файлы ВНЕ области защиты —
  # носитель перенесённого артефакта может жить где угодно) и записано в `$TMP/head_blobs`
  # с фильтром mode 100644/100755 (закрывает обход 1: dangling symlink с тем же блобом).
  # Здесь только проверка членства; ранний `awk exit` в пайпе дал бы SIGPIPE на upstream и
  # вернул rc 141 под `set -o pipefail` — за это отвечает предагрегация в файл.
  grep -qxF "$parent_blob_b" "$TMP/head_blobs" || return 1
  local q_path status q_blob
  while IFS=$'\t' read -r status q_path; do
    [ "$status" = "A" ] || continue
    [ -n "$q_path" ] || continue
    [ "$q_path" != "$p" ] || continue
    # РЕГУЛЯРНЫЙ ФАЙЛ на пути q в c. До фикса — только OID-матч, и dangling symlink q с
    # mode 120000 при том же блобе (git хранит цель симлинка как блоб) давал ложный rc0.
    # mode — первое поле `git ls-tree`; 100644/100755 — единственные пригодные носители,
    # потому что rename с mode-change на 120000/160000/040000 в следующем коммите даёт
    # тот же обход. Фильтр в awk: и mode, и имя.
    q_blob="$(git ls-tree "$c" -- "$q_path" 2>/dev/null | awk -v pth="$q_path" '$1 ~ /^(100644|100755)$/ && $4 == pth { print $3; exit }')"
    [ "$q_blob" = "$parent_blob_b" ] && [ -n "$q_blob" ] && return 0
  done < <(git log -1 --no-renames -m --pretty=format: --name-status "$c" 2>/dev/null)
  return 1
}

gone=0; excused=0; moved=0
while IFS= read -r p; do
  [ -n "$p" ] || continue
  if excuse_for "$p"; then
    excused=$((excused + 1))
    ok "исчез с явного разрешения: $p"
  elif moved_for "$p"; then
    moved=$((moved + 1))
    ok "перенесён, контент жив на HEAD: $p"
  else
    gone=$((gone + 1))
    bad "защищённый артефакт существовал и на HEAD его нет: $p"
  fi
done < "$TMP/missing"

