#!/usr/bin/env bash
# Защищённый артефакт: СУЩЕСТВОВАЛ — обязан существовать на HEAD.
#
# Инвариант от РЕЗУЛЬТАТА, а не от способа. На соседнем проекте это правило переписывали
# трижды, и каждый раз по одной причине: прежние редакции гонялись за СПОСОБОМ исчезновения
# файла. Запретили удаление — нашлось переименование. Запретили переименование — нашлось
# слияние `-s ours`, где файл исчезает без единого diff'а с удалением. Запретили и его —
# нашлось добавление-и-удаление внутри одной ветки, где на кончиках истории файла нет вовсе.
# Способов исчезнуть больше, чем можно перечислить; результат один, и правило от результата
# ловит их все одним предложением.
#
# КАК СЧИТАЕТСЯ «СУЩЕСТВОВАЛ». Объединение деревьев ВСЕХ коммитов, достижимых от HEAD.
# Именно достижимость закрывает `-s ours`: коммиты влитой стороны достижимы через второго
# родителя слияния, их деревья содержат файл, а HEAD — нет. Она же закрывает
# добавление-и-удаление: промежуточный коммит достижим, хотя на кончиках файла не видно.
#
# ОБЛАСТЬ ВЫВЕДЕНА, А НЕ ЗАДАНА СПИСКОМ. Каталоги вердиктов берутся из `roles/*.md`, поля
# `verdict:`: новая роль защищается сама, без правки этого файла. Список, набранный руками,
# отстал бы ровно на одну роль и молча — за одну сессию в этом репозитории добавление
# области дважды сразу находило необъявленное. `plans/` объявлен здесь явно и с причиной:
# план — единственный защищаемый артефакт, который не принадлежит ни одной роли, его пишет
# живая сессия.
#
# ИСКЛЮЧЕНИЕ ТОЛЬКО ЯВНОЕ И ТОЛЬКО ИМЕННОЕ:
#
#   ALLOW-ARTIFACT-DELETE: <путь> <причина>
#
# в теле любого коммита, достижимого от HEAD. План 005 §4 требовал лишь наличия строки в
# теле; здесь строка ОБЯЗАНА назвать путь и причину, и вот почему: безымянная строка — это
# индульгенция, она снимает защиту со всего дерева навсегда, потому что тело коммита уже не
# переписать. Разрешение на один файл и разрешение на все — разные предметы, и в истории их
# нечем развести. Усиление против плана записано здесь намеренно: норма, изменённая молча,
# наследуется всем, что построят по ней потом.
#
# Обратная сверка (исключение есть, а файл на месте) НЕ делается намеренно: файл могли
# вернуть, а тело коммита не переписать. Гейт, краснеющий на прошлом, которое уже нельзя
# исправить, отучает себе верить.
#
# Зелёная ветвь — принятое исключение — проверяется не фикстурой, а
# `scripts/drill_protected_exception.sh`: анти-плацебо доказывает только КРАСНОЕ, и
# непроверенное зелёное ветвление означало бы, что единственный законный способ удалить
# артефакт закрыт, а правило начнут обходить, а не соблюдать.
#
# ГРАНИЦА ЭТОГО БАРЬЕРА, названная прямо. «Существовал» здесь означает «существовал в графе,
# достижимом от HEAD». Перезапись истории (`reset --hard` назад, `amend`, `rebase`,
# `filter-branch`) выносит коммит из этого графа, и барьеру просто не дают доказательств.
# Гнаться за этим здесь нельзя: измерено — `git fsck --unreachable --no-reflogs` в этом
# репозитории показывает 3 недостижимых коммита от обычной работы, то есть такая область
# краснела бы на честном дереве. Исчезновение ИСТОРИИ — отдельный предмет, и у него отдельный
# барьер: `scripts/check_no_rewrite.sh`, которому проводка сообщает прежнюю вершину ветки.
#
# УСЕЧЁННАЯ ИСТОРИЯ — ОТКАЗ, А НЕ «НЕЧЕМ ПРОВЕРИТЬ». `actions/checkout` по умолчанию берёт
# глубину 1, и на таком дереве объединение достижимых коммитов равно самому HEAD: барьер стал
# бы ПУСТО-ЗЕЛЁНЫМ и подтверждал бы инвариант, ничего не проверив. Молчаливо зелёный гейт
# хуже красного, потому что красному ищут причину, а зелёному верят. Поэтому здесь код 1 с
# названной причиной, а не 2: 2 означало бы «нечем проверить» и в CI выглядело бы как
# особенность окружения, тогда как лечится это одной строкой `fetch-depth: 0`.
#
#   bash scripts/check_protected.sh            проверить это дерево
#   bash scripts/check_protected.sh <корень>   проверить другое дерево (так он предъявляется
#                                              красным против обманных заглушек)
#
# Коды возврата: 0 — ни один защищённый артефакт не исчез, 1 — исчез, 2 — нечем проверить.
set -euo pipefail

ROOT="$(cd "${1:-"$(dirname "${BASH_SOURCE[0]}")/.."}" && pwd)"
cd "$ROOT"

fails=0
ok()   { printf '  ok   %s\n' "$*" >&2; }
bad()  { fails=$((fails + 1)); printf '  FAIL %s\n' "$*" >&2; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

command -v git >/dev/null 2>&1 || skip "нет git — истории нет"
git rev-parse --git-dir >/dev/null 2>&1 || skip "$ROOT не репозиторий git — истории нет"
git rev-parse --verify HEAD >/dev/null 2>&1 || skip "в $ROOT нет ни одного коммита"

if [ "$(git rev-parse --is-shallow-repository)" = "true" ]; then
  printf 'ОТКАЗ: история усечена (shallow) — на глубине 1 инвариант подтверждается сам собой\n' >&2
  printf 'Лечится в проводке: actions/checkout с fetch-depth: 0.\n' >&2
  exit 1
fi

mkdir -p "$ROOT/tmp"
TMP="$(mktemp -d "$ROOT/tmp/protected.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT

# ── область ───────────────────────────────────────────────────────────────────
# Каталоги вердиктов берутся из ролей ВО ВСЕХ достижимых коммитах, а не только на HEAD.
# Адверсарий предъявил, чем была прежняя редакция: область, взятая с HEAD, служила
# ВЫКЛЮЧАТЕЛЕМ защиты — удали файл роли вместе с её вердиктами (или замени поле на `null`),
# и каталог перестаёт входить в область, `existed` его не содержит, барьер зелен. Защита,
# которую снимает тот же коммит, что и удаляет предмет, защитой не является.
#
# Читаются УНИКАЛЬНЫЕ блобы, а не файлы в каждом коммите: одна и та же роль живёт в истории
# десятками копий с одним содержимым, и различать надо содержимое, а не число коммитов.
: > "$TMP/roleblobs"
while IFS= read -r c; do
  git ls-tree -r "$c" -- roles/ 2>/dev/null | awk '$4 ~ /\.md$/ { print $3 }' >> "$TMP/roleblobs"
done < <(git rev-list HEAD)
sort -u "$TMP/roleblobs" -o "$TMP/roleblobs"

prefixes=()
while IFS= read -r blob; do
  [ -n "$blob" ] || continue
  v="$(git cat-file blob "$blob" 2>/dev/null \
       | awk 'FNR<=20 && sub(/^verdict:[[:space:]]*/, "") {
                gsub(/[[:space:]]+$/, "")
                if ($0 != "null" && $0 != "") print
                exit
              }' || true)"
  [ -n "$v" ] && prefixes+=("$v")
done < "$TMP/roleblobs"
prefixes+=("plans/")
mapfile -t prefixes < <(printf '%s\n' "${prefixes[@]}" | sort -u)


# ── что существовало хоть в одном достижимом коммите ──────────────────────────
: > "$TMP/existed.raw"
commits=0
while IFS= read -r c; do
  commits=$((commits + 1))
  git ls-tree -r --name-only "$c" -- "${prefixes[@]}" >> "$TMP/existed.raw"
done < <(git rev-list HEAD)
sort -u "$TMP/existed.raw" > "$TMP/existed"
git ls-tree -r --name-only HEAD -- "${prefixes[@]}" | sort -u > "$TMP/head"

# Разность считается `comm`, а не циклом на bash: это ДРУГАЯ мера, и она не повторяет способ,
# которым собраны оба множества.
comm -23 "$TMP/existed" "$TMP/head" > "$TMP/missing"

# ── исключение обязано лежать в ТОМ КОММИТЕ, который артефакт и убрал ─────────
# Прежняя редакция собирала разрешения из тел ВСЕХ достижимых коммитов в один вечный список.
# Адверсарий предъявил два следствия: разрешение годилось ПОВТОРНО после восстановления файла,
# и его можно было положить ЗАРАНЕЕ в посторонний коммит, а потом удалить артефакт молча.
# Разрешение обосновывает КОНКРЕТНОЕ удаление, а не выдаёт право на путь навсегда.
#
# Удаляющий коммит — последний достижимый, в котором путь исчез из дерева. `--no-renames`
# стоит намеренно: иначе результат зависел бы от `diff.renames` в конфиге машины, то есть
# мера меняла бы вердикт от настроек читателя. У слияния `-s ours` удаляющего коммита нет
# вовсе — такое исчезновение не извиняется ничем, и это правильно: чтобы законно убрать
# артефакт, делают обычный коммит с разрешением.
excuse_for() {  # <путь> → 0, если удаление разрешено ИМЕННО в удаляющем коммите
  local p="$1" c body line path reason
  c="$(git log HEAD --full-history --no-renames --diff-filter=D --format=%H -- "$p" | sed -n 1p)"
  [ -n "$c" ] || return 1
  body="$(git log -1 --format=%B "$c")"
  while IFS= read -r line; do
    path="${line%%[[:space:]]*}"
    reason="${line#"$path"}"
    reason="${reason#"${reason%%[![:space:]]*}"}"
    if [ -z "$path" ]; then
      bad "в коммите ${c:0:8} исключение ALLOW-ARTIFACT-DELETE не назвало путь — безымянное разрешение снимает защиту со всего дерева навсегда"
    elif [ "$path" != "$p" ]; then
      continue
    elif [ -z "$reason" ]; then
      bad "исключение ALLOW-ARTIFACT-DELETE для $path без причины — разрешение без записанной причины неотличимо от опечатки"
    else
      return 0
    fi
  done < <(printf '%s\n' "$body" \
           | awk 'sub(/^[[:space:]]*ALLOW-ARTIFACT-DELETE:[[:space:]]*/, "") { print }')
  return 1
}

gone=0; excused=0
while IFS= read -r p; do
  [ -n "$p" ] || continue
  if excuse_for "$p"; then
    excused=$((excused + 1))
    ok "исчез с явного разрешения: $p"
  else
    gone=$((gone + 1))
    bad "защищённый артефакт существовал и на HEAD его нет: $p"
  fi
done < "$TMP/missing"

printf '\nобласть: %s · коммитов пройдено: %d · существовало: %d · на HEAD: %d · исчезло: %d · с разрешения: %d\n' \
  "${prefixes[*]}" "$commits" "$(wc -l < "$TMP/existed")" "$(wc -l < "$TMP/head")" "$gone" "$excused" >&2

[ "$fails" -eq 0 ] || exit 1
