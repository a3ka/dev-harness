#!/usr/bin/env bash
# Барьер: идентификаторы артефактов уникальны, и каждый артефакт выдан механизмом.
#
# Заведено потому, что до этого механизма номер артефакта назначался вручную, и в этом
# репозитории уже сталкивались два файла под одним номером (план 005 §2). Номер выдаёт
# `next_id.sh`, и регистр выдачи — git-теги `refs/tags/id/<КЛАСС>/<NNN>`. Этот барьер
# сверяет артефакты и теги в ОБЕ СТОРОНЫ.
#
# ЧТО ЛОВИТСЯ:
#   1. два файла одного класса с одним номером — код 1, названы ОБА пути (требование
#      плана 005 §2). Это и есть «одинаковый номер»: правило работает на самих файлах,
#      без оглядки на теги. Дубль может прийти из гонки двух клонов (находка 5 второго
#      круга: каждый клон выдал свой 007), и после слияния обе ветки оказываются в
#      HEAD — `find` в локации класса видит оба файла;
#   2. номер артефакта, которому НЕТ тега выдачи — код 1, «номер N назначен рукой, а не
#      механизмом: <путь>». Прежняя редакция ловила это через `git log --diff-filter=A`,
#      и ветвь была недостижима на честном дереве (вердикт `verdicts/adversary/mech-2-ids.md`,
#      находка 4): любой закоммиченный номер уже считался «в истории». Теперь история
#      выдачи — теги, и коммит файла без тега действительно виден как нарушение;
#   3. файл с неправильным форматом номера (`7-x.md`, `0007-x.md`) — код 1, «номер N в
#      <путь> имеет неправильный формат (X цифр, ожидается 3)». Тот же идентификатор в
#      другой записи: `0007-x.md` при `id/PLAN/007` — это тот же номер 7. Три цифры
#      обязательны в ОБЕ стороны (находка 4 второго круга).
#
# ЧТО ЗАКОННО:
#   - артефакт без номера (`verdicts/adversary/mech-1-antiplacebo.md`) — это нормальный
#     безномерной артефакт, обратной силой не нумеруется;
#   - тег выдачи БЕЗ артефакта — номер зарезервирован (находка 6: разрешённое удаление
#     не освобождает номер). Это та самая зелёная ветвь, которую фикстурой не выразить —
#     она проверяется обратным: фикстура коммитит файл, удаляет его с разрешения и убеждается,
#     что номер в следующей выдаче пропущен;
#   - кириллица в имени (`007-план.md`) — репозиторий по-русски, кириллица в области.
#
# ОБЛАСТЬ ВЫВЕДЕНА ИЗ ПРЕДМЕТА, а не задана списком. Класс → куда он кладётся:
#   PLAN    → plans/                       — планы в корне;
#   VERDICT → verdicts/<роль>/             — пути читаются из roles/*.md (поле `verdict:`),
#                                             а не вписываются вторым списком;
#   ADR     → decisions/                   — место выбрано в `next_id.sh` и повторено здесь,
#                                             чтобы разные пути не заводили ещё одну
#                                             ручную таблицу.
#
# ОБХОД РЕКУРСИВНЫЙ. `verdicts/adversary/2026/002-x.md` — артефакт, и должен быть виден
# и при выдаче, и при сверке. Прежняя редакция ограничивалась `-maxdepth 1` и такие пути
# теряла (находка 3: подкаталоги роли полностью выпадали).
#
# ПРАВИЛО РАЗЛИЧЕНИЯ НОМЕРА. Разбор имени — ЕДИНСТВЕННАЯ реализация, импортируемая из
# `next_id.sh` (находка 5 второго круга: два разбора расходились молча). Шаблон —
# три цифры, дефис, не-цифра: `005-x.md` → 5, `007-план.md` → 7 (кириллица в области),
# `2026-08-17-x.md` → без номера (четыре цифры, и за дефисом сразу цифра). Неправильный
# формат (`7-x.md`, `0007-x.md`) — отдельный код возврата, и `check_ids` сообщает о нём
# как «номер N в <путь> имеет неправильный формат». Так разбор имени — один, и
# расходиться двум скриптам не по чему.
#
# ────────────────────────────────────────────────────────────────────────────
# ГРАНИЦА «НЕПОЛНЫЙ РЕГИСТР» (записана явно, измерена адверсарием — находка 3 второго
# круга). Барьер различает три состояния и называет их разными сообщениями.
#
#   (а) РЕГИСТР ПОЛОН — `refs/tags/id/<КЛАСС>/*` локально присутствует в нужном объёме.
#       Сверка по существу: дубли, ручные номера, неправильный формат — как описано
#       выше. Ветка (а) — нормальная работа барьера.
#
#   (б) РЕГИСТР НЕПОЛЕН ИЛИ НЕДОСТУПЕН — клон shallow (`git clone --depth 1`) или без
#       тегов (`git clone --no-tags`). Локально нет `refs/tags/id/*`, а артефакты с
#       номерами есть. Тогда сверка по (в) даёт ложное красное «номер назначен рукой»
#       на зарегистрированном артефакте — и такому красному перестают верить.
#       Барьер возвращает код 1 с НАЗВАННОЙ причиной и лечением: «shallow-клон без
#       тегов — реестр выдачи недоступен; выполни `fetch --tags` либо задай
#       `fetch-depth: 0` в checkout». Фикстура `case_shallow_bez_tegov.sh` предъявляет
#       это красным. В CI это не выстреливает потому, что `.github/workflows/ci.yml`
#       задаёт `fetch-depth: 0` и checkout v4 при нём выбирает все refs (замер адверсария
#       на этой же находке).
#
#   (в) РЕГИСТР ПОЛОН, ТЕГА НА КОНКРЕТНЫЙ НОМЕР НЕТ — артефакт есть, а `id/<КЛАСС>/<N>`
#       нет. Это «номер N назначен рукой»: либо забыли выдать, либо стёрли тег.
#       Сообщение отличается от (б) — здесь предметный путь, а не причина окружения.
# ────────────────────────────────────────────────────────────────────────────
#
# ────────────────────────────────────────────────────────────────────────────
# ГРАНИЦА «ТЕГ МОЖНО УДАЛИТЬ РУКОЙ» (записана явно, измерена адверсарием — находка 1
# второго круга). Тег `id/<КЛАСС>/<NNN>` — обычный локальный ref, и `git tag -d` стирает
# его без спроса.
#
#   ЧТО ДЕРЖИТ: ветка (в) — «номер N назначен рукой» — ловит случай «удалили тег,
#   артефакт остался». Это самая частая форма расхождения; барьер её видит и не
#   пропустит зелёной.
#
#   ЧТО НЕ ДЕРЖИТ: ручное удаление и артефакта, и тега вместе — освобождает номер.
#   Новый файл с тем же номером и новый тег будут согласованы, и барьер промолчит.
#   Это ГРАНИЦА, не дыра: чтобы стереть номер, нужно стереть оба следа. Согласованность
#   файла и тега защищает только от расхождения, не от стирания.
# ────────────────────────────────────────────────────────────────────────────
#
# ────────────────────────────────────────────────────────────────────────────
# ГРАНИЦА «ГОНОЧНЫЙ КЛОН» (записана явно, измерена адверсарием — находка 2 второго круга).
# Тег локален, и два НЕЗАВИСИМЫХ клона одновременно выдают 007 — каждый создаёт свой тег
# и свой `007-x.md`. Общего реестра между клонами нет, и `next_id.sh` это не закрывает.
#
#   ЧТО ДЕРЖИТ: локальная атомарность в одном `.git` — десять одновременных вызовов не
#   дублируют номер. Дрилл `drill_next_id_race.sh` это предъявляет зелёным.
#
#   ЧТО НЕ ДЕРЖИТ: общая резервация между клонами — её нет, и это ГРАНИЦА механизма.
#   Барьер ловит её при слиянии: `find` в локации класса видит ОБА файла одного номера,
#   называет их в красном «одинаковый номер N в классе <КЛАСС>: <путь-1> и <путь-2>».
#   Так общая атомарность достигается не выдачей, а сверкой. Фикстура
#   `case_dubl_mezhdu_vetkami.sh` предъявляет это красным.
# ────────────────────────────────────────────────────────────────────────────
#
# ГЕРМЕТИЧНОСТЬ ОТ ВНЕШНЕГО РЕПОЗИТОРИЯ. Скрипт снимает `GIT_DIR`, `GIT_WORK_TREE`,
# `GIT_INDEX_FILE`, `GIT_OBJECT_DIRECTORY`, `GIT_ALTERNATE_OBJECT_DIRECTORIES`,
# `GIT_TEMPLATE_DIR` — каждая из них, будучи выставленной в среде, перенаправляет `git`
# в чужой репозиторий. Адверсарий измерил (находка 6 второго круга): `GIT_DIR=<чужой>`
# делал `check_ids` зелёным на чужом `.git`, а предмет не проверялся вовсе.
#
#   bash scripts/check_ids.sh            проверить это дерево
#
# Коды возврата: 0 — уникальны и согласованы, 1 — нарушение, 2 — нечем проверить.

# ── ИМПОРТ ЕДИНСТВЕННОГО РАЗБОРА ИМЕНИ ────────────────────────────────────────
# Разбор имени артефакта — ЕДИНСТВЕННАЯ реализация, в `next_id.sh`. Два скрипта
# импортируют её через `NEXT_ID_LIB=1 source next_id.sh`; иначе расхождение двух
# разборов одного формата (`007-план.md`, `007-2026-x.md`) было дефектом области
# (находка 5 второго круга). После импорта функция `parse_artifact_basename` доступна.
NEXT_ID_LIB=1
# shellcheck disable=SC1091
. "$(dirname "${BASH_SOURCE[0]}")/next_id.sh"

set -euo pipefail

# ── ГЕРМЕТИЧНОЕ ОКРУЖЕНИЕ GIT ────────────────────────────────────────────────
# Снимаем шесть переменных окружения, которые перенаправляют `git` в чужой репозиторий
# сильнее, чем `-C "$HERE"`. Адверсарий измерил (находка 6 второго круга): `GIT_DIR` и
# `GIT_WORK_TREE` достаточно выставить в среде — и `-C` уже не работает, барьер валит
# зелёный на чужом `.git`. Это первая защита, дальше идёт `ls-remote` — он тоже
# подхватывает `GIT_OBJECT_DIRECTORY` / `GIT_ALTERNATE_OBJECT_DIRECTORIES`, поэтому
# `unset` нужен и здесь.
unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_TEMPLATE_DIR

HERE="$(cd "${1:-"$(dirname "${BASH_SOURCE[0]}")/.."}" && pwd)"

fails=0
ok()    { printf '  ok   %s\n' "$*" >&2; }
bad()   { fails=$((fails + 1)); printf '  FAIL %s\n' "$*" >&2; }
skip()  { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

command -v git >/dev/null 2>&1 || skip "нет git — историю выдачи прочитать нечем"
git -C "$HERE" rev-parse --git-dir >/dev/null 2>&1 \
  || skip "$HERE не репозиторий git — регистра выдачи нет"

class_locs() {
   case "$1" in
    PLAN)    printf 'plans/\n' ;;
    VERDICT)
      [ -d "$HERE/roles" ] || return 0
      find "$HERE/roles" -maxdepth 1 -type f -name '*.md' 2>/dev/null \
        | while IFS= read -r f; do
            grep -hoE '^verdict: [^[:space:]]+' "$f" 2>/dev/null
          done \
        | grep -v 'null' | sed 's/^verdict: //'
      ;;
    ADR)     printf 'decisions/\n' ;;
    *)       return 1 ;;
  esac
}

# ── пути файлов класса на HEAD: рекурсивно ────────────────────────────────────
# Печатает пары «путь<TAB>basename». Разбор basename делается в вызывающем коде,
# потому что `parse_artifact_basename` ставит `ARTIFACT_NUMBER` в окружение
# вызывающего, а `< <(collect_paths ...)` гонит `collect_paths` в под-шелле —
# переменная под-шелла не видна родителю (измерено: `7-x.md` рядом с `007-y.md`
# проходил зелёным, потому что `ARTIFACT_NUMBER` оставался в под-шелле).
collect_paths() {
  local class="$1"
  local loc d f name
  while IFS= read -r loc; do
    [ -n "$loc" ] || continue
    d="$HERE/$loc"
    [ -d "$d" ] || continue
    while IFS= read -r f; do
      [ -n "$f" ] || continue
      name="$(basename "$f")"
      printf '%s\t%s\n' "$f" "$name"
    done < <(find "$d" -type f -name '*.md' 2>/dev/null)
  done < <(class_locs "$class")
}

# ── теги выдачи класса: номера, у которых есть регистр ────────────────────────
# Регистр — `refs/tags/id/<КЛАСС>/<NNN>`. Тег без артефакта — законная резервация,
# артефакт без тега — «номер назначен рукой». Два множества — пути и номера тегов —
# сравниваются по `NNN`.
class_tag_numbers() {
  local class="$1"
  local tag n
  while IFS= read -r tag; do
    [ -n "$tag" ] || continue
    if [[ "$tag" =~ id/[^/]+/([0-9]+)$ ]]; then
      n=$((10#${BASH_REMATCH[1]}))
      printf '%s\n' "$n"
    fi
  done < <(git -C "$HERE" for-each-ref --format='%(refname:short)' "refs/tags/id/$class/" 2>/dev/null || true)
}

# ── определение полноты реестра (ветка (б) — неполный/недоступный регистр) ────
# Возвращает 0, если реестр полон (ветка (а) — нормальная сверка), и 1 — если он
# неполон либо недоступен (ветка (б) — отказ с названной причиной и лечением).
# Печатает причину одной строкой в stderr.
is_registry_complete() {
  # 1) shallow-клон: `--is-shallow-repository` возвращает true, и история обрезана.
  local is_shallow
  is_shallow="$(git -C "$HERE" rev-parse --is-shallow-repository 2>/dev/null || echo false)"
  if [ "$is_shallow" = "true" ]; then
    printf 'shallow-клон без полной истории — реестр выдачи (refs/tags/id/*) недоступен; выполни fetch --tags --unshallow либо задай fetch-depth: 0 в checkout\n' >&2
    return 1
  fi

  # 2) клон без тегов: remote имеет `refs/tags/id/*`, локально — нет. Аннотированные
  # теги приходят двумя строками (`refs/tags/id/...` и `refs/tags/id/...^{}` для
  # peeled); `sed` снимает суффикс `^{}`, и `sort -u` даёт число уникальных имён.
  local remote_count local_count
  remote_count="$(git -C "$HERE" ls-remote --tags origin "refs/tags/id/*" 2>/dev/null \
                  | awk '{print $2}' | sed 's/\^{}$//' | sort -u | wc -l | tr -d ' ')"
  local_count="$(git -C "$HERE" for-each-ref --format='%(refname:short)' "refs/tags/id/" 2>/dev/null \
                 | wc -l | tr -d ' ')"
  if [ "${remote_count:-0}" -gt "${local_count:-0}" ]; then
    printf 'теги реестра выдачи (refs/tags/id/*) не выбраны локально — clone был без --tags; выполни fetch --tags\n' >&2
    return 1
  fi

  return 0
}

# ── обход классов ──────────────────────────────────────────────────────────────
violations=0

# Реестр проверяем ОДИН РАЗ в начале, до обхода классов. Если он неполон — отказ с
# названной причиной и лечением, а не ложное «номер назначен рукой» на каждом классе.
if ! is_registry_complete; then
  bad "реестр выдачи неполон или недоступен — см. причину выше"
  exit 1
fi

for class in PLAN VERDICT ADR; do
  # Множество выданных номеров — для проверки «номер назначен рукой».
  declare -A has_tag=()
  n=""
  while IFS= read -r n; do
    [ -n "$n" ] && has_tag["$n"]=1
  done < <(class_tag_numbers "$class")
  unset n

  # Собираем пары «путь<TAB>номер<TAB>rc» в массив. Разбор basename делаем здесь,
  # в основном шелле, чтобы `ARTIFACT_NUMBER` не пропадал в под-шелле `< <(collect_paths)`.
  # `parse_artifact_basename "$name" || true` обязателен: функция возвращает 1 для
  # безномерных файлов (`mech-1-...md`, `2026-08-17-x.md`), и `set -e` иначе валит
  # барьер на первом же безномерном файле.
  # Собираем пары «путь<TAB>номер<TAB>rc» в массив. Разбор basename делаем здесь,
  # в основном шелле, чтобы `ARTIFACT_NUMBER` не пропадал в под-шелле `< <(collect_paths)`.
  #
  # `parse_artifact_basename "$name" || rc=$?` обязателен ИНАЧЕ, чем `|| true`:
  # функция возвращает 1 для безномерных файлов (`mech-1-...md`, `2026-08-17-x.md`)
  # и 2 для неправильного формата (`7-x.md`, `0007-x.md`). `set -e` иначе валит барьер
  # на первом же безномерном файле. И `|| true` сломал бы `rc` — он стал бы 0 вместо
  # реального возврата функции, и второй проход (дубли) начал бы ловить файлы с
  # неправильным форматом как валидные (измерено на этой правке: фикстура
  # `case_format_3cifry.sh` показывала «одинаковый номер» вместо «неправильный формат»).
  line=""
  f=""; n=""; rc=""; rel=""; digit_count=""
  artifacts=()
  while IFS=$'\t' read -r f name; do
    [ -n "$f" ] || continue
    rc=0
    parse_artifact_basename "$name" || rc=$?
    [ -n "${ARTIFACT_NUMBER:-}" ] || continue
    artifacts+=("$f"$'\t'"$ARTIFACT_NUMBER"$'\t'"$rc")
  done < <(collect_paths "$class")
  # Первый проход: ошибки формата и «номер назначен рукой». Артефакт без тега при
  # существующем теге для того же номера — ветка (в). Файл с неправильным форматом
  # (`7-x.md`, `0007-x.md`) — отдельное красное, чтобы владелец видел, ЧТО чинить.
  for line in "${artifacts[@]:-}"; do
    [ -n "$line" ] || continue
    IFS=$'\t' read -r f n rc <<<"$line"
    [ -n "$f" ] && [ -n "$n" ] || continue
    rel="${f#"$HERE"/}"
    if [ "$rc" = "2" ]; then
      digit_count=${#n}
      [ "$digit_count" -ge 4 ] && digit_count="4+" || digit_count="$digit_count"
      bad "номер $n в $rel имеет неправильный формат ($digit_count цифр, ожидается 3): тот же идентификатор в другой записи, три цифры обязательны"
      violations=$((violations + 1))
      continue
    fi
    if [ -z "${has_tag[$n]:-}" ]; then
      bad "номер $n назначен рукой, а не механизмом: $rel"
      violations=$((violations + 1))
    fi
  done

  # Второй проход: дубликаты номера в классе — оба пути названы. Проверяется ТОЛЬКО
  # для валидного формата (return 0); файлы с неправильным форматом уже названы выше,
  # и их дубль с валидным файлом того же номера виден как ошибка формата у них. Это
  # та самая ветка «гоночный клон» — после слияния двух веток с одинаковым номером
  # оба файла в `find` локации, и сверка называет ОБА.
  declare -A seen=()
  other_rel=""
  for line in "${artifacts[@]:-}"; do
    [ -n "$line" ] || continue
    IFS=$'\t' read -r f n rc <<<"$line"
    [ -n "$f" ] && [ -n "$n" ] || continue
    [ "$rc" = "0" ] || continue
    rel="${f#"$HERE"/}"
    if [ -n "${seen[$n]:-}" ]; then
      other_rel="${seen[$n]#"$HERE"/}"
      bad "одинаковый номер $n в классе $class: $other_rel и $rel"
      violations=$((violations + 1))
    else
      seen[$n]="$f"
    fi
  done
  unset seen has_tag artifacts line f n rc rel digit_count other_rel
done

if [ "$violations" -gt 0 ]; then
  exit 1
fi
ok "номера уникальны и согласованы с регистром выдачи"