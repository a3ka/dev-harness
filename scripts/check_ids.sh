#!/usr/bin/env bash
# Барьер: идентификаторы артефактов уникальны, и каждый артефакт выдан механизмом.
#
# Заведено потому, что до этого механизма номер артефакта назначался вручную, и в этом
# репозитории уже сталкивались два файла под одним номером (план 005 §2). Номер выдаёт
# `next_id.sh`, и регистр выдачи — git-теги `refs/tags/id/<КЛАСС>/<NNN>`. Этот барьер
# сверяет артефакты и теги в ОБЕ СТОРОНЫ.
#
# ЧТО ЛОВИТСЯ:
#   1. два файла одного класса с одним номером — код 1, названы ОБА пути (требование
#      плана 005 §2). Это и есть «одинаковый номер»: правило работает на самих файлах,
#      без оглядки на теги;
#   2. номер артефакта, которому НЕТ тега выдачи — код 1, «номер N назначен рукой, а не
#      механизмом: <путь>». Прежняя редакция ловила это через `git log --diff-filter=A`,
#      и ветвь была недостижима на честном дереве (вердикт `verdicts/adversary/mech-2-ids.md`,
#      находка 4): любой закоммиченный номер уже считался «в истории». Теперь история
#      выдачи — теги, и коммит файла без тега действительно виден как нарушение.
#
# ЧТО ЗАКОННО:
#   - артефакт без номера (`verdicts/adversary/mech-1-antiplacebo.md`) — это нормальный
#     безномерной артефакт, обратной силой не нумеруется;
#   - тег выдачи БЕЗ артефакта — номер зарезервирован (находка 6: разрешённое удаление
#     не освобождает номер). Это та самая зелёная ветвь, которую фикстурой не выразить —
#     она проверяется обратным: фикстура коммитит файл, удаляет его с разрешения и убеждается,
#     что номер в следующей выдаче пропущен.
#
# ОБЛАСТЬ ВЫВЕДЕНА ИЗ ПРЕДМЕТА, а не задана списком. Класс → куда он кладётся:
#   PLAN    → plans/                       — планы в корне;
#   VERDICT → verdicts/<роль>/             — пути читаются из roles/*.md (поле `verdict:`),
#                                             а не вписываются вторым списком;
#   ADR     → decisions/                   — место выбрано в `next_id.sh` и повторено здесь,
#                                             чтобы разные пути не заводили ещё одну
#                                             ручную таблицу.
#
# ОБХОД РЕКУРСИВНЫЙ. `verdicts/adversary/2026/002-x.md` — артефакт, и должен быть виден
# и при выдаче, и при сверке. Прежняя редакция ограничивалась `-maxdepth 1` и такие пути
# теряла (находка 3: подкаталоги роли полностью выпадали).
#
# ПРАВИЛО РАЗЛИЧЕНИЯ НОМЕРА. Номером считается ведущая группа цифр в начале basename'а,
# за которой идёт `-` и БУКВА: `005-x.md` → 5, `7-x.md` → 7, `123-abc.md` → 123. Формат
# выдачи — ровно три цифры с ведущими нулями (`007`); но распознавание в дереве должно
# ловить и неправильное написание, чтобы `plans/7-x.md` не остался незамеченным рядом с
# `plans/007-y.md` (находка 2: становился «тем же» 7). Дата `2026-08-17-x.md` отличается
# тем, что за первым дефисом сразу идёт ещё цифра, а не буква, и шаблон её отбрасывает.
# Безномерные артефакты (`mech-1-antiplacebo.md`) начинаются с буквы и тоже не матчатся.
#
#   bash scripts/check_ids.sh            проверить это дерево
#
# Коды возврата: 0 — уникальны и согласованы, 1 — нарушение, 2 — нечем проверить.
set -euo pipefail

HERE="$(cd "${1:-"$(dirname "${BASH_SOURCE[0]}")/.."}" && pwd)"

fails=0
ok()    { printf '  ok   %s\n' "$*" >&2; }
bad()   { fails=$((fails + 1)); printf '  FAIL %s\n' "$*" >&2; }
skip()  { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

command -v git >/dev/null 2>&1 || skip "нет git — историю выдачи прочитать нечем"
git -C "$HERE" rev-parse --git-dir >/dev/null 2>&1 \
  || skip "$HERE не репозиторий git — регистра выдачи нет"

class_locs() {
   case "$1" in
    PLAN)    printf 'plans/\n' ;;
    VERDICT)
      [ -d "$HERE/roles" ] || return 0
      find "$HERE/roles" -maxdepth 1 -type f -name '*.md' 2>/dev/null \
        | while IFS= read -r f; do
            grep -hoE '^verdict: [^[:space:]]+' "$f" 2>/dev/null
          done \
        | grep -v 'null' | sed 's/^verdict: //'
      ;;
    ADR)     printf 'decisions/\n' ;;
    *)       return 1 ;;
  esac
}

# ── артефакты класса на HEAD: рекурсивно, номер = ведущие цифры + дефис + буква ───
# Рекурсия нужна для `verdicts/<роль>/<год>/NNN-x.md`. Шаблон `^[0-9]+-[a-zA-Z]`
# ловит как выданные трехзначные (`005-x.md`), так и неправильно набранные рукой
# (`7-x.md`); даты (`2026-08-17-x.md`) отбрасываются, потому что за первым дефисом
# сразу идёт ещё цифра, а не буква, и безномерные артефакты (`mech-1-...`) — потому
# что в начале буквы.
collect() {
  local class="$1"
  while IFS= read -r loc; do
    [ -n "$loc" ] || continue
    local d="$HERE/$loc"
    [ -d "$d" ] || continue
    find "$d" -type f -name '*.md' 2>/dev/null
  done < <(class_locs "$class") \
  | while IFS= read -r f; do
      [ -n "$f" ] || continue
      local name; name="$(basename "$f")"
      if [[ "$name" =~ ^([0-9]+)-[a-zA-Z] ]]; then
        local n; n=$((10#${BASH_REMATCH[1]}))
        printf '%s\t%s\n' "$f" "$n"
      fi
    done
}

# ── теги выдачи класса: номера, у которых есть регистр ────────────────────────
# Регистр — `refs/tags/id/<КЛАСС>/<NNN>`. Тег без артефакта — законная резервация,
# артефакт без тега — «номер назначен рукой». Два множества — пути и номера тегов —
# сравниваются по `NNN`.
class_tag_numbers() {
  local class="$1"
  git -C "$HERE" for-each-ref --format='%(refname:short)' "refs/tags/id/$class/" 2>/dev/null \
    | while IFS= read -r tag; do
        [ -n "$tag" ] || continue
        if [[ "$tag" =~ id/[^/]+/([0-9]+)$ ]]; then
          printf '%s\n' "$((10#${BASH_REMATCH[1]}))"
        fi
      done
}

# ── обход классов ──────────────────────────────────────────────────────────────
violations=0
for class in PLAN VERDICT ADR; do
  # Множество выданных номеров — для проверки «номер назначен рукой».
  mapfile -t tag_nums < <(class_tag_numbers "$class")
  declare -A has_tag=()
  for n in "${tag_nums[@]}"; do
    [ -n "$n" ] && has_tag["$n"]=1
  done

  # Первый проход: артефакт без тега = «номер назначен рукой».
  mapfile -t artifacts < <(collect "$class")
  for line in "${artifacts[@]}"; do
    [ -n "$line" ] || continue
    IFS=$'\t' read -r f n <<<"$line"
    [ -n "$f" ] && [ -n "$n" ] || continue
    rel="${f#"$HERE"/}"
    if [ -z "${has_tag[$n]:-}" ]; then
      bad "номер $n назначен рукой, а не механизмом: $rel"
      violations=$((violations + 1))
    fi
  done

  # Второй проход: дубликаты номера в классе — оба пути названы.
  declare -A seen=()
  for line in "${artifacts[@]}"; do
    [ -n "$line" ] || continue
    IFS=$'\t' read -r f n <<<"$line"
    [ -n "$f" ] && [ -n "$n" ] || continue
    rel="${f#"$HERE"/}"
    if [ -n "${seen[$n]:-}" ]; then
      other_rel="${seen[$n]#"$HERE"/}"
      bad "одинаковый номер $n в классе $class: $other_rel и $rel"
      violations=$((violations + 1))
    else
      seen[$n]="$f"
    fi
  done
  unset seen has_tag
done

if [ "$violations" -gt 0 ]; then
  exit 1
fi
ok "номера уникальны и согласованы с регистром выдачи"