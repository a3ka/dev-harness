#!/usr/bin/env bash
# НЕ БАРЬЕР: предмет среза-1 контракта 008. Предполётный гейт автора перед созывом судьи
# (Н-38): контракт проходит 4 проверки (зоны/проба/счёт/арбитраж) или RC≠0 с ИМЕНОВАННОЙ
# причиной. Принимает аргумент <корень-дерева>, поэтому не самодостаточен для прогона на
# текущем дереве без указания — verify_antiplacebo не покрывает.
#
# Контракт API (закреплён meta-барьером check_check_contract_ready.sh):
#   вход: $1 = <корень-дерева> (НЕ <contract.md>); предмет читает <корень>/contract.md;
#   маркеры ищутся по ВСЕМУ файлу (НЕ по секциям — heads-up 008-1 архитектора);
#   - `ЗОНА <роль>: <путь>...` ИЛИ `РАБОТА НЕ РАЗДАЁТСЯ: <причина>` — хотя бы одно;
#   - `- `<команда в бэктиках>`` — проба: реальный ИСПОЛНЯЕМЫЙ файл, выходит ≠0 на текущем дереве;
#   - `счёт: N фикстур в <каталог>/` — если объявлено, фактический счёт `case_*.sh` в <каталог>/ == N;
#   - `арбитраж: <отн-путь>.md` — если объявлено, файл существует И строка 1 == «РЕШЕНИЕ»;
#   коды: 0 зелёный (печатает «OK» последней строкой); иначе 1 + первая ИМЕНОВАННАЯ причина.

ROOT="${1:?использование: $0 <корень-дерева>}"
CONTRACT="$ROOT/contract.md"

fail() {  # <причина> <сообщение>
  printf 'ОТКАЗ %s: %s\n' "$1" "$2" >&2
  exit 1
}

[ -f "$CONTRACT" ] || fail "контракт" "$CONTRACT не найден"

# ── 1. ЗОНА / РАБОТА НЕ РАЗДАЁТСЯ (хотя бы одно) ─────────────────────────────────
if ! grep -qE '^ЗОН' "$CONTRACT" && ! grep -qE '^РАБОТА НЕ РАЗДАЁТСЯ:' "$CONTRACT"; then
  fail "зон" "нет ни ЗОНА, ни РАБОТА НЕ РАЗДАЁТСЯ в $CONTRACT"
fi

# ── 2. Пробы: каждая - `<cmd>` — реальный исполняемый файл И rc≠0 ───────────────
while IFS= read -r line; do
  cmd=$(printf '%s\n' "$line" | sed -n 's/^- `\([^`]*\)`.*/\1/p')
  [ -z "$cmd" ] && fail "проб" "не извлёк команду из строки: $line"
  # Извлекаем путь к скрипту: если первый токен — интерпретатор (bash/sh/ksh/zsh или
  # абсолютный путь к интерпретатору), путь = следующий токен; иначе первый токен и есть путь.
  # Это закрывает bypass #1: пробы должны быть РЕАЛЬНЫМИ файлами, а не bash-127 от
  # несуществующего пути.
  first="${cmd%% *}"
  rest="${cmd#* }"
  case "$first" in
    bash|sh|ksh|zsh|ash|dash|/bin/bash|/usr/bin/bash|/bin/sh|/usr/bin/sh)
      script="${rest%% *}" ;;
    *) script="$first" ;;
  esac
  # Резолвим относительно $ROOT.
  case "$script" in
    /*) resolved="$script" ;;
    ./*|../*) resolved="$ROOT/${script#./}" ;;
    *) resolved="$ROOT/$script" ;;
  esac
  [ -f "$resolved" ] || fail "проб" "проба '$cmd': файл $resolved не существует — пробы должны быть реальные"
  [ -x "$resolved" ] || fail "проб" "проба '$cmd': $resolved не исполняемый (нет +x)"
  # Запуск в корне дерева, как автор контракта выполнял бы на своём дереве.
  ( cd "$ROOT" && bash -c "$cmd" ) >/dev/null 2>&1
  rc=$?
  [ "$rc" = "0" ] && fail "проб" "проба '$cmd' зелёная (rc=0) — должна быть красной на текущем дереве"
done < <(grep -E '^- `' "$CONTRACT" 2>/dev/null || true)

# Если маркер пробы есть, но мы ничего не нашли — это нормально (есть другие маркеры).
# Если ни одной пробы и ни одного счёта/арбитража — оставляем: ЗОНА уже проверена.

# ── 3. Счёт (если объявлен) ───────────────────────────────────────────────────────
if grep -qE '^счёт: ' "$CONTRACT"; then
  cline=$(grep -E '^счёт: ' "$CONTRACT" | head -1)
  declared=$(printf '%s\n' "$cline" | sed -n 's/^счёт: \([0-9]*\) фикстур в \(.*\)$/\1/p')
  dir=$(printf '%s\n' "$cline" | sed -n 's/^счёт: \([0-9]*\) фикстур в \(.*\)$/\2/p')
  declared="${declared:-}"
  dir="${dir:-}"
  [ -n "$declared" ] && [ -n "$dir" ] \
    || fail "счёт" "объявлен счёт без N или без каталога: '$cline'"
  actual=$(find "$ROOT/$dir" -maxdepth 1 -type f -name 'case_*.sh' 2>/dev/null | wc -l | tr -d ' ')
  [ "$declared" = "$actual" ] \
    || fail "счёт" "объявлено $declared фикстур в $dir/, фактически $actual"
fi

# ── 4. Арбитраж (если объявлен) ───────────────────────────────────────────────────
if grep -qE '^арбитраж: ' "$CONTRACT"; then
  arb_path=$(grep -E '^арбитраж: ' "$CONTRACT" | head -1 | sed 's/^арбитраж: //')
  full="$ROOT/$arb_path"
  [ -f "$full" ] || fail "арбитраж" "файл $full не найден"
  first=$(head -1 "$full" 2>/dev/null | tr -d $'\r')
  [ "$first" = "РЕШЕНИЕ" ] \
    || fail "арбитраж" "первая строка $full: '$first' ≠ 'РЕШЕНИЕ'"
fi
# Все 4 проверки зелёные.
printf 'OK\n'
exit 0