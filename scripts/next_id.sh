#!/usr/bin/env bash
# Выдача следующего номера артефакта по классу.
#
# Заведено потому, что два файла под одним идентификатором — нарушение, даже если предмет
# один: номер с двумя смыслами в истории нечем развести. Ручное назначение номеров уже
# сталкивалось в этом репозитории (план 005 §2), и выход один — выдавать номера только
# скриптом, чтобы у идентификатора была одна причина появления.
#
# Класс → куда он кладётся:
#   PLAN    → plans/                       — планы в корне репозитория;
#   VERDICT → verdicts/<роль>/             — пути ЧИТАЮТСЯ из roles/*.md (поле `verdict:`),
#                                             а не задаются вторым списком: правило «область
#                                             проверки важнее её порога» из плана 005 §1
#                                             здесь стоит прямо — список, набранный руками,
#                                             отстаёт от предмета молча;
#   ADR     → decisions/                   — каталога ещё нет, но в plan 006 будущая роль
#                                             `steward` ведёт записи решений там же. Решено
#                                             здесь, потому что место должно быть одно на
#                                             все классы: разные пути создали бы ещё один
#                                             список руками.
#
# Номер — максимум плюс один по ОБЪЕДИНЕНИЮ двух источников; разрывы не занимаются:
#   1. имена ссылок refs/heads/* ∪ refs/remotes/* — как в плане 005 §2;
#   2. имена файлов артефактов в локации класса.
# Второй источник обязателен по измеренной причине: ветка здесь одна (`main`), и номеров в
# именах ссылок нет вовсе, а `plans/` уже содержит 005 и 006. Счёт только по ссылкам выдал бы
# единицу и столкнулся бы с существующим артефактом на первом же вызове.
#
#   bash scripts/next_id.sh <класс>   печатает ОДИН номер в stdout; всё остальное — в stderr.
#
# Коды возврата: 0 — номер выдан, 1 — отказ, 2 — нечем проверить.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

die()  { printf 'ОТКАЗ: %s\n' "$*" >&2; exit 1; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

# Аргумент ровно один — класс. Больше или меньше — отказ с названной причиной.
[ "$#" -eq 1 ] || die "требуется один аргумент — класс (PLAN, VERDICT, ADR); получено: $#"
class="$1"

# Локации выводятся из роли файла, а не задаются списком. VERDICT особенно: его каталоги
# объявлены в `verdict:` ролей, и прежняя редакция взяла бы три имени руками — четвёртая
# роль отстала бы молча.
locations=()
case "$class" in
  PLAN)
    locations=("plans/")
    ;;
  VERDICT)
    while IFS= read -r p; do
      [ -n "$p" ] || continue
      locations+=("$p")
    done < <(grep -hoE '^verdict: [^[:space:]]+' "$HERE"/roles/*.md \
              | grep -v 'null' \
              | sed 's/^verdict: //')
    [ "${#locations[@]}" -gt 0 ] \
      || skip "ни одна роль не объявила verdict: кроме null — VERDICT выдавать некуда"
    ;;
  ADR)
    locations=("decisions/")
    ;;
  *)
    die "неизвестный класс: '$class' (допустимо: PLAN, VERDICT, ADR)"
    ;;
esac

# Сравнение номеров идёт как чисел. Ведущие нули (`010`) снимаются через `10#`, иначе
# строка `010` ложно меньше `9` в лексикографическом сравнении.
max=0

# Источник 1: имена ссылок. Из каждого имени вытаскиваем ПЕРВОЕ число. Сейчас все имена
# числовой части не содержат (ветка одна — `main`), и этот источник держит место на случай,
# когда кто-то назовёт ветку вроде `42-foo` или `2026-09-steward`.
while IFS= read -r ref; do
  [ -n "$ref" ] || continue
  if [[ "$ref" =~ ([0-9]+) ]]; then
    n=$((10#${BASH_REMATCH[1]}))
    [ "$n" -gt "$max" ] && max="$n"
  fi
done < <(git -C "$HERE" for-each-ref --format='%(refname:short)' refs/heads refs/remotes 2>/dev/null || true)

# Источник 2: файлы артефактов в локациях класса. Число — префикс имени до первого `-`.
# Файлы без числового префикса (`verdicts/adversary/mech-1-antiplacebo.md`) пропускаются:
# они законны (план 005 §2), и обратной силы у механизма нет.
for loc in "${locations[@]}"; do
  d="$HERE/$loc"
  [ -d "$d" ] || continue
  while IFS= read -r f; do
    [ -n "$f" ] || continue
    name="$(basename "$f")"
    if [[ "$name" =~ ^([0-9]+)- ]]; then
      n=$((10#${BASH_REMATCH[1]}))
      [ "$n" -gt "$max" ] && max="$n"
    fi
  done < <(find "$d" -maxdepth 1 -type f 2>/dev/null)
done

# Один номер в stdout — сюда подставляют имя файла. Всё остальное в stderr.
printf '%s\n' "$((max + 1))"