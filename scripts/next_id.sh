#!/usr/bin/env bash
# Выдача следующего номера артефакта по классу — атомарная, через резервацию тегом.
#
# Заведено потому, что до этого механизма два файла под одним идентификатором — нарушение,
# даже если предмет один: номер с двумя смыслами в истории нечем развести. Прежняя редакция
# только ПЕЧАТАЛА max+1 и оставляла выдачу без следа; параллельные вызовы получали один
# номер, и механизм против столкновения идентификаторов сам их и производил (вердикт
# `verdicts/adversary/mech-2-ids.md`, находка 1). Решение — резервация GIT-ТЕГОМ: `git tag`
# на существующем имени падает атомарно, и второй вызов обязан взять следующий номер, а не
# тот же. Тег — это и есть регистр выдачи, и артефакт без тега — «номер назначен рукой, а не
# механизмом».
#
# Класс → куда он кладётся:
#   PLAN    → plans/                       — планы в корне репозитория;
#   VERDICT → verdicts/<роль>/             — пути ЧИТАЮТСЯ из roles/*.md (поле `verdict:`),
#                                             а не задаются вторым списком: правило «область
#                                             проверки важнее её порога» из плана 005 §1
#                                             здесь стоит прямо — список, набранный руками,
#                                             отстаёт от предмета молча;
#   ADR     → decisions/                   — каталога ещё нет, но в plan 006 будущая роль
#                                             `steward` ведёт записи решений там же. Решено
#                                             здесь, потому что место должно быть одно на
#                                             все классы: разные пути создали бы ещё один
#                                             список руками.
#
# Номер — максимум плюс один по ОБЪЕДИНЕНИЮ источников:
#   1. теги `refs/tags/id/<КЛАСС>/*` — РЕГИСТР ВЫДАЧИ, и разрывы не занимаются: номер, чей
#      тег существует, не выдаётся повторно НИКОГДА, пока его собственный тег жив
#      (см. границу ниже);
#   2. имена ссылок refs/heads/* ∪ refs/remotes/* — на случай, когда кто-то назовёт ветку
#      `42-foo` или `2026-09-steward`;
#   3. файлы артефактов на HEAD — обход РЕКУРСИВНЫЙ: `verdicts/adversary/2026/002-x.md` тоже
#      артефакт (находка 3);
#   4. файлы артефактов в достижимой истории — обход рекурсивный по тем же правилам, чтобы
#      удалённый файл с тегом не мог быть выдан повторно.
#
# ПРАВИЛО РАЗЛИЧЕНИЯ НОМЕРА. ЕДИНСТВЕННАЯ реализация живёт в функции
# `parse_artifact_basename` (см. ниже); её же импортируют `check_ids.sh` и
# `drill_next_id_race.sh` через `NEXT_ID_LIB=1 source next_id.sh`. До этого разбор имени
# жил ДВАЖДЫ — здесь и в `check_ids.sh` — и расходился молча (находка 5 второго круга):
# `007-план.md` (русское имя в русском репозитории) и `007-2026-x.md` (дата после дефиса)
# один разбор принимал, другой отбрасывал, и нарушение не было видно ни сверке, ни выдаче.
# Теперь оба пользуются ОДНОЙ функцией: три цифры, дефис, не-цифра (`007-план.md` идёт,
# `007-2026-x.md` идёт в безномерные). Неправильный формат — ровно не три цифры
# (`7-x.md`, `0007-x.md`) — отдельный код возврата; `check_ids` сообщает о нём как
# «номер N в неправильном формате», и три цифры обязательны в ОБЕ стороны.
#
# ФОРМАТ — ровно три цифры с ведущими нулями: `007`, не `7`. Это контракт имён:
# артефакты называются `005-...`, `006-...`, и `plans/7-x.md` сломал бы и сортировку
# (лексикографически `7` старше `10`), и сверку (находка 2: `plans/7-x.md` рядом с
# `plans/007-y.md` становился «тем же» 7). Если максимум перевалил за 999 — отказ с
# названной причиной, а не молчаливое расширение формата.
#
# АТОМАРНОСТЬ. Перед тем как напечатать номер, скрипт СОЗДАЁТ тег `id/<КЛАСС>/<NNN>` —
# `git tag` на существующем имени возвращает ненулевой код. Тогда скрипт пересчитывает
# максимум (тег уже виден в `for-each-ref`) и пробует следующий. Это закрывает гонку двух
# вызовов за один номер В ОДНОМ `.git`: один выигрывает, другой обязан взять следующий.
#
# ────────────────────────────────────────────────────────────────────────────
# ГРАНИЦА «ТЕГ МОЖНО УДАЛИТЬ РУКОЙ» (записана явно, измерена адверсарием — находка 1
# второго круга). Тег `id/<КЛАСС>/<NNN>` — обычный локальный ref, и `git tag -d` стирает
# его без спроса.
#
#   ЧТО ДЕРЖИТ: номер, чей тег удалён, остаётся занятым, пока АРТЕФАКТ ЖИВ.
#   `check_ids.sh` это видит как ветку (в): «номер N назначен рукой, а не механизмом:
#   <путь>». Самая частая форма расхождения — удалили тег, артефакт забыли — ловится
#   сверкой и НЕ МОЖЕТ пройти зелёной.
#
#   ЧТО НЕ ДЕРЖИТ: ручное удаление и артефакта, и тега вместе — освобождает номер.
#   Скрипт снова выдаст тот же N, и `check_ids` промолчит: новые файл и тег согласованы.
#   Это ГРАНИЦА, не дыра: чтобы стереть номер, нужно стереть оба следа. Согласованность
#   файла и тега защищает только от расхождения, не от стирания. Скрытая граница — тот же
#   дефект, что и неполный регистр: адверсарий находит её прогоном и предъявляет как дыру,
#   поэтому она записана здесь явно, а не выводится из кода по контексту.
# ────────────────────────────────────────────────────────────────────────────
#
# ────────────────────────────────────────────────────────────────────────────
# ГРАНИЦА «ГОНОЧНЫЙ КЛОН» (записана явно, измерена адверсарием — находка 2 второго круга).
# Тег локален, и два НЕЗАВИСИМЫХ клона одновременно выдают 007 — каждый создаёт свой тег
# и свой `007-x.md`. Общего реестра между клонами нет.
#
#   ЧТО ДЕРЖИТ: локальная атомарность в одном `.git` — десять одновременных вызовов не
#   дублируют номер. Дрилл `drill_next_id_race.sh` это предъявляет зелёным.
#
#   ЧТО НЕ ДЕРЖИТ: общая резервация между клонами — её нет, и это не дефект скрипта, а
#   ГРАНИЦА механизма. После слияния двух таких веток `check_ids.sh` ОБЯЗАН увидеть дубль
#   номера и назвать ОБА артефакта — это ловит ветку (в): «номер N назначен рукой». Так
#   общая атомарность достигается не выдачей, а сверкой: локальная резервация даёт
#   уникальность внутри клона, а сверка ловит дубль при слиянии.
# ────────────────────────────────────────────────────────────────────────────
#
# ГЕРМЕТИЧНОСТЬ ОТ ВНЕШНЕГО РЕПОЗИТОРИЯ. Скрипт снимает `GIT_DIR`, `GIT_WORK_TREE`,
# `GIT_INDEX_FILE`, `GIT_OBJECT_DIRECTORY`, `GIT_ALTERNATE_OBJECT_DIRECTORIES`,
# `GIT_TEMPLATE_DIR` — каждая из них, будучи выставленной в среде, перенаправляет `git`
# в чужой репозиторий. Адверсарий измерил (находка 6 второго круга): `GIT_DIR=<чужой>`
# делал `check_ids` и `drill` зелёными на чужом `.git`, а предмет не проверялся вовсе.
# `git -c user.name=… -c user.email=… -c commit.gpgsign=false -c core.hooksPath=/dev/null`
# ставит идентичность и подпись в самом вызове — иначе пустой локальный конфиг временного
# репозитория валит `git tag` с «empty ident name» (находка адверсария на механизме 4).
#
# ПЕЧАТЬ. Один номер в stdout, всё остальное в stderr. Скрипт не печатает PASS — результат
# есть код возврата, как требует правило «скрипт не имеет права печатать PASS».
#
# --backfill <КЛАСС>. Одна команда, прогоняется при ЗАПУСКЕ МЕХАНИЗМА и больше не нужна:
# создаёт теги резервации для артефактов, чьи номера были выданы ДО заведения этого
# регистра. Сообщение тега — «выдано до заведения регистра», чтобы в `git show <tag>`
# причина была видна сразу, а не выводилась из контекста. Идемпотентно: повторный прогон
# не пересоздаёт уже существующие теги.
#
# КОРЕНЬ ДЛЯ ПРОВЕРКИ. Необязателен: по умолчанию — родитель каталога скрипта, как у
# остальных барьеров в этом репозитории. Дрилл `drill_next_id_race.sh` создаёт временный
# репозиторий и зовёт скрипт с явным корнем, чтобы не зависеть от того, что лежит в
# `plans/` основного дерева.
#
#   bash scripts/next_id.sh <КЛАСС>              выдать номер в основном дереве
#   bash scripts/next_id.sh <КОРЕНЬ> <КЛАСС>     выдать номер в указанном корне
#   bash scripts/next_id.sh --backfill <КЛАСС>   бэкфилл в основном дереве
#
# Коды возврата: 0 — номер выдан (или backfill завершён), 1 — отказ, 2 — нечем проверить.

# ── ГЕРМЕТИЧНОЕ ОКРУЖЕНИЕ GIT (стоит ДО `set -e`, чтобы работать и при импорте) ──
# Снимаем шесть переменных окружения, которые перенаправляют `git` в чужой репозиторий
# сильнее, чем `-C "$HERE"`. Адверсарий измерил (находка 6 второго круга): `GIT_DIR` и
# `GIT_WORK_TREE` достаточно выставить в среде — и `-C` уже не работает, барьер валит
# зелёный на чужом `.git`. Стоит здесь, а не после `set -e`, чтобы снимать переменные
# и в режиме импорта библиотеки (`NEXT_ID_LIB=1 source next_id.sh`) — иначе вызывающий
# скрипт (`check_ids.sh`) подхватывал их через свою среду.
unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_TEMPLATE_DIR

# ── РАЗДЕЛЯЕМАЯ БИБЛИОТЕКА ────────────────────────────────────────────────────
# Функция `parse_artifact_basename` — ЕДИНСТВЕННАЯ реализация разбора имени артефакта.
# Раньше разбор жил дважды (здесь и в `check_ids.sh`) и расходился молча (находка 5
# второго круга: `007-план.md` и `007-2026-x.md`). Два скрипта импортируют эту функцию
# через `NEXT_ID_LIB=1 source next_id.sh` и получают ровно ту же логику.
#
# parse_artifact_basename NAME
#   Возвращает 0, если NAME — ровно три цифры + дефис + не-цифра: `007-x.md`,
#   `007-план.md`. Репозиторий по-русски, кириллица — в области.
#   Возвращает 2, если NAME выглядит как нумерованный артефакт, но цифр НЕ три:
#   `7-x.md` (одна цифра), `0007-x.md` (четыре цифры). Тот же номер 7 в другой записи;
#   три цифры обязательны в ОБЕ стороны.
#   Возвращает 1, если NAME не нумерованный: `verdicts/.../mech-1-...md`,
#   `2026-08-17-x.md`, `007-2026-x.md` (за дефисом сразу цифра).
#   ARTIFACT_NUMBER — числовое значение (без ведущих нулей), только при возврате 0 или 2.
parse_artifact_basename() {
  local name="$1"
  if [[ "$name" =~ ^([0-9]{3})-([^0-9]) ]]; then
    ARTIFACT_NUMBER=$((10#${BASH_REMATCH[1]}))
    ARTIFACT_REST="${BASH_REMATCH[2]}"
    return 0
  fi
  if [[ "$name" =~ ^([0-9]+)-([^0-9]) ]]; then
    ARTIFACT_NUMBER=$((10#${BASH_REMATCH[1]}))
    ARTIFACT_REST="${BASH_REMATCH[2]}"
    return 2
  fi
  ARTIFACT_NUMBER=""
  ARTIFACT_REST=""
  return 1
}

# ── ИМПОРТ КАК БИБЛИОТЕКА ────────────────────────────────────────────────────
# Когда скрипт импортируется (`NEXT_ID_LIB=1 source next_id.sh`), определяется функция
# `parse_artifact_basename` и работа завершается. Иначе — основной код. Так одна
# реализация разбора имени живёт ровно в одном месте, и расхождение двух разборов
# одного формата невозможно по построению.
#
# Возврат стоит ДО `set -euo pipefail`: если бы `set -e` стоял выше, любая функция
# библиотеки, вернувшая код 1 (например, `parse_artifact_basename` для безномерного
# файла), валила бы импортирующий скрипт (`check_ids.sh`) — без объявленной причины.
if [ "${NEXT_ID_LIB:-}" = "1" ]; then
  return 0 2>/dev/null || exit 0
fi

set -euo pipefail

HERE_DEFAULT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HERE="$HERE_DEFAULT"

die()  { printf 'ОТКАЗ: %s\n' "$*" >&2; exit 1; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

command -v git >/dev/null 2>&1 || skip "нет git — историю выдачи прочитать нечем"

# ── разбор аргументов ──────────────────────────────────────────────────────────
# Два режима: <КЛАСС> — выдать номер, --backfill <КЛАСС> — создать теги для существующих
# артефактов. Необязательный первый аргумент — <КОРЕНЬ>: путь к репозиторию, в котором
# живут артефакты. Так дрилл и фикстуры указывают на свой временный `WORK`, а обычный
# запуск из CI/CLI работает без флагов, как требует контракт.
mode="issue"
root_given=0
case "${1:-}" in
  "")
    die "требуется аргумент — класс (PLAN, VERDICT, ADR); получено: 0"
    ;;
  --backfill)
    mode="backfill"
    [ "$#" -eq 2 ] || die "для --backfill требуется один аргумент — класс; получено: $#"
    class="$2"
    ;;
  /*|./*|../*|~/*)
    # Первый аргумент выглядит как путь. Это <КОРЕНЬ>, остальное — режим/класс.
    HERE="$(cd "$1" && pwd)"
    root_given=1
    shift
    case "${1:-}" in
      "")
        die "после <КОРЕНЬ> требуется класс; получено: 0"
        ;;
      --backfill)
        mode="backfill"
        [ "$#" -eq 2 ] || die "для --backfill после <КОРЕНЬ> требуется один аргумент — класс; получено: $#"
        class="$2"
        ;;
      *)
        [ "$#" -eq 1 ] || die "после <КОРЕНЬ> допустимы <КЛАСС> или --backfill <КЛАСС>; получено аргументов после корня: $#"
        class="$1"
        ;;
    esac
    ;;
  *)
    [ "$#" -eq 1 ] || die "требуется один аргумент — класс (PLAN, VERDICT, ADR); получено: $#"
    class="$1"
    ;;
esac
unset root_given

# ── локации класса ─────────────────────────────────────────────────────────────
# VERDICT: пути читаются из ролей. Захардкоженный список отстал бы от новой роли молча —
# это правило уже выстрелило (там три имени заданы списком и четвёртое пропущено), и здесь
# будет то же. Если `roles/` нет — отказ с названной причиной.
locations=()
case "$class" in
  PLAN)
    locations=("plans/")
    ;;
  VERDICT)
    # Локации выводятся из объявлений ролей ЕДИНСТВЕННОЙ реализацией грамматики
    # (`scripts/lib_roles.sh`). Прежняя редакция выхватывала значение однострочным `grep` по
    # `roles/*.md`: фронтматтер не читался, значение не валидировалось, подкаталоги не
    # обходились — и роль с `verdict: verdicts/*/` МОЛЧА выпадала из области. Найдено
    # ревьюером (`verdicts/review/shag-5.md`, находка 3); неразобранное объявление — отказ.
    # От САМОГО скрипта, а не от проверяемого дерева: `$HERE` — корень, названный аргументом,
    # и подключение оттуда означало бы, что код барьера приходит из предмета проверки.
    . "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib_roles.sh"
    [ -d "$HERE/roles" ] || skip "нет каталога roles/ — для VERDICT локации выводятся из verdict: ролей"
    while IFS=$'\t' read -r status path value; do
      case "$status" in
        ok)      locations+=("$value") ;;
        null)    ;;
        invalid) die "роль вне объявленной грамматики: $path значение «$value» — префикс обязан завершаться /, быть относительным, без шаблонов и ..; выход: привести к грамматике" ;;
      esac
    done < <(role_declarations "$HERE")
    [ "${#locations[@]}" -gt 0 ] \
      || skip "ни одна роль не объявила verdict: кроме null — VERDICT выдавать некуда"
    ;;
  ADR)
    locations=("decisions/")
    ;;
  # Контракт майлстоуна: предмет, критерий готовности, зоны исполнителей. Отсутствующий каталог
  # ЗАКОНЕН — первый контракт заводится этой же выдачей, и максимум тогда берётся по тегам
  # `id/CONTRACT/*`, как у любой пустой локации.
  CONTRACT)
    locations=("contracts/")
    ;;
  *)
    die "неизвестный класс: '$class' (допустимо: PLAN, VERDICT, ADR, CONTRACT)"
    ;;
esac

# ── текущий репозиторий и HEAD ────────────────────────────────────────────────
# Если $HERE не репозиторий git (фикстура с минимумом, пустой WORK) — отказ 2, потому что
# без git мы не можем ни читать регистр выдачи, ни создавать в нём теги. Команда выдачи без
# git в PATH — не имеет права сообщать успешную выдачу (находка 7).
git -C "$HERE" rev-parse --git-dir >/dev/null 2>&1 \
  || skip "$HERE не репозиторий git — выдавать номера негде"

# ── режим backfill ────────────────────────────────────────────────────────────
# Для каждого артефакта с валидным форматом (три цифры) в локациях класса — создать тег
# резервации, если его ещё нет. Сообщение тега фиксирует причину: «выдано до заведения
# регистра». Без сообщения причина неотличима от опечатки и в `git show <tag>` не видна.
# Неправильный формат (`7-x.md`, `0007-x.md`) — не подлежит backfill-у: владелец должен
# переписать имя, а сам тег всё равно будет выдан под валидным представлением номера.
if [ "$mode" = "backfill" ]; then
  created=0; skipped=0
  for loc in "${locations[@]}"; do
    d="$HERE/$loc"
    [ -d "$d" ] || continue
    while IFS= read -r f; do
      [ -n "$f" ] || continue
      name="$(basename "$f")"
      parse_artifact_basename "$name" || continue
      n="$ARTIFACT_NUMBER"
      tagname="id/${class}/$(printf '%03d' "$n")"
      if git -C "$HERE" show-ref --tags --quiet -- "refs/tags/$tagname"; then
        skipped=$((skipped + 1))
        continue
      fi
      git -C "$HERE" tag "$tagname" -m "выдано до заведения регистра" \
        || die "не удалось создать тег $tagname"
      created=$((created + 1))
    done < <(find "$d" -type f 2>/dev/null)
  done
  printf '  ok   backfill %s: создано %d, уже было %d\n' "$class" "$created" "$skipped" >&2
  exit 0
fi

# ── вычисление максимума по объединению источников ────────────────────────────
# Все источники дают ЧИСЛО, ведущие нули снимаются через `10#`. Цикл по тегам читает
# `refs/tags/id/<КЛАСС>/*`; цикл по веткам берёт ЛЮБОЕ первое число из имени (на случай
# `42-foo`); цикл по HEAD и по истории — рекурсивный, по тому же правилу (через
# `parse_artifact_basename`). `7-x.md` и `0007-x.md` — оба число 7, и оба идут в max;
# безномерные (`mech-1-...md`, `2026-08-17-x.md`) идут мимо.
max=0

# Источник 1: теги выдачи. Это РЕГИСТР, и именно он обеспечивает атомарность и
# неповторяемость: при гонке проигравший пересчитывает max и видит тег победителя.
while IFS= read -r tag; do
  [ -n "$tag" ] || continue
  if [[ "$tag" =~ id/[^/]+/([0-9]+)$ ]]; then
    n=$((10#${BASH_REMATCH[1]}))
    [ "$n" -gt "$max" ] && max="$n"
  fi
done < <(git -C "$HERE" for-each-ref --format='%(refname:short)' "refs/tags/id/$class/" 2>/dev/null || true)

# Источник 2: имена ссылок. Число — первая группа цифр в имени. Сейчас все ветки — `main`,
# и этот источник не даёт чисел; он держит место на случай именованной ветки.
while IFS= read -r ref; do
  [ -n "$ref" ] || continue
  if [[ "$ref" =~ ([0-9]+) ]]; then
    n=$((10#${BASH_REMATCH[1]}))
    [ "$n" -gt "$max" ] && max="$n"
  fi
done < <(git -C "$HERE" for-each-ref --format='%(refname:short)' refs/heads refs/remotes 2>/dev/null || true)

# Источник 3: файлы на HEAD (рекурсивно). Через `parse_artifact_basename` — тот же
# разбор, что в `check_ids.sh` и `drill_next_id_race.sh`. Возвраты 0 и 2 идут в max.
for loc in "${locations[@]}"; do
  d="$HERE/$loc"
  [ -d "$d" ] || continue
  while IFS= read -r f; do
    [ -n "$f" ] || continue
    name="$(basename "$f")"
    parse_artifact_basename "$name" || true
    [ -n "$ARTIFACT_NUMBER" ] || continue
    [ "$ARTIFACT_NUMBER" -gt "$max" ] && max="$ARTIFACT_NUMBER"
  done < <(find "$d" -type f 2>/dev/null)
done

# Источник 4: пути в достижимой истории. `git log --all --diff-filter=A --name-only` даёт
# файлы, добавленные когда-либо в любой достижимый коммит; их basename проверяется тем же
# правилом. Без рекурсии в `grep` `verdicts/adversary/2026/002-x.md` бы не попал
# (находка 3 — старая редакция ограничивалась одним уровнем).
while IFS= read -r path; do
  [ -n "$path" ] || continue
  base="${path##*/}"
  parse_artifact_basename "$base" || true
  [ -n "$ARTIFACT_NUMBER" ] || continue
  [ "$ARTIFACT_NUMBER" -gt "$max" ] && max="$ARTIFACT_NUMBER"
done < <(git -C "$HERE" log --all --diff-filter=A --name-only --format= 2>/dev/null \
         | awk -v locs="${locations[*]}" '
             BEGIN { for (i=1; i<=length(locs); i++) {} }
             {
               for (i=1; i<=split(locs, arr, " "); i++) {
                 l = arr[i]
                 if (length($0) > length(l) && substr($0, 1, length(l)) == l) {
                   print
                   break
                 }
               }
             }' || true)

# ── выдача с атомарной резервацией ────────────────────────────────────────────
# Создаём тег ДО печати. Если тег уже существует (гонка или backfill) — пересчитываем max
# и пробуем следующий номер; цикл ограничен попытками, чтобы сломанный внешний процесс,
# плодящий теги, не заставил нас крутиться бесконечно.
attempts=0
max_attempts=1000
while :; do
  attempts=$((attempts + 1))
  if [ "$attempts" -gt "$max_attempts" ]; then
    die "не удалось выдать номер за $max_attempts попыток — внешний процесс плодит теги?"
  fi

  n=$((max + 1))
  if [ "$n" -gt 999 ]; then
    die "следующий номер $n превышает 999 — выдавать дальше нечего, формат не расширяется"
  fi

  tagname="id/${class}/$(printf '%03d' "$n")"
  if git -C "$HERE" tag "$tagname" -m "выдача механизмом $(date -u +%Y-%m-%dT%H:%M:%SZ)"; then
    printf '%03d\n' "$n"
    exit 0
  fi

  # Тег уже существовал — это гонка или backfill. Пересчитываем max: если тег нашего
  # уровня уже есть, источник 1 даст его, и max поднимется. Если по-прежнему нет — мы
  # нарвались на внешнюю ошибку git, и зацикливаться нельзя.
  if ! git -C "$HERE" show-ref --tags --quiet -- "refs/tags/$tagname"; then
    die "git tag $tagname не удалось по причине, отличной от существования тега"
  fi

  max=0
  while IFS= read -r tag; do
    [ -n "$tag" ] || continue
    if [[ "$tag" =~ id/[^/]+/([0-9]+)$ ]]; then
      m=$((10#${BASH_REMATCH[1]}))
      [ "$m" -gt "$max" ] && max="$m"
    fi
  done < <(git -C "$HERE" for-each-ref --format='%(refname:short)' "refs/tags/id/$class/" 2>/dev/null || true)
done