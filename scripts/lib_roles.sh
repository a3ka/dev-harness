# НЕ БАРЬЕР: библиотека, а не гейт. Вердикт кодом возврата выносит тот, кто её подключил;
# сама она только разбирает и валидирует объявление роли. Классификация объявлена явно, потому
# что `scripts/verify_antiplacebo.sh` требует фикстуру от каждого барьера и не догадывается.
#
# ЕДИНСТВЕННАЯ реализация грамматики поля `verdict:`. Заведена по вердикту ревьюера
# `verdicts/review/shag-5.md`, находка 3: `check_protected.sh` уже разбирал объявление по
# решению арбитража строго, а `next_id.sh` и `check_ids.sh` продолжали выхватывать значение
# однострочным `grep`, не читая фронтматтер и ничего не валидируя. Роль с `verdict: verdicts/*/`
# у них МОЛЧА выпадала из области — то есть одно и то же объявление имело два смысла, и
# защита снималась тем же движением, что и предмет.
#
# Второй разбор одного формата расходится молча. В этом репозитории так уже было дважды: об
# этом прямо написано в `scripts/roles.ts`, и по этой же причине разбор имени артефакта сведён
# в одну функцию в `next_id.sh`. Третий случай закрыт здесь.
#
# Грамматика (решение арбитража, вопрос 1): поле `verdict:` обязано лежать во ФРОНТМАТТЕРЕ —
# первом блоке между `---`, читаемом целиком, без числового лимита строк. Значение — `null`
# либо буквальный относительный префикс каталога: завершается `/`, без `*?[`, без ведущего `/`,
# без `..`, без пробельных символов. Всё иное — неразобранное объявление, то есть ОТКАЗ с
# названным местом, а не пустое место.

# Печатает значение поля `verdict:` из фронтматтера. Вход — текст файла роли на stdin.
role_verdict_value() {
  awk 'NR == 1 && $0 == "---" { inside = 1; next }
       inside && $0 == "---"  { exit }
       inside && sub(/^verdict:[[:space:]]*/, "") { sub(/[[:space:]]+$/, ""); print; exit }'
}

# 0 — значение соответствует грамматике; 1 — нет. `null` соответствует и означает «вердиктов
# этой роли не предписано».
role_verdict_valid() {
  local v="$1"
  [ "$v" = "null" ] && return 0
  [ -n "$v" ] || return 1
  case "$v" in
    /*|*..*|*\**|*\?*|*\[*|*[[:space:]]*) return 1 ;;
    */)                                   return 0 ;;
    *)                                    return 1 ;;
  esac
}

# Обходит роли в дереве и печатает по строке `СТАТУС<TAB>ПУТЬ<TAB>ЗНАЧЕНИЕ`:
#   ok      — валидный префикс каталога вердиктов (значение непустое, не `null`);
#   null    — роль объявила отсутствие вердиктов;
#   invalid — объявление вне грамматики; вызвавший ОБЯЗАН отказать, а не пропустить.
# Обход РЕКУРСИВНЫЙ: роль в подкаталоге — та же роль, а `roles/*.md` глобом её не видит.
role_declarations() {
  local root="$1" f v
  [ -d "$root/roles" ] || return 0
  while IFS= read -r f; do
    [ -n "$f" ] || continue
    v="$(role_verdict_value < "$f" || true)"
    if [ "$v" = "null" ]; then
      printf 'null\t%s\t%s\n' "${f#"$root"/}" "$v"
    elif role_verdict_valid "$v"; then
      printf 'ok\t%s\t%s\n' "${f#"$root"/}" "$v"
    else
      printf 'invalid\t%s\t%s\n' "${f#"$root"/}" "${v:-нет поля verdict во фронтматтере}"
    fi
  done < <(find "$root/roles" -type f -name '*.md' 2>/dev/null | sort)
}
