#!/usr/bin/env bash
# Барьер: реестр решений `decisions/` существует, поля каждой записи — в объявленной
# грамматике, и состав — ровно семь файлов из перечня замороженного контракта.
#
# Заведено потому, что до этого контракта семь решений владельца жили в переписке и
# планах: находит их только тот, кто помнит, а прецедент, который не находится, не
# существует. Барьер механизирует три вещи:
#
#   1. ГРАММАТИКА ЗАПИСИ. Шесть полей объявлены контрактом и обязаны присутствовать в
#      каждом файле: дата, вопрос, решение, основание, область, условие пересмотра.
#      Поле пустое — отказ с названным именем поля: «нет поля <X> в <файл>».
#
#   2. СОСТАВ РЕЕСТРА. Ровно файлы 001-007 с именами из перечня в теле замороженного
#      контракта `contracts/002-approval-mode-steward.md`. Отсутствие любого из семи
#      — отказ с названным номером. Лишний файл — отказ с названным путём, потому что
#      молчаливое расширение реестра хуже явной ошибки: добавленная запись без
#      вердикта круга проходит под именем зарегистрированной.
#
#   3. ОСНОВАНИЕ. Хеш коммита, разрешающийся в истории (`git cat-file -e`). Для
#      записей 005-007 замороженная таблица контракта требует совпадения с
#      НАЗВАННЫМ хешом (арбитраж 4, вопрос 1): «разрешимое основание ≠ названный
#      коммит» было остаточным обходом, закрытым строковым сравнением. Для 001-004
#      пришпиливание к хешу невозможно по построению — там остаётся разрешимость.
#
# Область выведена из предмета: каталог `decisions/` на любой глубине, имя файла
# начинается с трёхзначного номера и дефиса (как в `check_ids.sh` — единый разбор).
# Прежняя редакция читала только `decisions/*.md`; подкаталог с записями по годам
# упал бы из области молча — того же класса дефект, что уже измерен.
#
# Герметичность от чужого репозитория — снятием шести переменных `GIT_*` (измерено
# адверсарием на `check_ids.sh`).
#
#   bash scripts/check_decisions.sh            проверить это дерево
#   bash scripts/check_decisions.sh <корень>   проверить подставное (так предъявляется
#                                               красным)
#
# Коды возврата: 0 — состав полон, поля в грамматике, основания разрешимы и (для
# 005-007) совпадают с таблицей контракта, 1 — нарушение, 2 — нечем проверить.
set -euo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_TEMPLATE_DIR GIT_CEILING_DIRECTORIES
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
NEXT_ID_LIB=1
# shellcheck disable=SC1091
. "$SELF_DIR/next_id.sh"

ROOT="$(cd "${1:-"$SELF_DIR/.."}" && pwd)"

violations=0
ok()   { printf '  ok   %s\n' "$*" >&2; }
bad()  { violations=$((violations + 1)); printf '  FAIL %s\n' "$*" >&2; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

command -v git >/dev/null 2>&1 || skip "нет git — историю прочитать нечем"
git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1 \
  || skip "$ROOT не репозиторий git — историю прочитать нечем"
git -C "$ROOT" rev-parse --verify HEAD >/dev/null 2>&1 \
  || skip "в $ROOT нет ни одного коммита — основания разрешать не из чего"

# ── ТАБЛИЦА КОНТРАКТА ────────────────────────────────────────────────────────
# Источник истины для 005-007 — замороженное тело контракта. Текст таблицы лежит в
# файле, и читается он ЕДИНСТВЕННЫМ разбором — строковым сравнением строки колонки.
# Три хеша из таблицы — единственное место, где контракт называет коммит числом; для
# 001-004 таблица называет прозу и хеш не требует. Любая правка контракта под зелёный
# краснеет на `check_contract_frozen.sh` — здесь её перечитывать не надо.
g() { git -C "$ROOT" "$@"; }
CONTRACT="contracts/002-approval-mode-steward.md"
[ -f "$ROOT/$CONTRACT" ] || skip "контракт-источник не найден: $ROOT/$CONTRACT"

# Пять записей 003-007 несут хеш в колонке 3 таблицы. Извлекаются строкой по формату
# `| 00N | ... | <хеш> |`, и любое расхождение с заявленным основанием записи — код 1.
# Ключи — с ведущими нулями, как в Markdown-таблице, чтобы избежать разночтения
# между числовым и строковым доступом.
declare -A TABLE_HASH=()
while IFS='|' read -r _ num _ hash _; do
  n="$(echo "$num" | tr -d ' ')"
  case "$n" in
    003|004) continue ;;  # таблица называет прозу, хеша нет
  esac
  # Колонка может содержать пояснение после хеша: «`fa4457a` (слово владельца)».
  # Хеш — первые 7+ hex после снятия кавычек и пробелов. Пояснение без хеша
  # вначале невозможно по построению таблицы.
  h="$(echo "$hash" | tr -d ' \`' | grep -oE '^[0-9a-f]{7,40}')"
  TABLE_HASH["$n"]="$h"
done < <(grep -E '^\| (00[3-7]) \|' "$ROOT/$CONTRACT" || true)

# Явная фиксация трёх хешей, которых требует арбитраж 4 (вопрос 1): это не
# перестраховка сверх `grep`, а ЗАПИСАННАЯ связь с замороженным текстом, чтобы
# будущая правка контракта без смены этого файла была видна механизму сразу.
for n in 005 006 007; do
  case "$n" in
    005) want="93fc601" ;;
    006) want="fa4457a" ;;
    007) want="8ed63e6" ;;
  esac
  got="${TABLE_HASH[$n]:-}"
  [ "$got" = "$want" ] || bad "таблица контракта для записи $n называет «$got», а арбитраж 4 фиксирует «$want» — расхождение контракта и замороженного вердикта"
done

# ── ОБХОД ФАЙЛОВ ─────────────────────────────────────────────────────────────
# Реестр — `decisions/` на любой глубине. Разбор имени — через
# `parse_artifact_basename` из `next_id.sh` (единая реализация с `check_ids.sh`).
mapfile -t DECISION_FILES < <(
  find "$ROOT/decisions" -type f -name '*.md' 2>/dev/null | sort
)

[ "${#DECISION_FILES[@]}" -gt 0 ] || bad "нет файлов в decisions/ — реестр пуст"

declare -A SEEN_NUMBER=()
declare -A FILE_FOR_NUMBER=()

# Шесть обязательных полей. Парсер — построчный: «поле: значение», продолжение —
# строка с отступом (≥2 пробелов) или табуляцией; пустая строка завершает поле.
REQUIRED_FIELDS=(дата вопрос решение основание область условие_пересмотра)
# Имя в файле: «условие пересмотра» — через пробел. Поиск по обоим представлениям.

# `parse_record <файл>` → печатает пары «имя_поля<TAB>значение», по одной на поле.
parse_record() {
  local f="$1"
  awk '
    BEGIN { FS = ": " }
    {
      # Только строки, начинающиеся с одного из шести имён и двоеточия — кандидаты.
      if (match($0, /^([а-яА-ЯёЁ ]+): /, m)) {
        cur = m[1]
        val = substr($0, RSTART + RLENGTH)
        # Поле может быть «условие пересмотра» — пробел в имени норма.
        sub(/[[:space:]]+$/, "", cur)
        printf "%s\t%s\n", cur, val
      } else if (/^[[:space:]]/ && cur != "") {
        # Продолжение предыдущего поля.
        printf "%s\t%s\n", cur, $0
      } else if ($0 ~ /^[[:space:]]*$/) {
        cur = ""
      }
    }
  ' "$f"
}

# ── ПРОВЕРКА КАЖДОГО ФАЙЛА ──────────────────────────────────────────────────
for f in "${DECISION_FILES[@]}"; do
  rel="${f#"$ROOT"/}"
  base="$(basename "$f" .md)"
  # Разбор имени: три цифры, дефис, имя. Единая реализация — `parse_artifact_basename`
  # из next_id.sh: ставит `ARTIFACT_NUMBER` в окружение вызывающего.
  unset ARTIFACT_NUMBER
  parse_artifact_basename "$base" >/dev/null 2>&1 || {
    bad "$rel: имя файла не разбирается как NNN-<имя> — единый разбор из next_id.sh"
    continue
  }
  num="$ARTIFACT_NUMBER"
  [ -n "$num" ] || { bad "$rel: не извлёкся номер из имени"; continue; }
  # Ключи ассоциативных массивов — числовые (`parse_artifact_basename` снимает
  # ведущие нули). Для таблицы контракта ключ — с ведущими нулями; `num_padded`
  # хранит его в обоих представлениях.
  num_padded="$(printf '%03d' "$num")"
  if [ -n "${SEEN_NUMBER[$num]:-}" ]; then
    bad "$rel: дубль номера $num_padded — в реестре уже есть ${SEEN_NUMBER[$num]}"
    continue
  fi
  SEEN_NUMBER[$num]="$rel"
  FILE_FOR_NUMBER[$num]="$rel"

  # Грамматика полей. Все шесть должны присутствовать с непустым значением.
  declare -A HAVE=()
  while IFS=$'\t' read -r k v; do
    [ -n "$k" ] || continue
    HAVE["$k"]+="$v"
  done < <(parse_record "$f")
  for field in "${REQUIRED_FIELDS[@]}"; do
    # «условие_пересмотра» в файле пишется через пробел: «условие пересмотра».
    file_key="$field"
    [ "$field" = "условие_пересмотра" ] && file_key="условие пересмотра"
    val="${HAVE[$file_key]:-}"
    if [ -z "$val" ]; then
      bad "$rel: нет поля «$file_key»"
    fi
  done

  # Основание — одиночный токен-хеш. Продолжений у него быть не должно: правило
  # гласит «называет существующий в истории коммит», а хеш — это одно слово.
  base_val="${HAVE[основание]:-}"
  # Снять ведущие/хвостовые пробелы и переводы строк, склеенные в парсере.
  base_hash="$(printf '%s' "$base_val" | tr -d '[:space:]')"
  if [ -z "$base_hash" ]; then
    bad "$rel: основание пустое"
    continue
  fi
  # Хеш коммита — 7+ hex; всё иное сразу отказ, без попыток `cat-file`.
  if ! printf '%s' "$base_hash" | grep -qE '^[0-9a-f]{7,40}$'; then
    bad "$rel: основание «$base_hash» не похоже на хеш коммита"
    continue
  fi
  if ! g cat-file -e "$base_hash" 2>/dev/null; then
    bad "$rel: основание «$base_hash» не разрешается в истории — git cat-file -e провалился"
    continue
  fi

  # Для 005-007 хеш должен совпасть с таблицей контракта. Для 001-004 таблица
  # хеша не даёт, и эта ветка не исполняется.
  if [ -n "${TABLE_HASH[$num_padded]:-}" ]; then
    if [ "$base_hash" != "${TABLE_HASH[$num_padded]}" ]; then
      bad "$rel: основание «$base_hash» не совпадает с хешем таблицы контракта «${TABLE_HASH[$num_padded]}» — арбитраж 4 требует строкового совпадения"
    fi
  fi
done

# ── ПОЛНОТА СОСТАВА ─────────────────────────────────────────────────────────
# Семь записей 001-007 должны существовать.
for n in 1 2 3 4 5 6 7; do
  if [ -z "${FILE_FOR_NUMBER[$n]:-}" ]; then
    bad "нет записи $(printf '%03d' "$n") в decisions/ — реестр неполон"
  fi
done
printf '\nзаписей: %d · нарушений: %d\n' "${#DECISION_FILES[@]}" "$violations" >&2
[ "$violations" -eq 0 ] || exit 1
ok "реестр решений полон, поля в грамматике, основания разрешимы"
