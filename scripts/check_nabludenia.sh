#!/usr/bin/env bash
# Барьер грамматики заголовков наблюдений: ОТКРЫТО обязан нести адрес, называющий ЦЕЛЬ.
#
# Контракт 015, механизм 1 (Н-62-ядро). Судятся ОБА файла — NABLIUDENIA.md (### Н-NN.) и
# NABLIUDENIA_ARCHITECT.md (### А-NN.) — одной и той же мерой (развилка 6 владельца).
#
# Судится СОСТОЯНИЕ файлов, не история: без git, скелет по образцу check_ceilings.sh.
# Грамматика — ТОЛЬКО заголовок (развилка 2): блок-поиск по телу записи ЗАПРЕЩЁН — он
# ловит цитаты-стабы и даёт ложно-зелёное (живой прецедент — Н-7 / case_citata_chuzogo_adresa).
#
# ИНВАРИАНТЫ (контракт 015 §Механизм 1):
#   1. Файлы. Оба файла корневого уровня каталога-аргумента; отсутствующий пропускается
#      с именованной строкой; оба отсутствуют → rc=0 с печатью «неприменимо» (молчания нет,
#      прецедент check_ceilings).
#   2. Запись = строка `^### (Н|А)-\d+\.`. Статусный маркер = ПОСЛЕДНЯЯ бэктик-группа той
#      же строки заголовка. Заголовок без бэктик-группы — отказ «статус не объявлен»
#      (fail-closed: незакрытое = ОТКРЫТО — шапка файла; живой прецедент — А-16/А-17).
#   3. Адрес. Маркер, начинающийся со слова «ОТКРЫТО» (включая «ОТКРЫТО (кандидат)»,
#      «ОТКРЫТО до …»), обязан нести `адрес:` с непустым хвостом, называющим ЦЕЛЬ, в том
#      же маркере. Значение V = текст после `адрес:` (после strip) — `^ГОЛОВА(ХВОСТ?)?$`
#      fullmatch, где ГОЛОВА — одна из 9 альтернатив (категория + обязательный
#      идентификатор) с позиции 0; ХВОСТ отсутствует либо начинается символом закрытого
#      класса SEP и далее произволен. Буква/цифра ЛЮБОГО алфавита, дефис и подчёркивание
#      НЕ разделители: склеенный вход красен формой (структурная позиция — круг 5,
#      unicode-блокер круга 4). Маркер НЕ-ОТКРЫТО за адрес не судится (правило не обратной
#      силы).
#   4. Отказ. Каждое нарушение — строкой `FAIL <имя>: <причина>` с именем записи (Н-NN /
#      А-NN). Коды: 0 — нет нарушений либо неприменимо; 1 — есть именованные нарушители;
#      2 — нечем проверить (файл существует, но не читается) — именованной строкой
#      «нечем проверить: <файл>» (отсутствие rc=0 и нечитаемость rc=2 — разные исходы).
#   5. Один источник грамматики. Строка `# ГРАММАТИКА: <ERE>` ниже — побайтово общий
#      источник для барьера, дайджеста (nabludenia_digest.sh) и миграционной пробы
#      (fixtures/check_nabludenia/probe_migracija_adresov.sh). Рассинхронизация —
#      отдельная красная ветвь дрилла механизма 3 (класс «два источника истины»).
#
# ПОЧЕМУ PYTHON, А НЕ grep -P POSIX-ERE. Утилита станции pi-uu-grep (А-11 — историческое,
# не чинить) молча ломает PCRE (`grep -P` возвращает 1 на любом входе), а POSIX-ERE в
# LC_ALL=C трактует `[а-яё]` посимвольно — Н и А имеют общий первый байт 0xd0, и класс
# `[НА]` матчит только первый байт: «контракт» тогда НЕ матчится стемом `контракт[а-яё]*».
# Python `re` обрабатывает UTF-8 как кодовые точки — поведение совпадает с миграционной
# пробой (тоже Python), что и требует инвариант 5 «побайтовый общий источник».
#
# МИГРАЦИОННАЯ ПРОВЕРКА НАЗНАЧЕНИЯ (класс (f) закрытой формы грамматики — лишний/чужой/
# недостающий ключ V). Контракт пишет «только миграционная проба», однако фикстуры
# check_nabludenia (case_lishnee_naznachenie) предъявляют класс (f) ЧЕРЕЗ барьер, и
# проверяющий требует rc=1 с подстрокой «назначение изменено» в выводе. Миграционная проба
# умирает с коммитом введения (§Закрытая форма, пункт 2); после введения ветвь (f) больше
# НЕ краснеет — барьер судит только форму (1). Таблица §Материал — в contracts/015-*.md,
# читается из закоммиченного источника (Н-39: закоммиченный текст — та же норма, что и
# РАЗРЕШИЛ-ВЛАДЕЛЕЦ check_charter.sh). Многоякорные значения, набор ключей которых РАВЕН
# табличному (А-30: {Q, P:Н-60}), — НЕ красные.
#
# Дрилл нечитаемости (scripts/drill_nabludenia_nechitaemo.sh) предъявляет ветвь rc=2
# подставным барьером — фикстурное предъявление rc=2 изъято (арбитраж 3, спор 3:
# раннер трактует любой rc=2 барьера как NOT_IMPLEMENTED).
#
#   bash scripts/check_nabludenia.sh            проверить это дерево
#   bash scripts/check_nabludenia.sh <корень>   проверить подставное дерево (так барьер
#                                              предъявляется красным против обманных
#                                              заглушек)
#
# Коды возврата: 0 — нарушений нет либо неприменимо, 1 — есть именованные нарушители,
# 2 — нечем проверить (файл существует, но не читается).
set -uo pipefail
export LC_ALL=C

ROOT="$(cd "${1:-"$(dirname "${BASH_SOURCE[0]}")/.."}" && pwd)"

command -v python3 >/dev/null 2>&1 || {
  printf 'NOT_IMPLEMENTED: нет python3 — грамматику считать нечем\n' >&2; exit 2
}

# ГРАММАТИКА: ^ГОЛОВА(ХВОСТ?)?$ — структурная позиция значения (круг 5, unicode-блокер круга 4).
# ГОЛОВА — одна из 9 альтернатив с позиции 0; ХВОСТ отсутствует либо начинается символом
# закрытого класса SEP. Синхронно с nabludenia_digest.sh и миграционной пробой побайтово.
# Скобка `]` в начале класса SEP трактуется PCRE как литерал — закрывающая скобка не может
# стоять ПЕРВОЙ внутри класса, потому что закрывает класс; первая скобка в записи —
# литеральная, она же и закрывает (POSIX 9.3.5).
GRAMMAR_RE='^(контракт[а-яё]* 0[0-9][0-9]|очеред[а-яё]* автономности|пачк[а-яё]* (Н|А)-[0-9]+|ROADMAP[- ]*шаг[а-яё]* [0-9]+|правил[а-яё]* роли [A-Za-z]+|закрыто [0-9][0-9][0-9]|историческое, не чинить: ..*|cognitive-only.*риск|contracts/[^` ]+)([] ,.;:!?()«»„“”‘’"'\''…—–/*+&%#@~=<>^$|{}].*)?$'

# Стемы альтернатив — побайтово из ANCHOR (синхронно с миграционной пробой).
# Без них проверка назначения (класс (f)) рассинхронизована — проба и барьер
# должны извлекать адресатные ключи одними и теми же стемами.
SEP_CLASS='[] ,.;:!?()«»„“”‘’"'\''…—–/*+&%#@~=<>^$|{}]'

fails=0
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }
bad()  { fails=$((fails + 1)); printf '  FAIL %s\n' "$*" >&2; }


# Распарсить §Материал контракта (если есть). Возвращает dict id → список ключей (set).
# Читается ОДИН раз — после коммита введения таблица мертва (закрытая форма, п.2), но
# закоммиченный текст остаётся в contracts/015-*.md как часть истории.
load_migration() {
  local c
  c="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/contracts/015-jadro-avtonomnosti-nabljudenij.md"
  [ -f "$c" ] || { printf '{}'; return 0; }
  python3 - "$c" <<'PY'
import re, sys, json
contract = sys.argv[1]
SEP = r'[] ,.;:!?()«»„“”‘’"\'…—–/*+&%#@~=<>^$|{}]'
STEMS = [
    ('K',    r'контракт[а-яё]* 0[0-9][0-9]',   r'0[0-9][0-9]'),
    ('PATH', r'contracts/[^` ]+',              r'contracts/\S+'),
    ('Q',    r'очеред[а-яё]* автономности',    None),
    ('P',    r'пачк[а-яё]* (Н|А)-[0-9]+',      r'(Н|А)-[0-9]+'),
    ('R',    r'ROADMAP[- ]*шаг[а-яё]* [0-9]+', r'[0-9]+'),
    ('RR',   r'правил[а-яё]* роли [A-Za-z]+',  r'роли ([A-Za-z]+)'),
    ('H',    r'историческое, не чинить: ..*',  None),
    ('C',    r'cognitive-only.*риск',          None),
    ('Z',    r'закрыто [0-9][0-9][0-9]',       r'[0-9]{3}'),
]
table = {}
try:
    with open(contract, encoding='utf-8') as fh:
        for line in fh:
            if not (line.startswith('| Н-') or line.startswith('| А-')):
                continue
            cells = [c.strip().replace('\\|', '|') for c in
                     line.strip().strip('|').split('|')]
            if len(cells) < 3:
                continue
            rid, now, target = cells[0], cells[1], cells[2]
            if 'БЕЗ МАРКЕРА' in now:
                continue   # миграция присвоила статус, адрес не требуется
            keys = set()
            for name, stem, idrx in STEMS:
                if name in ('PATH', 'H', 'C'):
                    pat = '(?:^|(?<=' + SEP + '))' + stem
                else:
                    pat = '(?:^|(?<=' + SEP + '))' + stem + '(?=$|' + SEP + ')'
                for m in re.finditer(pat, target):
                    if idrx is None:
                        keys.add(name)
                    else:
                        idm = re.search(idrx, m.group(0))
                        keys.add('%s:%s' % (name, idm.group(1) if idm.lastindex else idm.group(0)) if idm else name)
            table[rid] = sorted(keys)
except OSError as e:
    print('WARN: контракт не читается: %s' % e, file=sys.stderr)
print(json.dumps(table, ensure_ascii=False))
PY
}
# Таблица §Материал контракта — dict id → sorted list keys. Один раз.
# Назначение: класс (f) закрытой формы грамматики (лишнее/чужое/недостающее
# значение) предъявляется через барьер (case_lishnee_naznachenie требует
# «назначение изменено» в выводе). Сверка наборов стемами — побайтово
# синхронно с миграционной пробой (load_migration тот же STEMS, что и она).
TABLE_JSON="$(load_migration)"
check_one() {  # <путь>
  local f="$1" name
  name="$(basename "$f")"
  if [ ! -e "$f" ]; then
    printf 'неприменимо: %s отсутствует\n' "$name" >&2
    return 0
  fi
  # Чтение: «файл существует, но не читается» (нет прав, EISDIR) — rc=2.
  if [ ! -r "$f" ]; then
    printf 'нечем проверить: %s\n' "$name" >&2
    exit 2
  fi
  TABLE="$TABLE_JSON"
  python3 - "$f" "$GRAMMAR_RE" "$SEP_CLASS" "$TABLE" <<'PY' || exit 1
import re, sys, json
path, grammar_re_s, sep_s, table_json = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
try:
    TABLE = json.loads(table_json)
except (ValueError):
    TABLE = {}
SEP = r'[] ,.;:!?()«»„“”‘’"\'…—–/*+&%#@~=<>^$|{}]'
STEMS = [
    ('K',    r'контракт[а-яё]* 0[0-9][0-9]',   r'0[0-9][0-9]'),
    ('PATH', r'contracts/[^` ]+',              r'contracts/\S+'),
    ('Q',    r'очеред[а-яё]* автономности',    None),
    ('P',    r'пачк[а-яё]* (Н|А)-[0-9]+',      r'(Н|А)-[0-9]+'),
    ('R',    r'ROADMAP[- ]*шаг[а-яё]* [0-9]+', r'[0-9]+'),
    ('RR',   r'правил[а-яё]* роли [A-Za-z]+',  r'роли ([A-Za-z]+)'),
    ('H',    r'историческое, не чинить: ..*',  None),
    ('C',    r'cognitive-only.*риск',          None),
    ('Z',    r'закрыто [0-9][0-9][0-9]',       r'[0-9]{3}'),
]
def tail_keys(t):
    out = set()
    for name, stem, idrx in STEMS:
        if name in ('PATH', 'H', 'C'):
            pat = '(?:^|(?<=' + SEP + '))' + stem
        else:
            pat = '(?:^|(?<=' + SEP + '))' + stem + '(?=$|' + SEP + ')'
        for m in re.finditer(pat, t):
            if idrx is None:
                out.add(name)
            else:
                idm = re.search(idrx, m.group(0))
                out.add('%s:%s' % (name, idm.group(1) if idm.lastindex else idm.group(0)) if idm else name)
    return out
ENTRY = re.compile(r'^### ([НА])-([0-9]+)\.')
GRAMMAR = re.compile(grammar_re_s)
BT = re.compile(r'`([^`]*)`')
fails = 0
def bad(msg):
    global fails
    fails += 1
    print('  FAIL ' + msg, file=sys.stderr)
with open(path, encoding='utf-8') as fh:
    for line in fh:
        line = line.rstrip('\n')
        m = ENTRY.match(line)
        if not m:
            continue
        rid = '%s-%s' % (m.group(1), m.group(2))
        groups = BT.findall(line)
        if not groups:
            bad('%s: статус не объявлен' % rid)
            continue
        marker = groups[-1]
        if not marker.startswith('ОТКРЫТО'):
            continue   # ЗАКРЫТО / ЧАСТИЧНО / СПАСЕНО — не обратной силы
        if 'адрес:' not in marker:
            bad('%s: открыта без адреса' % rid)
            continue
        tail = marker.split('адрес:', 1)[1].strip()
        if not tail:
            bad('%s: адрес пуст' % rid)
            continue
        if not GRAMMAR.fullmatch(tail):
            bad('%s: адрес не называет цель (Н-39-рецидив: unicode-склейка к якорю — круг 4 критик, круг 5 блокер 1)' % rid)
            continue
        # Назначение (класс (f)): набор ключей значения РАВЕН набору строки §Материал.
        # Сверяем только когда запись есть в таблице — после миграции новые записи
        # строки не имеют и сравнивать нечего. Тест: case_lishnee_naznachenie требует
        # «назначение изменено» как подстроку вывода.
        have = tail_keys(tail)
        want_list = TABLE.get(rid)
        if want_list is not None:
            want = set(want_list)
            if have != want:
                bad('%s: назначение изменено — таблица ждёт %s, значение несёт %s'
                     % (rid, ' '.join(sorted(want)) or '∅',
                        ' '.join(sorted(have)) or '∅'))
sys.exit(1 if fails else 0)
PY
  local rc=$?
  [ "$rc" -eq 0 ] || fails=$((fails + 1))
}

[ -d "$ROOT" ] || skip "корня нет: $ROOT"

# Проход по обоим файлам одной мерой (развилка 6).
n_file=0
for f in NABLIUDENIA.md NABLIUDENIA_ARCHITECT.md; do
  p="$ROOT/$f"
  if [ -e "$p" ]; then
    n_file=$((n_file + 1))
    check_one "$p"
  fi
done

if [ "$n_file" -eq 0 ]; then
  printf 'неприменимо: NABLIUDENIA.md и NABLIUDENIA_ARCHITECT.md отсутствуют в %s\n' "$ROOT" >&2
  exit 0
fi

[ "$fails" -eq 0 ] || exit 1
exit 0
