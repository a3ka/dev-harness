#!/usr/bin/env bash
# Барьер: режим входа держится ПОЛИТИКОЙ подтверждений, и лаунчер её не затирает.
#
# Заведено по находке 3 круга адверсария по майлстоуну 002: контракт 002 обещал
# критерием 1 «правку без подтверждения не проходит (фикстура)», а в дереве лежала
# только статика — строка `tools.approvalMode: always-ask` в `.omp/config.yml`.
# Конфигурация может лежать в файле, которого живой запуск не читает, и тогда
# обещание режима держится ничем: удалить политику из запуска или увести запуск из
# каталога с конфигом было НЕЧЕМ поймать.
#
# ЧТО ИМЕННО ПРОВЕРЯЕТСЯ — три утверждения, каждое своим отказом:
#
#   1. СТАТИКА. `.omp/config.yml` проверяемого дерева несёт `tools.approvalMode:
#      always-ask` — именно внутри отображения `tools:`, а не любой строкой файла:
#      значение в чужом блоке omp не читает.
#
#   2. НАСЛЕДОВАНИЕ. Запуск лаунчера ПОДСТАВНЫМ `omp` (захват argv, окружения и
#      рабочего каталога) обязан показать, что omp поднимается ИЗ каталога, где
#      лежит тот самый конфиг с `always-ask`, и что в argv нет флага, отменяющего
#      политику. Запуск из чужого каталога равносилен запуску без политики: конфиг
#      проекта — файл, который omp читает от своего рабочего каталога.
#
#   3. ФЛАГ НЕ ПРОХОДИТ. `--approval-mode` (и родня: `--approvals`, `--yolo`,
#      `--dangerously-skip-permissions`) у лаунчера — красная ветвь: лаунчер обязан
#      ОТКАЗАТЬ, а не передать флаг в omp. Иначе режим снимается одним словом в
#      командной строке, и все обещания критерия 1 снимаются вместе с ним.
#
# ПОЧЕМУ ПОДСТАВНОЙ omp, А НЕ ЖИВОЙ ДИАЛОГ. Перехват живой сессии не строится —
# это записано в контракте 002 как `cognitive-only`. Предмет ЭТОГО барьера уже, и
# он механизируется целиком: чем поднят omp и в каком каталоге. Что делает сам omp,
# получив always-ask, — его собственный, проверенный вовне предмет.
#
# ГЕРМЕТИЧНОСТЬ. Подставной `omp` кладётся в свой каталог и подставляется ТОЛЬКО
# через PATH; переменные учёта задаются здесь явными пустышками, потому что лаунчер
# законно отказывает без них и отказ по учёту заслонил бы предмет. Черновик — в
# `tmp/check_approval/` проверяемого дерева (норма: временное в ./tmp).
#
#   bash scripts/check_approval.sh            проверить это дерево
#   bash scripts/check_approval.sh <корень>   проверить подставное (так предъявляется
#                                              красным)
#
# Коды возврата: 0 — политика в конфиге, запуск её наследует и флаг отвергнут,
# 1 — нарушение с названным местом, 2 — нечем проверить.
set -euo pipefail

ROOT="$(cd "${1:-"$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"}" && pwd)"

violations=0
ok()   { printf '  ok   %s\n' "$*" >&2; }
bad()  { violations=$((violations + 1)); printf '  FAIL %s\n' "$*" >&2; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

CONFIG="$ROOT/.omp/config.yml"
LAUNCHER="$ROOT/workshop"
[ -f "$CONFIG" ]   || skip "нет $CONFIG — политику подтверждений читать нечем"
[ -f "$LAUNCHER" ] || skip "нет $LAUNCHER — запуск проверять нечем"
command -v node >/dev/null 2>&1 || skip "нет node — лаунчер порождает промпт роли им"
command -v bash >/dev/null 2>&1 || skip "нет bash — лаунчер не запустить"

# ── 1. Статика: политика объявлена внутри отображения `tools:` ────────────────
# Разбор узкий и объявленный: `tools:` в первой колонке, затем строки с отступом до
# следующего ключа верхнего уровня. Строка `approvalMode` вне этого блока политикой
# не является, и барьер не имеет права принимать её за политику.
policy_of() {
  awk '
    /^tools:[[:space:]]*$/ { inside = 1; next }
    /^[^[:space:]#]/       { inside = 0 }
    inside && match($0, /^[[:space:]]+approvalMode:[[:space:]]*([^[:space:]#]+)/, m) {
      print m[1]; exit
    }
  ' "$1"
}
POLICY="$(policy_of "$CONFIG")"
if [ "$POLICY" != "always-ask" ]; then
  bad ".omp/config.yml: tools.approvalMode = «${POLICY:-не объявлено}», а режим входа держится значением «always-ask» (контракт 002, критерий 1)"
fi

# ── 2 и 3. Поведение лаунчера под подставным omp ──────────────────────────────
WORKDIR="$ROOT/tmp/check_approval/run-$$"
rm -rf "$WORKDIR"
mkdir -p "$WORKDIR/bin"
trap 'rm -rf "$WORKDIR"' EXIT

CAPTURE="$WORKDIR/capture"
cat > "$WORKDIR/bin/omp" <<'STUB'
#!/usr/bin/env bash
# Подставной omp: НИЧЕГО не делает, только записывает, чем и откуда его позвали.
{
  printf 'PWD\t%s\n' "$PWD"
  for a in "$@"; do printf 'ARG\t%s\n' "$a"; done
} >> "$CHECK_APPROVAL_CAPTURE"
exit 0
STUB
chmod +x "$WORKDIR/bin/omp"

# Флаги, снимающие политику. Список разделён на два: REJECTED всегда отвергаются
# лаунчером, YOLO — единственное имя клапана владельца, и его ветка проверяется
# отдельно в разделе 4. Списки объявлены ЗДЕСЬ и не читаются из лаунчера: проверка,
# берущая ожидание из проверяемого, есть отчёт о проверяемом.
REJECTED_FLAGS=(--approval-mode --approvals --dangerously-skip-permissions)

run_launcher() {  # <файл захвата> <аргументы лаунчера...>
  local cap="$1"; shift
  : > "$cap"
  # ЗАПУСК ИЗ НЕЙТРАЛЬНОГО КАТАЛОГА. Рабочий каталог проверяющего может сам нести
  # `.omp/config.yml` (так и есть, когда барьер зовут из корня дерева), и тогда «omp
  # поднят там, где лежит конфиг» выполнялось бы САМО — измерение показывало бы
  # каталог вызова, а не работу лаунчера. Черновик барьера конфига не несёт.
  ( cd "$WORKDIR" && env -i \
      PATH="$WORKDIR/bin:/usr/bin:/bin:/usr/local/bin" \
      HOME="${HOME:-$WORKDIR}" \
      LC_ALL="${LC_ALL:-C.UTF-8}" \
      TMPDIR="$WORKDIR" \
      CHECK_APPROVAL_CAPTURE="$cap" \
      METERING_PROXY_URL="http://check-approval.invalid" \
      METERING_PROXY_TOKEN="проверка" \
      MINIMAX_API_KEY="проверка" \
      bash "$LAUNCHER" "$@" >"$cap.out" 2>"$cap.err" )
}

# ── 2. Наследование: omp поднят из каталога с конфигом и без флагов политики ──
rc=0
run_launcher "$CAPTURE" || rc=$?
if [ "$rc" -ne 0 ]; then
  bad "штатный запуск лаунчера вернул $rc — политику наследовать нечему; вывод: $(tr '\n' ' ' < "$CAPTURE.err" | cut -c1-300)"
elif [ ! -s "$CAPTURE" ]; then
  bad "лаунчер не позвал omp — наследование политики предъявить нечем (захват пуст)"
else
  launch_pwd="$(awk -F'\t' '$1 == "PWD" { print $2; exit }' "$CAPTURE")"
  launch_cfg="$launch_pwd/.omp/config.yml"
  if [ ! -f "$launch_cfg" ]; then
    bad "omp поднят из «$launch_pwd», где нет .omp/config.yml — запуск не наследует конфиг проекта, и политика в файле остаётся необязательной"
  elif [ "$(policy_of "$launch_cfg")" != "always-ask" ]; then
    bad "omp поднят из «$launch_pwd», и конфиг этого каталога не несёт tools.approvalMode: always-ask — запуск наследует ДРУГУЮ политику"
  fi
  for flag in "${REJECTED_FLAGS[@]}"; do
    if awk -F'\t' -v f="$flag" '$1 == "ARG" && ($2 == f || index($2, f "=") == 1) { found = 1 }
                                END { exit(found ? 0 : 1) }' "$CAPTURE"; then
      bad "лаунчер сам передал omp «$flag» — политика подтверждений снята запуском, а не конфигом"
    fi
  done
  # Клапан владельца `--yolo` на штатном запуске не задействован, и его argv НЕ ДОЛЖЕН
  # дойти до omp в исходной форме: лаунчер обязан ТРАНСЛИРОВАТЬ его в
  # `--approval-mode yolo` либо НЕ ПРИНИМАТЬ. Здесь `--yolo` при штатном запуске
  # вообще не появляется, и проверка служит зеркалом раздела 4: лаунчер не пропускает
  # `--yolo` мимо своего перехватчика.
  if awk -F'\t' -v f="--yolo" '$1 == "ARG" && ($2 == f || index($2, f "=") == 1) { found = 1 }
                              END { exit(found ? 0 : 1) }' "$CAPTURE"; then
    bad "лаунчер передал omp «--yolo» в исходной форме — клапан обязан быть трансляцией в --approval-mode yolo, а не пробросом"
  fi
fi

# ── 3. Флаг политики от вызывающего обязан быть ОТВЕРГНУТ ────────────────────
# Перебираются РОВНО REJECTED_FLAGS: `--yolo` — клапан владельца, его ветка
# проверяется отдельно в разделе 4, и его присутствие здесь сломало бы
# проверку (раздел 4 ожидает rc=0 и проброс, раздел 3 — rc=1 и отказ).
for flag in "${REJECTED_FLAGS[@]}"; do
  cap="$WORKDIR/capture-${flag#--}"
  frc=0
  run_launcher "$cap" "$flag" never || frc=$?
  if [ "$frc" -eq 0 ]; then
    bad "лаунчер принял «$flag never» кодом 0 — флаг, затирающий политику, обязан быть отказом"
  fi
  if awk -F'\t' -v f="$flag" '$1 == "ARG" && ($2 == f || index($2, f "=") == 1) { found = 1 }
                              END { exit(found ? 0 : 1) }' "$cap"; then
    bad "лаунчер передал «$flag» в omp — режим снимается одним словом командной строки"
  fi
done

# ── 4. Клапан владельца: --yolo форвардит --approval-mode yolo и баннер говорит ─
# Контракт 002 v5, критерий 1: единственный сниматель always-ask, и барьер обязан
# предъявить, что это работает. Три проверки, и провал любой — отказ:
#   - лаунчер НЕ отвергает `--yolo` (rc=0);
#   - omp получил `--approval-mode` и следующим аргументом `yolo` (трансляция,
#     не проброс);
#   - баннер несёт дословно «слово владельца» — без этого зелёная ветвь была бы
#     заявлена, а не предъявлена (правило 3).
yolo_cap="$WORKDIR/capture-yolo-valve"
yolo_err="$yolo_cap.err"
yrc=0
run_launcher "$yolo_cap" --yolo || yrc=$?
if [ "$yrc" -ne 0 ]; then
  bad "лаунчер отверг «--yolo» (код $yrc) — клапан владельца обязан быть принят (контракт 002 v5, критерий 1)"
else
  if ! awk -F'\t' 'BEGIN{ f = 1 }
      $1 == "ARG" && $2 == "--approval-mode" { saw_flag = NR; next }
      saw_flag && $1 == "ARG" && NR == saw_flag + 1 && $2 == "yolo" { f = 0; exit }
      END { exit f }
    ' "$yolo_cap"; then
    bad "лаунчер принял --yolo, но НЕ передал omp «--approval-mode yolo» — клапан не транслирует флаг"
  fi
  if [ ! -s "$yolo_err" ] || ! grep -q 'слово владельца' "$yolo_err"; then
    bad "лаунчер принял --yolo, но баннер не сказал «слово владельца» — клапан сработал без объявления (контракт 002 v5, критерий 1)"
  fi
fi

printf '\nполитика: %s · нарушений: %d\n' "${POLICY:-не объявлено}" "$violations" >&2
[ "$violations" -eq 0 ] || exit 1
ok "always-ask объявлен в конфиге, запуск его наследует, флаги отмены политики отвергнуты"
