#!/usr/bin/env bash
# Барьер не готов, пока не предъявлен КРАСНЫМ против обманной заглушки.
#
# Заведено потому, что до этого механизма «фикстуры есть» было утверждением сессии, а не
# репозитория: в HANDOFF.md записано «шесть фикстур» для `overlay.sh`, и в дереве не лежит
# ни одной. Утверждение переживает сессию только закоммиченным артефактом, а зелёный,
# которого никто не видел красным, не доказывает ничего — он одинаково зелен и у барьера,
# который проверяет, и у барьера, который печатает `ok` и выходит.
#
# ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. Не наличие файла рядом с барьером: файл `exit 1` удовлетворил бы
# такую проверку, и она стала бы плацебо о плацебо. Проверяется исполнением: фикстура
# приводит дерево в обманное состояние, ВЫЗЫВАЕТ барьер, и барьер обязан сам вернуть не ноль
# и сам назвать причину. Код возврата и вывод пишет ОБЁРТКА, а не фикстура: фикстура,
# которой доверили вынести вердикт о себе, напечатала бы любой.
#
# ОБЛАСТЬ ВЫВЕДЕНА ИЗ ПРЕДМЕТА, А НЕ ЗАДАНА ПРЕФИКСОМ. План 005 §1 писал «каждый
# `scripts/verify_*.sh` и `scripts/drill_*.sh`» — и этот список молча упускает
# `scripts/check_ids.sh` и `scripts/check_protected.sh` из §2 и §4 ТОГО ЖЕ плана, а также
# `overlay.sh`, `models_actual.sh` и `gen-harness.ts`, которые уже стоят гейтами. Поэтому
# область — ВСЁ содержимое `scripts/`, а роль каждого файла объявляет он сам своей шапкой:
#
#   `Коды возврата:`      — барьер: его вердикт есть код возврата, значит нужна фикстура;
#   `НЕ БАРЬЕР: <почему>` — вне области явно и с записанной причиной.
#
# Неклассифицированный файл — отказ. Новый файл в `scripts/` не может стать невидимым:
# чтобы выйти из области, надо это НАПИСАТЬ.
#
# ЧЕГО ЭТОТ БАРЬЕР НЕ ДЕЛАЕТ. Он не требует, чтобы барьер был зелёным на текущем дереве:
# зелень каждого барьера — предмет приёмки и CI, а не этого механизма. Здесь проверяется
# ровно одно: предъявлено ли красное.
#
# Соглашение о фикстуре — `fixtures/<имя барьера без расширения>/case_*.sh`:
#   `# ПРИЧИНА: <подстрока>`  обязательная шапка: что барьер должен назвать. Красное без
#                            названной причины не отличить от красного по случайной поломке;
#   $BARRIER                 ЧЕМ вызывать барьер (обёртка). Вызов другим путём не считается;
#   $WORK                    пустой каталог фикстуры. Дерево репозитория трогать нельзя;
#   $REPO                    корень, откуда можно копировать;
#   BARRIER_ROOT=$WORK       если барьер привязан к своему каталогу — обёртка положит туда
#                            побайтовую копию барьера и запустит её.
#
#   bash scripts/verify_antiplacebo.sh            проверить это дерево
#   bash scripts/verify_antiplacebo.sh <корень>   проверить подставное дерево (так этот
#                                                 барьер предъявляется красным сам)
#
# Коды возврата: 0 — у каждого барьера красное предъявлено, 1 — нет, 2 — нечем проверить.
set -euo pipefail

ROOT="$(cd "${1:-"$(dirname "${BASH_SOURCE[0]}")/.."}" && pwd)"
SCRIPTS="$ROOT/scripts"
FIXTURES="$ROOT/fixtures"

fails=0
ok()   { printf '  ok   %s\n' "$*" >&2; }
bad()  { fails=$((fails + 1)); printf '  FAIL %s\n' "$*" >&2; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

# Маркер опознаётся ЯКОРЕМ строки, а не вхождением подстроки: первая редакция искала
# подстроку и первым же прогоном объявила сам этот файл «и барьером, и не барьером» —
# оба маркера названы выше, в описании соглашения. Мера, ловящая свою же документацию,
# врёт о предмете. Перед маркером допустимы только рамка комментария и пробелы, поэтому
# упоминание в тексте (в кавычках, в скобках) объявлением не считается.
classify() {
  awk 'NR<=60 {
         if      ($0 ~ /^[[:space:]#*\/]*Коды возврата:/) b = 1
         else if ($0 ~ /^[[:space:]#*\/]*НЕ БАРЬЕР:/)     p = 1
       }
       END { print (b ? "b" : "") (p ? "p" : "") }' "$1"
}

# ── 1. Область: каждый файл в scripts/ объявляет свою роль сам ────────────────
barriers=()
for f in "$SCRIPTS"/*; do
  [ -f "$f" ] || continue
  name="$(basename "$f")"
  case "$(classify "$f")" in
    b)  barriers+=("$f") ;;
    p)  ;;
    bp) bad "$name: объявлен и барьером, и не барьером — роль файла обязана быть одна" ;;
    *)  bad "$name: не классифицирован — объявите в шапке 'Коды возврата:' либо 'НЕ БАРЬЕР: <почему>'" ;;
  esac
done

[ "${#barriers[@]}" -gt 0 ] || skip "в $SCRIPTS нет ни одного барьера — предъявлять нечего"

key_of() { local n; n="$(basename "$1")"; printf '%s' "${n%.*}"; }

# ── 2. Сверка в обе стороны: фикстура без барьера — тоже расхождение ───────────
if [ -d "$FIXTURES" ]; then
  for d in "$FIXTURES"/*; do
    [ -d "$d" ] || continue
    k="$(basename "$d")"
    found=0
    # `test && found=1` последней итерацией вернул бы не ноль и убил бы скрипт под `set -e`
    # молча — отказ без названной причины.
    for b in "${barriers[@]}"; do
      if [ "$(key_of "$b")" = "$k" ]; then found=1; fi
    done
    [ "$found" -eq 1 ] || bad "fixtures/$k: фикстура без барьера — она ничего не держит"
  done
fi

# ── 3. Прогон фикстур ─────────────────────────────────────────────────────────
# Временное — в ./tmp дерева, которое проверяется, а не в системном /tmp.
RUN="$ROOT/tmp/antiplacebo/run-$$"
mkdir -p "$RUN"
# ТЕЛО обёртки. Пути к барьеру и к учёту вызовов НЕ передаются фикстуре переменными
# окружения, а вшиваются в её собственную обёртку: прежняя редакция экспортировала
# `AP_INV`, и фикстура могла сама создать каталог вызова с нужным кодом и нужным текстом —
# то есть подделать учёт, ничего не вызвав. Учёт обязан быть недоступен тому, о ком он
# ведётся.
#
# ОСТАТОЧНЫЙ РИСК, помечен `cognitive-only`: обёртка — читаемый файл, и фикстура может
# вычитать пути из неё. Механизмом это не закрывается на общей файловой системе; закрывается
# тем, что фикстура — закоммиченный код, который читают адверсарий и ревьюер, а строка,
# разбирающая обёртку, в нём видна сразу. Ниже стоит и дешёвая проверка на прямое
# упоминание внутренних имён.
BODY="$RUN/wrapper.body"
cat > "$BODY" <<'WRAP'
# Код возврата и вывод САМОГО БАРЬЕРА пишутся в $AP_INV. Вердикт «красное предъявлено»
# выносит проверяющий: фикстура, которой это доверили, напечатала бы любой — тот самый
# дефект, против которого написан весь механизм.
set -uo pipefail
inv="$(mktemp -d "$AP_INV/inv.XXXXXX")"
real="$AP_REAL"
# Барьер, привязанный к своему каталогу, нельзя направить на подставное дерево аргументом.
# Тогда фикстура объявляет BARRIER_ROOT, и здесь кладётся ПОБАЙТОВАЯ копия барьера: предмет
# тот же, корень другой.
if [ -n "${BARRIER_ROOT:-}" ]; then
  mkdir -p "$BARRIER_ROOT/scripts"
  cp "$real" "$BARRIER_ROOT/scripts/$(basename "$real")"
  real="$BARRIER_ROOT/scripts/$(basename "$real")"
fi
case "$real" in
  *.ts) cmd=(node "$real") ;;
  *)    if [ -x "$real" ]; then cmd=("$real"); else cmd=(bash "$real"); fi ;;
esac
"${cmd[@]}" "$@" >"$inv/out" 2>&1
rc=$?
printf '%s' "$rc" > "$inv/rc"
cat "$inv/out"
exit "$rc"
WRAP

# Слепок дерева ДО прогона. Фикстура обязана жить в $WORK; фикстура, правящая репозиторий,
# оставляет за собой поломку, которую потом ищут неделю.
snapshot() {
  {
    cd "$ROOT"
    for p in scripts fixtures roles config .omp plans; do
      [ -e "$p" ] || continue
      find "$p" -type f -printf '%p %s %T@\n'
    done
    find . -maxdepth 1 -type f -printf '%p %s %T@\n'
  } | sort | sha256sum
}
before="$(snapshot)"

cases_total=0; reds=0; undecided=0
for b in "${barriers[@]}"; do
  key="$(key_of "$b")"
  dir="$FIXTURES/$key"
  mapfile -t cases < <(find "$dir" -maxdepth 1 -type f -name 'case_*.sh' 2>/dev/null | sort)
  if [ "${#cases[@]}" -eq 0 ]; then
    bad "$(basename "$b"): нет фикстур — ожидается fixtures/$key/case_*.sh"
    continue
  fi
  for c in "${cases[@]}"; do
    cases_total=$((cases_total + 1))
    cname="$key/$(basename "$c")"
    reason="$(awk 'NR<=40 && sub(/^# ПРИЧИНА:[[:space:]]*/, "") { print; exit }' "$c")"
    if [ -z "$reason" ]; then
      bad "$cname: не объявила причину — нужна шапка '# ПРИЧИНА: <подстрока вывода барьера>'"
      continue
    fi
    # Прямое упоминание внутренних имён учёта — попытка подделать вызов, а не проверить
    # барьер. Проверка дешёвая и ловит лоб-в-лоб; хитрый разбор обёртки остаётся за
    # адверсарием и ревьюером, и это записано в шапке остаточным риском.
    #
    # Область — ИСПОЛНЯЕМЫЕ строки, комментарии исключены. Первая редакция грепала файл
    # целиком и завалила фикстуру за то, что та ОБЪЯСНЯЛА, чего избегает. Это второй за
    # сессию случай меры, поймавшей свою же документацию: документация обязана иметь право
    # называть предмет. Конвейера здесь нет намеренно — `grep -v | grep -q` под `pipefail`
    # даёт не ноль на файле из одних комментариев, и запрет сработал бы на пустом месте.
    if awk '!/^[[:space:]]*#/ && /AP_INV|AP_REAL|wrapper\.body/ { f = 1 }
            END { exit(f ? 0 : 1) }' "$c"; then
      bad "$cname: упоминает внутренности учёта вызовов — учёт не принадлежит тому, о ком ведётся"
      continue
    fi
    d="$RUN/$key.$(basename "$c" .sh)"
    mkdir -p "$d/work" "$d/inv"
    # Обёртка своя на каждую фикстуру, пути вшиты: фикстура знает только $BARRIER.
    wrap="$d/barrier"
    { printf '#!/usr/bin/env bash\nAP_REAL=%q\nAP_INV=%q\n' "$b" "$d/inv"; cat "$BODY"; } > "$wrap"
    chmod +x "$wrap"
    set +e
    env -u BARRIER_ROOT -u AP_REAL -u AP_INV \
      BARRIER="$wrap" WORK="$d/work" REPO="$ROOT" \
      bash "$c" > "$d/case.out" 2>&1
    case_rc=$?
    set -e

    seen=0; red=0; green=0; nimpl=0
    for inv in "$d"/inv/inv.*; do
      [ -d "$inv" ] || continue
      seen=$((seen + 1))
      rc="$(cat "$inv/rc" 2>/dev/null || true)"
      if [ "$rc" = "0" ]; then green=$((green + 1)); continue; fi
      # Барьер, которому нечем проверять (нет omp, нет jq), отвечает 2 и NOT_IMPLEMENTED.
      # Считать это красным — ложь: «нечем проверить» не равно «проверено». Такая фикстура
      # не провал и не успех, и весь прогон обязан кончиться кодом 2, а не нулём.
      if [ "$rc" = "2" ] && grep -qF -e 'NOT_IMPLEMENTED' "$inv/out"; then nimpl=$((nimpl + 1)); fi
      if grep -qF -e "$reason" "$inv/out"; then red=1; fi
    done

    if [ "$seen" -eq 0 ]; then
      bad "$cname: не вызвала барьер через \$BARRIER (код фикстуры $case_rc) — вывод в $d/case.out"
    elif [ "$red" -eq 1 ]; then
      reds=$((reds + 1))
      ok "$cname: барьер красный, причина названа — «$reason»"
    elif [ "$nimpl" -gt 0 ]; then
      undecided=$((undecided + 1))
      printf '  ??   %s: барьеру нечем проверять (NOT_IMPLEMENTED) — красное не предъявлено, вывод в %s\n' \
        "$cname" "$d/inv" >&2
    elif [ "$green" -eq "$seen" ]; then
      bad "$cname: барьер остался зелёным на обманном дереве — красное не предъявлено"
    else
      bad "$cname: барьер упал, но не назвал объявленную причину «$reason» — вывод в $d/inv"
    fi
  done
done

after="$(snapshot)"
[ "$before" = "$after" ] || bad "фикстуры изменили дерево вне \$WORK — фикстура обязана быть без следа"

printf '\nбарьеров: %d · фикстур: %d · предъявлено красным: %d · нечем прогнать: %d\n' \
  "${#barriers[@]}" "$cases_total" "$reds" "$undecided" >&2
if [ "$fails" -gt 0 ]; then
  printf 'расхождений: %d · прогон оставлен в %s\n' "$fails" "$RUN" >&2
  exit 1
fi
if [ "$undecided" -gt 0 ]; then
  printf 'NOT_IMPLEMENTED: фикстур, которые не удалось прогнать: %d · прогон оставлен в %s\n' \
    "$undecided" "$RUN" >&2
  exit 2
fi
rm -rf "$RUN"
