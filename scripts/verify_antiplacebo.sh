# повторная канонизация через `cd $SCRATCH && pwd -P` внутри СОЗДАННОГО scratch —
# либо результат внутри ROOT (отказ), либо cd отказал (тоже отказ — симлинк-цепочка
# разорвана или скратч удалён между mkdir и cd). rm -rf безопасен: скратч — наш
# собственный, мы его только что создали (или не создали — тогда no-op). Отказ ДО
