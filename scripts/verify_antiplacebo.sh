    chmod +x "$wrap"

    # ── обслуживание заявок; учёт — в массивах проверяющего ──
    exec {reqfd}<>"$d/req"
    setsid env -u BARRIER_ROOT -u AP_REQ -u AP_RESP \
      BARRIER="$wrap" WORK="$d/work" REPO="$ROOT" \
      bash "$c" > "$d/case.out" 2>&1 &
    case_pid=$!

    inv_rc=(); inv_out=(); inv_argv=(); inv_cwd=(); inv_root=()
    serve() {
      local resp root cwd enc a argv=() out rc
      IFS=$'\x1f' read -r -t 0.2 resp root cwd enc <&"$reqfd" || return 1
      # `${a#x}` снимает маркер, которым клиент канала защищает ПУСТОЙ аргумент от схлопывания.
      for a in $enc; do argv+=("$(printf '%s' "${a#x}" | base64 -d)"); done
      set +e
      out="$( cd "$cwd" 2>/dev/null && ap_run "$b" "$root" "$d/env" "${argv[@]}" 2>&1 )"
      rc=$?
      set -e
      inv_rc+=("$rc"); inv_out+=("$out"); inv_cwd+=("$cwd"); inv_root+=("$root")
      inv_argv+=("$enc")
      # Журнал — ДЛЯ ЧЕЛОВЕКА, а не для вердикта: вердикт считается по массивам в памяти, а
      # без записи на диск отладка чужого прогона превращается в угадывание.
      { printf '=== вызов %d: код %s, каталог %s, корень «%s»\n' \
          "${#inv_rc[@]}" "$rc" "$cwd" "$root"
        printf '%s\n' "$out" | sed 's/^/    /'; } >> "$d/invocations.log"
      { printf '%s\n' "$rc"; printf '%s\n' "$out"; } > "$resp"
      return 0
    }
    while :; do
      serve && continue
      kill -0 "$case_pid" 2>/dev/null || break
    done
    serve || true
    set +e
    wait "$case_pid"; case_rc=$?
    set -e
    # Группа процессов фикстуры добивается ДО повтора: оставленный фоновый потомок правил бы
    # барьер во время повторного прогона и восстанавливал после.
    kill -- -"$case_pid" 2>/dev/null || true
    exec {reqfd}>&-

    seen="${#inv_rc[@]}"; green=0; degenerate=0; tool=0; alien=''; cand=-1
    for ((n = 0; n < seen; n++)); do
      rc="${inv_rc[$n]}"
      if [ "$rc" = "0" ]; then
        if [[ "${inv_out[$n]}" == *"$reason"* ]]; then degenerate=1; else green=1; fi
      elif [ "$rc" = "2" ]; then
        tool=1
      elif ! in_list "$rc" "$declared"; then
        alien="$rc"
      elif [ "$cand" -lt 0 ]; then
        cand=$n
      fi
    done

    if [ "$seen" -eq 0 ]; then
      bad "$cname: не вызвала барьер через \$BARRIER (код фикстуры $case_rc) — вывод в $d/case.out"
    elif [ "$degenerate" -eq 1 ]; then
      bad "$cname: причина «$reason» печатается и на ЗЕЛЁНОМ прогоне — она не называет ни отказ, ни предмет"
    elif [ "$tool" -eq 1 ]; then
      bad "$cname: барьер ответил «нечем проверить» (код 2) — фикстура обязана дать ему инструменты, иначе нарушение прячется под NOT_IMPLEMENTED"
    elif [ -n "$alien" ]; then
      bad "$cname: барьер вышел кодом $alien, которого не объявлял (объявлены: ${declared% }) — это неудача запуска, а не отказ по предмету"
    elif [ "$green" -eq 0 ]; then
      bad "$cname: нет положительного контроля — фикстура обязана предъявить барьер ЗЕЛЁНЫМ до порчи, иначе вечно-красный барьер неотличим от работающего"
    elif [ "$cand" -lt 0 ]; then
      bad "$cname: барьер остался зелёным на обманном дереве — красное не предъявлено"
    else
      # Красное засчитывает ПОВТОРНЫЙ прогон проверяющего: он повторяет ровно те условия,
      # которые сам же и запомнил, — argv, каталог, подставной корень, объявленное окружение.
      rargv=(); for a in ${inv_argv[$cand]}; do rargv+=("$(printf '%s' "${a#x}" | base64 -d)"); done
      set +e
      rout="$( cd "${inv_cwd[$cand]}" 2>/dev/null && ap_run "$b" "${inv_root[$cand]}" "$d/env" "${rargv[@]}" 2>&1 )"
      rrc=$?
      set -e
      printf '%s\n' "$rout" > "$d/rerun.out"
      if [ "$rrc" = "0" ] || [ "$rrc" = "2" ] || ! in_list "$rrc" "$declared"; then
        bad "$cname: повторный прогон проверяющего дал код $rrc — запись о вызове не подтверждена, вывод в $d/rerun.out"
      elif [[ "$rout" != *"$reason"* ]]; then
        bad "$cname: повторный прогон покраснел, но не назвал причину «$reason» — вывод в $d/rerun.out"
      else
        reds=$((reds + 1))
        ok "$cname: зелёный контроль есть, повторный прогон красный кодом $rrc — «$reason»"
      fi
    fi
  done
done

after="$(snapshot_of)"
if [ "$before" != "$after" ]; then
  menjalis="$(diff <(printf '%s\n' "$before") <(printf '%s\n' "$after") \
              | awk '/^[<>]/ { print $3 }' | sort -u | tr '\n' ' ' || true)"
  # Прочерк и stdin — плейсхолдеры хеша конфига, не имена файлов: выкидываются до проверки
  # пустоты, иначе «файлы: -» выдаёт себя за названную причину.
  menjalis="$(printf '%s\n' "$menjalis" | tr ' ' '\n' | grep -vE '^(-|stdin)?$' | tr '\n' ' ' || true)"
  # ПУСТОЙ СПИСОК ФАЙЛОВ при расхождении слепков означает ЛОКАЛЬНЫЙ GIT CONFIG: файлы не
  # менялись, а хеш выписки конфига — да. Именуется прямо, а не прочерком: причина обязана
  # называть предмет (правило 7 нормы).
  if [ -z "${menjalis// /}" ]; then
    menjalis="локальный git config"
  fi
  bad "дерево изменилось вне \$WORK — файлы: ${menjalis% }"
  printf '       фикстура обязана жить в $WORK; если названные файлы правит кто-то другой\n' >&2
  printf '       (соседный агент, редактор) — прогон недостоверен целиком, а не в одной строке\n' >&2
fi

printf '\nбарьеров: %d · фикстур: %d · предъявлено красным повторным прогоном: %d\n' \
  "${#barriers[@]}" "$cases_total" "$reds" >&2
if [ "$fails" -gt 0 ]; then
  printf 'расхождений: %d · прогон оставлен в %s\n' "$fails" "$RUN" >&2
  exit 1
fi
rm -rf "$RUN"
