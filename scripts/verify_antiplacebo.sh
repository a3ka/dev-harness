#!/usr/bin/env bash
# Барьер не готов, пока не предъявлен КРАСНЫМ против обманной заглушки.
#
# Заведено потому, что «фикстуры есть» было утверждением сессии, а не репозитория: в
# HANDOFF.md стояло «шесть фикстур» для `overlay.sh`, и в дереве не лежало ни одной.
# Зелёный, которого никто не видел красным, не доказывает ничего — он одинаково зелен у
# барьера, который проверяет, и у барьера, который печатает `ok` и выходит.
#
# ПРОВЕРЯЕТСЯ ИСПОЛНЕНИЕМ. Наличие файла рядом с барьером проверкой не является: файл из
# одной строки `exit 1` удовлетворил бы её, и она стала бы плацебо о плацебо. Фикстура
# обязана предъявить барьер СНАЧАЛА ЗЕЛЁНЫМ на целом дереве, затем внести обманное
# состояние и получить от барьера не ноль с НАЗВАННОЙ причиной.
#
# Положительный контроль обязателен по измеренной причине: адверсарий предъявил заглушку,
# которая печатала «e» ВСЕГДА — и на отказе, и на зелёном прогоне, — и объявляла «e» своей
# причиной. Проверка это принимала. Причина, которая печатается и на зелёном, не называет
# ни отказ, ни предмет. Зелёный прогон в той же фикстуре разводит эти два случая механизмом.
#
# КРАСНОЕ ЗАСЧИТЫВАЕТ ПРОВЕРЯЮЩИЙ СВОИМ ПОВТОРНЫМ ПРОГОНОМ, а не запись фикстуры. Обёртка
# запоминает, ЧЕМ и ГДЕ был вызван барьер (argv, каталог, подставной корень), после чего
# проверяющий вызывает барьер сам и требует того же отказа. Это закрывает подделку учёта:
# адверсарий подделал запись о вызове, вычитав путь учёта из читаемой обёртки, не вызвав
# барьер вовсе. Подделать запись всё ещё можно — но она стала лишь УКАЗАНИЕМ, где мерить,
# а меряет проверяющий. Чтобы обмануть его, придётся указать argv, на котором барьер
# действительно краснеет, то есть сделать работу настоящей фикстуры.
#
# ОБЛАСТЬ ВЫВЕДЕНА ИЗ ПРЕДМЕТА, А НЕ ЗАДАНА ПРЕФИКСОМ. План 005 §1 писал «каждый
# `scripts/verify_*.sh` и `scripts/drill_*.sh`» — и этот список молча упускает
# `scripts/check_ids.sh` и `scripts/check_protected.sh` из §2 и §4 ТОГО ЖЕ плана, а также
# три уже стоящих гейта. Поэтому область — ВСЁ содержимое `scripts/` на любой глубине, а
# роль каждого файла объявляет он сам своей ШАПКОЙ:
#
#   `Коды возврата: 0 — …, 1 — …, 2 — …`  барьер: его вердикт есть код возврата, нужна
#                                         фикстура. Перечисленные коды — ЕДИНСТВЕННЫЕ, с
#                                         которыми он имеет право выходить;
#   `НЕ БАРЬЕР: <почему>`                 вне области явно и с записанной причиной.
#
# Шапка — это первый непрерывный блок комментариев файла, и только он. Адверсарий выдал
# настоящий барьер за «НЕ БАРЬЕР», спрятав маркер в строке ДАННЫХ here-document: маркер
# внизу файла шапкой не является, потому что любая строка кода шапку закрывает.
#
# Объявленные коды проверяются потому, что иначе красным считается любая неудача запуска:
# заглушка адверсария печатала «команда не найдена» и выходила 127, и это принималось за
# отказ по предмету. Код 2 (`NOT_IMPLEMENTED`) красным НЕ считается и считается провалом
# фикстуры: «нечем проверить» не равно «проверено», а иначе внесённое нарушение прячется
# под нехватку инструмента — так адверсарий и заслонил настоящий отказ кодом 2.
#
# ЧЕГО ЭТОТ БАРЬЕР НЕ ДЕЛАЕТ. Он не судит, ОТНОСИТСЯ ли обманное состояние к предмету
# барьера: смысл предмета механизму недоступен. Помечено `cognitive-only`, остаточный риск
# записан прямо — фикстура может ронять барьер посторонним (отнятым файлом, чужим
# аргументом) и объявлять это причиной. Против этого стоят двое: положительный контроль
# отсекает вечно-красное, а фикстура — закоммиченный код, который читают адверсарий и
# ревьюер. Ложная мера дороже отсутствующей, поэтому риск назван, а не спрятан.
#
# Соглашение о фикстуре — `fixtures/<ключ барьера>/case_*.sh`, где ключ есть путь внутри
# `scripts/` без расширения и с `/`, заменёнными на `.` (`lib/verify_x.sh` → `lib.verify_x`):
#   `# ПРИЧИНА: <подстрока>`  обязательная шапка: что барьер должен напечатать, краснея, и
#                            чего он НЕ печатает на зелёном прогоне;
#   $BARRIER                 ЧЕМ вызывать барьер. Вызов другим путём не считается вовсе;
#   $WORK                    пустой каталог фикстуры. Дерево репозитория трогать нельзя —
#                            слепок берётся по СОДЕРЖИМОМУ, и правка с восстановленными
#                            размером и mtime тоже ловится (находка адверсария);
#   $REPO                    корень, откуда можно копировать;
#   BARRIER_ROOT=$WORK       если барьер привязан к своему каталогу — обёртка положит туда
#                            его побайтовую копию и запустит её.
#
#   bash scripts/verify_antiplacebo.sh            проверить это дерево
#   bash scripts/verify_antiplacebo.sh <корень>   проверить подставное дерево (так этот
#                                                 барьер предъявляется красным сам)
#
# Коды возврата: 0 — у каждого барьера красное предъявлено, 1 — нет, 2 — нечем проверить.
set -euo pipefail

ROOT="$(cd "${1:-"$(dirname "${BASH_SOURCE[0]}")/.."}" && pwd)"
SCRIPTS="$ROOT/scripts"
FIXTURES="$ROOT/fixtures"

fails=0
ok()   { printf '  ok   %s\n' "$*" >&2; }
bad()  { fails=$((fails + 1)); printf '  FAIL %s\n' "$*" >&2; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

[ -d "$SCRIPTS" ] || skip "нет каталога $SCRIPTS — область проверки не выводится"

# Шапка: первый непрерывный блок комментариев. Любая строка кода её закрывает, поэтому
# данные here-document маркером быть не могут.
header_of() {
  awk 'NR == 1 && /^#!/               { print; next }
       /^[[:space:]]*$/               { print; next }
       /^[[:space:]]*(#|\/\/|\/\*|\*)/ { print; next }
       { exit }' "$1"
}

classify() {
  awk '/^[[:space:]#*\/]*Коды возврата:/ { b = 1 }
       /^[[:space:]#*\/]*НЕ БАРЬЕР:/     { p = 1 }
       END { print (b ? "b" : "") (p ? "p" : "") }' <<< "$1"
}

# Коды берутся из шапки в её же формате `N — смысл`: перечень объявляет сам барьер, а не
# этот файл списком. Число без тире (например «60 строк» в тексте) кодом не считается.
codes_of() {
  grep -oE '[0-9]+[[:space:]]*—' <<< "$1" 2>/dev/null | tr -cd '0-9\n' | sort -u | tr '\n' ' ' || true
}

# ── 1. Область: каждый файл в scripts/ на любой глубине объявляет свою роль сам ─
barriers=(); keys=(); codes=()
while IFS= read -r f; do
  rel="${f#"$SCRIPTS"/}"
  if [ -L "$f" ] && [ ! -e "$f" ]; then
    bad "$rel: битая символическая ссылка — файл, которого нельзя прочесть, не выходит из области, а прячется в ней"
    continue
  fi
  if [ ! -r "$f" ]; then
    bad "$rel: не читается — роль файла не объявлена и не может быть прочитана"
    continue
  fi
  h="$(header_of "$f")"
  case "$(classify "$h")" in
    b)
      c="$(codes_of "$h")"
      if [ -z "${c// /}" ]; then
        bad "$rel: шапка не перечислила коды возврата в формате 'N — смысл' — тогда любая неудача запуска сойдёт за отказ"
        continue
      fi
      barriers+=("$f"); keys+=("$(printf '%s' "${rel%.*}" | tr '/' '.')"); codes+=("$c")
      ;;
    p)  ;;
    bp) bad "$rel: объявлен и барьером, и не барьером — роль файла обязана быть одна" ;;
    *)  bad "$rel: не классифицирован — объявите в шапке 'Коды возврата:' либо 'НЕ БАРЬЕР: <почему>'" ;;
  esac
done < <(find "$SCRIPTS" \( -type f -o -type l \) | sort)

[ "${#barriers[@]}" -gt 0 ] || skip "в $SCRIPTS нет ни одного барьера — предъявлять нечего"

# ── 2. Сверка в обе стороны: фикстура без барьера — тоже расхождение ───────────
if [ -d "$FIXTURES" ]; then
  for d in "$FIXTURES"/*; do
    [ -d "$d" ] || continue
    k="$(basename "$d")"
    found=0
    for kk in "${keys[@]}"; do
      if [ "$kk" = "$k" ]; then found=1; fi
    done
    [ "$found" -eq 1 ] || bad "fixtures/$k: фикстура без барьера — она ничего не держит"
  done
fi

# ── 3. Прогон фикстур ─────────────────────────────────────────────────────────
# Временное — в ./tmp проверяемого дерева, а не в системном /tmp.
RUN="$ROOT/tmp/antiplacebo/run-$$"
mkdir -p "$RUN"

# ЕДИНСТВЕННАЯ реализация запуска барьера. Её используют и обёртка, и повторный прогон
# проверяющего: две копии одного запуска разошлись бы молча, и повторный прогон перестал бы
# быть той же мерой.
INVOKE="$RUN/invoke.sh"
cat > "$INVOKE" <<'INV'
ap_invoke() {  # <барьер> <подставной корень или пусто> <файл окружения или пусто> <argv...>
  local real="$1" root="$2" envfile="$3"; shift 3
  if [ -n "$root" ]; then
    mkdir -p "$root/scripts"
    cp "$real" "$root/scripts/$(basename "$real")"
    real="$root/scripts/$(basename "$real")"
  fi
  local cmd=()
  case "$real" in
    *.ts) cmd=(node "$real") ;;
    *)    if [ -x "$real" ]; then cmd=("$real"); else cmd=(bash "$real"); fi ;;
  esac
  # ОКРУЖЕНИЕ — часть условий, в которых барьер краснел. Адверсарий предъявил это на
  # механизме 3: фикстура `overlay` кладёт подставной `omp` в свой PATH, повторный прогон
  # проверяющего запускался БЕЗ него и получал код 2 вместо красного. Повтор, не
  # воспроизводящий условий, повтором не является.
  if [ -n "$envfile" ] && [ -s "$envfile" ]; then
    local pairs=(); mapfile -d '' -t pairs < "$envfile"
    env -i "${pairs[@]}" "${cmd[@]}" "$@"
  else
    "${cmd[@]}" "$@"
  fi
}
INV
. "$INVOKE"

# Тело обёртки. Пути НЕ передаются фикстуре окружением, а вшиваются в её собственную
# обёртку: прежняя редакция экспортировала путь учёта, и фикстура могла создать запись о
# вызове, ничего не вызвав. Обёртка при этом читаема, и вычитать пути из неё можно — именно
# поэтому вердикт о красном выносит повторный прогон проверяющего, а не эта запись.
BODY="$RUN/wrapper.body"
cat > "$BODY" <<'WRAP'
set -uo pipefail
. "$AP_INVOKE"
mkdir -p "$AP_INV"
n=1
while [ -e "$AP_INV/inv.$n" ]; do n=$((n + 1)); done
inv="$AP_INV/inv.$n"
mkdir -p "$inv"
printf '%s' "${BARRIER_ROOT:-}" > "$inv/root"
printf '%s' "$PWD"              > "$inv/cwd"
: > "$inv/argv"
for a in "$@"; do printf '%s\0' "$a" >> "$inv/argv"; done
env -0 > "$inv/env"
ap_invoke "$AP_REAL" "${BARRIER_ROOT:-}" '' "$@" > "$inv/out" 2>&1
rc=$?
printf '%s' "$rc" > "$inv/rc"
cat "$inv/out"
exit "$rc"
WRAP

# Слепок дерева по СОДЕРЖИМОМУ. Прежняя редакция хешировала путь, размер и mtime, и
# адверсарий предъявил правку, которая меняет байт, сохраняя длину, и возвращает mtime через
# `touch -r`: слепок её не видел. Мера, не видящая предмета, хуже отсутствующей.
#
# `cd` стоит СНАРУЖИ конвейера намеренно: в первой редакции он был внутри группы `{ }`, то
# есть действовал только на первое звено, а `xargs sha256sum` запускался в исходном каталоге
# и не находил относительных путей. Найдено чужим прогоном: у соседнего исполнителя все
# фикстуры покраснели кодом 123 от `xargs`. Каталог у звена конвейера свой — это тот же
# класс дефекта замера, что и код возврата у конвейера.
#
# Слепок ПОФАЙЛОВЫЙ, а не одна сумма: одна сумма говорит «дерево изменилось» и оставляет
# читателя догадываться, кто это сделал. Измерено на этом же прогоне — изменился
# `scripts/check_ids.sh`, потому что рядом его писал соседний исполнитель, а сообщение винило
# фикстуру. Мера обязана предъявлять предмет: она называет файлы, а причину пусть назовёт
# тот, кто смотрит.
snapshot_to() (
  cd "$ROOT"
  {
    for p in scripts fixtures roles config .omp plans; do
      [ -e "$p" ] || continue
      find "$p" -type f -print0
    done
    find . -maxdepth 1 -type f -print0
  } | sort -z | xargs -0 sha256sum
)
snapshot_to > "$RUN/before.list"

in_list() { case " $2 " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }

cases_total=0; reds=0
i=-1
for b in "${barriers[@]}"; do
  i=$((i + 1))
  key="${keys[$i]}"; declared="${codes[$i]}"
  dir="$FIXTURES/$key"
  mapfile -t cases < <(find "$dir" -maxdepth 1 -type f -name 'case_*.sh' 2>/dev/null | sort)
  if [ "${#cases[@]}" -eq 0 ]; then
    bad "$(basename "$b"): нет фикстур — ожидается fixtures/$key/case_*.sh"
    continue
  fi
  for c in "${cases[@]}"; do
    cases_total=$((cases_total + 1))
    cname="$key/$(basename "$c")"
    reason="$(awk 'sub(/^# ПРИЧИНА:[[:space:]]*/, "") { print; exit }' "$c")"
    if [ -z "$reason" ]; then
      bad "$cname: не объявила причину — нужна шапка '# ПРИЧИНА: <подстрока вывода барьера>'"
      continue
    fi
    # Прямое упоминание внутренних имён учёта — лобовая подделка. Область — ИСПОЛНЯЕМЫЕ
    # строки: первая редакция грепала файл целиком и завалила фикстуру за то, что та
    # ОБЪЯСНЯЛА, чего избегает. Документация обязана иметь право называть предмет.
    if awk '!/^[[:space:]]*#/ && /AP_INV|AP_REAL|AP_INVOKE|wrapper\.body/ { f = 1 }
            END { exit(f ? 0 : 1) }' "$c"; then
      bad "$cname: упоминает внутренности учёта вызовов — учёт не принадлежит тому, о ком ведётся"
      continue
    fi

    d="$RUN/$key.$(basename "$c" .sh)"
    mkdir -p "$d/work" "$d/inv"
    wrap="$d/barrier"
    { printf '#!/usr/bin/env bash\nAP_REAL=%q\nAP_INV=%q\nAP_INVOKE=%q\n' "$b" "$d/inv" "$INVOKE"
      cat "$BODY"; } > "$wrap"
    chmod +x "$wrap"
    set +e
    env -u BARRIER_ROOT -u AP_REAL -u AP_INV -u AP_INVOKE \
      BARRIER="$wrap" WORK="$d/work" REPO="$ROOT" \
      bash "$c" > "$d/case.out" 2>&1
    case_rc=$?
    set -e

    seen=0; green=0; degenerate=0; tool=0; alien=''; candidate=''
    for inv in "$d"/inv/inv.*; do
      [ -d "$inv" ] || continue
      seen=$((seen + 1))
      rc="$(cat "$inv/rc" 2>/dev/null || true)"
      if [ "$rc" = "0" ]; then
        if grep -qF -e "$reason" "$inv/out"; then degenerate=1; else green=1; fi
      elif [ "$rc" = "2" ]; then
        tool=1
      elif ! in_list "$rc" "$declared"; then
        alien="$rc"
      elif [ -z "$candidate" ]; then
        candidate="$inv"
      fi
    done

    if [ "$seen" -eq 0 ]; then
      bad "$cname: не вызвала барьер через \$BARRIER (код фикстуры $case_rc) — вывод в $d/case.out"
    elif [ "$degenerate" -eq 1 ]; then
      bad "$cname: причина «$reason» печатается и на ЗЕЛЁНОМ прогоне — она не называет ни отказ, ни предмет"
    elif [ "$tool" -eq 1 ]; then
      bad "$cname: барьер ответил «нечем проверить» (код 2) — фикстура обязана дать ему инструменты, иначе нарушение прячется под NOT_IMPLEMENTED"
    elif [ -n "$alien" ]; then
      bad "$cname: барьер вышел кодом $alien, которого не объявлял (объявлены: ${declared% }) — это неудача запуска, а не отказ по предмету"
    elif [ "$green" -eq 0 ]; then
      bad "$cname: нет положительного контроля — фикстура обязана предъявить барьер ЗЕЛЁНЫМ до порчи, иначе вечно-красный барьер неотличим от работающего"
    elif [ -z "$candidate" ]; then
      bad "$cname: барьер остался зелёным на обманном дереве — красное не предъявлено"
    else
      # Красное засчитывается ПОВТОРНЫМ прогоном проверяющего: запись фикстуры лишь говорит,
      # где мерить, а мерит проверяющий сам.
      rroot="$(cat "$candidate/root")"; rcwd="$(cat "$candidate/cwd")"
      rargv=(); mapfile -d '' -t rargv < "$candidate/argv" 2>/dev/null || true
      set +e
      ( cd "$rcwd" && ap_invoke "$b" "$rroot" "$candidate/env" "${rargv[@]}" ) > "$candidate/rerun.out" 2>&1
      rrc=$?
      set -e
      if [ "$rrc" = "0" ] || [ "$rrc" = "2" ] || ! in_list "$rrc" "$declared"; then
        bad "$cname: повторный прогон проверяющего дал код $rrc — запись о вызове не подтверждена, вывод в $candidate/rerun.out"
      elif ! grep -qF -e "$reason" "$candidate/rerun.out"; then
        bad "$cname: повторный прогон покраснел, но не назвал причину «$reason» — вывод в $candidate/rerun.out"
      else
        reds=$((reds + 1))
        ok "$cname: зелёный контроль есть, повторный прогон красный кодом $rrc — «$reason»"
      fi
    fi
  done
done

snapshot_to > "$RUN/after.list"
if ! cmp -s "$RUN/before.list" "$RUN/after.list"; then
  # `|| true` обязателен: `diff` при различии возвращает 1, под `pipefail` это код ВСЕГО
  # конвейера, и подстановка убивала скрипт БЕЗ НАЗВАННОЙ ПРИЧИНЫ ровно в том месте, где он
  # собирался её назвать. Найдено своей же фикстурой: внешний прогон увидел красное, в котором
  # объявленного текста не было. Третий за сессию случай, когда код конвейера соврал о предмете.
  menjalis="$(diff "$RUN/before.list" "$RUN/after.list" | awk '/^[<>]/ { print $3 }' | sort -u | tr '\n' ' ' || true)"
  bad "дерево изменилось вне \$WORK — файлы: ${menjalis% }"
  printf '       фикстура обязана жить в $WORK; если названные файлы правит кто-то другой\n' >&2
  printf '       (соседний агент, редактор) — прогон недостоверен целиком, а не в одной строке\n' >&2
fi

printf '\nбарьеров: %d · фикстур: %d · предъявлено красным повторным прогоном: %d\n' \
  "${#barriers[@]}" "$cases_total" "$reds" >&2
if [ "$fails" -gt 0 ]; then
