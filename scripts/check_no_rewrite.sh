#!/usr/bin/env bash
# История не перезаписывается: прежняя вершина обязана остаться ПРЕДКОМ новой.
#
# Заведён по находке адверсария на `check_protected.sh`. Тот барьер считает «существовал» по
# объединению деревьев коммитов, ДОСТИЖИМЫХ от HEAD, — и это его честная граница, а не
# оплошность: после `git reset --hard` назад, `commit --amend`, `rebase` или `filter-branch`
# коммит с защищённым артефактом остаётся объектом в чьей-то локальной базе, но из присланного
# графа исчезает. Барьер, которому прислали такой граф, не может доказать, что артефакт
# существовал: доказательства ему не дали.
#
# Гнаться за этим внутри `check_protected.sh` нельзя, и это ИЗМЕРЕНО, а не решено вкусом:
# `git fsck --unreachable --no-reflogs` в этом самом репозитории показывает 3 недостижимых
# коммита от обычной работы (cherry-pick, удалённая ветка). Область, дающая красное на
# нормальном дереве, — ложная мера, а ложной верят.
#
# Поэтому предмет разделён. Исчезновение ФАЙЛА из дерева ловит `check_protected.sh`.
# Исчезновение ИСТОРИИ ловит этот барьер, и ловит там, где для этого есть данные: в проводке,
# где событие push сообщает ПРЕЖНЮЮ вершину ветки. Локально прежней вершины не знает никто —
# именно поэтому она передаётся аргументами, а не выясняется догадкой.
#
#   bash scripts/check_no_rewrite.sh <прежняя вершина> <новая вершина> [корень]
#
# Ноль вместо прежней вершины (`0000000000000000000000000000000000000000`) означает создание
# ветки — перезаписывать было нечего, это законно.
#
# Коды возврата: 0 — прежняя вершина осталась предком, 1 — история перезаписана, 2 — нечем
# проверить.
set -euo pipefail

BEFORE="${1:-}"
AFTER="${2:-}"
ROOT="$(cd "${3:-"$(dirname "${BASH_SOURCE[0]}")/.."}" && pwd)"
cd "$ROOT"

skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }
die()  { printf 'ОТКАЗ: %s\n' "$*" >&2; exit 1; }

[ -n "$BEFORE" ] && [ -n "$AFTER" ] \
  || skip "нужны две вершины: $(basename "$0") <прежняя> <новая> [корень]"
command -v git >/dev/null 2>&1 || skip "нет git"
git rev-parse --git-dir >/dev/null 2>&1 || skip "$ROOT не репозиторий git"

ZERO='0000000000000000000000000000000000000000'
if [ "$BEFORE" = "$ZERO" ]; then
  printf '  ok   ветка создана: перезаписывать было нечего\n' >&2
  exit 0
fi

# Прежняя вершина, которой в базе нет, — это НЕ повод согласиться. Именно так выглядит
# перезапись, дошедшая до нас без объектов: «не могу проверить» здесь ближе к отказу, но
# отличать эти два случая обязан читатель, поэтому код 2 и названная причина.
git cat-file -e "${BEFORE}^{commit}" 2>/dev/null \
  || skip "прежней вершины $BEFORE нет в этом клоне — объектов не прислали, доказать нечем"
git cat-file -e "${AFTER}^{commit}" 2>/dev/null \
  || skip "новой вершины $AFTER нет в этом клоне"

if git merge-base --is-ancestor "$BEFORE" "$AFTER"; then
  printf '  ok   прежняя вершина %s осталась предком %s\n' "${BEFORE:0:8}" "${AFTER:0:8}" >&2
  exit 0
fi

printf 'ОТКАЗ: история перезаписана — прежняя вершина %s не является предком %s\n' \
  "${BEFORE:0:8}" "${AFTER:0:8}" >&2
printf 'Выпавшие из графа коммиты (их деревья больше не доказывают существование артефактов):\n' >&2
git rev-list "$BEFORE" --not "$AFTER" --format='  %h %s' --no-commit-header 2>/dev/null \
  | sed -n '1,20p' >&2 || true
exit 1
