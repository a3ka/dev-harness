#!/usr/bin/env bash
# ГЕНЕРАТОР CI-workflow проекта из проектного манифеста — контракт 122 «CI проекта» (Г1).
#
#   bash scripts/gen_project_workflow.sh --repo R (--check|--write)
#
# Источник — <R>/.harness/ci.json (замкнутый алфавит: schemaVersion/projectId/
# jobs{key:{class∈{local,station},workdir,steps[{key,run}]}}). projectId манифеста
# обязан равняться projectId профиля <R>/.harness/harness.project.json — единственный
# источник identity, резолвер профиля не расширяется.
# --write пишет <R>/.github/workflows/ci.yml ДЕТЕРМИНИРОВАННЫМИ байтами (порядок
# джоб — по ключу, шагов — по порядку манифеста); --check — побайтовое сравнение с
# тем же рендером: любая ручная правка = дрейф (workflow-ruchnoj).
#
# Коды возврата: 0 — ok; 1 — именованный отказ из алфавита 122 (причина печатается
# на stderr как `gen ОТКАЗ: <причина>[: детали]`); 2 — ошибка вызова (неизвестный
# ключ, нет аргумента). Отказ с rc 0 — дефект: потребители (CI, предпроверка) судят
# код возврата, а не текст.
set -u

R=""
MODE=""
while [ $# -gt 0 ]; do
  case "$1" in
    --repo)  R=${2-}; shift ;;
    --check) MODE=check ;;
    --write) MODE=write ;;
    -h|--help)
      printf 'usage: gen_project_workflow.sh --repo <R> (--check|--write)\n'
      exit 0 ;;
    *) printf 'gen ОТКАЗ: неизвестный ключ: %s\n' "$1" >&2; exit 2 ;;
  esac
  shift
done
[ -n "$R" ] && [ -n "$MODE" ] || {
  printf 'gen ОТКАЗ: usage: gen_project_workflow.sh --repo <R> (--check|--write)\n' >&2
  exit 2
}

export PYTHONDONTWRITEBYTECODE=1
exec python3 - "$R" "$MODE" <<'PY'
import json, os, sys

ROOT, MODE = sys.argv[1], sys.argv[2]
WORKFLOW_REL = os.path.join('.github', 'workflows', 'ci.yml')
HEADER = ('# GENERATED by dev-harness gen_project_workflow — не править руками; '
          'источник — .harness/ci.json')


def refuse(reason, detail=None):
    text = reason if not detail else '%s: %s' % (reason, detail)
    sys.stderr.write('gen ОТКАЗ: %s\n' % text)
    sys.exit(1)


def read_json(path):
    try:
        with open(path, encoding='utf-8') as f:
            return json.load(f)
    except Exception:
        return None


def load_manifest():
    """Манифест .harness/ci.json; вне замкнутого алфавита — manifest-nevaliden."""
    path = os.path.join(ROOT, '.harness', 'ci.json')
    if not os.path.isfile(path):
        refuse('manifest-otsutstvuet', path)
    try:
        with open(path, encoding='utf-8') as f:
            raw = f.read()
    except OSError:
        refuse('manifest-nevaliden', 'не читается: %s' % path)
    try:
        return json.loads(raw)
    except ValueError as e:
        refuse('manifest-nevaliden', str(e))


def clean_text(value, allow_empty=False):
    """Однострочный текст без табов/переводов строки (run однострочный по контракту)."""
    return (isinstance(value, str) and (allow_empty or value != '')
            and '\n' not in value and '\r' not in value and '\t' not in value)


def validate(m):
    if not isinstance(m, dict) or set(m) - {'schemaVersion', 'projectId', 'jobs'}:
        refuse('manifest-nevaliden', 'корень: schemaVersion/projectId/jobs')
    if m.get('schemaVersion') != 1 or not clean_text(m.get('projectId')):
        refuse('manifest-nevaliden', 'schemaVersion != 1 или projectId не строка')
    jobs = m.get('jobs')
    if not isinstance(jobs, dict) or not jobs:
        refuse('manifest-nevaliden', 'jobs — непустое отображение key→job')
    for key, job in jobs.items():
        if not clean_text(key):
            refuse('manifest-nevaliden', 'ключ джобы не строка: %r' % (key,))
        if not isinstance(job, dict) or set(job) - {'class', 'workdir', 'steps'}:
            refuse('manifest-nevaliden', 'джоба %s: class/workdir/steps' % key)
        if job.get('class') not in ('local', 'station'):
            refuse('manifest-nevaliden', 'джоба %s: class=%r не из {local,station}'
                   % (key, job.get('class')))
        if 'workdir' in job and not clean_text(job['workdir']):
            refuse('manifest-nevaliden', 'джоба %s: workdir' % key)
        steps = job.get('steps')
        if not isinstance(steps, list) or not steps:
            refuse('manifest-nevaliden', 'джоба %s: steps — непустой список' % key)
        for step in steps:
            if not isinstance(step, dict) or set(step) - {'key', 'run'}:
                refuse('manifest-nevaliden', 'джоба %s: шаг key/run' % key)
            if not clean_text(step.get('key')) or not clean_text(step.get('run')):
                refuse('manifest-nevaliden', 'джоба %s: шаг key/run — непустые строки' % key)


def project_id_matches(manifest_id):
    """Единственный источник identity — профиль .harness/harness.project.json."""
    path = os.path.join(ROOT, '.harness', 'harness.project.json')
    if not os.path.isfile(path):
        refuse('profil-otsutstvuet', path)
    profile = read_json(path)
    if not isinstance(profile, dict) or profile.get('projectId') != manifest_id:
        refuse('profil-rashozhdenie',
               'профиль=%r манифест=%r' % (
                   profile.get('projectId') if isinstance(profile, dict) else None,
                   manifest_id))


def yaml_quote(value):
    """Одинарные кавычки YAML: значение переносится байт в байт, спецсимволы не едут."""
    return "'" + value.replace("'", "''") + "'"


def render(m):
    """Детерминированные байты workflow: джобы по ключу, шаги в порядке манифеста."""
    lines = [
        HEADER,
        'name: ci-project',
        'on:',
        '  push:',
        '  pull_request:',
        'concurrency:',
        '  group: ci-project-${{ github.ref }}',
        '  cancel-in-progress: true',
        'jobs:',
    ]
    jobs = m['jobs']
    for key in sorted(jobs):
        job = jobs[key]
        workdir = job.get('workdir', '.')
        lines.append('  %s:' % key)
        lines.append('    runs-on: ubuntu-latest')
        if workdir != '.':
            lines.append('    defaults:')
            lines.append('      run:')
            lines.append('        working-directory: %s' % yaml_quote(workdir))
        lines.append('    env:')
        lines.append('      PREFLIGHT_CLASS: %s' % job['class'])
        lines.append('    steps:')
        lines.append('      - uses: actions/checkout@v4')
        for step in job['steps']:
            lines.append('      - name: %s' % yaml_quote(step['key']))
            lines.append('        run: %s' % yaml_quote(step['run']))
    return '\n'.join(lines) + '\n'


manifest = load_manifest()
validate(manifest)
project_id_matches(manifest['projectId'])
text = render(manifest)
path = os.path.join(ROOT, WORKFLOW_REL)

if MODE == 'write':
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(text.encode('utf-8'))
    sys.stdout.write('gen OK: write %s\n' % WORKFLOW_REL)
    sys.exit(0)

if not os.path.isfile(path):
    refuse('workflow-otsutstvuet', '%s (сгенерируй --write)' % WORKFLOW_REL)
# Побайтовое сравнение (§Г1): текстовый режим Python нормализует \r\n и одиночный
# \r в \n ДО сравнения, и CRLF-версия файла проходила бы как «не ручная правка».
try:
    with open(path, 'rb') as f:
        current = f.read()
except OSError as e:
    refuse('workflow-otsutstvuet', '%s не читается: %s' % (WORKFLOW_REL, e))
if current != text.encode('utf-8'):
    refuse('workflow-ruchnoj', '%s разошёлся с манифестом' % WORKFLOW_REL)
sys.stdout.write('gen OK: check %s\n' % WORKFLOW_REL)
sys.exit(0)
PY