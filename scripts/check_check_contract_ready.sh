#!/usr/bin/env bash
# Барьер приёмки check_contract_ready (контракт 008, срез-1, тир-1).
#
# Гоняет ПРЕДМЕТ `scripts/check_contract_ready.sh` (пишет ИСПОЛНИТЕЛЬ) на игрушечных
# контрактах и УТВЕРЖДАЕТ код возврата + названную причину. Фикстуры ИНЛАЙН —
# самодостаточны, без внешних builder-скриптов. Образец идиомы — check_scoped_run.
#
# ПИНИТ УНОЗНАЧНОЕ ЯДРО срез-1 (то, что на 007/005 съедало круги судьи вместо автора):
#   (проба) объявленная приёмочная команда ОБЯЗАНА быть КРАСНОЙ (exit≠0) против дерева —
#           иначе судье нечего предъявлять (Н-38: «зелёная всегда бесполезна»);
#   (зоны)  контракт объявляет ЗОНА / РАБОТА НЕ РАЗДАЁТСЯ — иначе раздача неясна;
#   (готов) зоны + красная приёмка → RC0.
# Счёт-по-прозе и арбитражные перечни (контракт §Незаполненные требования) НЕ пинятся
# здесь: их машинно-читаемый формат не определён и разбирается на круге критика 008.
#
# КРАСНОЕ ПРОТИВ ТЕКУЩЕГО ДЕРЕВА: предмета ещё нет (владелец: реализацию начнёт исполнитель),
# run_subject даёт маркер отсутствия, и все ветви краснеют. Зелёными станут при верной реализации.
# Анти-плацебо: стаб-всегда-RC0 валит (зоны)/(проба); стаб-всегда-RC≠0 валит (готов).
#
#   bash scripts/check_check_contract_ready.sh [<ветвь>]   ветви: проба зоны готов (умолч. все)
# Коды возврата: 0 — запрошенные ветви зелены, 1 — ветвь провалена, 2 — нечем проверить.
set -uo pipefail
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null LC_ALL="${LC_ALL:-C.UTF-8}"

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SELF_DIR/.." && pwd)"
SUBJECT="$REPO/scripts/check_contract_ready.sh"
WANT="${1:-all}"

die()  { printf 'ОТКАЗ ветвь (%s): %s\n' "$1" "$2" >&2; exit 1; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

TMP="$REPO/tmp"; mkdir -p "$TMP" 2>/dev/null || skip "tmp не создать"
WORK="$(mktemp -d "$TMP/cccr.XXXXXX")" || skip "mktemp не смог"
trap 'rm -rf "$WORK"' EXIT

want() { [ "$WANT" = all ] || [ "$WANT" = "$1" ]; }
has()  { case "$2" in *"$1"*) return 0 ;; *) return 1 ;; esac; }

KNOWN="проба зоны готов"
if [ "$WANT" != all ]; then
  f=0; for k in $KNOWN; do [ "$WANT" = "$k" ] && f=1; done
  [ "$f" = 1 ] || { printf 'ОТКАЗ диспетчер: неизвестная ветвь «%s» (из: %s)\n' "$WANT" "$KNOWN" >&2; exit 1; }
fi

# Гоняет предмет на <contract.md>. Отсутствие предмета — маркер (RC=2), а не молчание:
# поведенческие ветви ниже краснеют от него (красное до реализации), не выдавая ложного зелёного.
run_subject() {  # <contract.md>
  if [ ! -f "$SUBJECT" ]; then OUT="ПРЕДМЕТ-ОТСУТСТВУЕТ"; RC=2; return 0; fi
  OUT="$(bash "$SUBJECT" "$1" 2>&1)"; RC=$?
}

# ── фикстуры-контракты (инлайн) ───────────────────────────────────────────────
# Готовый: зоны есть + приёмочная команда КРАСНАЯ (несуществующий барьер → exit≠0).
mk_ready() { cat > "$1" <<'EOF'
# Контракт TOY — готовый
## Зоны
ЗОНА implementer: scripts/toy_predmet.sh
## Приёмка-проводка
- `bash scripts/toy_barrier_NESUSHESTVUET.sh` → 0
EOF
}
# Без зон: приёмка есть и красная, но ЗОНА/РАБОТА-НЕ-РАЗДАЁТСЯ нет.
mk_nozones() { cat > "$1" <<'EOF'
# Контракт TOY — без зон
## Приёмка-проводка
- `bash scripts/toy_barrier_NESUSHESTVUET.sh` → 0
EOF
}
# Зелёная приёмка: зоны есть, но объявленная команда УЖЕ зелёная (`true`) → нечего предъявлять красным.
mk_greentest() { cat > "$1" <<'EOF'
# Контракт TOY — приёмка уже зелёная
## Зоны
ЗОНА implementer: scripts/toy.sh
## Приёмка-проводка
- `true` → 0
EOF
}

# ── (зоны) нет ЗОНА/РАБОТА-НЕ-РАЗДАЁТСЯ → RC≠0 + названо «зон» ───────────────────
if want зоны; then
  C="$WORK/nozones.md"; mk_nozones "$C"; run_subject "$C"
  [ "$RC" != 0 ] || die зоны "контракт без ЗОНА/РАБОТА-НЕ-РАЗДАЁТСЯ принят RC=0 — раздача неясна"
  has "зон" "$OUT" || die зоны "RC≠0, но причина «зоны» не названа. Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 200)"
  printf '  ok   (зоны) без зон → RC≠0, названо «зоны»\n' >&2
fi

# ── (проба) объявленная приёмка УЖЕ зелёная → RC≠0 + названо «проб» ─────────────
if want проба; then
  C="$WORK/green.md"; mk_greentest "$C"; run_subject "$C"
  [ "$RC" != 0 ] || die проба "приёмочная команда УЖЕ зелёная принята RC=0 — судье нечего предъявлять красным (Н-38)"
  has "проб" "$OUT" || die проба "RC≠0, но причина «проба» не названа. Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 200)"
  printf '  ok   (проба) зелёная приёмка → RC≠0, названо «проба»\n' >&2
fi

# ── (готов) зоны + красная приёмка → RC=0 (зелёный контроль) ────────────────────
if want готов; then
  C="$WORK/ready.md"; mk_ready "$C"; run_subject "$C"
  [ "$RC" = 0 ] || die готов "готовый контракт (зоны + красная приёмка) не RC0: RC=$RC. Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 200)"
  printf '  ok   (готов) зоны + красная приёмка → RC=0\n' >&2
fi

printf 'check_check_contract_ready: ветви «%s» зелены\n' "$WANT" >&2
exit 0
