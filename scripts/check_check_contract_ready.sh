#!/usr/bin/env bash
# НЕ БАРЬЕР: мета-барьер приёмки check_contract_ready (контракт 008, срез-1).
# Гоняет ПРЕДМЕТ `scripts/check_contract_ready.sh <root>` на ИНЛАЙН-фикстурах (mk_ready,
# mk_nozones, mk_greentest, mk_wrongcount, mk_arb_bad) и УТВЕРЖДАЕТ код возврата + наличие
# именованной причины. Не принимает внешних фикстур — структура ветвей ИНЛАЙН обеспечивает
# анти-плацебо: каждая ветвь ловит КОНКРЕТНЫЙ дефект и требует именованный термин; (готов)
# дополнительно требует маркер «OK» в выводе предмета, чтобы стаб-vsegda-0 не прошёл как зелёный.
# verify_antiplacebo не покрывает (НЕ БАРЬЕР по конструкции).
#
# ПИНИТ ЯДРО срез-1 (Н-38, урок 007/005: круги 1-3 у судьи вместо автора):
#   (зоны)     контракт объявляет ЗОНА / РАБОТА НЕ РАЗДАЁТСЯ — иначе раздача неясна;
#   (проба)    объявленная приёмочная команда СУЩЕСТВУЕТ (как файл) И КРАСНАЯ (exit≠0) против
#              текущего дерева — иначе судье нечего предъявлять (Н-38: «зелёная бесполезна»);
#   (счёт)     объявленное «N фикстур» = фактический счёт `case_*.sh` в объявленном каталоге;
#   (арбитраж) объявленный `verdicts/arbitration/<file>.md` существует и строка 1 = «РЕШЕНИЕ»;
#   (готов)    зоны + проба(существует+красная) + счёт + арбитраж + маркер «OK» → RC0.
#
# Анти-плацебо (стабы НЕ проходят):
#   стаб-всегда-RC0:        валит (зоны), (проба), (счёт), (арбитраж) — нет причин;
#   стаб-всегда-RC≠0:       валит (готов) — не зелёный;
#   стаб-RC0-без-OK:        валит (готов) — нет маркера «OK»;
#   стаб-только-«зоны»:     валит (проба)/(счёт)/(арбитраж)/(готов) — неполный ответ.
#
# КРАСНОЕ ПРОТИВ ТЕКУЩЕГО ДЕРЕВА: предмета ещё нет → run_subject → RC=2 маркер, все 5 ветвей краснеют.
# Зелёными станут при верной реализации предмета.
#
#   bash scripts/check_check_contract_ready.sh [<ветвь>]
#     <ветвь> — одна из: зоны проба счёт арбитраж готов (умолч. all)
#
# Коды возврата: 0 — запрошенные ветви зелёные, 1 — ветвь провалена, 2 — нечем проверить.
set -uo pipefail
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null LC_ALL="${LC_ALL:-C.UTF-8}"

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SELF_DIR/.." && pwd)"
SUBJECT="$REPO/scripts/check_contract_ready.sh"
WANT="${1:-all}"

die()  { printf 'ОТКАЗ ветвь (%s): %s\n' "$1" "$2" >&2; exit 1; }
skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }

TMP="$REPO/tmp"; mkdir -p "$TMP" 2>/dev/null || skip "tmp не создать"
WORK="$(mktemp -d "$TMP/cccr.XXXXXX")" || skip "mktemp не смог"
trap 'rm -rf "$WORK"' EXIT

want() { [ "$WANT" = all ] || [ "$WANT" = "$1" ]; }
has()  { case "$2" in *"$1"*) return 0 ;; *) return 1 ;; esac; }

KNOWN="зоны проба счёт арбитраж готов"
if [ "$WANT" != all ]; then
  f=0; for k in $KNOWN; do [ "$WANT" = "$k" ] && f=1; done
  [ "$f" = 1 ] || { printf 'ОТКАЗ диспетчер: неизвестная ветвь «%s» (из: %s)\n' "$WANT" "$KNOWN" >&2; exit 1; }
fi

# Гоняет предмет на корне дерева (<root>/scripts/check_contract_ready.sh).
# Отсутствие предмета — RC=2 маркер (а не молчание): все ветви ниже краснеют честно.
# При наличии предмета — исполняет "$SUBJECT <root>", имитируя задачу автора контракта.
run_subject() {  # <root>
  local r="$1"
  if [ ! -f "$SUBJECT" ]; then OUT="ПРЕДМЕТ-ОТСУТСТВУЕТ"; RC=2; return 0; fi
  OUT="$( "$SUBJECT" "$r" 2>&1 )"; RC=$?
}

# ── фикстуры-деревья (инлайн) ──────────────────────────────────────────────────
#
# Грамматика контракта (предмет ищет маркеры по ВСЕМУ файлу, не по секциям — см. heads-up
# 008-1 архитектора ДО раздачи; `mk_arb_bad` намеренно кладёт `арбитраж:` под `## Зоны`, а НЕ
# под `## Приёмочный критерий`, чтобы поймать предмет, ограничивший поиск секцией):
#   * строка вида `ЗОНА <роль>: <путь>...` — любое место файла (наличие хотя бы одной);
#   * либо `РАБОТА НЕ РАЗДАЁТСЯ: <причина>` (исключение — нет ЗОНА, но есть причина нераздачи);
#   * строка вида `- \`<команда в бэктиках>\`` — приёмочная проба (предмет ОБЯЗАН проверить,
#     что файл существует И exit≠0 на текущем дереве);
#   * строка вида `счёт: N фикстур в <каталог>/` — фактический счёт `case_*.sh` в <каталог>/;
#   * строка вида `арбитраж: <отн-путь>.md` — файл существует И строка 1 = «РЕШЕНИЕ».
# Каждая объявленная проба — реальный ИСПОЛНЯЕМЫЙ файл (НЕ bash-127 от несуществующего пути).
# Точные строки — КОНТРАКТ между мета-барьером и предметом; менять = менять замороженный шаг 3.

# Готовый: все 4 проверки проходят.
mk_ready() {
  local r="$1"
  mkdir -p "$r/scripts" "$r/fixtures/toy"
  cat > "$r/scripts/toy_barrier.sh" <<'EOF'
#!/usr/bin/env bash
# fake красная проба (для теста): реальный исполняемый, выходит ≠0 на пустом дереве
exit 1
EOF
  chmod +x "$r/scripts/toy_barrier.sh"
  cat > "$r/contract.md" <<EOF
# Тестовый контракт (готовый)
## Зоны
ЗОНА architect: scripts/

## Приёмочный критерий
- \`bash scripts/toy_barrier.sh\` → 0 (ожидаем красный: 1)
счёт: 0 фикстур в fixtures/toy/
арбитраж: verdicts/arbitration/_FAKE.md
EOF
  # Обходной арбитражный файл, всегда зелёный (строка 1 = «РЕШЕНИЕ»):
  mkdir -p "$r/verdicts/arbitration"
  cat > "$r/verdicts/arbitration/_FAKE.md" <<'EOF'
РЕШЕНИЕ
(заглушка для зелёного контроля мета-барьера)
EOF
}

# Без зон: раздача неясна.
mk_nozones() {
  local r="$1"
  mkdir -p "$r/scripts"
  cat > "$r/contract.md" <<'EOF'
# Тестовый контракт (без зон)
## Приёмочный критерий
- `bash scripts/none.sh` → 0
EOF
}

# Зелёная приёмка: проба есть, но это `true` (exit 0) — нечего предъявлять красным.
mk_greentest() {
  local r="$1"
  mkdir -p "$r/scripts"
  printf '#!/usr/bin/env bash\nexit 0\n' > "$r/scripts/true.sh"
  chmod +x "$r/scripts/true.sh"
  cat > "$r/contract.md" <<'EOF'
# Тестовый контракт (зелёная проба)
## Зоны
ЗОНА architect: scripts/

## Приёмочный критерий
- `bash scripts/true.sh` → 0 (ожидаем красный: 1)
EOF
}

# Рассогласованный счёт: объявлено N, фактически другое.
mk_wrongcount() {
  local r="$1"
  mkdir -p "$r/scripts" "$r/fixtures/cnt"
  printf '#!/usr/bin/env bash\nexit 1\n' > "$r/scripts/cnt_barrier.sh"
  chmod +x "$r/scripts/cnt_barrier.sh"
  # 2 реальных фикстуры, объявлено 5
  printf '#!/usr/bin/env bash\nexit 1\n' > "$r/fixtures/cnt/case_a.sh"
  printf '#!/usr/bin/env bash\nexit 1\n' > "$r/fixtures/cnt/case_b.sh"
  chmod +x "$r/fixtures/cnt/"*.sh
  cat > "$r/contract.md" <<'EOF'
# Тестовый контракт (рассогласованный счёт)
## Зоны
ЗОНА architect: scripts/

## Приёмочный критерий
- `bash scripts/cnt_barrier.sh` → 0 (ожидаем красный: 1)
счёт: 5 фикстур в fixtures/cnt/
EOF
}

# Непройденный арбитраж: объявлен файл, которого нет, либо первая строка ≠ «РЕШЕНИЕ».
mk_arb_bad() {
  local r="$1"
  mkdir -p "$r/scripts"
  printf '#!/usr/bin/env bash\nexit 1\n' > "$r/scripts/arb_barrier.sh"
  chmod +x "$r/scripts/arb_barrier.sh"
  cat > "$r/contract.md" <<'EOF'
# Тестовый контракт (непройденный арбитраж)
## Зоны
ЗОНА architect: scripts/
- `bash scripts/arb_barrier.sh` → 0 (ожидаем красный: 1)
арбитраж: verdicts/arbitration/_DOES_NOT_EXIST.md
EOF
}

# ── (зоны) нет ЗОНА/РАБОТА-НЕ-РАЗДАЁТСЯ → RC≠0 + названо «зон» ───────────────────
if want зоны; then
  R="$WORK/зоны"; mk_nozones "$R"
  run_subject "$R"
  [ "$RC" != 0 ] || die зоны "контракт без зон принят RC=0 — предмет не ловит отсутствие раздачи (Н-38). Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 240)"
  has "зон" "$OUT" || die зоны "контракт без зон не назван «зон» — термин не закреплён. Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 240)"
  printf '  ok   (зоны) без зон → RC≠0, названо «зон»\n' >&2
fi

# ── (проба) объявленная проба ЗЕЛЁНАЯ (exit 0) → RC≠0 + названо «проб» ─────────────
# Закрывает bypass #1 (bypass «проба из существующего файла»: стаб `true` тут и есть
# реальная зелёная проба — предмет ОБЯЗАН её поймать).
if want проба; then
  R="$WORK/проба"; mk_greentest "$R"
  run_subject "$R"
  [ "$RC" != 0 ] || die проба "зелёная проба (`true`) принята RC=0 — судье нечего предъявлять красным (Н-38). Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 240)"
  has "проб" "$OUT" || die проба "зелёная проба не названа «проб» — термин не закреплён. Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 240)"
  printf '  ok   (проба) зелёная проба → RC≠0, названо «проб»\n' >&2
fi

# ── (счёт) объявленное «N фикстур» ≠ факт → RC≠0 + названо «счёт» ──────────────
# Грамматика: «счёт: N фикстур в <каталог>/» — предмет ОБЯЗАН посчитать case_*.sh в <каталог>/.
if want счёт; then
  R="$WORK/счёт"; mk_wrongcount "$R"
  run_subject "$R"
  [ "$RC" != 0 ] || die счёт "рассогласованный счёт (2≠5) принят RC=0 — предмет не ловит Н-38 п.1. Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 240)"
  has "счёт" "$OUT" || die счёт "рассогласованный счёт не назван «счёт» — термин не закреплён. Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 240)"
  printf '  ok   (счёт) рассогласованный счёт (2≠5) → RC≠0, названо «счёт»\n' >&2
fi

# ── (арбитраж) объявленный арбитражный файл НЕ существует → RC≠0 + названо «арбитраж» ─
if want арбитраж; then
  R="$WORK/арбитраж"; mk_arb_bad "$R"
  run_subject "$R"
  [ "$RC" != 0 ] || die арбитраж "несуществующий арбитражный пункт принят RC=0 — предмет не ловит Н-38 п.3. Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 240)"
  has "арбитраж" "$OUT" || die арбитраж "несуществующий арбитраж не назван «арбитраж» — термин не закреплён. Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 240)"
  printf '  ok   (арбитраж) несуществующий арбитражный пункт → RC≠0, названо «арбитраж»\n' >&2
fi

# ── (готов) все 4 проверки зелёные → RC=0 (положительный контроль) ──────────────
if want готов; then
  R="$WORK/готов"; mk_ready "$R"
  run_subject "$R"
  [ "$RC" = 0 ] || die готов "готовый контракт не RC=0: RC=$RC. Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 240)"
  has "OK" "$OUT" || die готов "готовый контракт RC=0, но нет маркера «OK» в выводе предмета — стаб vsegda-0 не должен проходить как зелёный. Вывод: $(printf '%s' "$OUT" | tr '\n' ' ' | tail -c 240)"
  printf '  ok   (готов) готовый контракт → RC=0 + «OK» в выводе\n' >&2
fi

printf 'check_check_contract_ready: ветви «%s» зелены\n' "$WANT" >&2
exit 0