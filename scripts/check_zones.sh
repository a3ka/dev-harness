#!/usr/bin/env bash
# Исполнитель коммитит только в свою зону. Зона объявляется в ЗАМОРОЖЕННОМ контракте, а не в
# задании и не в переписке.
#
# Зачем вообще: `implementer` существует для параллелизма и границ, а не для ловли дефектов
# (измерено: на барьере в 200 строк разделение «спека отдельно, реализация отдельно» дефектов не
# ловит). Границу без механизма исполнитель расширяет молча — «попутно поправил, что попалось», —
# и остаётся дифф, который нечем ревьюить.
#
# ГРАММАТИКА, литерал, первая колонка строки в контракте:
#
#   ЗОНА <имя-автора>: <путь> [<путь>…]
#   РАБОТА НЕ РАЗДАЁТСЯ: <непустая причина>
#
# `<имя-автора>` — git `user.name` агента: агенты коммитят под своими именами (измерено в истории:
# `parity-fixes2`, `IdsFixes2`, `critic`). `<путь>` — каталог с завершающим `/` либо точный файл;
# относительный, без `* ? [`, без `..`, без ведущего `/`. Проверка пути — ЕДИНСТВЕННОЙ реализацией
# `path_prefix_valid` в `lib_roles.sh`, той же, что проверяет `verdict:` у ролей.
#
# ОДНО ИЗ ДВУХ ОБЪЯВЛЕНИЙ ОБЯЗАТЕЛЬНО, И МОЛЧАНИЕ НЕ ГОДИТСЯ. Контракт, который раздаётся, несёт
# `ЗОНА`-строки; контракт, который кодифицирует уже действующее соглашение, несёт
# `РАБОТА НЕ РАЗДАЁТСЯ:` с причиной. Отсутствие обеих — отказ: иначе «зон нет» и «зоны забыли»
# выглядят одинаково, а это разные предметы (правило 7 нормы). Так требование, которое у критика
# было когнитивным, стало механическим.
#
# ЗОНЫ ЧИТАЮТСЯ ИЗ БЛОБА ВЫСШЕЙ ЗАМОРОЗКИ, а не из рабочего дерева: иначе правка файла расширяла бы
# зону без заморозки, то есть исполнитель выдавал бы себе права сам. Черновик зон не даёт.
#
# ДИАПАЗОН — от ПЕРВОЙ заморозки контракта (`frozen/contracts/<NNN>/1..HEAD`), не от высшей: правка
# контракта версией v2 иначе стирала бы зону задним числом вместе с уже проверенными коммитами.
# Зона автора — ОБЪЕДИНЕНИЕ путей, объявленных этому имени во ВСЕХ замороженных контрактах:
# пересечение было бы бессмыслицей, два контракта дают человеку две работы, а не одну общую.
#
# НЕОБЪЯВЛЕННЫЕ АВТОРЫ НЕ ПРОВЕРЯЮТСЯ — владелец и прошлые сессии. Это цена того, чтобы гейт не
# краснел на истории, которую уже нельзя исправить.
#
# МИНТ-ПРИЗНАНИЕ (контракт 031, ветвь ii): путь registry/contracts.tsv под автором orchestrator
# исключается из суда зон ⟺ дельта коммита по этому пути — только-добавление строк грамматики
# манифеста ∧ для каждой строки тег id/CONTRACT/<NNN> жив локально ∧ tag-object-sha == sha
# строки. Иначе — bad() «коммит вне зоны» с теми же именами причин (минт-признание, локальный
# реестр; провенанс НЕ перепроверяется — дверь решила его на входе, прецедент 023 (iv)).
#
# ОСТАТОЧНЫЙ РИСК, помечен `cognitive-only`: `user.name` — не удостоверение. Объявленный исполнитель
# может выйти из зоны, назвавшись новым именем, и барьер этого не увидит по построению. Держится
# тремя вещами: имя в `ЗОНА`-строке пишет АРХИТЕКТОР в контракте, а не исполнитель себе; смена имени
# видна в `git log --format='%an %s'` и входит в область ревьюера; исполнитель коммитит в основной
# репозиторий, то есть его коммиты пересматриваются на приёмке пачки. Ужесточение — подписанные
# коммиты со сверкой ключа и имени — включается словом владельца.
#
# ВТОРОЙ ОСТАТОЧНЫЙ РИСК, тоже `cognitive-only` (арбитраж 040-II, Граница v4 п.6:
# verdicts/arbitration/contracts-040-batching-dostatochnost-oraculu.md): доверенный PATH
# (см. ниже) закрывает ПОЛНОТУ batched-вывода (сверка множеств ключей — author_map/
# paths_raw guards ниже), но НЕ его ПОДЛИННОСТЬ. Подмена `/usr/bin/git` (root-доступ,
# скомпрометированный пакет) либо неподписанные коммиты с произвольным содержимым —
# барьером не проверяются по построению; три независимых замера арбитра (З-B/З-C/З-D)
# доказали, что этот класс НЕ закрывается никакой проверкой ВНУТРИ барьера — сверщик сам
# живёт в TCB того же PATH, что и потенциально подменённый инструмент, а входное
# множество (`git rev-list`) фальсифицируемо ниже по течению от любой сверки. Чек-лист
# А-223 (NABLIUDENIA_ARCHITECT.md): «rc + сверка множеств ключей, И НЕ БОЛЬШЕ —
# подлинность содержимого не предмет вывода-арифметики, предмет границы доверия».
# Ужесточение (signed commits) — словом владельца, как и у риска `user.name` выше.
#
# ТРЕТИЙ ОСТАТОЧНЫЙ РИСК — ЗАКРЫТ v6 (был `cognitive-only`, Н-130, найдено verdicts/adversary/
# contracts-040-v4-circle.md `8e6123c`): доверенный PATH сам по себе не нейтрализует
# экспортированную bash-функцию с именем доверенной утилиты — bash разрешает функции РАНЬШЕ
# $PATH. v5 закрывала это ПЕРЕЧИСЛЕНИЕМ (`unset -f` 14 имён, употребляемых в этом файле);
# адверсарий круга-после-v5 (verdicts/adversary/contracts-040-v5-circle.md, `d46a615`)
# предъявил РЕКУРСИЮ: экспортированная функция `unset`, no-op'ящая ИМЕННО `-f`-форму,
# нейтрализует v5 целиком — `unset -f` перестаёт снимать что-либо, а `unset` в список 14
# имён не входит и войти не может (список — это то, ЧЕМ снимают, самого себя им не снимешь).
# Следующее «ещё одно имя» ждала бы та же рекурсия (что если отравлен `printf`, которым
# печатаются диагностики bad()/ok()? что если `[`?) — перечисление структурно не сходится.
# v6 переходит на `env -i` re-exec (блок «ГЕРМЕТИЧНОЕ ОКРУЖЕНИЕ» ниже, ДО `set -euo
# pipefail`) — закрывает ВЕСЬ класс «унаследованная экспортированная bash-функция с ЛЮБЫМ
# именем» структурно, БЕЗ перечисления: `env -i` строит дочернему процессу окружение из
# ПУСТОГО множества плюс явный allowlist, поэтому ни один `BASH_FUNC_<имя>%%` (сериализация
# Shellshock, единственный канал, которым функция переживает старт нового bash) не
# переживает границу — дочернему bash попросту нечего импортировать, независимо от имени
# утилиты и от того, откуда её вызывают (этот файл или сорсимые next_id.sh/lib_roles.sh/
# lib_zones.sh/lib_registry.sh — список `env`, `basename`, `find`, `date`, `cat`,
# `sha256sum`, `cut` из v5-редакции этого абзаца закрывается тем же движением, без
# добавления в какой-либо список). Прецедент структуры — `check_provodka.sh` (контракт 038,
# круг 9, verdicts/arbitration/038-vrazhdebnaja-sreda-zapuska.md): тот же класс риска, то же
# закрытие, тот же формат канонической проверки `/proc/$$/environ`. Алиасы — ПРОВЕРЕНО И
# ЗАКРЫТО отдельно, не переоткрывается этим фиксом: канала экспорта алиаса через окружение
# нет вовсе, non-interactive bash не разворачивает алиасы без `shopt -s expand_aliases`
# (которого здесь нет).
#
# ЧЕТВЁРТЫЙ ОСТАТОЧНЫЙ РИСК, тоже `cognitive-only` (арбитраж 040-III, verdicts/arbitration/
# contracts-040-vrazhdebnoe-okruzhenie-predel.md): класс «враждебное ОКРУЖЕНИЕ ВЫЗОВА» — всё,
# чем вызывающий управляет процессом барьера ДО и ПОМИМО его текста (`BASH_ENV`/`ENV`,
# экспортированные и slash-именованные bash-функции, `set --` из сорсимого файла, `SHELLOPTS`,
# `shopt`/ловушки, сорсинг) — СТРУКТУРНО НЕЗАКРЫВАЕМ script-internal средствами. Доказано самим
# арбитром живым замером трёх форм гарда (v6, форма прецедента, отклонённый кандидат
# argv-sentinel) на ОДНОМ теле барьера: `BASH_ENV` с `exit 0` даёт rc=0 с ПУСТЫМ выводом на ВСЕХ
# ТРЁХ формах без исключения — интерпретатор завершает процесс ДО первой строки барьера, точки
# исполнения раньше отравителя у скрипта нет в принципе. Блок «ГЕРМЕТИЧНОЕ ОКРУЖЕНИЕ» ниже
# снижает класс до РЕАЛИСТИЧНОГО случая — честный вызывающий с засорённым унаследованным
# окружением (голые имена функций, `GIT_*`, локаль) — и не закрывает случай вызывающего-
# соучастника, управляющего интерпретатором ДО старта скрипта. Дальнейшая борьба с ЭТИМ классом
# внутри барьера не окупается и НЕ мандируется решением арбитра — тот же статус, что у PATH-spy
# против `check_protected.sh` с осени 039: признанный остаток, демонстрация которого не входит в
# вердикт будущих кругов. Закрытие существует РОВНО в одной точке — ВЫЗОВЕ барьера доверенной
# стороной как `env -i PATH=/usr/bin:/bin LC_ALL=C.UTF-8 bash scripts/check_zones.sh …` — цена и
# воля ВЛАДЕЛЬЦА, не предмет адверсарных кругов 040.
#
# Merge-коммиты пропускаются; их содержимое — предмет ревью.
#
# РЕФАКТОРИНГ (контракт 016, срез 1): чтение замороженных контрактов и ЗОНА-строк ВЫНЕСЕНО в
# `scripts/lib_zones.sh` — единый читатель формата (прецедент lib_roles/lib_registry). Этот
# барьер остаётся ЗАКОММИЧЕННЫМ по поведению: тексты bad()/ok() — те же, логика СПАСЕНО, фильтр
# процессных файлов и финальный отчёт — на месте; меняется только способ получения zones_scoped.
#
#   bash scripts/check_zones.sh            проверить это дерево
#   bash scripts/check_zones.sh <корень>   проверить другое (так предъявляется красным)
#
# Коды возврата: 0 — выходов за зону нет либо зон не объявлено, 1 — выход за зону или объявление
# вне грамматики, 2 — нечем проверить.
# ГЕРМЕТИЧНОЕ ОКРУЖЕНИЕ — RE-EXEC ЧЕРЕЗ `env -i` (v7). ДО ЛЮБОЙ ДРУГОЙ СТРОКИ КОДА, даже до
# `set -euo pipefail` и `unset GIT_DIR …` ниже: экспортированная bash-функция с ИМЕНЕМ ЛЮБОЙ
# утилиты переживает старт этого процесса через сериализацию `BASH_FUNC_<имя>%%=() {…}` в
# окружении (механизм Shellshock) и резолвится РАНЬШЕ $PATH при каждом голом вызове имени.
# Закрывает ТРЕТИЙ ОСТАТОЧНЫЙ РИСК из шапки файла (полная история — там); здесь — механика.
#
# ПРОВЕРКА — ПО ФАКТИЧЕСКОМУ ОКРУЖЕНИЮ ПРОЦЕССА (`/proc/$$/environ`), НЕ ПО ФЛАГУ-ЧАСОВОМУ.
# Часовой вида `[ -z "$REEXECED" ] || …` подделывается: вызывающий заранее выставляет
# `REEXECED=1` в своей отравленной среде, барьер решает «уже чисто» и исполняет остаток
# файла БЕЗ re-exec вовсе — тот же класс дыры уже был найден и закрыт на соседнем барьере
# (`scripts/check_no_leak.sh`, адверсарий к5, `4dfc0ff`, S-cnl-sanitized-guard-off). Сверка с
# КАНОНИЧЕСКИМ БАЙТОВЫМ СОДЕРЖИМЫМ всего окружения тем же движением не подделывается: чтобы
# пройти проверку «окружение РОВНО {PATH, LC_ALL}», атакующему пришлось бы не иметь своего
# `BASH_FUNC_*` в окружении вовсе — то есть перестать быть атакующим. `$(…)` обрезает
# завершающие переводы строк — сравнение с `$'PATH=/usr/bin:/bin\nLC_ALL=C.UTF-8'` (без
# хвостового `\n`) корректно и после того, как `tr` перевёл замыкающий NUL записи
# `/proc/pid/environ` в `\n` (живой прогон). Порядок переменных в `env -i PATH=… LC_ALL=…
# bash …` обязан совпадать с порядком в строке сравнения — `env` кладёт их в environ
# дочернего процесса в порядке своих аргументов (живой прогон; расхождение порядка дало бы
# вечный re-exec — пойман как баг при подготовке фикса, не гипотетический).
#
# ДВЕ ПЕРЕМЕННЫЕ В ALLOWLIST, НИ ОДНОЙ ЛИШНЕЙ (каждая протащенная непроверенной — канал
# протаскивания отравы, например `GIT_CONFIG_GLOBAL` вызывающего вместо `/dev/null` ниже):
#   PATH   — доверенный резолв git/awk/sed/grep/sort/tr/wc/mktemp/mkdir/cp/rm/mv/comm/dirname
#            и всего, что употребляют сорсимые next_id.sh/lib_roles.sh/lib_zones.sh/
#            lib_registry.sh — та же доктрина, что и `export PATH=…` ниже.
#   LC_ALL — контракты и ЗОНА-грамматика несут кириллицу (`ЗОНА `, тексты bad()/ok()); под
#            C-локалью без LC_ALL символьные классы на многобайтовом UTF-8 небезопасны
#            (прецедент `scripts/check_decisions.sh`: «под C-локали кириллица не матчится»).
#            Канон. содержимое — дословно из `check_provodka.sh` (контракт 038, круг 9,
#            verdicts/arbitration/038-vrazhdebnaja-sreda-zapuska.md), переиспользуется, не
#            изобретается заново.
#   HOME и TMPDIR НЕ протаскиваются: ни один прочитанный исходник (этот файл, lib_zones.sh,
#   lib_roles.sh, lib_registry.sh) не обращается к `$HOME` (сверено grep'ом по дереву).
#   Собственный скратч барьера ниже — явный путь С каталогом (`$ROOT/tmp/zones.XXXXXX`),
#   `mktemp` `$TMPDIR` для него не читает; скратч `lib_zones.sh` падает на документированный
#   там же дефолт `${TMPDIR:-/tmp}`. Не протащенный TMPDIR закрывает канал, которым
#   вызывающий подсунул бы барьеру подконтрольный каталог скратча.
#
# CWD НЕ ТРОГАЕТСЯ: ни `env`, ни `bash` не делают `chdir`; дочерний процесс наследует РАБОЧИЙ
# КАТАЛОГ вызывающего через `fork`, а не через переменную `PWD` (`env -i` стирает саму
# переменную `PWD`, но не факт cwd) — относительный аргумент-корень (`${1:-…}` ниже)
# резолвится в ROOT ТОЧНО так же, как до re-exec (живой прогон: запуск из подкаталога с
# относительным `.` даёт тот же ROOT, что и без re-exec).
#
# АБСОЛЮТНЫЕ ПУТИ У `env` И `bash` — ОБЯЗАТЕЛЬНЫ, НО НЕ ДОСТАТОЧНЫ. Слово БЕЗ `/` в позиции
# команды ищется через таблицу ФУНКЦИЙ процесса раньше $PATH — путь со слэшем закрывает ИМЕННО
# этот резолв: подложенный каталог в PATH вызывающего абсолютный путь не достаёт. НО путь со
# слэшем таблицу функций НЕ обходит целиком: bash ДОПУСКАЕТ объявление функции с ЛИТЕРАЛЬНЫМ
# слэшем в имени (`function /usr/bin/env { ...; }`) через файл, сорсимый `BASH_ENV` ДО первой
# строки этого скрипта, и такая функция ПЕРЕХВАТЫВАЕТ вызов по абсолютному пути тем же
# механизмом, что и голое имя (`export -f` этот канал не даёт — `BASH_FUNC_/usr/bin/env%%` bash
# отвергает, но сорсимое объявление не отвергнуто никогда). Опровергнуто арбитром живым замером:
# verdicts/arbitration/contracts-040-vrazhdebnoe-okruzhenie-predel.md, векторы D/E. Абсолютный
# путь — защита от подложенного $PATH-каталога, а НЕ от вызывающего, управляющего
# интерпретатором ДО старта скрипта — см. ЧЕТВЁРТЫЙ ОСТАТОЧНЫЙ РИСК шапки файла.
#
# УПРАВЛЕНИЕ ОПИРАЕТСЯ НА `exec` КАК НА СЛОВО — НАМЕРЕННО, ПОД `POSIXLY_CORRECT=1`. Прежняя
# редакция избегала голого `exec` из опасения, что тень-функция съест переход молчаливым
# no-op'ом; опасение само по себе верно, но купленная взамен `if/else`-форма оказалась
# fail-open — no-op её единственной команды неотличим от успешного re-exec (измерено
# адверсарием: verdicts/adversary/contracts-040-v6-circle.md). Замер арбитра снял опасение по
# ДРУГОМУ пути: присваивание `POSIXLY_CORRECT=1` СТРОКОЙ ВЫШЕ `exec` — не команда, функцией не
# перехватывается — и немедленно включает POSIX-режим, в котором `exec` резолвится как SPECIAL
# BUILTIN раньше пользовательских функций с тем же именем: унаследованная `exec() { return 0;
# }` его больше не перехватывает (прецедент `check_provodka.sh`, контракт 038, круг 9; здесь —
# verdicts/arbitration/contracts-040-vrazhdebnoe-okruzhenie-predel.md, вектор H — тень `exec`
# присутствует, красный сохраняется). РОВНО ОДНА команда с абсолютным путём внутри `if … fi`:
# успешный re-exec заменяет образ процесса и НЕ возвращается; захват АРГУМЕНТА exec (не самого
# exec — slash-функция на `/usr/bin/env`, см. абзац выше) исполняет тело в отравленном процессе
# — это ЧЕТВЁРТЫЙ ОСТАТОЧНЫЙ РИСК шапки файла, не устранимый ни этим, ни любым другим текстом
# внутри скрипта.
#
# СОРСИНГ (`( return 0 2>/dev/null )` в условии) — та же гигиена честного вызова, что у
# `check_provodka.sh` (круг 10, verdicts/arbitration/038-sourced-ispolnenie-granica.md §3):
# сорс этого файла в чужую оболочку с предсуществующим враждебным состоянием (локальные
# функции, `trap … DEBUG`) вне модели угроз этого блока по тому же решению арбитража — этот
# файл нигде в дереве не сорсится как библиотека (сверено grep'ом), проверка — на будущее.
#
# ОСТАТОЧНОЕ: `/proc/$$/environ` — Linux/procfs, тот же прецедент и тот же риск, что уже
# принят в `check_provodka.sh` (окружение исполнения проекта — Linux, CI и рабочая станция).
# ПЕРВЫЙ И ВТОРОЙ ОСТАТОЧНЫЕ РИСКИ шапки файла (`user.name`; подлинность git за пределами
# доверенного PATH) этим фиксом не закрываются и не расширяются — другой класс, см. выше.
if ( return 0 2>/dev/null ) || [[ "$(/usr/bin/tr '\0' '\n' < /proc/$$/environ)" != $'PATH=/usr/bin:/bin\nLC_ALL=C.UTF-8' ]]; then
  POSIXLY_CORRECT=1
  exec /usr/bin/env -i PATH=/usr/bin:/bin LC_ALL=C.UTF-8 /usr/bin/bash "${BASH_SOURCE[0]}" "$@"
fi
