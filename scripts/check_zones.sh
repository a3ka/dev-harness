#!/usr/bin/env bash
# Исполнитель коммитит только в свою зону. Зона объявляется в ЗАМОРОЖЕННОМ контракте, а не в
# задании и не в переписке.
#
# Зачем вообще: `implementer` существует для параллелизма и границ, а не для ловли дефектов
# (измерено: на барьере в 200 строк разделение «спека отдельно, реализация отдельно» дефектов не
# ловит). Границу без механизма исполнитель расширяет молча — «попутно поправил, что попалось», —
# и остаётся дифф, который нечем ревьюить.
#
# ГРАММАТИКА, литерал, первая колонка строки в контракте:
#
#   ЗОНА <имя-автора>: <путь> [<путь>…]
#   РАБОТА НЕ РАЗДАЁТСЯ: <непустая причина>
#
# `<имя-автора>` — git `user.name` агента: агенты коммитят под своими именами (измерено в истории:
# `parity-fixes2`, `IdsFixes2`, `critic`). `<путь>` — каталог с завершающим `/` либо точный файл;
# относительный, без `* ? [`, без `..`, без ведущего `/`. Проверка пути — ЕДИНСТВЕННОЙ реализацией
# `path_prefix_valid` в `lib_roles.sh`, той же, что проверяет `verdict:` у ролей.
#
# ОДНО ИЗ ДВУХ ОБЪЯВЛЕНИЙ ОБЯЗАТЕЛЬНО, И МОЛЧАНИЕ НЕ ГОДИТСЯ. Контракт, который раздаётся, несёт
# `ЗОНА`-строки; контракт, который кодифицирует уже действующее соглашение, несёт
# `РАБОТА НЕ РАЗДАЁТСЯ:` с причиной. Отсутствие обеих — отказ: иначе «зон нет» и «зоны забыли»
# выглядят одинаково, а это разные предметы (правило 7 нормы). Так требование, которое у критика
# было когнитивным, стало механическим.
#
# ЗОНЫ ЧИТАЮТСЯ ИЗ БЛОБА ВЫСШЕЙ ЗАМОРОЗКИ, а не из рабочего дерева: иначе правка файла расширяла бы
# зону без заморозки, то есть исполнитель выдавал бы себе права сам. Черновик зон не даёт.
#
# ДИАПАЗОН — от ПЕРВОЙ заморозки контракта (`frozen/contracts/<NNN>/1..HEAD`), не от высшей: правка
# контракта версией v2 иначе стирала бы зону задним числом вместе с уже проверенными коммитами.
# Зона автора — ОБЪЕДИНЕНИЕ путей, объявленных этому имени во ВСЕХ замороженных контрактах:
# пересечение было бы бессмыслицей, два контракта дают человеку две работы, а не одну общую.
#
# НЕОБЪЯВЛЕННЫЕ АВТОРЫ НЕ ПРОВЕРЯЮТСЯ — владелец и прошлые сессии. Это цена того, чтобы гейт не
# краснел на истории, которую уже нельзя исправить.
#
# МИНТ-ПРИЗНАНИЕ (контракт 031, ветвь ii): путь registry/contracts.tsv под автором orchestrator
# исключается из суда зон ⟺ дельта коммита по этому пути — только-добавление строк грамматики
# манифеста ∧ для каждой строки тег id/CONTRACT/<NNN> жив локально ∧ tag-object-sha == sha
# строки. Иначе — bad() «коммит вне зоны» с теми же именами причин (минт-признание, локальный
# реестр; провенанс НЕ перепроверяется — дверь решила его на входе, прецедент 023 (iv)).
#
# ОСТАТОЧНЫЙ РИСК, помечен `cognitive-only`: `user.name` — не удостоверение. Объявленный исполнитель
# может выйти из зоны, назвавшись новым именем, и барьер этого не увидит по построению. Держится
# тремя вещами: имя в `ЗОНА`-строке пишет АРХИТЕКТОР в контракте, а не исполнитель себе; смена имени
# видна в `git log --format='%an %s'` и входит в область ревьюера; исполнитель коммитит в основной
# репозиторий, то есть его коммиты пересматриваются на приёмке пачки. Ужесточение — подписанные
# коммиты со сверкой ключа и имени — включается словом владельца.
#
# ВТОРОЙ ОСТАТОЧНЫЙ РИСК, тоже `cognitive-only` (арбитраж 040-II, Граница v4 п.6:
# verdicts/arbitration/contracts-040-batching-dostatochnost-oraculu.md): доверенный PATH
# (см. ниже) закрывает ПОЛНОТУ batched-вывода (сверка множеств ключей — author_map/
# paths_raw guards ниже), но НЕ его ПОДЛИННОСТЬ. Подмена `/usr/bin/git` (root-доступ,
# скомпрометированный пакет) либо неподписанные коммиты с произвольным содержимым —
# барьером не проверяются по построению; три независимых замера арбитра (З-B/З-C/З-D)
# доказали, что этот класс НЕ закрывается никакой проверкой ВНУТРИ барьера — сверщик сам
# живёт в TCB того же PATH, что и потенциально подменённый инструмент, а входное
# множество (`git rev-list`) фальсифицируемо ниже по течению от любой сверки. Чек-лист
# А-223 (NABLIUDENIA_ARCHITECT.md): «rc + сверка множеств ключей, И НЕ БОЛЬШЕ —
# подлинность содержимого не предмет вывода-арифметики, предмет границы доверия».
# Ужесточение (signed commits) — словом владельца, как и у риска `user.name` выше.
#
# ТРЕТИЙ ОСТАТОЧНЫЙ РИСК, тоже `cognitive-only` (Н-130, NABLIUDENIA.md; найдено адверсарием
# круга-после-арбитража 040-II, verdicts/adversary/contracts-040-v4-circle.md, `8e6123c`):
# доверенный PATH сам по себе не нейтрализует экспортированную bash-функцию с именем
# доверенной утилиты — bash разрешает функции РАНЬШЕ $PATH. Закрыто явным `unset -f` сразу
# после пина (см. ниже) для всех 14 утилит, употребляемых В ЭТОМ ФАЙЛЕ (тот же список, что
# probe-блок выше); закрытие проверено живым прогоном для того же процесса, вложенных
# `bash -c`, командных подстановок и конвейерных подоболочек. ЧТО ОСТАЁТСЯ НЕЗАКРЫТЫМ:
# сорсимые next_id.sh/lib_roles.sh/lib_zones.sh/lib_registry.sh голо вызывают утилиты ВНЕ
# этого списка — `env`, `basename`, `find`, `date`, `cat`, `sha256sum`, `cut` (измерено
# чтением при подготовке этого фикса) — ни одна не пробуется и не неймится `unset -f` здесь;
# экспортированная функция с ЛЮБЫМ из ЭТИХ имён обходит суд тем же классом. Вне предмета
# этого фикса (список ограничен явно ТЕМИ ЖЕ 14, что несёт probe-блок v4); адресуется
# отдельным заходом — расширением probe/unset-списка на объединение утилит, транзитивно
# употребляемых деревом source'ов, либо переходом на `env -i` с явным re-exec (дороже:
# требует поимённо перечислить каждую легитимно нужную переменную окружения). Алиасы —
# ПРОВЕРЕНО И ЗАКРЫТО, не остаточный риск: канала экспорта алиаса через окружение нет вовсе,
# non-interactive bash не разворачивает алиасы без `shopt -s expand_aliases` (которого здесь
# нет) — оба факта подтверждены живым прогоном.
#
# Merge-коммиты пропускаются; их содержимое — предмет ревью.
#
# РЕФАКТОРИНГ (контракт 016, срез 1): чтение замороженных контрактов и ЗОНА-строк ВЫНЕСЕНО в
# `scripts/lib_zones.sh` — единый читатель формата (прецедент lib_roles/lib_registry). Этот
# барьер остаётся ЗАКОММИЧЕННЫМ по поведению: тексты bad()/ok() — те же, логика СПАСЕНО, фильтр
# процессных файлов и финальный отчёт — на месте; меняется только способ получения zones_scoped.
#
#   bash scripts/check_zones.sh            проверить это дерево
#   bash scripts/check_zones.sh <корень>   проверить другое (так предъявляется красным)
#
# Коды возврата: 0 — выходов за зону нет либо зон не объявлено, 1 — выход за зону или объявление
# вне грамматики, 2 — нечем проверить.
set -euo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_TEMPLATE_DIR GIT_CEILING_DIRECTORIES
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null

# ДОВЕРЕННЫЙ PATH — ДО ПЕРВОЙ ВНЕШНЕЙ КОМАНДЫ (арбитраж 040-II, Граница v4 п.1:
# verdicts/arbitration/contracts-040-batching-dostatochnost-oraculu.md; та же доктрина,
# что check_protected.sh:66-95 с контракта 039). Три круга адверсария на A2-батчинге
# предъявляли PATH-spy — подменённый `git`, резолвящийся через унаследованный $PATH, с
# константным автором либо усечённым выводом; арбитр независимо измерил (З-E): под
# тотальным git-саботажником check_protected.sh продолжает работать (PATH запинен, ноль
# вызовов спая), а ЭТОТ барьер падал (PATH не был запинен). Вектор закрывает ЛЮБУЮ
# внешнюю утилиту ниже, не только git. Фиксируем PATH здесь, ДО первого внешнего вызова
# (`dirname` при вычислении SELF_DIR ниже) — и проверяем наличие КАЖДОЙ употребляемой в
# ЭТОМ файле утилиты по имени: отсутствие даёт именной rc=2, а не необъяснённый крах.
# ОСТАТОЧНЫЙ РИСК подлинности вывода при живом PATH — см. выше, рядом с риском `user.name`.
export PATH=/usr/bin:/bin

# НЕЙТРАЛИЗАЦИЯ ЭКСПОРТИРОВАННЫХ BASH-ФУНКЦИЙ — СРАЗУ ПОСЛЕ ПИНА, ДО ПЕРВОГО ВНЕШНЕГО ВЫЗОВА
# (Н-130, NABLIUDENIA.md; найдено адверсарием круга-после-арбитража 040-II,
# verdicts/adversary/contracts-040-v4-circle.md, `8e6123c`). Доверенный PATH выше НЕ
# обесточивает экспортированную bash-функцию с именем доверенной утилиты: bash разрешает
# функции РАНЬШЕ $PATH при старте ЛЮБОГО дочернего bash, и унаследованная `export -f git`
# (либо сырой env `BASH_FUNC_git%%=() {...}`, тот же механизм сериализации, что Shellshock)
# переживает `export PATH=...` и перехватывает каждый голый вызов имени — внутри ЭТОГО
# процесса, вложенных `bash -c`, командных подстановок `$(...)` и конвейерных подоболочек
# (все три формы проверены живым прогоном при подготовке фикса). `command git` — ОДИН вызов
# действительно обходит функцию (проверено живьём), но не лекарство ДЛЯ КЛАССА: голых
# вызовов этих 14 имён десятки, разбросаны по этому файлу и по сорсимым
# next_id.sh/lib_roles.sh/lib_zones.sh/lib_registry.sh, и переписывать каждый — та же
# хрупкость, что у пропущенного абсолютного пути: упущенный call-сайт — дыра, и её находит
# не тот, кто писал строку. `unset -f` — ОДНА точка отказа на ВСЕ call-сайты сразу: снимает
# функцию из таблицы ЭТОГО процесса И её экспортный бит, поэтому дальнейшие форкнутые
# подпроцессы (`$(...)`, конвейеры) И заново запущенные дочерние bash (`bash -c`) резолвят
# голое имя снова через доверенный PATH — оба пути проверены живым прогоном. `unset -f` на
# функции, которой нет, возвращает rc=0 (не роняет `set -e` этого файла) — суффикс
# `2>/dev/null || true` здесь для явности читателю, а не потому что команда способна отказать.
# Алиасы — НЕ вектор: канала сериализации алиаса через окружение нет вовсе (`BASH_FUNC_*%%` —
# механизм только для функций), и non-interactive bash не разворачивает алиасы без
# `shopt -s expand_aliases`, которого в этом файле нет, — оба факта проверены живым прогоном
# отдельно. Что этой строкой НЕ закрыто — см. ТРЕТИЙ ОСТАТОЧНЫЙ РИСК в шапке файла выше.
unset -f dirname git awk sed grep sort tr wc mktemp mkdir cp rm mv comm 2>/dev/null || true

skip() { printf 'NOT_IMPLEMENTED: %s\n' "$*" >&2; exit 2; }
command -v dirname >/dev/null 2>&1 || skip "нет dirname в доверенном PATH — путь скрипта нечем вычислить"
command -v git     >/dev/null 2>&1 || skip "нет git в доверенном PATH — историю коммитов нечем читать"
command -v awk     >/dev/null 2>&1 || skip "нет awk в доверенном PATH — разбор зон, авторов и путей нечем вести"
command -v sed     >/dev/null 2>&1 || skip "нет sed в доверенном PATH — хунк-парсер минт-дельты нечем вести"
command -v grep    >/dev/null 2>&1 || skip "нет grep в доверенном PATH — фильтрацию строк нечем вести"
command -v sort    >/dev/null 2>&1 || skip "нет sort в доверенном PATH — множества коммитов и авторов нечем упорядочить"
command -v tr      >/dev/null 2>&1 || skip "нет tr в доверенном PATH — служебную очистку строк нечем вести"
command -v wc      >/dev/null 2>&1 || skip "нет wc в доверенном PATH — счёт строк нечем вести"
command -v mktemp  >/dev/null 2>&1 || skip "нет mktemp в доверенном PATH — скратч-каталог нечем создать"
command -v mkdir   >/dev/null 2>&1 || skip "нет mkdir в доверенном PATH — tmp/ нечем создать"
command -v cp      >/dev/null 2>&1 || skip "нет cp в доверенном PATH — вывод zones_load нечем скопировать"
command -v rm      >/dev/null 2>&1 || skip "нет rm в доверенном PATH — скратч нечем убрать"
command -v mv      >/dev/null 2>&1 || skip "нет mv в доверенном PATH — промежуточные файлы нечем переименовать"
command -v comm    >/dev/null 2>&1 || skip "нет comm в доверенном PATH — разность судимых и исключённых коммитов нечем считать"

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
NEXT_ID_LIB=1
# shellcheck disable=SC1091
. "$SELF_DIR/next_id.sh"
# shellcheck disable=SC1091
. "$SELF_DIR/lib_roles.sh"
# shellcheck disable=SC1091
. "$SELF_DIR/lib_zones.sh"

ROOT="$(cd "${1:-"$SELF_DIR/.."}" && pwd)"
# LIB_ZONES_ROOT — канонический корень, от которого __lib_zones_cleanup вычисляет
# путь маркера (см. __lib_zones_paths в lib_zones.sh; скратч и маркер лежат ВНЕ корня
# — канон 014). Задаётся сразу после вычисления ROOT — до первого вызова zones_load.
LIB_ZONES_ROOT="$ROOT"

fails=0
ok()   { printf '  ok   %s\n' "$*" >&2; }
bad()  { fails=$((fails + 1)); printf '  FAIL %s\n' "$*" >&2; }
# shellcheck disable=SC1091
. "$SELF_DIR/lib_registry.sh"

command -v git >/dev/null 2>&1 || skip "нет git — историю коммитов прочитать нечем"
git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1 || skip "$ROOT не репозиторий git"
git -C "$ROOT" rev-parse --verify HEAD >/dev/null 2>&1 || skip "в $ROOT нет ни одного коммита"

g() { git -C "$ROOT" "$@"; }

# Чтение зон через ЕДИНСТВЕННУЮ реализацию lib_zones.sh (контракт 016, срез 1).
# registry_state уже проверен внутри zones_load; здесь его повторять не нужно.
mkdir -p "$ROOT/tmp"
TMP="$(mktemp -d "$ROOT/tmp/zones.XXXXXX")"
# Цепочка: __lib_zones_cleanup снимает скратч lib_zones (через маркер ВНЕ корня —
# ${LIB_ZONES_BASE:-/tmp}/lib_zones.<hash8>.active, см. lib_zones.sh), затем
# `rm -rf "$TMP"` — снимает СВОЙ скратч. Без цепочки установленный ниже
# `trap '...' EXIT` затирал бы уборку lib_zones.
trap '__lib_zones_cleanup; rm -rf "$TMP"' EXIT

# Реестр заморозок проверяется ДО zones_load: на shallow/missing-клоне выдаём rc=1
# с НАЗВАННОЙ причиной (замороженная ветвь), а не rc=2 NOT_IMPLEMENTED — пусто-зелёный
# гейт хуже красного (прецедент case_reestr_nedostupen).
state="$(registry_state "$ROOT" 'frozen/')"
case "$state" in
  full|unknown-remote) ;;
  *)
    printf 'ОТКАЗ: реестр заморозок (refs/tags/frozen/*) недоступен: %s\n' "$state" >&2
    printf 'Лечится: %s\n' "$(registry_cure "$state")" >&2
    printf 'Без реестра зоны не читаются, и барьер стал бы пусто-зелёным.\n' >&2
    exit 1
    ;;
esac

# Чтение зон через ЕДИНСТВЕННУЮ реализацию lib_zones.sh (контракт 016, срез 1).
out="$(zones_load "$ROOT" 2>/dev/null)" || {
  printf 'NOT_IMPLEMENTED: реестр заморозок недоступен\n' >&2; exit 2; }
cp "$out/zones_scoped"    "$TMP/zones_scoped"
cp "$out/zones_violations" "$TMP/zones_violations"
cp "$out/ranges"          "$TMP/ranges"
cp "$out/contracts_list"  "$TMP/contracts_list"
contracts=$(wc -l < "$TMP/contracts_list" | tr -d ' ')
: > "$TMP/saved"
: > "$TMP/process_excluded"
# Список тегов refs/tags/frozen/contracts/ — для СПАСЕНО-логики ниже.
g for-each-ref --format='%(refname)' 'refs/tags/frozen/contracts/' 2>/dev/null | sort > "$TMP/tags" || true
# контракт, файл, причина, автор, путь, сырая_строка. awk парсит с FS=\0
# (внутри строки табуляция не рвёт поле, как и в `read -d '' nnn file ...`).
# Чтение NUL-разделённых нарушений ЗОНА. Каждая запись — 6 полей, разделённых \0:
# контракт, файл, причина, автор, путь, сырая_строка. awk парсит с FS=\0
# (внутри строки табуляция не рвёт поле, как и в `read -d '' nnn file ...`).
awk -v FS='\0' 'NF >= 3 {
  reason = $3
  file = $2; author = $4; path = $5; raw_line = $6
  if (reason == "bad_author")
    printf("строка ЗОНА вне объявленной грамматики в %s: «%s» — нужно «ЗОНА <имя-автора>: <путь> [<путь>…]»\n", file, raw_line)
  else if (reason == "tab_in_author")
    printf("строка ЗОНА вне объявленной грамматики в %s: имя автора «%s» содержит табуляцию — имя сериализуется как TSV-поле и разделитель в нём не живёт\n", file, author)
  else if (reason == "no_paths")
    printf("строка ЗОНА вне объявленной грамматики в %s: «%s» — у автора «%s» не назван ни один путь\n", file, raw_line, author)
  else if (reason == "quote_in_path")
    printf("строка ЗОНА вне объявленной грамматики в %s: путь «%s» у автора «%s» содержит кавычку — пути разделены пробелами, кавычек грамматика не несёт\n", file, path, author)
  else if (reason == "bad_prefix")
    printf("строка ЗОНА вне объявленной грамматики в %s: путь «%s» у автора «%s» — путь обязан быть относительным, без шаблонов, .. и пробелов; каталог завершается /\n", file, path, author)
}' "$TMP/zones_violations" | while IFS= read -r line; do bad "$line"; done
# Зелёное НАЗЫВАЕТСЯ. Сводка зон по контрактам с правильным $file — для отчёта. Замороженная
# ветвь: зелёное должно быть названо, иначе молчаливый барьер неотличим из не видящего файл.
if [ "$fails" -eq 0 ]; then
  # (no ok-prints yet at this stage; they appear later per-contract)
  :
fi

# РАБОТА НЕ РАЗДАЁТСЯ + СПАСЕНО — замороженная ветвь, остаётся в check_zones. Чтение тела
# контракта остаётся здесь (для сообщений ok() с привязкой к файлу).
while IFS= read -r nnn; do
  [ -n "$nnn" ] || continue
  vmax=0
  while IFS= read -r t; do
    if [[ "$t" =~ ^refs/tags/frozen/contracts/${nnn}/([0-9]+)$ ]]; then
      k=$((10#${BASH_REMATCH[1]}))
      [ "$k" -gt "$vmax" ] && vmax="$k"
    fi
  done < "$TMP/tags"
  [ "$vmax" -gt 0 ] || continue
  file="$(g ls-tree -r --name-only "refs/tags/frozen/contracts/$nnn/$vmax^{commit}" -- ':(literal)contracts/' 2>/dev/null \
          | awk -v n="$nnn" 'index($0, "contracts/" n "-") == 1 { print; exit }')"
  [ -n "$file" ] || continue
  body="$(g cat-file -p "refs/tags/frozen/contracts/$nnn/$vmax^{commit}:$file" 2>/dev/null || true)"

  declared=0
  # Объявлен ли вообще хоть один ЗОНА для этого контракта?
  if awk -F'\t' -v n="$nnn" '$3 == n' "$TMP/zones_scoped" | grep -q .; then declared=1; fi
  # РАБОТА НЕ РАЗДАЁТСЯ
  while IFS= read -r line; do
    declared=1
    reason="${line#РАБОТА НЕ РАЗДАЁТСЯ:}"
    if [ -z "${reason//[[:space:]]/}" ]; then
      bad "строка РАБОТА НЕ РАЗДАЁТСЯ вне объявленной грамматики в $file: причина пуста — объявление без причины неотличимо из опечатки"
    else
      ok "$file — работа не раздаётся:${reason}"
    fi
  done < <(printf '%s\n' "$body" | grep '^РАБОТА НЕ РАЗДАЁТСЯ:' || true)

  # СПАСЕНО — замороженная ветвь. Грамматика контракта 003 v3 (решение арбитража):
  # «СПАСЕНО <автор>: <полные 40-символьные хеши через пробел> — <непустая причина>».
  s_until="HEAD"
  if g rev-parse --verify --quiet "refs/tags/done/contracts/$nnn/1" >/dev/null 2>&1; then
    s_until="refs/tags/done/contracts/$nnn/1"
  fi
  while IFS= read -r line; do
    rest="${line#СПАСЕНО }"
    s_author="${rest%%:*}"
    s_tail="${rest#*:}"
    if [ "$s_author" = "$rest" ] || [ -z "${s_author//[[:space:]]/}" ] || [[ "$s_author" == *$'\t'* ]]; then
      bad "строка СПАСЕНО вне объявленной грамматики в $file: «$line» — нужно «СПАСЕНО <автор>: <полные хеши> — <причина>»"
      continue
    fi
    if ! awk -F'\t' -v a="$s_author" -v n="$nnn" '$1 == a && $3 == n { f=1 } END { exit(f ? 0 : 1) }' "$TMP/zones_scoped"; then
      bad "строка СПАСЕНО вне объявленной грамматики в $file: автор «$s_author» не объявлен ЗОНА-строкой этого контракта"
      continue
    fi
    case "$s_tail" in
      *—*) s_hashes="${s_tail%%—*}"; s_reason="${s_tail#*—}" ;;
      *)   bad "строка СПАСЕНО вне объявленной грамматики в $file: «$line» — нет «— <причина>»"; continue ;;
    esac
    if [ -z "${s_reason//[[:space:]]/}" ]; then
      bad "строка СПАСЕНО вне объявленной грамматики в $file: причина пуста — объявление без причины неотличимо из опечатки"
      continue
    fi
    set -f
    for h in $s_hashes; do
      case "$h" in
        *'"'*) bad "строка СПАСЕНО вне объявленной грамматики в $file: хеш «$h» содержит кавычку" ;;
      esac
      if ! [[ "$h" =~ ^[0-9a-f]{40}$ ]]; then
        bad "строка СПАСЕНО вне объявленной грамматики в $file: «$h» — не полный 40-символьный hex"
        continue
      fi
      if ! g cat-file -e "$h^{commit}" 2>/dev/null; then
        bad "строка СПАСЕНО в $file называет несуществующий коммит «$h»"
        continue
      fi
      g merge-base --is-ancestor "refs/tags/frozen/contracts/$nnn/1" "$h" 2>/dev/null \
        && g merge-base --is-ancestor "$h" "$s_until" 2>/dev/null || {
          bad "строка СПАСЕНО в $file называет коммит «$h» вне диапазона контракта (frozen/contracts/$nnn/1..$s_until)"
          continue
        }
      printf '%s\t%s\t%s\n' "$s_author" "$h" "$nnn" >> "$TMP/saved"
    done
    set +f
  done < <(printf '%s\n' "$body" | grep '^СПАСЕНО ' || true)
  if [ "$declared" -eq 0 ]; then
    bad "$file: контракт не объявил ни зон, ни отказа от раздачи — нужна строка «ЗОНА <автор>: <путь>» либо «РАБОТА НЕ РАЗДАЁТСЯ: <причина>». Молчание не годится: «зон нет» и «зоны забыли» выглядят одинаково"
  fi
done < "$TMP/contracts_list"

if [ ! -s "$TMP/zones_scoped" ]; then
  printf '\nзамороженных контрактов: %d · зон не объявлено — проверять нечего\n' "$contracts" >&2
  [ "$fails" -eq 0 ] || exit 1
  exit 0
fi

