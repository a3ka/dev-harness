# ── обход коммитов в диапазонах ───────────────────────────────────────────────
# Семантика ОТКРЫТОГО окна контракта (контракт 021, ветвь А):
#   судимое множество = прямые не-merge первого-родителя в диапазоне
#   ∪ коммиты, принесённые merge'ями с маркером `land: wip/<NNN>/<author>`
#     в первой строке (%s) — `rev-list <merge>^1..<merge> --no-merges`
#     (тот же родительский примитив, что charter И-7).
#   merge'и с чужим маркером (`wip/<OTHER>/…`) НЕ приносят коммиты в
#   окно N — линейный rev-list --no-merges --reverse уходит (захватывал
#   чужие merge-принесённые, измеренная боль Н-66).
#   Прочие правки логики суда (авторы → зоны → дельта путей) — НЕ здесь.
# draft-признание (контракт 023, ветвь iv, обобщение 021 / чинит А-89): суд путей
#   дельты идёт ПО НОМЕРУ ПУТИ M (не номеру ОКОНА nnn): каждая рука читает свой M.
#   рука А — тег id/CONTRACT/<M> указывает НА САМОМ судимом коммите C (обобщение
#     ручной 021 с «номера окна» на «номер пути»: покрывает А-89 «draft в чужом
#     открытом окне» и исторические теги-на-коммите 020/021);
#   рука Б — тег id/CONTRACT/<M> жив ∧ его коммит is-ancestor C ∧ НЕТ
#     frozen/contracts/<M>/* в предках C (новая форма: итерации резерва до
#     заморозки M; после заморозки M итерации НЕ признаются — путь судится зонами);
#   исключается ТОЛЬКО путь contracts/<M>-*; прочие пути того же коммита судятся
#   обычным порядком — тег не индульгенция на весь коммит (инвариант 021 :337-339
#   сохранён дословно). Ретро-СТАБИЛЬНО: предикат зависит только из предков
#   судимого коммита, не из текущего HEAD. Признание (iv) читает ЛОКАЛЬНЫЙ реестр
#   (существование тега) — провенанс не проверяет: аудит истории судит уже
#   закоммиченное, дверь (iii) уже решила вопрос провенанса на входе.
# минт-признание (контракт 031, ветвь ii): для пути registry/contracts.tsv под
#   автором orchestrator путь исключается из суда зон ⟺ дельта коммита по этому
#   пути — только-добавление строк грамматики манифеста ∧ для каждой строки тег
#   id/CONTRACT/<NNN> жив локально ∧ tag-object-sha == sha строки. Провенанс на
#   origin НЕ перепроверяется (дверь 031 (i) решила его на входе). Иначе — bad()
#   «коммит вне зоны» с теми же именами причин, что у двери 031 (минт-признание,
#   локальный реестр). Fail-closed чтения локального реестра: тег, удалённый из
#   локального реестра к моменту аудита, красит признание — лечение восстановлением
#   тега, НЕ ослаблением признания (прецедент 023 (iv)).
commits=0; checked=0
while IFS=$'\t' read -r nnn since; do
  [ -n "$nnn" ] || continue
  until="${since#*..}"
  [ "$until" = "$since" ] && until=""
  since="${since%%..*}"
  awk -F'\t' -v n="$nnn" '$3 == n { print $1 }' "$TMP/zones_scoped" | sort -u > "$TMP/authors"
  [ -s "$TMP/authors" ] || continue
  range="$since..HEAD"
  [ -n "$until" ] && range="$since..$until"
  # Линейный rev-list (как раньше) — для контрактов с ЗАКРЫТЫМИ окнами и
  # без чужих wip/<OTHER>/… merge'ей даёт ту же сводку (регресс-инвариант
  # ветви Г; для 017/019 merge'и без `land:` маркера тоже остаются).
  if ! g rev-list --no-merges --reverse "$range" > "$TMP/commits" 2>/dev/null; then
    printf 'ОТКАЗ: git rev-list --no-merges --reverse отказал (контракт %s, диапазон %s) — список судимых коммитов окна недоступен.\n' "$nnn" "$range" >&2
    printf 'Лечится: диагностируйте git-окружение (PATH, версия git, доступность объектной базы) и повторите прогон.\n' >&2
    printf 'Без списка коммитов окно стало бы пусто-зелёным — это дороже красного (прецедент case_reestr_nedostupen, тот же класс, что круг 1 контракта 040, арбитраж 040-II п.3).\n' >&2
    exit 1
  fi
  # Исключаем коммиты, принесённые ЧУЖИМИ wip-merge'ями (`land: wip/<OTHER>/…`):
  # в последовательной истории таких нет, регресс закрытых контрактов
  # держится; в открытом окне с cross-track касанием они уходят. Merge'и
  # БЕЗ `land:` маркера (admin merge, intra-wip сведение) трактуются как
  # внутренние — НЕ исключаем (та же семантика, что в линейной модели).
  : > "$TMP/exclude"
  g rev-list --merges "$range" 2>/dev/null | while IFS= read -r mc; do
    [ -n "$mc" ] || continue
    msg="$(g log -1 --format=%s "$mc" 2>/dev/null)"
    case "$msg" in
      "land: wip/${nnn}/"*) ;;  # свой merge — НЕ исключаем
      "land: wip/"*) g rev-list --no-merges "${mc}^1..${mc}" 2>/dev/null >> "$TMP/exclude" ;;
    esac
  done
  sort -u "$TMP/exclude" -o "$TMP/exclude"
  if [ -s "$TMP/exclude" ]; then
    # comm требует лекс-сортировки обоих входов; $TMP/commits хранит хронологию (--reverse),
    # поэтому фильтруем через лекс-сортированную копию — множество судимых коммитов неизменно,
    # хронологический обход цикла суда сохранён.
    sort -u "$TMP/commits" -o "$TMP/commits_sorted"
    comm -23 "$TMP/commits_sorted" "$TMP/exclude" > "$TMP/judged"
    mv "$TMP/judged" "$TMP/commits"
  fi

  # ── A2 BATCHING (контракт 040, §Инварианты п.1) ───────────────────────────────
  # Два метаданных на коммит — автор коммита (раньше: per-commit `g log -1 --format='%an' "$c"`,
  # `:333`) и список путей дельты (раньше: per-commit `g diff-tree -r --no-commit-id --name-only
  # --no-renames "$c"`, `:472`) — извлекаются ОДНИМ batched-запросом НА ОКНО. Число git-вызовов
  # ВНУТРИ окна перестаёт зависеть от числа коммитов: было N (автор) + N (diff-tree) = 2N,
  # стало 2 (по одному batched-вызову на мету). Решающая логика, bad()/ok(), СПАСЕНО,
  # merge-исключение по `land: wip/<OTHER>/…`, draft/минт-признания и фильтр процессных файлов
  # остаются БАЙТ-В-БАЙТ: меняется ТОЛЬКО способ добычи двух мет; редкие ветви
  # (draft/минт/СПАСЕНО-ancestry) по-прежнему линейны по ЗАТРОНУТЫМ путям/контрактам, не по
  # общему числу коммитов (§Инварианты п.1 явно).
  #
  # ОБА batched-запроса ниже ОДИНАКОВЫЕ для ЛЮБОГО числа коммитов в $TMP/commits: форма
  # `--no-walk --stdin` для `git log` сохраняет порядок stdin→stdout; форма `--stdin`
  # для `git diff-tree` БЕЗ `--no-commit-id` (default) выводит SHA-заголовок перед блоком
  # путей — это эквивалент per-commit-семантики (для пустого коммита — 0 путей, что
  # совпадает с тем, что даёт `git diff-tree --no-commit-id --name-only <root>`). Флаги
  # `--root -m` НЕ ставим: они включают файлы корневого коммита и merge-only-пути, чего
  # per-commit-форма НЕ возвращает — для check_protected те же флаги ОБЯЗАТЕЛЬНЫ
  # (§Инварианты п.5), там семантика другая.

  # 1. БATCHED author lookup (вместо per-commit log -1): один git-вызов на ОКНО.
  #    `--no-walk --stdin` сохраняет порядок строк stdin → строк stdout; формат
  #    `%H%x00%an%x00` кладёт SHA и автора через NUL-разделитель (автор может
  #    содержать пробелы — TAB-разделение ненадёжно). Неудача команды — FAIL-CLOSED,
  #    НЕ пустой map (v2-fix контракта 040, адверсарий круг 1:
  #    verdicts/adversary/contracts-040-oracle-a2-diff-tree.md). Прежняя редакция
  #    подставляла пустой author_nul на любом rc≠0 команды — тогда ВСЕ коммиты окна
  #    теряли автора одинаково с «не судимым», нарушитель исчезал ИЗ СУДА ЗОН
  #    целиком, а барьер отвечал rc=0 (живой toy: honest rc=1, poisoned rc=0 на
  #    PATH-spy, возвращающем 127 ТОЛЬКО на --no-walk). Тот же класс и то же
  #    лекарство, что «реестр заморозок недоступен» выше (прецедент
  #    case_reestr_nedostupen): пусто-зелёный гейт хуже красного — отказ команды
  #    останавливает ЭТО ОКНО именованным exit 1 (код ниже), а не подставляет
  #    пустой файл.
  #
  #    ГАРД на пустом списке судимых коммитов: `git log --no-walk --format=… --stdin`
  #    с ПУСТЫМ stdin возвращает запись ТЕКУЩЕГО HEAD (fallback-поведение голого stdin
  #    у git log) — не пустой вывод. На пустом окне такая «лишняя» запись привела бы
  #    к ложному совпадению HEAD_sha с $TMP/authors (если автор HEAD — зонный) и к
  #    холостому вызову diff-tree по HEAD; внутренний цикл читает $TMP/commits (тут
  #    пусто), так что к checked-счётчику это не идёт, но лишний git-вызов и лишняя
  #    запись в $TMP/matched_commits — мусор, которого допускать нельзя (та же
  #    причина, по которой для diff-tree уже стоит `[ -s "$TMP/matched_commits" ]`).
  if [ -s "$TMP/commits" ]; then
    if ! g log --no-walk --format='%H%x00%an%x00' --stdin < "$TMP/commits" \
        > "$TMP/author_nul" 2>/dev/null; then
      printf 'ОТКАЗ: batched git log --no-walk --stdin отказал (контракт %s, диапазон %s) — список авторов окна недоступен.\n' "$nnn" "$range" >&2
      printf 'Лечится: диагностируйте git-окружение (PATH, версия git, доступность объектной базы) и повторите прогон.\n' >&2
      printf 'Без списка авторов совпадения по автору не находятся, и окно стало бы пусто-зелёным — это дороже красного (прецедент case_reestr_nedostupen).\n' >&2
      exit 1
    fi
  else
    : > "$TMP/author_nul"
  fi
  # Разбор NUL-record'ов попарно в TAB-разделённый map sha TAB author.
  # `git log` ставит '\n' ПОСЛЕ каждой пары `\0\0` (запись формата «%H%x00%an%x00\n»
  # на коммит): если этого '\n' не снять, awk с RS='\0' увидит следующий SHA как
  # record «\n<sha>», regex /^[0-9a-f]{40}$/ не совпадёт, и ВСЕ записи кроме первой
  # будут отброшены — author_map потеряет N-1 из N записей, и `checked` рухнет
  # (замерено на реальном дереве: 19 вместо 1046). tr -d '\n' снимает разделители
  # строк; имя автора '\n' по грамматике git log не содержит, искажение полей
  # исключено.
  tr -d '\n' < "$TMP/author_nul" > "$TMP/author_nul.tmp" && mv "$TMP/author_nul.tmp" "$TMP/author_nul"
  awk -v RS='\0' '
    (NR % 2 == 1) && /^[0-9a-f]{40}$/ { sha = $0; next }
    (NR % 2 == 0) && sha != ""        { printf("%s\t%s\n", sha, $0); sha = "" }
  ' "$TMP/author_nul" > "$TMP/author_map" || : > "$TMP/author_map"
  # ── A2 completeness guard (контракт 040 круг 2 адверсария,
  #    verdicts/adversary/contracts-040-oracle-a2-diff-tree-v2.md) ─────────
  # Успешный (rc=0) batched-вызов НЕ доказывает ПОЛНЫЙ вывод: PATH-spy может
  # делегировать реальному git и всё же оборвать stdout после ПЕРВОЙ
  # синтаксически валидной NUL-записи, вернув rc=0 — «отказ, выглядящий
  # успехом» без сигнала в самом rc (живой обход адверсария: honest даёт
  # 2 записи, poisoned — только первую, оба rc=0). Разбор выше строит
  # author_map ТОЛЬКО из того, что реально пришло; SHA, отсечённый
  # усечением, уходит в ТУ ЖЕ ветвь `[ -n "$an" ] || continue` (:432), что
  # и легитимно-неавторские коммиты — нарушитель молча пропадает из суда.
  # Сравнение ЧИСЕЛ (строк на входе против записей на выходе) недостаточно:
  # перестановка или дубликат-с-пропуском-иного сохраняют равенство
  # счётчиков при неполном множестве. Лекарство — СВЕРКА МНОЖЕСТВ ключей:
  # ассоциативный массив по SHA из author_map против множества SHA из
  # $TMP/commits — каждый требуемый SHA обязан иметь РОВНО ОДНУ запись.
  # Несовпадение (нехватка ИЛИ задвоение) — ТОТ ЖЕ именованный fail-closed
  # класс и код возврата, что явный отказ команды выше: один симптом того
  # же корня («batched-вывод авторов окна недостоверен»), а не отдельный
  # барьер на отдельный повод. Ноль дополнительных git-вызовов — сверка
  # идёт по уже полученным файлам этого же окна.
  awk -F'\t' '
    NR == FNR { if ($1 != "") want[$1] = 1; next }
    { seen[$1]++ }
    END {
      missing = 0; dup = 0
      for (s in want) {
        if (!(s in seen))      missing++
        else if (seen[s] != 1) dup++
      }
      printf("%d\t%d\n", missing, dup)
    }
  ' "$TMP/commits" "$TMP/author_map" > "$TMP/author_map_completeness"
  IFS=$'\t' read -r missing_shas dup_shas < "$TMP/author_map_completeness"
  if [ "${missing_shas:-0}" -gt 0 ] || [ "${dup_shas:-0}" -gt 0 ]; then
    printf 'ОТКАЗ: batched git log --no-walk --stdin вернул неполный поток (контракт %s, диапазон %s) — %s SHA без записи автора, %s SHA с более чем одной записью; список авторов окна недостоверен.\n' \
      "$nnn" "$range" "${missing_shas:-0}" "${dup_shas:-0}" >&2
    printf 'Лечится: диагностируйте git-окружение (PATH, версия git, доступность объектной базы) и повторите прогон.\n' >&2
    printf 'Частичный, но синтаксически валидный успешный вывод опаснее явного отказа — недостающая запись сделала бы нарушителя невидимым (verdicts/adversary/contracts-040-oracle-a2-diff-tree-v2.md).\n' >&2
    exit 1
  fi

  # Хронологический список коммитов, чей автор — в $TMP/authors (зоны окна).
  # Автор-фильтрация СНИМАЕТСЯ из горячего цикла: --no-merges --reverse отдал
  # $TMP/commits в хронологическом порядке; awk не нарушает порядок. Дедупликация
  # (seen[$1]++) — защита от повторов в $TMP/commits, которые не должны возникать,
  # но если возникнут, батчинг потеряет не более одной записи.
  awk -F'\t' '
    NR==FNR { z[$1]=1; next }
    ($2 in z) { if (!seen[$1]++) print $1 }
  ' "$TMP/authors" "$TMP/author_map" > "$TMP/matched_commits"

  # 2. БATCHED diff-tree (вместо per-commit diff-tree): один git-вызов на ОКНО.
  #    `--always` (арбитраж 040-II, Граница v4 п.2: verdicts/arbitration/
  #    contracts-040-batching-dostatochnost-oraculu.md, замер З-A) печатает SHA-заголовок
  #    ДЛЯ КАЖДОГО входного SHA, включая root и коммит с нулевым диффом против родителя —
  #    без этого флага такой коммит пропускался БЕЗ заголовка вовсе, и «SHA отсутствует в
  #    paths_raw» было структурно неразличимо между «легитимно пустой/root коммит» и
  #    «обрезан атакой» (незакрытый сосед-риск А-223, назван architect'ом в круге 2, не
  #    адверсарием). С `--always` пути такого коммита остаются 0 строк (per-commit-
  #    семантика «0 путей» сохранена байт-в-байт, замер З-A) — меняется ТОЛЬКО
  #    присутствие заголовка. `--no-renames` — для детерминизма относительно
  #    `diff.renames` конфига машины читателя (та же причина, что уже записана в
  #    check_protected.sh для `excuse_for`/`moved_for`).
  if [ -s "$TMP/matched_commits" ]; then
    # `-z` (адверсарий круг 7, находка 1: verdicts/adversary/contracts-040-v7-circle.md)
    # ОБЯЗАТЕЛЕН: без него git КВОТИРУЕТ путь в двойные кавычки с C-style-эскейпами, как
    # только в имени встречается non-ASCII байт (`scripts/é.sh` → `"scripts/\303\251.sh"`,
    # октальный эскейп КАЖДОГО байта UTF-8) ИЛИ управляющий символ вроде LF
    # (`line<LF>break.sh` → `"line\nbreak.sh"`, где `\n` здесь — ДВА печатных символа `\`
    # и `n`, а НЕ байт 0x0A — живой замер `od -c` различает эти формы байт-в-байт).
    # Сравнение такого квотированного текста с НЕэкранированным путём зоны ложно красит
    # честный коммит — находка 1 предъявила ОБА случая («Честный файл с LF в имени
    # красится тем же механизмом»). `-z` печатает путь ВЕРБАТИМ (сырыми байтами, включая
    # настоящий LF-байт внутри имени) и разделяет ВСЕ записи потока (и заголовки, и пути)
    # байтом NUL — путь не может содержать NUL (git/POSIX это запрещают), значит NUL
    # остаётся ЕДИНСТВЕННЫМ безопасным разделителем независимо от того, какие байты несёт
    # само имя; та же доктрина, что уже применена author-стороне батчинга чуть выше
    # (`%x00`-формат). `core.quotePath=false` НЕ выбран: он отключает квотирование ТОЛЬКО
    # для байтов ≥0x80 (git-doc), а LF/TAB/кавычка/бэкслеш квотируются ВСЕГДА независимо
    # от quotePath (живой замер: `-c core.quotePath=false` БЕЗ `-z` всё ещё даёт
    # `"line\nbreak.sh"` для LF-имени) — `-z` закрывает оба подкласса одним флагом,
    # `core.quotePath=false` закрыл бы только non-ASCII-подкласс.
    g diff-tree -r --no-renames --name-only --always -z --stdin \
      < "$TMP/matched_commits" > "$TMP/paths_raw"
  else
    : > "$TMP/paths_raw"
  fi

  # ── A2 paths_raw completeness + позиционный разбор блоков ───────────────────────
  # Арбитраж 040-II, Граница v4 п.2 задал полноту; адверсарий круга 7 (находка 2:
  # verdicts/adversary/contracts-040-v7-circle.md) предъявил, что СТАРАЯ форма отличала
  # SHA-заголовок от строки-пути РЕГЭКСПОМ `/^[0-9a-f]{40}$/` — ПО ФОРМЕ значения.
  # Легальное имя файла из ровно 40 hex-символов (git/POSIX это разрешают; находка
  # предъявила top-level `aaaa…aaaa`, РАВНЫЙ объявленной зоне) неотличимо от SHA ПО
  # ФОРМЕ — только ПО ПОЗИЦИИ в потоке. Разбор ниже классифицирует запись не шаблоном,
  # а ДВУМЯ структурными фактами: (1) `git diff-tree --stdin` читает и печатает коммиты
  # ПО ОДНОМУ, В ТОМ ЖЕ ПОРЯДКЕ, в каком они пришли на stdin — эмпирически проверено
  # (`od -c` на дереве с шестью коммитами: порядок блоков совпал с порядком stdin
  # байт-в-байт) — то же потоковое свойство, на которое уже опирается author-сторона
  # батчинга («--no-walk --stdin для git log сохраняет порядок stdin→stdout», см. выше);
  # (2) `$TMP/matched_commits` — ТОТ ЖЕ файл, что подан на `--stdin` diff-tree выше,
  # значит его строки, ПО ПОРЯДКУ, это ТОЧНО ожидаемая последовательность заголовков.
  # Запись классифицируется заголовком блока N ⟺ она равна N-й (по счёту уже
  # поглощённых заголовков) строке `matched_commits` — сравнение СТРОГО ПОЗИЦИОННОЕ (со
  # СЛЕДУЮЩИМ ожидаемым SHA, не «с любым SHA из множества»): sha коммита-потомка
  # криптографически зависит от дерева/содержимого коммита-предка через цепочку
  # `parent <sha>` — изменение содержимого предка меняет sha ЛЮБОГО потомка, поэтому
  # предок не может предъявить (без разрыва хеш-функции) sha ЕЩЁ НЕ СУЩЕСТВУЮЩЕГО
  # потомка КАК СВОЙ путь; легальный путь, случайно совпадающий с ЧУЖИМ (не текущим
  # ожидаемым) элементом множества — например, с sha уже поглощённого предка, — не
  # смещает границу блока, а лишь бракует запись сверкой missing/dup ниже (тот же
  # именованный fail-closed класс, что и раньше: редчайшее, но ИМЕНОВАННОЕ, не
  # молчаливое, совпадение).
  #
  # Побочный продукт ОДНОГО прохода — `$TMP/paths_by_commit`: NUL-разделённые пары
  # «sha, путь, sha, путь, …» (путь — сырые байты, любой, кроме NUL; LF/TAB внутри
  # допустимы и не рвут границу записи). BATCHED paths lookup ниже читает ЭТОТ файл
  # вместо повторного регэксп-сканирования `$TMP/paths_raw` за каждый коммит.
  # Пред-усечение файла ДО awk: `print … > pairsfile` внутри awk открывает-и-усекает
  # файл ТОЛЬКО при ПЕРВОЙ фактической записи — окно, где у ВСЕХ коммитов 0 путей
  # (например, из одних root/empty-коммитов), не вызвало бы ни одной записи, и файл, не
  # будь он усечён здесь явно, унаследовал бы содержимое ПРЕДЫДУЩЕГО окна.
  : > "$TMP/paths_by_commit"
  awk -v ORS='\0' -v pairsfile="$TMP/paths_by_commit" -v ord="$TMP/matched_commits" '
    BEGIN {
      RS = "\n"
      while ((getline line < ord) > 0) {
        if (line != "") { want[line] = 1; order[++n] = line }
      }
      close(ord)
      RS = "\0"
    }
    {
      if (idx < n && $0 == order[idx + 1]) { idx++; seen[$0]++; cur = $0; next }
      if (idx == 0) { extra++; next }
      if ($0 in want) { seen[$0]++ }
      print cur > pairsfile
      print $0 > pairsfile
    }
    END {
      missing = 0; dup = 0
      for (s in want) {
        if (!(s in seen))      missing++
        else if (seen[s] != 1) dup++
      }
      printf("%d\t%d\t%d\n", missing, dup, extra + 0)
    }
  ' "$TMP/paths_raw" > "$TMP/paths_raw_completeness"
  IFS=$'\t' read -r missing_paths dup_paths extra_paths < "$TMP/paths_raw_completeness"
  if [ "${missing_paths:-0}" -gt 0 ] || [ "${dup_paths:-0}" -gt 0 ] || [ "${extra_paths:-0}" -gt 0 ]; then
    printf 'ОТКАЗ: batched git diff-tree --stdin вернул неполный/искажённый поток (контракт %s, диапазон %s) — %s SHA без заголовка путей, %s SHA с более чем одной заголовочной записью, %s записей до первого распознанного заголовка окна; список путей окна недостоверен.\n' \
      "$nnn" "$range" "${missing_paths:-0}" "${dup_paths:-0}" "${extra_paths:-0}" >&2
    printf 'Лечится: диагностируйте git-окружение (PATH, версия git, доступность объектной базы) и повторите прогон.\n' >&2
    printf 'Частичный, но синтаксически валидный успешный вывод опаснее явного отказа — недостающая/задвоенная запись сделала бы нарушителя невидимым либо исказила границы блока (verdicts/adversary/contracts-040-oracle-a2-diff-tree-v2.md, находка (б); арбитраж 040-II п.2; verdicts/adversary/contracts-040-v7-circle.md, находка 2).\n' >&2
    exit 1
  fi

  # Счётчик `commits` ниже считает коммиты, дошедшие ДО author-фильтра (как и
  # в исходной форме, §Инварианты п.1); для не-совпавших цикл пройдёт, увеличит
  # `commits`, прочтёт автора из map (O(awk)), skip'нет — что эквивалентно
  # per-commit форме по счётчикам и текстам ok/bad.
  while IFS= read -r c; do
    [ -n "$c" ] || continue
    commits=$((commits + 1))
    # BATCHED author-lookup: O(1) awk-map-read вместо per-commit git-вызова.
    an="$(awk -F'\t' -v c="$c" '$1 == c { print $2; exit }' "$TMP/author_map")"
    [ -n "$an" ] || continue
    grep -qxF -- "$an" "$TMP/authors" || continue
    if grep -qxF "$(printf '%s\t%s\t%s' "$an" "$c" "$nnn")" "$TMP/saved"; then
      printf '  ok   контракт %s: коммит %s (%s) — СПАСЕНО, из суда зон выведен\n' "$nnn" "${c:0:8}" "$an" >&2
      continue
    fi
    checked=$((checked + 1))
    # Н-100: зона автора — ОБЪЕДИНЕНИЕ путей из ВСЕХ замороженных контрактов — так заявлено
    # шапкой выше и так судит check_staged (единый читатель lib_zones). Per-contract фильтр
    # красил легальные коммиты перекрывающихся окон (026∥027): путь зоны B внутри диапазона
    # окна A выходил «вне зоны» у второго потребителя зон, пройдя первого.
    awk -F'\t' -v a="$an" '$1 == a { print $2 }' "$TMP/zones_scoped" | sort -u > "$TMP/mine"
    # NUL-разделённое чтение (`-d ''`, не `-r` одной строкой): путь может нести
    # СЫРОЙ LF-байт (адверсарий круг 7, находка 1) — построчное `read` расщепило бы
    # ОДИН путь на ДВА фантомных, и второй фантом мог бы ложно выйти «вне зоны»
    # (первый совпал бы с префиксом, второй — уже нет). Источник ниже (BATCHED paths
    # lookup) печатает пути NUL-терминированными специально под это чтение.
    while IFS= read -r -d '' f; do
      [ -n "$f" ] || continue
      # draft-признание (контракт 023, ветвь iv): ПО НОМЕРУ ПУТИ M (не номеру ОКОНА nnn).
      # Парсим M из basename f (три цифры, дефис, не-цифра). Две руки:
      #   рука А — тег id/CONTRACT/<M> указывает НА САМОМ судимом коммите C
      #     (обобщение ручной 021 с «номера окна» на «номер пути»: покрывает
      #     А-89 «draft в чужом открытом окне» и исторические теги-на-коммите);
      #   рука Б — тег id/CONTRACT/<M> жив ∧ его коммит is-ancestor C ∧
      #     НЕТ frozen/contracts/<M>/* в предках C (новая форма: итерации
      #     резерва до заморозки M; после заморозки M итерации НЕ признаются
      #     — путь судится зонами);
      #   исключается ТОЛЬКО путь contracts/<M>-*; прочие пути того же коммита
      #   идут обычным порядком (тег не индульгенция на весь коммит).
      skip_path=
      if [ "${f%%/*}" = "contracts" ]; then
        base="${f##*/}"            # e.g. M-slug.md
        head3="${base:0:3}"        # первые три символа basename
        case "$head3" in
          [0-9][0-9][0-9])
            path_m="$head3"
            # рука А: тег id/CONTRACT/<M> на самом коммите C
            if g tag --points-at "$c" "id/CONTRACT/$path_m" 2>/dev/null \
                 | grep -qxF -- "id/CONTRACT/$path_m"; then
              skip_path=1
            else
              # рука Б: тег жив ∧ его коммит is-ancestor C ∧ НЕТ frozen/contracts/<M>/* в предках C
              tag_commit="$(g rev-parse --verify --quiet "refs/tags/id/CONTRACT/$path_m^{commit}" 2>/dev/null || true)"
              if [ -n "$tag_commit" ] && g merge-base --is-ancestor "$tag_commit" "$c" 2>/dev/null; then
                freeze_in_ancestors=0
                while IFS= read -r ft; do
                  [ -z "$ft" ] && continue
                  ft_commit="$(g rev-parse --verify --quiet "${ft}^{commit}" 2>/dev/null || true)"
                  if [ -n "$ft_commit" ] && g merge-base --is-ancestor "$ft_commit" "$c" 2>/dev/null; then
                    freeze_in_ancestors=1
                    break
                  fi
                done < <(g for-each-ref --format='%(refname)' "refs/tags/frozen/contracts/$path_m/" 2>/dev/null)
                if [ "$freeze_in_ancestors" -eq 0 ]; then
                  skip_path=1
                fi
              fi
            fi
            ;;
        esac
      fi
      # ── минт-признание (контракт 031, ветвь ii): путь registry/contracts.tsv под
      # автором orchestrator исключается ИЗ ЭТОГО ПУТИ ⟺ дельта коммита по этому
      # пути — только-добавление строк грамматики манифеста ∧ для каждой строки тег
      # id/CONTRACT/<NNN> жив локально ∧ tag-object-sha == sha строки. Провенанс на
      # origin НЕ перепроверяется (дверь 031 (i) решила его на входе, прецедент 023
      # (iv)). Fail-closed: чтение локального реестра — тег, удалённый к моменту
      # аудита, красит признание; лечение восстановлением тега, не ослаблением.
      if [ "$an" = "orchestrator" ] && [ "$f" = "registry/contracts.tsv" ]; then
        # Дельта коммита по этому пути vs родитель.
        if g rev-parse --verify --quiet "${c}^" >/dev/null 2>&1; then
          mint_diff="$(g diff -U0 "${c}^" "$c" -- registry/contracts.tsv 2>/dev/null || true)"
        else
          # Самый первый коммит: дельта против пустого дерева.
          mint_diff="$(g diff -U0 $(g rev-parse --verify 4b825dc642cb6eb9a060e54bf899d15f3f938a82) "$c" -- registry/contracts.tsv 2>/dev/null || true)"
        fi
        hunk_body="$(printf '%s\n' "$mint_diff" | awk '/^@@/ { h=1; next } /^diff / { h=0 } h')"
        mint_add="$(printf '%s\n' "$hunk_body" | awk '/^\+/ { c++ } END { print c+0 }')"
        mint_del="$(printf '%s\n' "$hunk_body" | awk '/^-/ { c++ } END { print c+0 }')"
        if [ "$mint_add" -lt 1 ] || [ "$mint_del" -ne 0 ]; then
          bad "коммит вне зоны: $an ${c:0:8} $f — дверь минта 031: дельта манифеста не только-добавление"
          continue
        fi
        # Грамматика: «^[0-9]{3} → [0-9a-f]{40}$».
        # ALL-LINES predicate (контракт 031/4, механизм 1, условие 2): грамматику
        # обязана держать КАЖДАЯ добавленная (+) содержательная строка манифеста, не
        # только подмножество. valid_count == mint_add — иначе именованный отказ
        # «строка не по грамматике манифеста». Перечисление ведётся по hunk_body —
        # хунк-контекстный парсер арбитража verdicts/arbitration/diff-parser-031-dver-mina.md.
        added_lines="$(printf '%s\n' "$hunk_body" | sed -n 's/^+\([0-9]\{3\} \xe2\x86\x92 [0-9a-f]\{40\}\)$/\1/p')"
        valid_count="$(printf '%s\n' "$added_lines" | awk 'NF { c++ } END { print c+0 }')"
        if [ "$valid_count" -ne "$mint_add" ]; then
          bad "коммит вне зоны: $an ${c:0:8} $f — дверь минта 031: строка не по грамматике манифеста"
          continue
        fi
        # Проверка каждой строки: тег жив ∧ ANNOTATED ∧ tag-object-sha == sha строки.
        mint_fail=0
        while IFS= read -r ln; do
          [ -n "$ln" ] || continue
          if [ "$mint_fail" -ne 0 ]; then break; fi
          nnn="${ln%% *}"
          sha_ln="${ln##* }"
          if [ -z "$nnn" ] || [ -z "$sha_ln" ]; then
            bad "коммит вне зоны: $an ${c:0:8} $f — дверь минта 031: строка не по грамматике манифеста"
            mint_fail=1; break
          fi
          if ! g show-ref --verify --quiet "refs/tags/id/CONTRACT/$nnn"; then
            bad "коммит вне зоны: $an ${c:0:8} $f — дверь минта 031: тег id/CONTRACT/$nnn не жив локально"
            mint_fail=1; break
          fi
          tag_type="$(g cat-file -t "refs/tags/id/CONTRACT/$nnn" 2>/dev/null || true)"
          if [ "$tag_type" != "tag" ]; then
            bad "коммит вне зоны: $an ${c:0:8} $f — дверь минта 031: тег id/CONTRACT/$nnn не аннотированный"
            mint_fail=1; break
          fi
          tag_sha="$(g rev-parse "refs/tags/id/CONTRACT/$nnn" 2>/dev/null || true)"
          if [ "$tag_sha" != "$sha_ln" ]; then
            bad "коммит вне зоны: $an ${c:0:8} $f — дверь минта 031: sha строки ≠ tag-object-sha живого тега"
            mint_fail=1; break
          fi
        done <<< "$added_lines"
        if [ "$mint_fail" -eq 0 ]; then
          # Признание прошло — путь исключается ИЗ ЭТОГО ПУТИ (не из коммита).
          skip_path=1
        else
          continue
        fi
      fi
      if [ -n "$skip_path" ]; then
        continue
      fi
      if is_process_file "$f"; then
        printf '%s\n' "$f" >> "$TMP/process_excluded"
        continue
      fi
      inside=1
      while IFS= read -r p; do
        case "$p" in
          */) case "$f" in "$p"*) inside=0; break ;; esac ;;
          *)  [ "$f" = "$p" ] && { inside=0; break; } ;;
        esac
      done < "$TMP/mine"
      [ "$inside" -eq 0 ] || bad "коммит вне зоны: $an ${c:0:8} $f — зона автора (объединение всех замороженных): $(tr '\n' ' ' < "$TMP/mine")"
    # BATCHED paths lookup: пути $c из $TMP/paths_by_commit (один awk на коммит, без
    # git; см. позиционный разбор выше). `$TMP/paths_by_commit` — NUL-разделённые пары
    # «sha, путь, sha, путь, …» В ФИКСИРОВАННОМ ЧЕТНОСТНОМ порядке (нечётная запись —
    # sha владельца, следующая чётная — его путь) — извлечение $c ПРОСТОЕ равенство по
    # ПОЛЯМ ЧЁТНОЙ ПАРЫ, а не regex-угадывание границы блока (границу уже провёл
    # позиционный проход выше, ОДИН раз на окно). Для коммита без путей (например,
    # корневой) в `paths_by_commit` нет ни одной пары с sha=$c — тот же 0-путей-эффект,
    # что у per-commit-формы, для которой `git diff-tree --no-commit-id --name-only
    # <root>` тоже даёт 0 путей.
    done < <(awk -v RS='\0' -v ORS='\0' -v want="$c" '
      NR % 2 == 1 { sha = $0; next }
      sha == want { print }
    ' "$TMP/paths_by_commit")
  done < "$TMP/commits"
done < "$TMP/ranges"
printf '\nпроцессных вне суда:%s\n' "${process_list:+ $process_list}" >&2

printf '\nзамороженных контрактов: %d · объявленных авторов: %d · коммитов в диапазонах: %d · проверено по зонам: %d\n' \
  "$contracts" "$(wc -l < "$TMP/authors" 2>/dev/null | tr -d ' ')" "$commits" "$checked" >&2

[ "$fails" -eq 0 ] || exit 1
exit 0