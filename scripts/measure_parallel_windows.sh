#!/usr/bin/env bash
# Мера параллельности окон контрактов (§10 ROADMAP, контракт 021 ветвь В,
# решение арбитража fda7bbe). НЕ БАРЬЕР: возвращает код, а не вердикт;
# именованная причина пишется в stderr, чтобы вызывающий мог её процитировать.
#
# ДОГОВОР (ветвь В контракта 021, текст 021-sud-okna-svoej-vetki.md:73-91):
#   вход <корень> <A> <B> (трёхзначные номера контрактов, как в тегах);
#   окна перекрылись ⟺ frozen/contracts/A/1 раньше done/contracts/B/1 И
#   frozen/contracts/B/1 раньше done/contracts/A/1;
#   rc 0 — перекрытие доказано; rc 1 — «не параллельно» с именами и
#   временами ЛИБО «недостающий тег» с именем тега.
#
# ВРЕМЕННАЯ ОСЬ (правка 3 по решению арбитража fda7bbe, fda7bbe коммит):
#   «раньше» — порядок МОМЕНТОВ времени коммиттера коммита тега (%ct,
#   числовое unix-время; сравнение `-lt`); строковое %ci-представление
#   договором не является (слабая лексикографическая форма умирает на
#   воротах 4 red_mera: +0000/+1400/-1100/+0000 даёт лексикографическое
#   «перекрытие», моменты строго возрастают).
#
# ТЕГИ читаются как аннотированные: deref до коммита `${tag}^{commit}`.
# `rev-list -1 --format=%ct <commit>` выдаёт unix-время коммиттера этого
# коммита; для лёгкого тега rev-list выдаст одну строку с временем.
#
# ОБРАБОТКА ОТСУТСТВУЮЩЕГО ТЕГА — отдельный путь ДО сравнения моментов:
#   пустая выборка (%ct пуст) ⇒ rc 1 «недостающий тег <tag>». Это
#   красная не зелёная (пусто-зелёный гейт хуже красного; прецедент
#   case_reestr_nedostupen).
#
# Коды возврата: 0 — перекрытие окон доказано; 1 — «не параллельно» либо
#               «недостающий тег» (с именованной причиной в stderr).
set -uo pipefail

R="${1:?корень}" A="${2:?номер A}" B="${3:?номер B}"

command -v git >/dev/null 2>&1 || {
  printf 'ОТКАЗ: нет git — меру исполнить нечем\n' >&2
  exit 1
}
git -C "$R" rev-parse --git-dir >/dev/null 2>&1 || {
  printf 'ОТКАЗ: %s не репозиторий git\n' "$R" >&2
  exit 1
}

# committer time коммита, на который указывает тег. Аннотированный тег
# deref через ^{commit}; log -1 --format=%ct даёт чистую строку unix-времени
# (rev-list с --format=%ct печатает «commit <sha>» ДО значения, требует grep).
ct() {  # <имя-тега>
  git -C "$R" log -1 --format=%ct "${1}^{commit}" 2>/dev/null
}

fa="$(ct "frozen/contracts/$A/1")"
db="$(ct "done/contracts/$B/1")"
fb="$(ct "frozen/contracts/$B/1")"
da="$(ct "done/contracts/$A/1")"

# Недостающий тег — красный с именем тега (а не молча зелёный).
for entry in "frozen/contracts/$A/1:$fa" \
             "done/contracts/$B/1:$db" \
             "frozen/contracts/$B/1:$fb" \
             "done/contracts/$A/1:$da"; do
  if [ -z "${entry#*:}" ]; then
    printf 'недостающий тег %s\n' "${entry%%:*}" >&2
    exit 1
  fi
done

# Перекрытие — оба неравенства МОМЕНТОВ (числовое `-lt`). Лексикографическая
# форма отбита воротами 4 red_mera (смешанные offset: +0000/+1400/-1100/+0000).
if [ "$fa" -lt "$db" ] && [ "$fb" -lt "$da" ]; then
  exit 0
fi

printf 'не параллельно: frozen/contracts/%s/1 (%s) → done/contracts/%s/1 (%s); frozen/contracts/%s/1 (%s) → done/contracts/%s/1 (%s)\n' \
  "$A" "$fa" "$B" "$db" "$B" "$fb" "$A" "$da" >&2
exit 1
